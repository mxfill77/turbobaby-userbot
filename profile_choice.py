# -*- coding: utf-8 -*-
"""
profile_choice.py — ВЫБОР УЧЁТКИ СТРОИТЕЛЕЙ ПОЛОСЫ ПК ОДНИМ ФАЙЛОМ В РАБОЧЕМ ДЕРЕВЕ.

ЗАЧЕМ (класс 18–22.09.2026, замеры 70u). Какой учёткой работают строители полосы ПК — headless
`claude -p` исполнителя и думатель, — решала ПОСТОЯННАЯ ПЕРЕМЕННАЯ ПОЛЬЗОВАТЕЛЯ
`CLAUDE_CONFIG_DIR` в `HKCU\\Environment`. Рычаг рабочий, но ТЯЖЁЛЫЙ, и тяжесть у него тройная:
  • он ЗА ПРЕДЕЛАМИ проекта (реестр) — для headless-полосы это красная операция класса `outside`,
    то есть полоса сама себя переключить не может ни при каком задании;
  • он действует на ВСЕ будущие процессы учётной записи владельца, включая единственную дверь
    с телефона, — цена ошибки шире, чем полоса;
  • переключение требует НОВОГО сеанса (блок окружения собирается при входе), то есть перезахода
    владельца.

РАЗЛИЧИЕ, НА КОТОРОМ СТОИТ ВЕСЬ МОДУЛЬ (замер 70u, `docs/artifacts/2026-09-22-70u-PROFILOBRATNO-2209.md`,
таблица п.3, прогоны M1 и M2). У переменной `CLAUDE_CONFIG_DIR` ТРИ состояния, а не два:
    M1  переменной НЕТ вовсе            → CLI идёт в ОСНОВНОЙ профиль; маркеров отказа входа 0
    M2  переменная ЕСТЬ и ПУСТА (`''`)  → CLI идёт в профиль БЕЗ ВХОДА; маркеров отказа входа 3
    B   переменная ЕСТЬ и указывает путь → CLI идёт в этот профиль
Пустая переменная — не «никакая», а ОТДЕЛЬНОЕ И ХУДШЕЕ состояние: полоса остаётся подписанной ни
на какой счёт, и МОЛЧА (демон ошибок входа в лог не пишет). Поэтому здесь действует запрет,
который не смягчается ничем: `env[KEY] = ""` не выполняется НИ НА ОДНОЙ дороге этого модуля —
ветки, которая ставит пустое значение, в нём нет физически (инвариант `PROFILE_CHOICE_NEVER_EMPTY`).

ЧТО ДЕЛАЕТ МОДУЛЬ. Читает один текстовый файл рабочего дерева (`claude_profile_choice.txt`) и
говорит, что сделать с ключом `CLAUDE_CONFIG_DIR` в окружении РЕБЁНКА — того самого словаря,
который демон собирает копией своего окружения перед спавном `claude`. Реестр при этом не
трогается ни на чтение, ни на запись: постоянная переменная пользователя остаётся как есть, а
ребёнок получает решение файла ПОВЕРХ унаследованного значения.

ТРИ ИСХОДА, И ТРЕТИЙ — ГЛАВНЫЙ:
    слово ОСНОВНОЙ          → ACT_DROP : ключ УДАЛЯЕТСЯ из окружения ребёнка (состояние M1)
    существующий каталог    → ACT_SET  : ключ равен этому пути (состояние B)
    всё остальное           → ACT_KEEP : окружение НЕ ТРОГАЕТСЯ ВОВСЕ, ни одним ключом
«Всё остальное» названо поимённо и каждый случай несёт СВОЮ причину для журнала захода: файла
нет · файл не прочитан · значение пустое · значимых строк больше одной · управляющий символ ·
значение неправдоподобно длинное · путь не существует или не каталог. Третий исход — это
ПРЕЖНЕЕ ПОВЕДЕНИЕ БАЙТ-В-БАЙТ (ребёнок наследует окружение демона), то есть направление ошибки
здесь безопасное: не поняли файл — не сделали ничего и сказали об этом словами.

ПОЧЕМУ КОММЕНТАРИИ В ФАЙЛЕ РАЗРЕШЕНЫ. Строка отката («как переключить обратно») обязана лежать
РЯДОМ со значением, иначе её не прочтёт тот, кто откатывает. Значит парсер обязан уметь
пропускать `#`-строки и пустые — и он умеет. Значимых строк после этого должно остаться РОВНО
одна: две — это спор двух решений, и спор разрешается не выбором, а отказом (ACT_KEEP).

ЧИСТОТА (инвариант `PROFILE_CHOICE_PURE`, замок в test_profile_choice.py). Ни сети, ни
подпроцессов, ни БД, ни секретов, ни реестра: `io`, `os`, `collections` — и всё. Модуль НИЧЕГО
НЕ УДАЛЯЕТ с диска и НЕ ПИШЕТ на диск ни одной строкой; единственное, что он меняет, — переданный
ему словарь окружения. Замыкание демона он не растит ни на файл.
"""

import io
import os
from collections import namedtuple

# ── имена. Ключ — тот самый, которым CLI выбирает каталог профиля ─────────────────────────────
KEY = "CLAUDE_CONFIG_DIR"

# Место файла названо ЯВНО и одно: корень рабочего дерева ПК. Не `tmp/` (он под .gitignore, и
# решение полосы потерялось бы при первой же чистке), не `docs/` (там артефакты, а не рычаги) —
# корень, рядом с прочими данными полосы (`price_source.json`, `topics_map.json`, `team_registry.json`).
CHOICE_REL = "claude_profile_choice.txt"

# Слово главного исхода. Сверка идёт ПО ВЕРХНЕМУ РЕГИСТРУ после strip: «основной», « Основной »
# и «ОСНОВНОЙ» — одно и то же слово, написанное человеком в трёх настроениях.
WORD_MAIN = "ОСНОВНОЙ"

ACT_DROP = "drop"    # ключа в окружении ребёнка НЕТ (состояние M1 замера 70u)
ACT_SET = "set"      # ключ равен названному пути (состояние B)
ACT_KEEP = "keep"    # окружение не тронуто вовсе — прежнее поведение байт-в-байт

# Правдоподобный потолок длины пути. Windows-путь длиннее этого — не путь, а мусор в файле;
# судим числом, а не «на глаз», чтобы причина в журнале была проверяемой.
VALUE_MAX = 4096

Decision = namedtuple("Decision", "action value reason")


def choice_path(repo=None, path=None):
    """Абсолютный путь файла выбора. `path` — прямое указание (тесты, разовые замеры)."""
    if path:
        return str(path)
    return os.path.join(str(repo or os.getcwd()), CHOICE_REL)


def read_raw(repo=None, path=None):
    """→ (текст | None, причина отказа чтения). Файла нет → (None, "") — это ШТАТНО и отличается
    от «файл есть, но не прочитан» (None, "UnicodeDecodeError: …"). Два разных исхода, две разные
    строки в журнале: «полоса не настроена» и «полоса настроена, но настройку не разобрать»."""
    p = choice_path(repo, path)
    try:
        if not os.path.isfile(p):
            return None, ""
        # utf-8-sig, а не utf-8: PowerShell 5.1 (`Set-Content -Encoding UTF8`, `Out-File`) пишет
        # BOM. str.strip() его не снимает, поэтому первая `#`-строка переставала быть комментарием →
        # «значимых строк 2» → ACT_KEEP, то есть молча прежний профиль (разбор 22.09,
        # docs/artifacts/2026-09-22-rc-device-profile2-stall.md). Без BOM читается так же, как utf-8.
        with io.open(p, encoding="utf-8-sig") as f:
            return f.read(), ""
    except Exception as e:                       # noqa: BLE001 — любой отказ чтения = не знаем
        return None, "%s: %s" % (type(e).__name__, str(e)[:120])


def payload(text):
    """Значимая строка файла → (значение, причина-брак). Пустые строки и `#`-комментарии
    выбрасываются: в файле обязана лежать строка отката человеческим языком."""
    lines = []
    for ln in str(text).splitlines():
        s = ln.strip()
        if not s or s.startswith("#"):
            continue
        lines.append(s)
    if not lines:
        return "", "значение пустое (значимых строк 0)"
    if len(lines) > 1:
        return "", "значимых строк %d, а решение обязано быть одно" % len(lines)
    v = lines[0]
    if len(v) > VALUE_MAX:
        return "", "значение длиной %d символов (потолок %d) — испорчено" % (len(v), VALUE_MAX)
    if any(ord(ch) < 32 for ch in v):
        return "", "в значении управляющий символ — испорчено"
    # Кавычки вокруг пути человек ставит машинально (копия из проводника). Снимаем ОДНУ пару.
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1].strip()
        if not v:
            return "", "значение пустое (внутри кавычек ничего нет)"
    return v, ""


def decide(raw, err="", isdir=None):
    """ЧИСТОЕ решение: (сырой текст файла | None, причина отказа чтения) → Decision.
    `isdir` инъектируется в тестах — иначе единственное обращение к диску здесь."""
    isdir = isdir or os.path.isdir
    if err:
        return Decision(ACT_KEEP, "", "файл выбора %s не прочитан (%s)" % (CHOICE_REL, err))
    if raw is None:
        return Decision(ACT_KEEP, "", "файла выбора %s нет" % CHOICE_REL)
    value, bad = payload(raw)
    if bad:
        # ВЕТКА «ИСПОРЧЕННОЕ ЗНАЧЕНИЕ НЕ ТРОГАЕТ ОКРУЖЕНИЕ». Соблазн поставить сюда `value` (то
        # есть пустую строку) выглядит безобидно и является ровно тем обходимым дефектом, ради
        # запрета которого написан модуль: пустой ключ уводит CLI в профиль БЕЗ ВХОДА (M2).
        return Decision(ACT_KEEP, "", bad)
    if value.strip().upper() == WORD_MAIN:
        return Decision(ACT_DROP, "",
                        "слово %s — ключ %s снят из окружения ребёнка (основной профиль)"
                        % (WORD_MAIN, KEY))
    try:
        exists = bool(isdir(value))
    except Exception as e:                       # noqa: BLE001 — «не проверить» ≠ «существует»
        return Decision(ACT_KEEP, "", "путь «%s» не проверить (%s)" % (value, type(e).__name__))
    if not exists:
        return Decision(ACT_KEEP, "", "путь «%s» не существует или не каталог" % value)
    return Decision(ACT_SET, value, "путь «%s» — ключ %s поставлен ребёнку" % (value, KEY))


def apply_to(env, repo=None, path=None, isdir=None, reader=None):
    """ПРИМЕНИТЬ решение файла к УЖЕ СОБРАННОМУ словарю окружения ребёнка (правка на месте).
    → Decision (её `reason` и идёт строкой в журнал захода).

    ACT_KEEP не трогает `env` НИ ОДНИМ ключом — это проверяется тестом сравнением словарей
    целиком, а не наличием `KEY`."""
    raw, err = (reader or read_raw)(repo, path)
    d = decide(raw, err, isdir)
    if d.action == ACT_DROP:
        env.pop(KEY, None)
    elif d.action == ACT_SET:
        env[KEY] = d.value
    return d


def line(d, tid=None):
    """Строка для журнала захода. «Не применён» и «применён» звучат РАЗНЫМИ словами: третий
    исход обязан называть себя, а не выглядеть успехом."""
    who = ("id=%s " % tid) if tid is not None else ""
    if d.action == ACT_KEEP:
        return ("%sвыбор учётки строителей НЕ ПРИМЕНЁН: %s — окружение ребёнка по %s не тронуто "
                "(наследуется от демона)" % (who, d.reason, KEY))
    return "%sвыбор учётки строителей: %s" % (who, d.reason)
