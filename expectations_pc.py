def human_age(sec):
    """«48 мин» / «5 ч 12 мин» / «1 сут 10 ч». Ноль дробей: заметку читают с телефона."""
    s = max(0, int(sec or 0))
    d, rest = divmod(s, 86400)
    h, rest = divmod(rest, 3600)
    m = rest // 60
    if d:
        return "%d сут %d ч" % (d, h)
    if h:
        return "%d ч %d мин" % (h, m)
    return "%d мин" % m


def _mins(sec):
    return "%d мин" % int(round(float(sec or 0) / 60.0))


def _count_word(n):
    """Число для заметки. `None` печатается СЛОВАМИ «не прочитано», а не нулём: у ветки, чей
    ожидаемый результат — ноль, напечатанный вместо незнания ноль читается как «всё хорошо»."""
    return "не прочитано" if n is None else "%d" % int(n)


def _when_word(ts):
    """Время для заметки. Отсутствие времени называется словами, а не пустотой."""
    return "времени нет" if ts is None else str(ts)


