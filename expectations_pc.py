def limit_env(name, default, env=None, scale=60.0):
    """Порог из окружения → СЕКУНДЫ (значение задано в минутах). Пусто/мусор → дефолт; 0 → ветка
    мертва. НОЛЬ ЗДЕСЬ ЗНАЧИМ (объявленный откат), поэтому парсер свой, а не `_env_int` демона:
    тот на «0» отдаёт дефолт, то есть выключить им ветку нельзя."""
    try:
        raw = str(((env if env is not None else {}) or {}).get(name) or "").strip()
    except Exception:
        return float(default) * scale
    if not raw:
        return float(default) * scale
    try:
        v = float(raw.replace(",", "."))
    except (TypeError, ValueError):
        return float(default) * scale
    return (v if v >= 0 else float(default)) * scale


