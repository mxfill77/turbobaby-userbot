# ПУЛЬС — НЕ ЗАМЕТКА ВЛАДЕЛЬЦУ, А СТРОКА ЖУРНАЛА, и адресована она наблюдателю ВНЕ машины. Тип
# `NOTE` стои́т первым словом намеренно: писатель journal-строки берёт тип из первого слова
# (`cowork_log_append.LOG_TYPES`), а всё неопознанное молча становится `DONE` — пульс, ставший
# «DONE», врал бы о сделанной работе.
PULSE_HEAD = "NOTE ПУЛЬС"


def render_pulse(v, lane="ПК"):
    """Строка пульса в журнал. Говорит РОВНО то, что доказано, и НАЗЫВАЕТ СВОЮ ЦЕНУ: читающий
    обязан понимать, что молчание этой строки — новость, а не тишина по бездействию."""
    v = v if isinstance(v, dict) else {}
    turn = v.get("turn") if isinstance(v.get("turn"), dict) else {}
    parts = [PULSE_HEAD, str(lane or "ПК"),
             "контур жив: оборот poll_once %s назад" % human_age(turn.get("wall")),
             "следа работы в журнале нет %s (порог пульса %s)"
             % (human_age(v.get("silence")), _mins(v.get("limit")))]
    slept = float(turn.get("slept") or 0.0)
    if slept > 60:
        # Сон машины называется ОТДЕЛЬНО: без этого «оборот 9 ч назад» читалось бы как поломка.
        parts.append("по часам бодрствования %s, сон машины %s в счёт не идёт"
                     % (human_age(turn.get("awake")), human_age(slept)))
    parts.append("это след ЖИЗНИ, а не отчёт о работе: пишется только при ДОКАЗАННОМ обороте, "
                 "поэтому его молчание значит «ПК не даёт оборота», а не «задач не было»")
    return " · ".join(parts)


# ФОРМА СТРОКИ О ДЕТЯХ ВЗЯТА ГОТОВОЙ, А НЕ ПРИДУМАНА. Голова та же (`PULSE_HEAD`), полоса тем же
# вторым сегментом, разделитель тот же ` · `, и сегмент «контур жив: оборот poll_once …» стои́т
# здесь ДОСЛОВНО тем же текстом, что в пульсе демона: сосед разбирает пульс по нему, и строка о
# детях обязана быть разбираема ТЕМ ЖЕ способом, а не своим собственным.
KIDS_MARK = "дети контура"
# Число детей на длину строки влиять НЕ ДОЛЖНО: внутри своего сегмента дети разделены ` ; `,
# поэтому сегментов у строки всегда пять, сколько бы детей ни завёл вотчдог.
KIDS_SEP = " ; "
# Копия `cowork_log_append.LINE_MAX` (наблюдатель не импортирует писателя). Строка длиннее этого
# уедет ТЕЛОМ В ФАЙЛ, а в мозг ляжет обрезанная голова — то есть сосед перестанет видеть детей
# ровно тогда, когда о них есть что сказать. Поэтому длина здесь не пожелание, а замок.
KIDS_LINE_MAX = 600
# Ступени сжатия ПРИЧИН. Режется всегда причина и никогда — имя и состояние: имя с состоянием
# несут вердикт, причина его лишь объясняет.
KIDS_WHY_STEPS = (110, 70, 45, 24, 0)


def _kid_word(k, why_max):
    """Один ребёнок строкой: «имя — состояние (чем доказано / почему не знаем)»."""
    k = k if isinstance(k, dict) else {}
    name, state = str(k.get("name")), str(k.get("state"))
    if state == MOD_OK:
        return "%s — %s (свой продукт %s назад)" % (name, state, _age_short(k.get("wall")))
    if state == MOD_IDLE:
        if k.get("dead"):
            # Приговор вынесен пробой процесса, а не возрастом продукта, — и строка обязана
            # сказать ИМЕННО ЭТО: иначе сосед прочтёт «нет продукта N минут» и станет ждать, пока
            # число вырастет, тогда как ждать уже нечего.
            return "%s — %s (процесса из лока в системе нет)" % (name, state)
        age = k.get("awake") if k.get("awake") is not None else k.get("wall")
        return "%s — %s (своего продукта нет %s)" % (name, state, human_age(age))
    why = str(k.get("why") or "").strip()
    if not why or why_max <= 0:
        return "%s — %s" % (name, state)
    return "%s — %s (%s)" % (name, state, why[:why_max])


def _render_kids(v, lane, why_max):
    turn = v.get("turn") if isinstance(v.get("turn"), dict) else {}
    kids = v.get("kids") or []
    return " · ".join([
        PULSE_HEAD, str(lane or "ПК"),
        "контур жив: оборот poll_once %s назад" % human_age(turn.get("wall")),
        "%s: %s" % (KIDS_MARK, KIDS_SEP.join(_kid_word(k, why_max) for k in kids)),
        "ПЕРИОДИЧЕСКАЯ строка (период %s), а не тревога: «%s» здесь значит «проверить не удалось», "
        "а не «мёртв»; её молчание значит «полоса не даёт оборота либо ПК не наблюдает», а не «с "
        "детьми всё хорошо»" % (_mins(v.get("limit")), MOD_UNKNOWN),
    ])


def render_kids(v, lane="ПК"):
    """Строка о детях в журнал: КАЖДЫЙ ребёнок назван по имени и со своим состоянием.

    Как и пульс демона, НАЗЫВАЕТ СВОЮ ЦЕНУ: её молчание — новость, а не тишина по бездействию.
    И умещается в `KIDS_LINE_MAX` не надеждой, а устройством — сжимая причины ступенями, пока
    строка не влезет. Имена и состояния при этом не режутся ни на одной ступени: пусть лучше
    сосед не узнает, ПОЧЕМУ «неизвестно», чем не узнает, о ком речь."""
    v = v if isinstance(v, dict) else {}
    line = ""
    for why_max in KIDS_WHY_STEPS:
        line = _render_kids(v, lane, why_max)
        if len(line) <= KIDS_LINE_MAX:
            return line
    return line


