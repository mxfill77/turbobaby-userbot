# ══════════════ О4: СЛЕД ЖИЗНИ НАРУЖУ (полоса свидетельствует, а не судит) ═════════════════
def life_state(facts, cfg=None, now=None):
    """Доказан ли ОБОРОТ прямо сейчас → (LIFE_PROVEN | LIFE_UNKNOWN, подробности).

    ОТЛИЧИЕ ОТ О2 РОВНО ОДНО, И ОНО — ЗАМОК. О2 спрашивает «встал ли демон» и законно принимает
    за работу ОБЪЯВЛЕННЫЙ синхронный заход (штамп CLAIM): продукт в производстве — это работа.
    О4 спрашивает другое — «есть ли ЧТО положить наружу как факт жизни», и штамп заход доказывает,
    а замкнутый виток — нет. Поэтому ветка `busy` здесь отвергается: пульс, написанный по штампу,
    пережил бы смерть демона посреди задачи и врал бы наружу ровно там, где нужнее всего правда.

    Всё прочее — три исхода О2, сведённые к двум: любое «неизвестно» остаётся «неизвестно» и
    пульса не пишет. Права сказать «мёртв» у этой функции нет вовсе (сказать это может только
    наблюдатель вне машины)."""
    cfg = cfg if isinstance(cfg, dict) else config()
    if float(cfg.get("life") or 0.0) <= 0:
        return LIFE_UNKNOWN, {"why": "ветка О4 выключена порогом"}                # откат
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return LIFE_UNKNOWN, {"why": "время прогона не разобрано"}
    if now <= 0:
        return LIFE_UNKNOWN, {"why": "времени прогона нет"}
    state, info = turn_state(facts, cfg, now)
    if state != TURN_OK:
        return LIFE_UNKNOWN, dict(info, why=(info.get("why") or "оборот не доказан: %s" % state))
    busy = info.get("busy")
    if isinstance(busy, dict):
        return LIFE_UNKNOWN, dict(info, why="тишину оборота объясняет объявленный заход (работа "
                                            "объявлена %s назад) — это работа, а не замкнутый "
                                            "виток" % human_age(busy.get("age")))
    return LIFE_PROVEN, dict(info)


def pulse_due(facts, cfg=None, now=None):
    """Пора ли оставить наружу след жизни → (bool, подробности).

    ПОРЯДОК ПРОВЕРОК ЗДЕСЬ — ЧАСТЬ СМЫСЛА:
      1. порог 0 → ветка мертва ДО чтения фактов (объявленный откат);
      2. следа не прочитали → молчим: не зная, когда полоса говорила в последний раз, пульс
         пришлось бы слать каждый тик — это долбёжка моста и мусор в журнале;
      3. след СВЕЖИЙ → молчать и есть правильный ответ: работа уже оставила след, дублировать
         его пульсом значит превращать журнал в кардиограмму;
      4. оборот не доказан → молчим ВСЕГДА (замок против ложного зелёного);
      5. недавняя попытка → пол повтора: спавн писателя докладывает о старте, а не об успехе."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("life") or 0.0)
    if limit <= 0:
        return False, {"why": "ветка О4 выключена порогом"}
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return False, {"why": "время прогона не разобрано"}
    t = (facts or {}).get("trace")
    if not isinstance(t, dict):
        return False, {"why": "факта о последнем следе нет вовсе"}
    if not t.get("ok"):
        return False, {"why": "реестр следов не прочитан (%s)" % (t.get("err") or "причина не названа")}
    try:
        ts = float(t.get("ts") or 0.0)
    except (TypeError, ValueError):
        ts = 0.0
    if ts <= 0 or now <= 0:
        return False, {"why": "время последнего следа не разобрано"}
    silence = now - ts
    if silence <= limit:
        return False, {"why": "след свежий: %s назад (порог %s)" % (human_age(silence), _mins(limit)),
                       "silence": silence, "limit": limit}
    state, info = life_state(facts, cfg, now)
    if state != LIFE_PROVEN:
        # ГЛАВНАЯ ВЕТКА ЗАМКА: молчание пульса — это честное «сказать наружу нечего», и именно оно
        # даёт серверному О4 право зазвучать. Пульс «на всякий случай» отнял бы у него зубы.
        return False, {"why": "оборот не доказан — наружу говорить нечего (%s)" % info.get("why"),
                       "silence": silence, "limit": limit}
    try:
        att = float(t.get("attempt") or 0.0)
    except (TypeError, ValueError):
        att = 0.0
    retry = float(cfg.get("life_retry") or 0.0)
    if att > 0 and retry > 0 and 0 <= (now - att) < retry:
        return False, {"why": "прошлая попытка пульса %s назад (пол повтора %s)"
                              % (human_age(now - att), _mins(retry)),
                       "silence": silence, "limit": limit}
    return True, {"silence": silence, "limit": limit, "turn": info, "ts": ts}


# ══════ ПУБЛИКАЦИЯ ВЕРДИКТА О ДЕТЯХ: ПРИБОР УЖЕ ЕСТЬ, НЕ ХВАТАЛО ГОЛОСА (18.08.2026) ═══════
#
# ЗАБОР ЧЕСТЕРТОНА, ОДНОЙ СТРОКОЙ И С ДАТАМИ: публиковать было НЕКУДА. Прибор о детях (О3)
# заведён 11.08.2026 16:17 (2239c65), а канал наружу — пульс в журнал — родился 14.08.2026 16:02
# (096153d), на трое суток ПОЗЖЕ, и родился под ОДИН предмет: оборот демона. Ни одна строка ни
# того, ни другого захода не запрещает говорить наружу о детях и не называет причины молчать;
# коммит канала прямо говорит «другие ожидания (О1, О2, О3) не менялись» — это дисциплина объёма,
# а не решение молчать. Запрет владельца 11.08 у слоя ровно один и он про ЗУБЫ, а не про голос:
# ожидание НАБЛЮДАЕТ (задач не ставит, процессов не поднимает) — а публиковать наружу О4 уже
# умеет и делает. Забор не снесён: он ставился вокруг другого поля.
#
# ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ, ХОТЯ И ПРОСИТСЯ: ни один порог О3 не тронут, ни одна его ветка не
# переписана, новых судей не заведено. Эта половина файла умеет ровно одно — СКАЗАТЬ НАРУЖУ то,
# что О3 уже решил, и сказать это ПЕРИОДИЧЕСКИ, а не по событию.
def kids_state(facts, cfg=None, now=None):
    """Состояние КАЖДОГО ребёнка контура ПОИМЁННО → [{"name","state","why",…}] в порядке `KIDS`.

    СОСТОЯНИЙ ТРИ, И ТРЕТЬЕ НЕ РАВНО ВТОРОМУ. Слова берутся у О3 ДОСЛОВНО («делает работу» /
    «работы нет» / «неизвестно») и НЕ переводятся в «жив/не жив»: слова «жив» этот слой про
    ребёнка не говорит никогда — живой PID работающим сервисом не является, и ровно ради этого
    закона О3 и строился. «Неизвестно» здесь читается как «проверить не удалось» и стои́т
    отдельным состоянием потому, что слить его со вторым — значит объявить мёртвым того, кого
    нечем проверить.

    ЧЕГО В ФАКТАХ НЕТ НАМЕРЕННО — снимка надзора контур-вотчдога
    (`pc_orchestrator.client_watch.json`). Он живёт ВНУТРИ демона, то есть внутри того, чья
    остановка и продержала модербота мёртвым 33.9 часа 05–06.08.2026; взять его за факт значило
    бы унаследовать ровно ту слепоту, ради ухода от которой наблюдателя и вынесли наружу.
    ПОИМЁННО — ЗНАЧИТ И ПО СВОЕМУ ПРИЗНАКУ (правка 18.08.2026). До неё судился один ребёнок из
    трёх, и судился по ОБЩЕЙ записи в `moderation_ipc.db`, у которой три писателя; двум другим
    доставалось «прибора нет». Теперь у каждого свой источник и свой предел, кратный ЕГО
    собственному периоду (`KID_SIGNS`), а общая запись в канал не даёт зелёного никому и едет
    рядом как СВЕДЕНИЕ."""
    cfg = cfg if isinstance(cfg, dict) else config()
    out = []
    for name in KIDS:
        state, info = kid_state(name, facts, cfg, now)
        info = info if isinstance(info, dict) else {}
        out.append({"name": name, "state": state, "why": info.get("why", ""),
                    "wall": info.get("wall"), "awake": info.get("awake"),
                    "limit": info.get("limit"), "src": info.get("src"),
                    "dead": info.get("dead"), "channel_age": info.get("channel_age")})
    return out


def kids_signature(kids):
    """Подпись состояния детей — ТОЛЬКО имена и состояния. Возрасты и причины в неё не входят
    НАМЕРЕННО: они меняются каждый тик наблюдателя, и подпись с ними звала бы строку в журнал
    каждые десять минут, то есть превратила бы след живости в кардиограмму."""
    return "|".join("%s=%s" % (k.get("name"), k.get("state")) for k in (kids or []))


def kids_pulse_due(facts, cfg=None, now=None):
    """Пора ли положить наружу строку о детях → (bool, подробности).

    ПОРЯДОК ПРОВЕРОК — ЧАСТЬ СМЫСЛА:
      1. порог 0 → ветка мертва ДО чтения фактов (объявленный откат);
      2. ОБОРОТ НЕ ДОКАЗАН → молчим ВСЕГДА. Это тот же замок, что у О4, и здесь он не
         формальность: строка о детях — тоже след полосы наружу, а серверное О4 считает следом
         ЛЮБУЮ строку ПК. Периодическая строка, уходящая при вставшем демоне, отняла бы у соседа
         зубы ровно там, где они нужнее всего, — поэтому эта ветка не смеет доказывать жизнь
         полосы больше, чем её доказывает замкнутый виток;
      3. строки не было вовсе → говорим сразу (первая публикация не ждёт периода);
      4. состояние СМЕНИЛОСЬ и пол повтора выдержан → говорим, не дожидаясь периода: упавший
         ребёнок не обязан ждать шести часов, а пол держит частоту при мигании;
      5. иначе — ПЕРИОД: строка выходит ПОТОМУ ЧТО ПРОШЛО ВРЕМЯ, а не потому что что-то
         случилось. В этом вся разница между следом живости и событием, и ровно её не хватало
         соседу, чтобы поднять ожидание о детях."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("kids") or 0.0)
    if limit <= 0:
        return False, {"why": "публикация о детях выключена порогом"}          # откат
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return False, {"why": "время прогона не разобрано"}
    if now <= 0:
        return False, {"why": "времени прогона нет"}
    kids = kids_state(facts, cfg, now)
    base = {"kids": kids, "sig": kids_signature(kids), "limit": limit}
    lstate, linfo = life_state(facts, cfg, now)
    if lstate != LIFE_PROVEN:
        return False, dict(base, why="оборот не доказан — наружу говорить нечего (%s)"
                                     % linfo.get("why"))
    base["turn"] = linfo
    last = (facts or {}).get("kids_last")
    last = last if isinstance(last, dict) else {}
    try:
        att = float(last.get("attempt") or 0.0)
    except (TypeError, ValueError):
        att = 0.0
    base["was"] = last.get("sig")
    if att <= 0:
        return True, dict(base, since=None, why="строки о детях наружу ещё не было")
    since = max(0.0, now - att)
    base["since"] = since
    retry = float(cfg.get("kids_retry") or 0.0)
    if last.get("sig") != base["sig"]:
        if since < retry:
            return False, dict(base, why="состояние детей сменилось, но прошлая строка %s назад "
                                         "(пол повтора %s)" % (human_age(since), _mins(retry)))
        return True, dict(base, why="состояние детей сменилось")
    if since < limit:
        return False, dict(base, why="строка о детях свежая: %s назад (период %s)"
                                     % (human_age(since), _mins(limit)))
    return True, dict(base, why="период вышел")


# ═════════ О5: КЛИЕНТАМ НЕ УХОДИТ НИЧЕГО (судится РЕЗУЛЬТАТ, а не флаг) ════════════════════
def _int_or_none(val):
    """Целое | None. `None` — честное «не знаю», и оно НЕ становится нулём НИ ОДНОЙ ветвью: у
    ожидания, чей ожидаемый результат и есть ноль, подмена незнания нулём читается как «ничего не
    ушло» — то есть как ложное благополучие."""
    if val is None:
        return None
    try:
        return int(val)
    except (TypeError, ValueError):
        return None


def _float_or_none(val):
    """То же для дробного: незнание доезжает наверх, а не превращается в 0.0."""
    if val is None:
        return None
    try:
        return float(val)
    except (TypeError, ValueError):
        return None


def client_spoken(info):
    """СКОЛЬКО ушло по совокупности свидетелей → число | None. МАКСИМУМ, а не сумма: свидетели не
    независимы (bot-режим пишет и в очередь, и в реестр попыток), и сумма удвоила бы одну и ту же
    отправку. Максимум — честный ПОЛ: «не меньше этого», и он не завышает новость."""
    info = info if isinstance(info, dict) else {}
    known = [n for n in (_int_or_none(info.get("sent")), _int_or_none(info.get("second")))
             if n is not None]
    if len(known) == 0:
        return None
    return max(known)


def client_state(facts, cfg=None, now=None):
    """→ (ТИХО | УШЛО | НЕИЗВЕСТНО, подробности). Предмет — ЧИСЛО ОТПРАВЛЕННЫХ КЛИЕНТУ, и ничего
    больше: ни флаг, ни живой процесс, ни строка кода этой функции не видны вовсе.

    ПОРЯДОК ПРОВЕРОК — ЗАМОК, А НЕ ПОРЯДОК СТРОК. Второй свидетель (реестр попыток) спрашивается
    ДО того, как проверена читаемость очереди: reply-режим в очередь не пишет ВООБЩЕ, значит
    непрочитанная очередь не вправе спрятать отправку, о которой реестр уже знает. Правило
    односторонней громкости: добавить нарушение свидетель может, снять — не может ни одной ветвью.

    ТРИ ИСХОДА, и «неизвестно» возвращается на каждую дырку: ветка выключена порогом · факта нет
    вовсе · источник не прочитан · счётчик не разобран. Ни одна дорога отсюда не ведёт к «тихо»
    иначе как через ПРОЧИТАННЫЙ ноль."""
    cfg = cfg if isinstance(cfg, dict) else config()
    if float(cfg.get("client", 0.0)) <= 0:
        return CLIENT_UNKNOWN, {"why": "ветка О5 выключена порогом"}          # откат
    src = facts.get("client") if isinstance(facts, dict) else None
    if not isinstance(src, dict):
        return CLIENT_UNKNOWN, {"why": "факта об отправленном клиенту нет вовсе"}
    raw_pairs = src.get("pairs")
    pairs = raw_pairs if isinstance(raw_pairs, dict) else {}
    second = None
    if pairs.get("ok") is True:
        second = _int_or_none(pairs.get("sent"))
    info = {"sent": None, "second": second, "pairs_ok": pairs.get("ok"),
            "pairs_err": pairs.get("err"), "pairs_last": pairs.get("last"),
            "armed": _int_or_none(src.get("armed")),
            "attempted": _int_or_none(src.get("attempted")),
            "total": _int_or_none(src.get("total")),
            "last": src.get("last_sent"), "why": ""}
    if src.get("ok") is True:
        info["sent"] = _int_or_none(src.get("sent"))
    if second is not None and second > 0:
        return CLIENT_SPOKE, info
    if src.get("ok") is not True:
        err = src.get("err")
        info["why"] = ("источник истины не прочитан (%s)"
                       % ("причина не названа" if err is None else err))
        return CLIENT_UNKNOWN, info
    if info["sent"] is None:
        info["why"] = "счётчик отправленных не разобран"
        return CLIENT_UNKNOWN, info
    if info["sent"] > 0:
        return CLIENT_SPOKE, info
    return CLIENT_SILENT, info


# ═══ О6: ПРОЦЕСС НЕСЁТ ТО, ЧТО ЛЕЖИТ НА ДИСКЕ (замыкание импортов, а не список имён) ════════
def code_state(name, facts, cfg=None, now=None):
    """Состояние ОДНОГО наблюдаемого процесса по его ЗАМЫКАНИЮ → (состояние, подробности).

    Предмет — ДВА ЧИСЛА и их разность: `newest` (самая свежая mtime среди файлов import-замыкания
    процесса, посчитанного ТЕМ ЖЕ обходом, что держит ворота клиентского контура) и `started`
    (момент запуска процесса, снятый пробой ОС). `behind = newest - started` больше нуля значит
    буквально «на диске новее, чем в памяти».

    ПОРЯДОК ВЕТОК — ЧАСТЬ СМЫСЛА, и он ОБРАТЕН порядку О1–О5 в одном месте: здесь каждая дырка
    ведёт к «неизвестно», а «неизвестно» ставит пометку, а не снимает её.
      1. порог 0 → ветка мертва целиком (объявленный откат) — и это ЕДИНСТВЕННАЯ дорога к
         молчанию, объявленная человеком;
      2. процесса нет в перечне наблюдаемых → «неизвестно»: сочинять входную точку некому;
      3. факта нет вовсе → «неизвестно»;
      4. ЗАМЫКАНИЕ НЕ ПОСЧИТАНО (граф не построился, каталог не читается) → «неизвестно». Ровно
         здесь молчание было бы дороже всего: не зная зависимостей, мы не знаем и о протухании;
      5. самой свежей правки не разобрать → «неизвестно»;
      6. процесса по локу в системе НЕТ → «неизвестно»: о коде того, кого не существует, судить
         нечем, а лечит смерть контур-вотчдог, а не эта ветка;
      7. момент запуска не добыт → «неизвестно»;
      8. процесс МОЛОЖЕ самой свежей правки (behind <= 0) → «код с диска»;
      9. расхождение не больше порога → «код с диска», и причина названа числом: доставка законно
         занимает время (у демона измеренные 28 с);
     10. иначе — «на диске новее»."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("code") or 0.0)
    info = {"name": name, "limit": limit}
    if limit <= 0:
        return CODE_UNKNOWN, dict(info, off=True, why="ветка О6 выключена порогом")
    if name not in CODE_WATCHED:
        return CODE_UNKNOWN, dict(info, why="процесса «%s» в перечне наблюдаемых нет" % name)
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return CODE_UNKNOWN, dict(info, why="время прогона не разобрано")
    src = (facts or {}).get("code") if isinstance(facts, dict) else None
    fact = src.get(name) if isinstance(src, dict) else None
    if not isinstance(fact, dict):
        return CODE_UNKNOWN, dict(info, why="факта о замыкании %s нет вовсе" % name)
    files = _int_or_none(fact.get("files"))
    newest = _float_or_none(fact.get("newest"))
    started = _float_or_none(fact.get("started"))
    info.update({"files": files, "newest": newest, "newest_file": fact.get("newest_file"),
                 "started": started, "pid": fact.get("pid"), "entry": fact.get("entry"),
                 # УЛИКА ЕДЕТ РЯДОМ С ВЕРДИКТОМ И НИКОГДА КАК ДОВОД: сколько файлов замыкания
                 # рукописная карта демона не знает. Ни одна ветка ниже её не читает — решение
                 # принимается вычислением, а карта тут только для того, чтобы её отставание было
                 # ВИДНО владельцу тем же сообщением.
                 "gap": fact.get("gap"), "mapped": _int_or_none(fact.get("mapped")),
                 "age": None if started is None else now - started})
    if fact.get("ok") is not True:
        return CODE_UNKNOWN, dict(info, why="замыкание %s не посчитано (%s)"
                                            % (name, fact.get("reason") or "причина не названа"))
    if newest is None or newest <= 0:
        return CODE_UNKNOWN, dict(info, why="самой свежей правки в замыкании %s не разобрать" % name)
    if fact.get("opened") is False:
        return CODE_UNKNOWN, dict(info, dead=True,
                                  why="процесса PID %s из лока в системе нет — о коде мёртвого "
                                      "судить нечем" % fact.get("pid"))
    if started is None or started <= 0:
        return CODE_UNKNOWN, dict(info, why="момент запуска %s не добыт (%s)"
                                            % (name, fact.get("err") or "проба не сделана"))
    behind = newest - started
    info["behind"] = behind
    if behind <= 0:
        return CODE_FRESH, dict(info, why="процесс запущен позже самой свежей правки замыкания")
    if behind <= limit:
        return CODE_FRESH, dict(info, why="расхождение %s меньше порога %s — доставка законно "
                                          "занимает время" % (_age_short(behind), _mins(limit)))
    # ВТОРАЯ ОСЬ — И ОНА ОТВЕЧАЕТ НА ДРУГОЙ ВОПРОС. `behind` говорит, НАСКОЛЬКО процесс позади;
    # `waited` — СКОЛЬКО МЫ УЖЕ ЖДЁМ обновления. Смешивать их нельзя: у процесса, живущего вторые
    # сутки, behind равен этим суткам с первой же минуты после коммита, и по нему тревога звучала
    # бы мгновенно — ровно та авария, которой на деле нет.
    #
    # СЧИТАЕМ ОТ `since`, А НЕ ОТ `newest`, И ЭТО НЕ ДЕТАЛЬ. `since` — самая РАННЯЯ правка, которую
    # процесс ещё не взял; она неподвижна, пока живёт воплощение. `newest` же едет вперёд с каждым
    # чужим коммитом в замыкание, и ожидание, считанное от него, обнулялось бы раньше, чем истекал
    # бы срок: замер 05.09 — userbot не перезапускался с 03.09 (отстал на 2 сут), а `now - newest`
    # у него 6 мин. Тревога по `newest` не прозвучала бы ни разу НИКОГДА — то самое смягчение,
    # которое съедает настоящий отказ.
    #
    # `since` НЕТ (старая форма фактов, чужой вызов) — считаем от `newest` и ГОВОРИМ ОБ ЭТОМ в
    # заметке: такая оценка ожидания ЗАНИЖЕНА, то есть ветка тише, чем должна быть, и молчать о
    # собственной глухоте она не вправе.
    since = _float_or_none(fact.get("since"))
    info["since"] = since
    info["wait_exact"] = since is not None
    waited = max(0.0, now - (since if since is not None else newest))
    wait_limit = float(cfg.get("code_wait") or 0.0)
    info["waited"] = waited
    info["wait_limit"] = wait_limit
    # Ноль на второй оси — объявленный откат ТОЛЬКО тревоги: `late` не станет истиной никогда,
    # расхождение продолжит говориться новостью. Первую ось это не трогает.
    info["late"] = bool(wait_limit > 0 and waited > wait_limit)
    info["say"] = CODE_SAY_LATE if info["late"] else CODE_SAY_NEWS
    return CODE_STALE, info


def code_states(facts, cfg=None, now=None):
    """Состояние КАЖДОГО наблюдаемого процесса ПОИМЁННО → [{"name","state","why",…}].

    Зовётся КАЖДЫЙ прогон и целиком пересчитывается из фактов — в этом вся правка 02.09.2026.
    Прежняя пометка была СОБЫТИЕМ («pc_agent изменён» в момент self-update) и говорилась один раз;
    состояние же не умеет замолчать, пока расхождение живо."""
    cfg = cfg if isinstance(cfg, dict) else config()
    out = []
    for name in CODE_WATCHED:
        state, info = code_state(name, facts, cfg, now)
        info = info if isinstance(info, dict) else {}
        out.append({"name": name, "state": state, "why": info.get("why", ""),
                    "behind": info.get("behind"), "files": info.get("files"),
                    "newest_file": info.get("newest_file"), "gap": info.get("gap"),
                    "mapped": info.get("mapped"), "age": info.get("age"),
                    "started": info.get("started"), "newest": info.get("newest"),
                    # Вторая ось едет ПОИМЁННО рядом с первой: читающий обязан видеть, что
                    # «просрочено» — это про СРОК ОЖИДАНИЯ, а не про величину расхождения.
                    "waited": info.get("waited"), "wait_limit": info.get("wait_limit"),
                    "since": info.get("since"), "wait_exact": info.get("wait_exact"),
                    "late": info.get("late"), "say": info.get("say"),
                    "pid": info.get("pid"), "off": info.get("off")})
    return out


def su_state(facts):
    """ПОЧЕМУ обновление не случилось → (причина, подробности). Чистая функция фактов.

    Три исхода, и они РАЗНОЙ ОПАСНОСТИ — в этом весь смысл разделения (п.6 задания):
      `SU_GATE`  — самообновление отказало ЗАЯВЛЕННО: гейт кода/тестов красный. Механизм жив и
                   работает по правилам; чинить надо тесты, а не механизм;
      `SU_DIRTY` — ворота авто-рестарта отказали: рабочее дерево грязное. Тоже заявленный отказ
                   (живой случай 03.09.2026: 8.12 ч ожидания, причина в логе названа);
      `SU_QUIET` — источник ПРОЧИТАН и отказа в нём НЕТ. Это самый опасный исход: обновления нет и
                   никто не сказал почему — то есть механизм не отказал, а ПРОМОЛЧАЛ;
      `SU_BLIND` — источник не читается. «Неизвестно», а не «в порядке»: слепота благополучием не
                   является ни на одной дороге.
    Раздела `su` в фактах нет вовсе (старая форма, чужой вызов) → тоже `SU_BLIND`: приговор о
    причине на непроизведённом наблюдении не строят."""
    src = (facts or {}).get("su") if isinstance(facts, dict) else None
    if not isinstance(src, dict):
        return SU_BLIND, {"why": "фактов о самообновлении нет вовсе — причину назвать нечем"}
    if src.get("ok") is not True:
        return SU_BLIND, {"why": "источник самообновления не прочитан (%s)"
                                 % (src.get("reason") or "причина не названа")}
    kind = str(src.get("kind") or "")
    if kind == "gate":
        return SU_GATE, {"why": src.get("why") or "гейт самообновления провален",
                         "at": _float_or_none(src.get("at")), "what": src.get("what")}
    if kind == "dirty":
        return SU_DIRTY, {"why": src.get("why") or "рабочее дерево грязное",
                          "at": _float_or_none(src.get("at")), "what": src.get("what")}
    return SU_QUIET, {"why": "самообновление об отказе не сообщало — почему обновления нет, "
                             "НЕИЗВЕСТНО", "at": _float_or_none(src.get("at"))}


# ═══════════════════════════ РЕШЕНИЕ: ЧИСТАЯ ФУНКЦИЯ ФАКТОВ ════════════════════════════════
def _o1(facts, cfg, now):
    """О1 — строка полосы ПК не сменила состояние за отведённое время. Две ветки, два порога."""
    out = []
    rows = _rows(facts)
    if rows is None:
        return out                                    # снимка нет → фактов нет → молчим
    pc = [r for r in rows if _lane(r) == LANE]
    wait_limit = float(cfg.get("new") or 0.0)
    run_limit = float(cfg.get("run") or 0.0)
    busy_row = any(_status(r) == "in_progress" for r in pc)
    for r in pc:
        st = _status(r)
        try:
            since = float(r.get("since") or 0.0)
        except (TypeError, ValueError):
            continue
        if since <= 0:
            continue
        age = now - since
        if st in WAIT_STATUSES and wait_limit > 0:
            if busy_row:
                continue                              # исполнитель занят — законная очередь
            # ПОРОГ БЕРЁТ ЧИСТОЕ ОЖИДАНИЕ, а не возраст строки: сколько она простояла ИМЕННО ПРИ
            # СВОБОДНОЙ полосе. Счётчик копят руки; факта нет → нарушения нет (fail-safe в молчание).
            try:
                free = float(r.get("free_wait") or 0.0)
            except (TypeError, ValueError):
                continue
            if free <= wait_limit or _step_blocked(r, rows):
                continue
            out.append({"kind": "o1_pc_new", "key": "o1n|%s|%d" % (r.get("id"), int(since)),
                        "id": r.get("id"), "from": str(r.get("from") or ""), "status": st,
                        "age": age, "free": free, "limit": wait_limit})
        elif st == "in_progress" and run_limit > 0 and age > run_limit:
            out.append({"kind": "o1_pc_run", "key": "o1r|%s|%d" % (r.get("id"), int(since)),
                        "id": r.get("id"), "from": str(r.get("from") or ""), "status": st,
                        "age": age, "limit": run_limit})
    return out


