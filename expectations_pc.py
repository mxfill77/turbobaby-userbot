def kid_state(name, facts, cfg=None, now=None):
    """Состояние ОДНОГО ребёнка по ЕГО СОБСТВЕННОМУ признаку → (состояние, подробности).

    Судится ПРОДУКТ, а не существование процесса: живой PID работающим сервисом не является —
    залипший event-loop остаётся в списке процессов, а продукта не даёт. Слова у всех троих одни
    и те же («делает работу» / «работы нет» / «неизвестно»), а вот ИСТОЧНИК и ПРЕДЕЛ — у каждого
    свои (`KID_SIGNS`), и в этом весь смысл правки 18.08.2026.

    ПОРЯДОК ВЕТОК — ЧАСТЬ СМЫСЛА:
      1. признака нет в таблице → «неизвестно»: сочинять его на месте некому;
      2. факта нет вовсе → «неизвестно»;
      3. порог 0 → ветка этого ребёнка мертва (объявленный откат);
      4. признак НЕ ДОКАЗЫВАЕТ живость (двигается под нагрузкой, замирает в простое) →
         «неизвестно» ВСЕГДА, каким бы свежим он ни был;
      5. процесса из лока в системе НЕТ → «работы нет». Это и есть правка живого случая 18.08:
         прежде здесь стояло «неизвестно», и заведомо мёртвый ребёнок со свежей записью в ОБЩЕМ
         канале выглядел непроверяемым;
      6. источник не прочитан / время не разобрано → «неизвестно»;
      7. накопленная тишина больше предела → «работы нет»; иначе продукт свеж — и слово даёт
         `_kid_fresh`, которому нужна ещё и живая проба;
      8. тишина не измерена, а стенной возраст больше предела → «неизвестно»: чем набран возраст,
         молчанием ребёнка или сном машины, здесь не известно."""
    cfg = cfg if isinstance(cfg, dict) else config()
    sign = KID_SIGNS.get(name)
    if not isinstance(sign, dict):
        return MOD_UNKNOWN, {"name": name, "why": "собственного признака у «%s» в таблице нет" % name}
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return MOD_UNKNOWN, {"name": name, "why": "время прогона не разобрано"}
    fact, sil = _kid_slot(name, facts)
    if not isinstance(fact, dict):
        return MOD_UNKNOWN, {"name": name,
                             "why": ("факта о модерботе нет вовсе" if name == KIDS_JUDGED
                                     else "факта о продукте %s нет вовсе" % name)}
    limit = kid_limit(name, cfg)
    if limit <= 0:
        return MOD_UNKNOWN, {"name": name,
                             "why": ("ветка О3 выключена порогом" if name == KIDS_JUDGED
                                     else "наблюдение за %s выключено порогом" % name)}
    who = kid_writer(fact)
    ts = _float_or_none(fact.get("own"))
    wall = None if (ts is None or ts <= 0) else now - ts
    awake, since = None, None
    if isinstance(sil, dict) and sil.get("measured"):
        awake = _float_or_none(sil.get("awake"))
        since = sil.get("since")
    channel = _float_or_none(fact.get("channel"))
    info = {"name": name, "limit": limit, "ts": ts, "wall": wall, "pid": fact.get("pid"),
            "who": who, "src": sign.get("src"), "tick": sign.get("tick"), "since": since,
            # ОБЩИЙ КАНАЛ ЕДЕТ РЯДОМ КАК СВЕДЕНИЕ И НИКОГДА КАК ДОВОД: ни одна ветка ниже его не
            # читает. Он нужен владельцу, чтобы видеть обе величины разом — «канал свеж, а его
            # собственного продукта нет» и есть точное описание случая 18.08.
            "channel": channel, "channel_age": None if channel is None else now - channel}
    if awake is not None:
        info["awake"] = awake
        if wall is not None:
            info["slept"] = max(0.0, wall - awake)
    if sign.get("idle_proof") is not True:
        return MOD_UNKNOWN, dict(info, why="признак «%s» двигается под нагрузкой и замирает в "
                                           "простое — живостью он не является" % sign.get("src"))
    if who is False:
        return MOD_IDLE, dict(info, dead=True,
                              why="процесса PID %s из лока в системе нет — свой продукт "
                                  "производить некому" % fact.get("pid"))
    if not fact.get("ok"):
        return MOD_UNKNOWN, dict(info, why="продукт %s не прочитан (%s)"
                                           % (name, fact.get("err") or "причина не названа"))
    if wall is None:
        return MOD_UNKNOWN, dict(info, why="время последней записи (%s) не разобрано"
                                           % sign.get("src"))
    if awake is not None:
        if awake > limit:
            return MOD_IDLE, info
        return _kid_fresh(info, who)
    if wall <= limit:
        return _kid_fresh(info, who)
    return MOD_UNKNOWN, dict(info, why="запись старше порога, но чем набран возраст — молчанием "
                                       "%s или сном машины — не измерено (%s)"
                                       % (name, (sil or {}).get("why") or "накопленной тишины нет"))


