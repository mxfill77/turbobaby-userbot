def human_age(sec):
    """«48 мин» / «5 ч 12 мин» / «1 сут 10 ч». Ноль дробей: заметку читают с телефона."""
    s = max(0, int(sec or 0))
    d, rest = divmod(s, 86400)
    h, rest = divmod(rest, 3600)
    m = rest // 60
    if d:
        return "%d сут %d ч" % (d, h)
    if h:
        return "%d ч %d мин" % (h, m)
    return "%d мин" % m


def _mins(sec):
    return "%d мин" % int(round(float(sec or 0) / 60.0))


def render(v, lane="ПК"):
    """Текст заметки. Отправляет её РУКА (expectations_pc_run) — модуль решения в канал не ходит."""
    kind = str((v or {}).get("kind") or "")
    parts = [NOTE_HEAD.get(kind, "🔔 ожидание нарушено"), str(lane or "ПК")]
    if kind == "o1_pc_new":
        parts += [
            "задача %s (%s) стои́т в `%s` %s" % (v.get("id"), v.get("from") or "?",
                                                 v.get("status"), human_age(v.get("age"))),
            # ОБА числа названы: общий возраст — то, что видно глазами в очереди; чистое ожидание —
            # то, ПО ЧЕМУ взят порог. Без второго заметка выглядела бы придиркой к живой очереди.
            "из них %s при СВОБОДНОЙ полосе (порог %s), сейчас на pc ни одной строки in_progress"
            % (human_age(v.get("free")), _mins(v.get("limit"))),
        ]
    elif kind == "o1_pc_run":
        parts += [
            "задача %s (%s) висит in_progress %s (порог %s)"
            % (v.get("id"), v.get("from") or "?", human_age(v.get("age")), _mins(v.get("limit"))),
            "это дольше всех сроков полосы (прогон 45 мин, повтор 45 мин, реапер одиночек 90 мин) "
            "— значит её не закрыл и собственный реапер демона",
        ]
    elif kind == "o2_pc_turn":
        parts += [
            "последний оборот poll_once %s назад по часам бодрствования (порог %s)"
            % (human_age(v.get("awake")), _mins(v.get("limit"))),
            "по стенным часам %s, из них сон машины %s — сон в счёт не идёт"
            % (human_age(v.get("wall")), human_age(v.get("slept"))),
            "очередь ПК не движется, пока это так; жив ли процесс — по этому факту не сужу",
        ]
        od = v.get("overdue") or None
        if isinstance(od, dict):
            # Идущий заход молчание оправдывает (это работа), но ПЕРЕЖИВШИЙ свой срок — нет:
            # значит не сработал собственный kill демона, и владелец должен это прочитать.
            parts.append("заход id=%s идёт %s при объявленном сроке %s — свой kill не сработал"
                         % (od.get("task"), human_age(od.get("age")), _mins(od.get("limit"))))
    elif kind == "o3_pc_moderbot":
        who = v.get("who")
        parts += [
            "своей записи в moderation_ipc нет %s по часам бодрствования (порог %s, тик бота 5с)"
            % (human_age(v.get("awake")), _mins(v.get("limit"))),
            "по стенным часам %s, из них сон машины %s — сон в счёт не идёт"
            % (human_age(v.get("wall")), human_age(v.get("slept"))),
        ]
        # Состояние процесса называется ОТДЕЛЬНОЙ строкой и после продукта — потому что это разные
        # новости: «жив, но молчит» чинится иначе, чем «его нет», и владелец обязан прочитать что
        # именно из двух. Третьей строкой честно живёт «не знаю».
        if who is True:
            parts.append("процесс PID %s жив — живой PID работающим сервисом не является: "
                         "тик не идёт" % v.get("pid"))
        elif who is False:
            parts.append("процесса PID %s из лока в системе нет — модербот не запущен; свежую "
                         "запись в IPC, если она есть, делал кто-то другой" % v.get("pid"))
        else:
            parts.append("жив ли процесс — не проверено: сужу только по отсутствию продукта")
        parts.append("клиент этого не видит: userbot зовёт его мёртвым уже через 15с тишины и "
                     "черновики ему не отдаёт")
    else:
        parts.append("нарушение ожидания")
    parts.append(TAIL)
    return " · ".join(parts)


# ПУЛЬС — НЕ ЗАМЕТКА ВЛАДЕЛЬЦУ, А СТРОКА ЖУРНАЛА, и адресована она наблюдателю ВНЕ машины. Тип
# `NOTE` стои́т первым словом намеренно: писатель journal-строки берёт тип из первого слова
# (`cowork_log_append.LOG_TYPES`), а всё неопознанное молча становится `DONE` — пульс, ставший
# «DONE», врал бы о сделанной работе.
PULSE_HEAD = "NOTE ПУЛЬС"


def render_pulse(v, lane="ПК"):
    """Строка пульса в журнал. Говорит РОВНО то, что доказано, и НАЗЫВАЕТ СВОЮ ЦЕНУ: читающий
    обязан понимать, что молчание этой строки — новость, а не тишина по бездействию."""
    v = v if isinstance(v, dict) else {}
    turn = v.get("turn") if isinstance(v.get("turn"), dict) else {}
    parts = [PULSE_HEAD, str(lane or "ПК"),
             "контур жив: оборот poll_once %s назад" % human_age(turn.get("wall")),
             "следа работы в журнале нет %s (порог пульса %s)"
             % (human_age(v.get("silence")), _mins(v.get("limit")))]
    slept = float(turn.get("slept") or 0.0)
    if slept > 60:
        # Сон машины называется ОТДЕЛЬНО: без этого «оборот 9 ч назад» читалось бы как поломка.
        parts.append("по часам бодрствования %s, сон машины %s в счёт не идёт"
                     % (human_age(turn.get("awake")), human_age(slept)))
    parts.append("это след ЖИЗНИ, а не отчёт о работе: пишется только при ДОКАЗАННОМ обороте, "
                 "поэтому его молчание значит «ПК не даёт оборота», а не «задач не было»")
    return " · ".join(parts)


def render_close(key, lane="ПК", detail=""):
    """Закрытие эпизода — одна строка тем же семейством. Без неё владелец не знает, кончилось ли."""
    head = str(key or "").split("|", 1)[0]
    what = {"o1n": "очередь ПК снова движется",
            "o1r": "задача больше не висит в работе",
            "o2t": "демон ПК снова даёт оборот",
            "o3m": "модербот снова делает свою работу: своя запись в IPC подтверждена"
            }.get(head, "ожидание снова выполняется")
    parts = [CLOSE_HEAD, str(lane or "ПК"), what]
    if detail:
        parts.append(str(detail))
    return " · ".join(parts)
