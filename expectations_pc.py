# ═══════════════════ РАЗБОР СЫРЫХ СТРОК (текст → число; мира не касается) ═══════════════════
def parse_iso(val):
    """ISO-время очереди («2026-08-04T16:52:10.902Z») → эпоха | None. Мусор → None (молчим).

    ЖИВОЙ ФОРМАТ снят с прода, а не идеализирован: мост отдаёт «…Z», а heartbeat демона пишет
    `datetime.now(timezone.utc).isoformat()` — «2026-08-11T04:44:17.163000+00:00». Строка БЕЗ
    зоны читается как UTC: очередь и heartbeat пишут UTC, а машина живёт в UTC+7, и локальное
    чтение дало бы ошибку в семь часов — ровно тот класс, из-за которого cclog считает время сам.
    """
    s = str(val or "").strip()
    if not s:
        return None
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    try:
        dt = datetime.datetime.fromisoformat(s)
    except (ValueError, TypeError):
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=datetime.timezone.utc)
    try:
        return dt.timestamp()
    except (OverflowError, OSError, ValueError):
        return None


STEP_RE = re.compile(r"^\[шаг (\d+)/(\d+) родитель (\d+)\]")   # зеркало _STEP_RE демона
DEC_WAIT_STATUSES = ("in_progress", "needs_approval", "approved")


def _rows(facts):
    """Строки снимка очереди | None (снимка нет → фактов нет → молчим)."""
    q = (facts or {}).get("queue") or {}
    if not q.get("ok"):
        return None
    return [r for r in (q.get("rows") or []) if isinstance(r, dict)]


def _lane(row):
    return str(row.get("lane") or "").strip().lower()


def _status(row):
    return str(row.get("status") or "").strip().lower()


def _step_blocked(row, rows):
    """Зеркало гварда последовательности демона: шаг цепочки ждёт ЗАКОННО, пока у его родителя
    открыт другой шаг. → True = нарушением это НЕ считается.

    Без этого зеркала первая же красная цепочка рождала бы заметку каждый прогон, пока владелец
    не ответит: сиблинг в `needs_approval` ждёт ЧЕЛОВЕКА и может ждать сутками."""
    m = STEP_RE.match(str(row.get("text") or ""))
    if not m:
        return False
    num, parent = int(m.group(1)), int(m.group(3))
    for other in rows:
        if other is row:
            continue
        st = _status(other)
        if st not in OPEN_STATUSES:
            continue
        try:
            oid = int(other.get("id") or 0)
        except (TypeError, ValueError):
            oid = 0
        if oid == parent:                              # родитель цепочки ещё открыт
            return True
        om = STEP_RE.match(str(other.get("text") or ""))
        if not om or int(om.group(3)) != parent:
            continue
        if st in DEC_WAIT_STATUSES:                    # сиблинг занят / ждёт владельца
            return True
        if st == "new" and int(om.group(1)) < num:     # впереди шаг с меньшим номером
            return True
    return False


