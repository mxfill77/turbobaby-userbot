def queue_state(facts, cfg=None, now=None):
    """→ (состояние, подробности). ТРЕТИЙ ИСХОД ЗДЕСЬ НЕ УКРАШЕНИЕ: снимок очереди приходит через
    мост, который может лежать. «Мост молчит» и «очередь движется» — разные новости, и подменять
    вторую первой значит соврать в самую дорогую сторону."""
    q = (facts or {}).get("queue")
    if not isinstance(q, dict):
        return QUEUE_UNKNOWN, {"why": "снимка очереди в фактах нет вовсе"}
    if not q.get("ok"):
        return QUEUE_UNKNOWN, {"why": "снимок очереди не получен (%s)"
                                      % (q.get("err") or "причина не названа")}
    rows = [r for r in (q.get("rows") or []) if isinstance(r, dict) and _lane(r) == LANE]
    try:
        stuck = bool(_o1(facts, cfg if isinstance(cfg, dict) else config(),
                         float((facts or {}).get("now") or 0.0) if now is None else float(now)))
    except Exception:                                # noqa: BLE001 — кривая строка не смеет
        return QUEUE_UNKNOWN, {"why": "снимок есть, но разобрать его не удалось"}
    return (QUEUE_STUCK if stuck else QUEUE_OK), {"rows": len(rows)}


def busy_state(facts, now, turn_ts=None):
    """Объявлена ли работа → (исход, подробности | None). Исходов ТРИ, и средний не равен первому.

    ПРЕДМЕТ — момент, когда полоса в последний раз ОБЪЯВИЛА работу. Руки снимают его как время
    правки реестра отметок, и ровно тот же факт тем же способом читает сторож самого демона
    (`pc_orchestrator._wd_busy_age`). Ни одного ПОЛЯ внутри реестра здесь не спрашивается
    СОЗНАТЕЛЬНО: id строк очереди переиспользуются, и поле `at` повторно выданного номера
    принадлежит прошлому воплощению задачи, а не идущей работе (живой провал 17.08.2026).

      · РАБОТА ИДЁТ — объявление СВЕЖЕЕ последнего оборота и не старше «свой срок + хвост»;
      · РАБОТЫ НЕТ — объявлять было нечего · объявление не позже оборота (тот заход этим оборотом
        уже замкнут, и молчание ПОСЛЕ него он не оправдывает) · объявление пережило свой срок;
      · НЕИЗВЕСТНО — факта нет вовсе · реестр не прочитан · часы разъехались. Ни одна из этих
        дорог не ведёт ни к «работа идёт», ни к приговору.

    ЗАМОК «ПОЗЖЕ ОБОРОТА» ПРИШЁЛ ВМЕСТЕ С ПРЕДМЕТОМ и без него не работает: реестр на завершении
    задачи НЕ чистится, поэтому след давно закрытого захода иначе вечно выдавал бы стоящий демон
    за работающий — та же ошибка предмета, только на файле вместо поля.

    Слепота ограничена СВЕРХУ и только этим: доверяем штампу не дольше, чем полоса объявила себе
    сама (`TASK_TIMEOUT`) плюс хвост оборота. Штамп мёртвого экземпляра поэтому не оправдывает
    ничего дольше 55 минут — иначе смерть посреди задачи выглядела бы работой ВЕЧНО, то есть
    детектор терял бы зубы ровно там, где он нужнее всего.

    Подробности отдаются и во ВТОРОМ исходе — но только когда объявление свежее оборота и просто
    пережило срок: это и есть «свой kill не сработал», и владелец обязан это прочитать."""
    b = (facts or {}).get("busy")
    if not isinstance(b, dict) or not b.get("ok"):
        return BUSY_UNKNOWN, None
    try:
        since = float(b.get("since") or 0.0)
        now = float(now)
    except (TypeError, ValueError):
        return BUSY_UNKNOWN, None
    if since <= 0:
        return BUSY_IDLE, None                 # реестр прочитан, объявлять нечего
    if turn_ts is not None:
        try:
            if since <= float(turn_ts):
                return BUSY_IDLE, None         # объявление не позже оборота — тот заход замкнут
        except (TypeError, ValueError):
            return BUSY_UNKNOWN, None
    age = now - since
    if age < -BUSY_SKEW_SEC:
        return BUSY_UNKNOWN, None              # отметка из будущего: часам верить нельзя
    try:
        declared = float(b.get("limit") or 0.0)
    except (TypeError, ValueError):
        declared = 0.0
    declared = min(max(declared, 0.0), BUSY_MAX_SEC) or TASK_TIMEOUT_SEC
    info = {"since": since, "age": max(0.0, age), "limit": declared,
            "allow": declared + BUSY_GRACE_SEC}
    return (BUSY_RUN if info["age"] <= info["allow"] else BUSY_IDLE), info


def turn_state(facts, cfg=None, now=None):
    """→ (состояние, подробности). Судит ПРОДУКТ демона — оборот `poll_once`, а не признак жизни.

    ПОЧЕМУ ТИШИНА МЕРИТСЯ НЕ СТЕННЫМИ ЧАСАМИ. ПК спит; во сне не крутится никто, и это не поломка
    демона (о сне он сам пишет карточку «🛌 ПК СПАЛ»). Возраст heartbeat по стенным часам после
    девятичасового сна равен девяти часам — и заметка о «вставшем демоне» была бы ложью о предмете.
    Поэтому руки накапливают тишину В ЧАСАХ БОДРСТВОВАНИЯ, наблюдение за наблюдением; здесь только
    сравнение с порогом.

    ТРИ ИСХОДА. «Неизвестно» возвращается на КАЖДУЮ дырку в фактах: heartbeat не прочитан · время
    в нём не разобрано · накопленной тишины нет (первый прогон наблюдателя, потерянное состояние,
    перезагрузка машины) · часов бодрствования на этой машине нет. Ни одна из этих дорог не ведёт
    к «жив».

    ПОРЯДОК ПРОВЕРОК. Штамп занятости спрашивается ДО измеренной тишины: «демон объявил заход
    id=N столько-то минут назад» — это положительный факт с потолком, а не отсутствие факта, и
    отвечать на него «неизвестно» значило бы прятать известное. Всё остальное — после."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("turn") or 0.0)
    hb = (facts or {}).get("heartbeat")
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return TURN_UNKNOWN, {"why": "время прогона не разобрано"}
    if not isinstance(hb, dict):
        return TURN_UNKNOWN, {"why": "факта о heartbeat нет вовсе"}
    if limit <= 0:
        return TURN_UNKNOWN, {"why": "ветка О2 выключена порогом"}          # откат
    if not hb.get("ok"):
        return TURN_UNKNOWN, {"why": "heartbeat демона не прочитан (%s)"
                                     % (hb.get("err") or "причина не названа")}
    ts = parse_iso(hb.get("raw")) if hb.get("ts") is None else hb.get("ts")
    try:
        ts = None if ts is None else float(ts)
    except (TypeError, ValueError):
        ts = None
    if ts is None or ts <= 0:
        return TURN_UNKNOWN, {"why": "время в heartbeat не разобрано (%.60s)" % str(hb.get("raw"))}
    wall = now - ts
    if wall <= limit:
        return TURN_OK, {"wall": wall, "limit": limit, "ts": ts}
    bstate, busy = busy_state(facts, now, turn_ts=ts)
    if bstate == BUSY_UNKNOWN:
        # ШТАМП НЕ ПРОЧИТАН. Отличить идущую работу от остановки нечем — а «нечем отличить» это
        # третий исход, а не второй: приговор здесь был бы догадкой, а молчание — ложным зелёным.
        b = (facts or {}).get("busy")
        why = (b.get("err") or "причина не названа") if isinstance(b, dict) \
            else "факта о штампе занятости нет вовсе"
        return TURN_UNKNOWN, {"why": "оборот молчит дольше порога, а объявлена ли сейчас работа "
                                     "— не прочитано (%s)" % why,
                              "wall": wall, "limit": limit, "ts": ts}
    if bstate == BUSY_RUN:
        # ОБОРОТ ИДЁТ: демон синхронно исполняет ОБЪЯВЛЕННЫЙ заход внутри poll_once. Продукт в
        # производстве — это работа, а не поломка (контрфакт замера: 25 ложных заметок за 20
        # суток). Проверка стои́т ДО измеренной тишины намеренно: штамп — положительный факт с
        # потолком (`allow`), а не отсутствие факта, и подменять его словом «неизвестно» значило
        # бы прятать известное.
        return TURN_OK, {"wall": wall, "limit": limit, "ts": ts, "busy": busy}
    # Возраст перешёл порог по СТЕННЫМ часам, и объявленным заходом он не объяснён. Чем он набран
    # — молчанием демона или сном машины — решает ТОЛЬКО накопленная тишина бодрствования.
    # Её нет → незнание, а не приговор.
    s = (facts or {}).get("silence")
    if not isinstance(s, dict) or not s.get("measured"):
        return TURN_UNKNOWN, {"why": "heartbeat старше порога, но чем набран возраст — молчанием "
                                     "демона или сном машины — не измерено (%s)"
                                     % ((s or {}).get("why") or "накопленной тишины нет"),
                              "wall": wall, "limit": limit, "ts": ts}
    try:
        awake = float(s.get("awake") or 0.0)
    except (TypeError, ValueError):
        return TURN_UNKNOWN, {"why": "накопленная тишина не разобрана", "wall": wall, "ts": ts}
    info = {"wall": wall, "awake": awake, "limit": limit, "ts": ts,
            "slept": max(0.0, wall - awake)}
    if awake <= limit:
        return TURN_OK, info
    if busy is not None:
        # Подробности во втором исходе бывают ровно в одном случае: работа объявлена ПОЗЖЕ
        # последнего оборота и пережила свой объявленный срок — это уже не работа.
        info["overdue"] = busy
    return TURN_SILENT, info


def moderbot_writer(facts):
    """Кто автор свежей записи в IPC: ТОТ САМЫЙ модербот (True) · заведомо не он (False) ·
    подтвердить нечем (None). Первая половина замка против ложного зелёного у О3.

    ЗАЧЕМ ЭТО ВООБЩЕ. Наблюдаемый факт — mtime ОБЩЕГО файла `moderation_ipc.db`, а писателей у
    него несколько: модербот тиком, userbot черновиками, тренажёр сессией. Свежесть файла поэтому
    доказывает «кто-то писал», а не «модербот работает»: мёртвый модербот при живом клиентском
    трафике выглядел бы здоровым ровно столько, сколько идёт трафик. Ответ склеен из ДВУХ
    положительных фактов — процесс с номером из лока существует И запущен тогда же, когда написан
    лок. Второй нужен против переиспользования PID: номер, доставшийся чужому процессу, иначе
    читался бы как «модербот на месте».

    Ни один провал не даёт True: нет лока · пробу не сделали · возрастов не добыли → None.
    """
    m = (facts or {}).get("moderbot")
    if not isinstance(m, dict):
        return None
    if not m.get("pid"):
        return None                                  # лока нет либо номер не разобран
    opened = m.get("opened")
    if opened is None:
        return None                                  # пробу процесса сделать не удалось
    if not opened:
        return False                                 # процесса с номером из лока в системе НЕТ
    try:
        started = m.get("started")
        lock_ts = m.get("lock_mtime")
        if started is None or lock_ts is None:
            return None                              # возраст запуска не добыт — авторство не наше дело выдумывать
        return abs(float(started) - float(lock_ts)) <= MOD_LOCK_SKEW_SEC
    except (TypeError, ValueError):
        return None


def _mod_fresh(info, who):
    """Продукт СВЕЖИЙ. «Свежий продукт» и «модербот работает» — разные утверждения, и второе
    выдаётся только при доказанном авторстве. Иначе третий исход, но не приговор."""
    if who is True:
        return MOD_OK, info
    if who is False:
        return MOD_UNKNOWN, dict(info, why="запись в IPC есть и она не стара, но процесса с "
                                           "номером из лока в системе нет — писал не модербот")
    return MOD_UNKNOWN, dict(info, why="запись в IPC не стара, но чья она — не подтверждено "
                                       "(процесс по локу не опрошен)")


def moderbot_state(facts, cfg=None, now=None):
    """→ (состояние, подробности). Судит ПРОДУКТ модербота — запись его пятисекундного тика, а не
    существование процесса. Живой PID работающим сервисом не является: залипший event-loop
    остаётся в списке процессов, а продукта не даёт.

    ПОРЯДОК ПРОВЕРОК. Накопленная тишина спрашивается ДО свежести файла НАМЕРЕННО: файл общий, и
    при мёртвом модерботе его двигает чужой писатель — «свежий mtime» тогда положительным фактом
    о модерботе не является, а накопленный счётчик своей записи является.

    ТРИ ИСХОДА, и «неизвестно» возвращается на каждую дырку: ветка выключена порогом · факта нет
    вовсе · `os.stat` не удался · время не разобрано · возраст перешёл порог, но чем он набран —
    молчанием бота или сном машины — не измерено · автор свежей записи не подтверждён."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("mod") or 0.0)
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return MOD_UNKNOWN, {"why": "время прогона не разобрано"}
    m = (facts or {}).get("moderbot")
    if not isinstance(m, dict):
        return MOD_UNKNOWN, {"why": "факта о модерботе нет вовсе"}
    if limit <= 0:
        return MOD_UNKNOWN, {"why": "ветка О3 выключена порогом"}                # откат
    if not m.get("ok"):
        return MOD_UNKNOWN, {"why": "продукт модербота не прочитан (%s)"
                                    % (m.get("err") or "причина не названа")}
    try:
        ts = float(m.get("mtime") or 0.0)
    except (TypeError, ValueError):
        ts = 0.0
    if ts <= 0:
        return MOD_UNKNOWN, {"why": "время последней записи в IPC не разобрано"}
    who = moderbot_writer(facts)
    wall = now - ts
    info = {"wall": wall, "limit": limit, "ts": ts, "pid": m.get("pid"), "who": who,
            "since": None}
    s = (facts or {}).get("mod_silence")
    awake = None
    if isinstance(s, dict) and s.get("measured"):
        try:
            awake = float(s.get("awake") or 0.0)
            info["since"] = s.get("since")
        except (TypeError, ValueError):
            awake = None
    if awake is not None:
        info.update({"awake": awake, "slept": max(0.0, wall - awake)})
        if awake > limit:
            return MOD_IDLE, info
        return _mod_fresh(info, who)
    if wall <= limit:
        return _mod_fresh(info, who)
    return MOD_UNKNOWN, dict(info, why="запись старше порога, но чем набран возраст — молчанием "
                                       "модербота или сном машины — не измерено (%s)"
                                       % ((s or {}).get("why") or "накопленной тишины нет"))


# ══════════════ О4: СЛЕД ЖИЗНИ НАРУЖУ (полоса свидетельствует, а не судит) ═════════════════
def life_state(facts, cfg=None, now=None):
    """Доказан ли ОБОРОТ прямо сейчас → (LIFE_PROVEN | LIFE_UNKNOWN, подробности).

    ОТЛИЧИЕ ОТ О2 РОВНО ОДНО, И ОНО — ЗАМОК. О2 спрашивает «встал ли демон» и законно принимает
    за работу ОБЪЯВЛЕННЫЙ синхронный заход (штамп CLAIM): продукт в производстве — это работа.
    О4 спрашивает другое — «есть ли ЧТО положить наружу как факт жизни», и штамп заход доказывает,
    а замкнутый виток — нет. Поэтому ветка `busy` здесь отвергается: пульс, написанный по штампу,
    пережил бы смерть демона посреди задачи и врал бы наружу ровно там, где нужнее всего правда.

    Всё прочее — три исхода О2, сведённые к двум: любое «неизвестно» остаётся «неизвестно» и
    пульса не пишет. Права сказать «мёртв» у этой функции нет вовсе (сказать это может только
    наблюдатель вне машины)."""
    cfg = cfg if isinstance(cfg, dict) else config()
    if float(cfg.get("life") or 0.0) <= 0:
        return LIFE_UNKNOWN, {"why": "ветка О4 выключена порогом"}                # откат
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return LIFE_UNKNOWN, {"why": "время прогона не разобрано"}
    if now <= 0:
        return LIFE_UNKNOWN, {"why": "времени прогона нет"}
    state, info = turn_state(facts, cfg, now)
    if state != TURN_OK:
        return LIFE_UNKNOWN, dict(info, why=(info.get("why") or "оборот не доказан: %s" % state))
    busy = info.get("busy")
    if isinstance(busy, dict):
        return LIFE_UNKNOWN, dict(info, why="тишину оборота объясняет объявленный заход (работа "
                                            "объявлена %s назад) — это работа, а не замкнутый "
                                            "виток" % human_age(busy.get("age")))
    return LIFE_PROVEN, dict(info)


def pulse_due(facts, cfg=None, now=None):
    """Пора ли оставить наружу след жизни → (bool, подробности).

    ПОРЯДОК ПРОВЕРОК ЗДЕСЬ — ЧАСТЬ СМЫСЛА:
      1. порог 0 → ветка мертва ДО чтения фактов (объявленный откат);
      2. следа не прочитали → молчим: не зная, когда полоса говорила в последний раз, пульс
         пришлось бы слать каждый тик — это долбёжка моста и мусор в журнале;
      3. след СВЕЖИЙ → молчать и есть правильный ответ: работа уже оставила след, дублировать
         его пульсом значит превращать журнал в кардиограмму;
      4. оборот не доказан → молчим ВСЕГДА (замок против ложного зелёного);
      5. недавняя попытка → пол повтора: спавн писателя докладывает о старте, а не об успехе."""
    cfg = cfg if isinstance(cfg, dict) else config()
    limit = float(cfg.get("life") or 0.0)
    if limit <= 0:
        return False, {"why": "ветка О4 выключена порогом"}
    try:
        now = float((facts or {}).get("now") or 0.0) if now is None else float(now)
    except (TypeError, ValueError):
        return False, {"why": "время прогона не разобрано"}
    t = (facts or {}).get("trace")
    if not isinstance(t, dict):
        return False, {"why": "факта о последнем следе нет вовсе"}
    if not t.get("ok"):
        return False, {"why": "реестр следов не прочитан (%s)" % (t.get("err") or "причина не названа")}
    try:
        ts = float(t.get("ts") or 0.0)
    except (TypeError, ValueError):
        ts = 0.0
    if ts <= 0 or now <= 0:
        return False, {"why": "время последнего следа не разобрано"}
    silence = now - ts
    if silence <= limit:
        return False, {"why": "след свежий: %s назад (порог %s)" % (human_age(silence), _mins(limit)),
                       "silence": silence, "limit": limit}
    state, info = life_state(facts, cfg, now)
    if state != LIFE_PROVEN:
        # ГЛАВНАЯ ВЕТКА ЗАМКА: молчание пульса — это честное «сказать наружу нечего», и именно оно
        # даёт серверному О4 право зазвучать. Пульс «на всякий случай» отнял бы у него зубы.
        return False, {"why": "оборот не доказан — наружу говорить нечего (%s)" % info.get("why"),
                       "silence": silence, "limit": limit}
    try:
        att = float(t.get("attempt") or 0.0)
    except (TypeError, ValueError):
        att = 0.0
    retry = float(cfg.get("life_retry") or 0.0)
    if att > 0 and retry > 0 and 0 <= (now - att) < retry:
        return False, {"why": "прошлая попытка пульса %s назад (пол повтора %s)"
                              % (human_age(now - att), _mins(retry)),
                       "silence": silence, "limit": limit}
    return True, {"silence": silence, "limit": limit, "turn": info, "ts": ts}


# ═════════ О5: КЛИЕНТАМ НЕ УХОДИТ НИЧЕГО (судится РЕЗУЛЬТАТ, а не флаг) ════════════════════
def _int_or_none(val):
    """Целое | None. `None` — честное «не знаю», и оно НЕ становится нулём НИ ОДНОЙ ветвью: у
    ожидания, чей ожидаемый результат и есть ноль, подмена незнания нулём читается как «ничего не
    ушло» — то есть как ложное благополучие."""
    if val is None:
        return None
    try:
        return int(val)
    except (TypeError, ValueError):
        return None


def _float_or_none(val):
    """То же для дробного: незнание доезжает наверх, а не превращается в 0.0."""
    if val is None:
        return None
    try:
        return float(val)
    except (TypeError, ValueError):
        return None


def client_spoken(info):
    """СКОЛЬКО ушло по совокупности свидетелей → число | None. МАКСИМУМ, а не сумма: свидетели не
    независимы (bot-режим пишет и в очередь, и в реестр попыток), и сумма удвоила бы одну и ту же
    отправку. Максимум — честный ПОЛ: «не меньше этого», и он не завышает новость."""
    info = info if isinstance(info, dict) else {}
    known = [n for n in (_int_or_none(info.get("sent")), _int_or_none(info.get("second")))
             if n is not None]
    if len(known) == 0:
        return None
    return max(known)


def client_state(facts, cfg=None, now=None):
    """→ (ТИХО | УШЛО | НЕИЗВЕСТНО, подробности). Предмет — ЧИСЛО ОТПРАВЛЕННЫХ КЛИЕНТУ, и ничего
    больше: ни флаг, ни живой процесс, ни строка кода этой функции не видны вовсе.

    ПОРЯДОК ПРОВЕРОК — ЗАМОК, А НЕ ПОРЯДОК СТРОК. Второй свидетель (реестр попыток) спрашивается
    ДО того, как проверена читаемость очереди: reply-режим в очередь не пишет ВООБЩЕ, значит
    непрочитанная очередь не вправе спрятать отправку, о которой реестр уже знает. Правило
    односторонней громкости: добавить нарушение свидетель может, снять — не может ни одной ветвью.

    ТРИ ИСХОДА, и «неизвестно» возвращается на каждую дырку: ветка выключена порогом · факта нет
    вовсе · источник не прочитан · счётчик не разобран. Ни одна дорога отсюда не ведёт к «тихо»
    иначе как через ПРОЧИТАННЫЙ ноль."""
    cfg = cfg if isinstance(cfg, dict) else config()
    if float(cfg.get("client", 0.0)) <= 0:
        return CLIENT_UNKNOWN, {"why": "ветка О5 выключена порогом"}          # откат
    src = facts.get("client") if isinstance(facts, dict) else None
    if not isinstance(src, dict):
        return CLIENT_UNKNOWN, {"why": "факта об отправленном клиенту нет вовсе"}
    raw_pairs = src.get("pairs")
    pairs = raw_pairs if isinstance(raw_pairs, dict) else {}
    second = None
    if pairs.get("ok") is True:
        second = _int_or_none(pairs.get("sent"))
    info = {"sent": None, "second": second, "pairs_ok": pairs.get("ok"),
            "pairs_err": pairs.get("err"), "pairs_last": pairs.get("last"),
            "armed": _int_or_none(src.get("armed")),
            "attempted": _int_or_none(src.get("attempted")),
            "total": _int_or_none(src.get("total")),
            "last": src.get("last_sent"), "why": ""}
    if src.get("ok") is True:
        info["sent"] = _int_or_none(src.get("sent"))
    if second is not None and second > 0:
        return CLIENT_SPOKE, info
    if src.get("ok") is not True:
        err = src.get("err")
        info["why"] = ("источник истины не прочитан (%s)"
                       % ("причина не названа" if err is None else err))
        return CLIENT_UNKNOWN, info
    if info["sent"] is None:
        info["why"] = "счётчик отправленных не разобран"
        return CLIENT_UNKNOWN, info
    if info["sent"] > 0:
        return CLIENT_SPOKE, info
    return CLIENT_SILENT, info


# ═══════════════════════════ РЕШЕНИЕ: ЧИСТАЯ ФУНКЦИЯ ФАКТОВ ════════════════════════════════
def _o1(facts, cfg, now):
    """О1 — строка полосы ПК не сменила состояние за отведённое время. Две ветки, два порога."""
    out = []
    rows = _rows(facts)
    if rows is None:
        return out                                    # снимка нет → фактов нет → молчим
    pc = [r for r in rows if _lane(r) == LANE]
    wait_limit = float(cfg.get("new") or 0.0)
    run_limit = float(cfg.get("run") or 0.0)
    busy_row = any(_status(r) == "in_progress" for r in pc)
    for r in pc:
        st = _status(r)
        try:
            since = float(r.get("since") or 0.0)
        except (TypeError, ValueError):
            continue
        if since <= 0:
            continue
        age = now - since
        if st in WAIT_STATUSES and wait_limit > 0:
            if busy_row:
                continue                              # исполнитель занят — законная очередь
            # ПОРОГ БЕРЁТ ЧИСТОЕ ОЖИДАНИЕ, а не возраст строки: сколько она простояла ИМЕННО ПРИ
            # СВОБОДНОЙ полосе. Счётчик копят руки; факта нет → нарушения нет (fail-safe в молчание).
            try:
                free = float(r.get("free_wait") or 0.0)
            except (TypeError, ValueError):
                continue
            if free <= wait_limit or _step_blocked(r, rows):
                continue
            out.append({"kind": "o1_pc_new", "key": "o1n|%s|%d" % (r.get("id"), int(since)),
                        "id": r.get("id"), "from": str(r.get("from") or ""), "status": st,
                        "age": age, "free": free, "limit": wait_limit})
        elif st == "in_progress" and run_limit > 0 and age > run_limit:
            out.append({"kind": "o1_pc_run", "key": "o1r|%s|%d" % (r.get("id"), int(since)),
                        "id": r.get("id"), "from": str(r.get("from") or ""), "status": st,
                        "age": age, "limit": run_limit})
    return out


def _o2(facts, cfg, now):
    """О2 — демон не дал ни одного оборота `poll_once` за отведённое время бодрствования."""
    if float(cfg.get("turn") or 0.0) <= 0:
        return []                                     # откат: ветка мертва до чтения фактов
    state, info = turn_state(facts, cfg, now)
    if state != TURN_SILENT:
        return []                                     # в т.ч. «неизвестно»: незнание не приговор
    return [{
        "kind": "o2_pc_turn",
        # Эпизод ключуется ПОСЛЕДНИМ оборотом: пока демон молчит, это одно и то же молчание, а
        # новый оборот и закрывает эпизод, и меняет ключ — второй заметки о том же не будет.
        "key": "o2t|%d" % int(info.get("ts") or 0),
        "awake": info.get("awake"), "wall": info.get("wall"), "slept": info.get("slept"),
        "limit": info.get("limit"), "ts": info.get("ts"),
        "overdue": info.get("overdue"),
    }]


def _o3(facts, cfg, now):
    """О3 — модербот не дал ни одной СВОЕЙ записи в IPC за отведённое время бодрствования."""
    if float(cfg.get("mod") or 0.0) <= 0:
        return []                                     # откат: ветка мертва до чтения фактов
    state, info = moderbot_state(facts, cfg, now)
    if state != MOD_IDLE:
        return []                                     # в т.ч. «неизвестно»: незнание не приговор
    return [{
        "kind": "o3_pc_moderbot",
        # Эпизод ключуется НАЧАЛОМ ТИШИНЫ, а не последней записью: в самом дорогом случае (бот
        # мёртв, а файл двигает чужой писатель) ключ по mtime менялся бы каждые десять минут и
        # владелец получал бы заметку об одном и том же молчании снова и снова.
        "key": "o3m|%d" % int(info.get("since") or info.get("ts") or 0),
        "awake": info.get("awake"), "wall": info.get("wall"), "slept": info.get("slept"),
        "limit": info.get("limit"), "ts": info.get("ts"), "pid": info.get("pid"),
        "who": info.get("who"),
    }]


def _o5(facts, cfg, now):
    """О5 — клиентам ушло хоть что-то, ЛИБО прибор ослеп дольше порога. Две ветки, одна цель.

    Вторая ветка нужна ровно потому, что предмет первой — НОЛЬ: ослепший прибор молчит точно так
    же, как исправный при выполненном ожидании, и без заметки о слепоте «тихо» становится вечным.
    Порог берёт НАКОПЛЕННОЕ НЕЗНАНИЕ в часах бодрствования (руки копят его наблюдение за
    наблюдением), а не возраст файла: сон машины незнанием не является."""
    limit = float(cfg.get("client", 0.0))
    if limit <= 0:
        return []                                     # откат: ветка мертва до чтения фактов
    state, info = client_state(facts, cfg, now)
    if state == CLIENT_SPOKE:
        return [{
            "kind": "o5_pc_client_sent",
            # Ключ несёт ОБА числа: новая отправка меняет счётчик, рождает НОВЫЙ эпизод и новую
            # заметку. Та же отправка второй заметки не даёт (одна заметка на эпизод).
            "key": "o5s|%s|%s" % (info.get("sent"), info.get("second")),
            "sent": info.get("sent"), "second": info.get("second"),
            "spoken": client_spoken(info), "last": info.get("last"),
            "pairs_last": info.get("pairs_last"), "pairs_ok": info.get("pairs_ok"),
            "armed": info.get("armed"), "attempted": info.get("attempted"),
            "total": info.get("total"), "limit": limit,
        }]
    if state != CLIENT_UNKNOWN:
        return []
    blind = facts.get("client_unknown") if isinstance(facts, dict) else None
    if not isinstance(blind, dict):
        return []                                     # незнание не измерено → заметки нет
    if blind.get("measured") is not True:
        return []
    awake = _float_or_none(blind.get("awake"))
    if awake is None or awake <= limit:
        return []
    since = _float_or_none(blind.get("since"))
    return [{
        "kind": "o5_pc_client_unknown",
        # Эпизод ключуется НАЧАЛОМ слепоты: пока источник не читается, это одна и та же слепота.
        "key": "o5u|%d" % (0 if since is None else int(since)),
        "awake": awake, "limit": limit, "since": since, "why": info.get("why"),
        "pairs_ok": info.get("pairs_ok"), "second": info.get("second"),
    }]


def verdict(facts, cfg=None):
    """ФАКТЫ → список нарушений. Ни одного обращения к миру: ни ФС, ни сети, ни времени — всё
    приходит в `facts`. Пустой список = вердикта нет (НЕ «всё хорошо»: сказать так слой не умеет).

    Любое исключение внутри ветки гасится в молчание ЭТОЙ ветки: одна кривая строка очереди не
    смеет отнять у владельца заметку о вставшем демоне."""
    if not isinstance(facts, dict):
        return []
    cfg = cfg if isinstance(cfg, dict) else config()
    try:
        now = float(facts.get("now") or 0.0)
    except (TypeError, ValueError):
        return []
    if now <= 0:
        return []
    out = []
    for fn in (_o1, _o2, _o3, _o5):
        try:
            out.extend(fn(facts, cfg, now) or [])
        except Exception:                                            # noqa: BLE001
            continue
    return out


def closures(facts, cfg, open_keys):
    """Какие ИЗ УЖЕ ОБЪЯВЛЕННЫХ эпизодов ДОКАЗАННО закрылись.

    ДОКАЗАННО — ключевое слово и вторая половина замка против ложного зелёного: закрытым считается
    эпизод, чей ИСТОЧНИК ФАКТА доступен и говорит «нарушения больше нет». Источник недоступен
    (мост молчит, heartbeat не прочитан, тишина не измерена) → эпизод НЕ закрывается: молчание
    источника выздоровлением не является."""
    cfg = cfg if isinstance(cfg, dict) else config()
    live = {str(v.get("key")) for v in (verdict(facts, cfg) or [])}
    rows = _rows(facts)                              # None = снимка очереди нет
    try:
        now = float((facts or {}).get("now") or 0.0)
    except (TypeError, ValueError):
        now = 0.0
    turn = turn_state(facts, cfg, now)[0] if now > 0 else TURN_UNKNOWN
    mod = moderbot_state(facts, cfg, now)[0] if now > 0 else MOD_UNKNOWN
    client = client_state(facts, cfg, now)[0] if now > 0 else CLIENT_UNKNOWN
    out = []
    for key in (open_keys or []):
        key = str(key)
        if key in live:
            continue                                 # нарушение продолжается — закрывать нечего
        kind = key.split("|", 1)[0]
        if kind in ("o1n", "o1r") and rows is not None:
            out.append(key)                          # снимок есть, строки в нарушении нет
        elif kind == "o2t" and turn == TURN_OK:
            out.append(key)                          # оборот ДОКАЗАННО вернулся (не «не знаю»)
        elif kind == "o3m" and mod == MOD_OK:
            # ДОКАЗАННО и здесь: закрывает только «делает работу» — то есть своя свежая запись
            # с подтверждённым автором. «Неизвестно» эпизод не закрывает: перестать видеть
            # модербота не значит дождаться его выздоровления.
            out.append(key)
        elif kind == "o5u" and client != CLIENT_UNKNOWN:
            # Слепота кончилась ДОКАЗАННО: источник истины прочитан (безразлично, что он показал).
            out.append(key)
        # `o5s` в этом переборе НЕТ НАМЕРЕННО, и это не пропуск. Отправленное клиенту сообщение не
        # отменяется: «ожидание снова выполняется» после него было бы ложью, поэтому эпизод «ушло»
        # не закрывается НИКОГДА и ни одним фактом. Закрыть его может только владелец — руками,
        # сняв ключ из состояния наблюдателя.
    return out


