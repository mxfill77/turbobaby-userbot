def render_line(word, info):
    """ОДНА строка о доле — для витрины и для `--status`. Длина замерена вызывающим, а не
    подразумевается: окно витрины тесное, и молчаливая обрезка на этой полосе запрещена."""
    info = info if isinstance(info, dict) else {}
    if word == SHARE_UNKNOWN:
        return "доля гашения цены: НЕИЗВЕСТНО (%s)" % (info.get("why") or "причина не названа")
    roads = info.get("roads") or {}
    named = ", ".join("%s %d" % (k, v) for k, v in sorted(roads.items(), key=lambda x: -x[1])
                      if k != ROAD_OK)
    tail = " · дороги: %s" % named if named else " · дорог отказа не было"
    return ("доля гашения цены: %d из %d = %.0f %% · нужно %d (не хватает %d)%s"
            % (info.get("quenched", 0), info.get("judged", 0), info.get("share_pp", 0.0),
               info.get("need", 0), max(0, int(info.get("need", 0)) - int(info.get("judged", 0))),
               tail))


def vitrina_lines(state, cfg=None, now=None):
    """Строки о доле для ВИТРИНЫ → список (всегда ровно одна строка). Чистая функция.

    ПОЧЕМУ ОДНА СТРОКА, И ЭТО ЗАМЕРЕНО. Окно витрины — `vitrina_pc.TEXT_MAX` = 3900 символов, и
    оно уже переполнено: живое сообщение оборота 11.09 16:51 UTC весило 4192 символа, перелив 292,
    из-за чего раздел «ЧТО РАБОТАЕТ И ЧТО НЕТ» (727 симв.) в тему не доезжает ЦЕЛИКОМ. После
    обрезки свободно **287 символов** — вот весь бюджет этой строки. Замер живой строки 12.09:
    83 символа; худший реалистичный случай (все пять дорог названы числами) — 142. С маркером
    «• » и переводом строки это 86 и 145 против 287, то есть строка влезает и НЕ выдавливает
    соседний раздел. Молчаливой обрезки здесь не случается ни одной веткой; сторожит границу
    `test_price_quench_pc.TestRenderLine`.

    МОЛЧИТ — ЗНАЧИТ МОЛЧИТ: состояния нет вовсе → строка всё равно есть и говорит «НЕИЗВЕСТНО» с
    причиной. Пустоту за благополучие витрина не выдаёт — тот же класс, от которого весь модуль."""
    word, info = verdict({"quench": state}, cfg, now)
    return [render_line(word, info)]
