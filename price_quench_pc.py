"""ДОЛЯ ГАШЕНИЯ ЦЕНЫ — чистая логика прибора полосы ПК (заведено 12.09.2026, задание 42-a).

ЧТО ЭТО ЗА ПРИБОР И ЧЕМ ОН НЕ ЯВЛЯЕТСЯ. Он меряет ОДНО: собирается ли ценовая записка, когда
её собирают. Не «мост жив», не «сторож свежести на месте», не «слепок цены свежий» — все трое
бывают верны ровно в ту минуту, когда quote-блока в записке нет. Прибор копит ДОЛЮ гашения и
называет ДОРОГУ отказа; тревоги он не поднимает (см. «ПОРОГ» ниже) — он показывает число.

ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ О7, И ЭТО НЕ ДУБЛЬ (замер 12.09, числа в артефакте задания). О7 «цена
называется клиенту числом» — прибор ПАССИВНЫЙ: он читает хвост журнала продукта и судит по
пáре следов «гасилка была, пересчёта после неё нет». Отсюда две его границы, обе измеренные:

  1. О7 ЗАВИСИТ ОТ ЖИВОГО ТРАФИКА. Нет клиента, спросившего о цене, — нет ценовых строк, и
     честный ответ О7 «судить не по чему» (`expectations_pc.price_state`, ветка пустого хвоста).
     Наш прибор спрашивает цену САМ и потому меряет и в тишине.
  2. О7 СЛЕП К ДВУМ ДОРОГАМ ИЗ ТРЁХ. Его источник истины — `logs/userbot_stderr.log`, а
     `pricing` пишет в СВОЙ файл и до корневого журнала не доходит вовсе (`pricing.py:29`
     → `log.propagate = False`). Замер хвоста 4 МБ за 12.09: строк `price_source: … кепка:`
     — 888, строк `price_gate:` — 2, строк происхождения `pricing` — **0**. Дорога «источник
     цены» (`price_source.reprice` → error) в его счёт тоже не попадает: она не начинается ни
     с `price_gate: `, ни с «кепка:», и обе его ветки её пропускают (`price_facts`, `continue`).

ЧЕТЫРЕ ЧАСТИ КОНТРАКТА НАБЛЮДЕНИЯ — дословно, потому что без них прибор не допускается:

  РЕЗУЛЬТАТ       — в ценовой записке ЕСТЬ quote-блок. Именно блок, а не «вызов вернулся» и не
                    «код ответа 200»: блок есть ровно то, что доезжает в ответ клиенту кодом.
  ИСТОЧНИК ИСТИНЫ — сама записка, собранная боевым путём продукта
                    (`suggest.build_pricing_note`), и её разбор боевым же детектором
                    `suggest._quote_block_from_note`. Не наш пересказ и не вторая реализация.
  СПОСОБ          — судится РЕЗУЛЬТАТ: `_quote_block_from_note(note)` непусто. Живость процесса,
                    код возврата и отсутствие исключения результатом НЕ являются и в счёт не
                    идут ни одной веткой: заход, вернувший 0 и пустую записку, — это гашение.
  ОТРИЦАТЕЛЬНЫЙ   — намеренно созданное состояние «цена погашена, а прибор молчит» обязано дать
  ТЕСТ              ОТКАЗ. Живёт в `test_price_quench_pc.py` и бьёт в обе стороны: подложенная
                    пустая записка обязана дать `quenched=True` с НАЗВАННОЙ дорогой, а подлог
                    «дорога не названа» обязан дать «неизвестно», а не тихое благополучие.

ПОРОГ ТРЕВОГИ НЕ НАЗНАЧЕН, И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА. На 11.09 доля гашения была 1 из 7
наблюдений. Семь — это МАЛО: точный 95 %-й интервал Клоппера–Пирсона для 1/7 равен примерно
[0.4 %, 58 %], то есть по семи наблюдениям «редкий транзиент» и «гаснет чаще, чем через раз»
НЕРАЗЛИЧИМЫ. Сколько нужно — посчитано, а не округлено (:func:`need_observations`), и до этого
числа прибор копит долю и показывает её, а тревогу не поднимает ни одной веткой.
"""

# ═════════════════════════ ДОРОГИ ОТКАЗА ══════════════════════════════════════
# Имя дороги — ответ на вопрос «где умерло число», и он обязан быть ОДИН на исход. Порядок
# разбора ниже (`road_of`) идёт от места гибели ВВЕРХ по конвейеру: сторож стои́т последним в
# коде и первым в разборе, потому что его отказ перекрывает всё, что успел отдать мост.
ROAD_OK = "цена собралась"
ROAD_GATE = "сторож свежести"
ROAD_SOURCE = "источник цены"
ROAD_BRIDGE = "мост"
ROAD_BUSY = "всё занято"
ROAD_NOBODY = "модели нет в парке"
ROAD_UNKNOWN = "неизвестно"

# Дороги, на которых числа нет ЗАКОННО: клиенту в эту минуту его и не должны называть. В доле
# гашения они НЕ участвуют — иначе доля меряла бы занятость парка, а не отказ ценового пути.
LAWFUL_ROADS = (ROAD_BUSY, ROAD_NOBODY)

# ═════════════════════════ ТРИ ИСХОДА ═════════════════════════════════════════
# «Неизвестно» — отдельный ответ, а не вежливая форма «в порядке»: ослепший прибор молчит ровно
# так же, как исправный при собравшейся цене, и разница между ними — вся ценность ветки.
SHARE_COUNTED, SHARE_GROWING, SHARE_UNKNOWN = "доля сосчитана", "копим наблюдения", "неизвестно"

EVERY_ENV, EVERY_DEFAULT = "PRICE_QUENCH_EVERY_MIN", 30.0     # пол каденции пробы, минуты
KEEP_ENV, KEEP_DEFAULT = "PRICE_QUENCH_KEEP", 512             # кольцо наблюдений серии

# ЗАМЕР, НА КОТОРОМ СТОИ́Т `need_observations`, И ОН ЗАПИСАН ЗДЕСЬ, А НЕ ПРИПОМНЕН.
# Доля 11.09 = 1 гашение на 7 наблюдений (предполёт 0/1, круг снимка 1/1, зонд пяти сборок 0/5;
# артефакт `docs/artifacts/2026-09-11-ЗОНД-pyat-sborok-1109.md`, §4).
SEED_OBS, SEED_QUENCHED = 7, 1
# Полуширина доверительного интервала, ради которой считается потребное число наблюдений.
# 5 процентных пунктов — НЕ круглая красота: это та точность, при которой доля 14 % перестаёт
# накрывать ноль, то есть «гаснет изредка» становится отличимо от «не гаснет вовсе».
TARGET_HALFWIDTH_PP = 5.0
Z95 = 1.96


def _num(value, default=None):
    """Число или `default`. Мусор числом не притворяется — он им не становится."""
    try:
        if value is None or isinstance(value, bool):
            return default
        out = float(value)
    except (TypeError, ValueError):
        return default
    if out != out or out in (float("inf"), float("-inf")):
        return default
    return out


def limit_env(name, default, env=None, scale=60.0):
    """Ручка порога → число. Мусор и пустое → объявленный дефолт; `0` → объявленный откат ветки.

    Форма одолжена у `expectations_pc.limit_env` намеренно: две ручки одной полосы, читаемые
    по-разному, расходятся молча. `scale` здесь ЯВНЫЙ, потому что доля меряется не в минутах, и
    домножение на 60 увело бы её в никуда (мина, названная разведкой этого задания)."""
    raw = (env or {}).get(name)
    val = _num(raw if raw is not None else default, None)
    if val is None:
        val = _num(default, 0.0)
    return float(val) * float(scale)


def config(env=None):
    """Все объявленные числа прибора одним словарём. Ни одного обращения к миру."""
    src = env if isinstance(env, dict) else {}
    return {
        "every": limit_env(EVERY_ENV, EVERY_DEFAULT, src),          # секунды
        "keep": int(limit_env(KEEP_ENV, KEEP_DEFAULT, src, scale=1.0)),
        "need": need_observations(),
    }


def need_observations(obs=SEED_OBS, quenched=SEED_QUENCHED, halfwidth_pp=TARGET_HALFWIDTH_PP):
    """СКОЛЬКО НАБЛЮДЕНИЙ НУЖНО, ЧТОБЫ ПОРОГ СТАЛ ОСМЫСЛЕННЫМ. → целое число.

    Считается, а не назначается: n ≥ z²·p(1−p)/e², где p — ДОЛЯ, ИЗМЕРЕННАЯ НА ТОМ, ЧТО ЕСТЬ
    (по умолчанию 1 из 7 за 11.09), e — потребная полуширина в долях единицы. На семенном замере
    это даёт 189 наблюдений; при поле каденции в 30 минут — 94.5 часа, то есть около четырёх
    суток непрерывного счёта.

    ПОЧЕМУ ЧИСЛО ЕДЕТ ВМЕСТЕ С ЗАМЕРОМ, А НЕ СТОИ́Т КОНСТАНТОЙ: доля, накопленная прибором,
    уточнит p, и потребное n пересчитается само. Константа здесь молча врала бы ровно в тот день,
    когда доля изменится."""
    n = _num(obs, 0.0) or 0.0
    k = _num(quenched, 0.0) or 0.0
    e = (_num(halfwidth_pp, TARGET_HALFWIDTH_PP) or TARGET_HALFWIDTH_PP) / 100.0
    if n <= 0 or e <= 0:
        return 0
    p = min(max(k / n, 0.0), 1.0)
    if p <= 0.0 or p >= 1.0:
        # Вырожденная доля (ноль гашений или сплошные гашения) дисперсии не даёт вовсе. Берём
        # самый дорогой случай p=0.5 — он МАКСИМИЗИРУЕТ потребное n, то есть прибор скорее
        # попросит лишних наблюдений, чем объявит порог осмысленным раньше времени.
        p = 0.5
    return int(-(-(Z95 * Z95 * p * (1.0 - p) / (e * e)) // 1))      # потолок деления


# ═════════════════════════ ДОРОГА ОТКАЗА ══════════════════════════════════════

def road_of(calls, quoted, timeout_sec=None, tries=None, head=""):
    """ЦЕПОЧКА ВЫЗОВОВ ОДНОЙ СБОРКИ → (ДОРОГА, чем доказана). Чистая функция.

    ПОЧЕМУ ЦЕПОЧКА, А НЕ ПРЕДУПРЕЖДЕНИЯ. Задание 42-a называло предметом разбора предупреждения,
    которые зонд пишет рядом со сборкой. Замер 12.09 эту премису поправил: `pricing` уводит свой
    логгер из корневого дерева (`pricing.py:29` → `log.propagate = False`), и ни одно его
    предупреждение до слушателя НЕ доходит — 60 записей за 10 сборок зонда, из них `pricing` ноль
    при 55 живых вызовах `quote_for_model`. Дорогу называет ЦЕПОЧКА, и только она.

    ПОРЯДОК РАЗБОРА — ПРИЧИННЫЙ: кто умер ПЕРВЫМ, тот и дорога. Он был найден ОТРИЦАТЕЛЬНЫМ
    ТЕСТОМ, а не придуман, и первая его редакция была НЕВЕРНА — это записано здесь, потому что
    ошибка тихая. Сперва здесь стоял разбор «сторож → источник → мост», по доводу «сторож ниже по
    коду, значит перекрывает». Отрицательный тест 12.09 (мост подменён дверью, которая не
    отвечает) назвал дорогой **источник цены** вместо моста, и вот почему это ложь:
    `price_source.reprice` при входе не-`ok` возвращает ТОТ ЖЕ объект нетронутым
    (`price_source.py:504-505`), то есть ПРОПУСКАЕТ чужую ошибку сквозь себя. Обёртка видит у
    него `status="error"` и без причинного порядка обвиняет невиновного.

    Поэтому: мост разбирается ПЕРВЫМ. Отказ сторожа считается дорогой только когда мост
    котировку отдал, а гашение источника — только когда и мост отдал, и сторож разрешил.
    """
    rows = [c for c in (calls or []) if isinstance(c, dict)]
    if quoted:
        return ROAD_OK, "quote-блок в записке есть"

    quotes = [c for c in rows if c.get("fn") == "pricing.quote_for_model"]
    broken = [c for c in quotes if c.get("exc") or c.get("status") == "error"]
    if not broken:
        gate = [c for c in rows if c.get("fn") == "price_gate.allow"]
        refused = [c for c in gate if c.get("may") is False]
        if refused:
            why = (refused[0].get("card") or "").strip()
            return ROAD_GATE, ("сторож свежести не разрешил назвать цену%s"
                               % (": " + why[:200] if why else " (причина сторожем не названа)"))

        src = [c for c in rows if c.get("fn") == "price_source.reprice"]
        bad = [c for c in src if c.get("status") == "error" or c.get("exc")]
        if bad:
            code = bad[0].get("noprice") or bad[0].get("exc")
            return ROAD_SOURCE, ("источник цены погасил число%s"
                                 % (" (%s)" % code if code else " (код не назван)"))
    if broken:
        secs = [s for s in (_num(c.get("sec")) for c in quotes) if s is not None]
        worst = max(secs) if secs else None
        cap = _num(timeout_sec)
        n_tries = _num(tries)
        if worst is not None and cap and worst >= cap * 0.9:
            return ROAD_BRIDGE, ("исчерпание времени ожидания моста: вызов %.2f с при потолке "
                                 "%.0f с%s" % (worst, cap,
                                               "" if not n_tries else " × %d попыт." % int(n_tries)))
        exc = next((c.get("exc") for c in broken if c.get("exc")), None)
        return ROAD_BRIDGE, ("мост не отдал котировку%s; по времени это НЕ исчерпание ожидания "
                             "(худший вызов %s при потолке %s)"
                             % (" (%s)" % exc if exc else "",
                                "—" if worst is None else "%.2f с" % worst,
                                "—" if not cap else "%.0f с" % cap))

    if any(c.get("status") == "none_available" for c in quotes):
        return ROAD_BUSY, "котировки получены, но все подходящие байки заняты на эти даты"
    if any(c.get("status") == "no_candidates" for c in quotes):
        return ROAD_NOBODY, "модели или дат в запросе нет, либо такой модели нет в парке"

    # Сюда приходит всё, чего мы назвать не смогли. Молчать здесь нельзя, а придумывать —
    # тем более: называем ИМЕННО ТО, ЧЕГО НЕ ХВАТИЛО, как велит п.6 задания.
    if not rows:
        return ROAD_UNKNOWN, ("цепочки вызовов нет вовсе — записывающие обёртки не встали "
                              "(без них дорога не определяется ни одной веткой)")
    seen = ", ".join(sorted({str(c.get("fn")) for c in rows})) or "—"
    lead = (" ".join(str(head or "").split()))[:120]
    return ROAD_UNKNOWN, ("quote-блока нет, но ни одна дорога себя не назвала; в цепочке были: "
                          "%s%s" % (seen, "; первая строка записки: «%s»" % lead if lead else ""))


def is_quench(road):
    """Считается ли эта дорога ГАШЕНИЕМ. Законное молчание (занятость парка, отсутствие модели)
    гашением НЕ является: иначе доля мерила бы наполненность парка, а не отказ ценового пути.
    «Неизвестно» тоже не гашение — и не благополучие: оно живёт третьим счётом."""
    return road not in (ROAD_OK, ROAD_UNKNOWN) + tuple(LAWFUL_ROADS)


# ═════════════════════════ ДОЛЯ ═══════════════════════════════════════════════

def tally(obs):
    """Наблюдения → счёт по исходам. Чистая функция, ни одного обращения к миру.

    ЗНАМЕНАТЕЛЬ НАЗВАН ЯВНО, потому что молчаливый знаменатель — классическая ложь доли:
    считаются только СУДИМЫЕ наблюдения (собралась цена либо погасла). «Неизвестно» и законное
    молчание стоя́т РЯДОМ своими числами и в долю не входят ни одной веткой."""
    rows = [o for o in (obs or []) if isinstance(o, dict)]
    out = {"total": len(rows), "quenched": 0, "ok": 0, "unknown": 0, "lawful": 0, "roads": {}}
    for o in rows:
        road = str(o.get("road") or ROAD_UNKNOWN)
        out["roads"][road] = out["roads"].get(road, 0) + 1
        if road == ROAD_OK:
            out["ok"] += 1
        elif road == ROAD_UNKNOWN:
            out["unknown"] += 1
        elif road in LAWFUL_ROADS:
            out["lawful"] += 1
        else:
            out["quenched"] += 1
    out["judged"] = out["ok"] + out["quenched"]
    out["share"] = (float(out["quenched"]) / out["judged"]) if out["judged"] else None
    return out


def verdict(facts, cfg=None, now=None):
    """→ (ДОЛЯ СОСЧИТАНА | КОПИМ НАБЛЮДЕНИЯ | НЕИЗВЕСТНО, подробности). Три исхода, ни одного
    обращения к миру: и наблюдения, и часы приезжают в `facts`.

    ТРЕВОГИ ЗДЕСЬ НЕТ НИ В ОДНОЙ ВЕТКЕ, и это не забывчивость (п.5 задания). Порог без
    записанного замера запрещён, а замера пока нет: до `need` наблюдений прибор показывает долю
    числом и говорит, скольких ему не хватает."""
    cfg = cfg if isinstance(cfg, dict) else config()
    need = int(cfg.get("need") or 0)
    src = facts.get("quench") if isinstance(facts, dict) else None
    if not isinstance(src, dict):
        return SHARE_UNKNOWN, {"why": "факта о гашении нет вовсе", "need": need}
    if src.get("ok") is not True:
        err = (src.get("err") or "").strip()
        return SHARE_UNKNOWN, {"why": ("состояние прибора не прочитано (%s)"
                                       % (err or "причина не названа")), "need": need}
    counts = tally(src.get("obs"))
    info = dict(counts)
    info.update({"need": need, "probe": src.get("probe"), "last": src.get("last"),
                 "series_started": src.get("series_started"), "why": ""})
    if not counts["judged"]:
        info["why"] = ("судимых наблюдений нет ни одного (всего записей %d, из них «неизвестно» "
                       "%d, законного молчания %d) — судить не по чему"
                       % (counts["total"], counts["unknown"], counts["lawful"]))
        return SHARE_UNKNOWN, info
    share_pp = 100.0 * counts["share"]
    info["share_pp"] = share_pp
    if counts["judged"] < need:
        info["why"] = ("доля гашения %d из %d = %.0f %% · для осмысленного порога нужно %d "
                       "судимых наблюдений, не хватает %d"
                       % (counts["quenched"], counts["judged"], share_pp, need,
                          need - counts["judged"]))
        return SHARE_GROWING, info
    info["why"] = ("доля гашения %d из %d = %.0f %% на %d судимых наблюдениях — порог назначать "
                   "можно, замер записан" % (counts["quenched"], counts["judged"], share_pp,
                                             counts["judged"]))
    return SHARE_COUNTED, info


# ═════════════════════════ КАДЕНЦИЯ ═══════════════════════════════════════════

def probe_due(last_ts, cfg=None, now=None):
    """Пора ли идти мерить → (bool, почему). Частоту решает ПРИБОР, а не звонящий: демон зовёт
    его каждый оборот, а в сеть прибор идёт по своему полу (`PRICE_QUENCH_EVERY_MIN`).

    Форма одолжена у `srv_delivery.due` — на этой полосе уже стои́т ровно такой замок, и вторая
    его реализация с другим поведением разошлась бы с первой молча."""
    cfg = cfg if isinstance(cfg, dict) else config()
    every = float(cfg.get("every") or 0.0)
    if every <= 0:
        return False, "ветка выключена порогом (%s=0)" % EVERY_ENV          # объявленный откат
    prev = _num(last_ts)
    if prev is None:
        return True, "прошлой пробы нет — меряем впервые"
    age = float(now or 0.0) - prev
    if age < 0:
        # Часы поехали назад (перевод, восстановление из снимка). Это НЕ «пора» и НЕ «рано» —
        # это незнание, и честнее промерить, чем считать возраст отрицательным числом.
        return True, "часы ушли назад (возраст %.0f с) — меряем и переставляем штамп" % age
    if age < every:
        return False, "рано: прошло %.0f с при поле %.0f с" % (age, every)
    return True, "прошло %.0f с при поле %.0f с" % (age, every)


