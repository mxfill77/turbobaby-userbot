# -*- coding: utf-8 -*-
"""ПЕРЕПОКАЗ кейса экзамена: та же карточка, но с шапкой «это перепоказ и вот чем он отличается».

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ КЛЮЧ У `exam_show`. Две причины, обе измеренные:

1. **Замок свежести ловца.** `exam_show.agent_carries_button` сравнивает mtime файлов замыкания
   кнопки (`pc_agent.py`, `exam_show.py`) с моментом рождения живого агента. Любая правка
   `exam_show.py` делает файл новее старта агента — и показ ОТКАЗЫВАЕТ САМ СЕБЕ ровно в тот заход,
   который собрался показывать. Перепоказ живёт своим файлом, потому что в заход, который
   показывает, файлы замыкания кнопки не правят (правило полосы, 12.09.2026).
2. **Анти-проба `dispatch_notify.probe_verdict`.** Живая отправка владельцу разрешена только с
   точки входа, лежащей В КОРНЕ репозитория: разовый скрипт из `tmp/` до владельца не доходит
   СОЗНАТЕЛЬНО. Значит у перепоказа обязана быть своя дверь в корне — иначе она заводится
   каждый раз заново и каждый раз мимо тестов.

ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Не собирает черновиков и не зовёт голову ни одной веткой — прогонщика
корпуса здесь нет вовсе, и это проверяется по исходнику, а не на слово. Не правит снимок: текст
вопроса и ответа берётся из снимка КАК ЕСТЬ —
подрисовать в карточке то, чего нет в снимке, нельзя по построению. Шапка есть свойство ЭТОЙ
отправки: в снимок она не ложится, и следующий обычный показ её не унаследует.

ПОЧЕМУ ОТЛИЧИЕ ОБЯЗАТЕЛЬНО. Перепоказ без названного отличия — это вторая одинаковая карточка:
владелец тратит внимание на то, чтобы САМОМУ найти разницу с предыдущей. Поэтому `--note` не имеет
умолчания, и пустое отличие отказывает ДО сети.

    venv/Scripts/python.exe exam_reshow.py --case 1 --note "<чем отличается>" [--dry]
"""
import argparse
import sys

import exam_show

MARK = "🔁 ПЕРЕПОКАЗ"


def header(case_id, note):
    """Шапка перепоказа → строка. Чистая функция: ни сети, ни диска.

    Называет три вещи, и каждая нужна владельцу до того, как он начнёт читать карточку: что это
    перепоказ (а не второй кейс), что прежняя карточка ЖИВА (её кнопки по-прежнему пишут вердикт —
    тапать можно любую), и чем именно новая от неё отличается."""
    return ("%s кейса %s — прежняя карточка остаётся висеть, её кнопки рабочие; тапать можно "
            "любую.\n%s\n" % (MARK, case_id, note.strip()))


def reshow(case_id, note, sender=None, chat=None, agent_fn=None):
    """Показать кейс заново ОДНИМ сообщением с шапкой. → (ok, строка словами).

    Идёт через боевой `exam_show.show`, а не мимо него: все четыре замка показа (адрес — только
    группа-тренажёр, снимок на диске, отпечаток корпуса, живой агент несёт кнопку) обязаны
    отработать и на перепоказе. Подставлен ТОЛЬКО отправщик."""
    note = (note or "").strip()
    if not note:
        return False, ("⛔ перепоказ без названного отличия не делаем: владелец получил бы вторую "
                       "одинаковую карточку и искал разницу сам. Назови «--note»")
    head = header(case_id, note)
    if sender is None:
        import dispatch_notify
        base = dispatch_notify.send_chat_strict
    else:
        base = sender

    def wrapped(text, dest, markup=None):
        return base(head + "\n" + text, dest, markup)

    return exam_show.show(case_id, chat=chat, sender=wrapped, agent_fn=agent_fn)


def main(argv=None):
    ap = argparse.ArgumentParser(description="перепоказ сохранённого кейса экзамена")
    ap.add_argument("--case", required=True, type=int)
    ap.add_argument("--note", default="", help="чем этот показ отличается от предыдущего")
    ap.add_argument("--dry", action="store_true", help="напечатать текст и НЕ отправлять")
    a = ap.parse_args(argv if argv is not None else sys.argv[1:])
    if a.dry:
        seen = []

        def dry(text, dest, markup=None):
            seen.append(text)
            print("─── ушло бы в %s (%d симв., фигурных скобок %d) ───\n%s\n─── кнопки: %s"
                  % (dest, len(text), text.count("{"), text, markup))
            return ("СУХО", True, "0")
        ok, msg = reshow(a.case, a.note, sender=dry)
        print("\nИСХОД: ok=%s · %s\nСУХО: наружу не ушло ничего" % (ok, msg))
        return 0 if ok else 1
    ok, msg = reshow(a.case, a.note)
    print(msg)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
