# -*- coding: utf-8 -*-
"""
result_ref.py — АДРЕС РЕЗУЛЬТАТА шага полосы ПК: ВИД и УКАЗАТЕЛЬ. Место, куда адрес можно
положить, — и НИЧЕГО сверх этого.

ПОВОД (своя полоса, проверяемо здесь). Перепись 15.08.2026, коммит a545ad2, артефакт
`docs/artifacts/2026-08-15-orchestrator-trusts-report-pc.md`: 87 мест судят исход в 6 видах,
62 из них — по ОТЧЁТУ исполнителя, 25 — по чтению назад, и НИ ОДНО из 25 не читает продукт
задачи или шага цепи (виды 1-2, 37 мест — ноль). Причина названа там же §2: «источник истины
у шага не записан НИГДЕ» — очередь несёт 9 колонок (`id`, `created`, `from`, `task_text`,
`status`, `result`, `approved_by`, `updated`, `lane`), под адрес результата ни одной, а
`PLANNER_PREAMBLE` не требует от шага назвать продукт ни одним словом.

ЧТО ЗАВЕДЕНО ЭТИМ ФАЙЛОМ (дословно, чтобы мирить с полосой VPS):
    имя поля   `result_ref`
    тип        строка `"<вид><SEP><указатель>"`, `""` — законное значение «адрес не назван»
    виды       `commit` · `file` · `row` · `brain` · `service` (ровно пять, см. KINDS/KIND_TITLES)
Имя поля — оно же ключевое слово маркера (`FIELD`): разойтись порознь они не могут.

ГДЕ ОНО ЖИВЁТ НА ПОЛОСЕ ПК И ПОЧЕМУ НЕ КОЛОНКОЙ. Лист очереди у полос ОДИН, десятую колонку
даёт только правка Apps Script моста — это за границей полосы ПК (и правка стоила бы обеим
полосам сразу, §7 разбора). Поэтому носитель здесь — ИМЕНОВАННЫЙ МАРКЕР в `task_text`,
ровно тем же устройством, каким полоса уже носит родство цепи и остаток плана
(`dec_port_spec.md:115`: «Родство цепи — ТОЛЬКО по паттернам в task_text, схема очереди не
менялась, решение плана C»; `[шаг i/N родитель pid]`, `[сводка родитель pid]`,
`[коррекция плана родитель pid]`). Читатель `read_item` СНАЧАЛА смотрит настоящую колонку
`result_ref` ряда: в день, когда мост её заведёт, мирить полосы будет нечего — колонка
перекроет маркер сама, без правки читающих.

ЧЕГО ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО (граница захода 16.08.2026):
  • проверки адреса — ни git, ни `os.path`, ни моста, ни базы: «по адресу что-то есть» этот
    модуль сказать НЕ УМЕЕТ и уметь не должен;
  • вердикта шага, третьего исхода, правила «нет адреса — нет зелёного» — ни одной ветки;
  • ни одного из 87 мест переписи не тронуто.
Граница держится УСТРОЙСТВОМ, а не докстрингом: единственный импорт модуля — `re`, инвариант
`RESULT_REF_PURE` в `test_result_ref.py` роняет гейт на любой попытке дать ему руки.

МИНА, названная заранее. Маркер едет В ТЕКСТЕ шага, а текст шага режется по `RESULT_MAX`
(`pc_orchestrator._loc_release`): длинный указатель откусит хвост ТЗ. Отсюда `POINTER_MAX`
и жёсткий отказ `make()` на переросшем указателе — молча укоротить адрес хуже, чем не принять.

ОТКАТ (одной строкой): перестать передавать `ref` в `pc_orchestrator._loc_release` — при
дефолте `ref=""` строка шага собирается БАЙТ-В-БАЙТ как до правки; целиком — `git revert`
коммита этого захода.
"""

import re

# Имя поля = ключевое слово маркера. Мирить полосы — по этой строке.
FIELD = "result_ref"

# ПЯТЬ ВИДОВ АДРЕСА (перечень владельца, заход 16.08.2026). Вид отвечает на вопрос «ЧЕМ
# доказывается, что результат есть», указатель — «ГДЕ именно его искать».
KIND_COMMIT = "commit"      # коммит в origin/main
KIND_FILE = "file"          # файл на диске
KIND_ROW = "row"            # строка в базе
KIND_BRAIN = "brain"        # узел мозга
KIND_SERVICE = "service"    # старт сервиса моложе коммита
KINDS = (KIND_COMMIT, KIND_FILE, KIND_ROW, KIND_BRAIN, KIND_SERVICE)

KIND_TITLES = {
    KIND_COMMIT: "коммит в origin/main",
    KIND_FILE: "файл на диске",
    KIND_ROW: "строка в базе",
    KIND_BRAIN: "узел мозга",
    KIND_SERVICE: "старт сервиса моложе коммита",
}

EMPTY = ""                  # «адрес не назван» — ЗАКОННОЕ значение поля, а не сбой
SEP = ":"                   # первое двоеточие делит вид и указатель; в указателе их сколько угодно
POINTER_MAX = 200           # потолок указателя (см. «МИНА» в шапке)

# Символы, которые ломают сам маркер: скобки — его границы, переводы строк рвут строку очереди
# (и разбор журнала по заголовкам), таб коверкает выравнивание карточек.
BAD_CHARS = ("[", "]", "\r", "\n", "\t")

# Маркер в тексте задачи: «[result_ref commit:a545ad2]». Внутрь скобок не пускаем ни скобок,
# ни переводов строк — иначе «жадный» маркер съел бы половину ТЗ.
_MARK_RE = re.compile(r"\[" + FIELD + r"\s+([^\[\]\r\n]+)\]")


def _pointer_ok(pointer):
    """Указатель годен: непустой, в пределах потолка, без символов, ломающих маркер."""
    if len(pointer) == 0:
        return False
    if len(pointer) > POINTER_MAX:
        return False
    for ch in BAD_CHARS:
        if ch in pointer:
            return False
    return True


def make(kind, pointer):
    """(вид, указатель) → значение поля `"<вид>:<указатель>"`.

    ОТКАЗ ГРОМКИЙ (ValueError), а не тихое «не назван»: пишущий обязан узнать, что его адрес
    не принят, — молчаливая потеря адреса и есть тот класс, ради которого поле заводится."""
    k = str(kind).strip().lower()
    p = str(pointer).strip()
    if k not in KINDS:
        raise ValueError("неизвестный вид адреса %r (виды: %s)" % (kind, ", ".join(KINDS)))
    if len(p) == 0:
        raise ValueError("указатель пуст: вид без указателя адресом не является")
    if len(p) > POINTER_MAX:
        raise ValueError("указатель длиннее %d символов (%d) — он откусит хвост ТЗ шага"
                         % (POINTER_MAX, len(p)))
    for ch in BAD_CHARS:
        if ch in p:
            raise ValueError("указатель несёт символ %r, ломающий маркер" % ch)
    return k + SEP + p


def parse(value):
    """Значение поля → (вид, указатель) | None. `None` = «адресом не является» (в том числе
    пустая строка — законное «не назван»). Разбор НИЧЕГО не проверяет по факту: существует ли
    коммит/файл/строка — этот модуль не знает и знать не может."""
    if not isinstance(value, str):
        return None
    raw = value.strip()
    if SEP not in raw:
        return None
    kind, pointer = raw.split(SEP, 1)
    kind = kind.strip().lower()
    pointer = pointer.strip()
    if kind not in KINDS:
        return None
    if not _pointer_ok(pointer):
        return None
    return kind, pointer


def is_named(value):
    """Адрес назван (разбираемое непустое значение)? Пустое → False, и это НЕ сбой."""
    return parse(value) is not None


def norm(value):
    """Значение → канонический вид (`commit:a545ad2`) | `EMPTY`. Непонятое приравнивается к
    «не назван» — судить по нему всё равно нечем, а на исход поле не влияет ни одной веткой."""
    got = parse(value)
    if got is None:
        return EMPTY
    return got[0] + SEP + got[1]


def marker(value):
    """Значение → маркер `[result_ref <вид>:<указатель>]` | `EMPTY` (пусто/непонятно)."""
    val = norm(value)
    if len(val) == 0:
        return EMPTY
    return "[" + FIELD + " " + val + "]"


def prefix(value):
    """Маркер С РАЗДЕЛЯЮЩИМ ПРОБЕЛОМ для склейки в текст шага, либо `EMPTY`.

    Ради этого метода и живёт функция: при пустом адресе она отдаёт ПУСТУЮ строку, и текст
    шага собирается байт-в-байт как до появления поля."""
    mk = marker(value)
    if len(mk) == 0:
        return EMPTY
    return mk + " "


def read(text):
    """Текст задачи → значение поля | `EMPTY`. Берётся ПЕРВЫЙ РАЗБИРАЕМЫЙ маркер: битый или
    чужой (`[result_ref мусор]`) настоящий не глушит, а порядок записи старше приписки."""
    if not isinstance(text, str):
        return EMPTY
    for m in _MARK_RE.finditer(text):
        val = norm(m.group(1))
        if len(val) > 0:
            return val
    return EMPTY


def read_item(item):
    """РЯД ОЧЕРЕДИ → значение поля | `EMPTY`.

    Порядок источников — не вкусовой: НАСТОЯЩАЯ КОЛОНКА `result_ref` сильнее маркера в тексте.
    Сегодня колонки нет ни у одной полосы; в день, когда мост её заведёт, этот читатель уже
    предпочтёт её — мирить полосы будет нечем, а маркер останется совместимостью назад."""
    if not isinstance(item, dict):
        return EMPTY
    col = item.get(FIELD)
    if isinstance(col, str):
        val = norm(col)
        if len(val) > 0:
            return val
    return read(item.get("task_text"))
