# две разные ошибки, начинающиеся одинаково («ошибка выполнения …»), слились бы в
# одну причину. Обрезка живёт только в ПОКАЗЕ (:data:`CANON_SHOW`), где длинная
# строка мешает читать, а не решает.
#
# ЧЕСТНАЯ ГРАНИЦА, НАЗВАННАЯ ВСЛУХ: канон терпим к тому, чем одна причина
# отличается от СЕБЯ (номера, пути, кавычки, регистр, пунктуация), и НЕ терпим к
# разной длине фразы. Ошибка с плавающим хвостом (стек, дословный вывод ребёнка)
# каноном не склеится, и сигнал Б её не поймает. Это приемлемо ровно потому, что
# канон — ЧЕТВЁРТАЯ ступень опознания, а живой корпус ходит по первой: в
# `pc_orchestrator.log` 70 упоминаний `причина=<код>`.
CANON_SHOW = 12               # слов класса в СТРОКЕ ДЛЯ ЧЕЛОВЕКА; сравнение полное

# ═════════════════════════ КОНТРАКТЫ ДРУГИХ МОДУЛЕЙ ══════════════════════════
# ЛИТЕРАЛЫ ЗАИМСТВОВАНЫ, А НЕ ИМПОРТИРОВАНЫ, и это идиома полосы, а не лень:
# ровно так `contour_digest` держит имена полей реестра вердиктов («импорта
# `done_judge_pc` в чистом слое НЕТ намеренно… равенство литералов сторожит
# тест»). Причина та же — чистый слой не тянет за собой ни sqlite, ни диск, ни
# демона. РАВЕНСТВО КАЖДОГО ИЗ НИХ СВОЕМУ ВЛАДЕЛЬЦУ СТОРОЖИТ ТЕСТ, а не обещание
# в комментарии.
FAIL_CODE_RE = re.compile(r"причина=([a-z_]+)")     # = pc_orchestrator.FAIL_CODE_RE
REJECT_MARK = "отклонено Филиппом"                  # = card_terminal_log.REJECT_MARK
UNKNOWN_PREFIX = ("НЕИЗВЕСТНО (V0): результат по названному адресу "
                  "НЕ ПРОЧИТАН")                    # = done_judge_pc.UNKNOWN_PREFIX
# Человеческие имена кодов — тоже зеркало (`pc_orchestrator.FAIL_REASONS`), и
# тоже под тестом. Незнакомый код НЕ теряется: он остаётся классом под своим
# собственным именем, потому что новый код демона — это новая причина, а не
# «прочее».
FAIL_NAMES = {
    "approval_timeout": "таймаут подтверждения",
    "heartbeat_timeout": "таймаут сердцебиения",
    "run_timeout": "таймаут прогона",
    "model_refusal": "отказ модели",
    "exec_error": "ошибка выполнения",
    "unbacked_red": "заявка на красное без карточки гарда",
    "network_outage": "связи нет",
}
CLS_REJECT = "отказ владельца"
CLS_UNKNOWN = "вердикт судьи: продукт по адресу не прочитан"
CLS_SILENT = "причина не названа"

# ═════════════════════════ ВНЕШНИЙ ОТКАЗ ═════════════════════════════════════
# ОДИН РАЗЛИЧИТЕЛЬ НА ОБОИХ ПОТРЕБИТЕЛЕЙ (:func:`external_refusal`), и это главный
# замок этой правки, а не оформление. Потребителей у него два — суточный счёт
# (`shtab_box_run`: сколько слотов дня съедено) и сигнал А («две подряд
# недоказанные»), — и написать его дважды значило бы завести две копии, которые
# разойдутся МОЛЧА на первой же правке списка кодов. Второго мнения о том, что
# такое «отказ чужого API», у полосы нет ни одной ветки.
#
# ЧТО ИМЕННО ОТДЕЛЯЕТСЯ. Не «неудача вообще», а РОВНО ОДИН класс: заход, который
# умер на чужой стороне, НЕ ОСТАВИВ СЛЕДА РАБОТЫ. Такой слот полоса не тратила и
# задачу не проваливала — сгорел он у поставщика модели.
#
# ЖИВОЙ КОРПУС, НА КОТОРОМ ЭТО ИЗМЕРЕНО (лог демона 03.09.2026, два слота ящика):
#   • #101 20:36:06 — `причина=exec_error`, дословно «claude exit=1: API Error: 529
#     Overloaded. This is a server-side issue…», следы: коммитов 0, журнала 0.
#     ВНЕШНИЙ ОТКАЗ по обоим признакам;
#   • #100 20:23:33 — `причина=exec_error`, дословно «API Error: Server error
#     mid-response. The response above may be incomplete.», НО следы: коммитов 1
#     (14cb105 «Замок единственной копии…»), журнала 0. Внешним отказом ЭТОТ ряд
#     НЕ считается, и это не придирка: заход успел сделать работу, слот полоса
#     потратила, а «сделано ли задание» — вопрос к нам, а не к чужому API.
# То есть из ДВУХ слотов, названных премисой сгоревшими на чужом API, признак
# Штаба («умер до первой команды либо без следов работы») засчитывает ОДИН.
# Расхождение названо, а не подогнано.
#
# ПРИЗНАК МАШИННЫЙ И УЖЕ СУЩЕСТВУЮЩИЙ, а не выдуманный здесь: обе половины —
# готовые строки `pc_orchestrator.fail_result`, которые демон пишет в итог сам.
# Своего разбора вывода ребёнка этот слой не заводит и завести не может: он
# чистый, headless-процесса не видел и видеть не должен.
EXT_CODES = ("exec_error", "network_outage")
# ПОЧЕМУ ЭТИ ДВА И ПОЧЕМУ НЕ ОСТАЛЬНЫЕ ПЯТЬ. `network_outage` — это уже ВЕРДИКТ
# демона «внешний обрыв связи, а не ошибка исполнителя», вынесенный по двум
# независимым свидетелям (`_fail_is_network`); спорить с ним вторым разбором
# нечем и незачем. `exec_error` — единственный код, под которым к нам приходит
# смерть ребёнка от чужого API, и именно поэтому он ОДИН требует второй половины
# признака (слов самого ребёнка): под ним же приходят и наши собственные падения.
# Остальные пять внешними не бывают по построению: `approval_timeout` ждал
# ЧЕЛОВЕКА, `run_timeout` — наша задача не влезла в потолок, `heartbeat_timeout` —
# наш контур (процесс умер, ПК уснул), `model_refusal` и `unbacked_red` — заявка
# нашего же исполнителя на красное.
EXT_API_RE = re.compile(r"api error", re.I)   # так зовёт свой отказ САМ claude CLI
# Дословные куски `pc_orchestrator.fail_result`; равенство сторожит тест.
EXT_NO_TRACE = "Следов работы в окне"    # ветка «окно известно, следов НЕТ»
EXT_UNKNOWN_WINDOW = "Окно работы неизвестно"   # ветка «окна нет» — это НЕ «следов нет»
FAIL_HEAD = "[причина="                  # начало ЧАСТИ ДЕМОНА в тексте итога
# ТРИ ПОДРЯД — порог сигнала Д, дословно по заданию. Выше порога А (две) намеренно:
# у А улика — наша недоказанная работа, у Д — чужая перегрузка, которая проходит
# сама. Останавливать полосу на второй чужой ошибке значило бы делать её заложницей
# каждой минуты плохой погоды у поставщика.
EXT_STREAK_FLOOR = 3

# Маркер info-карточки ревизора. ЗАИМСТВОВАН (= `pc_orchestrator.REVIZOR_OWNER_MARK`)
# по той же причине, что и три литерала выше: чистый слой демона не импортирует.
# Равенство сторожит тест, а не обещание. Два ОСТАЛЬНЫХ вида, ждущих мнения,
# литералами здесь НЕ набраны вовсе — их спрашивают у `zayavki_pc`, потому что
# третий экземпляр той же строки разошёлся бы с обоими молча.
REVIZOR_CARD_MARK = "[ревизор-находки]"    # = pc_orchestrator.REVIZOR_OWNER_MARK

# Виды ряда `needs_approval`. Слова — для человека: по ним он читает строку
# остановки и строку витрины, и «держит» с «ждёт мнения» не смеют слиться в одно.
KIND_BLOCK = "карточка гарда"        # держит операцию: исполнитель остановлен и ждёт «да»
KIND_ASK = "заявка"                  # ждёт мнения: «да» = «принято к сведению», не держит НИЧЕГО
KIND_UNKNOWN = "вид не определён"    # тела нет — считаем ДЕРЖАЩЕЙ (отказ консервативный)

# ═════════════════════════ СТРОКА СНЯТИЯ ═════════════════════════════════════
# ФОРМА ОДНА, И ОНА ПЕЧАТАЕТСЯ ФРАЗОЙ ОСТАНОВКИ ЦЕЛИКОМ. Разбор намеренно
# терпимый к пробелам и регистру ключевых слов не трогает: строку копируют, а не
# набирают, — но копируют люди, и лишний пробел не смеет стоить владельцу второго
# захода.
RELEASE_RE = re.compile(r"\[\[\s*ЯЩИК\s+СНЯТЬ\s+метка=([0-9a-f]{6,32})\s*\]\]")
RELEASE_FORM = "[[ЯЩИК СНЯТЬ метка=%s]]"

# ═════════════════════════ КАНОН ПРИЧИНЫ ═════════════════════════════════════
# Что вычищается перед сравнением — ПЕРЕМЕННЫЕ части, из-за которых одна и та же
# причина выглядит тремя. Порядок замен важен: кавычки уносят вложенные пути и
# числа целиком, поэтому идут первыми.
_RE_QUOTED = re.compile(r"['\"«][^'\"»\r\n]{0,300}['\"»]")
_RE_PATH = re.compile(r"[0-9A-Za-zА-Яа-яЁё_.-]*[\\/][0-9A-Za-zА-Яа-яЁё_./\\-]+")
_RE_HEX = re.compile(r"\b[0-9a-fA-F]{6,}\b")
_RE_NUM = re.compile(r"\d+")
_RE_PUNCT = re.compile(r"[^0-9A-Za-zА-Яа-яЁё_]+")


def canon_reason(text):
    """Причина словами → КАНОН для сравнения. → str (пусто = сравнивать нечем).

    Вычищает ровно то, чем один и тот же отказ отличается от СЕБЯ САМОГО: номера
    задач, длительности таймаутов, пути, кавычки и шестнадцатеричные хвосты.
    Первая строка выбрасывается, если это МАРКЕР РЯДА ЯЩИКА, — он в каждой задаче
    свой (дата и ключ), и склеивать по нему нельзя.

    НЕ ОБРЕЗАЕТСЯ: сравнение идёт по строке целиком (разбор — у :data:`CANON_SHOW`).
    """
    s = str(text or "")
    lines = s.splitlines()
    if lines and shtab_box.MARK_RE.match(lines[0]):
        lines = lines[1:]
    s = "\n".join(lines).casefold()
    s = _RE_QUOTED.sub(" ", s)
    s = _RE_PATH.sub(" ", s)
    s = _RE_HEX.sub(" ", s)
    s = _RE_NUM.sub(" ", s)
    return " ".join(w for w in _RE_PUNCT.split(s) if w)


def show_class(cls):
    """Имя класса причины В СТРОКУ ДЛЯ ЧЕЛОВЕКА. → str.

    Режет ПОКАЗ, а не сравнение: строка остановки читается глазами, и канон в
    сорок слов в ней бесполезен. Обрезка помечается многоточием — молча
    укороченное имя читалось бы как полное.
    """
    words = str(cls or "").split()
    if len(words) <= CANON_SHOW:
        return str(cls or "")
    return " ".join(words[:CANON_SHOW]) + " …"


def reason_class(result):
    """Текст итога закрытой строки → (класс, чем опознан). → (str, str).

    Четыре ступени опознания, от твёрдого к мягкому — разбор в шапке,
    §«ЧТО СЧИТАТЬ ОДНОЙ ПРИЧИНОЙ». Пустой итог классом ЯВЛЯЕТСЯ
    (:data:`CLS_SILENT`): три задачи, провалившиеся вовсе без слов, — это
    повторяющаяся поломка, а не три разных случая.
    """
    text = str(result or "")
    m = FAIL_CODE_RE.search(text)
    if m:
        code = m.group(1)
        return ("%s (%s)" % (FAIL_NAMES.get(code, "код демона"), code), "код причины")
    if text.lstrip().startswith(REJECT_MARK):
        return (CLS_REJECT, "маркер отказа владельца")
    if UNKNOWN_PREFIX in text:
        return (CLS_UNKNOWN, "маркер вердикта судьи")
    canon = canon_reason(text)
    if not canon:
        return (CLS_SILENT, "итог пуст")
    return ("прочее: %s" % canon, "канон причины (сравнение по строке целиком)")


def daemon_part(result):
    """Текст итога → ЧАСТЬ, НАПИСАННАЯ ДЕМОНОМ. → str (пусто = её нет).

    ═══ ЗАЧЕМ РЕЗАТЬ, А НЕ ИСКАТЬ ПО ВСЕЙ СТРОКЕ ════════════════════════════

    Итог провала склеен из ДВУХ ЧУЖИХ ДРУГ ДРУГУ ТЕКСТОВ, и это видно прямо в
    `pc_orchestrator.fail_result`: сначала идёт ``lead`` — маркер причины и
    ЧЕРНОВИК ДОКЛАДА, который писал НАШ ЖЕ ИСПОЛНИТЕЛЬ, — и только потом
    ``[причина=…]`` и улики, которые пишет демон.

    Черновик пишет модель, и она пишет туда что угодно, включая дословную цитату
    чужого отказа: задача, разбирающая ЭТОТ САМЫЙ класс, обязана процитировать в
    докладе и «API Error: 529», и «Следов работы в окне … нет». Ищи признак по
    строке целиком — и наш собственный провал на задаче про внешние отказы
    объявил бы себя внешним отказом, то есть получил бы бесплатный слот за
    рассказ о бесплатных слотах. Ровно этот случай стои́т отрицательным тестом.

    Признак берётся ТОЛЬКО из части демона. Части нет вовсе (итог без
    ``[причина=``: закрытие руками, отказ владельца, вердикт судьи) → пусто, и
    внешним такой ряд не станет ни одной веткой.
    """
    text = str(result or "")
    at = text.find(FAIL_HEAD)
    return text[at:] if at >= 0 else ""


def external_refusal(row):
    """Эта закрытая строка сгорела на ЧУЖОМ API, а не на нашей работе? → (bool, слова).

    ЕДИНСТВЕННЫЙ РАЗЛИЧИТЕЛЬ ВНЕШНЕГО ОТКАЗА НА ПОЛОСЕ. Им пользуются ОБА
    потребителя — суточный счёт (`shtab_box_run`) и сигнал А, — и третьего
    экземпляра у полосы нет: разбор, почему это важнее удобства, — в шапке
    раздела «ВНЕШНИЙ ОТКАЗ».

    ═══ ЧЕТЫРЕ УСЛОВИЯ, И ВСЕ ОБЯЗАТЕЛЬНЫ ═══════════════════════════════════

    1. статус ``failed``. Сданное задание внешним отказом не бывает по смыслу
       слова, а ``needs_approval`` ещё не закрыто;
    2. это не РЕШЕНИЕ ЧЕЛОВЕКА (``отклонено Филиппом``) и не вердикт судьи:
       отказ владельца лежит в том же ``failed``, и списывать его на чужое API
       значило бы прятать слово человека за погодой;
    3. код причины — из :data:`EXT_CODES`, и для ``exec_error`` дополнительно
       нужны СЛОВА САМОГО РЕБЁНКА о чужом API (``API Error``). Под этим кодом
       приходят и наши собственные падения — без второй половины признак
       записал бы в чужие любую ошибку исполнения;
    4. СЛЕДОВ РАБОТЫ В ОКНЕ НЕТ — дословная фраза демона. Это и есть «умер до
       первой команды либо без следов работы» из задания, и без него признак
       прощал бы заходы, которые успели наработать (живой #100 от 03.09:
       та же ``API Error``, но коммит 14cb105 в окне — слот потрачен, ряд наш).

    ТРЕТИЙ ИСХОД НЕ ДАЁТ ЛЬГОТЫ. Ветка демона «окно работы неизвестно — следы НЕ
    проверялись» (:data:`EXT_UNKNOWN_WINDOW`) означает «не знаю, была ли работа»,
    а не «работы не было». Списать на чужое API незнание — значит выдать льготу
    там, где улики нет вовсе; на всей полосе «не знаю» не превращается в «хорошо»
    ни одной веткой, и здесь тоже не превратится.
    """
    one = row if isinstance(row, dict) else {}
    if str(one.get("status") or "") != "failed":
        return False, "ряд не в статусе failed — внешним отказом бывает только провал"
    text = str(one.get("result") or "")
    if text.lstrip().startswith(REJECT_MARK):
        return False, "решение владельца (%s) — не отказ чужого API" % REJECT_MARK
    part = daemon_part(text)
    if not part:
        return False, "в итоге нет части демона (%s…) — судить не по чему" % FAIL_HEAD
    m = FAIL_CODE_RE.search(part)
    code = m.group(1) if m else ""
    if code not in EXT_CODES:
        return False, ("причина «%s» внешней не бывает: её называет НАШ контур"
                       % (code or "не названа"))
    if code == "exec_error" and not EXT_API_RE.search(part):
        return False, ("причина exec_error, но о чужом API исполнитель не сказал ни слова "
                       "— это наша ошибка выполнения")
    if EXT_NO_TRACE not in part:
        if EXT_UNKNOWN_WINDOW in part:
            return False, ("окно работы неизвестно — были ли следы, НЕ ЗНАЕМ; льготы за "
                           "незнание не даём")
        return False, "в окне задачи есть следы работы — слот полоса потратила"
    return True, ("отказ чужого API (%s) без следов работы в окне — слот суток не съеден "
                  "и недоказанной задачей не считается" % code)


def external_keys(rows):
    """Ряды :func:`box_rows` → ключи заданий, сгоревших на чужом API. → set.

    Корпусный вид ТОГО ЖЕ :func:`external_refusal`, а не второе правило: суточный
    счёт живёт на маркерах (пары «день, ключ»), а различитель — на рядах, и мост
    между ними обязан быть ровно один.
    """
    return {str((r or {}).get("key") or "") for r in (rows or [])
            if (r or {}).get("key") and external_refusal(r)[0]}


# ═════════════════════════ КОРПУС: ЗАКРЫТЫЕ ЗАДАНИЯ ЯЩИКА ════════════════════


def box_rows(rows, statuses=("failed", "done")):
    """Ряды очереди → ТОЛЬКО закрытые задания ЯЩИКА, по возрастанию номера. → list.

    Опознание — по МАРКЕРУ РЯДА (:data:`shtab_box.MARK_RE`), тому же, которым
    ящик считает свой суточный потолок и свой дедуп. Третьего мнения о том, что
    такое «ряд из ящика», у полосы не заводится.

    ПОРЯДОК — ПО НОМЕРУ ОЧЕРЕДИ, и это выбор с названной ценой. Времени закрытия
    в рядах моста мы не читаем (его нет ни в одном поле, которым пользуется
    ящик), а «две ПОДРЯД» без порядка не существует вовсе. Номер монотонен внутри
    поколения очереди; на сбросе нумерации (очередь начинает с 1) порядок
    поколений теряется — граница названа вслух и стои́т в артефакте.
    """
    keep = set(statuses or ())
    out = []
    for it in (rows or []):
        row = it if isinstance(it, dict) else {}
        if keep and str(row.get("status") or "") not in keep:
            continue
        m = shtab_box.MARK_RE.match(str(row.get("task_text") or ""))
        if not m:
            continue
        try:
            num = int(row.get("id"))
        except (TypeError, ValueError):
            continue
        out.append({"id": num, "day": m.group(1), "key": m.group(2),
                    "status": str(row.get("status") or ""),
                    "result": str(row.get("result") or "")})
    out.sort(key=lambda r: r["id"])
    return out


def proved(row, judged):
    """Эта закрытая строка получила вердикт «сделано»? → (bool, слова).

    ДВА УСЛОВИЯ, оба обязательны: статус ``done`` И вердикт судьи «доказана».
    Одного ``done`` не хватает — в режиме ``addr`` безадресное закрытие остаётся
    ``done``, и счёт по одному исходу зачитывал бы работу, которую никто не
    проверял (тот же довод, что у :func:`contour_digest.is_clean`).

    Слово судьи берётся у :func:`contour_digest.judged_of` — ЧУЖОГО устройства с
    четырьмя ответами. Свой разбор реестра разошёлся бы с ним на первой правке
    имён полей.
    """
    one = row or {}
    said = contour_digest.judged_of(one.get("id"), judged)
    if str(one.get("status") or "") != "done":
        if str(one.get("result") or "").lstrip().startswith(REJECT_MARK):
            return False, "отклонена владельцем"
        return False, "закрыта как failed"
    if said == contour_digest.JUDGE_PROVED:
        return True, said
    return False, "судья: %s" % said


