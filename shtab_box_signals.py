# в шапке узла, а шапка читается мостом и может не прочитаться; прежде
# нечитаемая шапка означала «меток снятия нет», то есть НЕДОСТУПНОСТЬ МОСТА
# ЧИТАЛАСЬ КАК ОТСУТСТВИЕ СЛОВА ВЛАДЕЛЬЦА, и ящик снова просил метку, которую
# владелец уже дал. Слово владельца из узла не исчезает — значит однажды
# увиденное снятие остаётся увиденным, и «не прочитали шапку» больше не
# отменяет решения человека.
HOLD_SCHEMA = "turbobaby.shtab_box_hold/v1"


def holdable(one):
    """Этот сигнал подлежит ЗАМКУ (переживает виток)? → bool.

    Четыре условия, и каждое отсекает свой класс: сработал · держит ЭТОТ слой
    (Г показывает, но не держит) · снимается СЛОВОМ ВЛАДЕЛЬЦА (В снимается сам,
    как только владелец ответил, и замок сделал бы его вечным) · ОПРЕДЕЛЁННЫЙ
    (разбор — в шапке раздела). Уже запертый второй раз не запирается.
    """
    one = one or {}
    return bool(one.get("on") and one.get("enforced") and not one.get("released")
                and not one.get("held") and one.get("determinate")
                and one.get("release") == BY_OWNER and str(one.get("mark") or ""))


def hold_record(one, now=""):
    """Сработавший сигнал → запись замка. → dict (пустая метка = писать нечего).

    Хранится ровно то, чем фраза остановки собирается заново: буква, метка,
    слова и момент. Времени функция не знает — его подаёт вызывающий
    (инвариант чистоты :data:`SHTAB_SIGNALS_PURE`).

    РЯДЫ ХРАНЯТСЯ ОТДЕЛЬНЫМ ПОЛЕМ (06.09.2026), а не только внутри ``why``, и это
    не удобство: извещение владельцу обязано назвать, КАКИЕ РЯДЫ подняли сигнал
    (:func:`hold_notice`), а вытаскивать номера обратно из человеческой фразы
    значило бы разбирать собственный текст регулярным выражением — тот самый
    класс, на котором полоса уже обжигалась. У сигналов без улик поле пустое, и
    извещение честно говорит «ряды названы в причине», а не выдумывает номера.
    """
    one = one or {}
    return {"schema": HOLD_SCHEMA, "mark": str(one.get("mark") or ""),
            "sig": str(one.get("sig") or ""), "why": str(one.get("why") or ""),
            "count": one.get("count"), "at": str(now or ""), "released": False,
            "evidence": [str(e) for e in (one.get("evidence") or ())][:6]}


def hold_free(rec_mark, now="", by=""):
    """Метка, снятая словом владельца → запись снятия. → dict.

    Отдельной строкой, а не правкой прежней: файл замка дописывается и никогда
    не переписывается — ровно как долгая память взятых ключей
    (:func:`shtab_box_run.remember`). Переписывание файла состояния стои́т
    потерянной строки на первом же обрыве.

    ``by`` — КЕМ снято, словами (06.09.2026). Дорог снятия стало две — метка в
    шапке узла и ответ в Telegram, — и «кто ответил» перестало быть очевидным из
    самого факта. Право оно не судит и судить не может: личности звонящего у
    этого слоя нет вовсе (её знает только `pc_agent`, см. §«ОТВЕТ В TELEGRAM»);
    поле — СЛЕД для человека, читающего замок глазами.
    """
    return {"schema": HOLD_SCHEMA, "mark": str(rec_mark or ""), "released": True,
            "at": str(now or ""), "by": str(by or "")}


def hold_index(held):
    """Строки файла замка → {метка: запись}, поздняя строка поверх ранней. → dict.

    Схлопывание живёт ЗДЕСЬ, а не в руках, потому что это правило чтения, а не
    работа с диском: строка снятия несёт одну метку и признак, а слова и момент
    случая остаются от строки постановки.
    """
    out = {}
    for rec in (held or ()):
        rec = rec if isinstance(rec, dict) else {}
        mark = str(rec.get("mark") or "")
        if not mark:
            continue
        merged = dict(out.get(mark) or {})
        merged.update(rec)
        out[mark] = merged
    return out


def hold_release(held, released=()):
    """ВСЕ снятые метки: увиденные сейчас плюс увиденные когда-то. → set.

    Одна дверь на весь вопрос «снят ли этот случай»: и :func:`evaluate`, и
    :func:`merge_held` получают ОДНО множество. Два мнения о снятии разошлись бы
    молча на первой же нечитаемой шапке — с чего эта правка и началась.
    """
    out = {str(m) for m in (released or ()) if str(m or "")}
    for mark, rec in hold_index(held).items():
        if rec.get("released"):
            out.add(mark)
    return out


def held_signal(rec):
    """Запись замка → сигнал, держащий ящик ПО ПАМЯТИ. → dict.

    Слова прежние плюс честная приписка: живой корпус этого случая больше не
    показывает. Без неё владелец пошёл бы искать в очереди ряды, которых там
    уже нет, и счёл бы остановку выдуманной.
    """
    rec = rec if isinstance(rec, dict) else {}
    one = _sig(str(rec.get("sig") or "?"), True,
               "%s · ДЕРЖИТСЯ ЗАМКОМ (случай записан %s): живой корпус очереди его больше не "
               "показывает — номера очереди идут по кругу и ряды пропадают, — но снятия словом "
               "владельца не было"
               % (str(rec.get("why") or "слова случая не сохранились"),
                  str(rec.get("at") or "момент не назван")),
               BY_OWNER, mark=str(rec.get("mark") or ""), count=rec.get("count"),
               # УЛИКИ ЕДУТ И СЮДА: запомненный случай обязан выглядеть для читателя
               # ровно тем же сигналом, что и живой, — иначе «ряды #1, #4, #6»
               # пропадали бы ровно тогда, когда живого корпуса уже нет, то есть
               # именно тогда, когда номера рядов человеку и нужны.
               evidence=rec.get("evidence") or ())
    one["held"] = True
    one["held_at"] = str(rec.get("at") or "")
    return one


def merge_held(signals, held=(), released=(), now=""):
    """Живые сигналы + замок + снятия → ОДИН список. → (сигналы, запереть, отпустить).

    ``released`` — уже собранное множество снятых меток (:func:`hold_release`),
    а не сырые метки шапки: снятие применяет одно место.

    Возвращает ТРИ вещи, и две последние — работа для рук:

    * **сигналы** — тот самый единственный список, из которого берутся и фраза
      владельцу, и запрет брать. Запомненный случай, которого живой корпус уже
      не показывает, встаёт на место молчащего сигнала своей буквы (список
      обязан оставаться перечнем ВСЕХ сторожей, а не превращаться в ленту);
    * **запереть** — записи для файла замка: сработавшие сейчас и ещё не
      запертые;
    * **отпустить** — метки, которые владелец снял словом ТОЛЬКО ЧТО: их
      признак надо положить на диск, иначе следующая нечитаемая шапка вернёт
      снятую остановку.
    """
    idx = hold_index(held)
    gone = {str(m) for m in (released or ())}
    out, live_marks = [], set()
    for one in (signals or []):
        one = dict(one)
        mark = str(one.get("mark") or "")
        if one.get("on") and mark and mark in gone and one.get("release") == BY_OWNER:
            one["released"], one["released_mark"] = True, mark
        if one.get("on") and mark:
            live_marks.add(mark)
        out.append(one)
    arm = [hold_record(one, now=now) for one in out
           if holdable(one) and str(one["mark"]) not in idx]
    free = sorted(m for m in gone if m in idx and not idx[m].get("released"))
    for mark in sorted(idx):
        if mark in gone or mark in live_marks:
            continue
        one = held_signal(idx[mark])
        slot = next((i for i, s in enumerate(out)
                     if s.get("sig") == one["sig"] and not s.get("on")), None)
        if slot is None:
            out.append(one)
        else:
            out[slot] = one
    return out, arm, free


# ═══════════ ИЗВЕЩЕНИЕ ОБ ОСТАНОВКЕ И ОТВЕТ В TELEGRAM (06.09.2026) ══════════
# ПРЕМИСА, ПЕРЕМЕРЕННАЯ ПО КОДУ, А НЕ ПРИНЯТАЯ НА СЛОВО. До этой правки поднятая
# остановка не выходила за пределы полосы НИ ОДНОЙ ВЕТКОЙ: `stop_words` уезжала в
# лог демона, в витрину и строкой `ASK` в журнал (`pc_orchestrator._shtab_box_announce`
# → `cowork_log`), а единственная дверь наружу у ящика — `shtab_box_run.notify_taken` —
# зовётся ТОЛЬКО внутри ветки `placed`, то есть на ВЗЯТИИ задания. Остановленный ящик
# не берёт ничего по построению, значит на остановке эта дверь не открывается никогда.
# Владелец узнавал о стоящем ящике из журнала, который читает не он, — то есть не
# узнавал вовсе. Премиса подтвердилась.
#
# ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕФЕКТА — ЦЕНА ОТВЕТА. Снять остановку можно было ровно
# одним способом: положить строку `[[ЯЩИК СНЯТЬ метка=…]]` В УЗЕЛ МОЗГА. С телефона
# это не делается, а владелец на этой полосе отвечает с телефона (то же основание,
# по которому кнопку получили заявки ступени G и ворота клиентского контура).
#
# ═══ ПОЧЕМУ КРИТИЧЕСКИЙ КАНАЛ, А НЕ ТЕМА ПОСТАНОВКИ ═════════════════════════
# Адрес выбирает ОДИН признак — ждёт ли сообщение ОТВЕТА владельца (правило
# владельца 10.08.2026, `CLAUDE.md`). Извещение о ВЗЯТИИ ответа не ждёт и потому
# едет строго в тему 328 без фолбэков. Это извещение ответа ЖДЁТ — им ящик и
# держится, — значит его место в инбоксе 1160, и кнопка под ним обязательна:
# карточка с кнопкой попадает в 1160 ВСЕГДА, мимо признака. Два сообщения с
# противоположными требованиями к адресу живут в одном модуле, и различает их не
# намерение автора, а РАЗНЫЕ ДВЕРИ (`notify_taken` против `notify_hold`).
#
# ═══ ОДНА ОСТАНОВКА — ОДНО ИЗВЕЩЕНИЕ, И ДЕРЖИТ ЭТО НЕ ВТОРОЙ РЕЕСТР ═════════
# Виток ящика — 30 минут, остановка живёт до слова владельца, то есть часы и
# сутки: докладывай мы ФАКТ остановки, одна метка дала бы под полсотни карточек
# за ночь. Признак «сказали» лежит ТАМ ЖЕ, где сама остановка, — отдельной
# строкой файла замка (:func:`hold_told`), и это ровно тот довод, которым живёт
# `hold_free`: второй реестр «кому уже сказали» разошёлся бы с первым молча
# (класс 539). Запись «сказали» ложится ПОСЛЕ доставки: не сказали и не
# записали — скажем следующим витком; записали бы вперёд — сорвавшаяся отправка
# осталась бы молчанием навсегда, а мы чиним ровно молчание.
#
# ПОЛЕ ВРЕМЕНИ У НЕЁ СВОЁ (`told_at`, а не `at`) И ЭТО НЕ КОСМЕТИКА: чтение
# схлопывает строки одной метки поздней поверх ранней (:func:`hold_index`), и
# `at` в строке доклада затёр бы МОМЕНТ СЛУЧАЯ — то самое число, которым
# запомненный сигнал объясняет человеку, когда его видели живьём.
HOLD_TOLD_KEY = "told"

# ФОРМА КНОПКИ ВЗЯТА У УЖЕ РАБОТАЮЩИХ, СВОЯ НЕ ВЫДУМАНА: `<вид>:<действие>:<хвост>`
# — так устроены кнопки цепей (`chain:stop:<pid>`), заявок (`zayavka:yes:<id>`) и
# ворот (`gate:yes:<коммит>`); ловит их ОДИН обработчик `pc_agent.on_chain_callback`
# тем же ботом, которым карточка отправлена. Хвост — метка случая, 12 hex
# (:func:`mark_of`), вместе с приставкой это 21 байт при потолке Telegram в 64.
RELEASE_CB = "box:free:%s"
RELEASE_BTN = "🔓 Снять остановку"
# СЛОВЕСНЫЙ ЗАПАСНОЙ ПУТЬ. Нужен не для красоты: живой случай 05.09 — владелец
# нажал кнопку ворот и получил «карточка устарела», потому что процесс агента был
# СТАРШЕ кнопки. Тап, которому некуда деться, стои́т владельцу потерянного ответа,
# поэтому адрес словами едет в самом извещении.
RELEASE_WORD = "ящик снять %s"
RELEASE_WORD_AT = "теме «PC-дев» (205)"
STOP_NOTICE_HEAD = "⛔ ЯЩИК ШТАБА ОСТАНОВЛЕН СИГНАЛОМ"
# Потолок сообщения. Причина сигнала бывает длинной (перечень рядов с вердиктами),
# и режется ИМЕННО ОНА: метка, кнопка и словесный адрес — то, ради чего извещение
# существует, и обрезаться они не смеют ни при какой длине.
STOP_NOTICE_MAX = 900
STOP_NOTICE_WHY_MAX = 400


def telegram_way(mark):
    """«Чем снимается» ДОРОГОЙ TELEGRAM — одной вставкой. → str.

    Живёт отдельной функцией, потому что этих слов ДВА МЕСТА: фраза остановки
    (`stop_words` → журнал и витрина) и карточка владельцу (:func:`hold_notice`).
    Два их экземпляра разошлись бы молча, и владелец, прочитавший журнал, искал
    бы кнопку не там — ровно тот класс, которым живёт весь этот куст.
    """
    m = str(mark or "")
    return ("ответом в Telegram: кнопка под извещением в инбоксе либо слово «%s» в %s"
            % (RELEASE_WORD % m, RELEASE_WORD_AT))


def hold_told(mark, now=""):
    """Метка, о которой владельцу СКАЗАЛИ → запись замка. → dict.

    Ни ``at``, ни ``sig``, ни ``why`` здесь нет СОЗНАТЕЛЬНО (разбор — в шапке
    раздела): строка доклада обязана добавить к случаю один признак и не тронуть
    в нём больше ничего.
    """
    return {"schema": HOLD_SCHEMA, "mark": str(mark or ""), HOLD_TOLD_KEY: True,
            "told_at": str(now or "")}


def untold(held):
    """Записи замка, о которых владельцу ЕЩЁ НЕ СКАЗАЛИ. → list[dict].

    Снятые не берутся ни одной веткой: остановка, которую владелец уже отпустил,
    новостью не является, а карточка о ней звала бы снимать снятое.

    ПОРЯДОК — ПО МЕТКЕ, а не по времени: у двух случаев одного витка момент
    записи совпадает посимвольно, и «по времени» означало бы «в случайном
    порядке» — то есть разный текст на двух одинаковых прогонах.
    """
    return [rec for _m, rec in sorted(hold_index(held).items())
            if not rec.get("released") and not rec.get(HOLD_TOLD_KEY)]


def release_buttons(mark):
    """Инлайн-клавиатура ответа в ОДИН ТАП. → dict.

    Ответ обязан работать с телефона и не требовать точного набора текста —
    основание то же, что у кнопок заявок (`zayavki_pc.buttons`). Кнопка ОДНА:
    второй («не снимать») у остановки нет и быть не может — бездействие и есть
    «не снимать», а кнопка с этим смыслом лишь предлагала бы владельцу нажать
    что-нибудь.
    """
    return {"inline_keyboard": [[
        {"text": RELEASE_BTN, "callback_data": RELEASE_CB % str(mark or "")},
    ]]}


def hold_notice(rec):
    """Запись замка → извещение владельцу. → str (пусто = писать нечего).

    ТРИ ЧАСТИ, И КАЖДАЯ ЗАТРЕБОВАНА ОТДЕЛЬНО (задание 06.09): КАКОЙ СИГНАЛ ·
    КАКИЕ РЯДЫ ЕГО ПОДНЯЛИ · ЧЕМ СНИМАЕТСЯ. Фраза без одной из трёх неотличима от
    общего «что-то сломалось»: по первой владелец понимает, кого разбирать, по
    второй — где смотреть, по третьей — что сделать, чтобы полоса поехала.

    РЯДЫ БЕРУТСЯ ИЗ УЛИК, А НЕ ВЫДИРАЮТСЯ ИЗ ПРИЧИНЫ. Улик нет (их не бывает у
    остановки «не знаю») — так и говорим, а не молчим: «ряды не названы» и «рядов
    ноль» — разные новости.
    """
    rec = rec if isinstance(rec, dict) else {}
    mark = str(rec.get("mark") or "")
    if not mark:
        return ""
    letter = str(rec.get("sig") or "?")
    rows = [str(e) for e in (rec.get("evidence") or ()) if str(e or "")]
    why = " ".join(str(rec.get("why") or "причина не сохранилась").split())
    if len(why) > STOP_NOTICE_WHY_MAX:
        why = why[:STOP_NOTICE_WHY_MAX - 1] + "…"
    head = ("%s %s («%s») — заданий Штаба полоса больше НЕ БЕРЁТ"
            % (STOP_NOTICE_HEAD, letter, TITLE.get(letter, "имя сигнала не сохранилось")))
    # ТРЕТИЙ ИСХОД И ЗДЕСЬ, И ОН НЕ УМОЗРИТЕЛЬНЫЙ: поле улик заведено 06.09.2026, а
    # записи замка СТАРШЕ его не имеют вовсе — живая запись полосы `ddac4cc3b98a`
    # (сигнал А, заперта 06.09 11:45Z) именно такая. Сказать про неё «рядов нет» было
    # бы враньём: ряды у случая есть (#101 и #102), их нет В ЗАПИСИ, и человека надо
    # отправить туда, где они лежат, — в причину.
    rows_line = ("Подняли ряды: %s." % ", ".join(rows) if rows
                 else "Ряды отдельным полем в записи не сохранились — они названы в причине ниже.")
    # СЛОВА «ЧЕМ СНИМАЕТСЯ» — ТЕ ЖЕ, ЧТО В ЖУРНАЛЕ: их печатает одна функция
    # (:func:`telegram_way`), а не две похожие. Владелец читает про один и тот же
    # случай в двух местах, и разъехаться эти два текста не смеют ни на слово.
    tail = ("Снять: %s. Снимает ТОЛЬКО владелец и ТОЛЬКО этот случай — следующий такой же "
            "остановит снова." % telegram_way(mark))
    stamp = "Метка случая: %s (записан %s)." % (mark, str(rec.get("at") or "момент не назван"))
    # РЕЖЕМ ПРИЧИНУ, А НЕ ХВОСТ. Слепое ``[:MAX]`` отрезало бы ровно то, ради чего
    # извещение существует, — метку, кнопку и словесный адрес ответа: они стоя́т
    # последними, потому что человек читает их последними, а не потому, что они
    # менее важны. Это тот же порядок обрезки, что у извещения о взятии
    # (`shtab_box.take_notice`): голова и хвост целы всегда, платит середина.
    over = len("\n".join([head, rows_line, "Почему: %s" % why, stamp, tail])) - STOP_NOTICE_MAX
    if over > 0:
        why = why[:max(1, len(why) - over - 1)] + "…"
    return "\n".join([head, rows_line, "Почему: %s" % why, stamp, tail])
