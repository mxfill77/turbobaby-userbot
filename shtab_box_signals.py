def evaluate(*, closed=(), open_rows=(), judged=None, day="", left=None,
             budget=None, released=(), rows_ok=True, open_ok=True, judged_ok=True,
             marks_ok=True):
    """Все факты → ПЯТЬ сигналов, в порядке А·Б·В·Г·Д. → list[dict].

    Порядок постоянный и полный: человек обязан видеть все пять в одном месте,
    в том числе молчащие. Список, из которого молчащие вычеркнуты, читается как
    «остальных сигналов не существует» — а их существует ровно пять.

    ``released`` — метки, снятые словом владельца. Снятый сигнал остаётся в
    списке и остаётся ``on``: он не исчез, он ПРОЩЁН, и человеку это видно
    отдельным полем. Прячь мы его — владелец не смог бы отличить «сигнала нет» от
    «сигнал есть, но я его вчера снял».
    """
    marks = set(released or ())
    out = [
        signal_a(closed, judged, rows_ok=rows_ok, judged_ok=judged_ok, day=day),
        signal_b(closed, day, rows_ok=rows_ok),
        signal_c(open_rows, rows_ok=open_ok),
        signal_d(left, budget=budget, day=day, marks_ok=marks_ok),
        signal_e(closed, day, rows_ok=rows_ok),
    ]
    for one in out:
        if one["on"] and one["release"] == BY_OWNER and one["mark"] in marks:
            one["released"] = True
            one["released_mark"] = one["mark"]
    return out


def active(signals):
    """Сигналы, которые ДЕРЖАТ ящик прямо сейчас. → list[dict].

    Держит сигнал, если он сработал, НЕ снят словом владельца и исполняется этим
    слоем. Сигнал Г исполняется не здесь (:func:`signal_d`), поэтому в остановку
    он не входит, хотя в показ входит всегда.
    """
    return [s for s in (signals or [])
            if s.get("on") and s.get("enforced") and not s.get("released")]


def stop_words(signals, node=None, checked=True, why=""):
    """ОДНА человеческая фраза остановки. → str (пусто = ящик не остановлен).

    Молчащая остановка запрещена заданием, и запрет этот держится не намерением,
    а формой строки: она обязана назвать ЧТО сработало, НА ЧЁМ стои́т числом и ЧЕМ
    снимается. Фраза без одной из трёх частей неотличима от пустого ящика — а
    пустой ящик и остановленный ящик суть разные новости.

    ``checked`` — УДАЛОСЬ ЛИ В ЭТОТ ОБОРОТ ПОСМОТРЕТЬ, НЕ СНЯЛ ЛИ ВЛАДЕЛЕЦ. Метки
    снятия живут в шапке узла, шапка читается мостом, мост молчит измеримо часто.
    Прежде нечитаемая шапка молча означала «снятия нет», и фраза требовала
    положить метку — ту самую, которую владелец мог положить час назад. Это и
    есть третий исход, доложенный как факт: «не смогли проверить» выдавало себя
    за «вы не отвечали». Держится ящик по-прежнему («не знаю» значит «стоп»), но
    ПРОСЬБА к человеку исчезает, а вместо неё говорится, чего мы не смогли.
    """
    on = active(signals)
    if not on:
        return ""
    box = str(node or shtab_box.NODE_NAME)
    parts = []
    for one in on:
        head = "сигнал %s («%s»): %s" % (one["sig"], one["title"], one["why"])
        if one["release"] != BY_OWNER:
            head += ". Снимается %s — держать словом не нужно" % one["release"]
        elif checked:
            head += (". Снимается %s — %s, либо положите в узел %s строку %s (снимает ИМЕННО этот "
                     "случай; следующий такой же остановит снова)"
                     % (BY_OWNER, telegram_way(one["mark"]), box, RELEASE_FORM % one["mark"]))
        else:
            head += (". Снимается %s — %s. СНЯЛИ ЛИ ЕЁ МЕТКОЙ В УЗЛЕ, в этот оборот ПРОВЕРИТЬ НЕ "
                     "УДАЛОСЬ (%s): шапка узла %s не прочитана, поэтому «снятия нет» сказать "
                     "НЕЛЬЗЯ, это НЕИЗВЕСТНО. Ящик держится, но если строку %s вы уже положили — "
                     "класть заново НЕ НУЖНО, она никуда не делась"
                     % (BY_OWNER, telegram_way(one["mark"]), str(why or "причина не названа"), box,
                        RELEASE_FORM % one["mark"]))
        parts.append(head)
    return "СИГНАЛЬНАЯ ОСТАНОВКА ЯЩИКА · " + " · ".join(parts)


def all_words(signals, day=""):
    """ВСЕ ПЯТЬ сигналов одним перечнем — для витрины и для ``--status``. → list[str].

    Показывает и молчащие: человек, которому показали только сработавшие, не
    знает, сколько сторожей вообще стои́т, и не отличит «тихо» от «не считалось».
    """
    out = []
    for one in (signals or []):
        if one.get("released"):
            state = "СНЯТ словом владельца (метка %s)" % one.get("released_mark")
        elif one.get("held"):
            # ОТДЕЛЬНОЕ СЛОВО, А НЕ ПРОСТО «СТОП»: «сигнал видит случай сейчас» и
            # «случай видели тогда, снятия не было» — разные новости, и владелец,
            # пошедший смотреть корпус по второй, не найдёт там ничего.
            state = "СТОП ПО ЗАМКУ (случай видели %s, снятия не было)" % (one.get("held_at") or "?")
        elif one.get("on") and not one.get("determinate"):
            state = "СТОП по незнанию"
        elif one.get("on"):
            state = "СТОП" if one.get("enforced") else "есть (держит не этот слой)"
        else:
            state = "тихо"
        out.append("сигнал %s «%s» — %s: %s"
                   % (one.get("sig"), one.get("title"), state, one.get("why")))
    return out


def journal_line(signals, day="", node=None, checked=True, why=""):
    """Строка-индекс остановки в журнал. → str (пусто = писать нечего).

    Тип записи — ``ASK``, а не ``DONE``, и это не оформление: остановка сигналов
    А и Б есть РАЗВИЛКА, ждущая решения человека, а ритуал полосы велит помечать
    развилку с выбором человека именно так. Остановку, которая снимается сама
    (В, Г и Д), развилкой не зовём — она никого ни о чём не спрашивает: одинокий
    сигнал Д ляжет в журнал как ``NOTE``, и это верно — владельцу сообщают новость
    о чужой стороне, а не задают вопрос о нашей.

    ``checked`` едет насквозь в :func:`stop_words` и здесь ничего не решает
    отдельно: строка журнала обязана нести ТЕ ЖЕ слова, что видел владелец, —
    два текста об одном случае разошлись бы молча.
    """
    on = active(signals)
    if not on:
        return ""
    kind = "ASK" if any(s["release"] == BY_OWNER for s in on) else "NOTE"
    return "%s ЯЩИК ШТАБА за %s: %s" % (kind, str(day or "?"),
                                        stop_words(signals, node=node, checked=checked, why=why))


def marks(signals):
    """Метки СРАБОТАВШИХ и не снятых сигналов — для дедупа доклада. → list.

    У сигналов без метки (В и Г снимаются сами) её роль играет пара «буква и
    число, на котором сигнал стои́т»: доклад обязан повториться, когда число
    поменялось, и промолчать, когда всё то же самое. У Д метка есть (в неё входят
    сутки и номера рядов), поэтому его доклад дедупится по случаю, а не по счёту.
    """
    out = []
    for one in active(signals):
        out.append(one.get("mark") or "%s:%s" % (one.get("sig"), one.get("count")))
    return out


# ═════════════════════════ ЗАМОК ОСТАНОВКИ (05.09.2026) ══════════════════════
# ЗАЧЕМ ОН ПОНАДОБИЛСЯ — ЗАМЕР СВОЕЙ ЖЕ ПОЛОСЫ ЗА 05.09, А НЕ ОПАСЕНИЕ.
#
# Фраза остановки обещает человеку ЗАМОК: «Снимается ТОЛЬКО словом владельца».
# Обещание держать было нечем. Объявление жило в памяти (`said` в метке оборота
# демона), а ЗАПРЕТ БРАТЬ был чистой функцией от корпуса, читаемого мостом
# КАЖДЫЙ ВИТОК: `signal_b` считает провалы среди закрытых рядов живой очереди.
# Корпус этот не вечен — номера очереди идут по кругу, и в тот же день замерено,
# что опрос всех шести статусов отдал 7 рядов вместо двух с половиной сотен
# (:func:`shtab_box.merge_known`). Выпали ряды — счёт упал ниже порога — фраза
# исчезла МОЛЧА, и ящик взял следующее задание, хотя владелец не снимал ничего.
#
# ЖИВОЙ СЛУЧАЙ С ЧИСЛАМИ (лог демона 05.09, метка `e0140bfc78dc`, сигнал Б —
# «вердикт судьи» три раза, ряды #1, #4, #6):
#   • 12:58:21 — объявлена, дальше семь витков подряд показывает фразу;
#   • 14:35 · 14:50 · 15:02 · 15:22 · 15:55 — ПЯТЬ ВЗЯТИЙ подряд;
#   • 16:35:17 — объявлена ВТОРОЙ раз, ТОЙ ЖЕ меткой;
#   • 16:45:26 — шестое взятие (#13).
# Второе объявление той же метки и есть доказательство, что снятия не было:
# снятый сигнал в :func:`active` не входит ни одной веткой, значит объявиться
# второй раз не может. Остановка была не ложной, а ДЫРЯВОЙ.
#
# ═══ ОДНО РЕШЕНИЕ В ОДНОМ МЕСТЕ ═════════════════════════════════════════════
# После этой правки и фраза владельцу, и запрет брать выходят из ОДНОГО списка
# сигналов, который собирает :func:`merge_held`: `stop_words` печатает его,
# `marks` дедупит по нему доклад, `shtab_box.select` получает ту же фразу. Второй
# памяти о том, «стои́т ли остановка», у полосы не заводится — иначе она разошлась
# бы с первой молча, ровно как разошлись бы два счёта суточного потолка.
#
# ═══ ЧТО ЗАПОМИНАЕТСЯ, А ЧТО НЕТ, И ПОЧЕМУ ══════════════════════════════════
# Запоминается ТОЛЬКО остановка, которая (а) снимается словом владельца и
# (б) ОПРЕДЕЛЁННАЯ (`determinate`). Остановка «не знаю» (мост не отдал корпус)
# в замок НЕ идёт СОЗНАТЕЛЬНО: она стои́т не на увиденной улике, а на отсутствии
# ответа прибора, и уходит сама, как только прибор ответил. Запирай мы её —
# каждое моргание моста требовало бы слова человека, а моргает он на этой полосе
# измеримо часто (в тот же день: 08:18:32 «закрытые ряды не прочитаны», 16:24:53
# «очередь недоступна, предел ожидания 90с»). Виток, в котором она сработала,
# ящик по-прежнему держит целиком — меняется только её СРОК ЖИЗНИ.
#
# СНЯТИЕ ПОМНИТСЯ ТОЖЕ, И ЭТО ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ ПРАВКИ. Метки снятия живут
# в шапке узла, а шапка читается мостом и может не прочитаться; прежде
# нечитаемая шапка означала «меток снятия нет», то есть НЕДОСТУПНОСТЬ МОСТА
# ЧИТАЛАСЬ КАК ОТСУТСТВИЕ СЛОВА ВЛАДЕЛЬЦА, и ящик снова просил метку, которую
# владелец уже дал. Слово владельца из узла не исчезает — значит однажды
# увиденное снятие остаётся увиденным, и «не прочитали шапку» больше не
# отменяет решения человека.
HOLD_SCHEMA = "turbobaby.shtab_box_hold/v1"


def holdable(one):
    """Этот сигнал подлежит ЗАМКУ (переживает виток)? → bool.

    Четыре условия, и каждое отсекает свой класс: сработал · держит ЭТОТ слой
    (Г показывает, но не держит) · снимается СЛОВОМ ВЛАДЕЛЬЦА (В снимается сам,
    как только владелец ответил, и замок сделал бы его вечным) · ОПРЕДЕЛЁННЫЙ
    (разбор — в шапке раздела). Уже запертый второй раз не запирается.
    """
    one = one or {}
    return bool(one.get("on") and one.get("enforced") and not one.get("released")
                and not one.get("held") and one.get("determinate")
                and one.get("release") == BY_OWNER and str(one.get("mark") or ""))


def hold_record(one, now=""):
    """Сработавший сигнал → запись замка. → dict (пустая метка = писать нечего).

    Хранится ровно то, чем фраза остановки собирается заново: буква, метка,
    слова и момент. Времени функция не знает — его подаёт вызывающий
    (инвариант чистоты :data:`SHTAB_SIGNALS_PURE`).

    РЯДЫ ХРАНЯТСЯ ОТДЕЛЬНЫМ ПОЛЕМ (06.09.2026), а не только внутри ``why``, и это
    не удобство: извещение владельцу обязано назвать, КАКИЕ РЯДЫ подняли сигнал
    (:func:`hold_notice`), а вытаскивать номера обратно из человеческой фразы
    значило бы разбирать собственный текст регулярным выражением — тот самый
    класс, на котором полоса уже обжигалась. У сигналов без улик поле пустое, и
    извещение честно говорит «ряды названы в причине», а не выдумывает номера.
    """
    one = one or {}
    return {"schema": HOLD_SCHEMA, "mark": str(one.get("mark") or ""),
            "sig": str(one.get("sig") or ""), "why": str(one.get("why") or ""),
            "count": one.get("count"), "at": str(now or ""), "released": False,
            "evidence": [str(e) for e in (one.get("evidence") or ())][:6]}


def hold_free(rec_mark, now="", by=""):
    """Метка, снятая словом владельца → запись снятия. → dict.

    Отдельной строкой, а не правкой прежней: файл замка дописывается и никогда
    не переписывается — ровно как долгая память взятых ключей
    (:func:`shtab_box_run.remember`). Переписывание файла состояния стои́т
    потерянной строки на первом же обрыве.

    ``by`` — КЕМ снято, словами (06.09.2026). Дорог снятия стало две — метка в
    шапке узла и ответ в Telegram, — и «кто ответил» перестало быть очевидным из
    самого факта. Право оно не судит и судить не может: личности звонящего у
    этого слоя нет вовсе (её знает только `pc_agent`, см. §«ОТВЕТ В TELEGRAM»);
    поле — СЛЕД для человека, читающего замок глазами.
    """
    return {"schema": HOLD_SCHEMA, "mark": str(rec_mark or ""), "released": True,
            "at": str(now or ""), "by": str(by or "")}


def hold_index(held):
    """Строки файла замка → {метка: запись}, поздняя строка поверх ранней. → dict.

    Схлопывание живёт ЗДЕСЬ, а не в руках, потому что это правило чтения, а не
    работа с диском: строка снятия несёт одну метку и признак, а слова и момент
    случая остаются от строки постановки.
    """
    out = {}
    for rec in (held or ()):
        rec = rec if isinstance(rec, dict) else {}
        mark = str(rec.get("mark") or "")
        if not mark:
            continue
        merged = dict(out.get(mark) or {})
        merged.update(rec)
        out[mark] = merged
    return out


def hold_release(held, released=()):
    """ВСЕ снятые метки: увиденные сейчас плюс увиденные когда-то. → set.

    Одна дверь на весь вопрос «снят ли этот случай»: и :func:`evaluate`, и
    :func:`merge_held` получают ОДНО множество. Два мнения о снятии разошлись бы
    молча на первой же нечитаемой шапке — с чего эта правка и началась.
    """
    out = {str(m) for m in (released or ()) if str(m or "")}
    for mark, rec in hold_index(held).items():
        if rec.get("released"):
            out.add(mark)
    return out


def held_signal(rec):
    """Запись замка → сигнал, держащий ящик ПО ПАМЯТИ. → dict.

    Слова прежние плюс честная приписка: живой корпус этого случая больше не
    показывает. Без неё владелец пошёл бы искать в очереди ряды, которых там
    уже нет, и счёл бы остановку выдуманной.
    """
    rec = rec if isinstance(rec, dict) else {}
    one = _sig(str(rec.get("sig") or "?"), True,
               "%s · ДЕРЖИТСЯ ЗАМКОМ (случай записан %s): живой корпус очереди его больше не "
               "показывает — номера очереди идут по кругу и ряды пропадают, — но снятия словом "
               "владельца не было"
               % (str(rec.get("why") or "слова случая не сохранились"),
                  str(rec.get("at") or "момент не назван")),
               BY_OWNER, mark=str(rec.get("mark") or ""), count=rec.get("count"),
               # УЛИКИ ЕДУТ И СЮДА: запомненный случай обязан выглядеть для читателя
               # ровно тем же сигналом, что и живой, — иначе «ряды #1, #4, #6»
               # пропадали бы ровно тогда, когда живого корпуса уже нет, то есть
               # именно тогда, когда номера рядов человеку и нужны.
               evidence=rec.get("evidence") or ())
    one["held"] = True
    one["held_at"] = str(rec.get("at") or "")
    return one


def merge_held(signals, held=(), released=(), now=""):
    """Живые сигналы + замок + снятия → ОДИН список. → (сигналы, запереть, отпустить).

    ``released`` — уже собранное множество снятых меток (:func:`hold_release`),
    а не сырые метки шапки: снятие применяет одно место.

    Возвращает ТРИ вещи, и две последние — работа для рук:

    * **сигналы** — тот самый единственный список, из которого берутся и фраза
      владельцу, и запрет брать. Запомненный случай, которого живой корпус уже
      не показывает, встаёт на место молчащего сигнала своей буквы (список
      обязан оставаться перечнем ВСЕХ сторожей, а не превращаться в ленту);
    * **запереть** — записи для файла замка: сработавшие сейчас и ещё не
      запертые;
    * **отпустить** — метки, которые владелец снял словом ТОЛЬКО ЧТО: их
      признак надо положить на диск, иначе следующая нечитаемая шапка вернёт
      снятую остановку.
    """
    idx = hold_index(held)
    gone = {str(m) for m in (released or ())}
    out, live_marks = [], set()
    for one in (signals or []):
        one = dict(one)
        mark = str(one.get("mark") or "")
        if one.get("on") and mark and mark in gone and one.get("release") == BY_OWNER:
            one["released"], one["released_mark"] = True, mark
        if one.get("on") and mark:
            live_marks.add(mark)
        out.append(one)
    arm = [hold_record(one, now=now) for one in out
           if holdable(one) and str(one["mark"]) not in idx]
    free = sorted(m for m in gone if m in idx and not idx[m].get("released"))
    for mark in sorted(idx):
        if mark in gone or mark in live_marks:
            continue
        one = held_signal(idx[mark])
        slot = next((i for i, s in enumerate(out)
                     if s.get("sig") == one["sig"] and not s.get("on")), None)
        if slot is None:
            out.append(one)
        else:
            out[slot] = one
    return out, arm, free


