# ЛИТЕРАЛЫ ЗАИМСТВОВАНЫ, А НЕ ИМПОРТИРОВАНЫ, и это идиома полосы, а не лень:
# ровно так `contour_digest` держит имена полей реестра вердиктов («импорта
# `done_judge_pc` в чистом слое НЕТ намеренно… равенство литералов сторожит
# тест»). Причина та же — чистый слой не тянет за собой ни sqlite, ни диск, ни
# демона. РАВЕНСТВО КАЖДОГО ИЗ НИХ СВОЕМУ ВЛАДЕЛЬЦУ СТОРОЖИТ ТЕСТ, а не обещание
# в комментарии.
FAIL_CODE_RE = re.compile(r"причина=([a-z_]+)")     # = pc_orchestrator.FAIL_CODE_RE
REJECT_MARK = "отклонено Филиппом"                  # = card_terminal_log.REJECT_MARK
UNKNOWN_PREFIX = ("НЕИЗВЕСТНО (V0): результат по названному адресу "
                  "НЕ ПРОЧИТАН")                    # = done_judge_pc.UNKNOWN_PREFIX
# Человеческие имена кодов — тоже зеркало (`pc_orchestrator.FAIL_REASONS`), и
# тоже под тестом. Незнакомый код НЕ теряется: он остаётся классом под своим
# собственным именем, потому что новый код демона — это новая причина, а не
# «прочее».
FAIL_NAMES = {
    "approval_timeout": "таймаут подтверждения",
    "heartbeat_timeout": "таймаут сердцебиения",
    "run_timeout": "таймаут прогона",
    "model_refusal": "отказ модели",
    "exec_error": "ошибка выполнения",
    "unbacked_red": "заявка на красное без карточки гарда",
    "network_outage": "связи нет",
}
CLS_REJECT = "отказ владельца"
CLS_UNKNOWN = "вердикт судьи: продукт по адресу не прочитан"
CLS_SILENT = "причина не названа"

# Маркер info-карточки ревизора. ЗАИМСТВОВАН (= `pc_orchestrator.REVIZOR_OWNER_MARK`)
# по той же причине, что и три литерала выше: чистый слой демона не импортирует.
# Равенство сторожит тест, а не обещание. Два ОСТАЛЬНЫХ вида, ждущих мнения,
# литералами здесь НЕ набраны вовсе — их спрашивают у `zayavki_pc`, потому что
# третий экземпляр той же строки разошёлся бы с обоими молча.
REVIZOR_CARD_MARK = "[ревизор-находки]"    # = pc_orchestrator.REVIZOR_OWNER_MARK

# Виды ряда `needs_approval`. Слова — для человека: по ним он читает строку
# остановки и строку витрины, и «держит» с «ждёт мнения» не смеют слиться в одно.
KIND_BLOCK = "карточка гарда"        # держит операцию: исполнитель остановлен и ждёт «да»
KIND_ASK = "заявка"                  # ждёт мнения: «да» = «принято к сведению», не держит НИЧЕГО
KIND_UNKNOWN = "вид не определён"    # тела нет — считаем ДЕРЖАЩЕЙ (отказ консервативный)

# ═════════════════════════ СТРОКА СНЯТИЯ ═════════════════════════════════════
# ФОРМА ОДНА, И ОНА ПЕЧАТАЕТСЯ ФРАЗОЙ ОСТАНОВКИ ЦЕЛИКОМ. Разбор намеренно
# терпимый к пробелам и регистру ключевых слов не трогает: строку копируют, а не
# набирают, — но копируют люди, и лишний пробел не смеет стоить владельцу второго
# захода.
RELEASE_RE = re.compile(r"\[\[\s*ЯЩИК\s+СНЯТЬ\s+метка=([0-9a-f]{6,32})\s*\]\]")
RELEASE_FORM = "[[ЯЩИК СНЯТЬ метка=%s]]"

# ═════════════════════════ КАНОН ПРИЧИНЫ ═════════════════════════════════════
# Что вычищается перед сравнением — ПЕРЕМЕННЫЕ части, из-за которых одна и та же
# причина выглядит тремя. Порядок замен важен: кавычки уносят вложенные пути и
# числа целиком, поэтому идут первыми.
_RE_QUOTED = re.compile(r"['\"«][^'\"»\r\n]{0,300}['\"»]")
_RE_PATH = re.compile(r"[0-9A-Za-zА-Яа-яЁё_.-]*[\\/][0-9A-Za-zА-Яа-яЁё_./\\-]+")
_RE_HEX = re.compile(r"\b[0-9a-fA-F]{6,}\b")
_RE_NUM = re.compile(r"\d+")
_RE_PUNCT = re.compile(r"[^0-9A-Za-zА-Яа-яЁё_]+")


def canon_reason(text):
    """Причина словами → КАНОН для сравнения. → str (пусто = сравнивать нечем).

    Вычищает ровно то, чем один и тот же отказ отличается от СЕБЯ САМОГО: номера
    задач, длительности таймаутов, пути, кавычки и шестнадцатеричные хвосты.
    Первая строка выбрасывается, если это МАРКЕР РЯДА ЯЩИКА, — он в каждой задаче
    свой (дата и ключ), и склеивать по нему нельзя.

    НЕ ОБРЕЗАЕТСЯ: сравнение идёт по строке целиком (разбор — у :data:`CANON_SHOW`).
    """
    s = str(text or "")
    lines = s.splitlines()
    if lines and shtab_box.MARK_RE.match(lines[0]):
        lines = lines[1:]
    s = "\n".join(lines).casefold()
    s = _RE_QUOTED.sub(" ", s)
    s = _RE_PATH.sub(" ", s)
    s = _RE_HEX.sub(" ", s)
    s = _RE_NUM.sub(" ", s)
    return " ".join(w for w in _RE_PUNCT.split(s) if w)


def show_class(cls):
    """Имя класса причины В СТРОКУ ДЛЯ ЧЕЛОВЕКА. → str.

    Режет ПОКАЗ, а не сравнение: строка остановки читается глазами, и канон в
    сорок слов в ней бесполезен. Обрезка помечается многоточием — молча
    укороченное имя читалось бы как полное.
    """
    words = str(cls or "").split()
    if len(words) <= CANON_SHOW:
        return str(cls or "")
    return " ".join(words[:CANON_SHOW]) + " …"


def reason_class(result):
    """Текст итога закрытой строки → (класс, чем опознан). → (str, str).

    Четыре ступени опознания, от твёрдого к мягкому — разбор в шапке,
    §«ЧТО СЧИТАТЬ ОДНОЙ ПРИЧИНОЙ». Пустой итог классом ЯВЛЯЕТСЯ
    (:data:`CLS_SILENT`): три задачи, провалившиеся вовсе без слов, — это
    повторяющаяся поломка, а не три разных случая.
    """
    text = str(result or "")
    m = FAIL_CODE_RE.search(text)
    if m:
        code = m.group(1)
        return ("%s (%s)" % (FAIL_NAMES.get(code, "код демона"), code), "код причины")
    if text.lstrip().startswith(REJECT_MARK):
        return (CLS_REJECT, "маркер отказа владельца")
    if UNKNOWN_PREFIX in text:
        return (CLS_UNKNOWN, "маркер вердикта судьи")
    canon = canon_reason(text)
    if not canon:
        return (CLS_SILENT, "итог пуст")
    return ("прочее: %s" % canon, "канон причины (сравнение по строке целиком)")


# ═════════════════════════ КОРПУС: ЗАКРЫТЫЕ ЗАДАНИЯ ЯЩИКА ════════════════════


def box_rows(rows, statuses=("failed", "done")):
    """Ряды очереди → ТОЛЬКО закрытые задания ЯЩИКА, по возрастанию номера. → list.

    Опознание — по МАРКЕРУ РЯДА (:data:`shtab_box.MARK_RE`), тому же, которым
    ящик считает свой суточный потолок и свой дедуп. Третьего мнения о том, что
    такое «ряд из ящика», у полосы не заводится.

    ПОРЯДОК — ПО НОМЕРУ ОЧЕРЕДИ, и это выбор с названной ценой. Времени закрытия
    в рядах моста мы не читаем (его нет ни в одном поле, которым пользуется
    ящик), а «две ПОДРЯД» без порядка не существует вовсе. Номер монотонен внутри
    поколения очереди; на сбросе нумерации (очередь начинает с 1) порядок
    поколений теряется — граница названа вслух и стои́т в артефакте.
    """
    keep = set(statuses or ())
    out = []
    for it in (rows or []):
        row = it if isinstance(it, dict) else {}
        if keep and str(row.get("status") or "") not in keep:
            continue
        m = shtab_box.MARK_RE.match(str(row.get("task_text") or ""))
        if not m:
            continue
        try:
            num = int(row.get("id"))
        except (TypeError, ValueError):
            continue
        out.append({"id": num, "day": m.group(1), "key": m.group(2),
                    "status": str(row.get("status") or ""),
                    "result": str(row.get("result") or "")})
    out.sort(key=lambda r: r["id"])
    return out


def proved(row, judged):
    """Эта закрытая строка получила вердикт «сделано»? → (bool, слова).

    ДВА УСЛОВИЯ, оба обязательны: статус ``done`` И вердикт судьи «доказана».
    Одного ``done`` не хватает — в режиме ``addr`` безадресное закрытие остаётся
    ``done``, и счёт по одному исходу зачитывал бы работу, которую никто не
    проверял (тот же довод, что у :func:`contour_digest.is_clean`).

    Слово судьи берётся у :func:`contour_digest.judged_of` — ЧУЖОГО устройства с
    четырьмя ответами. Свой разбор реестра разошёлся бы с ним на первой правке
    имён полей.
    """
    one = row or {}
    said = contour_digest.judged_of(one.get("id"), judged)
    if str(one.get("status") or "") != "done":
        if str(one.get("result") or "").lstrip().startswith(REJECT_MARK):
            return False, "отклонена владельцем"
        return False, "закрыта как failed"
    if said == contour_digest.JUDGE_PROVED:
        return True, said
    return False, "судья: %s" % said


# ═════════════════════════ МЕТКА СЛУЧАЯ ══════════════════════════════════════


def mark_of(sig, ident):
    """Метка случая — 12 hex от «сигнал|улика». → str.

    Считает :func:`recon_auto.key_of`; своего sha256 здесь нет. УЛИКА, А НЕ ДЕНЬ:
    метка обязана меняться вместе со случаем, иначе снятое вчера слово владельца
    гасило бы завтрашнюю остановку — то есть выключало бы сигнал навсегда.
    """
    return recon_auto.key_of("shtab_box.signal.%s" % str(sig or ""), str(ident or ""))


def release_marks(text):
    """Текст узла-ящика → множество меток, снятых словом владельца. → set.

    Ищет по ВСЕМУ узлу, а не внутри блоков задач: строка снятия — не задание, у
    неё нет ни ключа, ни тела, и требовать от владельца обернуть её в
    ``[[ЗАДАЧА …]]`` значило бы просить второе действие там, где условие
    разрешает одно.
    """
    return set(RELEASE_RE.findall(str(text or "")))


# ═════════════════════════ СИГНАЛЫ ═══════════════════════════════════════════


def _sig(sig, on, why, release, mark="", count=None, evidence=(), enforced=True,
         determinate=True):
    return {"sig": sig, "title": TITLE.get(sig, ""), "on": bool(on), "why": why,
            "release": release, "mark": mark, "count": count,
            "evidence": [str(e) for e in (evidence or ())][:6],
            "enforced": bool(enforced), "determinate": bool(determinate),
            "released": False, "released_mark": ""}


def signal_a(rows, judged, rows_ok=True, judged_ok=True, day=""):
    """Сигнал А: две последние закрытые задачи ящика подряд — без «сделано».

    ТРЕТИЙ ИСХОД ПЕРВЫМ: корпус не прочитан или реестра вердиктов нет — сигнал
    СЧИТАЕТСЯ СРАБОТАВШИМ («не знаю» значит «стоп»), но говорит об этом другими
    словами, чем сработавший по факту.

    МЕНЬШЕ ДВУХ ЗАКРЫТЫХ — ЭТО НЕ СИГНАЛ, а отсутствие корпуса, и путать их
    нельзя: у ящика, поставившего первое в жизни задание, «двух подряд» ещё не
    существует, и остановка на этом основании была бы остановкой ни на чём.
    """
    if not rows_ok:
        ident = "неизвестно|корпус|%s" % str(day or "")
        return _sig(SIG_A, True, "закрытые ряды очереди не прочитаны — доказаны ли последние "
                                 "задания ящика, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» "
                                 "значит «стоп»", BY_OWNER, mark_of(SIG_A, ident),
                    determinate=False)
    if not judged_ok:
        ident = "неизвестно|реестр|%s" % str(day or "")
        return _sig(SIG_A, True, "реестр вердиктов судьи не прочитан — что судья сказал о "
                                 "последних заданиях ящика, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки "
                                 "«не знаю» значит «стоп»", BY_OWNER, mark_of(SIG_A, ident),
                    determinate=False)
    tail = list(rows or [])[-STREAK_FLOOR:]
    if len(tail) < STREAK_FLOOR:
        return _sig(SIG_A, False, "закрытых заданий ящика %d — «%d подряд» ещё не из чего "
                                  "составить" % (len(rows or []), STREAK_FLOOR),
                    BY_OWNER, count=len(rows or []))
    verdicts = [proved(r, judged) for r in tail]
    if any(ok for ok, _w in verdicts):
        return _sig(SIG_A, False, "последние %d закрытых задания ящика подряд недоказанными не "
                                  "являются" % STREAK_FLOOR, BY_OWNER, count=0)
    ident = "|".join(str(r["id"]) for r in tail)
    words = ", ".join("#%s — %s" % (r["id"], w) for r, (_ok, w) in zip(tail, verdicts))
    return _sig(SIG_A, True, "%d последних закрытых задания ящика подряд без вердикта "
                             "«сделано»: %s" % (STREAK_FLOOR, words),
                BY_OWNER, mark_of(SIG_A, ident), count=STREAK_FLOOR,
                evidence=["#%s" % r["id"] for r in tail])


def signal_b(rows, day, rows_ok=True):
    """Сигнал Б: одна причина — третий раз за сутки.

    СЧЁТ ИДЁТ ПО РЯДАМ, А НЕ ПО ОБОРОТАМ, и это главный замок от ложной тревоги.
    Ящик заглядывает в корпус каждые полчаса и видит одни и те же закрытые ряды;
    считай он ВСТРЕЧИ, одна вчерашняя ошибка набрала бы «третий раз» за полтора
    часа сама с собой. Единица счёта — НОМЕР ЗАКРЫТОЙ СТРОКИ, поэтому повторное
    чтение того же корпуса счёт не двигает, а рестарт демона его не обнуляет.

    КОРПУС — ТОЛЬКО ``failed``, И ЭТО НАШЁЛ СОБСТВЕННЫЙ ТЕСТ. Три УСПЕШНО сданных
    задания с одинаковым отчётом давали «одну причину третий раз» и останавливали
    ящик за хорошую работу. Отчёт исполнителя причиной отказа не является; отказ
    владельца и вердикт судьи «неизвестно» своих статусов не имеют и лежат в
    ``failed`` маркерами — то есть весь предмет сигнала Б там и только там.

    СУТКИ БЕРУТСЯ ИЗ МАРКЕРА РЯДА (день, когда задание ВЗЯТО), а не из времени
    закрытия: времени закрытия ящик не читает ни в одном поле. Граница названа
    вслух — задание, взятое вчера и упавшее сегодня, посчитается за вчера.
    """
    if not rows_ok:
        ident = "неизвестно|корпус|%s" % str(day or "")
        return _sig(SIG_B, True, "закрытые ряды очереди не прочитаны — повторяется ли причина, "
                                 "ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» значит «стоп»",
                    BY_OWNER, mark_of(SIG_B, ident), determinate=False)
    today = str(day or "")
    if not today:
        return _sig(SIG_B, True, "сутки не названы — «третий раз за сутки» посчитать НЕЧЕМ; "
                                 "у остановки «не знаю» значит «стоп»",
                    BY_OWNER, mark_of(SIG_B, "неизвестно|сутки"), determinate=False)
    tally = {}
    for row in (rows or []):
        if row.get("day") != today:
            continue
        if str(row.get("status") or "") != "failed":
            continue                       # сданная задача причины отказа не имеет вовсе
        cls, how = reason_class(row.get("result"))
        slot = tally.setdefault(cls, {"class": cls, "how": how, "ids": []})
        if row["id"] not in slot["ids"]:
            slot["ids"].append(row["id"])
    worst = None
    for slot in tally.values():
        if worst is None or len(slot["ids"]) > len(worst["ids"]):
            worst = slot
    if worst is None:
        return _sig(SIG_B, False, "провалов у заданий ящика за %s нет — причинам не из чего "
                                  "повторяться" % today, BY_OWNER, count=0)
    count = len(worst["ids"])
    if count < REPEAT_FLOOR:
        return _sig(SIG_B, False, "самая частая причина провала за %s встретилась %d раз при "
                                  "пороге %d («%s»)"
                    % (today, count, REPEAT_FLOOR, show_class(worst["class"])),
                    BY_OWNER, count=count)
    ident = "%s|%s" % (today, worst["class"])
    return _sig(SIG_B, True, "одна причина третий раз за %s: «%s» — %d раз (%s; опознана: %s)"
                % (today, show_class(worst["class"]), count,
                   ", ".join("#%s" % i for i in worst["ids"][:6]), worst["how"]),
                BY_OWNER, mark_of(SIG_B, ident), count=count,
                evidence=["#%s" % i for i in worst["ids"]])


def body_of(row):
    """Ряд очереди → ТЕЛО, по которому опознаётся вид. → str.

    Два поля, и оба нужны: живая очередь зовёт тело ``task_text``, а слепок
    очереди хранит ПЕРВУЮ его строку под именем ``goal``. Маркер вида стои́т
    первым и переживает эту обрезку — поэтому обоих полей хватает, и правило
    ровно то же, которым живёт :func:`zayavki_pc.split_awaiting` (равенство
    сторожит тест: разойдись они, витрина и ящик назвали бы один ряд по-разному).
    """
    one = row if isinstance(row, dict) else {}
    text = one.get("task_text")
    if not str(text or "").strip():
        text = one.get("goal")
    return str(text or "")


def awaiting_kind(row):
    """Ряд ``needs_approval`` → (вид, чем опознан). → (str, str).

    ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ПОЛОСА РЕШАЕТ, ДЕРЖИТ ЛИ РЯД ОПЕРАЦИЮ. Разбор в
    шапке, §«ЧТО СЧИТАТЬ КАРТОЧКОЙ»; коротко — вопрос один: ждёт ли кто-нибудь
    «да». Ждёт исполнитель (значит ряд подлежит ``APPROVAL_TTL``) — карточка
    гарда. Ждёт сам вопрос — заявка, и ящик она не держит.

    ПРИЗНАКИ ДВУХ ВИДОВ ЗАЯВОК СПРОШЕНЫ У :mod:`zayavki_pc`, а не набраны здесь:
    он уже держит их равенство ступеням B и E своими тестами. Свой, третий
    экземпляр тех же строк разошёлся бы с обоими МОЛЧА.

    ТРЕТИЙ ИСХОД — :data:`KIND_UNKNOWN`, и он считается ДЕРЖАЩИМ (см.
    :func:`split_waiting`): цена ошибки несимметрична. Но зовётся он своими
    словами, потому что «не разобрали ряд» и «владелец держит красную операцию» —
    разные новости.
    """
    text = body_of(row)
    if not text.strip():
        return KIND_UNKNOWN, "у ряда нет тела ни в task_text, ни в goal — разбирать нечего"
    if zayavki_pc.is_zayavka(text):
        return KIND_ASK, "заявка внешнего канала (ступень B, признак zayavki_pc.is_zayavka)"
    if zayavki_pc.is_recon_ask(text):
        return KIND_ASK, "заявка разведки (ступень E, признак zayavki_pc.is_recon_ask)"
    if text.startswith(REVIZOR_CARD_MARK):
        return KIND_ASK, "info-карточка ревизора (маркер %s)" % REVIZOR_CARD_MARK
    return KIND_BLOCK, "тело не несёт маркера вопроса — ряд подлежит APPROVAL_TTL, значит «да» ждёт исполнитель"


def split_waiting(rows):
    """Ряды ``needs_approval`` → ДЕРЖАЩИЕ и ЖДУЩИЕ МНЕНИЯ, врозь. → dict.

    Три кучки, а числа два: ``block`` (карточки гарда) и ``unknown`` (вид не
    определён) вместе составляют ДЕРЖАЩИХ — отказ консервативный, — а ``ask``
    остаётся отдельным числом и в сумму не входит НИКОГДА. Складывать их нельзя:
    первое число говорит «полоса остановлена», второе — «владельцу есть что
    почитать», и одно слово на две новости здесь уже стоило ящику простоя.

    Ряды НЕ в ``needs_approval`` не попадают ни в одну кучку: предмет сигнала В —
    ожидание ответа, а не открытая работа (её судит замок ``owner_busy``).
    """
    out = {"block": [], "ask": [], "unknown": [], "why": {}}
    for row in (rows or []):
        one = row if isinstance(row, dict) else {}
        if str(one.get("status") or "") != "needs_approval":
            continue
        kind, how = awaiting_kind(one)
        out["why"][str(one.get("id"))] = how
        if kind == KIND_ASK:
            out["ask"].append(one)
        elif kind == KIND_UNKNOWN:
            out["unknown"].append(one)
        else:
            out["block"].append(one)
    return out


def holding(split):
    """Ряды, которые ДЕРЖАТ ящик: карточки гарда плюс неопознанные. → list."""
    got = split if isinstance(split, dict) else {}
    return list(got.get("block") or []) + list(got.get("unknown") or [])


def _ids(rows, limit=6):
    return ", ".join("#%s" % (r or {}).get("id") for r in list(rows or [])[:limit])


def signal_c(open_rows, rows_ok=True):
    """Сигнал В: владельцу выписана карточка, ДЕРЖАЩАЯ ОПЕРАЦИЮ, ответа нет.

    ПРЕДМЕТ — ВСЯ ПОЛОСА, А НЕ ОДИН ЯЩИК, и это выбор, сделанный ЗАМЕРОМ, а не
    вкусом. Собственные ряды ящика замок владельца ``owner_busy`` уже держит:
    ``_is_owner_work`` отдаёт для ``from=Filipp-shtab`` истину при любом открытом
    статусе, включая ``needs_approval``, — то есть узкое чтение («только карточки
    по заданиям ящика») стоило бы РОВНО НОЛЬ и повторяло бы существующий замок.
    А вот карточки гарда по ЧУЖИМ рядам тот же ``_is_owner_work`` пропускает, и
    ровно их этот сигнал и ловит.

    СЧИТАЮТСЯ ТОЛЬКО ДЕРЖАЩИЕ (правка 03.09.2026, разбор в шапке). До неё сигнал
    брал ВСЕ ряды ``needs_approval`` подряд, и живой замер того же дня назвал
    цену: пять открытых рядов — пять заявок, карточек гарда ноль, ящик стои́т.
    Заявка не держит ничего: «да» на ней означает «принято к сведению» и задачи
    не рождает ни одной веткой.

    ЧИСЛА ИДУТ ВРОЗЬ И В ОДНО НЕ СКЛАДЫВАЮТСЯ. Строка называет ДЕРЖАЩИХ числом и
    номерами, а ждущих мнения — отдельным числом и отдельными номерами, даже
    когда держащих ноль: молчание про пять открытых заявок читалось бы как «у
    владельца пусто».

    ЧЕМ ЭТО НЕ СТАНОВИТСЯ «ВЫКЛЮЧЕНО НАВСЕГДА»: карточка гарда на полосе смертна.
    ``process_approval_timeouts`` роняет ряд ``needs_approval`` старше
    ``APPROVAL_TTL`` (2760 с = 46 мин) в ``failed`` сам — и теперь это правда без
    оговорок, потому что освобождённые от TTL виды сюда больше не попадают.
    """
    if not rows_ok:
        return _sig(SIG_C, True, "открытые ряды очереди не прочитаны — ждёт ли владелец ответа "
                                 "по карточке, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» значит "
                                 "«стоп»", BY_ITSELF, determinate=False)
    split = split_waiting(open_rows)
    hold, ask = holding(split), list(split["ask"])
    if not hold:
        return _sig(SIG_C, False,
                    "карточек гарда, держащих операцию, нет (ждут мнения %d%s)"
                    % (len(ask), (": %s" % _ids(ask)) if ask else ""),
                    BY_ITSELF, count=0)
    blind = list(split["unknown"])
    blind_words = (" Из них %d с НЕОПОЗНАННЫМ видом ряда (%s) — считаем держащими: не разобрали "
                   "тело, а пропустить карточку гарда дороже лишней остановки."
                   % (len(blind), _ids(blind))) if blind else ""
    return _sig(SIG_C, True,
                "держат %d, ждут мнения %d. Держат операцию карточки гарда: %s — пока владелец "
                "не ответил, новых заданий не берём; это не поломка, а очередь на его решение.%s%s"
                % (len(hold), len(ask), _ids(hold), blind_words,
                   (" Ждут мнения (ящик не держат): %s." % _ids(ask)) if ask else ""),
                BY_ITSELF, count=len(hold),
                evidence=["#%s" % (r or {}).get("id") for r in hold])


def signal_d(left, budget=None, day="", marks_ok=True):
    """Сигнал Г: суточный потолок. ПОКАЗЫВАЕТСЯ, НЕ ИСПОЛНЯЕТСЯ (см. шапку).

    ``left`` — сколько ещё можно взять сегодня, посчитанное ЧУЖИМ счётом
    (:func:`shtab_box.budget_left`). Своего счёта здесь нет ни одной ветки:
    второй экземпляр разошёлся бы с первым молча.
    """
    cap = shtab_box.DAILY_BUDGET if budget is None else int(budget)
    if not marks_ok:
        return _sig(SIG_D, True, "корпус маркеров суток не прочитан — сколько заданий взято "
                                 "сегодня, НЕИЗВЕСТНО; день считается исчерпанным",
                    BY_DAY, enforced=False, determinate=False)
    try:
        rest = int(left)
    except (TypeError, ValueError):
        return _sig(SIG_D, True, "остаток суточного потолка не назван числом — день считается "
                                 "исчерпанным", BY_DAY, enforced=False, determinate=False)
    if rest > 0:
        return _sig(SIG_D, False, "суточный потолок: осталось %d из %d за %s"
                    % (rest, cap, str(day or "?")), BY_DAY, count=rest, enforced=False)
    return _sig(SIG_D, True, "суточный потолок исчерпан: %d из %d за %s"
                % (cap, cap, str(day or "?")), BY_DAY, count=0, enforced=False)


