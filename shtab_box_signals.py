def mark_of(sig, ident):
    """Метка случая — 12 hex от «сигнал|улика». → str.

    Считает :func:`recon_auto.key_of`; своего sha256 здесь нет. УЛИКА, А НЕ ДЕНЬ:
    метка обязана меняться вместе со случаем, иначе снятое вчера слово владельца
    гасило бы завтрашнюю остановку — то есть выключало бы сигнал навсегда.
    """
    return recon_auto.key_of("shtab_box.signal.%s" % str(sig or ""), str(ident or ""))


def release_marks(text):
    """Текст узла-ящика → множество меток, снятых словом владельца. → set.

    Ищет по ВСЕМУ узлу, а не внутри блоков задач: строка снятия — не задание, у
    неё нет ни ключа, ни тела, и требовать от владельца обернуть её в
    ``[[ЗАДАЧА …]]`` значило бы просить второе действие там, где условие
    разрешает одно.
    """
    return set(RELEASE_RE.findall(str(text or "")))


