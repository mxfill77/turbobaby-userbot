def addr_door(row):
    """Ряд закрыт ДВЕРЬЮ МАРКЕРА-ПРОТИВ-АДРЕСА, которая реестра не пишет? → (bool, слова).

    ═══ ОТКУДА БЕРЁТСЯ ПРИЗНАК: ИЗ МЕСТА СОБЫТИЯ ════════════════════════════

    Первая строка итога (:data:`ADDR_CLOSE_HEAD`) написана САМИМ ДЕМОНОМ в точке
    закрытия: `pc_orchestrator._maybe_mark_vs_address` собирает текст
    `mark_vs_address_pc.close_result` и кладёт его в `complete_task(done)`. Отчёта
    исполнителя на этой дороге НЕТ ВОВСЕ — его stdout выброшен там же, где родилась
    карточка гарда, — а черновик доклада едет ОТДЕЛЬНЫМ блоком НИЖЕ головы.

    ТРЕТИЙ ВОПРОС К ПРИЗНАКУ — «МОЖНО ЛИ ЕГО ПОДНЯТЬ, НЕ СОВЕРШИВ СОБЫТИЯ» —
    ОТВЕЧЕН ЧЕСТНО, И ОТВЕТ НЕ «НЕТ», А «НЕ В ОДИНОЧКУ». Модель умеет напечатать
    любую строку, в том числе эту, — но признак спрашивается ТОЛЬКО у ряда, о
    котором реестр УЖЕ промолчал (:func:`silent_sort`), а на всех прочих зелёных
    дорогах ПК-полосы реестр пишется безусловно: `pc_orchestrator._judge_done`
    зовёт `done_judge_pc.note` ДО развилки режима, и вердикт там есть всегда
    (`judge` возвращает `None` только на не-`done`). Значит подделка требует
    ОДНОВРЕМЕННО выдуманной головы И сорвавшейся записи реестра — и остаток этот
    назван, а не спрятан.

    ПОЗИЦИЯ — ЧАСТЬ ПРИЗНАКА. Голова обязана стоять В НАЧАЛЕ (тот же приём, что у
    `отклонено Филиппом` и у маркеров судьи): цитата той же фразы в теле доклада
    подписью двери не является, а отчёт режется с ХВОСТА — вытеснить голову нечем.
    """
    text = str((row if isinstance(row, dict) else {}).get("result") or "")
    if not text.lstrip().startswith(ADDR_CLOSE_HEAD):
        return False, ""
    return True, ("закрыта ЗЕЛЁНЫМ дверью маркера-против-адреса (подпись двери стои́т первой "
                  "строкой итога): продукт по названному адресу прочитан тем же прибором, а "
                  "реестра вердиктов эта дверь НЕ ПИШЕТ — судья закрытия здесь не звался вовсе")


def silent_sort(row):
    """Ряд сдан, а записи о суде НЕТ ВОВСЕ → КОТОРЫЙ из трёх сортов. → (str, str).

    Порядок веток — от признака, который нельзя поднять без события, к остатку:

    1. **полоса ряда не наша** → :data:`SORT_NOJUDGE`. Признак — поле ``lane``
       САМОГО РЯДА ОЧЕРЕДИ (`shtab_box.row_lane`, единственный владелец вопроса),
       то есть ровно то поле, по которому демон решает, брать ли ряд. Поднять его,
       не совершив закрытия, можно — и это ПРАВИЛЬНО: сорт утверждает не событие, а
       ОТСУТСТВИЕ устройства («реестр пишет судья ПК, чужие ряды он не судит ни
       одной веткой»), которое истинно с минуты создания ряда. О том, что судья
       где-то сработал, этот сорт не утверждает ничего — врать ему нечем;
    2. **закрыто дверью мимо реестра** → :data:`SORT_UNCALLED` (:func:`addr_door`,
       признак с места события — см. её докстринг);
    3. **остаток** → :data:`SORT_UNREAD`: наш ряд, наша обычная дверь, а вердикта
       нет. Это и есть «судья звался и не смог» — ЕДИНСТВЕННЫЙ сорт, на котором
       ящику есть смысл стоять. НАПРАВЛЕНИЕ ОСТАТКА КОНСЕРВАТИВНО: новая дверь,
       которая однажды закроет ряд ящика зелёным мимо реестра и не поставит своей
       подписи, попадёт СЮДА и остановит ящик — то есть незнание по-прежнему
       читается как «стоп», а не как «хорошо».
    """
    one = row if isinstance(row, dict) else {}
    lane = str(one.get("lane") or shtab_box.LANE_DEFAULT)
    if lane != shtab_box.LANE_PC:
        return SORT_NOJUDGE, ("сдана (done) рядом полосы %r, а реестр вердиктов пишет судья "
                              "ПОЛОСЫ ПК и чужих рядов не судит ни одной веткой — записи нет и "
                              "быть не может; это ОТСУТСТВИЕ судьи у той полосы, а не поломка "
                              "нашего" % lane)
    door, door_why = addr_door(one)
    if door:
        return SORT_UNCALLED, "сдана (done), " + door_why
    return SORT_UNREAD, ("сдана (done) НАШЕЙ полосой обычной дверью, а записи о суде нет вовсе — "
                         "судья закрытия звался и вердикта НЕ ОСТАВИЛ: доказательство лежит, "
                         "прочитать его нечем")


def sort_of(row, judged):
    """Закрытый ряд → СОРТ ИСХОДА и слова к нему. → (str из :data:`SORTS`, str).

    ПОРЯДОК ВЕТОК — ЭТО И ЕСТЬ ПРАВИЛО, и он выбран так, чтобы ни один ряд не
    получил льготы за незнание:

    1. **вердикт «сделано»** — :func:`proved`; всё прочее ниже;
    2. **закрыт как ``done``, а записи о суде НЕТ ВОВСЕ** (``JUDGE_SILENT``) →
       :func:`silent_sort`, ТРИ РАЗНЫХ СОРТА (разбор — в шапке раздела): прибор
       полосы сломан (:data:`SORT_UNREAD`), судьи у полосы ряда нет вовсе
       (:data:`SORT_NOJUDGE`), закрытие прошло дверью мимо реестра
       (:data:`SORT_UNCALLED`). Работа во всех трёх сдана и лежит; недоказанной
       работой это не является — это НЕПРОЧИТАННОЕ доказательство. Два ОСТАЛЬНЫХ
       ответа судьи остаются у А намеренно: «не доказана» — он прочитал и сказал
       НЕТ, «без адреса» — адрес обязан называть исполнитель, и не названный им
       адрес есть наша недоделка, а не поломка судьи;
    3. **решение владельца** (``отклонено Филиппом``) → :data:`SORT_OURS`, как и
       вчера. Граница названа вслух: отказ человека «работой не сделанной» тоже не
       является, но задание его среди трёх исходов не называет, и уводить его из А
       этой правкой значило бы ослабить сигнал сверх заказанного;
    4. **внешний отказ** (:func:`external_refusal`, все четыре условия) →
       :data:`SORT_EXT`, счёт и порог у сигнала Д — как и вчера;
    5. **ряд ЧУЖОЙ полосы, закрытый провалом** → :data:`SORT_FOREIGN`. Наш
       различитель на такой итог ответить НЕ МОЖЕТ (его условие — литералы
       ПК-демона), и его сегодняшнее «False» означает не «наш провал», а «не
       читал». Уверенное имя вместо незнания — это и есть та ложь, ради которой
       ящик вставал 19.09;
    6. **всё остальное** → :data:`SORT_OURS`.

    ПОЧЕМУ ``done`` ЧУЖОЙ ПОЛОСЫ НЕ ИДЁТ В :data:`SORT_FOREIGN`. Потому что вопрос
    к нему другой: текст итога тут вообще ни при чём, а реестр вердиктов — НАШ, и
    его молчание о чужом ряде есть в точности «доказательство не прочитано». Ветка
    2 отвечает на него раньше и правильнее.
    """
    one = row if isinstance(row, dict) else {}
    ok, why = proved(one, judged)
    if ok:
        return SORT_PROVED, why
    if str(one.get("status") or "") == "done":
        said = contour_digest.judged_of(one.get("id"), judged, goal=one.get("goal"))
        if said == contour_digest.JUDGE_SILENT:
            return silent_sort(one)
        return SORT_OURS, why
    if str(one.get("result") or "").lstrip().startswith(REJECT_MARK):
        return SORT_OURS, why
    ext_ok, ext_why = external_refusal(one)
    if ext_ok:
        return SORT_EXT, ext_why
    if str(one.get("lane") or shtab_box.LANE_DEFAULT) != shtab_box.LANE_PC:
        return SORT_FOREIGN, ("итог написан демоном полосы %r, а различитель внешнего отказа "
                              "читает литералы НАШЕГО демона — внешний это отказ или наш провал, "
                              "СКАЗАТЬ НЕЧЕМ"
                              % str(one.get("lane") or shtab_box.LANE_DEFAULT))
    return SORT_OURS, why


def sort_tally(rows, judged):
    """Ряды → сколько их какого сорта. → dict (все сорта есть ВСЕГДА, пусть и нулями).

    Ключ без значения читался бы как «сорта не существует», а их существует ровно
    пять — тот же довод, по которому :func:`evaluate` показывает и молчащие сигналы.
    """
    out = {s: 0 for s in SORTS}
    for row in (rows or ()):
        out[sort_of(row, judged)[0]] += 1
    return out


def _skipped_words(tally):
    """Сколько рядов вычеркнуто из корпуса А и КУДА они ушли. → str (пусто = никуда).

    Строка обязана назвать счёт КАЖДОГО сорта отдельно: «вычеркнуто 7» без имён
    читается как «семь чужих отказов», и ровно так витрина 19.09 прятала от
    владельца два ряда, которые чужими отказами не были.

    СОРТ БЕЗ СИГНАЛА НАЗЫВАЕТ, ЧТО ЯЩИК ИМ НЕ ОСТАНАВЛИВАЕТСЯ (22.09.2026). Это и
    есть «выход из знаменателя с НАЗВАННОЙ ПРИЧИНОЙ»: ряд, вычеркнутый молча,
    неотличим от ряда, которого не было, — а таких рядов на живой полосе 6 из 7 в
    корпусе трёх остановок 21.09.
    """
    parts = []
    for sort_name in (SORT_EXT, SORT_UNREAD, SORT_FOREIGN, SORT_NOJUDGE, SORT_UNCALLED):
        if tally.get(sort_name):
            parts.append("%s: %d — %s"
                         % (sort_name, tally[sort_name],
                            ("их считает сигнал %s" % SORT_SIGNAL[sort_name])
                            if sort_name in SORT_SIGNAL else SORT_QUIET[sort_name]))
    return (" (вычеркнуто из корпуса А — %s)" % "; ".join(parts)) if parts else ""


# ═════════════════════════ МЕТКА СЛУЧАЯ ══════════════════════════════════════


def mark_of(sig, ident):
    """Метка случая — 12 hex от «сигнал|улика». → str.

    Считает :func:`recon_auto.key_of`; своего sha256 здесь нет. УЛИКА, А НЕ ДЕНЬ:
    метка обязана меняться вместе со случаем, иначе снятое вчера слово владельца
    гасило бы завтрашнюю остановку — то есть выключало бы сигнал навсегда.
    """
    return recon_auto.key_of("shtab_box.signal.%s" % str(sig or ""), str(ident or ""))


def release_marks(text):
    """Текст узла-ящика → множество меток, снятых словом владельца. → set.

    Ищет по ВСЕМУ узлу, а не внутри блоков задач: строка снятия — не задание, у
    неё нет ни ключа, ни тела, и требовать от владельца обернуть её в
    ``[[ЗАДАЧА …]]`` значило бы просить второе действие там, где условие
    разрешает одно.
    """
    return set(RELEASE_RE.findall(str(text or "")))


# ═════════════════════════ СИГНАЛЫ ═══════════════════════════════════════════


def _sig(sig, on, why, release, mark="", count=None, evidence=(), enforced=True,
         determinate=True):
    return {"sig": sig, "title": TITLE.get(sig, ""), "on": bool(on), "why": why,
            "release": release, "mark": mark, "count": count,
            "evidence": [str(e) for e in (evidence or ())][:6],
            "enforced": bool(enforced), "determinate": bool(determinate),
            "released": False, "released_mark": "",
            # ЗАМОК: сигнал держит ящик ПО ПАМЯТИ, а не по живому корпусу
            # (:func:`merge_held`). Поле есть у КАЖДОГО сигнала, а не только у
            # запомненного: читателю нельзя предлагать отличать «False» от
            # «ключа нет» — это второй способ спросить одно и то же.
            "held": False, "held_at": ""}


def signal_a(rows, judged, rows_ok=True, judged_ok=True, day=""):
    """Сигнал А: две последние закрытые задачи ящика подряд — без «сделано».

    ТРЕТИЙ ИСХОД ПЕРВЫМ: корпус не прочитан или реестра вердиктов нет — сигнал
    СЧИТАЕТСЯ СРАБОТАВШИМ («не знаю» значит «стоп»), но говорит об этом другими
    словами, чем сработавший по факту.

    МЕНЬШЕ ДВУХ ЗАКРЫТЫХ — ЭТО НЕ СИГНАЛ, а отсутствие корпуса, и путать их
    нельзя: у ящика, поставившего первое в жизни задание, «двух подряд» ещё не
    существует, и остановка на этом основании была бы остановкой ни на чём.

    ВНЕШНИЙ ОТКАЗ ИЗ КОРПУСА ВЫЧЁРКИВАЕТСЯ (:func:`external_refusal`), и это
    правка 06.09.2026. Живой случай, ради которого она сделана: 03.09 сигнал А
    остановил ящик на #100 и #101, а #101 умер на «API Error: 529 Overloaded» без
    единого следа работы — то есть недоказанной задачей он не был, недоказанным
    было чужое API. Вычерк идёт ДО хвоста, а не после: считай мы «две последние
    строки, среди которых бывают чужие», порог зависел бы от того, сколько раз
    моргнул поставщик, а не от нашей работы.

    ВЫЧЕРК НЕ ОСЛАБЛЯЕТ СИГНАЛ, А СУЖАЕТ ЕГО ПРЕДМЕТ: две наши недоказанные
    подряд останавливают ящик ровно как вчера, даже если между ними легли три
    чужих отказа — соседство считается по НАШИМ рядам. Чужие при этом не
    теряются: их считает сигнал Д своим счётом и своей остановкой.
    """
    if not rows_ok:
        ident = "неизвестно|корпус|%s" % str(day or "")
        return _sig(SIG_A, True, "закрытые ряды очереди не прочитаны — доказаны ли последние "
                                 "задания ящика, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» "
                                 "значит «стоп»", BY_OWNER, mark_of(SIG_A, ident),
                    determinate=False)
    if not judged_ok:
        ident = "неизвестно|реестр|%s" % str(day or "")
        return _sig(SIG_A, True, "реестр вердиктов судьи не прочитан — что судья сказал о "
                                 "последних заданиях ящика, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки "
                                 "«не знаю» значит «стоп»", BY_OWNER, mark_of(SIG_A, ident),
                    determinate=False)
    every = list(rows or [])
    sorts = [sort_of(r, judged)[0] for r in every]
    tally = {s: 0 for s in SORTS}
    for name in sorts:
        tally[name] += 1
    # КОРПУС А — РОВНО ДВА СОРТА: наша недоказанная работа и доказанная. Первый
    # кормит сигнал, второй РВЁТ череду (доказанная задача — это «полоса работает»).
    # Остальные три вычёркиваются: они не кормят А и не рвут его череду, потому что
    # о НАШЕЙ работе не говорят ни да, ни нет. Ровно так с 06.09 жил внешний отказ —
    # здесь к нему добавлены ещё два исхода, а правило осталось тем же.
    ours = [r for r, name in zip(every, sorts) if name in (SORT_OURS, SORT_PROVED)]
    skipped = _skipped_words(tally)
    tail = ours[-STREAK_FLOOR:]
    if len(tail) < STREAK_FLOOR:
        return _sig(SIG_A, False, "закрытых заданий ящика %d, из них наших %d%s — «%d подряд» "
                                  "ещё не из чего составить"
                    % (len(every), len(ours), skipped, STREAK_FLOOR),
                    BY_OWNER, count=len(ours))
    verdicts = [proved(r, judged) for r in tail]
    if any(ok for ok, _w in verdicts):
        return _sig(SIG_A, False, "последние %d НАШИХ закрытых задания ящика подряд "
                                  "недоказанными не являются%s" % (STREAK_FLOOR, skipped),
                    BY_OWNER, count=0)
    ident = "|".join(str(r["id"]) for r in tail)
    words = ", ".join("#%s — %s" % (r["id"], w) for r, (_ok, w) in zip(tail, verdicts))
    return _sig(SIG_A, True, "%d последних НАШИХ закрытых задания ящика подряд без вердикта "
                             "«сделано»: %s%s" % (STREAK_FLOOR, words, skipped),
                BY_OWNER, mark_of(SIG_A, ident), count=STREAK_FLOOR,
                evidence=["#%s" % r["id"] for r in tail])


def silent_words(rows, judged):
    """ТРИ СОРТА БЕЗ ВЕРДИКТА — счёт каждого, строка человеку. → str (пусто = ни одного).

    ЗАЧЕМ ОТДЕЛЬНАЯ СТРОКА, А НЕ ОДНО ЧИСЛО. До 22.09 все три ехали одним счётом
    сигнала Е, и владелец, пришедший «чинить судью», находил исправного судью: из
    семи живых рядов трёх остановок 21.09 шесть были рядами ЧУЖОЙ полосы, а
    седьмой — закрытием другой дверью. Число без имени сорта посылает человека не
    туда, а молчание о сорте — то же число, только невидимое.

    СТРОКА ПЕЧАТАЕТСЯ И ПРИ СРАБОТАВШЕМ Е, И ПРИ МОЛЧАЩЕМ: сорт, показанный только
    в остановке, читается как «его не бывает, пока не встали».
    """
    tally = sort_tally(rows, judged)
    total = sum(tally.get(s, 0) for s in (SORT_UNREAD, SORT_NOJUDGE, SORT_UNCALLED))
    if not total:
        return ""
    return (" Вердикта нет вовсе у %d ряд(ов) корпуса, и это ТРИ РАЗНЫЕ НОВОСТИ: «%s» — %d "
            "(ТОЛЬКО этот сорт держит ящик); «%s» — %d (%s); «%s» — %d (%s)."
            % (total,
               SORT_UNREAD, tally.get(SORT_UNREAD, 0),
               SORT_NOJUDGE, tally.get(SORT_NOJUDGE, 0), SORT_QUIET[SORT_NOJUDGE],
               SORT_UNCALLED, tally.get(SORT_UNCALLED, 0), SORT_QUIET[SORT_UNCALLED]))


def _streak_signal(sig, rows, judged, sort_name, floor, head, tail_words, also=""):
    """Общая механика «N ПОДРЯД одного сорта». → dict сигнала.

    ОДНО УСТРОЙСТВО НА ДВА СЧЁТА, А НЕ ДВА ПОХОЖИХ, и это та же причина, по которой
    у полосы один различитель внешнего отказа: две копии «взять хвост и проверить
    сорт» разошлись бы молча на первой правке. Разными у Е и Ж остаются ровно те
    три вещи, которыми они и отличаются: сорт, порог и СЛОВА.

    ХВОСТ БЕРЁТСЯ ИЗ КОРПУСА ЦЕЛИКОМ, а не из отфильтрованного по сорту: «подряд»
    значит СОСЕДСТВО, и ряд другого сорта между двумя своими череду РВЁТ. Считай мы
    по отфильтрованному списку, два ряда за разные недели с двадцатью успехами между
    ними назвались бы «подряд».
    """
    every = list(rows or [])
    tail = every[-floor:]
    hits = [r for r in tail if sort_of(r, judged)[0] == sort_name]
    if len(tail) < floor or len(hits) < floor:
        return _sig(sig, False, "закрытых заданий ящика %d, из них последних подряд сорта «%s» "
                                "— %d при пороге %d%s"
                    % (len(every), sort_name, len(hits), floor, also),
                    BY_OWNER, count=len(hits))
    ident = "|".join(str(r["id"]) for r in tail)
    words = ", ".join("#%s — %s" % (r["id"], sort_of(r, judged)[1]) for r in tail)
    return _sig(sig, True, "%s: %s. %s%s" % (head % floor, words, tail_words, also),
                BY_OWNER, mark_of(sig, ident), count=len(hits),
                evidence=["#%s" % r["id"] for r in tail])


def signal_f(rows, judged, rows_ok=True, judged_ok=True, day=""):
    """Сигнал Е: три подряд сданных ряда НАШЕЙ полосы, у которых СУДЬЯ ЗВАЛСЯ И НЕ СМОГ.

    ═══ ПРЕДМЕТ СУЖЕН 22.09.2026 (задание 70p), И ВОТ ПОЧЕМУ ════════════════

    До этой правки Е стоял на признаке «записи о суде нет вовсе», а под ним лежат
    ТРИ разных факта (разбор — в шапке раздела сортов). ЗАМЕР ЖИВОГО ЗАМКА
    (`pc_orchestrator.shtab_box_hold.jsonl`, все три постановки Е за всю жизнь
    сигнала, 21.09.2026): 13:26 — ряды #6, #7, #8; 13:40 — #7, #8, #9; 21:04 —
    #23, #25, #26. По долгой памяти ящика (`pc_orchestrator.shtab_box_taken.jsonl`)
    ШЕСТЬ из семи — ``lane=vps``, а седьмой (#23, ``lane=pc``) закрыт дверью
    маркера-против-адреса (`pc_orchestrator.log`: ``MARK-ADDR-CLOSE id=23`` 22.09
    02:58:55, продукт `docs/artifacts/2026-09-22-70l-ARHIVPISHETSNOVA-2209.md`).
    То есть рядов, на которых остановка осмысленна, среди уликов было НОЛЬ, а
    ночь полоса простояла дважды.

    ПРАВО НЕ ОСЛАБЛЕНО ТАМ, ГДЕ ОНО ОСМЫСЛЕННО: на сорте «судья не смог» ящик
    по-прежнему встаёт, порог тот же, снимает по-прежнему ТОЛЬКО владелец. Два
    других сорта не исчезли и не стали успехом — у них свои имена, свой счёт и
    своя строка человеку (:func:`silent_words`), и они не кормят ни одного
    сигнала и не рвут череду А.

    ═══ ЗАЧЕМ ОН ОТДЕЛЬНЫЙ, ЕСЛИ РАНЬШЕ ЭТО СЧИТАЛ А ══════════════════════════

    ═══ ЗАЧЕМ ОН ОТДЕЛЬНЫЙ, ЕСЛИ РАНЬШЕ ЭТО СЧИТАЛ А ══════════════════════════

    Затем, что А зовёт владельца разбирать НАШУ РАБОТУ, а здесь разбирать надо
    СУДЬЮ. Живой случай, ради которого сигнал заведён: 19.09 в 18:06:52 ящик встал
    на паре #113+#114, и #114 был рядом, который СДАЛ работу — коммит 5e78c36 и
    артефакт 67x лежат в ``origin/main``, — но вердикта не получил, потому что
    реестр вердиктов пишет ПК-демон, а ряд закрывал СЕРВЕРНЫЙ. Строка остановки при
    этом звала владельца разбирать работу, которой не было изъяна.

    ═══ ПОЧЕМУ ЭТО НЕ ОСЛАБЛЕНИЕ ═════════════════════════════════════════════

    Ящик по-прежнему ВСТАЁТ, и снимает остановку по-прежнему ТОЛЬКО владелец
    (:data:`BY_OWNER`): ветки самоснятия у Е нет ни одной, суточной льготы — тоже.
    Изменились имя, порог и адрес вопроса, а не право. Порог выше, чем у А
    (:data:`UNREAD_STREAK_FLOOR` против :data:`STREAK_FLOOR`), и это названо числом
    в разделе порогов: улики о нашей работе здесь нет вовсе, а останавливать полосу
    на второй поломке измерителя значит судить работу по молчанию прибора.

    ТРЕТИЙ ИСХОД: корпус или реестр не прочитаны — сигнал МОЛЧИТ и говорит, почему.
    Тот же самый факт уже держит ящик сигналом А («не знаю» значит «стоп»), и
    второе «не знаю» о том же добавило бы не строгости, а шума — ровно довод
    :func:`signal_e`.
    """
    if not rows_ok or not judged_ok:
        return _sig(SIG_F, False, "%s не прочитан — вердикты последних заданий посчитать НЕЧЕМ; "
                                  "ящик на этом же факте уже держит А, второго «не знаю» о том "
                                  "же не заводим" % ("корпус" if not rows_ok else "реестр судьи"),
                    BY_OWNER, determinate=False)
    return _streak_signal(
        SIG_F, rows, judged, SORT_UNREAD, UNREAD_STREAK_FLOOR,
        "%d последних закрытых задания ящика подряд сданы НАШЕЙ полосой обычной дверью, а "
        "судья закрытия вердикта не оставил",
        "Разбирать надо СУДЬЮ, а не работу: доказательство лежит, прочитать его нечем — "
        "смотреть адрес результата и реестр вердиктов. Снимается ТОЛЬКО словом владельца.",
        also=silent_words(rows, judged))


def signal_g(rows, judged, rows_ok=True, judged_ok=True, day=""):
    """Сигнал Ж: три подряд закрытых провалом ряда ЧУЖОЙ полосы — судить нечем.

    ═══ ЧТО ЭТОТ СИГНАЛ УТВЕРЖДАЕТ, А ЧЕГО НЕ УТВЕРЖДАЕТ ═════════════════════

    Он НЕ говорит «полоса сломалась» и НЕ говорит «виновата чужая сторона». Он
    говорит ровно одно: ряд закрыт провалом, итог написан демоном другой полосы, и
    единственный различитель внешнего отказа, который есть у ПК, читает литералы
    СВОЕГО демона (:data:`EXT_PROC_RE`, :data:`EXT_NO_TRACE_END_RE`). На таком ряде
    его ответ «нет» означает «не читал», а не «наш провал».

    Живой случай: #113 от 19.09 (``lane=vps``) умер за 19.8 с с ``tokens_in=0
    tokens_out=0`` и пустым ``modelUsage`` — заход не начинался вовсе. Сигнал А
    засчитал его нашей недоказанной работой ДВАЖДЫ (пары #112+#113 в 16:03 и
    #113+#114 в 18:06).

    ═══ ПОЧЕМУ НЕ НАУЧИТЬ РАЗЛИЧИТЕЛЬ ЧИТАТЬ ЧУЖОЙ ФОРМАТ ════════════════════

    Разбор — в шапке раздела сортов: чужие литералы пришлось бы списать из
    репозитория, которого на полосе нет, и сторожить их равенство владельцу было бы
    НЕЧЕМ. Честное «судить нечем» с собственной остановкой строже молчаливого
    расхождения.

    ПРАВО НЕ ОСЛАБЛЕНО: снимает только владелец, ветки самоснятия нет, суточной
    льготы нет. Третий исход — как у :func:`signal_f`.
    """
    if not rows_ok or not judged_ok:
        return _sig(SIG_G, False, "%s не прочитан — полосу и исход последних заданий назвать "
                                  "НЕЧЕМ; ящик на этом же факте уже держит А, второго «не знаю» "
                                  "о том же не заводим"
                    % ("корпус" if not rows_ok else "реестр судьи"),
                    BY_OWNER, determinate=False)
    return _streak_signal(
        SIG_G, rows, judged, SORT_FOREIGN, FOREIGN_STREAK_FLOOR,
        "%d последних закрытых задания ящика подряд пришли с ЧУЖОЙ полосы и прочитаны быть "
        "не могут",
        "Разбирать надо НЕ работу: внешний это отказ поставщика или наш провал, слой ПК "
        "сказать не может — судит демон той полосы. Снимается ТОЛЬКО словом владельца.")


def signal_b(rows, day, rows_ok=True):
    """Сигнал Б: одна причина — третий раз за сутки.

    СЧЁТ ИДЁТ ПО РЯДАМ, А НЕ ПО ОБОРОТАМ, и это главный замок от ложной тревоги.
    Ящик заглядывает в корпус каждые полчаса и видит одни и те же закрытые ряды;
    считай он ВСТРЕЧИ, одна вчерашняя ошибка набрала бы «третий раз» за полтора
    часа сама с собой. Единица счёта — НОМЕР ЗАКРЫТОЙ СТРОКИ, поэтому повторное
    чтение того же корпуса счёт не двигает, а рестарт демона его не обнуляет.

    КОРПУС — ТОЛЬКО ``failed``, И ЭТО НАШЁЛ СОБСТВЕННЫЙ ТЕСТ. Три УСПЕШНО сданных
    задания с одинаковым отчётом давали «одну причину третий раз» и останавливали
    ящик за хорошую работу. Отчёт исполнителя причиной отказа не является; отказ
    владельца и вердикт судьи «неизвестно» своих статусов не имеют и лежат в
    ``failed`` маркерами — то есть весь предмет сигнала Б там и только там.

    СУТКИ БЕРУТСЯ ИЗ МАРКЕРА РЯДА (день, когда задание ВЗЯТО), а не из времени
    закрытия: времени закрытия ящик не читает ни в одном поле. Граница названа
    вслух — задание, взятое вчера и упавшее сегодня, посчитается за вчера.

    ВНЕШНИЙ ОТКАЗ ВЫЧЁРКИВАЕТСЯ И ЗДЕСЬ (06.09.2026), и нашёл это СОБСТВЕННЫЙ
    ТЕСТ, а не рассуждение. Три отказа чужого API подряд — это ОДИН код причины
    (``exec_error``), то есть для Б это «одна причина третий раз», и он вставал
    рядом с сигналом Д на том же самом факте. Беда не в лишней строке: у Б снятие
    ТОЛЬКО СЛОВОМ ВЛАДЕЛЬЦА, а у Д — со сменой суток, и обещание «за погоду
    человека не будим» тонуло в требовании положить метку. Две остановки об одном
    случае с противоположными правилами снятия — это не строгость, а молчаливое
    противоречие. Предмет Б сужен до НАШИХ причин; чужие считает Д своим счётом.

    ЧЕСТНАЯ ЦЕНА ВЫЧЕРКА, НАЗВАННАЯ ЧИСЛОМ: три чужих отказа РОССЫПЬЮ за сутки
    (между ними наши сданные задания) больше не ловит никто — Б их вычеркнул, Д
    ищет ПОДРЯД. Это принято сознательно: россыпь означает, что между отказами
    работа шла, то есть ящик не молотит папку впустую, а ради этого сигналы и
    заведены. Стеной внешнее ложится подряд — там и стои́т Д.
    """
    if not rows_ok:
        ident = "неизвестно|корпус|%s" % str(day or "")
        return _sig(SIG_B, True, "закрытые ряды очереди не прочитаны — повторяется ли причина, "
                                 "ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» значит «стоп»",
                    BY_OWNER, mark_of(SIG_B, ident), determinate=False)
    today = str(day or "")
    if not today:
        return _sig(SIG_B, True, "сутки не названы — «третий раз за сутки» посчитать НЕЧЕМ; "
                                 "у остановки «не знаю» значит «стоп»",
                    BY_OWNER, mark_of(SIG_B, "неизвестно|сутки"), determinate=False)
    tally = {}
    for row in (rows or []):
        if row.get("day") != today:
            continue
        if str(row.get("status") or "") != "failed":
            continue                       # сданная задача причины отказа не имеет вовсе
        if external_refusal(row)[0]:
            continue                       # чужое API — предмет сигнала Д, а не Б
        cls, how = reason_class(row.get("result"))
        slot = tally.setdefault(cls, {"class": cls, "how": how, "ids": []})
        if row["id"] not in slot["ids"]:
            slot["ids"].append(row["id"])
    worst = None
    for slot in tally.values():
        if worst is None or len(slot["ids"]) > len(worst["ids"]):
            worst = slot
    if worst is None:
        return _sig(SIG_B, False, "провалов у заданий ящика за %s нет — причинам не из чего "
                                  "повторяться" % today, BY_OWNER, count=0)
    count = len(worst["ids"])
    if count < REPEAT_FLOOR:
        return _sig(SIG_B, False, "самая частая причина провала за %s встретилась %d раз при "
                                  "пороге %d («%s»)"
                    % (today, count, REPEAT_FLOOR, show_class(worst["class"])),
                    BY_OWNER, count=count)
    ident = "%s|%s" % (today, worst["class"])
    return _sig(SIG_B, True, "одна причина третий раз за %s: «%s» — %d раз (%s; опознана: %s)"
                % (today, show_class(worst["class"]), count,
                   ", ".join("#%s" % i for i in worst["ids"][:6]), worst["how"]),
                BY_OWNER, mark_of(SIG_B, ident), count=count,
                evidence=["#%s" % i for i in worst["ids"]])


def body_of(row):
    """Ряд очереди → ТЕЛО, по которому опознаётся вид. → str.

    Два поля, и оба нужны: живая очередь зовёт тело ``task_text``, а слепок
    очереди хранит ПЕРВУЮ его строку под именем ``goal``. Маркер вида стои́т
    первым и переживает эту обрезку — поэтому обоих полей хватает, и правило
    ровно то же, которым живёт :func:`zayavki_pc.split_awaiting` (равенство
    сторожит тест: разойдись они, витрина и ящик назвали бы один ряд по-разному).
    """
    one = row if isinstance(row, dict) else {}
    text = one.get("task_text")
    if not str(text or "").strip():
        text = one.get("goal")
    return str(text or "")


def awaiting_kind(row):
    """Ряд ``needs_approval`` → (вид, чем опознан). → (str, str).

    ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ПОЛОСА РЕШАЕТ, ДЕРЖИТ ЛИ РЯД ОПЕРАЦИЮ. Разбор в
    шапке, §«ЧТО СЧИТАТЬ КАРТОЧКОЙ»; коротко — вопрос один: ждёт ли кто-нибудь
    «да». Ждёт исполнитель (значит ряд подлежит ``APPROVAL_TTL``) — карточка
    гарда. Ждёт сам вопрос — заявка, и ящик она не держит.

    ПРИЗНАКИ ДВУХ ВИДОВ ЗАЯВОК СПРОШЕНЫ У :mod:`zayavki_pc`, а не набраны здесь:
    он уже держит их равенство ступеням B и E своими тестами. Свой, третий
    экземпляр тех же строк разошёлся бы с обоими МОЛЧА.

    ТРЕТИЙ ИСХОД — :data:`KIND_UNKNOWN`, и он считается ДЕРЖАЩИМ (см.
    :func:`split_waiting`): цена ошибки несимметрична. Но зовётся он своими
    словами, потому что «не разобрали ряд» и «владелец держит красную операцию» —
    разные новости.
    """
    text = body_of(row)
    if not text.strip():
        return KIND_UNKNOWN, "у ряда нет тела ни в task_text, ни в goal — разбирать нечего"
    if zayavki_pc.is_zayavka(text):
        return KIND_ASK, "заявка внешнего канала (ступень B, признак zayavki_pc.is_zayavka)"
    if zayavki_pc.is_recon_ask(text):
        return KIND_ASK, "заявка разведки (ступень E, признак zayavki_pc.is_recon_ask)"
    if text.startswith(REVIZOR_CARD_MARK):
        return KIND_ASK, "info-карточка ревизора (маркер %s)" % REVIZOR_CARD_MARK
    return KIND_BLOCK, "тело не несёт маркера вопроса — ряд подлежит APPROVAL_TTL, значит «да» ждёт исполнитель"


def split_waiting(rows):
    """Ряды ``needs_approval`` → ДЕРЖАЩИЕ и ЖДУЩИЕ МНЕНИЯ, врозь. → dict.

    Три кучки, а числа два: ``block`` (карточки гарда) и ``unknown`` (вид не
    определён) вместе составляют ДЕРЖАЩИХ — отказ консервативный, — а ``ask``
    остаётся отдельным числом и в сумму не входит НИКОГДА. Складывать их нельзя:
    первое число говорит «полоса остановлена», второе — «владельцу есть что
    почитать», и одно слово на две новости здесь уже стоило ящику простоя.

    Ряды НЕ в ``needs_approval`` не попадают ни в одну кучку: предмет сигнала В —
    ожидание ответа, а не открытая работа (её судит замок ``owner_busy``).
    """
    out = {"block": [], "ask": [], "unknown": [], "why": {}}
    for row in (rows or []):
        one = row if isinstance(row, dict) else {}
        if str(one.get("status") or "") != "needs_approval":
            continue
        kind, how = awaiting_kind(one)
        out["why"][str(one.get("id"))] = how
        if kind == KIND_ASK:
            out["ask"].append(one)
        elif kind == KIND_UNKNOWN:
            out["unknown"].append(one)
        else:
            out["block"].append(one)
    return out


def holding(split):
    """Ряды, которые ДЕРЖАТ ящик: карточки гарда плюс неопознанные. → list."""
    got = split if isinstance(split, dict) else {}
    return list(got.get("block") or []) + list(got.get("unknown") or [])


def _ids(rows, limit=6):
    return ", ".join("#%s" % (r or {}).get("id") for r in list(rows or [])[:limit])


def signal_c(open_rows, rows_ok=True):
    """Сигнал В: владельцу выписана карточка, ДЕРЖАЩАЯ ОПЕРАЦИЮ, ответа нет.

    ПРЕДМЕТ — ВСЯ ПОЛОСА, А НЕ ОДИН ЯЩИК, и это выбор, сделанный ЗАМЕРОМ, а не
    вкусом. Собственные ряды ящика замок владельца ``owner_busy`` уже держит:
    ``_is_owner_work`` отдаёт для ``from=Filipp-shtab`` истину при любом открытом
    статусе, включая ``needs_approval``, — то есть узкое чтение («только карточки
    по заданиям ящика») стоило бы РОВНО НОЛЬ и повторяло бы существующий замок.
    А вот карточки гарда по ЧУЖИМ рядам тот же ``_is_owner_work`` пропускает, и
    ровно их этот сигнал и ловит.

    СЧИТАЮТСЯ ТОЛЬКО ДЕРЖАЩИЕ (правка 03.09.2026, разбор в шапке). До неё сигнал
    брал ВСЕ ряды ``needs_approval`` подряд, и живой замер того же дня назвал
    цену: пять открытых рядов — пять заявок, карточек гарда ноль, ящик стои́т.
    Заявка не держит ничего: «да» на ней означает «принято к сведению» и задачи
    не рождает ни одной веткой.

    ЧИСЛА ИДУТ ВРОЗЬ И В ОДНО НЕ СКЛАДЫВАЮТСЯ. Строка называет ДЕРЖАЩИХ числом и
    номерами, а ждущих мнения — отдельным числом и отдельными номерами, даже
    когда держащих ноль: молчание про пять открытых заявок читалось бы как «у
    владельца пусто».

    ЧЕМ ЭТО НЕ СТАНОВИТСЯ «ВЫКЛЮЧЕНО НАВСЕГДА»: карточка гарда на полосе смертна.
    ``process_approval_timeouts`` роняет ряд ``needs_approval`` старше
    ``APPROVAL_TTL`` (2760 с = 46 мин) в ``failed`` сам — и теперь это правда без
    оговорок, потому что освобождённые от TTL виды сюда больше не попадают.
    """
    if not rows_ok:
        return _sig(SIG_C, True, "открытые ряды очереди не прочитаны — ждёт ли владелец ответа "
                                 "по карточке, ОПРЕДЕЛИТЬ НЕЛЬЗЯ; у остановки «не знаю» значит "
                                 "«стоп»", BY_ITSELF, determinate=False)
    split = split_waiting(open_rows)
    hold, ask = holding(split), list(split["ask"])
    if not hold:
        return _sig(SIG_C, False,
                    "карточек гарда, держащих операцию, нет (ждут мнения %d%s)"
                    % (len(ask), (": %s" % _ids(ask)) if ask else ""),
                    BY_ITSELF, count=0)
    blind = list(split["unknown"])
    blind_words = (" Из них %d с НЕОПОЗНАННЫМ видом ряда (%s) — считаем держащими: не разобрали "
                   "тело, а пропустить карточку гарда дороже лишней остановки."
                   % (len(blind), _ids(blind))) if blind else ""
    return _sig(SIG_C, True,
                "держат %d, ждут мнения %d. Держат операцию карточки гарда: %s — пока владелец "
                "не ответил, новых заданий не берём; это не поломка, а очередь на его решение.%s%s"
                % (len(hold), len(ask), _ids(hold), blind_words,
                   (" Ждут мнения (ящик не держат): %s." % _ids(ask)) if ask else ""),
                BY_ITSELF, count=len(hold),
                evidence=["#%s" % (r or {}).get("id") for r in hold])


def signal_d(left, budget=None, day="", marks_ok=True):
    """Сигнал Г: суточный потолок. ПОКАЗЫВАЕТСЯ, НЕ ИСПОЛНЯЕТСЯ (см. шапку).

    ``left`` — сколько ещё можно взять сегодня, посчитанное ЧУЖИМ счётом
    (:func:`shtab_box.budget_left`). Своего счёта здесь нет ни одной ветки:
    второй экземпляр разошёлся бы с первым молча.
    """
    cap = shtab_box.DAILY_BUDGET if budget is None else int(budget)
    if not marks_ok:
        return _sig(SIG_D, True, "корпус маркеров суток не прочитан — сколько заданий взято "
                                 "сегодня, НЕИЗВЕСТНО; день считается исчерпанным",
                    BY_DAY, enforced=False, determinate=False)
    try:
        rest = int(left)
    except (TypeError, ValueError):
        return _sig(SIG_D, True, "остаток суточного потолка не назван числом — день считается "
                                 "исчерпанным", BY_DAY, enforced=False, determinate=False)
    if rest > 0:
        return _sig(SIG_D, False, "суточный потолок: осталось %d из %d за %s"
                    % (rest, cap, str(day or "?")), BY_DAY, count=rest, enforced=False)
    return _sig(SIG_D, True, "суточный потолок исчерпан: %d из %d за %s"
                % (cap, cap, str(day or "?")), BY_DAY, count=0, enforced=False)


def signal_e(rows, day, rows_ok=True):
    """Сигнал Д: три внешних отказа подряд — лежит ЧУЖОЕ, а не наше.

    ═══ ЗАЧЕМ ОН, ЕСЛИ ВНЕШНИЙ ОТКАЗ И ТАК НИЧЕГО НЕ СТОИТ ══════════════════

    Затем, что «ничего не стоит» — это про ОДИН отказ. Освободив внешний отказ от
    суточного слота и от сигнала А, мы сняли с ящика оба тормоза разом: пока
    чужое API лежит, ящик может брать задание за заданием, каждое будет умирать
    на первой же минуте, и ни один счётчик этого не заметит — ровно то, чего
    боится задание («сломанное ТЗ будет крутиться вечно под видом чужой
    перегрузки»). Льгота обязана иметь свою цену, и вот она.

    ═══ ЧЕМ ЭТА ОСТАНОВКА ОТЛИЧАЕТСЯ ОТ СИГНАЛА А ══════════════════════════

    ИМЕНЕМ, СЛОВАМИ И ПОРЯДКОМ СНЯТИЯ, и все три различия обязательны. А зовёт
    человека разбирать НАШУ работу и держится ТОЛЬКО его словом. Д не зовёт
    разбирать ничего: он сообщает, что лежит чужое, и снимается САМ со сменой
    суток (:data:`BY_EXT`). Прочитавший обе строки владелец обязан с первого слова
    понимать, к кому вопрос, — иначе остановка «за погоду» научит его не верить и
    остановке «за работу».

    ═══ ПОЧЕМУ КОРПУС — ТЕКУЩИЕ СУТКИ ══════════════════════════════════════

    Потому что обещание «снимается со сменой суток» обязано держаться формой, а
    не намерением. Считай Д по всему корпусу — остановленный ящик перестал бы
    закрывать новые ряды, хвост из трёх чужих отказов застыл бы навсегда, и
    обещание превратилось бы в вечный стоп без слова человека. Сутки берутся ИЗ
    МАРКЕРА РЯДА, тем же правилом и с той же названной вслух границей, что у
    сигнала Б: задание, взятое вчера и упавшее сегодня, считается за вчера.

    ТРЕТИЙ ИСХОД ЗДЕСЬ НЕ ЗАВОДИТСЯ ВТОРЫМ ГОЛОСОМ. Не прочитан корпус или не
    названы сутки — Д молчит и говорит, почему: тот же самый факт уже держит ящик
    сигналами А и Б («не знаю» значит «стоп»), и третья остановка о том же
    добавила бы не строгости, а шума. Отсутствие внешних отказов и незнание о них
    здесь не сливаются: они называются разными словами.
    """
    if not rows_ok:
        return _sig(SIG_E, False, "закрытые ряды не прочитаны — внешние отказы посчитать НЕЧЕМ; "
                                  "ящик на этом же факте уже держат А и Б, второго «не знаю» "
                                  "о том же не заводим", BY_EXT, determinate=False)
    today = str(day or "")
    if not today:
        return _sig(SIG_E, False, "сутки не названы — «три подряд за сутки» посчитать НЕЧЕМ; "
                                  "ящик на этом же факте уже держит Б", BY_EXT, determinate=False)
    same_day = [r for r in (rows or []) if (r or {}).get("day") == today]
    tail = same_day[-EXT_STREAK_FLOOR:]
    verdicts = [external_refusal(r) for r in tail]
    hits = [r for r, (ok, _w) in zip(tail, verdicts) if ok]
    if len(tail) < EXT_STREAK_FLOOR or len(hits) < EXT_STREAK_FLOOR:
        return _sig(SIG_E, False, "закрытых заданий ящика за %s — %d, из них последних подряд "
                                  "на чужом API — %d при пороге %d"
                    % (today, len(same_day), len(hits), EXT_STREAK_FLOOR),
                    BY_EXT, count=len(hits))
    ident = "%s|%s" % (today, "|".join(str(r["id"]) for r in tail))
    # СЛОВА ПРОЦЕССА — В СТРОКУ, И ИМЕННО ЗДЕСЬ ОНИ НУЖНЕЕ ВСЕГО (17.09). Условие их не читает,
    # поэтому «чья сторона» строка больше не утверждает: под Д теперь встаёт и стойкая поломка
    # СВОЕЙ среды (протухший вход), которую сменой суток не вылечить. Прочесть, что это, человек
    # обязан по словам процесса, а не по нашему ярлыку.
    last = _ext_words(daemon_part(str(tail[-1].get("result") or "")))
    return _sig(SIG_E, True, "%d последних закрытых задания ящика за %s подряд умерли, НЕ ОСТАВИВ "
                             "СЛЕДОВ РАБОТЫ (%s; последний — %s). Лежит ВНЕШНЕЕ к заданиям: их "
                             "разбирать нечего — ящик встаёт, чтобы не молотить папку впустую. "
                             "Чья сторона — чужая перегрузка или свой вход, — читается по словам "
                             "процесса, а не решается ими: если слова о входе или ключе, смена "
                             "суток не вылечит, чинить вход"
                % (EXT_STREAK_FLOOR, today, ", ".join("#%s" % r["id"] for r in tail), last),
                BY_EXT, mark_of(SIG_E, ident), count=len(hits),
                evidence=["#%s" % r["id"] for r in tail])


