def box_rows(rows, statuses=("failed", "done")):
    """Ряды очереди → ТОЛЬКО закрытые задания ЯЩИКА, по возрастанию номера. → list.

    Опознание — по МАРКЕРУ РЯДА (:data:`shtab_box.MARK_RE`), тому же, которым
    ящик считает свой суточный потолок и свой дедуп. Третьего мнения о том, что
    такое «ряд из ящика», у полосы не заводится.

    ПОРЯДОК — ПО НОМЕРУ ОЧЕРЕДИ, и это выбор с названной ценой. Времени закрытия
    в рядах моста мы не читаем (его нет ни в одном поле, которым пользуется
    ящик), а «две ПОДРЯД» без порядка не существует вовсе. Номер монотонен внутри
    поколения очереди; на сбросе нумерации (очередь начинает с 1) порядок
    поколений теряется — граница названа вслух и стои́т в артефакте.
    """
    keep = set(statuses or ())
    out = []
    for it in (rows or []):
        row = it if isinstance(it, dict) else {}
        if keep and str(row.get("status") or "") not in keep:
            continue
        m = shtab_box.MARK_RE.match(str(row.get("task_text") or ""))
        if not m:
            continue
        try:
            num = int(row.get("id"))
        except (TypeError, ValueError):
            continue
        # ПЕРВАЯ СТРОКА РЯДА ЕДЕТ ЦЕЛИКОМ, а не только разобранные день и ключ:
        # имя ряда поднимает ЧУЖАЯ дверь (:func:`contour_digest.row_name`) и делает
        # это из сырого текста. Подай мы ей склейку своих `day`/`key`, у полосы
        # завелось бы второе правило имени — и разошлось бы с первым на первой же
        # правке маркера, молча (тот же класс, что у :class:`TestMirrors`).
        # ПОЛОСА РЯДА ЕДЕТ ВМЕСТЕ С НИМ (20.09.2026, задание 68i), и спрашивается
        # она у ЕДИНСТВЕННОГО владельца вопроса (`shtab_box.row_lane`, пустое поле =
        # ПК). Без неё слой не умел отличить ряд, чей итог написал НАШ демон, от
        # ряда, чей итог написал чужой, — и отвечал о втором так же уверенно, как о
        # первом. Цена этого незнания измерена: ряд #113 (lane=vps, 19.09) умер на
        # чужой стороне за 19.8 с с нулём токенов, а сигнал А засчитал его нашим
        # провалом, потому что литералы `external_refusal` — литералы ПК-демона.
        out.append({"id": num, "day": m.group(1), "key": m.group(2),
                    "goal": str(row.get("task_text") or ""),
                    "lane": shtab_box.row_lane(row),
                    "status": str(row.get("status") or ""),
                    "result": str(row.get("result") or "")})
    out.sort(key=lambda r: r["id"])
    return out


def proved(row, judged):
    """Эта закрытая строка получила вердикт «сделано»? → (bool, слова).

    ДВА УСЛОВИЯ, оба обязательны: статус ``done`` И вердикт судьи «доказана».
    Одного ``done`` не хватает — в режиме ``addr`` безадресное закрытие остаётся
    ``done``, и счёт по одному исходу зачитывал бы работу, которую никто не
    проверял (тот же довод, что у :func:`contour_digest.is_clean`).

    Слово судьи берётся у :func:`contour_digest.judged_of` — ЧУЖОГО устройства с
    четырьмя ответами. Свой разбор реестра разошёлся бы с ним на первой правке
    имён полей.

    СПРАШИВАЕМ ИМЕНЕМ, А НЕ НОМЕРОМ (правка 11.09.2026, хвост задания 32-a). Ключом
    реестра судьи стало ИМЯ ряда — «ключ маркера плюс номер» (коммит ff8b149),
    потому что номер переиспользуется: за 10.09 нумерация начиналась заново дважды.
    Здесь же цель ряда не подавалась вовсе, и `judged_of` спрашивала ГОЛЫЙ НОМЕР —
    семь перенесённых миграцией записей слой не находил и отвечал «судья не судил».
    Направление отказа безопасное (не сильнее незнания), но ответ НЕВЕРНЫЙ, а цена
    у него не нулевая: на паре таких рядов сигнал А останавливает ящик, то есть
    исправная полоса встаёт по выдуманной причине.

    МАРКЕРА У РЯДА НЕТ → имени нет, и ключом остаётся НОМЕР: :func:`row_name` сама
    ведёт эту ветку, и прежнее поведение безмаркерного ряда цело.
    """
    one = row or {}
    said = contour_digest.judged_of(one.get("id"), judged, goal=one.get("goal"))
    if str(one.get("status") or "") != "done":
        if str(one.get("result") or "").lstrip().startswith(REJECT_MARK):
            return False, "отклонена владельцем"
        return False, "закрыта как failed"
    if said == contour_digest.JUDGE_PROVED:
        return True, said
    return False, "судья: %s" % said


