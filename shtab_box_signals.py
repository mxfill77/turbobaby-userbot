# случайность формулировки (цитата со словами «API Error» проходила и тогда); без словаря её
# держит только якорь конца строки. Итог обрезан и фразы в конце нет — отсутствие следов НЕ
# доказано, ряд остаётся нашим: направление отказа то же, что у «окно неизвестно».
EXT_NO_TRACE_END_RE = re.compile(
    r"Следов работы в окне [^\n]{1,40} нет \(коммитов 0, записей журнала 0\)\.\s*\Z")
# ФОРМА ПРОЦЕССНОГО ПАДЕНИЯ — ЯКОРЬ, БЕЗ КОТОРОГО СЛОВА НИЧЕГО НЕ ЗНАЧАТ.
# Слова про чужой отказ демон берёт из вывода ребёнка, а вывод ребёнка пишет НАША
# ЖЕ модель. Ровно поэтому слова засчитываются ТОЛЬКО там, где рядом стои́т факт,
# которого текст не производит: НЕНУЛЕВОЙ КОД ВОЗВРАТА ПРОЦЕССА. Его ставит ОС и
# CLI, а не отчёт; напечатать его себе исполнитель не может ни одной строкой.
# Якорь стои́т В НАЧАЛЕ части демона (`match`, а не `search`) намеренно: у демона
# эта форма ровно одна — `pc_orchestrator.py` → ветка `if rc != 0`, — а ветка
# `insufficient_output` (rc == 0) кладёт в итог ХВОСТ ЧУЖОГО STDOUT и головы не
# имеет вовсе. Ищи форму где угодно в строке — и процитированный в хвосте текст
# доклада поднял бы признак сам. Это третий конец отрицательного теста.
EXT_PROC_RE = re.compile(r"^\[причина=[a-z_]+[^\]]*\]:\s*claude exit=(\d+)")
# Коды, которым процессное падение обязано быть ДОКАЗАНО головой части демона. Их два, и
# второй (`external_limit`, 21.09) попал сюда не по симметрии: имя «работать не дали» ставится
# у самого выхода процесса и только при ненулевом коде, но текст итога может прийти сюда и
# мимо демона (переписанный ряд, ручное закрытие) — проверка ловит ровно это.
EXT_PROC_CODES = ("exec_error", "external_limit")
# Дословные куски `pc_orchestrator.fail_result`; равенство сторожит тест.
EXT_NO_TRACE = "Следов работы в окне"    # ветка «окно известно, следов НЕТ»
EXT_UNKNOWN_WINDOW = "Окно работы неизвестно"   # ветка «окна нет» — это НЕ «следов нет»
FAIL_HEAD = "[причина="                  # начало ЧАСТИ ДЕМОНА в тексте итога
# ТРИ ПОДРЯД — порог сигнала Д, дословно по заданию. Выше порога А (две) намеренно:
