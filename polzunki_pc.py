# -*- coding: utf-8 -*-
"""ПОЛЗУНКИ ГЛОБАЛЬНОЙ СКИДКИ — чистая логика прибора полосы ПК (заведено 15.09.2026, 62-g).

ЧТО ОН МЕРЯЕТ И ЧЕМ НЕ ЯВЛЯЕТСЯ. Он сверяет ТРИ живых числа с тем, что предписывают правила
сезона, и на СМЕНУ КАРТИНЫ один раз говорит владельцу числами: что стои́т, что предписано, с
какого замера держится. Он НЕ правит ни одной ячейки, НЕ открывает таблицу, НЕ решает за
человека и не поднимает тревоги — переставляет ползунок человек, прибор только показывает.

ОСНОВАНИЕ — решение владельца 12.09.2026, дословно: ползунки «должны выставлены быть по
умолчанию в зависимости от сезона. Если они сдвинут, это значит, они были сдвинуты под
какого-то конкретного клиента или под какую-то конкретную ситуацию», и бот «может это
переспрашивать, чтобы ползунки обратно выставлять». Отсюда форма текста: ВОПРОС, а не приговор
(:func:`text`). Право сказать «верни» прибору не давали ни одной строкой.

ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ СТОРОЖА СВЕЖЕСТИ (`price_freshness`), И ЭТО НЕ ДУБЛЬ. Сторож сверяет живые
ручки с ЗАПИСАННЫМ СЛЕПКОМ `price_source.json` и отвечает на вопрос «можно ли называть цену по
записанному правилу». Мы сверяем те же живые ручки с ПРАВИЛАМИ СЕЗОНА и отвечаем на другой
вопрос — «стои́т ли ручка там, где ей положено стоять по календарю». Числа совпадут не всегда:
слепок 02.09 держал `I3=0.15` и на 13.09 разошёлся с живым `0.0` (сторож сказал «УСТАРЕЛО»), а
15.09 ручку вернули, и сторож замолчал — хотя вопрос «а тот ли это сезон» он не задавал ни разу.
Обратный случай тоже возможен по построению: пересоберись слепок в день сдвига, сторож увидел бы
свежесть, а сезонного расхождения не заметил бы никто.

ТРИ ИСХОДА, И ОНИ НЕ СЛИВАЮТСЯ (:data:`MATCH` · :data:`DIVERGED` · :data:`UNKNOWN`):

    СОВПАДАЕТ    все снятые ручки стоя́т на предписанном — прибор МОЛЧИТ
    РАСХОЖДЕНИЕ  хотя бы одна разошлась — числами: что стои́т, что предписано, с какого замера
    НЕИЗВЕСТНО   дверь молчит ЛИБО правила чисел на этот месяц не называют — и тогда СЛОВАМИ,
                 что именно неизвестно. «Неизвестно» не является вежливой формой «совпадает»:
                 ослепший прибор молчит ровно так же, как исправный при сошедшихся ручках.

ПОРЯДОК ВЕТОК В :func:`judge` — ЧАСТЬ СМЫСЛА. Сперва спрашиваются ПРАВИЛА (не назвали числа —
сверять не с чем, и живые числа тут ничего не спасают), потом ДВЕРЬ (молчит — сверять нечего),
и только потом сравниваются пары. Расхождение сильнее незнания ОТДЕЛЬНОЙ ручки: две сошлись,
третья разошлась, четвёртой нет — это РАСХОЖДЕНИЕ с названной вслух непрочитанной ручкой, а не
«неизвестно» (иначе одна молчащая категория прятала бы съехавшую соседку).

СИГНАЛ РОЖДАЕТСЯ ТОЛЬКО НА СМЕНУ СОСТОЯНИЯ (:func:`signal`). Та же картина второго сигнала не
рождает — ни на втором обороте, ни на сотом. У молчания два разных повода, и путать их нельзя:
«всё сошлось» (исход СОВПАДАЕТ) и «новостей нет» (картина не менялась). Возврат ручки на
предписанное — новость, и о нём говорится ОДИН раз, после чего прибор замолкает.
"""

import datetime

# ═════════════════════════ ТРИ ИСХОДА ════════════════════════════════════════
MATCH, DIVERGED, UNKNOWN = "СОВПАДАЕТ", "РАСХОЖДЕНИЕ", "НЕИЗВЕСТНО"

# ═════════════════════════ ЧТО ВООБЩЕ ЗА РУЧКИ ═══════════════════════════════
# Ячейки и категории взяты У ТОГО ЖЕ ИСТОЧНИКА, что и пробы сторожа свежести
# (`price_freshness_run.PROBES`, замер листа 15.08 — docs/artifacts/2026-08-15-manager-price-sheet.md
# §2.2). Второй экземпляр этой раскладки разошёлся бы со сторожем молча, и два прибора судили бы
# РАЗНЫЕ ручки под одними именами; поэтому здесь ТОЛЬКО имена и род, а список юнитов не
# переписывается вовсе.
#
# ГРАНИЦА ЦИТАТЫ НАЗВАНА, А НЕ СПРЯТАНА: правила делят парк на ДВЕ категории («скутеры» и
# «мотоциклы»), лист — на ТРИ ручки. Слов «Моты 1»/«Моты 2», адресов ячеек и самого слова
# «ползунок» в узле правил нет вовсе (замер 13.09, docs/artifacts/2026-09-13-ПОЛЗУНКИ-zamer-dveri-1309.md
# §1.4). Раскладка «мотоциклы → H3 и I3» — из ЗАМЕРА ЛИСТА, и следствие честное: правила
# предписывают ОДНО число на ОБЕ мотоциклетные ручки, разного для «Моты 1» и «Моты 2» они не
# предписывают ни строкой.
MOTO, SCOOTER = "мотоциклы", "скутеры"
CELLS = (
    ("H3", "Моты 1", MOTO),
    ("I3", "Моты 2", MOTO),
    ("J3", "Скутеры", SCOOTER),
)
CELL_NAME = {cell: name for cell, name, _kind in CELLS}
CELL_KIND = {cell: kind for cell, _n, kind in CELLS}

# ═════════════════════════ ЧТО ПРЕДПИСЫВАЮТ ПРАВИЛА ══════════════════════════
# ДОСЛОВНАЯ ОПОРА — узел `business_rules`, блок «УТОЧНЕНИЯ ВЛАДЕЛЬЦА 16.08» (:196-223), снят
# чтением 13.09 04:11 UTC+7 (тот же артефакт, §1.1). Цитата держится здесь ЦЕЛИКОМ, потому что
# пересказ «июнь-октябрь = 15/25» уже однажды родил бы неверный вывод: соседний блок
# «СЕЗОННЫЙ КАЛЕНДАРЬ ЦЕН» называет сентябрь прямо, но помечен «СВЕДЕНИЯ УСТАРЕЛИ» и опорой быть
# не может, а живая редакция растянула дно на октябрь.
RULE_QUOTE = ("СООТНОШЕНИЕ ВЕЛИЧИН, спор снят: 10% — потолок скидки на переходе март-май. "
              "25% на скутеры и 15% на мотоциклы — дно глубокого низкого сезона, июнь-октябрь. "
              "Это разные места календаря, а не противоречие.")
RULE_SRC = "business_rules → УТОЧНЕНИЯ ВЛАДЕЛЬЦА 16.08 (замер 13.09)"

# Месяцы, на которые правила называют ЧИСЛО, а не потолок и не направление.
LOW_MONTHS = (6, 7, 8, 9, 10)
PRESCRIBED_LOW = {MOTO: 0.15, SCOOTER: 0.25}

# ЧТО ПРАВИЛА НЕ НАЗЫВАЮТ ЧИСЛОМ, сказано словами и НЕ достраивается догадкой. «10% — потолок
# скидки» это ПРЕДЕЛ, а не положение ручки: ручка на 0.03 потолка не нарушает, и звать её
# расхождением значило бы выдумать предписание, которого владелец не давал. Так же и высокий
# сезон: «почти везде надбавка… к 20 декабря -10%» задаёт направление и дату, а не одно число
# на категорию.
NO_NUMBERS_WHY = {
    "весна": "март-май правила называют ПОТОЛОК скидки (10%), а не положение ручки",
    "зима": "высокий сезон правила описывают направлением и датами (надбавка, к 20 декабря -10%), "
            "а не одним числом на категорию",
}

# ДОПУСК СРАВНЕНИЯ. Ручка задаётся процентом с шагом 1 п.п. (0.01), поэтому 0.0005 — это
# ПОЛОВИНА десятой доли шага, то есть заведомо мельче любого осмысленного поворота, и при этом
# крупнее дребезга двоичного представления. Точное `==` здесь брать нельзя: числа приезжают из
# JSON через ответ двери, и один пересчёт по дороге дал бы ложное расхождение на 1e-17.
TOL = 0.0005

# ═════════════════════════ СЛОВА, КОТОРЫЕ НЕЛЬЗЯ ПОДМЕНИТЬ ═══════════════════
WHY_DOOR_SILENT = "дверь молчит"
WHY_NO_RULES = "правила чисел не называют"
CELL_UNREAD = "не снялась"


def season_of(when):
    """Момент → (ключ сезона, месяц). Чистая. ``when`` — datetime либо None."""
    if not isinstance(when, datetime.datetime):
        return None, None
    m = int(when.month)
    if m in LOW_MONTHS:
        return "низкий", m
    if m in (3, 4, 5):
        return "весна", m
    return "зима", m


def prescribed(when):
    """Момент → ({ячейка: число} | None, почему нет). Чистая.

    ``None`` — это ЧЕСТНОЕ «правила чисел не называют», и пустым словарём оно не подменяется:
    пустая карта предписаний дала бы тот же исход «сверять нечего», но с ЛОЖНОЙ причиной
    «ручек нет» вместо «правил на этот месяц нет».
    """
    season, month = season_of(when)
    if season is None:
        return None, "%s: момент замера не назван" % WHY_NO_RULES
    if season != "низкий":
        return None, "%s: %s (месяц %d)" % (WHY_NO_RULES, NO_NUMBERS_WHY[season], month)
    return {cell: PRESCRIBED_LOW[kind] for cell, _n, kind in CELLS}, ""


def _live_of(facts):
    """Факты двери → ({ячейка: число|None}, причина отказа). Форма фактов — та, что отдаёт
    :func:`price_freshness_run.live_handles`; своего разбора ответа двери здесь нет."""
    if not isinstance(facts, dict):
        return None, "фактов двери нет вовсе"
    handles = facts.get("handles")
    if facts.get("ok") is not True or not isinstance(handles, dict):
        why = str(facts.get("error") or "").strip() or "живой лист не ответил"
        return None, why
    live = {}
    for cell, _n, _k in CELLS:
        value = handles.get(cell)
        live[cell] = None if isinstance(value, bool) or not isinstance(value, (int, float)) \
            else float(value)
    if all(v is None for v in live.values()):
        why = str(facts.get("error") or "").strip() or "ни одна ручка не снялась"
        return None, why
    return live, str(facts.get("error") or "").strip()


def judge(facts, when=None):
    """Факты двери + момент → вердикт. Чистая, мира не трогает. → dict.

    Ключи вердикта: ``state`` (один из трёх исходов), ``rows`` (по строке на ручку),
    ``diverged``/``unread`` (списки ячеек), ``must`` (карта предписаний | None), ``why``.
    """
    must, why_rules = prescribed(when)
    live, why_door = _live_of(facts)
    out = {"state": UNKNOWN, "rows": [], "diverged": [], "unread": [],
           "must": must, "live": live, "why": ""}

    rows = []
    for cell, name, kind in CELLS:
        value = live.get(cell) if isinstance(live, dict) else None
        need = must.get(cell) if isinstance(must, dict) else None
        if value is None:
            state = UNKNOWN
        elif need is None:
            state = UNKNOWN
        elif abs(value - need) <= TOL:
            state = MATCH
        else:
            state = DIVERGED
        rows.append({"cell": cell, "name": name, "kind": kind,
                     "live": value, "must": need, "state": state})
    out["rows"] = rows

    # ПРАВИЛА СПРАШИВАЮТСЯ ПЕРВЫМИ: не назвали числа — сверять не с чем, и никакие живые
    # значения этого не чинят. Ветка стои́т выше двери сознательно.
    if must is None:
        out["why"] = why_rules
        return out
    if live is None:
        out["why"] = "%s: %s" % (WHY_DOOR_SILENT, why_door)
        return out

    out["diverged"] = [r["cell"] for r in rows if r["state"] == DIVERGED]
    out["unread"] = [r["cell"] for r in rows if r["live"] is None]
    if out["diverged"]:
        out["state"] = DIVERGED
        out["why"] = "разошлись с правилами сезона: %s" % ", ".join(out["diverged"])
        if out["unread"]:
            # НЕПРОЧИТАННАЯ РУЧКА НАЗЫВАЕТСЯ ВСЛУХ ДАЖЕ В РАСХОЖДЕНИИ: молчание о ней читалось
            # бы как «остальные проверены и сошлись», а они не проверены вовсе.
            out["why"] += " (не снялись: %s)" % ", ".join(out["unread"])
        return out
    if out["unread"]:
        out["state"] = UNKNOWN
        out["why"] = "%s: не снялись ручки %s%s" % (WHY_DOOR_SILENT, ", ".join(out["unread"]),
                                                    (" — %s" % why_door) if why_door else "")
        return out
    out["state"] = MATCH
    out["why"] = "все три ручки стоя́т на предписанном правилами сезона"
    return out


# ═════════════════════════ ПОДПИСЬ КАРТИНЫ ═══════════════════════════════════

def picture(verdict):
    """Вердикт → подпись ЖИВОЙ КАРТИНЫ (что стои́т). → str.

    По ней считается «с какого замера держится»: сменилась подпись — держится с этого замера.
    В подпись идут ТОЛЬКО снятые значения, без исхода и без причины: иначе смена месяца
    (а значит и предписания) обнуляла бы возраст неподвижной ручки.
    """
    parts = []
    for row in (verdict or {}).get("rows") or []:
        value = row.get("live")
        parts.append("%s=%s" % (row.get("cell"),
                                CELL_UNREAD if value is None else ("%.4f" % float(value))))
    return "|".join(parts)


def key(verdict):
    """Вердикт → подпись СОСТОЯНИЯ, на смену которой рождается сигнал. → str.

    Причина отказа В ПОДПИСЬ НЕ ИДЁТ, и это не небрежность: дверь отказывает разными словами
    («клиент моста не поднялся», «H3/XSR: дверь отказала»), и клади мы текст в подпись, каждый
    новый оттенок одного и того же незнания рождал бы владельцу новый сигнал. В подписи —
    исход, картина и род незнания, то есть ровно то, что меняет СМЫСЛ для человека.
    """
    got = verdict or {}
    state = got.get("state") or UNKNOWN
    kind = ""
    if state == UNKNOWN:
        kind = WHY_NO_RULES if got.get("must") is None else WHY_DOOR_SILENT
    return "%s#%s#%s" % (state, picture(got), kind)


RETURNED, MOVED, BLIND = "возврат", "расхождение", "неизвестно"


def signal(verdict, state=None):
    """Вердикт + прежнее состояние → (нужен ли сигнал, род). Чистая. → (bool, str|"").

    ЧЕТЫРЕ ВЕТКИ, И КАЖДАЯ ЗАКРЫТА ОТРИЦАТЕЛЬНЫМ ТЕСТОМ:

      1. картина та же (подпись совпала) → сигнала НЕТ, каким бы исход ни был;
      2. исход СОВПАДАЕТ, а прежде сигнала не было вовсе → сигнала НЕТ. Прибор при сошедшихся
         ручках молчит, и первый же его запуск на исправной полосе обязан быть немым;
      3. исход СОВПАДАЕТ после НЕсовпадения → сигнал :data:`RETURNED`, ОДИН раз. Возврат — это
         новость, а следующий оборот той же картины (ветка 1) её уже не повторит;
      4. прочее (расхождение, незнание) → сигнал своего рода.
    """
    shown = (state or {}).get("signal_key") or ""
    shown_state = (state or {}).get("signal_state") or ""
    now_key = key(verdict)
    if now_key == shown:
        return False, ""
    state_now = (verdict or {}).get("state") or UNKNOWN
    if state_now == MATCH:
        if not shown or shown_state == MATCH:
            return False, ""
        return True, RETURNED
    return True, (MOVED if state_now == DIVERGED else BLIND)


# ═════════════════════════ ТЕКСТ ДЛЯ ЧЕЛОВЕКА ════════════════════════════════
# ФОРМА — ВОПРОС, А НЕ ПРИГОВОР (пункт 3 задания и решение владельца 12.09). Прибор не знает и
# не может узнать, под какого клиента двигали ручку: истории положений у ручек нет вовсе
# (docs/artifacts/2026-08-15-calendar-switches.md §2.4). Поэтому он спрашивает.
ASK = ("Это сдвинуто под конкретного клиента или конкретную ситуацию — или вернуть по сезону? "
       "Решает человек: прибор ползунков не трогает и ни одной ячейки не правит.")
HEAD = "ПОЛЗУНКИ СКИДКИ"


def _num(value, missing=CELL_UNREAD):
    """Число ручки → короткая запись. ``None`` печатается СЛОВАМИ, а не нулём.

    Слово подставляется вызывающим, и это не украшение: у живой стороны ``None`` значит «ручка
    не снялась», у стороны предписания — «правила числа не называют». Одно слово на оба случая
    врало бы ровно в том месте, ради которого прибор и заведён.
    """
    if value is None:
        return missing
    return ("%.4f" % float(value)).rstrip("0").rstrip(".") or "0"


NO_RULE_NUM = "правила числа не называют"


def pairs(verdict, only=None):
    """Строки «ячейка «имя» стои́т X → предписано Y» через точку. → str.

    Когда предписания нет вовсе, хвост «→ предписано …» НЕ печатается: «предписано правила
    числа не называют» читается как сломанная строка, а не как названное незнание.
    """
    out = []
    for row in (verdict or {}).get("rows") or []:
        if only and row.get("cell") not in only:
            continue
        head = "%s «%s» %s" % (row.get("cell"), row.get("name"), _num(row.get("live")))
        out.append(head if row.get("must") is None
                   else "%s → предписано %s" % (head, _num(row.get("must"))))
    return " · ".join(out)


def held_words(since_words, rounds):
    """«с какого замера держится» словами. Ни одна ветка не превращает незнание в число."""
    if not since_words:
        return "С какого замера держится — неизвестно (времени первого замера в состоянии нет)"
    tail = "" if not rounds else ", замеров подряд %d" % int(rounds)
    return "Держится с замера %s%s" % (since_words, tail)


def text(verdict, kind, since_words="", rounds=0):
    """Вердикт + род сигнала → текст владельцу. Чистая. → str."""
    got = verdict or {}
    held = held_words(since_words, rounds)
    if kind == MOVED:
        return ("%s: РАСХОЖДЕНИЕ. %s. Правила сезона: %s. %s. %s"
                % (HEAD, pairs(got), RULE_SRC, held, ASK))
    if kind == RETURNED:
        return ("%s: ВЕРНУЛИ по сезону. %s. Правила сезона: %s. %s. "
                "Дальше прибор об этом молчит." % (HEAD, pairs(got), RULE_SRC, held))
    return ("%s: НЕИЗВЕСТНО — %s. Что снято: %s. %s. Пока неизвестно, прибор ничего не "
            "предписывает и ползунков не трогает."
            % (HEAD, got.get("why") or "причина не названа", pairs(got) or "ни одной ручки", held))


def vitrina_row(verdict, kind, since_words="", rounds=0):
    """Строка для витрины полосы. → str | None (прибор молчит).

    Молчит ровно в одном случае — исход СОВПАДАЕТ и сказать о возврате уже сказано. Пустая
    строка вместо `None` тут была бы ошибкой: витрина роняет раздел без строк, а «ползунки в
    порядке» она обязана не показывать, а НЕ ПОКАЗЫВАТЬ (пункт 2: совпадает — прибор молчит).
    """
    got = verdict or {}
    state = got.get("state") or UNKNOWN
    if state == MATCH and kind != RETURNED:
        return None
    return text(got, kind or (MOVED if state == DIVERGED else BLIND),
                since_words=since_words, rounds=rounds)
