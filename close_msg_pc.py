"""close_msg_pc.py — ТРИ ЧЕЛОВЕЧЕСКИЕ СТРОКИ В НАЧАЛЕ СООБЩЕНИЯ О ЗАКРЫТИИ. Чистая логика.

ЗАЧЕМ (прямой заказ владельца 04.09.2026: «из сообщения о закрытии не понять, что
происходит и зачем»). Замер того же дня по живому `pc_orchestrator.log` — пять
закрытий подряд, последнее #158 в 05:06:35, — говорит, чем сообщение начинается
СЕЙЧАС::

    ✅ Оркестратор: задача #158 выполнена — [V0 судит done: сделано ·
    V0: PROVEN / all_gates_passed по адресу «docs/artifacts/2026-09-04-потолок-…

Это машинный текст. Он отвечает на вопрос «ЧЕМ доказано закрытие» и не отвечает ни
на один из трёх, с которыми владелец открывает телефон: что спрашивали, что вышло,
что дальше. Хвост при этом режется (`pc_orchestrator._cap_result`, потолок
**4500** — не 4000, как гласила премиса задания; замер 04.09: 101 тело в
``docs/artifacts/reports/``), то есть внизу пропадает как раз то, что человек
дочитал бы последним.

ЧТО МОДУЛЬ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Он СТАВИТ ТРИ СТРОКИ В НАЧАЛО — и больше
ничего. Отчёт исполнителя, строка судьи закрытия и ссылка на полное тело не
трогаются ни символом: они съезжают на три строки вниз, и режется по-прежнему то,
что внизу. В этом весь смысл порядка.

СУДИТЬ ИСХОД МОДУЛЬ НЕ УМЕЕТ ВОВСЕ, и это защита, а не скромность. Предсмертный
взгляд задания назвал способ провалиться дословно: «строку „вышло“ соберут из
первого абзаца отчёта — и она будет бодро сообщать, что всё прекрасно, ровно там,
где задание провалено». Поэтому слово исхода БЕРЁТСЯ У СУДЬИ ЗАКРЫТИЯ дословно
(``done_judge_pc.DONE`` / ``UNKNOWN`` / ``UNKNOWN_PREFIX``), а не сочиняется по
прозе отчёта. Нет строки судьи — так и написано: ``вердикт не назван``. Первый
абзац отчёта не читается ни одной веткой; тест ``test_cheerful_report_cannot_dress_up``
держит это на живой форме «всё прекрасно» при непройденном суде.

ТРИ ИСТОЧНИКА, ПО ОДНОМУ НА СТРОКУ (премиса задания, проверена 04.09):

===============  ==========================================================
строка           откуда берётся ДОСЛОВНО
===============  ==========================================================
``СПРАШИВАЛИ``   первая строка раздела «ЦЕЛЬ» тела задания
``ВЫШЛО``        слово судьи закрытия + до ДВУХ чисел из отчёта
``ДАЛЬШЕ``       состояние ряда очереди (статус, который сейчас пишется)
===============  ==========================================================

У КАЖДОЙ СТРОКИ ТРЕТИЙ ИСХОД, И ОН НАЗЫВАЕТСЯ СЛОВАМИ. Пустая строка и бодрая
выдумка запрещены одинаково: раздела цели нет → ``цель не названа заданием``;
строки судьи нет → ``вердикт не назван отчётом``; статус пуст или незнаком →
``состояние ряда неизвестно``. Ни одна ветка не подставляет вместо них первую
попавшуюся фразу отчёта.

ГРАНИЦЫ (каждая закрыта тестом, а не обещанием):

* модуль ЧИСТЫЙ — ни диска, ни моста, ни очереди, ни времени. Вход: три строки
  текста, выход: одна. Исключений не поднимает ни одной веткой (сбой сборки трёх
  строк не смеет уронить закрытие задачи — см. :func:`prepend`);
* ИДЕМПОТЕНТЕН: текст, уже начинающийся тремя строками, возвращается байт-в-байт.
  Демон зовёт сборку один раз, но повторный заход по той же строке очереди не
  должен рожать вторую шапку;
* вердикт судьи не переписывается и не пересказывается — только ЦИТИРУЕТСЯ одним
  словом. Показать исход и судить исход — разные работы, и вторая уже сделана.
"""

import re

import done_judge_pc

# ── ФОРМА ТРЁХ СТРОК ───────────────────────────────────────────────────────────
# Метки — не украшение: по ним сборка узнаёт СВОЮ шапку и не ставит вторую
# (идемпотентность), и по ним же владелец видит, где кончается человеческая часть
# и начинается техника.
L_ASK = "СПРАШИВАЛИ: "
L_GOT = "ВЫШЛО: "
L_NEXT = "ДАЛЬШЕ: "

# ПОТОЛОК СТРОКИ — ВЫБОР, А НЕ ЗАМЕР, и назвать это честно дешевле, чем выдать за
# измерение: телефона у полосы нет, померить ширину экрана нечем. 90 знаков — это
# примерно две строки телеграма на телефоне при обычном шрифте; больше — и «одной
# фразы» уже не выходит, меньше — и цель задания режется на полуслове.
LINE_MAX = 90

# ── ТРЕТИЙ ИСХОД КАЖДОЙ СТРОКИ ─────────────────────────────────────────────────
GOAL_UNKNOWN = "цель не названа заданием"
VERDICT_UNKNOWN = "вердикт не назван отчётом"
NEXT_UNKNOWN = "состояние ряда неизвестно"

# ── ДАЛЬШЕ: ровно три слова задания, ни одного своего ──────────────────────────
NEXT_WAIT = "ждёт решения владельца"
NEXT_GO = "идём дальше сами"
NEXT_STOP = "остановились, причина: %s"
NEXT_STOP_MUTE = "остановились, причина в отчёте не названа"

# Статусы очереди, у которых смысл «дальше» ОДНОЗНАЧЕН. Всё, чего здесь нет
# (пустой статус, опечатка, новый статус очереди), уходит в третий исход —
# «неизвестно», а не в ближайшее по смыслу.
_NEXT_BY_STATUS = {
    "needs_approval": NEXT_WAIT,
    "done": NEXT_GO,
}

# ЗАГОЛОВОК РАЗДЕЛА ЦЕЛИ. Требуем ЗАГЛАВНОЕ «ЦЕЛЬ» и разделитель за ним: так
# случайная проза («цель этой правки была другой») заголовком не притворится.
# Разметку (`#`, `**`, `>`, `-`) снимаем — задания приходят и markdown-ом.
_GOAL_RE = re.compile(
    r"^[\s#>*_·•\-]*ЦЕЛЬ(?:\s+[А-ЯЁA-Z]+)?[\s*_]*[.:—–-]\s*(.*)$")

# СТРОКА СУДЬИ ЗАКРЫТИЯ — ровно та, что кладёт `done_judge_pc.line()`. Форма
# берётся не из головы: сверяется с живым литералом тестом
# `test_judge_line_form_is_taken_from_the_judge_itself`.
_JUDGE_RE = re.compile(r"\[V0 судит done:\s*([^·\]\n]+?)\s*·")

# ПРИЧИНА ПРОВАЛА — та же форма, что печатает `pc_orchestrator.fail_result`:
# `[причина=<код> · <человеческое имя>]`. Берём ИМЯ (владельцу нужен смысл, а не
# код), а если его нет — код: назвать причину хоть как-то лучше, чем промолчать.
_FAIL_RE = re.compile(r"\[причина=([a-z_]+)(?:\s*·\s*([^\]\n]+))?\]")

# ПРИЧИНА, КОТОРУЮ НАЗВАЛ СУДЬЯ. Недоказанное закрытие приходит БЕЗ головы
# `[причина=…]` — её печатает только `fail_result` демона, а судья кладёт свою:
# `<UNKNOWN_PREFIX> — <причина>`. Не читай мы её, самый частый провал полосы
# докладывался бы владельцу как «причина не названа» при названной причине.
_JUDGE_WHY_RE = re.compile(re.escape(done_judge_pc.UNKNOWN_PREFIX) + r"\s*—\s*([^\n]+)")

# ЧИСЛО В ОТЧЁТЕ. Отсекаем то, что числом для человека не является: даты
# (`2026-09-04`), время (`05:06`), куски путей и хешей (`42687d8`, `v0.1`).
# Остаётся ровно то, что владелец прочитает как число.
_NUM_RE = re.compile(r"(?<![\w./:,-])\d+(?:[.,]\d+)?%?(?![\w/:.-])")

# Границы фразы: на них режем цель, если она длиннее строки телефона.
_PHRASE_END_RE = re.compile(r"[.!?;](?:\s|$)")


def _clip(text, cap):
    """Строка под потолок телефона. Режем ПО СЛОВУ и ставим многоточие — обрубок
    посреди слова читается как сбой, а не как сокращение."""
    s = " ".join(str(text or "").split())
    if len(s) <= cap:
        return s
    cut = s[:max(1, cap - 1)]
    space = cut.rfind(" ")
    if space >= cap // 2:
        cut = cut[:space]
    return cut.rstrip(" ,;:—–-") + "…"


def _phrase(text, cap):
    """ОДНА фраза из текста цели, дословно. Кончилась фраза раньше потолка — берём
    её целиком; не кончилась — режем по слову."""
    s = " ".join(str(text or "").split())
    if not s:
        return ""
    m = _PHRASE_END_RE.search(s)
    if m and m.start() + 1 <= cap:
        s = s[:m.start() + 1]
    return _clip(s, cap)


def goal(task_text):
    """Первая строка раздела «ЦЕЛЬ» тела задания. → строка ДОСЛОВНО | ``None``.

    ``None`` — раздела цели в задании нет вовсе. Это НЕ повод взять соседнюю
    фразу: задание без цели существует (короткие постановки владельца, рычаги,
    осиротевшие ряды), и честное «цель не названа» тут единственный правдивый
    ответ. Текст задания не правится ни символом — только читается."""
    lines = str(task_text or "").splitlines()
    for i, raw in enumerate(lines):
        m = _GOAL_RE.match(raw)
        if not m:
            continue
        tail = (m.group(1) or "").strip(" *_")
        if tail:
            return tail
        # Заголовок стоит своей строкой — цель на следующей непустой.
        for nxt in lines[i + 1:]:
            if nxt.strip():
                return nxt.strip(" *_>#-")
        return None
    return None


def verdict_word(report):
    """Слово ИСХОДА из строки судьи закрытия. → строка | ``None``.

    Слово берётся ДОСЛОВНО и своими не заменяется: сообщение показывает исход, а
    не судит его. Два места, где судья своё слово говорит, и оба читаются здесь:
    строка ``done_judge_pc.line()`` в зелёном отчёте и маркер
    ``UNKNOWN_PREFIX`` в тексте недоказанного закрытия. Судья молчал (провал не
    по суду — таймаут, обрыв связи, ошибка исполнения) → ``None``."""
    s = str(report or "")
    if done_judge_pc.UNKNOWN_PREFIX in s:
        return done_judge_pc.UNKNOWN
    m = _JUDGE_RE.search(s)
    if m:
        return m.group(1).strip()
    return None


def _judge_free(report):
    """Отчёт БЕЗ служебных вставок закрытия: строки судьи, маркера «неизвестно» и
    головы причины провала. Нужно ровно для чисел: число, взятое из вердикта, было
    бы не «из отчёта исполнителя», а из чужой строки про этот же отчёт."""
    s = str(report or "")
    s = _JUDGE_RE.sub(" ", s)
    s = re.sub(r"\[V0 судит done:[^\]\n]*\]", " ", s)
    s = _FAIL_RE.sub(" ", s)
    s = s.replace(done_judge_pc.UNKNOWN_PREFIX, " ")
    return s


def numbers(report, limit=2):
    """До ``limit`` чисел ИЗ ОТЧЁТА ИСПОЛНИТЕЛЯ, дословно и в порядке появления.

    Дословно — значит без пересчёта, без округления и без единиц, которых в
    отчёте не было. Повторы схлопываем: «4500 при потолке 4500» — это одно число,
    а не два, и вторая ячейка нужнее другому."""
    seen, out = set(), []
    for m in _NUM_RE.finditer(_judge_free(report)):
        tok = m.group(0)
        if tok in seen:
            continue
        seen.add(tok)
        out.append(tok)
        if len(out) >= max(0, int(limit)):
            break
    return out


def next_step(status, report=""):
    """Что дальше — по СОСТОЯНИЮ РЯДА ОЧЕРЕДИ. → одна из четырёх строк.

    Признак ожидания владельца живёт в статусе, а не в прозе отчёта: отчёт может
    сколько угодно писать «жду „да“», но ждёт ряд, а не текст. Провал причину
    НАЗЫВАЕТ — берём её из готовой головы ``[причина=… · …]``, которую печатает
    сам демон; головы нет — так и говорим."""
    st = str(status or "").strip().lower()
    if st in _NEXT_BY_STATUS:
        return _NEXT_BY_STATUS[st]
    if st != "failed":
        return NEXT_UNKNOWN
    s = str(report or "")
    m = _FAIL_RE.search(s)
    if m:
        return NEXT_STOP % (m.group(2) or m.group(1)).strip()
    m = _JUDGE_WHY_RE.search(s)
    if m:
        # Причина судьи ЦИТИРУЕТСЯ, а не пересказывается: сообщение показывает
        # исход, а не судит его.
        return NEXT_STOP % m.group(1).strip()
    return NEXT_STOP_MUTE


def lead(task_text, report, status):
    """ТРИ СТРОКИ ШАПКИ — то, что владелец прочитает с телефона первым.

    Порядок вопросов задан заказом владельца и не переставляется: что спрашивали,
    что вышло, что дальше. Каждая строка — под потолок телефона."""
    g = goal(task_text)
    ask = _phrase(g, LINE_MAX - len(L_ASK)) if g else ""
    word = verdict_word(report)
    if word:
        got = _clip(word, LINE_MAX - len(L_GOT))
        nums = numbers(report)
        if nums:
            # Числа помечены источником НАМЕРЕННО. Голое «сделано · 20, 20» рядом
            # с недоказанным закрытием читается как похвальба; «из отчёта: 20, 20»
            # честно говорит, что это цитата исполнителя, а не вывод судьи.
            tail = " · из отчёта: " + ", ".join(nums)
            if len(L_GOT) + len(got) + len(tail) <= LINE_MAX:
                got += tail
    else:
        got = VERDICT_UNKNOWN
    return "\n".join([
        L_ASK + (ask or GOAL_UNKNOWN),
        L_GOT + got,
        L_NEXT + _clip(next_step(status, report), LINE_MAX - len(L_NEXT)),
    ])


def has_lead(report):
    """Текст уже начинается тремя строками шапки?"""
    return str(report or "").lstrip().startswith(L_ASK)


def prepend(report, task_text, status):
    """ОТЧЁТ С ТРЕМЯ СТРОКАМИ ВПЕРЕДИ. Единственная точка сборки.

    Ниже шапки текст едет БАЙТ-В-БАЙТ: вердикт судьи, отчёт исполнителя и ссылка
    на полное тело не сокращаются и не переписываются.

    НЕ ПОДНИМАЕТ ИСКЛЮЧЕНИЙ НИ ОДНОЙ ВЕТКОЙ. Косметика сообщения не смеет уронить
    закрытие задачи: сорвалась сборка — владелец получит прежнее сообщение, то
    есть ровно то, что получал вчера, а не потерянную строку очереди."""
    body = "" if report is None else str(report)
    try:
        if has_lead(body):
            return body
        head = lead(task_text, body, status)
    except Exception:                                   # noqa: BLE001 — см. докстринг
        return body
    return head + "\n\n" + body if body.strip() else head
