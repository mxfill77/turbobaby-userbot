def _clip(text, cap):
    """Строка под потолок телефона. Режем ПО СЛОВУ и ставим многоточие — обрубок
    посреди слова читается как сбой, а не как сокращение."""
    s = " ".join(str(text or "").split())
    if len(s) <= cap:
        return s
    cut = s[:max(1, cap - 1)]
    space = cut.rfind(" ")
    if space >= cap // 2:
        cut = cut[:space]
    return cut.rstrip(" ,;:—–-") + "…"


def _phrase(text, cap):
    """ОДНА фраза из текста цели, дословно. Кончилась фраза раньше потолка — берём
    её целиком; не кончилась — режем по слову."""
    s = " ".join(str(text or "").split())
    if not s:
        return ""
    m = _PHRASE_END_RE.search(s)
    if m and m.start() + 1 <= cap:
        s = s[:m.start() + 1]
    return _clip(s, cap)


def goal(task_text):
    """Первая строка раздела «ЦЕЛЬ» тела задания. → строка ДОСЛОВНО | ``None``.

    ``None`` — раздела цели в задании нет вовсе. Это НЕ повод взять соседнюю
    фразу: задание без цели существует (короткие постановки владельца, рычаги,
    осиротевшие ряды), и честное «цель не названа» тут единственный правдивый
    ответ. Текст задания не правится ни символом — только читается."""
    lines = str(task_text or "").splitlines()
    for i, raw in enumerate(lines):
        m = _GOAL_RE.match(raw)
        if not m:
            continue
        tail = (m.group(1) or "").strip(" *_")
        if tail:
            return tail
        # Заголовок стоит своей строкой — цель на следующей непустой.
        for nxt in lines[i + 1:]:
            if nxt.strip():
                return nxt.strip(" *_>#-")
        return None
    return None


def verdict_word(report):
    """Слово ИСХОДА из строки судьи закрытия. → строка | ``None``.

    Слово берётся ДОСЛОВНО и своими не заменяется: сообщение показывает исход, а
    не судит его. Два места, где судья своё слово говорит, и оба читаются здесь:
    строка ``done_judge_pc.line()`` в зелёном отчёте и МАРКЕР в тексте
    недоказанного закрытия. Маркеров с 11.09.2026 два — «неизвестно» и «не
    доказано», — и разбирает их сам судья (:func:`done_judge_pc.outcome_of`).
    Судья молчал (провал не по суду — таймаут, обрыв связи, ошибка исполнения)
    → ``None``."""
    s = str(report or "")
    marked = done_judge_pc.outcome_of(s)
    if marked is not None:
        return marked
    m = _JUDGE_RE.search(s)
    if m:
        return m.group(1).strip()
    return None


def _judge_free(report):
    """Отчёт БЕЗ служебных вставок закрытия: строки судьи, маркера «неизвестно» и
    головы причины провала. Нужно ровно для чисел: число, взятое из вердикта, было
    бы не «из отчёта исполнителя», а из чужой строки про этот же отчёт."""
    s = str(report or "")
    s = _JUDGE_RE.sub(" ", s)
    s = re.sub(r"\[V0 судит done:[^\]\n]*\]", " ", s)
    s = _FAIL_RE.sub(" ", s)
    return done_judge_pc.strip_marks(s)


def numbers(report, limit=2):
    """До ``limit`` чисел ИЗ ОТЧЁТА ИСПОЛНИТЕЛЯ, дословно и в порядке появления.

    Дословно — значит без пересчёта, без округления и без единиц, которых в
    отчёте не было. Повторы схлопываем: «4500 при потолке 4500» — это одно число,
    а не два, и вторая ячейка нужнее другому."""
    seen, out = set(), []
    for m in _NUM_RE.finditer(_judge_free(report)):
        tok = m.group(0)
        if tok in seen:
            continue
        seen.add(tok)
        out.append(tok)
        if len(out) >= max(0, int(limit)):
            break
    return out


def next_step(status, report=""):
    """Что дальше — по СОСТОЯНИЮ РЯДА ОЧЕРЕДИ. → одна из четырёх строк.

    Признак ожидания владельца живёт в статусе, а не в прозе отчёта: отчёт может
    сколько угодно писать «жду „да“», но ждёт ряд, а не текст. Провал причину
    НАЗЫВАЕТ — берём её из готовой головы ``[причина=… · …]``, которую печатает
    сам демон; головы нет — так и говорим."""
    st = str(status or "").strip().lower()
    if st in _NEXT_BY_STATUS:
        return _NEXT_BY_STATUS[st]
    if st != "failed":
        return NEXT_UNKNOWN
    s = str(report or "")
    m = _FAIL_RE.search(s)
    if m:
        return NEXT_STOP % (m.group(2) or m.group(1)).strip()
    why = done_judge_pc.reason_of(s)
    if why:
        # Причина судьи ЦИТИРУЕТСЯ, а не пересказывается: сообщение показывает
        # исход, а не судит его. Читает её сам судья — оба его маркера разом.
        return NEXT_STOP % why
    return NEXT_STOP_MUTE


def report_ref(report):
    """АДРЕС ОТЧЁТА, названный в самом отчёте. → 'docs/artifacts/…md' | ''.

    Своего адреса функция не строит ни одной веткой: она ЧИТАЕТ тот, что уже
    напечатан строкой судьи закрытия. Сочини мы его сами — у полосы завелось бы
    второе мнение о том, где лежит отчёт, и разошлось бы оно с первым молча."""
    m = _REF_RE.search(str(report or ""))
    return m.group(0) if m else ""


def _complete(text, cap, ref=""):
    """Текст под потолок и ЗАКОНЧЕННЫЙ. → строка.

    Влез целиком → байт-в-байт. Не влез → режем по границе ФРАЗЫ (границы слова
    мало: «отвечаемой ОТТУДА, ГДЕ ОНА…» — законченное слово и оборванная мысль) и
    ГОВОРИМ СЛОВАМИ, что текст сокращён и где лежит полный. Голое многоточие
    сообщает, что текст кончился не там, и не сообщает, где он кончается на самом
    деле; адрес превращает обрубок в ссылку.

    Фразы в бюджет не поместилось ни одной → режем по слову, но пометка остаётся:
    сокращение обязано называть себя даже тогда, когда сокращать пришлось грубо.

    ПОМЕТКА ИДЁТ СВЕРХ ПОТОЛКА, А НЕ ВНУТРИ НЕГО, и это не поблажка себе. Внутри
    она отнимала бы у САМОГО ТЕКСТА ровно столько, сколько длинен адрес отчёта, —
    а адреса полосы длинные (живой: 63 знака), и при потолке 200 тексту осталось
    бы сто. Замер на двух живых целях: с пометкой внутри договаривает одна фраза
    из двух и одна из трёх, сверх потолка — две из двух и две из трёх. Потолок
    здесь бюджет МЫСЛИ, а пометка — служебная приписка к ней."""
    s = " ".join(str(text or "").split())
    cap = max(1, int(cap))
    if len(s) <= cap:
        return s
    head = ""
    for m in _PHRASE_END_RE.finditer(s):
        end = m.start() + 1
        if end > cap:
            break
        head = s[:end]
    if not head:
        head = _clip(s, cap).rstrip("…").rstrip(" ,;:—–-")
    return head.rstrip() + ((CUT_REF % ref) if ref else CUT_NOREF)


def explain(task_text, report="", cap=GOAL_MAX):
    """ПОЯСНЕНИЕ — что спрашивали, законченной мыслью. → строка.

    Источник прежний и единственный (раздел «ЦЕЛЬ» тела задания, :func:`goal`);
    новое здесь одно — текст ДОГОВАРИВАЕТ. Цели в задании нет → прежнее честное
    «цель не названа заданием», а не соседняя фраза."""
    g = goal(task_text)
    if not g:
        return GOAL_UNKNOWN
    return _complete(g, cap, report_ref(report))


# ═══ РАЗДЕЛ «ЧТО ДАЛЬШЕ»: ГДЕ МЫ В ПЛАНЕ ════════════════════════════════════════

def _plural(n, one, few, many):
    """Русское согласование числа. Не украшение: «в ящике ещё 3 задание» читается
    как сбой прибора и отвлекает ровно там, где нужно прочитать число."""
    n = abs(int(n))
    if n % 100 // 10 == 1:
        return many
    last = n % 10
    return one if last == 1 else (few if 2 <= last <= 4 else many)


def _dur(minutes):
    """Минуты → человеческая длительность. → строка."""
    m = int(round(float(minutes)))
    if m < 60:
        return "%d мин" % max(1, m)
    h, m = divmod(m, 60)
    if h < 24:
        return "%d ч" % h if not m else "%d ч %d мин" % (h, m)
    d, h = divmod(h, 24)
    return "%d сут" % d if not h else "%d сут %d ч" % (d, h)


def _pace(taken):
    """Моменты последних взятий → ритм. → {ok, median_min, samples}.

    МЕДИАНА, А НЕ СРЕДНЕЕ: ночная пауза в шесть часов среди двадцатиминутных
    промежутков утащила бы среднее втрое и дала бы «оценку», которой ни один
    замер не соответствует. Промежутков меньше двух → ``ok=False``: ритм из одной
    пары чисел — это не ритм, а совпадение."""
    ts = sorted(float(t) for t in (taken or ()) if isinstance(t, (int, float)))
    gaps = sorted(b - a for a, b in zip(ts, ts[1:]) if b > a)
    if len(gaps) < 2:
        return {"ok": False, "median_min": 0.0, "samples": len(ts)}
    mid = len(gaps) // 2
    med = gaps[mid] if len(gaps) % 2 else (gaps[mid - 1] + gaps[mid]) / 2.0
    return {"ok": True, "median_min": med / 60.0, "samples": len(ts)}


def facts_from_box(report, prev=None, now=None):
    """Отчёт оборота ящика → СЛЕПОК для сообщения о закрытии. Чистая функция.

    Слепок мал СОЗНАТЕЛЬНО: четыре числа, имя и хвост моментов взятия. Он не
    реестр и замком не является — потеряется, и цена этому «неизвестно» в одном
    сообщении, а не пропущенное задание (дедуп ящика живёт в живой очереди и
    здесь не дублируется ни одним полем).

    «ЖДЁТ» СЧИТАЕТСЯ ВЫЧИТАНИЕМ ИЗВЕСТНОГО, а не разбором причин отказа: из
    документов папки убираем взятые (ключ в маркерах очереди), снятые Штабом и те,
    кому УЖЕ отказали ворота. Читай мы вместо этого фразы отказов, счёт разъезжался
    бы с ящиком на первой же перефразировке — молча.

    ═══ КОРПУС МАРКЕРОВ НЕПОЛОН → ЧИСЛА НЕТ ВОВСЕ ════════════════════════════

    Это главная ветка функции, и она лечит ИЗМЕРЕННЫЙ обман, а не воображаемый.
    Ящик читает закрытые ряды очереди ДОРОГО и потому не всегда (``get_pending
    ("done")`` — 120 строк за 26.8 с), а без них маркеры знают лишь ОТКРЫТЫЕ ряды.
    Живой замер 05.09 в таком состоянии: папка отдала 37 документов, снятых 7,
    открытым маркером помечен 1 — «ждут 29». Настоящее число много меньше:
    двадцать с лишним из этих ключей уже взяты и ЗАКРЫТЫ, просто закрытых рядов
    не спрашивали. Скажи мы «29», сообщение уверенно врало бы втрое — и проверить
    это владельцу было бы нечем.

    Поэтому ``marks_ok=False`` — это НЕ число, а «НЕИЗВЕСТНО». И прежний слепок
    при этом НЕ затирается: у него остаётся СВОЯ отметка времени, а возраст судит
    :func:`plan_facts`. Так «мы знали полчаса назад» не превращается ни в свежее
    знание, ни в пустоту.

    Папка не перечислена (или перечислена усечённо) → тот же исход по той же
    причине. Ноль отсюда не выходит ни одной веткой: «ящик пуст» и «ящик не
    прочитан» — разные новости, и вторая не смеет прикидываться первой."""
    rep = report if isinstance(report, dict) else {}
    build = rep.get("build") if isinstance(rep.get("build"), dict) else {}
    old = prev if isinstance(prev, dict) else {}
    taken = [float(t) for t in (old.get("taken") or ()) if isinstance(t, (int, float))]
    placed = rep.get("placed") or []
    if now is not None and placed:
        taken = taken + [float(now)] * len(placed)
    out = {"ts": (None if now is None else float(now)), "ok": False, "why": "",
           "waiting": 0, "next": "", "retry": 0, "taken": taken[-TAKEN_KEEP:]}
    if not build.get("folder_ok") or not build.get("marks_ok"):
        out["why"] = str(
            build.get("off_why") or (build.get("folder_why") if not build.get("folder_ok") else "")
            or build.get("marks_why")
            or "корпус маркеров очереди не прочитан — сколько ещё ждёт, неизвестно")[:200]
        if old.get("ok"):
            # ПРЕЖНЕЕ ЗНАНИЕ НЕ ЗАТИРАЕМ, но и не молодим: своя отметка времени
            # остаётся при нём, и через час возраст сам переведёт его в «НЕИЗВЕСТНО».
            keep = dict(old)
            keep["taken"] = out["taken"]
            keep["why"] = out["why"]
            return keep
        return out
    marks = set()
    for pair in (build.get("task_marks") or ()):
        try:
            marks.add(str(tuple(pair)[1]))
        except Exception:                               # noqa: BLE001 — чужая форма ≠ падение
            continue
    gates = build.get("gates") if isinstance(build.get("gates"), dict) else {}
    docs = [d for d in (build.get("docs") or ()) if isinstance(d, dict)]
    wait = []
    for doc in sorted(docs, key=lambda d: str(d.get("name") or "")):
        key = str(doc.get("key") or "")
        gate = gates.get(key)
        if not key or key in marks or doc.get("revoked"):
            continue
        if isinstance(gate, dict) and not gate.get("ok"):
            continue
        wait.append(key)
    retry = [b for b in (build.get("retry") or ()) if isinstance(b, dict)]
    out.update({"ok": True, "waiting": len(wait), "next": wait[0] if wait else "",
                "retry": len(retry)})
    return out


def plan_facts(census, now=None, queue=None, stale=PLAN_STALE_SEC):
    """Слепок ящика + ряды очереди → факты раздела. Чистая функция.

    ЧЕТЫРЕ ИСТОЧНИКА ОТВЕЧАЮТ ПОРОЗНЬ, и это главное свойство: отказ одного не
    гасит остальных и не превращается в ноль у соседа. Слепка нет · слепок без
    отметки времени · слепок старше ``stale`` · слепок сам говорит «не прочитал» —
    четыре разные причины одного исхода НЕИЗВЕСТНО, и каждая называется словами.

    СТАРЫЙ СЛЕПОК МОЛЧИТ НЕ ИЗ ОСТОРОЖНОСТИ. Оборот ящика ходит раз в полчаса;
    «в ящике 3» вчерашним числом — это уверенное враньё, которое владелец
    проверить не может, а «неизвестно» — правда, которую он проверит за минуту."""
    c = census if isinstance(census, dict) else {}
    box = {"ok": False, "why": "слепка оборота ящика нет", "waiting": 0, "next": ""}
    retry = {"ok": False, "count": 0}
    pace = {"ok": False, "median_min": 0.0, "samples": 0}
    if c:
        ts = c.get("ts")
        age = (float(now) - float(ts)) if (now is not None
                                           and isinstance(ts, (int, float))) else None
        if age is None:
            box["why"] = "у слепка ящика нет отметки времени"
        elif age > float(stale):
            box["why"] = "слепку ящика %d мин" % int(age // 60)
        elif not c.get("ok"):
            box["why"] = str(c.get("why") or "оборот ящика папку не прочитал")
        else:
            box = {"ok": True, "why": "", "waiting": int(c.get("waiting") or 0),
                   "next": str(c.get("next") or "")}
            retry = {"ok": True, "count": int(c.get("retry") or 0)}
            pace = _pace(c.get("taken"))
    q = queue if isinstance(queue, dict) else {}
    run = {"ok": bool(q.get("ok")), "waiting": int(q.get("waiting") or 0),
           "next_id": q.get("next_id")}
    return {"box": box, "run": run, "retry": retry, "pace": pace}


def plan_lines(facts):
    """Факты → РОВНО :data:`PLAN_LINES` пунктов раздела. → список строк.

    Порядок пунктов не меняется никогда: ящик · что идёт сейчас · доведение ·
    оценка. Постоянство формы здесь важнее полноты: владелец читает это каждое
    закрытие, и раздел, у которого пункты переставляются или пропадают, придётся
    читать целиком каждый раз — то есть он перестанет читаться вовсе."""
    f = facts if isinstance(facts, dict) else {}

    def part(name):
        got = f.get(name)
        return got if isinstance(got, dict) else {}

    box, run, ret, pace = part("box"), part("run"), part("retry"), part("pace")
    waiting = int(box.get("waiting") or 0)
    out = []

    if not box.get("ok"):
        out.append(P_BOX_UNKNOWN % str(box.get("why") or "источник не назван"))
    elif waiting:
        out.append(P_BOX_N % (waiting, _plural(waiting, "е", "я", "й"),
                              str(box.get("next") or P_BOX_NONAME)))
    elif ret.get("ok") and int(ret.get("count") or 0):
        # ОТДЕЛЬНЫЙ ЗАКОННЫЙ ИСХОД, НАЗВАННЫЙ СЛОВАМИ (требование задания 05.09):
        # новых заданий нет, а работа идёт. Пустой раздел на этом месте читался бы
        # как поломка ящика ровно тогда, когда ящик здоров.
        out.append(P_BOX_RETRY % int(ret["count"]))
    else:
        out.append(P_BOX_EMPTY)

    if not run.get("ok"):
        out.append(P_RUN_UNKNOWN)
    elif int(run.get("waiting") or 0):
        out.append(P_RUN_ALONE % (int(run["waiting"]), run.get("next_id")))
    else:
        out.append(P_RUN_ALONE_EMPTY)

    if not ret.get("ok"):
        out.append(P_RETRY_UNKNOWN)
    elif int(ret.get("count") or 0):
        out.append(P_RETRY_N % int(ret["count"]))
    else:
        out.append(P_RETRY_0)

    if not box.get("ok") or not pace.get("ok"):
        out.append(P_ETA_UNKNOWN)
    elif not waiting:
        out.append(P_ETA_EMPTY)
    else:
        med = float(pace.get("median_min") or 0.0)
        out.append(P_ETA % (_dur(waiting * med), int(pace.get("samples") or 0),
                            int(round(med))))
    return [_clip(x, LINE_MAX) for x in out]


def plan_block(facts):
    """Раздел «ЧТО ДАЛЬШЕ» одним куском. → строка ('' — раздела не просили).

    ``facts is None`` и ``facts == {}`` РАЗВЕДЕНЫ, и это не педантизм: первое —
    «раздела не просили» (старый вызывающий, тест чистой шапки), второе —
    «спросили, а источники не ответили», и второе обязано быть ВИДНО четырьмя
    «неизвестно», а не тишиной.

    Потолок раздела режется здесь и в последний раз: длина проверяется числом
    (:data:`PLAN_MAX`), а не глазом автора следующей правки."""
    if facts is None:
        return ""
    body = "\n".join(PLAN_BULLET + x for x in plan_lines(facts))
    return _clip_block(PLAN_HEAD + "\n" + body, PLAN_MAX)


def _clip_block(text, cap):
    """Блок под потолок ПО ЦЕЛЫМ СТРОКАМ: полстроки хуже, чем строкой меньше."""
    s = str(text or "")
    if len(s) <= cap:
        return s
    keep = []
    for line in s.split("\n"):
        if len("\n".join(keep + [line])) > cap:
            break
        keep.append(line)
    return "\n".join(keep)


def lead(task_text, report, status, facts=None):
    """ШАПКА — то, что владелец прочитает с телефона первым.

    Порядок вопросов задан заказом владельца и не переставляется: что спрашивали,
    что вышло, что дальше, и с 05.09 — где мы в плане. Пояснение договаривает
    (:func:`explain`), остальные строки — под потолок телефона."""
    ask = explain(task_text, report)
    word = verdict_word(report)
    if word:
        got = _clip(word, LINE_MAX - len(L_GOT))
        nums = numbers(report)
        if nums:
            # Числа помечены источником НАМЕРЕННО. Голое «сделано · 20, 20» рядом
            # с недоказанным закрытием читается как похвальба; «из отчёта: 20, 20»
            # честно говорит, что это цитата исполнителя, а не вывод судьи.
            tail = " · из отчёта: " + ", ".join(nums)
            if len(L_GOT) + len(got) + len(tail) <= LINE_MAX:
                got += tail
    else:
        got = VERDICT_UNKNOWN
    head = "\n".join([
        L_ASK + (ask or GOAL_UNKNOWN),
        L_GOT + got,
        L_NEXT + _clip(next_step(status, report), LINE_MAX - len(L_NEXT)),
    ])
    plan = plan_block(facts)
    return head + ("\n\n" + plan if plan else "")


def leading_mark(report, keep_first=()):
    """МАШИННЫЙ МАРКЕР, стоящий первым символом итога. → префикс | ``None``.

    Перечень свой не заводим ни одной строкой: он приходит параметром из того
    единственного места, где живёт (``pc_orchestrator.NO_HEAL_PREFIXES``)."""
    s = str(report or "").lstrip()
    for p in (keep_first or ()):
        if p and s.startswith(p):
            return p
    return None


def has_lead(report, keep_first=()):
    """Текст уже начинается тремя строками шапки? Маркер причины опознанию не мешает.

    Маркер обязан читаться ЗДЕСЬ, а не только в :func:`prepend`: шапка стои́т ЗА
    маркером, и слепой к нему ``has_lead`` объявил бы «шапки нет» на тексте, где
    она есть, — то есть приписал бы вторую. Идемпотентность держится этой веткой,
    а не порядком вызовов у вызывающего."""
    s = str(report or "").lstrip()
    mark = leading_mark(s, keep_first)
    if mark:
        s = s[len(mark):].lstrip()
    return s.startswith(L_ASK)


def prepend(report, task_text, status, keep_first=(), facts=None):
    """ОТЧЁТ С ЧЕЛОВЕЧЕСКОЙ ШАПКОЙ ВПЕРЕДИ. Единственная точка сборки.

    Ниже шапки текст едет БАЙТ-В-БАЙТ: вердикт судьи, отчёт исполнителя и ссылка
    на полное тело не сокращаются и не переписываются.

    ``keep_first`` — префиксы, которые обязаны остаться ПЕРВЫМИ символами итога
    (машинный контракт гейтов самопочинки, см. шапку модуля). Такой префикс
    поднимается НАД шапкой, и это единственный байт, который правка трогает ниже
    себя: разделитель между маркером и остатком отчёта. Набор пуст (дефолт) —
    поведение прежнее, шапка идёт первой строкой.

    ``facts`` — факты раздела «ЧТО ДАЛЬШЕ» (:func:`plan_facts`). ``None`` значит
    «раздела не просили» и даёт прежнюю трёхстрочную шапку байт-в-байт; пустой
    словарь значит «спросили, источники не ответили» и даёт раздел из четырёх
    «неизвестно». Молчаливо пропасть раздел не может ни в одном из двух случаев.

    ШАПКА ВЛЕЗАЕТ ПО ПОСТРОЕНИЮ, А НЕ ПО НАДЕЖДЕ НА ПОТОЛОК: три строки под
    :data:`LINE_MAX` (пояснение — под :data:`GOAL_MAX`) плюс раздел под
    :data:`PLAN_MAX`, то есть меньше тысячи знаков при потолке очереди 4500.
    Резать её обрезке не придётся ни разу — режется то, что ниже.

    НЕ ПОДНИМАЕТ ИСКЛЮЧЕНИЙ НИ ОДНОЙ ВЕТКОЙ. Косметика сообщения не смеет уронить
    закрытие задачи: сорвалась сборка — владелец получит прежнее сообщение, то
    есть ровно то, что получал вчера, а не потерянную строку очереди."""
    body = "" if report is None else str(report)
    try:
        if has_lead(body, keep_first):
            return body
        head = lead(task_text, body, status, facts)
    except Exception:                                   # noqa: BLE001 — см. докстринг
        return body
    if not body.strip():
        return head
    mark = leading_mark(body, keep_first)
    if not mark:
        return head + "\n\n" + body
    return mark + " " + head + "\n\n" + body.lstrip()[len(mark):].lstrip()
