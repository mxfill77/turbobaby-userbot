def outcome_of(result):
    """Исход упавшей строки: `rejected` (владелец сказал НЕТ) · `unknown` (продукт прочитать не
    удалось ЛИБО отказала чужая сторона) · `failed` (сбой). Разница не косметическая — сбой
    переотправляют, решение человека переотправлять НЕЛЬЗЯ, а неизвестность зовёт чинить СУДЬЮ
    или ждать ЧУЖОГО канала, но не переделывать работу.

    Порядок проверок: отказ владельца ПЕРВЫМ. Он стои́т в начале строки и ни один вердикт судьи
    его не перекрывает; обратный порядок дал бы отказу владельца чужое имя.

    НЕ ДОКАЗАНО судьёй — это `failed`, и это не упущение: там прибор ПРОЧИТАЛ продукт и ответил
    «нет», то есть ряд действительно упал. Отдельного разреза требует ровно тот исход, где о
    работе не сказано ничего.

    ═══ ЧУЖОЙ ОТКАЗ — ТОЖЕ «НЕИЗВЕСТНО», И ЭТО ТРЕТИЙ ИСХОД, А НЕ ЧЕТВЁРТЫЙ ═══════════════════

    Заход, который умер на стороне поставщика, НЕ ОСТАВИВ СЛЕДОВ РАБОТЫ, о нашей работе не
    сказал НИЧЕГО — ровно то состояние знания, ради которого исход «неизвестно» и заведён.
    Записывать его в `failed` значит утверждать, что полоса задачу провалила, а она её не
    начинала. Живая цена ошибки измерена: 12.09.2026 четыре ряда ящика (#33, #34, #37, #38)
    легли с дословным `claude exit=1: You've hit your session limit` при нуле коммитов и нуле
    записей журнала — и дважды за сутки подняли сигнальную остановку ящика, то есть купили
    владельцу четыре нажатия за чужую погоду.

    ЛЬГОТЫ БЕЗ ПРИЧИНЫ ЗДЕСЬ НЕТ, как и у судьи: слова причины приходят от самого различителя и
    печатаются в показе (:func:`unknown_words_of`). Четыре условия различителя обязательны все,
    и ни одно из них не производится текстом доклада — разбор в `shtab_box_signals`."""
    if first_line(result).startswith(REJECT_MARK):
        return OUT_REJECTED
    if judge_outcome(result) == JUDGE_UNKNOWN_WORD:
        return OUT_UNKNOWN
    if external_refusal_words(result) is not None:
        return OUT_UNKNOWN
    return OUT_FAILED


# Чем именно вызвана неизвестность. Слово машинное — по нему счёт серии делит тревогу на «про
# СУДЬЮ» и «про КАНАЛ», а показ печатает две разные строки: судью чинят, чужой канал пережидают.
UNKNOWN_BY_JUDGE, UNKNOWN_BY_EXT = "судья", "чужая сторона"


def unknown_by(result):
    """Кто виноват в неизвестности этой строки: :data:`UNKNOWN_BY_JUDGE` | :data:`UNKNOWN_BY_EXT`.

    Спрашивается ТЕМ ЖЕ порядком, что и исход, — иначе два места разошлись бы в ответе о той же
    строке. Вердикт судьи сильнее: если судья успел сказать «не прочитал», это про прибор."""
    if judge_outcome(result) == JUDGE_UNKNOWN_WORD:
        return UNKNOWN_BY_JUDGE
    return UNKNOWN_BY_EXT if external_refusal_words(result) is not None else UNKNOWN_BY_JUDGE


def unknown_words_of(result):
    """ПРИЧИНА неизвестности словами ТОГО, кто её назвал. → строка (никогда не пустая)."""
    if unknown_by(result) == UNKNOWN_BY_EXT:
        return external_refusal_words(result) or "чужая сторона отказала, слов не оставила"
    return judge_reason(result)


def judge_reason(result):
    """ПРИЧИНА СЛОВАМИ СУДЬИ из текста итога. → строка (никогда не пустая).

    Пункт 4 решения Штаба: «неизвестно» без названной причины не принимается. Здесь это
    ЧИТАЕТСЯ обратно — и если причины в тексте нет, так и сказано, а не показан пустой хвост."""
    try:
        import done_judge_pc
        why = done_judge_pc.reason_of(result)
    except Exception:                                   # noqa: BLE001 — судьи нет → скажем прямо
        why = None
    return why or first_line(result) or "причина судьёй не названа"


def reject_words(result):
    """Что владелец сказал СВЕРХ самого отказа (кнопка · кто ответил · пояснение). Маркер из
    строки убираем: он машинный и в разрезе «отклонено» не новость. Режет ПОКАЗ (:func:`shown`)."""
    head = first_line(result)
    tail = head[len(REJECT_MARK):].strip(" :·—-") if head.startswith(REJECT_MARK) else head
    return tail or "пояснения не оставлено"


def apply_failed(closed, failed_items, read_at, window):
    """Итог чтения упавших → в реестр. Строка есть среди упавших — «упало»/«отклонено» с причиной;
    ушла ДО этого чтения и там не найдена — «сдано»; ушла ПОСЛЕ — исход остаётся не сверенным.

    ВЕТКА ЛОЖИТСЯ НА ТО ЖЕ ПРАВИЛО ЦЕЛИКОМ, и мест здесь два, а не одно. Запись клалась
    `out[номер] = …` БЕЗУСЛОВНО: исход нового ряда затирал запись прежнего владельца номера, и
    прежний исчезал молча (перепись 11.09, §2.А). Теперь адресом записи служит личность —
    затирается ровно та запись, о которой пришла новость.

    Второе место тоньше и без него правка была бы половинчатой: набор `seen` («эту строку мы
    среди упавших видели») тоже жил номером, поэтому ряд A, честно ушедший в «сдано», не получал
    исхода, если номер A к этому часу носил упавший ряд B. Личность разводит их и здесь."""
    out = _rekey(closed)
    seen = set()
    for it in failed_items:
        if not isinstance(it, dict):
            continue
        key = closed_id(it.get("id"), it.get("goal"))
        seen.add(key)
        at = as_float(it.get("since"))
        if at is None:
            at = read_at            # времени у строки нет — считаем её увиденной СЕЙЧАС, не вечной
        if read_at - at > window:
            continue
        got = outcome_of(it.get("result"))
        row = {"id": it.get("id"), "at": at, "goal": it.get("goal"),
               "outcome": got, "why": it.get("result")}
        if got == OUT_UNKNOWN:
            # ВИНОВНИК НЕИЗВЕСТНОСТИ ЕДЕТ НА САМОМ РЯДУ, а не вычисляется читателем заново: счёт
            # серии (`contour_digest`) чист — ни диска, ни импортов, — и спросить различитель у
            # себя не может. Поля нет (старое состояние на диске) → читатель считает виновником
            # судью: это прежнее поведение, а не новое утверждение.
            row["by"] = unknown_by(it.get("result"))
        out[key] = row
    for key, item in out.items():
        at = as_float(item.get("at"))
        if item.get("outcome") is None and key not in seen and at is not None and at <= read_at:
            item["outcome"] = "done"
    return out


