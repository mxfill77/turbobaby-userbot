def remainder_words(remainder, attempt, artifact=""):
    """Остаток СЛОВАМИ — первая строка тела дожима. → str.

    Требование задания дословно: «в тело дожима первой строкой попадает ОСТАТОК
    словами: какие пункты не отвечены и чем это установлено». Поэтому здесь две
    вещи, и обе обязательны: ПЕРЕЧЕНЬ пунктов и СПОСОБ, которым это установлено, —
    исполнитель обязан видеть, что его судили сверкой с пунктами, а не мнением.
    """
    items = []
    for row in (remainder or ()):
        text = str(row.get("text") or "").strip()
        items.append("п.%s «%s»" % (row.get("n"), text[:160]))
    line = ("%s %d из %d. ОСТАТОК (не отвечено в артефакте): %s. "
            "УСТАНОВЛЕНО СВЕРКОЙ артефакта %s с пунктами раздела «ЧТО СДЕЛАТЬ» этого же "
            "документа: опорных слов пункта в артефакте не нашлось. ДОДЕЛАТЬ НЕДОСТАЮЩЕЕ, "
            "нового не придумывать: остаток берётся из пунктов исходного задания, ветки, "
            "расширяющей задание, быть не должно. Артефакт по тому же адресу ДОПОЛНИТЬ, "
            "а не заменить."
            % (RETRY_MARK, int(attempt), ATTEMPT_MAX, "; ".join(items) or "перечень пуст",
               artifact or "по названному адресу"))
    return line[:REMAINDER_MAX]


def strip_retry(body):
    """Тело → тело БЕЗ прежней строки дожима. → str.

    Без этого третья попытка носила бы остаток второй, а четвёртая — оба: тело
    росло бы к потолку :data:`shtab_box.BODY_MAX` и уперлось бы в отказ ворот на
    ровном месте. Исходное задание при этом не трогается ни символом — снимается
    ровно наша приписка.
    """
    text = str(body or "").lstrip()
    if not text.startswith(RETRY_MARK):
        return str(body or "").strip()
    parts = text.split("\n\n", 1)
    return (parts[1].strip() if len(parts) > 1 else "")


# УМОЛЧАНИЕ — ЭКЗЕМПЛЯР `shtab_box.BODY_MAX` (замер ёмкости 16.09.2026: 5000 − 500 под
# шапку). Литералом, а не импортом: модуль чистый и ворот не зовёт; боевой вызов передаёт
# потолок сам, а расхождение умолчания с оригиналом ловит
# `test_the_retry_default_moved_with_the_body_ceiling`.
def retry_body(body, remainder, attempt, artifact="", body_max=4500):
    """Исходное тело + остаток → ТЕЛО ДОЖИМА. → (тело | None, причина).

    Тело исходного задания едет ДОСЛОВНО и целиком — вместе с запретами, полосой и
    адресом результата. Это не бережливость, а условие: дожим проходит ТЕ ЖЕ
    ворота приёма (:func:`shtab_box.check`), и ни одно из них не ослаблено ни на
    символ. Наше здесь — ровно одна приписка сверху.

    ``None`` — дожим не собрался, и причина названа: тело с припиской переросло
    потолок строки очереди. Молча укоротить чужое задание нельзя (обрежется
    адрес результата, стоящий последней строкой).
    """
    clean = strip_retry(body)
    if not clean:
        return None, "тело исходного задания пустое — дожимать нечего"
    head = remainder_words(remainder, attempt, artifact)
    text = "%s\n\n%s" % (head, clean)
    if len(text) > int(body_max):
        return None, ("тело дожима %d символов при потолке %d — приписка остатка не влезает, "
                      "а резать чужое задание нельзя (обрежется адрес результата)"
                      % (len(text), int(body_max)))
    return text, ""


