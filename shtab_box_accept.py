SHARE = 0.5
MIN_HITS = 2

# ЧЕМ ПЛАТИТ ЭТОТ ПОРОГ В ДРУГУЮ СТОРОНУ, названо честно. Артефакт, сделавший
# работу, но НЕ НАЗВАВШИЙ пункт своими словами, получит ДОЖАТЬ — и это «сомнение
# → ДОЖАТЬ» задания, а не поломка. Круг при этом не бесконечен и не слеп: остаток
# едет в тело дожима ПЕРЕЧНЕМ ПУНКТОВ, то есть исполнитель второй попытки видит
# ровно то, чего в артефакте не хватает, и дописывает раздел, а не переделывает
# работу. Потолок :data:`ATTEMPT_MAX` обрывает круг на пятой в любом случае.

# Первая строка тела дожима. Слово ищется при разборе, поэтому оно константа, а не
# литерал по месту: два экземпляра одного маркера расходятся молча.
RETRY_MARK = "ДОЖИМ, попытка"
REMAINDER_MAX = 1200              # потолок остатка словами; тело задания и так ≤ shtab_box.BODY_MAX


# ═════════════════════════ РАЗБОР РЯДА ОЧЕРЕДИ ═══════════════════════════════
# Зеркала литералов `shtab_box.task_text`. Их два, и оба сверяются ТЕСТОМ, а не
# обещанием (``test_head_mirrors_shtab_box``): текст ряда собирает чужая функция, и
# разъедься мы с ней молча — дожим носил бы в теле нашу же шапку, а ворота приёма
# считали бы её частью чужого задания.
HEAD_MARK = "[от Штаба"
HEAD_SOURCE_RE = re.compile(r"^Источник: документ (?P<name>\S+) папки мозга "
                            r"\(file id (?P<id>[^)]*)\)")


def body_of(task_text):
    """Текст ряда очереди → ТЕЛО задания без нашей шапки. → str.

    Шапка ящика — ровно три строки и пустая строка за ними, поэтому граница берётся
    ПЕРВЫМ пустым абзацем, а не счётом строк: счёт сломался бы от любой новой
    строки шапки молча, а пустой абзац стои́т в самой сборке (`shtab_box.task_text`).
    Текст не из ящика возвращается как есть — резать чужое нельзя.
    """
    text = str(task_text or "")
    if not text.lstrip().startswith(HEAD_MARK):
        return text.strip()
    parts = text.split("\n\n", 1)
    return parts[1].strip() if len(parts) > 1 else ""


def source_of(task_text):
    """Текст ряда → {'name', 'id'} исходного документа папки. → dict (пустые — не найдено).

    Дожим обязан встать ТЕМ ЖЕ документом, и «тем же» доказывается именем и file id
    из самого ряда: ходить за ними в папку мозга не нужно — они уже приехали в
    строке происхождения, которую ящик пишет каждой задаче.
    """
    for line in str(task_text or "").splitlines()[:5]:
        match = HEAD_SOURCE_RE.match(line.strip())
        if match:
            return {"name": match.group("name"), "id": match.group("id")}
    return {"name": "", "id": ""}


def key_of(task_text):
    """Текст ряда → ключ задания ящика. → str ('' — ряд не из ящика)."""
    match = re.match(r"^\s*\[от Штаба дата=\d{4}-\d{2}-\d{2} ключ=([0-9A-Za-z._-]{3,40})\]",
                     str(task_text or ""))
    return match.group(1) if match else ""


# ═════════════════════════ КЛЮЧ И ПОПЫТКА ════════════════════════════════════


def attempt_of(key):
    """Ключ → номер попытки. → int ≥ 1.

    Базовый ключ — это ПЕРВАЯ попытка, а не нулевая: владелец считает заходы с
    единицы, и «пять на задание» обязано означать пять строк очереди, а не шесть.
    """
    match = ATTEMPT_RE.match(str(key or ""))
    return int(match.group("n")) if match else 1


def base_key(key):
    """Ключ любой попытки → ключ ИСХОДНОГО документа. → str.

    Нужен там, где спрашивают «а не то же ли это задание»: имя документа в папке
    мозга не меняется от номера попытки.
    """
    match = ATTEMPT_RE.match(str(key or ""))
    return match.group("base") if match else str(key or "")


def retry_key(key, attempt_max=ATTEMPT_MAX):
    """Ключ закрытой попытки → ключ СЛЕДУЮЩЕЙ. → (ключ | None, причина словами).

    ``None`` — дожима не будет, и причина названа. Их ровно две, и обе честные:
    потолок попыток исчерпан (тогда слово владельцу, :func:`owner_card`) либо
    ключ дожима не влезает в потолок :data:`KEY_MAX`. Второе не выдумка: маркер
    очереди читают дедуп, суточный счёт и сводка контура одной регуляркой, и ключ
    длиннее сорока символов перестал бы ей отвечать — задание бралось бы заново
    каждый виток, и увидеть это было бы нечем.
    """
    key = str(key or "")
    nxt = attempt_of(key) + 1
    if nxt > int(attempt_max):
        return None, ("потолок попыток исчерпан: %d из %d — задание больше не дожимается, "
                      "слово владельцу" % (nxt - 1, int(attempt_max)))
    if nxt > 9:
        return None, "номер попытки не однозначный — форма ключа дожима держит одну цифру"
    candidate = "%s%s%d" % (base_key(key), ATTEMPT_SEP, nxt)
    if not KEY_RE.match(candidate):
        return None, ("ключ дожима %r не по форме или длиннее %d символов — обрезать его нельзя "
                      "(обрезанный ключ есть ДРУГОЕ задание, и дедуп разъедется молча)"
                      % (candidate, KEY_MAX))
    return candidate, ""


# ═════════════════════════ ПУНКТЫ ЗАДАНИЯ ════════════════════════════════════


def points(body):
    """Тело задания → пункты раздела «ЧТО СДЕЛАТЬ». → [{'n', 'text'}].

    Пустой список — это «сверять не с чем», и наверху он становится
    :data:`UNKNOWN`, а не молчаливым ПРИНЯТО.

    Продолжения пунктов приклеиваются к своему номеру: Штаб пишет пункт абзацем, и
    опорные слова живут во второй строке не реже, чем в первой.
    """
    lines = str(body or "").splitlines()
    start = None
    for i, line in enumerate(lines):
        if DO_HEAD_RE.match(line):
            start = i + 1
            break
    if start is None:
        return []
    out = []
    for line in lines[start:]:
        match = POINT_RE.match(line)
        if match:
            if len(out) >= POINTS_MAX:
                break
            out.append({"n": int(match.group("n")), "text": match.group("text").strip()})
            continue
        if not line.strip():
            continue
        if SECTION_RE.match(line) and not out:
            # Заголовок ДО первого пункта — раздел пуст, дальше чужой текст.
            break
        if SECTION_RE.match(line):
            break
        if out:
            out[-1]["text"] = ("%s %s" % (out[-1]["text"], line.strip())).strip()
    return out


def stems(text):
    """Текст → множество основ. Одна дорога к основе у пункта и у артефакта.

    Второй экземпляр этой функции разошёлся бы с первым молча — а тогда пункт и
    артефакт мерились бы разными линейками, и дожим приходил бы на пустом месте.
    """
    out = set()
    for word in WORD_RE.findall(str(text or "")):
        low = word.casefold().replace("ё", "е")
        out.add(low[:STEM])
    return out


def terms(text):
    """Пункт → его ОПОРНЫЕ слова (основы, без боилерплейта). → sorted list.

    Пустой список значит «у пункта нет своих слов» — такой пункт не судится ни в
    одну сторону, и наверху он назван поимённо, а не молча зачтён.
    """
    return sorted(s for s in stems(text) if s not in STOP)


def answered(point_terms, art_stems, share=SHARE, min_hits=MIN_HITS):
    """Пункт отвечён артефактом? → (bool, [ненайденные основы], найдено, всего).

    Мера одна и названа числом: доля найденных опорных слов ≥ ``share`` И не
    меньше ``min_hits`` разных слов. Никаких «артефакт сказал, что сделал».
    """
    point_terms = list(point_terms or ())
    art_stems = art_stems if isinstance(art_stems, (set, frozenset)) else set(art_stems or ())
    found = [t for t in point_terms if t in art_stems]
    missing = [t for t in point_terms if t not in art_stems]
    total = len(point_terms)
    if not total:
        return False, [], 0, 0
    ok = (len(found) >= int(min_hits) or len(found) == total) and \
         (float(len(found)) / float(total)) >= float(share)
    return bool(ok), missing, len(found), total


