def owner_card(key, verdict, attempt=ATTEMPT_MAX, name=""):
    """Пятая попытка не принята → строка владельцу. → str.

    Задание требует не бросать молча. Карточка называет ТРИ вещи: сколько заходов
    потрачено, какие пункты не закрылись и чем это установлено, — чтобы владелец
    решал по фактам, а не по слову прибора.
    """
    items = ", ".join("п.%s" % r.get("n") for r in (verdict or {}).get("remainder", ())) or "—"
    return ("ЯЩИК ШТАБА: задание %s (%s) не закрылось за %d захода(ов) — потолок попыток. "
            "Не отвечены пункты: %s. Установлено сверкой артефакта с разделом «ЧТО СДЕЛАТЬ» "
            "исходного документа. Дожим остановлен, решение за владельцем."
            % (str(key or "?"), str(name or "документ не назван"), int(attempt), items))


def journal_line(key, verdict, day, artifact=""):
    """Одна строка исхода приёмки в журнал. → str.

    Пишется и на ПРИНЯТО тоже: приёмка, молчащая при успехе, неотличима от
    приёмки, которая не работала.
    """
    v = verdict or {}
    return ("ARTIFACT приёмка ящика: задание %s за %s → %s (%s) · артефакт %s"
            % (str(key or "?"), str(day or "?"), str(v.get("verdict") or UNKNOWN),
               str(v.get("why") or "причина не названа")[:300],
               artifact or "по названному адресу"))


