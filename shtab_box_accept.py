# ДОЖИМЫ ТРАТЯТ СУТОЧНЫЙ ПОТОЛОК ЯЩИКА НАРАВНЕ С ПЕРВЫМИ ЗАХОДАМИ, и это НЕ
# недосмотр и НЕ поблажка, которую забыли снять. Требование задания дословно:
# «доделать начатое важнее, чем начать новое».
#
# Механика ровно та же, и отдельной ветки под неё нет вовсе: у дожима СВОЙ ключ,
# значит в очередь он встаёт своим маркером `[от Штаба дата=… ключ=…]`, значит
# `shtab_box.markers` считает его наравне со всеми, значит `budget_left` вычитает
# его из тех же восьми. Никакой льготы ему не выписано ни строкой — и следующий
# читающий обязан понимать, что это НАМЕРЕНИЕ, а не дыра.
#
# ПОРЯДОК ЖЕ У ДОЖИМА ПЕРВЫЙ: руки подают его в отбор ПЕРЕД документами папки, и
# при потолке витка (`shtab_box.TICK_LIMIT` = 1) это значит буквально «сначала
# доделываем, потом берём новое». Дожимов больше, чем осталось на сутки, — новые
# задания в этот день не берутся вовсе, и это правильный порядок, а не голодание.
BUDGET_WORDS = ("дожим тратит суточный потолок ящика наравне с первым заходом "
                "(доделать начатое важнее, чем начать новое) и подаётся в отбор ПЕРВЫМ")
