# ── ИМЕНА ИСХОДОВ — часть договора, по ним пишут условия потребители. ─────────────────────
OK = "ЗАМЕР СВЕЖ"
NO_MEASURE = "ЗАМЕРА НЕТ"
NOT_A_THRESHOLD = "НЕ ПОРОГ"
NO_RECORD = "ЗАПИСИ НЕТ"
BROKEN = "ПАСПОРТ БИТЫЙ"
STALE = "ЗАМЕР ПРОТУХ"
UNREAD = "ПРОЧЕСТЬ НЕ СМОГЛИ"
STATES = (OK, NO_MEASURE, NOT_A_THRESHOLD, NO_RECORD, BROKEN, STALE, UNREAD)

# КРАСНЫЕ исходы. `ЗАМЕРА НЕТ` и `НЕ ПОРОГ` сюда НЕ входят — см. докстроку.
RED = (NO_RECORD, BROKEN, STALE, UNREAD)

# ── РОДЫ ЗАМЕРА. Замер живой латентности и слово владельца протухают с РАЗНОЙ скоростью,
# и одним горизонтом их мерить нельзя: дверь моста меняет хвост за две недели, а частота
# пересмотра цен — это решение человека, оно не ветшает по календарю вовсе. ──────────────
KIND_LATENCY = "латентность"
KIND_DECISION = "решение"
KIND_NOT = "не порог"
KINDS = (KIND_LATENCY, KIND_DECISION, KIND_NOT)

# ПАСПОРТ ПОРОГА: терпит=все паспорта рода «латентность» делят один горизонт протухания
#   | замер=ДВА наблюдённых протухания собственной полосы: WD_PRODUCT_SILENT 1800с (замер
#   12.08 a8d0b39 → опровергнут 05.09 медианой сборки 1841с) = 24 сут; PRICE_GATE_PROBE_SEC
#   90с (замер 20-21.08 45a38cf → опровергнут 06.09 медианой круга 95.15с) = 16 сут. Горизонт
#   = ПОЛОВИНА КОРОТЧАЙШЕГО протухания (16 ÷ 2), то есть замер обязан быть перемерян вдвое
#   раньше, чем протух самый быстрый из наблюдённых. Доктрина двукратного запаса та же, что
#   у ONE/PROBE 06.09, но ОБРАЩЁННАЯ: у потолка запас идёт ВВЕРХ от худшего, у срока годности
#   — ВНИЗ от быстрейшего. ОСНОВАНИЕ СЛАБОЕ И НАЗВАНО СЛАБЫМ: n=2, оба случая августовские,
#   доверительного интервала здесь нет. Третий наблюдённый случай обязан пересчитать число
#   | снят=2026-09-06 | делится=каждый паспорт рода «латентность»
#   | предел-единицы=НЕ НУЖЕН: горизонт не расходуется операциями, он сравнивается с датой —
#   исчерпать его одной операцией нельзя по построению
#   | род=латентность | артефакт=docs/artifacts/2026-09-06-правило-порога-запись-замера-06.09.md
HORIZON_LATENCY_DAYS = 8.0

# ПАСПОРТ ПОРОГА: терпит=паспорта рода «решение» — слово владельца и бизнес-факт
#   | замер=НЕТ | снят=— | делится=НЕ ДЕЛИТСЯ
#   | предел-единицы=НЕ НУЖЕН
#   | род=решение | артефакт=—
# (пусто = горизонта по календарю нет: решение владельца протухает, когда владелец его меняет,
#  а не когда проходит N суток. Проверяющий требует у такого паспорта ССЫЛКУ на источник слова
#  в поле `замер`, и это единственное, что он о нём может честно проверить.)
HORIZON_DECISION_DAYS = None

_FIELDS_REQUIRED = ("терпит", "замер", "снят", "делится", "предел-единицы")

# ── ОТКРЫТИЕ КАНДИДАТОВ. Ищем не ИМЕНА (список имён отстаёт молча — это ровно тот дефект,
# который модуль и лечит), а ФОРМУ: модульная числовая ручка окружения, модульная числовая
# константа с предельным именем, и присвойка таймаута живому клиенту. Новый порог, заведённый
# в покрытом файле, находится САМ и требует паспорта в тот же день. ──────────────────────
_RE_ENV = re.compile(
    r"^(?P<name>[A-Za-z_][A-Za-z_0-9]*)\s*=\s*"
    r"(?:int|float)\s*\(\s*os\.getenv\(\s*[\"'](?P<env>[^\"']+)[\"']\s*,\s*[\"'](?P<val>[-0-9.]*)[\"']")
_RE_BARE = re.compile(
    r"^(?P<name>[A-Z][A-Z_0-9]*(?:DEFAULT|DEADLINE|BUDGET|TIMEOUT|TTL|WORKERS|LIMIT|MAX|SILENT|ALLOW|DAYS))"
    r"\s*=\s*(?P<val>-?\d+(?:\.\d+)?)\s*(?:#|$)")
_RE_ATTR_TIMEOUT = re.compile(
    r"^\s*(?P<name>[A-Za-z_][\w.]*\.timeout)\s*=\s*(?P<val>-?\d+(?:\.\d+)?)\s*(?:#|$)")


def _passport_block(lines, idx):
    """Текст паспорта над строкой `idx` (0-based) или None.

    Блок — сплошной прогон строк-комментариев НЕПОСРЕДСТВЕННО над значением. Пустая строка и
    любая строка кода блок обрывают: паспорт обязан касаться значения, а не висеть где-то выше.
    """
    out = []
    i = idx - 1
    while i >= 0:
        raw = lines[i].strip()
        if not raw.startswith("#"):
            break
        out.append(raw.lstrip("#").strip())
        i -= 1
    out.reverse()
    text = " ".join(out)
    if MARK not in text:
        return None
    return text[text.index(MARK) + len(MARK):].strip()


def parse_passport(text):
    """Текст паспорта → (поля, беда|None). Беда — СЛОВАМИ, а не флагом: её читает человек."""
    if not text:
        return {}, "паспорт пуст"
    fields = {}
    for chunk in text.split("|"):
        chunk = chunk.strip()
        if not chunk or "=" not in chunk:
            continue
        key, _, value = chunk.partition("=")
        key = key.strip().lower()
        if key and key not in fields:          # первое вхождение — своё, дубль не затирает
            fields[key] = value.strip()
    missing = [f for f in _FIELDS_REQUIRED if not fields.get(f)]
    if missing:
        return fields, "нет обязательных полей: %s" % ", ".join(missing)
    kind = fields.get("род", KIND_LATENCY)
    if kind not in KINDS:
        return fields, "род «%s» не из списка %s" % (kind, "/".join(KINDS))
    fields["род"] = kind
    return fields, None


def _measure_date(fields):
    """Дата замера → (date|None, беда|None). `замер=НЕТ` — законный исход, а не беда."""
    measured = fields.get("замер", "").strip()
    if measured.upper().startswith("НЕТ"):
        return None, None
    raw = fields.get("снят", "").strip()
    if raw in ("", "—", "-"):
        return None, "замер назван, а дата съёма не названа"
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", raw)
    if not m:
        return None, "дата съёма «%s» не в форме ГГГГ-ММ-ДД" % raw
    try:
        return datetime.date(int(m.group(1)), int(m.group(2)), int(m.group(3))), None
    except ValueError:
        return None, "дата съёма «%s» не существует" % raw


def horizon_days(kind):
    """Горизонт протухания рода. None — по календарю не протухает (решение владельца)."""
    if kind == KIND_LATENCY:
        return HORIZON_LATENCY_DAYS
    return HORIZON_DECISION_DAYS


def judge_one(name, line, value, passport, today):
    """ОДИН порог → запись вердикта. Чистая функция, голден; сегодняшнюю дату инъектируют.

    Никогда не бросает: непонятый паспорт — это ИСХОД `ПАСПОРТ БИТЫЙ`, а не авария прибора.
    """
    rec = {"name": name, "line": line, "value": value,
           "state": None, "why": "", "kind": None, "measured_on": None,
           "age_days": None, "unit": None, "unit_limit": None}
    if passport is None:
        rec["state"] = NO_RECORD
        rec["why"] = "паспорта над значением нет — число молчит о своём основании"
        return rec
    fields, bad = parse_passport(passport)
    rec["unit"] = fields.get("делится")
    rec["unit_limit"] = fields.get("предел-единицы")
    rec["kind"] = fields.get("род")
    if bad:
        rec["state"] = BROKEN
        rec["why"] = bad
        return rec
    if fields["род"] == KIND_NOT:
        rec["state"] = NOT_A_THRESHOLD
        rec["why"] = fields.get("терпит", "объявлено «не порог»")
        return rec
    when, bad = _measure_date(fields)
    if bad:
        rec["state"] = BROKEN
        rec["why"] = bad
        return rec
    if when is None:
        rec["state"] = NO_MEASURE
        rec["why"] = "паспорт честно говорит «замера нет»; значение не менять без замера"
        return rec
    rec["measured_on"] = when.isoformat()
    age = (today - when).days
    rec["age_days"] = age
    limit = horizon_days(fields["род"])
    if limit is None:
        rec["state"] = OK
        rec["why"] = "род «%s» — по календарю не протухает (источник назван в замере)" % fields["род"]
        return rec
    if age > limit:
        rec["state"] = STALE
        rec["why"] = ("замер снят %s — %d сут назад при горизонте %g сут; "
                      "перемерить или назвать «замера нет»" % (when.isoformat(), age, limit))
        return rec
    rec["state"] = OK
    rec["why"] = "замер снят %s, возраст %d сут при горизонте %g сут" % (when.isoformat(), age, limit)
    return rec


def scan_text(text):
    """Текст модуля → кандидаты-пороги [(name, line, value, passport|None)].

    Строки внутри тройных кавычек НЕ разбираются: докстрока, показывающая форму паспорта,
    не смеет притвориться порогом (иначе этот самый модуль уронил бы сам себя примером).
    """
    lines = text.splitlines()
    out, in_doc, fence = [], False, ""
    for i, line in enumerate(lines):
        stripped = line.strip()
        if in_doc:
            if fence in line:
                in_doc = False
            continue
        for q in ('"""', "'''"):
            if stripped.startswith(q) and not (len(stripped) > 5 and stripped.endswith(q)):
                in_doc, fence = True, q
                break
        if in_doc:
            continue
        m, name = _RE_ENV.match(line), None
        if m:
            name = m.group("name")
        else:
            m = _RE_BARE.match(line)
            if m:
                name = m.group("name")
            else:
                m = _RE_ATTR_TIMEOUT.match(line)
                if m:
                    name = m.group("name")
        if not m:
            continue
        out.append((name, i + 1, m.group("val"), _passport_block(lines, i)))
    return out


def audit(sources, today=None, names=None):
    """ГЛАВНОЕ. {имя файла: текст|None} → сводка вердиктов.

    `sources[f] is None` означает «файл не прочитан» — исход `ПРОЧЕСТЬ НЕ СМОГЛИ`, КРАСНЫЙ.
    `names` — необязательный отбор ИМЁН внутри файла (для файлов, покрытых не целиком:
    охват такого файла обязан быть назван поимённо, а не подразумеваться).
    """
    day = today if today is not None else datetime.date.today()
    rows, counts = [], {s: 0 for s in STATES}
    for path in sorted(sources):
        text = sources[path]
        if text is None:
            rows.append({"file": path, "name": "—", "line": 0, "value": "",
                         "state": UNREAD, "why": "файл не прочитан", "kind": None,
                         "measured_on": None, "age_days": None,
                         "unit": None, "unit_limit": None})
            counts[UNREAD] += 1
            continue
        wanted = names.get(path) if isinstance(names, dict) else None
        for name, line, value, passport in scan_text(text):
            if wanted is not None and name not in wanted:
                continue
            rec = judge_one(name, line, value, passport, day)
            rec["file"] = path
            rows.append(rec)
            counts[rec["state"]] += 1
    red = [r for r in rows if r["state"] in RED]
    with_unit_limit = [r for r in rows if r["state"] not in (NOT_A_THRESHOLD, UNREAD)
                       and (r.get("unit_limit") or "").strip()
                       and not (r["unit_limit"].upper().startswith("НЕТ"))
                       and not (r["unit_limit"].upper().startswith("НЕ НУЖЕН"))]
    return {"rows": rows, "counts": counts, "red": red, "ok": not red,
            "with_unit_limit": [r["name"] for r in with_unit_limit],
            "total": len(rows)}
