# `threshold_ledger.py` покрывает САМ СЕБЯ намеренно: горизонт протухания — тоже общий порог,
# и проверяющий, стоящий на непроверенном числе, был бы ровно тем дефектом, который он ловит.
COVERED_FILES = ("price_gate.py", "price_freshness.py", "price_freshness_run.py",
                 "pricing.py", "suggest.py", "threshold_ledger.py")
# Файл, покрытый НЕ ЦЕЛИКОМ, обязан назвать своё покрытие ПОИМЁННО — иначе «зелено» читалось
# бы как «весь демон проверен». Оба имени взяты не наугад: BRIDGE_LOOP_BUDGET назван премисой
# задания, WD_PRODUCT_SILENT — первый из трёх случаев класса за сутки.
COVERED_NAMES = {"pc_orchestrator.py": ("BRIDGE_LOOP_BUDGET", "WD_PRODUCT_SILENT")}
# НЕПОКРЫТОЕ НАЗВАНО ЧИСЛОМ, И ЧИСЛО ИЗМЕРЕНО, А НЕ ПРИКИНУТО. Открытие 06.09 теми же
