# -*- coding: utf-8 -*-
"""ПРАВИЛО ПОРОГА: у каждого общего порога есть ПАСПОРТ, и его отсутствие КРАСНО.

ЗАЧЕМ ЗАВЕДЕНО — ТРЕТИЙ СЛУЧАЙ ОДНОГО КЛАССА ЗА СУТКИ, а не третья заплата.

  1. 05.09.2026 — `WD_PRODUCT_SILENT` = 1800с (замер 12.08, коммит a8d0b39) оказался НИЖЕ
     медианы сборки пакета ревьюеру (1841с на 39 сборках): каждая успешная сборка обязана
     была позвать владельца, и 25 из 39 позвали. Между замером и обнаружением — 24 суток.
  2. 06.09.2026 — `PRICE_GATE_PROBE_SEC` = 90с (замер 20-21.08, коммит 45a38cf) оказался НИЖЕ
     медианы круга проб (95.15с): половина кругов в него не влезала. Между замером и
     обнаружением — 16 суток.
  3. 06.09.2026, разведка того же захода — из ПЯТИ общих порогов ценового пути замером был
     обоснован ОДИН, и тот протух.

Правило «порог сверяется с замером» в каноне рамки ЕСТЬ (§6, FACT-культура). Дефект не в том,
что правила нет, а в том, что ЕГО НЕ ПРОВЕРЯЕТ НИЧТО: круглое число заводится молча, живёт
годами и опознаётся только по аварии. Этот модуль и есть недостающий проверяющий.

ЧТО ТАКОЕ ОБЩИЙ ПОРОГ. Один лимит, который МНОГИЕ операции делят между собой: девять проб
делят бюджет, сотня quote делит дедлайн сборки, все чтения витка делят потолок моста. У такого
порога есть свойство, которого нет у одиночного таймаута: **исчерпать его может ОДНА операция,
а заплатят ВСЕ** — и заплатят молча, потому что выброшенное не отличается от несуществующего.

────────────────────────────────────────────────────────────────────────────────────────────
ФОРМА ПАСПОРТА (машиночитаемая, живёт РЯДОМ СО ЗНАЧЕНИЕМ — комментарием прямо над ним):

    # ПАСПОРТ ПОРОГА: терпит=<что делит порог> | замер=<чем обоснован | НЕТ>
    #   | снят=<ГГГГ-ММ-ДД | —> | делится=<единица деления | НЕ ДЕЛИТСЯ>
    #   | предел-единицы=<имя своей ручки | НЕТ: чем грозит | НЕ НУЖЕН: почему>
    #   | род=<латентность | решение | не порог> | артефакт=<путь | —>

Поля разделены `|`, запись продолжается на соседние строки-комментарии того же блока.
Порядок полей значения не имеет, имя поля — до первого `=`.

ПОЧЕМУ РЯДОМ СО ЗНАЧЕНИЕМ, А НЕ В РЕЕСТРЕ. Реестр отстаёт молча — ровно так отстала локальная
проекция рамки и ровно так отстал `docs/PROJECT_OPERATING_FRAME.md`. Правка значения и правка
паспорта обязаны быть ОДНИМ движением руки, иначе паспорт станет вторым враньём поверх первого.

────────────────────────────────────────────────────────────────────────────────────────────
ЧТО КРАСНЕЕТ (и это единственное, ради чего модуль существует):

  • `ЗАПИСИ НЕТ`      — у порога нет паспорта. КРАСНО. Это и есть «круглое число завелось молча».
  • `ПАСПОРТ БИТЫЙ`   — паспорт есть, но в нём нет обязательного поля или дата не разбирается.
                        КРАСНО: полупаспорт хуже отсутствия, он выглядит доказательством.
  • `ЗАМЕР ПРОТУХ`    — замер назван, но снят раньше горизонта своего рода. КРАСНО.
  • `ЗАМЕРА НЕТ`      — паспорт честно говорит «замера нет». НЕ КРАСНО, и это СОЗНАТЕЛЬНО:
                        задание Штаба 06.09 прямо запрещает менять значение без замера, а
                        значит запрещает и красить его в аварию. Замок против побега в эту
                        ветку — ХРАПОВИК СЧЁТА в тесте: число таких порогов не смеет расти.
  • `НЕ ПОРОГ`        — паспорт объявляет, что число порогом не является (адрес темы, id).
                        Тоже под храповиком счёта.
  • `ЗАМЕР СВЕЖ`      — зелено.

ТРЕТИЙ ИСХОД ЕСТЬ И ЗДЕСЬ: файл не прочитан → `ПРОЧЕСТЬ НЕ СМОГЛИ`, и это КРАСНО, а не
«значит порогов там нет». Молчание источника исправностью не является — то же правило, что
у слоя ожиданий О1-О4.

────────────────────────────────────────────────────────────────────────────────────────────
ГОРИЗОНТ ПРОТУХАНИЯ — САМ ПОРОГ, И У НЕГО ТОЖЕ ЕСТЬ ПАСПОРТ (см. `HORIZON_LATENCY_DAYS`).
Иначе проверяющий стоял бы на круглом числе, запрещая круглые числа.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Не правит значений, не ходит в сеть, не читает диск САМ (текст
подают руки — `threshold_ledger_run.py` и тест), не судит, ХОРОШ ли порог: паспорт доказывает
только то, что число НЕ МОЛЧИТ о своём основании. Порог с честным паспортом «замера нет»
остаётся невыясненным — но перестаёт быть невидимым, а это разные вещи.

ОХВАТ НАЗВАН И СЧИТАН ВСЛУХ (`UNCOVERED_NOTE`): вне охвата остаётся `pc_orchestrator.py`
целиком, кроме двух поимённо названных порогов, — 67 кандидатов. Молчаливого усечения здесь
нет ни одного: непокрытое обязано быть НАЗВАНО ЧИСЛОМ, иначе «покрыто 100 %» читается как
«покрыто всё».
"""

