AGENT_LOCK = os.path.join(REPO, "pc_agent.lock")
AGENT_SRC = "pc_agent.py"
# Замыкание кнопки по ВРЕМЕНИ — ровно один файл: тот, чей код ЖИВЁТ В ПАМЯТИ живого процесса.
BUTTON_CLOSURE = (AGENT_SRC,)
# Где в исходнике агента лежит разбор `exam:`-колбэков. Вынимается ТЕКСТОМ, а не импортом:
# `import pc_agent` затащил бы сюда живого бота с его конфигом, а нужна ровно одна строка.
def _agent_parse_re(name):
    """Поиск строки разбора с ИМЕНЕМ `name` в исходнике агента. Имя — целым словом: разбор живого
    набора не должен находиться поиском разбора тренажёра и наоборот."""
    return re.compile(r"""\b%s\s*=\s*re\.compile\(\s*r?(['"])(.+?)\1""" % re.escape(name))


def card_callbacks(case_id, shot=None):
    """Все `callback_data`, которые НАПЕЧАТАЕТ карточка этого снимка (порядок кнопок сохранён).

    Один источник с отправкой — `markup`. Второй перечень токенов литералами разъехался бы с
    печатью молча, и замок зеленел бы на кнопках, которых в карточке уже нет."""
    rows = markup(case_id, shot)["inline_keyboard"]
    return [b["callback_data"] for row in rows for b in row]


def agent_parse(src_path=None, read_fn=None, name=None):
    """Разбор `exam:` ЖИВОГО агента, вынутый из его исходника → (скомпилированное|None, словами).

    None — «сверять не с чем», и это НЕИЗВЕСТНО, а не разрешение: исчезнувший `EXAM_CB_RE`
    значит «разбор переехал», а переехавший разбор мы не знаем.

    `name` — имя разбора; по умолчанию разбор ТЕКУЩЕГО набора (`AGENT_CB_NAME`)."""
    name = name or AGENT_CB_NAME
    path = src_path or os.path.join(REPO, AGENT_SRC)
    try:
        if read_fn is not None:
            text = read_fn(path)
        else:
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read()
    except OSError as e:
        return None, "исходник агента (%s) не прочитан (%s) — чем он разбирает тап, не видно" % (
            os.path.basename(path), type(e).__name__)
    m = _agent_parse_re(name).search(text)
    if m is None:
        return None, ("в «%s» нет `%s` — разбор кнопки переехал, и сверять карточку "
                      "не с чем" % (os.path.basename(path), name))
    try:
        return re.compile(m.group(2)), m.group(2)
    except re.error as e:
        return None, "разбор агента «%s» не компилируется (%s) — судить нечем" % (m.group(2), e)


def agent_carries_button(lock_path=None, mtime_fn=None, files=None, callbacks=None,
                         src_path=None, read_fn=None):
    """Разберёт ли ЖИВОЙ pc_agent кнопки ЭТОЙ карточки? → (исход, строка словами).

    исход: True — разберёт все; False — точно не разберёт; None — проверить нечем (НЕИЗВЕСТНО).

    ДВА ЗАМКА ПОДРЯД, порядок обязателен (см. шапку раздела):
    1) ВРЕМЯ — mtime `pc_agent.py` против момента рождения процесса. Python читает исходник один
       раз, на импорте, поэтому файл новее рождения процесса в его память не попадал;
    2) СОДЕРЖИМОЕ — каждый `callback_data` карточки против разбора из того же исходника. Законно
       только после (1): иначе сверка идёт с кодом, которого в процессе нет.
    `callbacks=None` — «карточка не предъявлена», исход НЕИЗВЕСТНО (показ запрещён)."""
    import proc_identity
    rec = proc_identity.read_lock(lock_path or AGENT_LOCK)
    if rec is None:
        return None, "лока pc_agent нет — жив ли агент и какой код несёт, отсюда не видно"
    if not rec.get("pid"):
        return None, "лок pc_agent без номера процесса — судить нечем"
    started = rec.get("started")
    if started is None:
        return None, "в локе pc_agent нет момента старта (старый формат) — судить нечем"
    pid = rec.get("pid")
    getm = mtime_fn or (lambda p: os.path.getmtime(p))
    newest, name = None, ""
    for f in (files or BUTTON_CLOSURE):
        try:
            m = getm(os.path.join(REPO, f))
        except OSError:
            continue
        if newest is None or m > newest:
            newest, name = m, f
    if newest is None:
        return None, "не прочитал mtime ни одного файла кнопки — судить нечем"
    if newest > started:
        lag = int(newest - started)
        return False, (
            "живой агент (pid %s) СТАРШЕ кода кнопки на %d с: файл «%s» правлен после его старта. "
            "Тап по такой кнопке вернёт «карточка устарела» и пропадёт — так было 05.09 в 10:29. "
            "Цена снятия: владелец шлёт агенту в тему 205 одно слово «обновись» (он сам делает "
            "git pull и перезапускает себя), после чего показ пойдёт" % (pid, lag, name))
    if not callbacks:
        return None, ("карточка не предъявлена (кнопок на сверку 0) — какие колбэки поедут "
                      "наружу, отсюда не видно; назови кейс (--case N)")
    rx, parse_words = agent_parse(src_path, read_fn)
    if rx is None:
        return None, parse_words
    cbs = list(callbacks)
    bad = [t for t in cbs if not rx.match(str(t))]
    if bad:
        return False, (
            "разбор живого агента (pid %s) НЕ принимает %d из %d колбэков карточки: %s. "
            "Его разбор — «%s»; тап по такой кнопке агент сочтёт чужим и МОЛЧА не донесёт до "
            "двери. Цена снятия: правка разбора в «%s», затем «обновись» агенту в тему 205" % (
                pid, len(bad), len(cbs), ", ".join("«%s»" % t for t in bad),
                parse_words, AGENT_SRC))
    return True, (
        "живой агент (pid %s) стартовал позже правки «%s» И разбирает ВСЕ её колбэки, числом %d "
        "(разбор «%s») — кнопки он поймёт" % (pid, name, len(cbs), parse_words))


def reach_as_moderbot(chat_id=None):
    """Виден ли чат МОДЕРБОТУ → (ok, строка словами). ЧТЕНИЕ (`getChat`), не отправка.

    Зачем вторая проба рядом с `dispatch_notify.chat_reachable`. Отказ «chat not found» у нашего
    бота имеет ДВЕ причины, и лечатся они по-разному: (1) бот не добавлен в группу — владелец
    добавляет его одним движением; (2) номер группы протух — группа могла стать супергруппой, и
    тогда добавлять некого, надо брать новый номер. Одним ботом их не различить, двумя — можно:
    модербот в этой группе ЖИВЁТ (он ставит там панель кнопок), и если номер видит он, а мы нет,
    то причина ровно первая.

    Токен берёт `suggest`, который и так читает конфиг, — мы его не читаем, не логируем и не
    печатаем (тот же приём, что у `pc_orchestrator._moderation_reply_send`). Двух `getUpdates` не
    создаём: `getChat` — чтение, с живым поллером модербота оно не конфликтует."""
    import urllib.error
    import urllib.request

    import suggest
    token = (getattr(suggest, "MODERBOT_TOKEN", "") or "").strip()
    if not token:
        return None, "MODERBOT_TOKEN пуст — этой пробой судить нечем"
    data = json.dumps({"chat_id": str(chat_id if chat_id is not None else TRAINER_CHAT)})
    req = urllib.request.Request("https://api.telegram.org/bot" + token + "/getChat",
                                 data=data.encode("utf-8"),
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            body = json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        try:
            body = json.loads(e.read().decode("utf-8"))
        except Exception:                                                  # noqa: BLE001
            body = {"ok": False, "description": "HTTP %s" % getattr(e, "code", "?")}
    except Exception as e:                                                 # noqa: BLE001
        return None, "проба не состоялась (%s)" % type(e).__name__
    if body.get("ok"):
        res = body.get("result") or {}
        return True, "чат виден модерботу: «%s» (%s)" % (
            res.get("title") or res.get("id"), res.get("type") or "?")
    return False, "модерботу тоже нет: code=%s %s" % (
        body.get("error_code"), str(body.get("description", ""))[:120])


