# ПОЧЕМУ ЗАМОК ПРОБЫ ЕЁ НЕ ОСТАНОВИЛ. `dispatch_notify.probe_verdict` судит по КАТАЛОГУ точки
# входа, а этот файл лежит в корне репозитория — то есть по признаку он боевой вход. Признак
