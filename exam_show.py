# Всё, что переключает набор. Одним перечнем — чтобы набор (и любой, кто переключал модуль в
# процессе) мог вернуть РОВНО то, что было, а не половину: половина и была прежним дефектом.
SET_FIELDS = ("CASES", "SHOTS_DIR", "VERDICTS", "SESSION", "LESSON_PATH", "HEAD_LESSON_PATH",
              "SET_NAME", "CB_HEAD", "AGENT_CB_NAME")


def set_state():
    """Текущие значения `SET_FIELDS` → dict (для возврата через `restore_set`)."""
    return dict((k, globals()[k]) for k in SET_FIELDS)


def restore_set(state):
    globals().update(dict((k, state[k]) for k in SET_FIELDS if k in state))


def use_live_set():
    """Переключить модуль на живой набор: корпус, снимки, журнал вердиктов, стол, база уроков,
    голова кнопок. Повторный вызов ничего не сдвигает (база головы не затирается базой набора)."""
    global CASES, SHOTS_DIR, VERDICTS, SESSION, LESSON_PATH, HEAD_LESSON_PATH
    global SET_NAME, CB_HEAD, AGENT_CB_NAME
    if SET_NAME != SET_LIVE:
        HEAD_LESSON_PATH = LESSON_PATH
    CASES, SHOTS_DIR = LIVE_CASES, LIVE_SHOTS
    VERDICTS, SESSION, LESSON_PATH = LIVE_VERDICTS, LIVE_DESK, LIVE_LESSONS
    SET_NAME, CB_HEAD, AGENT_CB_NAME = SET_LIVE, LIVE_CB_HEAD, LIVE_AGENT_CB_NAME


def main(argv=None):
    # ЛАНЕВОЙ ШОВ ВЫВОДА. Модуль импортировал `io_utf8` с первого дня, но НЕ ЗВАЛ его ни разу —
    # то есть шов был объявлен и не включён. Цена именно у этой двери выше обычной: её вывод
    # читает `pc_agent` субпроцессом, и любой из эмодзи ответа (⛔ ✅ 📝 🎓) на cp1251-консоли
    # уронил бы печать ПОСЛЕ того, как вердикт уже лёг на диск, — владелец увидел бы трассу
    # вместо расписки о записанном вердикте.
    io_utf8.force_utf8()
    a = build_parser().parse_args(argv)
    if a.live:
        if any(getattr(a, k) for k in LIVE_CLOSED):
            print(LIVE_REFUSED)
            return 2
        use_live_set()
        # КЕЙСА НЕТ В НАБОРЕ — ДВЕРИ ЕМУ НЕ ОТКРЫВАЮТСЯ (17.09.2026, задание 63-q). Откат набора по
        # источнику (`exam_set.py --rollback`) оставляет снимки откаченных кейсов на диске нетронутыми;
        # без этой строки `--card` отдал бы карточку кейса, которого в наборе больше нет.
        if a.case and find_case(a.case)[0] is None:
            print(LIVE_GONE % a.case)
            return 1
    if a.own_text:
        # ТЕКСТ ЕДЕТ ЧЕРЕЗ stdin, А НЕ ЧЕРЕЗ argv, и это не вкусовщина: правило владельца — живая
        # кириллица произвольной длины, а argv на Windows ходит через кодировку консоли и коверкает
        # её молча (класс известен полосе по журнальному писателю). stdin с явным utf-8 не коверкает.
        ok, msg = own_take(sys.stdin.read(), a.who)
        print(msg)
        return 0 if ok else 1
    if a.trace:
        print(trace())
        return 0
    if a.reach:
        import dispatch_notify
        ok, why = dispatch_notify.chat_reachable(TRAINER_CHAT)
        print("НАШ БОТ (AGENT_BOT_TOKEN): %s (%d) — %s" % (
            "ДОСТУПНА" if ok else "НЕДОСТУПНА", TRAINER_CHAT, why))
        mok, mwhy = reach_as_moderbot()
        print("МОДЕРБОТ (контроль):       %s — %s" % (
            {True: "ДОСТУПНА", False: "НЕДОСТУПНА", None: "НЕИЗВЕСТНО"}[mok], mwhy))
        if not ok and mok is True:
            print("⇒ номер группы ЖИВОЙ, а нашего бота в ней НЕТ: лечится добавлением бота.")
        elif not ok and mok is False:
            print("⇒ группу не видит НИ ОДИН бот: номер протух (супергруппа?) — добавлять некого.")
        return 0 if ok else 1
    if a.agent:
        # Проба повторяет ЖИВОЙ путь показа: токены строятся по тому же снимку, что уедет наружу.
        # Без `--case` карточки нет — и замок честно отвечает НЕИЗВЕСТНО, а не «ДА».
        shot = load_shot(a.case) if a.case else None
        cbs = card_callbacks(a.case, shot) if shot is not None else None
        if a.case and shot is None:
            print("⛔ сохранённого черновика кейса %s нет — сверять нечего." % a.case)
            return 1
        carries, why = agent_carries_button(callbacks=cbs)
        print("%s — %s" % ({True: "ДА", False: "НЕТ", None: "НЕИЗВЕСТНО"}[carries], why))
        if cbs:
            print("колбэки карточки (%d): %s" % (len(cbs), ", ".join(cbs)))
        return 0 if carries else 1
    if a.rollback:
        ok, msg = rollback(a.rollback, who=a.who)
        print(msg)
        return 0 if ok else 1
    for key, door in (("tap", None), ("toggle", toggle), ("apply", apply_marked),
                      ("own", own_start)):
        if not getattr(a, key):
            continue
        if not a.case:
            print("⛔ кейс не назван (--case N) — ничего не записано.")
            return 2
        if key == "tap":
            ok, msg = tap(a.case, a.tap, a.who)
        elif key == "toggle":
            ok, msg = toggle(a.case, a.toggle, a.who)
        else:
            ok, msg = door(a.case, a.who)
        print(msg)
        return 0 if ok else 1
    if not a.case:
        print("⛔ кейс не назван (--case N). Умолчания нет: один кейс на экран — это правило.")
        return 2
    if a.freeze:
        ok, where, shot = freeze(a.case)
        print(("✅ черновик кейса %s собран и сохранён: %s" % (a.case, where)) if ok
              else "⛔ черновик не собран: %s" % where)
        # ИСХОД КРУГА КРИТИКА — СРАЗУ, А НЕ ПРИ ПОКАЗЕ. Собирающий видит ту же новость, что увидит
        # владелец сутки спустя, и видит её в ту минуту, когда ещё может позвать круг заново.
        if ok and shot:
            print(critic_line(shot))
            print(owner_cards_line(shot))
        return 0 if ok else 1
    if a.slots:
        slots = shot_slots(a.case)
        if not slots:
            print("слотов кейса %s нет ни одного — сперва --freeze." % a.case)
            return 1
        print("слотов кейса %s: %d (новейший первым)" % (a.case, len(slots)))
        for i, (path, shot) in enumerate(slots):
            print("%s %s · коммит %s · корпус %s · собран %s" % (
                "→" if i == 0 else " ", os.path.basename(path), shot.get("commit") or "?",
                shot.get("corpus") or "?", shot.get("built_at") or "?"))
        return 0
    if a.card:
        shot = load_shot(a.case)
        if shot is None:
            print("⛔ сохранённого черновика кейса %s нет — сперва --freeze." % a.case)
            return 1
        print(card_text(shot, len(shot_slots(a.case))))
        return 0
    if a.show:
        ok, msg = show(a.case)
        print(msg)
        return 0 if ok else 1
    print("⛔ не назван ни один ключ действия (--freeze / --show / --card / --tap / --rollback).")
    return 2


if __name__ == "__main__":
    sys.exit(main())
