# ТРИ ЗАМКА ОТ СМЕШЕНИЯ:
#   1. голова эталона НЕ ВИДИТ: `freeze` отдаёт раннеру кейс БЕЗ поля `reference` — иначе бот
#      списал бы ответ, по которому его судят, и сравнение мерило бы копирование;
#   2. критику эталон не передаётся: подсказки остаются теми же, что у кнопки «🎓 Обучить»;
#   3. в карточке эталон стои́т СВОИМ блоком с пометкой «ответ человека», ПОСЛЕ блока бота, и с
#      `draft` не склеивается ни одной веткой.
# Снимок без поля (все снимки основного набора) показывается БАЙТ В БАЙТ как прежде: блока нет.
REFERENCE_KEY = "reference"
REFERENCE_FIELDS = ("who", "text", "mark", "parts", "gap_sec", "base")


def reference_of(case):
    """Эталон кейса → dict для снимка | None (поля у кейса нет — эталона не заявляли).

    Поле ЕСТЬ, а текста нет — отдаётся dict с пустым текстом, а не None: «эталона не заявляли» и
    «заявили, а сцепить не смогли» — разные новости, и карточка говорит их разными словами."""
    if REFERENCE_KEY not in (case or {}):
        return None
    ref = case.get(REFERENCE_KEY)
    ref = ref if isinstance(ref, dict) else {}
    out = dict((k, ref[k]) for k in REFERENCE_FIELDS if k in ref)
    out["who"] = str(ref.get("who") or "менеджер")
    out["text"] = str(ref.get("text") or "").strip()
    return out


def reference_block(shot):
    """Эталон человека в карточке → строка. Поля в снимке нет — '' (блока нет вовсе).

    Пустой текст при поле — слова «не сцеплен», а не пустой блок: эталон не выдумывается."""
    if REFERENCE_KEY not in (shot or {}):
        return ""
    ref = shot.get(REFERENCE_KEY)
    ref = ref if isinstance(ref, dict) else {}
    text = str(ref.get("text") or "").strip()
    if not text:
        return ("👤 ЭТАЛОН — ОТВЕТ ЧЕЛОВЕКА: ответ менеджера на этот вопрос в базе НЕ сцеплен — "
                "сравнивать не с чем, выдумывать его не стали.")
    where = ", ".join(x for x in (str(ref.get("mark") or ""),
                                  ("база %s" % ref["base"]) if ref.get("base") else "") if x)
    return ("👤 ЭТАЛОН — ОТВЕТ ЧЕЛОВЕКА (%s, тогда%s). Это НЕ ответ бота, бот его не видел:\n%s" % (
        ref.get("who") or "менеджер", (", " + where) if where else "", text))


def freeze(case_id, cases_path=None, runner=None, now=None, ph=None, critic=None):
    """Собрать черновик кейса ОДИН раз и положить на диск. → (ok, путь|причина, shot|None).

    ЕДИНСТВЕННАЯ ветка модуля, зовущая голову. Уже лежащий черновик НЕ перезаписывается НИ ОДНОЙ
    веткой: иначе «покажи ещё раз» молча меняло бы судимый текст — ровно то, от чего модуль и
    заведён. Отказ считается ПО КОММИТУ (12.09.2026): слот этого коммита уже собран — второй раз
    голову не зовём; коммит другой — это ДРУГОЙ ПРОДУКТ, и ему положен свой слот рядом со старым.
    Старые слоты не трогаются и не удаляются никогда.

    ОКНО ДАТ (`ph`) БЕРЁТСЯ ОДИН РАЗ И ИДЁТ В ОБА МЕСТА — голове (через `run_case`) и в записанный
    вопрос (через `trainer_run.substitute`). Два отдельных вызова `placeholders()` разъехались бы
    на границе суток и месяца, и снимок хранил бы вопрос, которого голова не видела. Замер
    12.09.2026, кейс 1: в снимке лежала СЫРАЯ строка корпуса `…XMAX 300 {when_sloppy}…`, а в ответе
    головы стояли сами даты «с 6 по 11 октября» — владельцу показали шаблон вместо вопроса.

    `ph` доводом, а не только изнутри: с подставленным `runner` (набор) живое окно считать нечем и
    незачем — `placeholders()` ходит за живой таблицей периодов ради `when_cross`."""
    case, total = find_case(case_id, load_cases(cases_path))
    if case is None:
        return False, "кейса %s в корпусе нет (всего %d)" % (case_id, total), None
    commit = head_commit()
    for path, shot in shot_slots(case_id):
        if str(shot.get("commit") or "") == commit or not commit:
            return False, ("черновик кейса %s на коммите %s уже собран: %s (перезаписи нет по "
                           "построению)" % (case_id, shot.get("commit") or "?", path)), shot
    target = shot_path(case_id, commit)
    # ЛОВУШКА КАРТОЧЕК ВЛАДЕЛЬЦУ стоит ДО первого импорта пути ответа и снимается в `finally` при
    # любом исходе круга (узел «ЛОВУШКА КАРТОЧЕК» выше). Не встала — голову не зовём.
    trap = owner_card_trap()
    try:
        trap.__enter__()
    except Exception as e:                                                  # noqa: BLE001
        return False, ("ловушка карточек владельцу не встала (%s: %s) — голову не зову: карточка "
                       "третьего исхода ушла бы владельцу вживую" % (type(e).__name__, e)), None
    try:
        import trainer_run                               # ленивый импорт: тянет suggest и сеть

        if ph is None:
            ph = trainer_run.placeholders()
        if runner is None:
            def runner(c):
                return trainer_run.run_case(c, ph)
        # ГОЛОВА И КРИТИК ВИДЯТ КЕЙС БЕЗ ЭТАЛОНА (замок 1 узла «ЭТАЛОН»): поле вырезается здесь,
        # до первого чужого вызова, а в снимок эталон кладётся из ПОЛНОГО кейса ниже.
        head_case = dict((k, v) for k, v in case.items() if k != REFERENCE_KEY)
        rec = runner(head_case)
        draft = (rec.get("draft") or "").strip()
        if not draft:
            return False, "голова не дала черновика (%s) — показывать нечего" % (
                rec.get("unknown") or "причина не названа"), None
        raw = question_of(case)
        question = trainer_run.substitute(raw, ph)
        # ПОДСКАЗКИ РОЖДАЮТСЯ ЗДЕСЬ И БОЛЬШЕ НИГДЕ. Критику дан ТОТ ЖЕ транскрипт, который видела
        # голова (`build_transcript` — чистая функция, головы не зовёт), и ЗАМОРОЖЕННЫЙ черновик.
        #
        # ОТКАЗ КРИТИКА НЕ ОТМЕНЯЕТ СНИМКА, и это выбор, а не халатность: круг головы за черновик
        # уже заплачен, а снимок без подсказок — законный снимок (`NO_HINTS`), который показывается
        # и судится как все, собранные до 12.09. Уронить его из-за молчания критика значило бы
        # выбросить оплаченный ответ и заставить платить второй раз.
        # МЕТКИ ЖИВЫХ ПРИМЕРОВ, которые видела голова (задание 51-b). Транскрипт тот же, что у
        # головы и у критика — `build_transcript` чистая функция от (case, ph), и второй её вызов
        # даёт тот же текст. Подбор детерминирован, поэтому метки здесь — те самые, что стояли в
        # промпте, а не похожие. Пусто — законный исход («примеров ниже порога нет»), а не поломка.
        transcript = trainer_run.build_transcript(head_case, ph)
        try:
            import suggest
            examples = suggest.live_examples_marks(transcript)
        except Exception as e:                                              # noqa: BLE001
            print("метки примеров снять не удалось (%s) — снимок кладём без них" % type(e).__name__)
            examples = []
        # ИСХОД КРУГА КРИТИКА — ОТДЕЛЬНЫМ ПОЛЕМ СНИМКА, и полей исхода три, а не одно (52-b).
        # Подставленный критик (набор) отдаёт ПРОСТО СПИСОК — тогда отчёт собирается здесь из
        # того, что видно: сколько подсказок вышло. Живой отдаёт ПАРУ (подсказки, отчёт) и кладёт в
        # отчёт то, чего отсюда не видно ни одной веткой: сколько ждали и какой длины был ответ.
        # Разделяет их ТИП, а не длина: список из двух подсказок — тоже последовательность из двух.
        hints, report = [], None
        try:
            got = _call_critic(critic or _default_critic, question, draft, transcript,
                               case.get("id"))
            if isinstance(got, tuple):
                got, report = got
            hints = hints_of({"hints": got})
        except Exception as e:                                              # noqa: BLE001
            print("критик подсказок не дал (%s) — снимок кладём без них" % type(e).__name__)
            report = critic_report([], error=type(e).__name__, limit=CRITIC_TIMEOUT)
        if report is None:
            report = critic_report(hints, limit=CRITIC_TIMEOUT)
        shot = {
            "case": case.get("id"), "total": total, "name": case.get("name") or "",
            "lang": case.get("lang") or "", "question": question,
            "question_raw": raw,
            "draft": draft, "note": rec.get("note") or "", "hints": hints,
            "critic": report,
            "examples": examples,
            "corpus": corpus_fingerprint(cases_path), "commit": commit,
            "rules": head_rules_version(), "built_at": stamp(now),
            # КАРТОЧКИ ВЛАДЕЛЬЦУ, пойманные ловушкой на этом круге, — рядом с ответом, дословно.
            # Пустой список — «ловушка стояла, карточек не было»; поля нет — снимок старше ловушки.
            OWNER_CARDS_KEY: [dict(c) for c in trap.cards],
        }
        # ЭТАЛОН — ТОЛЬКО когда кейс его заявил: снимки основного набора ключа не получают, и их
        # состав полей остаётся прежним.
        if REFERENCE_KEY in case:
            shot[REFERENCE_KEY] = reference_of(case)
        os.makedirs(SHOTS_DIR, exist_ok=True)
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            json.dump(shot, f, ensure_ascii=False, indent=2, sort_keys=True)
            f.write("\n")
        return True, target, shot
    finally:
        trap.__exit__(None, None, None)


