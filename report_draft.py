# -*- coding: utf-8 -*-
"""
report_draft.py — ЧЕРНОВИК ДОКЛАДА ЗАХОДА: слова самого исполнителя, уцелевшие при обрыве.

ЗАЧЕМ (класс 22.08.2026, замер ночи 21→22.08). Итоговый отчёт headless живёт РОВНО в одном месте —
в stdout ребёнка, который демон читает ОДНИМ `communicate()` в самом конце. На таймауте прогона
`run_claude` убивает ребёнка и его буфер ВЫБРАСЫВАЕТ (`p.communicate(timeout=30)`, возврат не
используется), поэтому отчёт, дописанный на 99%, стоит РОВНО НОЛЬ. Отсюда почерк, одинаковый у
двух живых задач:

    id=21 (22.08, 2700с): последний вызов инструмента на −63с, до него ВСЁ сдано — файл артефакта
          (−1083с), коммит и пуш (−514/−508с), запись в мозг (−496с), строка ARTIFACT в журнал
          (−170с), строка DONE (−63с). Убит на выдаче отчёта; владелец не получил ни слова.
    id=81 (21.08, 2700с): убит через 19.9с после коммита артефакта — тот же шаг, тот же исход
          (разбор: docs/artifacts/2026-08-21-task81-forensics.md).

Сам доклад при этом НЕ ДОРОГ: замер 41 закрытой задачи 20–22.08 даёт хвост «последний вызов →
отчёт в руках» медиана 57с · p90 88с · max 143с — это 2.1% и 5.3% потолка 2700с. Дорога не длина
доклада, а его НЕДЕЛИМОСТЬ: он атомарен, стои́т последним и при обрыве пропадает весь.

ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ. Даёт заходу второй, ДЕШЁВЫЙ канал доклада — обычный файл в
`tmp/pc_report/`, который заход пишет РАНО и обновляет по вехам (5–15 строк, одна правка).
Демон читает этот файл на КАЖДОМ исходе, где своих слов у захода не осталось: таймаут прогона,
ошибка запуска, пустой stdout, отсутствие строки RESULT, смерть карточки по таймауту
подтверждения. Три раздела заданы жёстко — «СДЕЛАНО», «НЕ СДЕЛАНО», «НЕИЗВЕСТНО»: это ровно те
три состояния знания, которых владельцу и не хватало, когда задача закрывалась одной фразой
«не закрыта, но в окне есть работа».

ЧИСТОТА (инвариант `REPORT_DRAFT_PURE`, замок в test_report_draft.py). Ни сети, ни секретов, ни
подпроцессов, ни БД. И НИЧЕГО НЕ УДАЛЯЕТ: черновик прошлого прогона не стирается, а отсекается
ИМЕНЕМ — в путь входит токен запуска, поэтому чужой файл прочитать нельзя по построению. Ровно
тот класс, на котором обожглись отметки старта (`pc_orchestrator.task_started.json`): очередь
переиспользует номера, и опознание «по номеру задачи» рано или поздно поднимает чужую запись.

ТРИ ИСХОДА ЧТЕНИЯ, а не два (контракт `parse_outcome`): черновика НЕТ · черновик ЕСТЬ и разобран ·
черновик ЕСТЬ, но разделов в нём не видно. Третий исход НЕ выдаётся за первый: «заход молчал» и
«я не смог прочитать» — разные новости, и вторая обязана называть себя.
"""

import io
import os
import re

# ── куда кладём. Место названо ЯВНО и одно: tmp/pc_report/ ────────────────────────────────────
# Каталог временный по смыслу, но НЕ по обращению: файлы отсюда — единственный уцелевший голос
# захода, и уборщика у них нет. Кап держит `pc_orchestrator` тем же способом, что у отметок
# старта (число файлов), а не удалением по возрасту из этого модуля.
DRAFT_REL_DIR = "tmp/pc_report"

HEAD_DONE = "СДЕЛАНО"
HEAD_NOT_DONE = "НЕ СДЕЛАНО"
HEAD_UNKNOWN = "НЕИЗВЕСТНО"
HEADS = (HEAD_DONE, HEAD_NOT_DONE, HEAD_UNKNOWN)

# Шапка блока в итоге задачи. Отдельным словом «ЧЕРНОВИК» сознательно: владелец обязан видеть,
# что читает промежуточную запись захода, а не его финальный отчёт (финального НЕТ — он пропал).
BLOCK_HEAD = "🧾 ЧЕРНОВИК ДОКЛАДА ЗАХОДА (его собственные слова, снятые с диска)"
ABSENT_NOTE = ("🧾 черновика доклада заход не оставил — его собственных слов нет ни одного "
               "(файл %s не найден)")
NONPARSE_NOTE = ("🧾 черновик доклада ЕСТЬ, но трёх разделов в нём не видно — отдаю как есть, "
                 "разбор не удался")
MISSING_NOTE = "не назван заходом"

BLOCK_MAX = 1500          # потолок блока в итоге: остаток RESULT_MAX нужен причине и уликам
RAW_MAX = 600             # сколько сырого текста отдаём при неразборе

_RE_STAMP = re.compile(r"<!--\s*pc_report\s+tid=(\S+)\s+token=(\S+)\s*-->")
# Заголовок раздела: «## СДЕЛАНО», «СДЕЛАНО:», «**НЕ СДЕЛАНО**» — заход пишет как удобно, читатель
# обязан узнать все три формы. Требование «ровно решётка и ровно два пробела» родило бы неразбор
# на пустом месте, а неразбор здесь стоит дороже вольности.
_RE_HEAD = re.compile(
    r"(?m)^\s{0,3}(?:#{1,6}\s*)?[*_`]{0,2}\s*(%s)\s*[*_`]{0,2}\s*:?\s*$"
    % "|".join(re.escape(h) for h in HEADS))


def draft_rel(tid, token):
    """Путь черновика ОТ КОРНЯ репо. Токен запуска в имени — замок от чужого файла: очередь
    переиспользует номера задач, и опознание по одному лишь номеру подняло бы прошлую жизнь
    этого id (живой класс отметок старта: у id=21 отметка была на 6.4 суток старше прогона)."""
    # Точка из токена выброшена НАМЕРЕННО вместе с прочим: одна разрешённая точка даёт «..» в
    # имени — из каталога это не выводит (разделителя нет), но читается как попытка и первым же
    # взглядом на путь порождает ложный диагноз. Замок — `test_gryaznyi_token_ne_uvodit_iz_kataloga`.
    safe = re.sub(r"[^0-9A-Za-z_-]", "-", str(token or "no-token"))
    return "%s/task%s-%s.md" % (DRAFT_REL_DIR, re.sub(r"\D", "", str(tid)) or "x", safe)


def draft_path(tid, token, root):
    """Абсолютный путь черновика. root передаём параметром — модуль про корень репо не знает."""
    return os.path.join(str(root), *draft_rel(tid, token).split("/"))


def _why(e):
    """Причина СЛОВАМИ. Обработчик, вернувший голую пустоту, — слепой читатель по счётчику
    `nonparse_scan`, и справедливо: «не смог» без причины неотличимо от «нечего было делать»."""
    return "%s: %s" % (type(e).__name__, e)


def ensure_dir(path):
    """Создать каталог черновика. → "" (каталог есть) | причина словами. Ничего не удаляет."""
    try:
        os.makedirs(os.path.dirname(str(path)) or ".", exist_ok=True)
        return ""
    except Exception as e:
        return _why(e)


def stamp(tid, token):
    """Шапка-штамп в первой строке файла: чей это черновик. Читателем НЕ требуется (замок — имя
    файла), но при разборе руками владелец видит принадлежность, не сверяя имя."""
    return "<!-- pc_report tid=%s token=%s -->" % (tid, token)


def clause(rel):
    """Абзац для промпта захода. Просим РАНО и КОРОТКО — это не второй отчёт, а страховка.

    Формулировка несёт ПРИЧИНУ («в stdout при обрыве пропадает целиком»), а не только приказ:
    исполнитель, знающий цену, пишет черновик по вехам сам, а не «когда попросят». Ровно тем же
    приёмом чинили абзац про NEEDS_APPROVAL — текст, обещавший кнопку, которой нет."""
    return (
        "\nЧЕРНОВИК ДОКЛАДА — ДЕШЁВО И РАНО (это НЕ отчёт и не артефакт): файл `%s`. Как только "
        "понял задание, положи туда три раздела — «## %s», «## %s», «## %s» — плюс строку "
        "«FACT: …». Дальше обновляй его ОДНОЙ правкой после каждой сданной вехи (правка легла · "
        "тесты прошли · артефакт записан): 5–15 коротких строк, без пересказа. ЗАЧЕМ: твой "
        "итоговый отчёт живёт только в stdout, и при обрыве по времени он пропадает ЦЕЛИКОМ — "
        "владелец получит вместо него ровно этот файл. Черновик финальный отчёт НЕ заменяет: "
        "сводку, блок FACT и последнюю строку «RESULT: …» пиши как прежде.\n"
        % (rel, HEAD_DONE, HEAD_NOT_DONE, HEAD_UNKNOWN))


def read(path):
    """→ (текст | None, причина). None — «НЕ ПРОЧИТАЛ», пустая строка — «прочитал, там пусто».

    Разница не педантичная: файла нет = заход не успел ни строки (законный исход), а вот отказ
    диска = наша слепота, и выдавать её за молчание захода нельзя. Ровно тот же третий исход,
    что держит контракт `parse_outcome`."""
    try:
        with io.open(str(path), "r", encoding="utf-8", errors="replace") as fh:
            return fh.read(), ""
    except Exception as e:
        return None, _why(e)


def sections(text):
    """Текст → {раздел: тело}. Только НАЗВАННЫЕ разделы; ненайденные в словарь не попадают —
    «пусто» и «не назван» тут разные вещи, и склеивать их нельзя."""
    s = "" if text is None else str(text)
    marks = [(m.start(), m.end(), m.group(1)) for m in _RE_HEAD.finditer(s)]
    out = {}
    for i, (st, en, name) in enumerate(marks):
        stop = marks[i + 1][0] if i + 1 < len(marks) else len(s)
        body = s[en:stop].strip()
        if name not in out or body:
            out[name] = body
    return out


def missing(text):
    """Каких из трёх разделов заход не назвал → кортеж имён (порядок как в HEADS)."""
    got = sections(text)
    return tuple(h for h in HEADS if h not in got)


def render(text, path_rel="", why="", block_max=BLOCK_MAX, raw_max=RAW_MAX):
    """Черновик → (исход, блок для итога). Исход — одно из трёх слов контракта читателя.

      • "absent"   — файла нет / пуст: блок называет это прямо, чтобы «молчал» не читалось
                     как «я не смотрел»;
      • "parsed"   — разделы найдены: отдаём их, ненайденный называем словами MISSING_NOTE;
      • "nonparse" — текст есть, разделов нет: отдаём сырую голову с пометкой.

    Блок режется по `block_max` — остаток RESULT_MAX нужен причине провала и уликам; при
    урезании тела раздела ставим «…»."""
    s = ("" if text is None else str(text)).strip()
    s = _RE_STAMP.sub("", s).strip()
    if not s:
        note = ABSENT_NOTE % (path_rel or DRAFT_REL_DIR)
        # Причина отказа чтения (если была) едет в текст: «файла не было» и «диск не дал прочесть»
        # — разные новости, и вторую нельзя выдавать за молчание захода.
        return "absent", (note + " [чтение: " + why + "]") if why else note
    got = sections(s)
    if not got:
        head = s[:raw_max]
        if len(s) > raw_max:
            head += "…"
        return "nonparse", "%s: %s" % (NONPARSE_NOTE, " ".join(head.split()))
    parts = []
    for h in HEADS:
        body = got.get(h)
        if body is None:
            parts.append("%s — %s" % (h, MISSING_NOTE))
        else:
            parts.append("%s: %s" % (h, " ".join(body.split()) or "пусто (раздел назван, тела нет)"))
    block = "%s. %s" % (BLOCK_HEAD, " · ".join(parts))
    if len(block) > block_max:
        block = block[:max(1, block_max - 1)].rstrip() + "…"
    return "parsed", block
