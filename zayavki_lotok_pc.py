from __future__ import annotations

import zayavki_route_pc as route

SCHEMA = "turbobaby.zayavki_lotok_pc/v1"

# Каталог лотка. Имя, а не путь: путь это уже диск, и его собирают руки.
# Сосед по `docs/` — `docs/review_inbox`, лоток ревью, с которого списан образец.
LOTOK_DIR = "docs/zayavki_lotok"

# Рубильник ступени. Поднят — заявка идёт ПРЕЖНИМ путём (ряд + карточка), байт-в-байт.
OFF_FLAG = "ZAYAVKI_LOTOK_PC_OFF"

UNKNOWN = "НЕИЗВЕСТНО"

# Разделитель шапки и дословного текста заявки. Литерал, а не догадка по разметке:
# по нему `claim_text_of` возвращает тело ОБРАТНО, и по нему же счёт маркеров
# получает ровно ту строку, которая иначе стояла бы в `task_text` ряда.
BODY_MARK = "## ТЕКСТ ЗАЯВКИ ДОСЛОВНО"

HEAD = "# ЗАЯВКА В ЛОТКЕ — РЯДА ОЖИДАНИЯ НЕ СОЗДАВАЛОСЬ"

# Слова, которыми файл лотка объясняет СЕБЯ тому, кто откроет его руками. Они не
# утверждают ничего о доставке: маршрут наблюдает СВОЁ решение, а судьбу чужих
# сообщений — нет (тот же урок, что снял отрицание карточки в `zayavki_route_pc`).
EXPLAIN = (
    "ЧТО ЭТО ЗНАЧИТ: по этой заявке НЕ создавалось ряда `needs_approval` — значит "
    "владельцу не показывали кнопку и никто не ждёт его ответа, чтобы работать "
    "дальше. Заявка не потеряна: она лежит здесь целиком, видна строкой в списке "
    "и числом на витрине. Ничего не удалено и не закрыто за владельца."
)


def informational(row, owner_work=None, enabled=True):
    """Ряд, который СОБИРАЮТСЯ поставить → вердикт маршрута. → dict.

    Своего различителя здесь нет ни одной строкой: зовём
    :func:`zayavki_route_pc.decide` — тот самый, которым полоса уже судит род и
    «держит ли работу». Поля возврата и правила отказа — его.
    """
    return route.decide(row, owner_work=owner_work, enabled=enabled)


def row_of(text, frm=""):
    """Текст будущей заявки + её ``from`` → ряд для различителя. → dict.

    ``from`` называется ЯВНО, потому что второй признак судит именно по нему, а
    выведенное из маркера значение слабее настоящего (`zayavki_route_pc.from_of`).
    """
    got = {"task_text": str(text or ""), "status": "needs_approval"}
    if str(frm or "").strip():
        got["from"] = str(frm).strip()
    return got


def file_name(day, key):
    """День и ключ заявки → имя файла лотка. → str.

    Форма списана с лотка ревью: дата спереди, чтобы каталог сортировался
    временем, ключ следом, чтобы одна заявка не легла дважды под разными именами.
    """
    safe = "".join(ch if (ch.isalnum() or ch in "-_") else "-" for ch in str(key or "no-key"))
    return "%s-%s.md" % (str(day or "0000-00-00"), safe[:64] or "no-key")


def file_text(text, verdict, stamp, day=""):
    """Текст заявки + вердикт → СОДЕРЖИМОЕ файла лотка. → str.

    Шапка машинная (её читает :func:`parse_file`), тело — ДОСЛОВНЫЙ текст заявки
    после :data:`BODY_MARK`. Пересказа тела в шапке нет: пересказ разошёлся бы с
    оригиналом молча, а оригинал здесь же, ниже.
    """
    d = verdict if isinstance(verdict, dict) else {}
    lines = [HEAD, "",
             "schema: `%s`" % SCHEMA,
             "положена: %s" % (stamp or UNKNOWN),
             "день: %s" % (day or UNKNOWN),
             "род: `%s` (%s)" % (d.get("kind") or UNKNOWN, d.get("how") or UNKNOWN),
             "from: `%s` (%s)" % (d.get("from") or UNKNOWN, d.get("from_how") or UNKNOWN),
             "почему не ряд: %s" % (d.get("why") or UNKNOWN),
             "", EXPLAIN, "", BODY_MARK, "", str(text or "")]
    return "\n".join(lines)


def parse_file(text):
    """Содержимое файла лотка → его поля. → dict.

    Разбор идёт по литералам шапки, а не по порядку строк: файл, дописанный
    руками, не обязан их сохранять. Поля, которых нет, называются
    :data:`UNKNOWN` — пустая строка читалась бы как измеренное «ничего».
    """
    got = str(text or "")
    out = {"schema": "", "at": UNKNOWN, "day": UNKNOWN, "kind": UNKNOWN,
           "from": UNKNOWN, "why": UNKNOWN, "claim": ""}
    for line in got.split("\n"):
        s = line.strip()
        if s.startswith("schema: "):
            out["schema"] = s[len("schema: "):].strip("` ")
        elif s.startswith("положена: "):
            out["at"] = s[len("положена: "):].strip() or UNKNOWN
        elif s.startswith("день: "):
            out["day"] = s[len("день: "):].strip() or UNKNOWN
        elif s.startswith("род: "):
            out["kind"] = s[len("род: "):].split("(")[0].strip("` ") or UNKNOWN
        elif s.startswith("from: "):
            out["from"] = s[len("from: "):].split("(")[0].strip("` ") or UNKNOWN
        elif s.startswith("почему не ряд: "):
            out["why"] = s[len("почему не ряд: "):].strip() or UNKNOWN
    out["claim"] = claim_text_of(got)
    return out


def claim_text_of(text):
    """Содержимое файла лотка → ДОСЛОВНЫЙ текст заявки. → str.

    Разделителя нет → пустая строка, а не весь файл: отдать шапку за текст
    заявки значило бы скормить счёту маркеров наши собственные слова.
    """
    got = str(text or "")
    idx = got.find(BODY_MARK)
    if idx < 0:
        return ""
    return got[idx + len(BODY_MARK):].lstrip("\n")


def queue_like(recs):
    """Записи лотка → ряды В ВИДЕ ОЧЕРЕДИ для ЧУЖИХ счётчиков маркеров. → list[dict].

    Ключевая функция всей правки, и вид возврата у неё не декоративный:
    ``review_intake.claim_markers`` и ``recon_auto.markers`` читают ``task_text``
    и матчат по нему СВОЮ регулярку. Отдав им лоток в этом виде, мы оставляем
    дедуп и суточный потолок ОДНИМ счётом на прежней регулярке — вместо того
    чтобы завести второй, который разойдётся с первым молча.
    """
    out = []
    for rec in (recs or []):
        text = str((rec or {}).get("claim") or "")
        if text:
            out.append({"task_text": text, "status": "лоток", "lane": "pc"})
    return out


def list_line(rec):
    """Запись лотка → ОДНА строка списка. → str.

    Чужого текста в строке нет ни слова: день, род, ``from``, наша причина и адрес
    файла. Полный текст лежит в файле, и строка на него УКАЗЫВАЕТ, а не
    пересказывает — тот же закон, что у указателя ступени D.
    """
    got = rec if isinstance(rec, dict) else {}
    return ("%s %s (%s) — ряда ожидания НЕ СОЗДАВАЛОСЬ; текст целиком: %s"
            % (got.get("day") or UNKNOWN, got.get("kind") or UNKNOWN,
               got.get("from") or UNKNOWN, got.get("rel") or UNKNOWN))


def day_rows(recs, today):
    """Записи лотка → записи ЗА НАЗВАННЫЙ ДЕНЬ, свежие первыми. → list[dict].

    Мерка — КАЛЕНДАРНЫЙ день из шапки, а не скользящие сутки: день кладёт в файл
    тот же код, который считает суточный потолок ступеней (``today_utc``), и
    вторая мерка тут разошлась бы с потолком.
    """
    day = str(today or "")
    out = [r for r in (recs or []) if str((r or {}).get("day") or "") == day]
    return sorted(out, key=lambda r: str(r.get("at") or ""), reverse=True)


def vitrina_lines(rows, ok=True, why="", limit=6):
    """Записи дня → строки витрины: ЧИСЛО отдельной строкой + список. → list[str].

    ЧИСЛА НОЛЬ ПО НЕЗНАНИЮ НЕ БЫВАЕТ — прямое требование задания. Лоток не
    прочитан → ``ok=False``, и строка говорит :data:`UNKNOWN` С ПРИЧИНОЙ: «в лотке
    0» читалось бы как измеренный факт и было бы неотличимо от честного тихого
    дня. Тот же закон, которым живёт единая дверь числа витрины.

    Список идёт ВТОРОЙ строкой и обрезан по ``limit`` с явным «и ещё N»:
    молчаливое усечение читается как «это всё».
    """
    if not ok:
        return ["ЗАЯВКИ В ЛОТКЕ за день: %s (%s)"
                % (UNKNOWN, why or "лоток не прочитан")]
    got = list(rows or [])
    # ЧИСЛО ЕДЕТ ВМЕСТЕ С ОГОВОРКОЙ, ЕСЛИ ОНА ЕСТЬ. Лоток бывает прочитан честно и
    # при этом пуст «по молодости» (каталога ещё нет — в него не клали ничего).
    # Это НЕ незнание, поэтому ноль тут законный; но и молчать о причине нельзя —
    # голый «0» читался бы как измеренный тихий день. Тот же приём, что у серии с
    # опорой: число без своей оговорки уже один раз врало молча.
    aside = (" · %s" % why) if why else ""
    head = ("ЗАЯВКИ В ЛОТКЕ за день: %d — ряда ожидания по ним не создавалось, "
            "владельцу кнопки не показывали (лежат в %s)%s" % (len(got), LOTOK_DIR, aside))
    if not got:
        return [head]
    shown = got[:limit]
    tail = " и ещё %d" % (len(got) - limit) if len(got) > limit else ""
    return [head, "  списком: %s%s" % ("; ".join(list_line(r) for r in shown), tail)]
