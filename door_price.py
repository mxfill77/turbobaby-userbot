# -*- coding: utf-8 -*-
"""door_price.py — ЦЕНА КЛИЕНТУ ЕСТЬ ЧИСЛО ЖИВОЙ ДВЕРИ, И БОЛЬШЕ НИЧЬЁ.

ОСНОВАНИЕ — решение владельца 12.09.2026, узел `business_rules`, блок
«РЕШЕНИЕ ВЛАДЕЛЬЦА 12.09.2026 — ЦЕНУ КЛИЕНТУ НАЗЫВАЕТ ЖИВОЙ ЛИСТ (ДВЕРЬ-ИСТОЧНИК-1209)».
Слово владельца дословно: «можно ориентироваться на этот лист». Это ПОПРАВКА к решению
17.08.2026 («источником цены служит ЗАПИСАННОЕ ПРАВИЛО, а не лист»): в части «откуда берётся
число, которое слышит клиент» та строка заменена этой.

ЧЕМ ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (`docs/artifacts/2026-09-12-cena-tri-chisla-sezon.md`):
на XMAX 300 нового поколения 06.10.2026→11.10.2026 живая дверь `quote_price` дала 704 ฿/сут и
3520 за 5 суток и сошлась с листом владельца ДО БАТА, а счёт по файлу `price_source.json` дал
682 — ступень корзины 4-6 в файле 1.03 против 1.0634 у самой двери; у ADV 350 к этому добавлена
низкая база 616 против листовых ≈704, и там промах уже −115 ฿/сут. На одной карточке из трёх
моделей недобор составил 765 ฿.

ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ:
  • ОТДАЁТ КЛИЕНТУ ТОТ ЖЕ ОБЪЕКТ, что вернула дверь (`client_quote` возвращает `res`, а не
    копию, — и это проверяется `assertIs`). Подмены нет НЕ ПО ОБЕЩАНИЮ, А ПО ПОСТРОЕНИЮ:
    ветки, которая писала бы в котировку число из файла, здесь не существует;
  • НАЗЫВАЕТ ТРЕТИЙ ИСХОД, когда дверь не ответила или ответила БЕЗ ЦЕНЫ: имя
    `KIND_DOOR_NO_PRICE` и записка `client_note`, в которой НЕТ НИ ОДНОЙ ЦИФРЫ и есть прямое
    требование сказать, что эту цену считает человек. Молчание запрещено наравне с выдумкой;
  • МЕРИТ РАСХОЖДЕНИЕ двери и файла на КАЖДОМ ответе с ценой и пишет его в журнал строкой от
    одного бата. Ответ при этом НЕ ОСТАНАВЛИВАЕТСЯ ни одной веткой — истина у двери, — но
    расхождение перестаёт быть молчаливым.

ЧЕГО НЕ ДЕЛАЕТ (границы, у каждой свой замок в тестах):
  • НЕ считает цену сам и не знает ни одной формулы: числа приходят из двери, а сравниваемое
    число — из `price_source`, который тут же и остаётся для внутренних прикидок;
  • НЕ ходит в сеть и не открывает ни одной таблицы: дверь зовёт вызывающий, сюда приходит
    УЖЕ полученный ответ;
  • НЕ судит ЗАНЯТОСТЬ. Исход `none_available` («байк занят») проходит НАСКВОЗЬ нетронутым:
    это ответ ПРО НАЛИЧИЕ, у него свой разговор и своя фраза, и третьим исходом он не является;
  • НЕ шлёт наружу ничего и клиента не знает — отдаёт текст записки вызывающему;
  • НЕ решает, звучит ли ответ: решает путь ответа (`suggest._resolve_model_price`).

ПОЧЕМУ СТОРОЖ СВЕЖЕСТИ ФАЙЛА (`price_gate`) БОЛЬШЕ НЕ ГАСИТ КЛИЕНТСКОЕ ЧИСЛО. Он сторожил
ФАЙЛ: снимок устаревает молча, и пока число клиенту давал файл, устаревание обязано было
означать молчание. Число клиенту даёт дверь, а дверь не устаревает по построению — она и есть
живое положение ручек. Погасить верное живое число из-за старости снимка значило бы оставить
файлу власть над клиентским ответом ровно там, где решение владельца её сняло. Вердикт сторожа
остаётся у внутренних путей и у прибора расхождения. Это ПРОЧТЕНИЕ ШТАБА, названное так же
прямо и в самом узле (часть третья блока ДВЕРЬ-ИСТОЧНИК-1209), а не слово владельца.

ЗАВИСИМОСТЕЙ ОТ `suggest` ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО (та же петля, что у `season_gate` и
`noprice_gate`): `suggest` импортирует этот модуль верхним импортом.

ОТКАТ, ОБЪЯВЛЕННЫЙ СЛОВОМ: `DOOR_PRICE_OFF=1` — прибор расхождения молчит, а число двери
по-прежнему уходит клиенту без подмены. Ветки «вернуть счёт по файлу в клиентский ответ» здесь
НЕТ вовсе и одной ручкой не открывается: источник сменило решение владельца, и возвращает его
тоже решение, а не переменная окружения.
"""

import datetime
import logging
import os

import price_source

log = logging.getLogger("door_price")

OFF_ENV = "DOOR_PRICE_OFF"
_TRUE = ("1", "true", "yes", "on", "да")

# ИМЯ ТРЕТЬЕГО ИСХОДА для пути ответа. Это `kind` из `suggest._resolve_model_price`. Прежнее
# имя «error» значило «источник не ответил» и вело в ТОТ ЖЕ фолбэк; новое имя нужно затем, что
# теперь у фолбэка есть ОБЯЗАННОСТЬ — произнести слова про человека. Ни одна ветка `suggest`,
# читающая kind по равенству («ok» / «min» / «none»), на него не смотрит.
KIND_DOOR_NO_PRICE = "door_no_price"

# Порог прибора: РОВНО ОДИН БАТ, как названо заданием. Не «процент» и не «заметное»: расхождение
# в один бат на суточной ставке — это 5 бат на пятисуточном сроке и 30 на месячном, и молчать
# о нём значит хранить ту же тишину, из которой родился недобор 765 ฿ на одной карточке.
DIVERGENCE_MIN_BAHT = 1


def off(env=None):
    """Прибор расхождения выключен объявленным откатом? Пусто/мусор → ВКЛЮЧЁН.

    Знак перевёрнут сознательно, как у `season_gate`/`noprice_gate`: молчащий прибор — это
    возврат к той самой тишине, ради снятия которой он заведён, и попасть в неё опечаткой
    нельзя. Читается НА КАЖДОМ ВЫЗОВЕ, а не на импорте: поворот ручки действует сразу.
    """
    source = env if isinstance(env, dict) else os.environ
    return str(source.get(OFF_ENV) or "").strip().lower() in _TRUE


# ------------------------------- есть ли у двери цена -------------------------

def _num(value):
    """Число котировки → int | None. Ни одна ветка не превращает «нет числа» в ноль: ноль есть
    ЦЕНА (и неправдоподобная), а отсутствие числа — другое состояние."""
    if isinstance(value, bool) or value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def has_price(q):
    """НЕСЁТ ЛИ ОТВЕТ ДВЕРИ ЦЕНУ. Чистая функция, ни файла, ни сети.

    Спрашивается РОВНО то, из чего клиентская фраза собирает число, — и спрашивается по тем же
    полям и в том же порядке, что `suggest._client_price`: дословная строка столбца J (`text`),
    суточная ставка, итог за срок, потолок низкого сезона. Пусто во всех четырёх → дверь
    ответила БЕЗ ЦЕНЫ, и это третий исход, а не повод посчитать самим.

    Почему не «status == ok и всё»: живая дверь умеет ответить `ok` с наличием и БЕЗ цены
    (`available` есть, чисел нет), и ровно этот случай раньше уходил в общий `error` без слов
    про человека. Замер полей, а не статуса, — единственное, что разводит их надёжно.
    """
    if not isinstance(q, dict):
        return False
    text = q.get("text")
    if isinstance(text, str) and text.strip():
        return True
    return any(_num(q.get(k)) is not None for k in ("day_price", "total", "cap_price"))


def kind_of(res):
    """ОТВЕТ ДВЕРИ → имя третьего исхода | None («класс не наш, иди прежней дорогой»).

    None возвращается на живой цене и на занятости — то есть на всём, кроме положительно
    установленного «двери нечего сказать о цене».
    """
    if not isinstance(res, dict):
        return None
    return KIND_DOOR_NO_PRICE if res.get("noquote") == KIND_DOOR_NO_PRICE else None


# ------------------------------- слова про человека ---------------------------
# НИ ОДНОЙ ЦИФРЫ в этой строке, и это не стиль. Белый список пост-чека черновика строится из
# ЛЮБЫХ чисел ценовой записки (`suggest._pc_wl_price_numbers`): попади сюда хоть дата, хоть
# номер правила — цифра стала бы РАЗРЕШЁННОЙ к произнесению ценой, и третий исход принёс бы
# клиенту ровно то число, ради запрета которого заведён.
HUMAN_LINE = (
    "Скажи прямо, что эту цену считает человек, и коллега вернётся с точной суммой. "
    "НЕ называй НИКАКОГО числа цены: ни точного, ни за сутки, ни за весь срок, ни «от …», "
    "ни диапазоном, ни СРЕДНИМ по классу или по соседним моделям, ни ориентиром, ни из FAQ; "
    "цены ДРУГИХ моделей вместо неё тоже НЕ называй. МОЛЧАТЬ ТОЖЕ НЕЛЬЗЯ, ответ обязан "
    "прозвучать: молчание запрещено наравне с выдумкой.")

HUMAN_LINE_EN = (
    "Say plainly that a human works out this price and a colleague will come back with the "
    "exact amount. Do NOT quote ANY price figure: no exact sum, no daily rate, no total, "
    "no «from …», no range, no AVERAGE over the class or neighbouring models, no ballpark, "
    "nothing from the FAQ; do not quote other models' prices instead of it either. STAYING "
    "SILENT IS ALSO FORBIDDEN, the answer must be spoken.")


def client_note(lang="ru"):
    """Ценовая записка третьего исхода: НИ ОДНОГО числа + прямое требование позвать человека."""
    return HUMAN_LINE_EN if lang == "en" else HUMAN_LINE


# ------------------------------- прибор расхождения ---------------------------

def file_total(model, ds, de, key_fn, q):
    """ЧТО ДАЛ БЫ ФАЙЛ на тот же вопрос. → (total|None, day|None, why).

    Нужен ТОЛЬКО прибору: это число во внешний ответ не попадает ни одной веткой, и вернуть
    его наружу некуда — вызывающий читает из него лишь строку журнала.

    Срок берётся `price_source._days_of`, то есть ТЕМ ЖЕ счётом, которым живёт сам файл.
    Своя арифметика дат здесь была бы хуже дублирования: разойдись она с файлом на сутки, и
    прибор показывал бы расхождение ОТ РАЗНОГО СРОКА, выдавая его за разную цену.
    """
    doc = price_source.load()
    if doc is None:
        return None, None, "файла нет или он не прочитался"
    days = price_source._days_of(q, ds, de)
    if not days:
        return None, None, "срок не определён"
    try:
        start = datetime.date.fromisoformat(str(ds))
    except (TypeError, ValueError):
        return None, None, "дата старта не разобрана"
    total, info = price_source.term_total(doc, model, start, days, key_fn, quote=q)
    if total is None:
        return None, None, str((info or {}).get("why") or "файл эту модель не судит")
    rates = (info or {}).get("day_prices") or []
    return total, (rates[0] if len(rates) == 1 else None), "посчитано по файлу"


def divergence_line(model, ds, de, door_total, file_total_, door_day=None, file_day=None):
    """Строка журнала о расхождении. Чистая функция — ни журнала, ни сети.

    Несёт РОВНО то, что названо заданием: модель, даты, ОБА числа и разницу. Знак разницы
    читается «файл минус дверь»: минус значит «файл дешевле двери», то есть недобор денег —
    ровно тот, что замерен 12.09 (−110 ฿ на пятисуточном XMAX, −575 на ADV 350).
    """
    diff = file_total_ - door_total
    parts = ["ЦЕНА РАСХОЖДЕНИЕ: модель=%s" % model,
             "даты=%s..%s" % (ds, de),
             "дверь=%d" % door_total,
             "файл=%d" % file_total_,
             "разница=%+d ฿ (файл минус дверь)" % diff]
    if door_day is not None and file_day is not None and door_day != file_day:
        parts.append("в сутки: дверь=%d файл=%d разница=%+d ฿"
                     % (door_day, file_day, file_day - door_day))
    parts.append("клиенту ушло число ДВЕРИ, ответ НЕ остановлен")
    return " | ".join(parts)


def measure(model, ds, de, key_fn, q, env=None):
    """ПРИБОР: сравнить число двери и число файла, расхождение от бата — в журнал. → строка|None.

    НИ ОДНОЙ ВЕТКИ, меняющей ответ. Возвращает текст строки (для тестов и ручной пробы) либо
    None, когда писать нечего: прибор выключен, файл этой модели не судит, числа двери нет,
    расхождение меньше бата. Любой сбой внутри — тоже None: прибор, уронивший ответ клиенту,
    хуже отсутствующего прибора.
    """
    if off(env):
        return None
    try:
        door = _num(q.get("total"))
        if door is None:
            return None                      # нечего сравнивать: итога за срок дверь не дала
        file_t, file_d, why = file_total(model, ds, de, key_fn, q)
        if file_t is None:
            log.info("прибор расхождения молчит (%s): модель %s %s..%s", why, model, ds, de)
            return None
        if abs(file_t - door) < DIVERGENCE_MIN_BAHT:
            return None                      # сошлись до бата — молчать тут и есть правда
        line = divergence_line(model, ds, de, door, file_t,
                               door_day=_num(q.get("day_price")), file_day=file_d)
        log.warning("%s", line)
        return line
    except Exception as exc:                 # noqa: BLE001 — нужен сам факт отказа прибора
        log.info("прибор расхождения сорвался (%s) — ответ клиенту не затронут",
                 type(exc).__name__)
        return None


# ------------------------------- единственная точка врезки --------------------

def client_quote(res, model, ds, de, key_fn, env=None):
    """ЕДИНСТВЕННАЯ ТОЧКА, ЧЕРЕЗ КОТОРУЮ ЦЕНА ДВЕРИ ИДЁТ КЛИЕНТУ.

    Вход и выход — тот же контракт, что у `pricing.quote_for_model`: {'status': …,
    'quote': dict|None}.

    Дверь дала цену  → возвращается ТОТ ЖЕ объект `res`, побайтно и по ссылке. Подмены нет по
                       построению: записи числа в котировку в этой функции не существует.
                       Попутно срабатывает прибор расхождения (в журнал, не в ответ).
    Дверь занята     → `none_available` проходит НАСКВОЗЬ нетронутым: это ответ про наличие.
    Дверь молчит или
    ответила без цены→ {'status': 'error', 'quote': None, 'noquote': KIND_DOOR_NO_PRICE}.
                       Ключ `noquote` — ИМЯ СОСТОЯНИЯ, а не решение: отвечать ли им, решает
                       путь ответа. Прежние читатели видят прежнее `status='error'`/`quote=None`
                       и ведут себя побайтно как раньше.
    """
    if not isinstance(res, dict):
        return {"status": "error", "quote": None, "noquote": KIND_DOOR_NO_PRICE}
    status, q = res.get("status"), res.get("quote")
    if status == "none_available":
        return res
    if status != "ok" or not has_price(q):
        out = {"status": "error", "quote": None, "noquote": KIND_DOOR_NO_PRICE}
        log.info("дверь цены не дала (status=%r, цифр в котировке нет) — считает человек: "
                 "модель %s %s..%s", status, model, ds, de)
        return out
    measure(model, ds, de, key_fn, q, env=env)
    return res
