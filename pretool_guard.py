#   поля стоит ДВАЖДЫ. Подделка попадает в ГОЛОВНУЮ строку (объект вклеен во фразу `_human`), то
#   есть ВЫШЕ честной, и читатель демона (`object_from_card`, ПЕРВОЕ совпадение по всему тексту)
#   отдавал 'чужая-цель — разрешить?' там, где гард напечатал 'C:/ProgramData/a.txt'.
# Fail-closed при этом не ломался (значения расходятся → высший вид вычёркивается `approval_covers`
# → операция не исполняется), но владелец читал карточку, называющую ЧУЖУЮ цель, и след ответа
# записывал её же. Цена ошибки здесь — не пропуск, а ОБМАН ЧИТАТЕЛЯ о том, ЧТО он подтверждает.
# ДВА ПОЯСА, и разница со штампом класса намеренная:
#   • ЗАПИСЬ (`scrub_obj_field`): значение объекта входит в карточку ОДНОЙ строкой (перенос
#     складывается в пробел) и без чужого имени служебного поля; след подделки ВИДИМЫЙ
#     (`OBJ_FIELD_MARK`), а не тихая чистка — попытка обязана быть заметна владельцу. Третьего
#     пояса-скраба у маркера здесь НЕТ и быть не может: в честной карточке эта строка стоит ПО
