def _decide_bash(cmd, cwd):
    """Разбор Bash/PowerShell. Тонкая обёртка над `_decide_bash_body`: вычисляет ОДИН РАЗ
    скан-текст и признак «секрет упомянут только пробой наличия», а по итогу проставляет вид
    `env_probe` там, где иначе в логе стояло бы безликое `unknown`. Само решение — в body."""
    if not cmd:
        return ("defer", "", "")
    scan = _scan_text(cmd)
    reach = _env_reach(cmd) if _RE_ENV.search(scan) else None
    probe = reach is not None
    action, kind, obj = _decide_bash_body(cmd, cwd, scan, probe)
    if action == "defer" and not kind and _RE_SQLITE_WORD.search(scan):
        # Питон-форма чтения базы доходит сюда через `_scan_python` с пустым видом. Смягчение не
        # должно стоить прозрачности (доктрина лога): в журнале обязано быть видно, что молча
        # прошло именно ЧТЕНИЕ базы, а не безымянное «ну ничего красного не нашли».
        sq = _sqlite_decide(scan)
        if sq and sq[0] == "sqlite_read":
            return ("defer", "sqlite_read", sq[1])
    if probe and action == "defer" and not kind:
        return ("defer", reach, "")     # прозрачность лога: проба и упоминание — РАЗНЫЕ строки
    if action == "defer" and not kind:
        # ДОКТРИНА ЛОГА, та же что у `sqlite_read`/`env_probe`/`cfg_read`: смягчение не должно
        # стоить прозрачности. Признак поймал СЛОВО, а не команду (`_verb_acts`) — в журнале
        # обязано быть видно, КАКОЙ именно признак промолчал и почему, иначе строка выглядит как
        # «ничего красного не нашли», и следующий разбор ложного класса начнётся с нуля.
        # Второй заход по СЫРОЙ команде. Признак мог не дожить до скан-текста вовсе: подпись к
        # выводу вырезается как данные (`_strip_print_args`), и с 01.08.2026 это касается и формы
        # `echo "--- SCHTASKS XML ---"` (раньше её спасал от вырезания ведущий дефис). Решения
        # ветка не меняет — только НАЗЫВАЕТ признак, который промолчал: иначе строка журнала
        # выглядит как «ничего красного не нашли», и следующий разбор начинается с нуля.
        w = _word_only_kind(scan) or _word_only_kind(cmd)
        if w:
            return ("defer", "word_" + w, "")
    if action == "defer" and not kind and _RE_LIVE_SHEET_HINT.search(scan):
        # Та же доктрина лога, что у `sqlite_read`/`env_probe`/`cfg_read`: смягчение не должно
        # стоить прозрачности. Слово живого листа прошло молча — в журнале обязано быть видно,
        # что это было УПОМИНАНИЕ, а не «ничего красного не нашли».
        return ("defer", "sheet_mention", "")
    cfg = _RE_CLAUDE_CFG_CMD.search(scan)
    if cfg and _is_pure_config_read(cmd) and (
            (action == "defer" and not kind) or (action, kind) == ("ask", "unknown")):
        # Та же доктрина лога, что у `sqlite_read` и `env_probe`: смягчение не должно стоить
        # прозрачности. Смотрелки вроде `sed -n`/`jq`/`diff` шелловым смотрелкам (`_RE_READONLY_SHELL`)
        # не известны и падали в безликое `unknown` — в журнале обязано быть видно, что молча прошло
        # именно ЧТЕНИЕ конфига. Решения это не меняет: `unknown` и так не красный (`_stays_red`).
        return ("defer", "cfg_read", cfg.group(0))
    return (action, kind, obj)


def _word_only_kind(scan):
    """Вид признака, который НАШЁЛСЯ в тексте, но командой не оказался (`_verb_acts` → False),
    иначе "". Нужен только логу: решения не меняет, но делает молчание объяснимым."""
    for rx, kind, verbs, _probe in _RED_CMD:
        if verbs and rx.search(scan) and not _verb_acts(scan, verbs, rx):
            return kind
    return ""


def _decide_bash_body(cmd, cwd, scan, env_probe=False, skip_kinds=frozenset()):
    # skip_kinds — виды, УЖЕ найденные в этой же команде предыдущим заходом (`red_kinds_bash`).
    # Нужен, чтобы «все красные виды команды» считались ТЕМ ЖЕ разборщиком, что и первый: второй
    # список правил разъехался бы с этим при первой же правке. Пустой набор → поведение
    # байт-в-байт прежнее.
    # Красное ищем в СКАН-ТЕКСТЕ: позиционные аргументы .py-скриптов — ДАННЫЕ, а не операция
    # (класс-фикс, порт с VPS). Сегменты шелла сохранены целиком, подстановки команд и пути к
    # секретам из аргументов НЕ вырезаются. `_RE_OUTSIDE_WRITE` ниже намеренно смотрит СЫРУЮ
    # команду: перенаправление `> C:\…` стоит после имени скрипта и вырезанием пряталось бы.
    netk, nettarget = _net_scan(scan)
    sq = _sqlite_decide(scan) if _RE_SQLITE_WORD.search(scan) else None
    # ЖИВОЙ ЛИСТ судим по тексту С ТЕЛАМИ HEREDOC: для денег и парка черновик — тоже обращение
    # (fail-closed). Всё прочее красное судится по `scan`, где тело heredoc уже вырезано как
    # данные. Поисковый шаблон и позиционные аргументы .py вырезаны в обоих текстах: `grep -n
    # gspread suggest.py` — это поиск, а не лист.
    sheet = _live_sheet_decide(_scan_text(cmd, keep_heredoc=True))
    for rx, kind, verbs, _probe in _RED_CMD:
        if kind in skip_kinds:
            continue                     # вид уже назван предыдущим заходом по ЭТОЙ же команде
        if rx.search(scan):
            # ОБЩАЯ ПРОВЕРКА ДЕЙСТВИЯ (замок 31.07.2026): имя-команду признают признаком, только
            # если она стоит в КОМАНДНОЙ ПОЗИЦИИ. Это снимает разом ложные `kill`/`delete`/
            # `schtasks`/`git_force` на слове в тексте записи, в шаблоне поиска и в фикстуре
            # гарда. Правила с `probe` сюда не попадают (verbs пуст) — их судит свой разборщик.
            if not _verb_acts(scan, verbs, rx):
                continue
            # Сеть: красное — только НАСТОЯЩИЙ выход наружу. Свой ssh-канал и упоминание слова
            # в тексте карточки не порождают (см. _net_scan).
            if kind == "network" and netk != "open":
                continue
            if kind == "clasp":
                # Разводим по подкоманде: чтение — зелёное, выкатка/исполнение — красное.
                cl = _clasp_decide(scan, cwd)
                if cl is None:
                    continue                  # `clasp` словом в тексте, а не командой
                return ("ask", cl[0], cl[1])
            if kind == "sqlite":
                # Разводим по оператору запроса. ЧТЕНИЕ (и просто имя модуля) не обрывает разбор:
                # уходим в `continue`, чтобы остальные красные ветви (env, конфиг `.claude`,
                # запись вне репо, боевые токены питона) отработали как раньше. Иначе
                # `python -c "…select…; os.remove(x)"` проехал бы зелёным целиком.
                if sq is None or sq[0] == "sqlite_read":
                    continue
                return ("ask", "sqlite", sq[1])
            if kind == "live_sheet":
                # Развод по ДЕЙСТВИЮ: слово `gspread`/адрес в тексте — не обращение к листу.
                # Настоящее обращение возвращает объект ВСЕГДА (имя листа либо честная пометка).
                if sheet is None:
                    continue
                return ("ask", "live_sheet", sheet)
            obj = ""
            if kind == "delete":
                obj = _extract_delete_target(scan) or ""
            elif kind == "kill":
                obj = _extract_kill_target(scan) or ""
            elif kind == "network":
                obj = nettarget or _extract_host(scan) or ""
            elif kind == "sqlite":
                obj = _extract_db(scan) or ""
            return ("ask", kind, obj)
    # ЖИВОЙ ЛИСТ мимо цикла: признак мог не попасть в `scan` (обращение лежит в теле heredoc —
    # черновике скрипта, который его и запишет). Деньги и парк красим и здесь — fail-closed.
    if sheet is not None and "live_sheet" not in skip_kinds:
        return ("ask", "live_sheet", sheet)
    # Секрет упомянут — но ПРОБА НАЛИЧИЯ секретом не делится (`_env_probe_only`). Признак пробы
    # НЕ обрывает разбор: команда идёт дальше по всем прочим красным ветвям (конфиг `.claude`,
    # запись вне репо, python-скан) — иначе `Test-Path .env; python evil.py` перестал бы
    # сканировать второй сегмент. Послабление касается ТОЛЬКО вида `env`.
    if not env_probe and "env" not in skip_kinds and _RE_ENV.search(scan):
        return ("ask", "env", "")
    # Конфиг `.claude` защищён для инструментов Write/Edit — значит его надо защитить и от
    # ОБХОДА через шелл. Иначе дыра тривиальна: сессия пишет settings.json.new (внутри репо,
    # зелёное) и копирует его поверх боевого одной командой `cp`, молча расширив свои права.
    # Чтение конфига остаётся зелёным (ветка _RE_READONLY_SHELL ниже — cat/type/Get-Content).
    m = _RE_CLAUDE_CFG_CMD.search(scan)
    if m and "edit_claude" not in skip_kinds and not _is_pure_config_read(cmd):
        return ("ask", "edit_claude", m.group(0))
    m = _RE_OUTSIDE_WRITE.search(cmd)
    if m and "outside" not in skip_kinds and not _inside_project(m.group(2)):
        return ("ask", "outside", m.group(2))
    # зелёное
    if _RE_SAFE_SCRIPTS.search(cmd):
        return ("defer", "", "")
    if _RE_GIT_SAFE.search(cmd):
        return ("defer", "", "")
    if _RE_TESTS.search(cmd):
        return ("defer", "", "")
    if _RE_PY.search(cmd):
        if _all_py_targets_are_tests(cmd):        # прямой запуск только test_*.py → без контент-скана
            return ("defer", "", "")
        return _scan_python(cmd, cwd, env_probe)
    m = _RE_UNTIL_WAIT.match(cmd)
    if m:
        cond = (m.group(1) or "").lstrip("! \t")
        tail = m.group(2) or ""
        if _RE_READONLY_SHELL.match(cond) and (not tail or _RE_READONLY_SHELL.match(tail)):
            return ("defer", "", "")
    if _RE_READONLY_SHELL.search(cmd):
        return ("defer", "", "")
    # Команда — ЧТЕНИЕ базы и ничего больше (`sqlite3 bookings.db "select 1"`): смотрелки шелла
    # её не знают, и без этой ветки она упала бы в `unknown`, а `unknown` — hard-блок, карточка
    # ВСЕГДА. Вид ставим честный: в журнале видно, что решение принято разбором запроса.
    if sq and sq[0] == "sqlite_read":
        return ("defer", "sqlite_read", sq[1])
    return ("ask", "unknown", "")


# ══ ВСЕ КРАСНЫЕ ВИДЫ ОДНОЙ КОМАНДЫ (корень В, склейка ПО КОМАНДЕ) ═══════════════════════════
# `_decide_bash_body` возвращает ПЕРВОЕ совпавшее правило `_RED_CMD`, а единственный сканер тела
# питона стоит НИЖЕ цикла. Значит `rm -rf tmp/x; python -c "…create_booking…"` даёт карточку про
# `delete`, а боевая запись Bridge в той же строке не названа НИГДЕ — и после «да» исполняется
# ВСЯ строка. Владелец подтверждает уборку черновика, а платит деньгами.
#
# Считаем ТЕМ ЖЕ разборщиком, повторными заходами со списком уже найденных видов: второй список
# правил разъехался бы с первым при ближайшей правке (`_kind_phrase` заведён ровно по этой
# причине). Заходов не больше `_RED_KINDS_MAX`: нам нужен ФАКТ «их больше одного», а не полный
# перечень, и цикл обязан кончиться на любой команде.
#
# ГРАНИЦА ЧЕСТНО: если ДВА красных вида приходят из одного `_scan_python` (боевой токен и запись
# в БД в теле одного скрипта), второй заход вернёт тот же вид и сбор остановится — счёт даст 1.
# Это недобор, а не перебор: недобор оставляет прежнее поведение, перебор ронял бы задачи.
_RED_KINDS_MAX = 3


def red_kinds_bash(cmd, cwd, env_probe=False):
    """Красные виды команды Bash/PowerShell → кортеж (kind, obj) в порядке нахождения."""
    found, skip = [], set()
    for _ in range(_RED_KINDS_MAX):
        action, kind, obj = _decide_bash_body(cmd, cwd, _scan_text(cmd), env_probe,
                                              skip_kinds=frozenset(skip))
        if action != "ask" or not kind or kind in skip:
            break
        found.append((kind, obj))
        skip.add(kind)
    return tuple(found)


# ── ДВЕ ОПЕРАЦИИ ИЛИ ОДНО ДЕЙСТВИЕ С ДВУМЯ ЯРЛЫКАМИ — РАЗЛИЧИТЕЛЬ СТРУКТУРНЫЙ ────────────────
# Замер по живому логу (5938 уникальных команд суток, оба файла `pretool_guard.log*`):
#   • больше одного красного ВИДА — 30 команд (0,51%), и почти все это ОДНО действие:
#     `cat > "C:/…/scratchpad/x.py"` = `edit_claude`+`outside`, heredoc-питон, читающий файл
#     секретов, = `env`+`py_write`. Отказывать им — трение на ровном месте;
#   • красное в РАЗНЫХ сегментах = ДВЕ операции — 1 команда (0,02%), и та `kill`+`kill`.
# Отсюда решение: НЕ отказ (цена трения кратно выше пользы при такой частоте), а СТРОКА В
# КАРТОЧКЕ. Сегодня вторая операция строки не названа НИГДЕ: карточка говорит про `delete`, а
# «да» освобождает и боевую запись Bridge из той же строки. Пусть карточка хотя бы не врёт.
# КЛАССОМ ОДОБРЕНИЯ ВТОРАЯ ОПЕРАЦИЯ НЕ СТАНОВИТСЯ: штамп остаётся один (`_write_marker`), иначе
# мы бы своей же правкой вернули «одно да → два класса».
SECOND_OP_MARK = ("⚠ В КОМАНДЕ ЕЩЁ ОДНА КРАСНАЯ ОПЕРАЦИЯ (%s) — она стоит отдельным шагом строки, "
                  "и «да» освободит строку ЦЕЛИКОМ. Надёжнее: раздели на два шага.")


def other_ops_in_command(kind, raw_cmd, cwd=None):
    """Красные операции ЭТОЙ ЖЕ команды из ДРУГИХ сегментов, чем названная карточкой → кортеж
    видов. Два вида ИЗ ОДНОГО сегмента — одно действие с двумя ярлыками, и в карточке им не
    место. `unknown` операцией не является: это «больше ничего не узнали», хвост разбора."""
    try:
        segs = _split_segments(raw_cmd or "")
        if len(segs) < 3:                      # один сегмент — второй операции неоткуда взяться
            return ()
        by_seg = {}
        for i, seg in enumerate(segs):
            if i % 2 or not seg.strip():
                continue
            ks = [k for k, o in red_kinds_bash(seg, cwd or PROJECT)
                  if k != "unknown" and _stays_red(k, o, seg)]
            if ks:
                by_seg[i] = ks
        own = {i for i, ks in by_seg.items() if kind in ks}
        if not own:
            return ()                          # вид карточки в сегментах не нашёлся — не судим
        others = []
        for i, ks in by_seg.items():
            if i in own:
                continue
            for k in ks:
                if k != kind and k not in others:
                    others.append(k)
        return tuple(others)
    except Exception:
        return ()                              # разбор второй операции карточку ронять не смеет


