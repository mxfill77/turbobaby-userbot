# строки, НАПЕЧАТАННОЙ САМОЙ МОДЕЛЬЮ. Это вторая половина класса «подделка подтверждений»: демон
# рождал карточку из текста исполнителя (`pc_orchestrator._detect_needs_approval`), а потом ИЗ ТОГО
