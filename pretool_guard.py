# Внутри `.claude` красное — ТОЛЬКО конфиг (вектор само-эскалации: правами и хуками сессия
# расширяет собственные полномочия). Рабочие данные агента там же — НЕ конфиг: память
# (projects/<репо>/memory/*.md), стенограммы (*.jsonl), сессии/тудушки/снапшоты шелла. Живой
# факт аудита 22:27: 3 из 20 последних Allow — это запись СВОИХ ЖЕ файлов памяти
# (rc-effort-override.md, claude-bin-stale-version.md, MEMORY.md). Подтверждения на них не
# защищают ничего, а поток притупляет внимание к настоящему красному.
_CLAUDE_CFG_FILE = re.compile(r"(?i)^(settings(\.[\w.-]+)?\.json|\.?claude\.json|[\w.-]*mcp[\w.-]*\.json)$")
_CLAUDE_CFG_DIR = ("hooks", "agents", "commands", "plugins", "skills")


def _is_claude_path(path):
    """True ⇔ путь — КОНФИГ Claude Code (settings*.json / mcp-конфиг / hooks|agents|commands|
    plugins|skills внутри `.claude`). Память, стенограммы и прочие рабочие данные агента → False."""
    n = os.path.normcase(os.path.normpath(path or ""))
    parts = n.split(os.sep)
    try:
        i = max(k for k, p in enumerate(parts) if p == ".claude")
    except ValueError:
        if os.path.basename(n) in (".claude.json", "claude.json"):
            return True                       # ~/.claude.json лежит РЯДОМ с каталогом, не внутри
        return False
    tail = parts[i + 1:]
    if not tail:
        return False                          # сам каталог .claude — не файл конфига
    if _CLAUDE_CFG_FILE.match(tail[-1]):
        return True
    return any(seg in _CLAUDE_CFG_DIR for seg in tail[:-1])


# Скретчпад сессии (%TEMP%\claude\<проект>\<сессия>\scratchpad\…) — САНКЦИОНИРОВАННАЯ временная
# зона harness'а: изолирована от репо и от данных пользователя, живёт один сеанс. Требование
# «правки только внутри репо» защищает от правок ЧУЖОГО кода, а не от временных файлов, ради
# которых скретчпад и существует. Живой факт аудита: 3 из 20 Allow — запись собственных
# временных скриптов разбора.
def _is_scratchpad(path):
    n = os.path.normcase(os.path.normpath(path or ""))
    parts = n.split(os.sep)
    return "scratchpad" in parts and "claude" in parts and (
        os.sep + "temp" + os.sep in n or os.sep + "tmp" + os.sep in n)


# ВРЕМЕННЫЕ каталоги, которых нет в git: `tmp/` внутри репозитория (.gitignore:60) и весь
# `%TEMP%\claude\**` (скретчпад сессии и соседние рабочие каталоги harness'а). Работа в них —
# это работа сессии со СВОИМИ черновиками: они не едут в историю, не видны прод-контуру и
# живут один сеанс. Подтверждение на них ничего не защищает.
_RE_TEMP_CLAUDE = re.compile(r"(?i)(^|[\\/])(temp|tmp)[\\/]claude[\\/]")


def _is_temp_zone(path):
    """True ⇔ путь лежит во временной зоне из .gitignore. Неразрешимый путь → False (fail-safe:
    непонятное не считаем временным). `..` в пути снимает доверие целиком — иначе
    `tmp/../suggest.py` проехал бы как «временный»."""
    s = (path or "").strip().strip("'\"").replace("\\", "/")
    if not s or ".." in s.split("/"):
        return False
    if _RE_TEMP_CLAUDE.search(s):
        return True                            # в т.ч. с неразвёрнутым $LOCALAPPDATA/%TEMP%
    if s.startswith("$") or s.startswith("%") or s.startswith("~"):
        return False                           # переменную не развернуть → не угадываем
    try:
        ap = s if os.path.isabs(s) or re.match(r"^[A-Za-z]:", s) else os.path.join(PROJECT, s)
        if re.match(r"^/[A-Za-z]/", ap):       # MSYS-форма /d/turbobaby-bot/… → D:\turbobaby-bot\…
            ap = ap[1] + ":" + ap[2:]
        ap = os.path.normcase(os.path.normpath(ap))
    except Exception:
        return False
    if not _inside_project(ap):
        return False
    rel = os.path.relpath(ap, PROJ_N).split(os.sep)
    return bool(rel) and rel[0] == "tmp"


def _is_memory_store(path):
    """Хранилище памяти агента: `.claude/projects/<репо>/memory/**`. Это СОБСТВЕННЫЕ заметки
    сессии, а не чужой код и не конфиг — правило «только внутри репо» защищает от правок чужого,
    и на память оно не про то. Конфигом эти файлы не являются (см. _is_claude_path), значит
    расширить свои права через них нельзя."""
    parts = os.path.normcase(os.path.normpath(path or "")).split(os.sep)
    try:
        i = parts.index("memory")
    except ValueError:
        return False
    return ".claude" in parts[:i] and "projects" in parts[:i]


def _sanctioned_outside(path):
    """Зоны ВНЕ репо, где запись не требует подтверждения: временные каталоги harness'а
    (`%TEMP%\\claude\\**`, включая скретчпад) и хранилище памяти агента. Оба — рабочая зона самой
    сессии, не вектор эскалации. Живой факт аудита 22:27: 6 из 20 последних Allow были про них."""
    return _is_scratchpad(path) or _is_temp_zone(path) or _is_memory_store(path)


def _is_test_target(path):
    """test_*.py как ЦЕЛЬ прямого запуска (в т.ч. tests/test_*.py). Содержимое тест-файлов —
    фикстуры с красными токенами (.env/os.remove/add_transaction/…), а НЕ боевые вызовы; сами
    тесты гейтуются в репо (review+git). Порт VPS-урока: арг-файлы тест-раннера не сканируем."""
    b = os.path.basename(path or "").lower()
    return b.startswith("test_") and b.endswith(".py")


def _all_py_targets_are_tests(cmd):
    """True ⇔ это прямой запуск python, где ВСЕ .py-цели — test_*.py (и нет -c/-m/stdin).
    Тогда контент не сканируем (тесты гейтуются в репо). Смешанный запуск (есть не-тест .py)
    или -c/-m/stdin → False, идём в полный _scan_python — красное для остального НЕ ослабляем."""
    if _RE_PY_FLAG.search(cmd):
        return False                          # -c/-m/stdin: .py-имя могло быть внутри кода → скан
    files = _RE_PY_FILE.findall(cmd)
    return bool(files) and all(_is_test_target(f) for f in files)


# Позиционные аргументы .py-скрипта — ДАННЫЕ, а не операция (порт класса VPS 23.07.2026,
# коммит 7af280c). `python cclog.py DONE "<боевое имя> записан"` интерпретатор НЕ исполняет —
# строку читает сам скрипт; её попадание в скан-текст давало ЛОЖНОЕ красное на каждой такой записи.
def _strip_script_cli_args(cmd):
    """Вырезать из СКАН-ТЕКСТА позиционные аргументы после токена, оканчивающегося на .py.
    Интерпретатор и имя скрипта остаются. Исполняется всегда ИСХОДНАЯ команда — правится только
    текст, по которому идёт поиск красных токенов.

    Доктрина не ослаблена — режем не всегда:
      • -c / -m / stdin в команде → там аргумент И ЕСТЬ код → возвращаем как есть (полный скан);
      • команда без интерпретатора python (grep/cat с .py в аргументе) → как есть;
      • аргумент, похожий на файл секретов (.env/*.session/…), СОХРАНЯЕМ — иначе
        `python reader.py .env` перестал бы блокироваться;
      • кривое квотирование → возвращаем исходную строку, не угадываем.
    """
    if not cmd or not _RE_PY.search(cmd) or _RE_PY_FLAG.search(cmd):
        return cmd
    try:
        toks = shlex.split(cmd)
    except Exception:
        return cmd
    kept, cut = [], False
    for t in toks:
        if not cut:
            kept.append(t)
            if t.lower().endswith(".py"):
                cut = True
            continue
        if _looks_like_secret_arg(t) or _RE_ARG_EXEC.search(t):
            kept.append(t)   # путь к секрету и подстановка команды обязаны остаться видимыми скану
    return " ".join(kept) if cut else cmd


# Аргумент, который САМ исполняет команду ($(…), `…`, ${…}), вырезать нельзя: это не данные,
# а операция. Иначе `cclog.py "$(rm -rf …)"` спрятал бы удаление за видом текста записи.
_RE_ARG_EXEC = re.compile(r"\$\(|`|\$\{")


def _looks_like_secret_arg(tok):
    """Аргумент — ПУТЬ к секрету, а не проза, где слово просто встретилось.
    `.env`, `../.env`, `C:/proj/.env`, `x.session` → да (вырезать нельзя);
    `DONE: правил .env и настройки` → нет (пробелы ⇒ это текст записи, а не путь)."""
    t = (tok or "").strip().strip("'\"")
    if not t or any(c.isspace() for c in t):
        return False
    return _is_secret_path(t) or bool(_RE_ENV.search(t))


# --------------------- разбор команды для СКАН-ТЕКСТА (порт VPS 25.07.2026) -------------------
# Класс один: БОЕВЫЕ СЛОВА В ДАННЫХ — это не операция. Скан-текст строится посегментно; сегменты
# сохраняются ЦЕЛИКОМ (иначе `python x.py && rm -rf D:\turbobaby-bot` спрятал бы удаление в
# вырезанном хвосте), а ВНУТРИ каждого вырезаются именно данные: позиционные аргументы
# .py-скрипта (уже было), текст `git -m` и поисковый шаблон grep/rg/sed/awk/Select-String.

_RE_ENV_ASSIGN = re.compile(r"^\w+=")      # env-префикс VAR=val перед именем команды
_WRAPPERS = {"sudo", "doas", "env", "nohup", "nice", "ionice", "time", "timeout",
             "stdbuf", "xargs", "systemd-run",
             # Ключевые слова шелла тоже стоят ПЕРЕД командой. Без них структурный разбор не
             # видел `until curl …; do sleep 5; done` — команда цикла пряталась за словом until,
             # и выход в сеть внутри ожидания переставал краснеть. Поймано существующим тестом
             # test_until_wait_does_not_whitelist_red при сужении сетевого признака 25.07.2026.
             "until", "while", "if", "then", "do", "done", "else", "elif", "!",
             "exec", "command"}
# Поисковые команды. К серверному набору добавлены ПК-специфичные Select-String / sls / findstr:
# на этой машине основной шелл PowerShell, и ищут обычно ими.
_SEARCH_CMDS = {"grep", "egrep", "fgrep", "zgrep", "rg", "ag", "ack", "sed", "awk", "gawk",
                "mawk", "select-string", "sls", "findstr"}
# Флаги, чьё значение — ШАБЛОН. Здесь ТОЛЬКО те, что значение действительно ЗАБИРАЮТ.
# Живой случай №7: `grep -n -E "\.env|deny|…" .claude/settings.json`. В прежнем перечне стояли
# `-n` и `-E`, а они у grep/sed БУЛЕВЫ (номера строк / расширенный синтаксис). Разбор считал
# значением `-n` следующий токен — то есть сам флаг `-E`, — вырезал ЕГО, а настоящий шаблон
# оставлял в скан-тексте. Слово `.env` ВНУТРИ ШАБЛОНА ПОИСКА становилось обращением к секрету.
# Булевы флаги и так пропускаются общей веткой `t.startswith("-")` ниже, а шаблон подхватывается
# как первый позиционный: убрать их отсюда — значит починить, ничего не ослабив (проверено на
# `grep -n P f`, `grep -E P f`, `sed -n 'скрипт' f` — вырезается ровно то же, что и раньше).
_PATTERN_FLAGS = {"-e", "--regexp", "--expression", "-pattern"}
# Флаги, чьё значение — ФАЙЛ, а не шаблон. Без них PowerShell-форма
# `Select-String -Path .env -Pattern TOKEN` теряла `.env` из скан-текста: первый позиционный
# аргумент считался шаблоном и вырезался вместе с путём к секрету — и ЧТЕНИЕ .env проезжало
# зелёным (проверено на HEAD до этой правки). Докрутка того же правила, что уже записано выше:
# операнды-файлы не трогаем.
_PATH_FLAGS = {"-path", "-literalpath", "-lp"}
_EXEC_IN_PATTERN = re.compile(
    r"\$\(|`|\bsystem\s*\(|\bpopen\s*\(|\|\s*['\"]?\s*(?:sh|bash|zsh|xargs)\b")


def _base(tok):
    """Имя команды без пути, кавычек, СКОБОК и .exe, нижним регистром (C:\\bin\\grep.exe → grep).

    Скобки снимаются из-за живого случая №1: `if (Test-Path "D:\\…\\.env") { … }` — на этом ПК
    основной шелл PowerShell, и условие пишется В СКОБКАХ. Токен приезжал как `(Test-Path`,
    в белом списке смотрелок наличия (`_EXISTS_CMDS`) не находился, и ПРОВЕРКА СУЩЕСТВОВАНИЯ
    файла превращалась в карточку «хочу обратиться к .env». Скобка — синтаксис шелла, а не
    часть имени команды; путей, начинающихся со скобки, на этой машине не бывает.
    Если после снятия скобок не остаётся НИЧЕГО — токен и БЫЛ скобкой: это командное имя
    `[` из POSIX-теста (`[ -f .env ]`), и снимать его нельзя."""
    raw = (tok or "").strip("'\"")
    name = os.path.basename(raw.strip("([{)]}") or raw).lower()
    return name[:-4] if name.endswith(".exe") else name


def _split_segments(cmd):
    """Команда → [сегмент, разделитель, сегмент, …] С УВАЖЕНИЕМ К КАВЫЧКАМ. Контракт как у
    прежнего _RE_SHELL_SEP.split (чётные — сегменты, нечётные — разделители дословно), но
    разделитель ВНУТРИ кавычек больше не режет.

    Живой провал 25.07.2026: запись в журнал
    `python cowork_log_append.py "DONE …, убраны os.remove и rm -rf …; демон 79694 active"`
    рвалась по точке с запятой ВНУТРИ текста записи. Кавычка оставалась непарной, shlex падал,
    аргумент переставал вырезаться — и гард видел «rm -rf» рядом с путём репозитория. Владелец
    не мог записать в журнал строку, где эти слова просто УПОМЯНУТЫ.

    `&` разделителем НЕ считаем — на ПК это оператор вызова PowerShell (`& "C:\\…\\claude.exe"`),
    а не связка команд. Дыры это не создаёт: не разрезанный кусок сканируется целиком."""
    out, buf, q, i, n = [], [], None, 0, len(cmd or "")
    while i < n:
        ch = cmd[i]
        if q:
            buf.append(ch)
            if ch == "\\" and q == '"' and i + 1 < n:
                buf.append(cmd[i + 1])
                i += 2
                continue
            if ch == q:
                q = None
            i += 1
            continue
        if ch in "'\"":
            q = ch
            buf.append(ch)
            i += 1
            continue
        if cmd[i:i + 2] in ("&&", "||"):
            out.append("".join(buf))
            out.append(cmd[i:i + 2])
            buf = []
            i += 2
            continue
        if ch in ";|\n":
            out.append("".join(buf))
            out.append(ch)
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    out.append("".join(buf))
    return out


def _cmd_index(toks):
    """Индекс слова-КОМАНДЫ сегмента: пропускает env-префикс (VAR=val) и обёртки
    (sudo/env/timeout N/…). None — команды в сегменте нет. Разбор СТРУКТУРНЫЙ, а не по подстроке:
    `cat pretool_guard.log` поисковой командой не станет от того, что рядом есть слово grep."""
    i, hops = 0, 0
    while i < len(toks) and _RE_ENV_ASSIGN.match(toks[i]):
        i += 1
    while i < len(toks) and hops < 4:
        name = _base(toks[i])
        if name not in _WRAPPERS:
            return i
        i += 1
        while i < len(toks) and toks[i].startswith("-"):
            i += 1
        if name in ("timeout", "nice", "ionice") and i < len(toks) \
                and re.match(r"^[\d.]+[smhd]?$", toks[i]):
            i += 1
        while i < len(toks) and _RE_ENV_ASSIGN.match(toks[i]):
            i += 1
        hops += 1
    return i if i < len(toks) else None


# ── «ЭТО КОМАНДА, А НЕ СЛОВО» — общая проверка действия для всех verbs-правил ────────────────
# Тот же приём, которым уже разведены сеть (`_net_scan`), удаление (`_delete_scan`) и проба
# наличия секрета (`_env_probe_only`): имя обязано стоять в КОМАНДНОЙ ПОЗИЦИИ сегмента.
# Здесь он вынесен в ОДНУ функцию и подключён ко ВСЕМ правилам таблицы разом — иначе каждый
# новый вид пришлось бы разводить отдельно, а именно так и накопились семь ложных классов.
#
# ЧТО НЕ ОСЛАБЛЕНО, поимённо (каждый пункт — сохранённое красное):
#   • сегмент, чью командную позицию не разобрать (кривое квотирование), считается СРАБОТАВШИМ;
#   • сегмент, чья команда — ИНТЕРПРЕТАТОР или ВЛОЖЕННЫЙ ШЕЛЛ (`bash -c`, `python -c`, `ssh
#     host …`, `xargs`), судится ПОДСТРОКОЙ как раньше — там аргумент и есть команда. Тот же
#     карве-аут уже принят в `_redirect_text` и `_line_runs_code`;
#   • подстановка команды в сегменте (`$(…)`, `` `…` ``) — тоже исполнение, судим подстрокой.
#
# ОТДЕЛЬНО ПРО PYTHON — единственное сужение карве-аута интерпретаторов, и оно доказуемое.
# У `bash -c "…"`, `ssh host "…"`, `xargs …` аргумент И ЕСТЬ командная строка: там подстрока
# честна. У `python -c "…"` аргумент — ИСХОДНЫЙ КОД, и строковый литерал в нём командой не
# становится сам по себе: чтобы имя `Stop-Process` что-то остановило, коду нужен ШЕЛЛОВЫЙ СТОК
# (`os.system`, `os.popen`, `subprocess`/`Popen`, `os.exec*`) либо подстановка шелла в самом
# сегменте. Живой случай №7: `python -c "print(g.decide({… 'Stop-Process -Id 11168 -Force'…}))"`
# — это ПРОГОН САМОГО ГАРДА на фикстуре, и он давал карточку «снять процесс PID 11168».
# Дыры сужение не открывает: питон-родное разрушение (`os.remove`, `shutil.rmtree`,
# `create_booking`, SQL-запись) ловится НЕ этой веткой, а `_py_write_call`/`_sqlite_decide`/
# `_RE_SQL_WRITE` в `_scan_python` — по ФОРМЕ ВЫЗОВА, и они остались как были.
_RE_SUBST_EXEC = re.compile(r"\$\(|`")
_PY_INTERP = {"python", "python3", "py"}
_RE_PY_SHELL_SINK = re.compile(
    r"(?i)\bos\.system\s*\(|\bos\.popen\s*\(|\bsubprocess\b|\bPopen\b|\bcheck_call\b|"
    r"\bcheck_output\b|\bos\.exec\w*\s*\(|\bos\.spawn\w*\s*\(|\bpty\.spawn\b|"
    r"\bcommands\.get\w*\s*\(")


def _verb_acts(cmd, verbs, rx):
    """True ⇔ признак `rx` поймал ДЕЙСТВИЕ, а не слово: имя из `verbs` стоит в командной позиции
    сегмента — либо сегмент таков, что его текст исполняется (интерпретатор/вложенный шелл/
    подстановка/неразобранные кавычки), и тогда решает подстрока, как до правки."""
    if not verbs:
        return True                      # правило судится своим probe — здесь не мешаем
    for i, seg in enumerate(_split_segments(cmd or "")):
        if i % 2:
            continue
        try:
            toks = shlex.split(seg)
        except Exception:
            if rx.search(seg):
                return True              # кавычки не разобраны → fail-safe, красное как было
            continue
        j = _cmd_index(toks)
        if j is None or j >= len(toks):
            continue
        name = _base(toks[j])
        if name in verbs:
            return True
        if name in _PY_INTERP and not _RE_SUBST_EXEC.search(seg):
            # аргумент python — КОД: имя шелловой команды в нём исполнится только через сток
            if _RE_PY_SHELL_SINK.search(seg) and rx.search(seg):
                return True
            continue
        if (name in _HEREDOC_EXEC or _RE_SUBST_EXEC.search(seg)) and rx.search(seg):
            return True                  # текст сегмента исполняется — подстрока как раньше
    return False


def _strip_git_msg(seg):
    """Текст `git commit -m "…"` — ДАННЫЕ, а не операция (нюанс bd5d516 на VPS). Сообщение
    коммита несёт боевые слова В ТЕКСТЕ: «убрал rm -rf из скрипта» — это описание правки, а не
    удаление. Вырезаются payload'ы -m/-am/--message во всех формах (-m txt, --message=txt,
    приклеенное -mtxt). Не git или сбой разбора → сегмент КАК ЕСТЬ (fail-safe: скан полный,
    `git commit -m "x" && rm -rf y` ловится вторым сегментом)."""
    try:
        toks = shlex.split(seg)
    except Exception:
        return seg
    i0 = 0
    while i0 < len(toks) and _RE_ENV_ASSIGN.match(toks[i0]):
        i0 += 1
    if i0 >= len(toks) or _base(toks[i0]) != "git":
        return seg
    out, i = [], 0
    while i < len(toks):
        t = toks[i]
        if t in ("-m", "-am", "--message"):
            out.append(t)
            i += 2
            continue
        if t.startswith("--message="):
            out.append("--message")
            i += 1
            continue
        if re.match(r"^-a?m.", t):        # приклеенный payload: -mтекст / -amтекст
            out.append("-m")
            i += 1
            continue
        out.append(t)
        i += 1
    return " ".join(out)


def _strip_search_pattern(toks, idx):
    """→ (токены БЕЗ поискового шаблона, вырезанные). Шаблон = аргумент -e/-E/-n/-Pattern либо
    ПЕРВЫЙ позиционный у поисковой команды. Операнды-ФАЙЛЫ не трогаем — иначе
    `grep -n TOKEN .env` перестал бы блокироваться. Шаблон с признаком ИСПОЛНЕНИЯ
    ($(…) / `…` / system( / | sh) не вырезаем: это уже не данные."""
    if idx is None or idx >= len(toks) or _base(toks[idx]) not in _SEARCH_CMDS:
        return toks, []
    drop, pat_seen, i = set(), False, idx + 1
    while i < len(toks):
        t = toks[i]
        if t.lower() in _PATH_FLAGS and i + 1 < len(toks):
            i += 2            # значение -Path/-LiteralPath — ОПЕРАНД-ФАЙЛ: сохраняем скану
            continue
        if t.lower() in _PATTERN_FLAGS and i + 1 < len(toks):
            drop.add(i + 1)
            pat_seen = True
            i += 2
            continue
        if t.startswith("-") and t != "-":
            i += 1
            continue
        if not pat_seen:
            drop.add(i)
            pat_seen = True
        i += 1
    keep, dropped = [], []
    for k, t in enumerate(toks):
        if k in drop and not _EXEC_IN_PATTERN.search(t):
            dropped.append(t)
        else:
            keep.append(t)
    return keep, dropped


def _mask(seg, dropped):
    """Убрать шаблоны из ТЕКСТА сегмента (в кавычках или без), сохранив всё прочее ДОСЛОВНО —
    red-скан не должен слабеть от переклейки токенов (на Windows shlex ест «\\» в путях).
    Форма не нашлась → текст как есть, то есть краснее."""
    out = seg
    for d in dropped:
        # Четвёртая форма — шаблон с ЭКРАНИРОВАННЫМИ кавычками внутри. shlex снимает `\"` до `"`,
        # и вырезание по литералу промахивалось: живой случай №7,
        # `grep -n -E "\.env|deny|\"model\"|clasp push" .claude/settings.json` — шаблон оставался
        # в скан-тексте, а вместе с ним и слово `.env`, дававшее карточку «обращение к секретам».
        for form in ('"' + d + '"', "'" + d + "'", d, '"' + d.replace('"', '\\"') + '"'):
            if d and form in out:
                out = out.replace(form, " ", 1)
                break
    return out


# ── ТЕЛО HEREDOC — ДАННЫЕ, А НЕ ОПЕРАЦИЯ (31.07.2026, третья часть пятой группы) ──────────────
# Тот же класс, что вырезание текста `git -m` и позиционных аргументов .py-скрипта: то, что
# команда ПЕРЕДАЁТ как текст, операцией не является. Живой журнал 30.07 — три карточки на
# сообщениях коммита, отданных через stdin (`git commit -F - <<'EOF' … EOF`): «хочу обратиться к
# .env» и «хочу изменить конфиг Claude Code» на строках, где эти имена просто НАЗВАНЫ в тексте
# сообщения. Плюс группа из пробы задачи 73: `cat > tmp/probe.py <<'PYEOF' … PYEOF` — пишется
# ЧЕРНОВИК, а путь конфига лежит в ТЕЛЕ скрипта, и карточка называла НЕВЕРНЫЙ объект.
#
# ЧТО НЕ ОСЛАБЛЕНО, намеренно и поимённо:
#   • ЗАГОЛОВОК КОМАНДЫ ОСТАЁТСЯ. `cat > .claude/settings.json <<'EOF'` — это по-прежнему запись
#     в конфиг: перенаправление стоит ДО тела и вырезанием не прячется;
#   • ТЕРМИНАТОР НЕ НАЙДЕН → не вырезаем НИЧЕГО (строка журнала, обрезанная 300 символами;
#     `1 << N` из кода). Непонятное остаётся красным — fail-safe, как везде в гарде;
#   • ЖИВОЙ ЛИСТ судится по тексту С ТЕЛОМ (см. `_decide_bash_body`): деньги и парк прячутся
#     даже в черновике;
#   • ТЕЛО, КОТОРОЕ ИСПОЛНЯЕТСЯ, — НЕ ДАННЫЕ. `bash <<'EOF' … EOF`, `python - <<'PY' … PY`,
#     `ssh host <<'EOF' … EOF`, `sqlite3 db <<EOF` подают телом КОМАНДЫ, а не текст: там оно
#     работает ровно как инлайн `-c`. Тот же приём, что уже принят в `_redirect_text` для
#     вложенных шеллов: строка-заголовок с интерпретатором отменяет вырезание ЦЕЛИКОМ.
_RE_HEREDOC = re.compile(r"<<-?\s*(?:'([^']+)'|\"([^\"]+)\"|([A-Za-z_][\w.-]*))")
_HEREDOC_EXEC = _NESTED_SHELLS | {"python", "python3", "py", "node", "perl", "ruby", "php",
                                  "sqlite3", "psql", "mysql", "ssh", "docker", "xargs"}


def _seg_runs_stdin_as_code(seg):
    """True ⇔ команда сегмента ИСПОЛНИТ то, что придёт ей на stdin (телом heredoc или трубой).

    ОДНА ГРАНИЦА, и она измерена (задача 87, 31.07.2026): `python` в списке стоит по праву —
    `python`, `python -` и `python -c …` действительно читают stdin как КОД. Но у
    `venv/Scripts/python.exe cowork_log_append.py` цель ИМЕНОВАНА, и stdin для неё — ДАННЫЕ,
    которые скрипт сам разбирает. Ровно этой разницы не было: `printf '%s' "…" |
    venv/Scripts/python.exe cowork_log_append.py` считался «текст становится кодом», текст
    оставался под сканом целиком, и имя файла секретов, НАЗВАННОЕ в журнальной строке, рождало
    карточку «хочу обратиться к секретам» на записи в мозг.

    Fail-safe как везде: сегмент не разобрался — считаем, что исполняет; интерпретатор без
    именованной цели — исполняет; всё, чего нет в `_HEREDOC_EXEC`, stdin не исполняет."""
    try:
        toks = shlex.split(seg or "")
    except Exception:
        return True                      # кавычки не разобраны → не вырезаем (краснее)
    j = _cmd_index(toks)
    if j is None or j >= len(toks):
        return False
    # `xargs` (и вообще обёртки) `_cmd_index` проходит НАСКВОЗЬ — ему нужна действующая команда.
    # Здесь вопрос другой: КТО СЪЕСТ stdin. У `… | xargs cat` его съедает обёртка и подаёт
    # прочитанное аргументом читалке — то есть текст становится операцией. Пропущенный префикс
    # обязан проверяться, иначе `echo ".env" | xargs cat` уехал бы зелёным.
    for t in toks[:j]:
        if _base(t) in _HEREDOC_EXEC:
            return True
    name = _base(toks[j])
    if name not in _HEREDOC_EXEC:
        return False
    if name in _PY_INTERP:
        rest = toks[j + 1:]
        if "-" in rest or "-c" in rest:
            return True                  # `python -` / инлайн-код: stdin и есть программа
        if "-m" in rest or any(t.lower().endswith(".py") for t in rest):
            return False                 # цель ИМЕНОВАНА → stdin ей ДАННЫЕ, а не код
    return True


def _line_runs_code(line):
    """True ⇔ в строке-заголовке есть команда, которая ИСПОЛНИТ тело heredoc (интерпретатор,
    вложенный шелл, ssh). Сбой разбора — тоже True: непонятное не вырезаем (fail-safe)."""
    for i, seg in enumerate(_split_segments(line or "")):
        if i % 2:
            continue
        if _seg_runs_stdin_as_code(seg):
            return True
    return False


def _strip_heredoc(cmd):
    """Команда без ТЕЛ heredoc: заголовок и сам терминатор сохранены, строки между ними убраны."""
    if not cmd or "<<" not in cmd:
        return cmd
    lines = cmd.split("\n")
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        out.append(line)
        i += 1
        if _RE_HEREDOC.search(line) and _line_runs_code(line):
            return cmd                    # телом подают КОД — вырезать нечего, всё под сканом
        for m in _RE_HEREDOC.finditer(line):
            delim = m.group(1) or m.group(2) or m.group(3)
            j = i
            while j < len(lines) and lines[j].strip() != delim:
                j += 1
            if j >= len(lines):
                return cmd                # терминатора нет → не угадываем, отдаём как есть
            out.append(lines[j])
            i = j + 1
    return "\n".join(out)


# ПЕЧАТЬ СВОЕГО АРГУМЕНТА — тоже данные. `echo "gspread.open('Лист1')"`, `Write-Output "зову
# create_booking(1)"` НИЧЕГО не исполняют: текст уходит в stdout. Признак `_PRINT_CMDS` уже
# принят гардом для секретов (`_env_probe_only`, живой факт задачи 55 — имя `.env` попало в
# карточку из ПОДПИСИ К ВЫВОДУ); здесь тот же довод распространён на скан-текст целиком.
# ТРИ ГУАРДА, каждый закрывает свой способ превратить печать в исполнение:
#   • перенаправление в сегменте (`echo '{}' > .claude/settings.json`) — это ЗАПИСЬ, не печать;
#   • труба ИЗ сегмента В ТО, ЧТО ИСПОЛНЯЕТ stdin (`echo "import gspread; …" | python`) — текст
#     становится КОДОМ. Именно «в то, что исполняет»: труба в ИМЕНОВАННЫЙ скрипт
#     (`… | venv/Scripts/python.exe cowork_log_append.py`) кодом текст не делает, см.
#     `_seg_runs_stdin_as_code` и шестую группу класса в шапке модуля;
#   • подстановка команды в самом аргументе (`echo "$(rm -rf x)"`) — аргумент исполняется.
# В любом из трёх случаев сегмент остаётся под сканом ЦЕЛИКОМ.
def _is_flag_token(tok):
    """Токен — ФЛАГ печати (`-n`, `-e`, `-NoNewline`), а не её текст.

    Раньше флагом считалось всё, что начинается с дефиса, — и подпись к выводу
    `echo "--- grep .env in journal bodies ---"` под это правило подпадала ЦЕЛИКОМ: текст
    оставался в скан-тексте и рождал карточку «хочу обратиться к секретам» (живой случай
    01.08.2026, пойман на собственной команде сессии). У флага пробелов внутри не бывает —
    этим и различаем; `echo "---"` без пробелов останется под сканом, и это безопасная сторона."""
    t = tok or ""
    return t.startswith("-") and not any(c.isspace() for c in t)


def _strip_print_args(seg, nxt="", rcv=""):
    """Сегмент-печать без своих аргументов; не печать или любой из трёх гуардов → как есть.
    `rcv` — СЛЕДУЮЩИЙ сегмент (получатель трубы): он и решает, станет ли текст кодом."""
    if _RE_REDIRECT.search(seg):
        return seg
    if (nxt or "").strip() == "|" and _seg_runs_stdin_as_code(rcv):
        return seg
    try:
        toks = shlex.split(seg)
    except Exception:
        return seg
    j = _cmd_index(toks)
    if j is None or j >= len(toks) or _base(toks[j]) not in _PRINT_CMDS:
        return seg
    dropped = [t for t in toks[j + 1:]
               if not _is_flag_token(t) and not _RE_ARG_EXEC.search(t)]
    return _mask(seg, dropped)


def _scan_text(cmd, keep_heredoc=False):
    """Текст для поиска КРАСНЫХ признаков. Исполняется всегда ИСХОДНАЯ команда — правится только
    то, по чему ищем. Внутри сегмента порядок: текст git -m → аргументы .py-скрипта → поисковый
    шаблон. Сегменты и разделители сохраняются, чтобы соседний кусок цепи остался под сканом.

    `keep_heredoc=True` оставляет тела heredoc на месте — этим текстом судят ЖИВОЙ ЛИСТ
    (fail-closed: запись в лист краснеет и из черновика)."""
    if not cmd:
        return cmd
    if not keep_heredoc:
        cmd = _strip_heredoc(cmd)
    out = []
    parts = _split_segments(cmd)
    for i, p in enumerate(parts):
        if i % 2:
            out.append(p)                       # разделитель — дословно
            continue
        clean = _strip_print_args(p, parts[i + 1] if i + 1 < len(parts) else "",
                                  parts[i + 2] if i + 2 < len(parts) else "")
        clean = _strip_script_cli_args(_strip_git_msg(clean))
        try:
            toks = shlex.split(clean)
        except Exception:
            out.append(clean)                   # кривое квотирование → сегмент как есть (краснее)
            continue
        _keep, dropped = _strip_search_pattern(toks, _cmd_index(toks))
        out.append(_mask(clean, dropped))
    return "".join(out)


# «Доверие по происхождению» (порт VPS a5c148e): файл ПОД git приехал в репо через review+git —
# его тело не сканируем, ровно тот же довод, что уже принят для test_*.py выше. Красное для всего
# остального НЕ ослаблено: инлайн -c/-m, сама команда, .env, живые таблицы и SQL-запись
# проверяются полностью, а НЕотслеживаемый .py по-прежнему читается и сканируется.
_TRACKED_CACHE = {}
_NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)   # без него git-проба мигала бы чёрным окном


def _is_repo_tracked(path, cwd):
    """True ⇔ .py-цель лежит внутри проекта и отслеживается git. git недоступен/ошибка → False
    (fail-safe: без доверия идём прежним путём — читаем и сканируем тело)."""
    if not path:
        return False
    for cand in (path, os.path.join(cwd or PROJECT, path), os.path.join(PROJECT, path)):
        try:
            ap = os.path.abspath(cand)
        except Exception:
            continue
        if not os.path.isfile(ap) or not _inside_project(ap):
            continue
        key = os.path.normcase(ap)
        if key not in _TRACKED_CACHE:
            try:
                rel = os.path.relpath(ap, PROJECT)
                p = subprocess.run(["git", "-C", PROJECT, "ls-files", "--error-unmatch", "--", rel],
                                   capture_output=True, text=True, timeout=5,
                                   creationflags=_NO_WINDOW)
                _TRACKED_CACHE[key] = (p.returncode == 0)
            except Exception:
                _TRACKED_CACHE[key] = False
        return _TRACKED_CACHE[key]
    return False


