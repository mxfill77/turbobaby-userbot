def _card_fields(kind, obj="", raw_cmd=""):
    """→ (объект, число). Объект — ЧТО именно трогаем (файл, хост, PID, проект); число — версия,
    PID, сколько целей. Пустая пара означает: признак сработал на ПОДСТРОКЕ, а не на действии."""
    o, n = (obj or "").strip(), ""
    cmd = raw_cmd or ""
    if kind == "delete":
        targets, _rec, _mask = _delete_scan(cmd)
        o = o or (targets[0] if targets else "")
        if targets:
            n = "%d цел%s" % (len(targets), "ь" if len(targets) == 1 else "и")
    elif kind == "kill":
        n = ""                      # число (PID) уже внутри объекта — второй строкой это шум
    elif kind == "schtasks":
        m = re.search(r"(?i)(?:/tn|-taskname)\s+[\"']?([^\"'\s;|&]+)", cmd)
        o = o or (m.group(1) if m else "")
    elif kind.startswith("clasp"):
        m = _RE_NUM_VERSION.search(cmd)
        if m:
            n = "версия " + m.group(1)
        else:
            d = re.search(r"(?i)-i\s+(\S{12,})", cmd)
            n = ("деплой …" + d.group(1)[-8:]) if d else ""
    elif kind == "git_force":
        m = re.search(r"(?i)git\s+(push|reset|clean)\b([^;|&]*)", cmd)
        o = o or ((m.group(1) + (" " + m.group(2).strip() if m.group(2).strip() else "")).strip()
                  if m else "")
    elif kind == "env":
        m = _RE_ENV.search(_scan_text(cmd)) if cmd else None
        o = o or (m.group(0).strip("'\" ") if m else "")
    elif kind == "live_sheet":
        # ДЕНЬГИ И ПАРК — FAIL-CLOSED. Объект обязателен: имя листа (вкладка, префикс диапазона
        # `Лист1!A1`, ключ таблицы, известное имя, хост живого контура), а если ничего не
        # извлеклось — карточка говорит об этом ЧЕСТНО и всё равно спрашивает. Раньше здесь был
        # только `_extract_host`, которого в питон-форме нет: объект оставался пустым, и правило
        # «нет объекта → журнал» глотало карточку на НАСТОЯЩЕМ обращении к листу.
        o = o or _extract_sheet(cmd) or LIVE_SHEET_UNKNOWN
    elif kind == "sqlite":
        # ИМЯ БАЗЫ — обязательный объект карточки записи (требование ТЗ 30.07.2026). Базу не
        # назвали в команде (`c.execute(…)` по соединению из переменной, имя в теле скрипта) —
        # берём ТАБЛИЦУ из запроса: это тоже объект, и он честный.
        o = o or _extract_db(cmd) or ""
        if not o:
            m = _RE_SQL_TABLE.search(cmd or "")
            o = ("таблица " + m.group(1)) if m else ""
    elif kind == "py_write" and o in _RED_PY_TOKENS:
        # ОБЪЕКТ ПРИШЁЛ ИМЕНЕМ ОПЕРАЦИИ: `_scan_python` отдаёт сюда токен `_RED_PY_TOKENS` —
        # это ДЕЙСТВИЕ, а не цель (карточка 136, блок правила у `_py_card_fields`). Меняем на
        # цель; не назвали цель — объекта нет, и карточку не выписывает `card_decision`.
        # Условие `o in _RED_PY_TOKENS` — то же, по которому вид держит красное (`_stays_red`):
        # деталь вроде «скрипт не прочитан» или «-m X» именем операции не является и остаётся
        # как была.
        o, n = _py_card_fields(cmd, o)
    # ОБЪЕКТ ВХОДИТ В КАРТОЧКУ ОДНОЙ СТРОКОЙ (`scrub_obj_field`, блок правила у `_RE_OBJ_LINE`):
    # его приносит исполнитель, и перенос строки внутри него дописывал в карточку вторую строку
    # служебного поля. Здесь же, а не только в `_card`, — потому что ЭТО ЖЕ значение возвращает
    # `card_object`, с которым сверяется «да» владельца: печатаемое и сверяемое обязаны совпадать.
    return scrub_obj_field(o)[0], n.strip()


def card_object(kind, obj="", raw_cmd=""):
    """ОБЪЕКТ, КОТОРЫЙ НАПЕЧАТАН В КАРТОЧКЕ, — и единственное, с чем сверяется «да» владельца.

    Та же привычка, что чинили 31.07 у класса одобрения: служебное значение читается ОТТУДА,
    куда его положил гард. Здесь — из того же места, откуда его читает глаз владельца. До этой
    правки совпадение держалось случайно (разбор и карточка называли объект одинаково), а как
    только карточка `py_write` стала называть ЦЕЛЬ вместо имени функции, «да» владельца на
    `tmp/x.txt` вернулось бы в гард сверкой с `os.remove` — то есть НЕ вернулось бы никогда:
    операция ходила бы по кругу. Fail-closed сохранён: пустой объект ключей не даёт."""
    try:
        return _card_fields(kind, obj, raw_cmd)[0]
    except Exception:
        return scrub_obj_field(obj)[0]      # и на аварийной ветке — ровно то, что печатается


def _rollback(kind, raw_cmd="", obj=""):
    """Одна строка отката. Для выкатки Apps Script собирается ПО КОМАНДЕ: тот же деплой, прежняя
    версия — ровно та строка, которой владелец сам откатывался (артефакт 2026-07-29). id деплоя
    маскируем хвостом: карточка обязана читаться, полный id есть в `clasp deployments`.
    Для `py_write` — ПО САМОЙ ОПЕРАЦИИ (`obj` = токен от `_scan_python`): у разрушения файла и
    у денежной проводки откат разный, а у неразобранной операции его нет вовсе."""
    if kind == "py_write":
        o = " ".join(str(obj or "").split())
        if o in _PY_FS_TOKENS:
            return _ROLLBACK_PY_FS
        if o in _PY_BRIDGE_TOKENS:
            return _ROLLBACK_PY.get(o) or _ROLLBACK["py_write"]
        return _ROLLBACK_PY_UNKNOWN
    if kind == "clasp_deploy":
        m = re.search(r"(?i)-i\s+(\S{12,})", raw_cmd or "")
        dep = ("…" + m.group(1)[-6:]) if m else "<deploymentId>"
        if re.search(r"(?i)(^|\s)clasp\s+undeploy\b", raw_cmd or ""):
            return "Откат: clasp deploy -i %s -V <снятая версия> (вернуть удалённый деплой)" % dep
        return "Откат: clasp deploy -i %s -V <прежняя версия из clasp deployments>" % dep
    return _ROLLBACK.get(kind, "Откат: обратной операцией вручную")


# ── ШАПКА ВЫСШЕГО ВИДА: одна строка делает ОБА дела ─────────────────────────────────────────
# Она и отличает карточку с первого взгляда (первый символ ⛔ вместо 🔴 — глаз ловит его ДО
# чтения слов, в списке уведомлений видна именно первая строка), и НАЗЫВАЕТ форму ответа.
# Одна строка, а не шапка+подвал: карточка обязана читаться за 3 секунды, и обычный вид не
# растёт ни на байт.
#
# ПОЧЕМУ РУКА НЕ СРАБОТАЕТ НА АВТОМАТЕ — довод, ради которого выбран именно ОБЪЕКТ В ОТВЕТЕ,
# а не вторая кнопка и не «ты уверен?»:
#   1) «да» и «да 12» — ФИКСИРОВАННАЯ моторная программа: одни и те же символы, одна и та же
#      длина, и её можно выполнить, ещё НЕ ПРОЧИТАВ карточку (номер виден в шапке очереди).
#      Ровно так сегодня прошли три `live_sheet` подряд. Имя объекта из карточки НЕЛЬЗЯ узнать
#      заранее: оно разное у каждой операции и лежит ВНУТРИ текста. Чтобы ответить, руке
#      сначала нужен глаз.
#   2) Это не второе подтверждение того же рода. «Ты уверен?» дважды подряд рука осваивает за
#      день (двойное «да» становится одной программой); переписывание объекта — ДРУГОЙ акт:
#      не согласие, а сверка. Автоматизировать нечего — каждый раз другой текст.
#   3) Цена промаха — круг, а не запись. Короткое «да» и «да» с ЧУЖИМ объектом одинаково НЕ
#      исполняют операцию (`approval_covers`): она вернётся владельцу, а не уйдёт в лист.
#   ГРАНИЦА ЧЕСТНО: объект можно списать из карточки, не вникая в смысл. Но списать его нельзя,
#   не посмотрев В КАРТОЧКУ и не найдя в ней ту самую строку, — а именно этот шаг и пропускался.
TOP_TIER_BANNER = "⛔ ВЫСШАЯ ЦЕНА · НЕОБРАТИМО · подтверждение только с объектом: «да %s»"


def _card(kind, obj="", raw_cmd=""):
    """Человеческая карточка. Обязательный минимум за 3 секунды: ЧТО меняется (первая строка),
    у какого ОБЪЕКТА, какое ЧИСЛО и одна строка ОТКАТА. Сырая команда — последней и обрезанной:
    она для прозрачности, а не для чтения. У ВЫСШЕГО вида сверху добавляется ОДНА строка-шапка
    (`TOP_TIER_BANNER`): вид виден до чтения, и форма ответа названа тут же."""
    o, n = _card_fields(kind, obj, raw_cmd)
    # ОБЕ подписанные строки стоят ВСЕГДА, пустое значение — честный прочерк (формат общий с
    # полосой сервера). Раньше строка «Число» при пустом значении просто исчезала, и владелец не
    # мог отличить «числа у операции нет по природе» от «карточка его потеряла».
    # Фраза карточки вклеивает объект В ГОЛОВНУЮ строку — значит и она обязана остаться ОДНОЙ
    # строкой: иначе поддельное служебное поле встаёт ВЫШЕ честного (`scrub_obj_field`).
    lines = ["🔴 " + _human(kind, scrub_obj_field(obj)[0]) + " — разрешить?",
             OBJ_LINE_PREFIX + (o or "—"),
             "Число: " + (n or "—")]
    lines.append(_rollback(kind, raw_cmd, obj))
    if raw_cmd:
        c = " ".join(raw_cmd.split())
        lines.append("Команда: " + (c if len(c) <= 200 else c[:200] + "…"))
        # ВТОРАЯ ОПЕРАЦИЯ ТОЙ ЖЕ СТРОКИ — названа, а не спрятана (корень В, склейка ПО КОМАНДЕ).
        # Ставится ПОСЛЕ команды: карточка читается за 3 секунды, и обычный однооперационный
        # случай не растёт ни на байт (замер: строка появляется у 0,02% живых команд).
        second = other_ops_in_command(kind, raw_cmd)
        if second:
            lines.append(SECOND_OP_MARK % ", ".join(second))
    if is_top_tier(kind) and _object_named(o):
        lines.insert(0, TOP_TIER_BANNER % _reply_key(o))
    # СКРАБ ЧУЖОГО ШТАМПА КЛАССА — здесь, у рождения карточки, а не только на входе в маркер:
    # объект операции приносит исполнитель, и его перенос строки доезжает во ВСЕ каналы разом
    # (интерактивный ответ хука, пуш владельцу, файл-маркер). След видимый: подделка обязана
    # быть заметна там же, где владелец читает карточку.
    card = scrub_kind_stamp("\n".join(lines))[0]
    forged = card.count(OBJ_FIELD_MARK)
    if forged:
        # Та же доктрина лога, что у штампа класса: попытка подделки обязана оставить строку, а
        # не только пометку в тексте — иначе разбор следующего случая начнётся с нуля.
        _log("guard", "card", "scrub", "obj_field",
             "снято чужое имя служебного поля из объекта операции ×%d" % forged)
    return card


def _deny_text(kind, obj="", raw_cmd=""):
    """Отказ вместо карточки высшего вида без названного объекта. Формулировка ОБУЧАЮЩАЯ: она
    говорит, что именно сделать, чтобы операция стала подтверждаемой, — иначе отказ читается как
    поломка гарда и его начинают обходить."""
    lines = ["⛔ ОТКАЗ: высшая цена, а ОБЪЕКТ НЕ НАЗВАН — " + _human(kind, ""),
             "Карточка высшего вида без объекта не выписывается: подтверждать в ней нечего, "
             "а подтвердить её можно (так сегодня прошла карточка «лист не определён»).",
             "Что делать: назови объект В САМОЙ КОМАНДЕ (имя листа, путь файла, PID, id деплоя) "
             "и повтори — придёт карточка с объектом. Операция НЕ выполнена."]
    if obj and str(obj).strip():
        lines.append("Гард смог сказать только: " + scrub_obj_field(obj)[0])
    if raw_cmd:
        c = " ".join(raw_cmd.split())
        lines.append("Команда: " + (c if len(c) <= 200 else c[:200] + "…"))
    return "\n".join(lines)


def card_gate(kind, obj, num=""):
    """ЕДИНОЕ ПРАВИЛО КАРТОЧКИ, общее с полосой сервера (29.07.2026) → True = карточка, False = журнал.

        • ОБЪЕКТ обязателен ВСЕГДА — для ОБЫЧНОГО вида. Нет объекта — признак сработал на
          ПОДСТРОКЕ, а не на действии: показывать владельцу нечего, идёт строка в журнал.
        • ЧИСЛО карточку НЕ гейтит НИКОГДА. Оно есть там, где операция несёт его ПО СВОЕЙ ПРИРОДЕ
          (сумма, пробег, количество целей, версия, PID), и честно пусто там, где не несёт.
        • Hard-блок и секреты (_HARD_CARD) спрашивают всегда — как и было. Деньги тоже.
        • ВЫСШИЙ ВИД (`_TOP_TIER`) — тоже всегда: решать, что с ним делать, обязан
          `card_decision`, а не эта функция. Без объекта он получит там `deny`. Разбор — ниже.

    ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ПРЕЖНЕГО ПК-ПРАВИЛА. Было «пусто И объект, И число → журнала», то есть
    безобъектная команда, в которой нашлась ЛЮБАЯ цифра, карточку РОЖДАЛА. Полоса сервера в тот же
    день гасила карточку при отсутствии объекта ИЛИ числа и потому молча съедала операции без
    числа по природе. Одно правило вместо двух: объект — гейт, число — поле.

    ПОЧЕМУ ВЫСШИЙ ВИД ВЫВЕДЕН ИЗ-ПОД ГЕЙТА ОБЪЕКТА (правка 02.08.2026, класс A-54). Правило
    «нет объекта → журнал» стояло на ПОСЫЛКЕ «нет объекта ⇔ признак поймал подстроку». Посылка
    была верна 29.07 и УМЕРЛА 31.07, когда замок `_verb_acts` перенёс отсев подстроки на слой
    раньше — в `_decide_bash_body`: имя-команду признают признаком, только если она стоит в
    КОМАНДНОЙ ПОЗИЦИИ. Собственный живой пример прежнего докстринга (`echo "---SCHTASKS XML---"`
    внутри `ls`) сюда больше не доходит вовсе — он умирает в `decide` видом `word_schtasks`.
    Значит для видов таблицы «пустой объект» с тех пор означает НЕ «поймали слово», а
    «ДЕЙСТВИЕ РАЗОБРАНО, а цель не извлеклась» — то есть ровно тот случай, ради которого
    высший вид и заведён. Две верные правки, сложенные вместе, дали неверное поведение.

    ЗАМЕР 02.08.2026 полным конвейером (`decide` → `decide_for_role` → `card_decision`), четыре
    фикстуры остановки процессов, все — `ask|kill`, объект пуст, решение `journal`, `sys.exit(0)`,
    операция ИСПОЛНЯЕТСЯ:
        taskkill /F /T /FI "IMAGENAME eq python.exe"   ← сносит ВСЕ python на машине: живых
                                                          ботов, демона и сам процесс задачи
        Get-Process python | Stop-Process -Force        ← то же конвейером PowerShell
        Stop-Process -InputObject $p -Force             ← цель в переменной
        kill -9                                          ← цель не названа вовсе
    Ни одна из четырёх не была подстрокой: `_verb_acts` подтвердил командную позицию у каждой.
    Место, которое мы считали отказом, было записью в журнал. Теперь оно отказывает.

    ЦЕНА И ЕЁ НАПРАВЛЕНИЕ. Ошибиться можно в обе стороны, и стороны неравны: лишний `deny`
    стоит одного круга (модель получает обучающий текст `_deny_text` и повторяет команду, назвав
    цель), пропущенный снос живого бота не стоит ничего вернуть. Fail-closed: не удаётся решить
    достоверно — операция не проходит.

    ЧТО ЗДЕСЬ НЕ ЗАКРЫТО И НАЗВАНО ЧЕСТНО: у ОБЫЧНОГО вида (`schtasks`, `network`, `git_force`,
    `sqlite`) та же посылка мертва ровно так же, но правило журнала оставлено как было — цена
    ошибки у них по списку владельца обратима, а замер частоты ложных срабатываний для них не
    делался. Это остаток, а не доказанная безопасность."""
    return bool((obj or "").strip()) or kind in _HARD_CARD or is_top_tier(kind)


def card_decision(kind, obj="", raw_cmd=""):
    """→ (решение, текст), решение ∈ ask | journal | deny. Единственная точка, где вид карточки
    превращается в поведение.

        ask     — карточка как была (обычный вид; высший вид — с шапкой);
        journal — признак сработал на ПОДСТРОКЕ, а не на действии (правило `card_gate`);
        deny    — ВЫСШИЙ вид, а объект не назван: карточку не выписываем ВОВСЕ.

    Про `deny` отдельно, потому что это единственное место, где гард ЗАПРЕЩАЕТ, а не спрашивает.
    Позиция «хук только добавляет подтверждения» не нарушена: `deny` строже `ask`, новых
    разрешений он не выдаёт. Повод буквальный: 31.07 пришла карточка `live_sheet` с объектом
    «лист не определён» — и её МОЖНО БЫЛО ПОДТВЕРДИТЬ. Подтверждение необратимого вслепую хуже
    отказа: отказ стоит одного круга, запись в живой лист не стоит ничего вернуть.
    ГРАНИЦА (переставлена 02.08.2026, класс A-54): у ВЫСШЕГО вида исключений НЕТ — нет объекта,
    значит `deny`, и в журнал он не уходит никогда. Прежняя граница звучала «`deny` бьёт только
    там, где карточка иначе бы родилась», и держалась на посылке «нет объекта ⇔ признак поймал
    подстроку»; посылку убил замок `_verb_acts` (31.07), отсеивающий подстроку слоем раньше.
    Цена ошибки: замер 02.08 показал ЧЕТЫРЕ фикстуры остановки процессов (включая `taskkill /F
    /T /FI "IMAGENAME eq python.exe"` — снос всех python на машине), которые шли `journal` и
    ИСПОЛНЯЛИСЬ. Разбор и числа — в докстринге `card_gate`.
    Обычный вид не тронут: у него «нет объекта → журнал» осталось как было (остаток назван там же).
    Любой сбой разбора → ask (FAIL-SAFE, как было)."""
    try:
        o, n = _card_fields(kind, obj, raw_cmd)
        if not card_gate(kind, o, n):
            return ("journal", "")
        if is_top_tier(kind) and not _object_named(o):
            # Подсказка отказа — `o or obj`: у `py_write` цель не извлеклась и `o` пуст, но
            # ИМЯ операции гард знает. Без него модель не поймёт, что именно назвать в команде,
            # и обучающий текст перестанет обучать.
            return ("deny", _deny_text(kind, o or obj, raw_cmd))
    except Exception:
        pass
    return ("ask", _card(kind, obj, raw_cmd))


def card_or_journal(kind, obj="", raw_cmd=""):
    """→ текст карточки либо None (карточки нет). Тонкая обёртка над `card_decision` — оставлена
    прежней по сигнатуре: ею пользуются вызывающие, которым нужен только текст карточки."""
    decision, text = card_decision(kind, obj, raw_cmd)
    return text if decision == "ask" else None


