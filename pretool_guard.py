def is_test_run(env=None):
    """Идёт ли ТЕСТ-ПРОГОН с точки зрения САМОГО ХУКА — в том числе когда его запустили
    ПОДПРОЦЕССОМ. Почему подпроцесс это увидит: тесты и гейт строят окружение как
    `dict(os.environ)` и отдают его в `subprocess.run(env=…)`, а переменные наследуются ВНИЗ по
    дереву процессов (в отличие от патча константы в памяти теста). Почему это НЕ спутать с боем:
    демон снимает все четыре имени с окружения боевого ребёнка, в живой headless-задаче их нет
    ФИЗИЧЕСКИ. Сверка на НЕПУСТОТУ, а не на `== "1"` (как читал прежний `_push`): значение вроде
    `0` в имени тест-флага ставит только тот, кто уже думает про тест-режим."""
    e = os.environ if env is None else env
    return any((e.get(k) or "").strip() for k in _TEST_RUN_ENVS)


def _cmd_declares_probe(cmd):
    """Объявила ли САМА КОМАНДА, что она проба: ведущий env-префикс `VAR=1 …` с одним из
    `_TEST_RUN_ENVS`. Читаем РОВНО ведущие присваивания (до первого не-`VAR=val` токена) — имя
    переменной в середине строки (в аргументе, в кавычках, в пересказе) объявлением НЕ является,
    иначе пометкой стал бы любой текст ПРО пробы: тот самый класс born-false, что закрывали у
    секретов 01.08 (`f4c3cff`). Сбой разбора → False (в сторону боя, не тише)."""
    try:
        toks = shlex.split(cmd or "")
    except Exception:
        toks = (cmd or "").split()        # то же смягчение, что у прочих разборщиков Windows-путей
    for t in toks:
        if not _RE_ENV_ASSIGN.match(t):
            return False                  # ведущие присваивания кончились — дальше уже команда
        name, _, val = t.partition("=")
        if name in _TEST_RUN_ENVS and val.strip():
            return True
    return False


# .py-цель ЦЕЛИКОМ, ВМЕСТЕ С ПУТЁМ. Соседний `_RE_PY_FILE` намеренно отдаёт только ИМЯ файла
# (его дело — «все ли цели тестовые»), и для места запуска он не годится: `D:/…/tmp/fx.py` он
# отдаёт как `fx.py`, а такой путь `_is_temp_zone` честно считает файлом в корне репо. Замер это
# и поймал — первая версия правки пропустила обе «пробы по месту» из четырёх.
_RE_PY_TARGET = re.compile(r"(?i)([^\s\"';|&]+\.py)(?=[\s\"';|&]|$)")


def _is_probe_script(cmd):
    """Проба ПО МЕСТУ ЗАПУСКА: .py-цель лежит во ВРЕМЕННОЙ зоне репозитория (`tmp/**`,
    .gitignore) или в скретчпаде сессии, либо названа одноразовой (`test_*`, `tmp_*`, `*_test*`,
    `*_dryrun*`). Раз эти каталоги объявлены черновиковыми, запуск ОТТУДА — проба по определению:
    замер 01.08 нашёл в них 100 пробных скриптов и НИ ОДНОГО под git.
    ЧЕСТНЫЙ ПРЕДЕЛ: настоящая разовая операция, запущенная оттуда, карточки владельцу тоже не
    даст — но она при этом и НЕ ИСПОЛНИТСЯ (решение остаётся ask/deny), а исполнитель увидит
    перехват с полным текстом и повторит вызов из нормального места."""
    for f in _RE_PY_TARGET.findall(cmd or ""):
        if _is_temp_zone(f) or _is_scratchpad(f) or _is_test_target(f):
            return True
        b = os.path.basename(f).lower()
        if b.startswith("tmp_") or "_test" in b or "_dryrun" in b:
            return True
    return False


def is_probe(cmd="", env=None):
    """ЕДИНЫЙ признак пробы для ОБОИХ каналов владельца. Три источника, любой достаточен:
      • окружение хука (`_TEST_RUN_ENVS`) — работает для гейта и тест-подпроцессов;
      • env-префикс в самой команде — единственный, доступный пробе ВНУТРИ живой задачи;
      • место/имя запускаемого скрипта — прежняя эвристика ПК, теперь гасящая ОБА канала."""
    return is_test_run(env) or _cmd_declares_probe(cmd) or _is_probe_script(cmd)


def set_probe(on):
    """Взвести латч пробы на весь прогон хука. ПОЧЕМУ ЛАТЧ, А НЕ ПАРАМЕТР: к каналам владельца
    ведут ТРИ места (`_write_marker`, `_push`, текст решения), параметр пришлось бы протаскивать
    в каждое, и СЛЕДУЮЩАЯ добавленная ветка про него забыла бы — ровно так и появилась течь,
    которую мы чиним. Латч закрывает ветки ПО ПОСТРОЕНИЮ."""
    global _PROBE_LATCH
    _PROBE_LATCH = bool(on)


def isolated(env=None):
    """Идёт ли изоляция каналов владельца: тест-прогон по окружению ИЛИ взведённый латч пробы.
    ЕДИНСТВЕННЫЙ источник правды для `marker_path`, `_push` и текста решения."""
    return is_test_run(env) or _PROBE_LATCH


def marker_path(mk, env=None):
    """Куда ЛОЖИТСЯ файл-маркер. В бою — ровно туда, куда указал демон. В пробе — СОСЕДНИЙ файл
    с префиксом: демон открывает имя, которое сам же назначил (`pc_ask_<id>.marker`), и пробный
    файл ему невидим — даже если путь почему-то остался боевым. Путь считается В МОМЕНТ ЗАПИСИ,
    поэтому развод работает и для хука-подпроцесса."""
    d, n = os.path.split(str(mk or ""))
    if not n or not isolated(env):
        return mk
    return os.path.join(d, PROBE_MARKER_PREFIX + n)


def _probe_intercept(card, mk=""):
    """ПЕРЕХВАТ НА ГРАНИЦЕ: владельцу не ушло ничего, а ИСПОЛНИТЕЛЬ видит ДОСЛОВНО то, что
    собиралось уйти, и каким каналом. Без этого изоляция неотличима от поломки: проба молча
    «ничего не делает», и автор пробы не знает, сработал ли гард вообще, — а ровно ради ответа на
    этот вопрос пробу и запускают. Текст идёт в решение хука (его читает исполнитель задачи), НЕ
    в канал владельца."""
    where = marker_path(mk) if mk else "не пишется (PRETOOL_ASK_MARKER пуст)"
    return ("🧪 ПРОБА — ПЕРЕХВАЧЕНО НА ГРАНИЦЕ. Владельцу НЕ ушло ничего ни одним каналом.\n"
            "  канал 1 (прямой пуш в тему-инбокс / личку): подавлен;\n"
            "  канал 2 (маркер → демон → карточка с кнопками): уведён в пробный файл → %s.\n"
            "Решение гарда НЕ ослаблено: без «да» команда не исполнится, отказ остаётся отказом, "
            "секреты остаются секретами.\n"
            "%s\n%s" % (where, PROBE_CARD_SEP, card))


def card_from_decision(reason):
    """ТЕКСТ КАРТОЧКИ из решения хука — оттуда, где он лежит, а не «весь текст решения».
    В бою решение и есть карточка; в пробе оно обёрнуто перехватом, и карточка стоит ДОСЛОВНО
    после разделителя. Функция нужна не гарду, а читателям решения (тесты, разбор): без неё
    каждый второй начинал бы резать текст своей регуляркой — ровно тот корень А, из-за которого
    служебные значения ищут поиском по свободному тексту вместо канонического места."""
    parts = str(reason or "").split(PROBE_CARD_SEP + "\n")
    return parts[-1]


def _push(card):
    """КАНАЛ 1 к владельцу. Глушение живёт ВНУТРИ отправителя, а не на месте вызова: так
    «гард решил отправить карточку» и «карточка ушла» остаются РАЗНЫМИ событиями — первое видно
    тесту, второе физически не происходит. Прежняя развилка на месте вызова означала бы, что в
    пробе отправитель не звался вовсе, и регресс «боевая операция карточку рождает» проверить
    было бы нечем: он одинаково молчал бы и когда всё хорошо, и когда канал сломан."""
    if isolated():
        return None   # проба/тест-прогон: ЕДИНЫЙ признак (прежде здесь стоял ТОЛЬКО
                      # PRETOOL_NOPUSH, и проба с любым другим флагом пушила владельцу в бой)
    cnt = (os.environ.get(NOTIFY_COUNT_ENV) or "").strip()
    if cnt:
        # МОК-СЧЁТЧИК (порт `notify.NOTIFY_COUNT_FILE` серверной полосы): тест видит ПОПЫТКУ
        # отправки, а сеть не дёргается вовсе — счётчик стоит ДО спавна отправителя.
        try:
            with open(cnt, "a", encoding="utf-8") as f:
                f.write(" ".join(str(card or "").split())[:200] + "\n")
        except Exception:
            pass
        return None
    try:
        subprocess.Popen(
            [VENV_PY, DNOTIFY, card],
            cwd=PROJECT,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL,
        )
    except Exception:
        pass  # пуш вторичен — не роняем решение
    return None


MARKER_TOKEN_ENV = "PRETOOL_MARKER_TOKEN"   # токен запуска демона: штампуем им каждую строку карточки,
MARKER_SEP = "\x1f"                          # чтобы демон принимал только карточки СВОЕГО запуска
# ТЕЛО ОДНОГО БЛОКА — потолок, ИЗМЕРЕННЫЙ, а не назначенный, и зажатый с ДВУХ сторон:
#   снизу — самая длинная ЗАКОННАЯ карточка. Замер по всем видам с предельными законными
#     значениями (объект длиной с MAX_PATH Windows 260, команда, обрезаемая до 200): максимум
#     1182 символа (`py_write`), обычная живая карточка — 178. Тест
#     `test_marker_card_max_fits_real_cards` меряет это заново и падает, если формат карточки
#     перерастёт порог: тогда порог пересчитывают, а не режут живые карточки молча;
#   сверху — обрезка демона `RESULT_MAX` (4500): при этом потолке под неё влезают ТРИ полных
#     блока со штампами, то есть штатный многоблочный маркер ПК не теряет ни одного класса
#     (`test_marker_card_max_leaves_room_for_three_blocks` в тестах демона).
# Зачем потолок вообще: объект-переросток ВЫТЕСНЯЛ настоящий штамп класса за обрезку демона, и
# «да» владельца возвращалось не двумя классами, а ЧУЖИМ вместо своего (замер D2 пробы).
MARKER_CARD_MAX = 1400
CARD_CUT_MARK = "…(тело карточки обрезано под штамп класса)"


def _fit_body_under_stamp(card, room=MARKER_CARD_MAX):
    """Обрезать ТЕЛО карточки до `room` так, чтобы после него поместился штамп класса.
    Режем ПО ГРАНИЦЕ СТРОК и оставляем видимую метку: обрезка обязана быть заметна, иначе
    урезанная карточка читается как полная."""
    c = str(card or "")
    if len(c) <= room:
        return c
    out, used = [], 0
    for ln in c.splitlines():
        if used + len(ln) + 1 > room:
            break
        out.append(ln)
        used += len(ln) + 1
    if not out:                       # первая же строка длиннее потолка — режем её саму
        out = [c[:room]]
    out.append(CARD_CUT_MARK)
    return "\n".join(out)


