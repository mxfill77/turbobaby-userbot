# ЧТО БЫЛО. Последняя строка `decide` отдавала `("defer","","")` ЛЮБОМУ имени вне семи, с
# комментарием «Grep/Glob/прочие read-only инструменты» — то есть предполагалось, что всё
# остальное безобидно. `defer` при этом НЕ вопрос и НЕ отказ: `main` на нём делает `sys.exit(0)`
# без единой строки вывода, а хук, не напечатавший `permissionDecision`, решения не принимает
# вовсе — его принимает glob-слой, где в `allow` стоят `Bash`, `Bash(*)`, `PowerShell`,
# `PowerShell(*)`, `Read`. Незнакомый КАНАЛ проходил. Молча.
#
# ПОЧЕМУ ЭТО КЛАСС, А НЕ ЧАСТНОСТЬ (он уже стрелял и оплачен). `PowerShell` — отдельный
# инструмент от `Bash`, и до правки он не стоял ни в matcher, ни здесь: `PowerShell(Remove-Item …)`
# шёл мимо красного гейта ЦЕЛИКОМ. Операция была ровно та же — красной она не была из-за ИМЕНИ
# КАНАЛА. Тот же механизм жив у каждого нового имени: `Task`, `WebFetch`, `SlashCommand`, любой
# `mcp__*` коннектор (правило владельца «Drive-коннектор красный» существует только прозой).
#
# ЧТО ТЕПЕРЬ. Имя, которого здесь нет, — не «read-only по умолчанию», а НЕИЗВЕСТНЫЙ КАНАЛ:
# `KIND_UNKNOWN_TOOL`, доктринально красный (`_stays_red`) и обязательный к карточке
# (`_HARD_CARD`). Fail-closed, той же стороной, что и сбой разбора самого гарда: лишняя карточка
# стоит одного круга, тихо прошедшая операция не стоит ничего вернуть.
#
# ПОЧЕМУ РЕЕСТР, А НЕ `if` ЕЩЁ НА ОДНО ИМЯ. Реестр читает СТОРОЖ
# (`test_pretool_guard.TestChannelRegistry`) той же формой, что `_ACTION_CHECK` читает
# `test_free_signs_declare_action_check`: список каналов ВЫВОДИТСЯ — гардованные имена сверяются
# с ЖИВЫМ matcher из боевого `.claude/settings.json` и с именами, которые различает исходник
# `decide` (через `ast`), в ОБЕ стороны. Поэтому новый канал накрывается замком САМ, а не когда
# правящий вспомнит дописать имя. До этого живой matcher был закреплён ОДНИМ литералом
# (`PowerShell`), остальные шесть имён — только в подготовленном образце, и там их пять.
#
# ГРАНИЦА ЧЕСТНАЯ, И ОНА УЖЕ. Реестр называет каналы, а не делает их безопасными: он покрывает
# ровно тот канал, где гард стоит, — вызов инструмента процессом с `cwd`=репо. Имя вне matcher
# сюда не доходит вовсе (хук на нём не запускается), и fail-closed для него — это готовность к
# тому дню, когда имя в matcher добавят, плюс сторож, который этот день заметит. Каналы «демон
# своей рукой», `pc_agent`, ряд очереди Моста и полоса VPS остаются вне: это отдельный заход.
CHANNEL_GUARD = "guard"   # канал ГАРДОВАН: имя ведёт к решающей функции, вид назначается здесь
CHANNEL_GREEN = "green"   # сознательно БЕЗ гарда, держатель НАЗВАН (пустой держатель = дефект)

_TOOL_CHANNELS = {
    # ── гардованы: множество обязано совпасть с ЖИВЫМ matcher, обе стороны стережёт сторож ──
    "Bash":         (CHANNEL_GUARD, "_decide_bash — разбор команды оболочки"),
    "PowerShell":   (CHANNEL_GUARD, "_decide_bash — тот же разбор; на этом ПК основной инструмент"),
    "Edit":         (CHANNEL_GUARD, "_decide_write — цель правки"),
    "Write":        (CHANNEL_GUARD, "_decide_write — цель записи"),
    "MultiEdit":    (CHANNEL_GUARD, "_decide_write — цель правки"),
    "NotebookEdit": (CHANNEL_GUARD, "_decide_write — цель правки"),
    "Read":         (CHANNEL_GUARD, "_decide_read — секреты и выход за пределы репо"),
    # ── сознательно зелёные: держатель — ПРИРОДА инструмента, а не наше доверие к нему ──
    # Оба ищут и возвращают текст: не пишут файлов, не удаляют, не поднимают процесс, не ходят в
    # сеть. Стоят здесь ИМЕННО ЗАПИСЬЮ, а не общим правилом «остальное зелёное»: общее правило
    # и было дырой. Добавлять сюда имя = утверждать, что у канала НЕТ побочного действия.
    "Grep":         (CHANNEL_GREEN, "поиск по СОДЕРЖИМОМУ файлов, только чтение"),
    "Glob":         (CHANNEL_GREEN, "поиск по ИМЕНАМ файлов, только чтение"),
}

KIND_UNKNOWN_TOOL = "unknown_tool"   # канал вне реестра: гард про него не знает ничего
UNNAMED_TOOL = "имя инструмента не названо"


def channel_status(tool):
    """Статус канала по имени инструмента → CHANNEL_GUARD | CHANNEL_GREEN | '' (нет в реестре)."""
    return (_TOOL_CHANNELS.get((tool or "").strip()) or ("", ""))[0]


def decide(data):
    """Чистая классификация: → ('defer','','') или ('ask', kind, obj). Без I/O."""
    tool = data.get("tool_name") or ""
    ti = data.get("tool_input") or {}
    cwd = data.get("cwd") or PROJECT
    if tool in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        return _decide_write(ti, cwd)
    if tool == "Read":
        return _decide_read(ti, cwd)
    # PowerShell — ОТДЕЛЬНЫЙ инструмент от Bash, и на этом ПК он основной. До правки он не
    # попадал ни в matcher хука, ни под классификацию: `PowerShell(Remove-Item …)` проходил
    # мимо КРАСНОГО гейта целиком. Красные признаки (Remove-Item / Stop-Process /
    # Invoke-WebRequest / .env) уже описаны в _RED_CMD в PowerShell-форме — переиспользуем их.
    if tool in ("Bash", "PowerShell"):
        return _decide_bash(ti.get("command") or "", cwd)
    if channel_status(tool) == CHANNEL_GREEN:
        return ("defer", "", "")          # держатель НАЗВАН в реестре, см. `_TOOL_CHANNELS`
    # Канала нет в реестре: не «read-only по умолчанию», а неизвестный канал → fail-closed.
    return ("ask", KIND_UNKNOWN_TOOL, (tool or "").strip() or UNNAMED_TOOL)


