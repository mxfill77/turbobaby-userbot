# Живой факт двух карточек одного вечера: согласие на лёгкую часть становилось согласием на
# тяжёлую, потому что маркер ДОПИСЫВАЛСЯ, а демон склеивал все блоки прогона в ОДНУ карточку.
#   • 144: безобидный листинг (блок 1, он же голова уведомления) + боевая запись Bridge (блок 2,
#     в превью не видна). К моменту отправки операции блока 2 не существовало уже 31 минуту;
#   • 145: уборка `tmp/srv-audit`, от которой отказались через 5 секунд, + чтение секретов
#     восемью минутами позже. Одно «да» вернуло бы в гард `delete,env` — ДВА класса.
# Обе пришлось отклонить, работа обеих задач пропала.
#
# ПРАВИЛО: первая красная операция прогона — ПОСЛЕДНЯЯ. Маркер несёт РОВНО ОДИН блок; вторая
# красная операция карточки не выписывает (её решение — по-прежнему отказ, она НЕ исполняется),
# а прогон обязан остановиться и доложить. Карточки идут ПО ОЧЕРЕДИ: следующий заход упрётся в
# оставшееся красное и родит свою карточку — с собственным объектом и собственным «да».
#
# ПОЧЕМУ ЛАТЧ ЖИВЁТ В ФАЙЛЕ, А НЕ В ПАМЯТИ: хук — отдельный процесс на КАЖДЫЙ вызов инструмента,
# общей памяти у них нет. Признак «блок этого прогона уже есть» читается оттуда же, куда пишется,
# и опознаётся ШТАМПОМ ТОКЕНА запуска: чужие/старые блоки латчем не являются (демон их и так
# игнорирует), поэтому файл с одними чужими блоками мы ПЕРЕЗАПИСЫВАЕМ своим — как на полосе VPS,
# где маркер кладётся атомарной заменой, а не дописыванием.
#
# ГРАНИЦА ЧЕСТНО: вторая операция пропадает из КАРТОЧКИ, но не из следа — строка её решения
# стоит в логе гарда, а исполнителю возвращается текст, прямо называющий остановку прогона.
MULTI_OP_NOTE = ("🔴 ВТОРАЯ КРАСНАЯ ОПЕРАЦИЯ ЭТОГО ПРОГОНА — карточка НЕ выписана.\n"
                 "Владельцу уже ушла карточка на ПЕРВУЮ красную операцию, и одна карточка несёт "
                 "ровно одну операцию: иначе «да» на лёгкую часть открывает тяжёлую.\n"
                 "Операция НЕ выполнена. Останови прогон и доложи: что сделано, на чём упёрся и "
                 "какая операция ждёт своей карточки. Следующий заход спросит про неё отдельно.\n"
                 "%s\n%s")


def _write_marker(mk, card, kind=""):
    """Записать красную карточку в файл-маркер headless-сигнала → True (записали) | False
    (латч: блок этого прогона уже стоит, карточка НЕ выписана — см. блок-правило выше).

    Последней строкой блока идёт КЛАСС операции (`KIND_LINE_PREFIX`) — он нужен демону, чтобы
    после «да» владельца вернуть одобрение ИМЕННО на этот класс (см. `kinds_from_card`). Строка
    живёт ТОЛЬКО в headless-канале: текст интерактивной карточки не меняется ни на байт.
    Формат строки: '<run_token>\\x1f<строка карточки>'. Токен из env PRETOOL_MARKER_TOKEN —
    задаёт демон на КАЖДЫЙ запуск; так демон отсеивает чужие/старые карточки (напр. фикстуры
    из subprocess-тестов гарда, унаследовавших боевой маркер).

    ДЕДУП СНЯТ ЗА НЕНАДОБНОСТЬЮ: он лечил «одно действие ретраится → карточка набегает ×5»
    совпадением ТЕЛА блока, то есть повтор ловил, а вторую РАЗНУЮ операцию пропускал. Латч
    первой красной закрывает оба случая разом и по построению.

    РАЗВОД БОЕВОГО И ПРОБНОГО ПУТИ СТОИТ ЗДЕСЬ, а не у вызывающего: маркер — канал 2 к владельцу,
    и следующая ветка, которая позовёт писателя, изолирована ПО ПОСТРОЕНИЮ, а не по памяти
    автора (см. `set_probe`)."""
    mk = marker_path(mk)
    c = (card or "").strip()
    if not c:
        return False
    # ВТОРОЙ ПОЯС того же правила (первый — `_card`): в маркер, из которого демон достаёт класс
    # одобрения, чужой штамп не попадает НИКОГДА — кем бы карточка ни была собрана. Скраб
    # идемпотентен, поэтому на штатном пути (карточка от `_card`) снимать уже нечего.
    c, scrubbed = scrub_kind_stamp(c)
    if scrubbed:
        _log("guard", "marker", "scrub", "kind_stamp",
             "снят чужой штамп класса из тела карточки ×%d" % scrubbed)
    c = _fit_body_under_stamp(c)          # тело — под штамп: он обязан пережить обрезку
    if kind:
        c += "\n" + KIND_LINE_PREFIX + kind
    token = os.environ.get(MARKER_TOKEN_ENV, "")
    stamp = token + MARKER_SEP
    block = "\n".join(stamp + ln for ln in c.splitlines())
    try:
        existing = ""
        if os.path.isfile(mk):
            with open(mk, "r", encoding="utf-8", errors="ignore") as f:
                existing = f.read()
        # ЛАТЧ: блок ЭТОГО прогона уже стоит → второй не пишем ни при каких условиях. Сверяем по
        # штампу токена, а не по телу: вторая операция отличается телом, и дедуп по телу её бы
        # пропустил — ровно так и склеивались карточки 144/145.
        if any(ln.startswith(stamp) for ln in existing.splitlines() if ln.strip()):
            _log("guard", "marker", "latched", kind or "-",
                 "вторая красная операция прогона: карточка НЕ выписана (одна карточка — одна операция)")
            return False
        with open(mk, "w", encoding="utf-8") as f:   # ЗАМЕНА, а не дописывание: чужие/старые
            f.write(block + "\n")                    # блоки демон и так игнорирует по токену
    except Exception:
        return False
    return True


def _emit_ask(card, kind=""):
    # Сигнал headless→демон (pc_orchestrator): в headless карточку не показать интерактивно,
    # поэтому при заданном env пишем красную карточку в файл-маркер — демон детектит и ставит
    # NEEDS_APPROVAL. В интерактивной сессии env не задан → поведение не меняется.
    mk = os.environ.get(ASK_MARKER_ENV)
    latched = False
    if mk:
        # ОДНА КАРТОЧКА — ОДНА ОПЕРАЦИЯ: писатель сам решает, первая это красная операция прогона
        # или вторая. Латч глушит ОБА канала владельца, а не один: карточка, ушедшая в личку без
        # блока в маркере, звала бы владельца решать по тому, чего в подтверждаемой карточке нет.
        latched = not _write_marker(mk, card, kind)   # канал 2 (развод боя и пробы — внутри писателя)
    if not latched:
        _push(card)                       # канал 1 (глушение пробы — внутри отправителя)
    # ТЕКСТ РЕШЕНИЯ читает ИСПОЛНИТЕЛЬ, а не владелец: в пробе показываем перехват на границе
    # (дословную карточку, которая собиралась уйти), в бою — саму карточку, как было. При латче —
    # прямую команду остановиться: исполнителю нужно знать, что второй карточки не будет.
    reason = _probe_intercept(card, mk or "") if isolated() else card
    if latched:
        reason = MULTI_OP_NOTE % (PROBE_CARD_SEP, reason)
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "ask",
        "permissionDecisionReason": reason,
    }}, ensure_ascii=False))
    sys.exit(0)


def _emit_deny(reason):
    """Отказ вместо карточки высшего вида без объекта. НИ маркера, НИ пуша: маркер породил бы у
    демона `needs_approval`, то есть ровно ту подтверждаемую карточку, которой быть не должно, а
    пуш звал бы владельца решать там, где решать не по чему. След остаётся строкой в логе гарда
    (решение `deny`) и самим текстом отказа — его видит модель и чинит команду."""
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": reason,
    }}, ensure_ascii=False))
    sys.exit(0)


def main():
    try:
        data = json.load(sys.stdin)
    except Exception:
        sys.exit(0)  # вход не распарсили → штатный flow (defer)
    headless = is_headless()
    role = "headless" if headless else "interactive"
    tool, detail = "", ""
    try:
        tool = data.get("tool_name") or ""
        ti = data.get("tool_input") or {}
        detail = ti.get("command") or ti.get("file_path") or ti.get("notebook_path") or ""
    except Exception:
        pass
    # ЕДИНЫЙ ПРИЗНАК ПРОБЫ считается ОДИН раз и ДО первой записи в любой канал владельца: ниже
    # к ним ведут три места, и все три обязаны быть изолированы, не сговариваясь между собой.
    set_probe(is_probe(detail))
    try:
        action, kind, obj = decide_for_role(data, headless)
    except Exception:
        # FAIL-SAFE в ЛЮБОЙ роли: ошибку анализа НЕ смягчаем (иначе сбой гарда = тихий пропуск,
        # а permissions.allow здесь широкий — гард единственный красный гейт).
        action, kind, obj = ("ask", "unknown", "")
    card, deny = None, None
    if action == "ask":
        decision, text = card_decision(kind, obj, detail if tool in ("Bash", "PowerShell") else "")
        action = decision          # ask → карточка; journal → строка в лог; deny → отказ
        card = text if decision == "ask" else None
        deny = text if decision == "deny" else None
    _log(role, tool, action, kind, detail)
    if deny is not None:
        _emit_deny(deny)
    if card is not None:
        _emit_ask(card, kind)
    sys.exit(0)  # defer / journal


if __name__ == "__main__":
    main()
