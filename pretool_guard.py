# ТРЕТИЙ случай ОДНОГО класса за сутки, и чиним мы здесь не место, а ПРИВЫЧКУ читать значение
# где угодно:
#   1) карточку владельцу рождал ЛЮБОЙ текст исполнителя, совпавший форматом (замок по
#      происхождению, 9e518b7): источник карточки стал ровно один — файл-маркер гарда;
#   2) класс одобрения брался из строки `op=<вид>`, НАПЕЧАТАННОЙ моделью (снято 31.07, блок ниже);
#   3) класс одобрения читался из ЛЮБОЙ строки карточки — вот это. Объект красной операции
#      подконтролен исполнителю (`Write` с `file_path`), перенос строки внутри объекта доезжал в
#      текст карточки, и `Класс операции: <чужой вид>` посреди тела читался наравне со штампом
#      гарда. Замер пробы (`tmp/probe_kind_stamp_origin.py`, до правки): одна честная карточка
#      «запись за пределами проекта» отдавала демону ДВА класса — `network, write_outside`, то
#      есть «да» владельца на один класс возвращалось в гард двумя.
#
# ПРАВИЛО, действующее ДЛЯ ВСЕХ служебных полей карточки: поле имеет ЗНАЧЕНИЕ только там, куда
# его положил сам гард. Три пояса, каждый закрывает свою половину:
#   • ЗАПИСЬ: чужой штамп снимается из тела `scrub_kind_stamp` — В ЛЮБОМ МЕСТЕ СТРОКИ (не только
#     с её начала: якорь на начало и был серверной «дырой формы» 87a4b85) и с ВИДИМЫМ СЛЕДОМ
#     (`KIND_STAMP_MARK`): попытка подделки обязана быть видна владельцу, а не пропасть молча;
#   • ЧТЕНИЕ: `kinds_from_card` берёт класс ТОЛЬКО из хвоста блока — ровно оттуда, куда его
#     кладёт `_write_marker`, — и только в КАНОНИЧЕСКОЙ форме, которую гард и печатает;
#   • ДЛИНА: тело режется под штамп (`MARKER_CARD_MAX`), иначе гигантский объект вытеснял бы
#     настоящий штамп за обрезку, оставив в карточке только поддельный.
# СКРАБ ШИРЕ ЧИТАТЕЛЯ НАМЕРЕННО: снимаем по вольной форме (регистр, пробелы вокруг слов и
# двоеточия), читаем по строгой. Обратная асимметрия дала бы щель ровно в разнице форм.
# ПРАВИЛО ПРИМЕНЕНО ВТОРОЙ РАЗ — к полю «Объект:» (01.08.2026, `scrub_obj_field`/`_is_obj_place`):
# у него тот же изъян и те же пояса, с одной честной разницей — в карточке эта строка стоит по
# праву, поэтому скраб идёт по ЗНАЧЕНИЮ объекта, а не по телу карточки. Разбор — блок у
# `_RE_OBJ_LINE`.
KIND_STAMP_MARK = "⚠ снят чужой штамп класса → "
_RE_KIND_STAMP_ANY = re.compile(r"(?i)класс\s+операции\s*:[ \t]*")
# ЧИТАТЕЛЬ: строка ЦЕЛИКОМ и в том виде, в каком её печатает `_write_marker`. Ни регистра, ни
# украшений, ни хвоста после класса: `Класс операции: network — разрешить?` штампом НЕ является.
_RE_KIND_LINE = re.compile(r"^Класс операции: ([a-z_]+(?:, [a-z_]+)*)$")
# Голова карточки: `🔴`/`⛔` (у демона — после префикса «NEEDS_APPROVAL (гард): »). По ней
# читатель узнаёт границу СЛЕДУЮЩЕГО блока: маркер ПК многоблочный, и штамп стоит в хвосте
# КАЖДОГО блока, а не один на всю карточку.
_RE_CARD_HEAD = re.compile(r"^(?:NEEDS_APPROVAL[^:]*:\s*)?[🔴⛔]")


def scrub_kind_stamp(text):
    """Снять из текста ЧУЖОЙ штамп класса → (текст, сколько снято).

    Зовётся там, где текст мог прийти НЕ от гарда: тело карточки собирается вокруг объекта
    операции, а объект приносит исполнитель. След видимый (`KIND_STAMP_MARK`) и значение
    сохраняем: владелец должен УВИДЕТЬ попытку, а не получить молча вычищенную карточку."""
    t = str(text or "")
    n = len(_RE_KIND_STAMP_ANY.findall(t))
    return (_RE_KIND_STAMP_ANY.sub(KIND_STAMP_MARK, t), n) if n else (t, 0)


def _is_stamp_place(lines, i):
    """→ True ⇔ строка i стоит ИМЕННО ТАМ, куда штамп класса кладёт `_write_marker`: в ХВОСТЕ
    блока карточки, то есть дальше либо ничего, либо голова СЛЕДУЮЩЕЙ карточки.
    Ошибка здесь может только УБАВИТЬ одобрение (класс не прочтён → красное снова спросит),
    поэтому строгость безопасна, а вольность — нет."""
    for ln in lines[i + 1:]:
        s = ln.strip()
        if not s:
            continue
        return bool(_RE_CARD_HEAD.match(s))
    return True
