def defect_signals(text):
    """Тело ряда → НАШИ слова-признаки. Чужих строк не возвращает НИ ОДНОЙ. → dict.

    ЕДИНСТВЕННОЕ МЕСТО, ГДЕ РАЗБОР ЗАГЛЯДЫВАЕТ НИЖЕ :data:`QUOTE_HEAD`, и оно
    устроено так, что вынести чужой текст наружу не может даже по ошибке: функция
    возвращает ТОЛЬКО те слова из НАШИХ трёх списков, которые в тексте нашлись.
    Всё, что она отдаёт, написано в этом файле выше; ни одного знака канала в
    возврате нет по построению, а не по аккуратности зовущего.

    Зачем вообще ниже границы. Вид находки про клиентский дефект не говорит НИЧЕГО
    (канал о нём не спрашивают), а :func:`digest` тело сознательно не читает.
    Значит признак берётся здесь — но наружу уходит ВЕРДИКТ, а не речь.
    """
    low = str(text or "").lower().replace("ё", "е")
    hit = lambda words: [w for w in words if w.replace("ё", "е") in low]
    return {"client": hit(CLIENT_WORDS), "defect": hit(DEFECT_WORDS),
            "cost": hit(COST_WORDS)}


def client_defect(got, signals=None, client_files=()):
    """Заявка — про клиентский дефект? → dict(is, why, premise_ok, surface, defect).

    Три условия определения выше, проверяются по порядку и КАЖДОЕ называет свой
    отказ отдельными словами: «посылка не жива», «предмет клиенту не виден»,
    «неверного поведения не названо», «названа цена, а не дефект». Одно слово
    «не подходит» на все четыре случая сделало бы сводку нечитаемой — по ней
    владелец и судит, стоит ли идти в лоток.

    ``client_files`` — адреса ПРЕМИСЫ, которые руки признали клиентскими по графу
    (`client_contour`). Пустой список означает «граф сказал: не клиентские», а НЕ
    «граф не спросили»: спрашивать или нет, решают руки, и своё незнание они
    обязаны привезти третьим исходом, а не пустотой.
    """
    d = got or {}
    sig = signals or {"client": [], "defect": [], "cost": []}
    out = {"is": False, "why": "", "premise_ok": False,
           "surface": list(client_files or []), "defect": list(sig.get("defect") or [])}

    # 1. ЖИВАЯ ПОСЫЛКА. Слово, а не код: :func:`digest` кладёт в ``premise`` уже
    #    русский заголовок исхода (`review_intake.PREMISE_TITLE`).
    premise = str(d.get("premise") or "").strip().upper()
    if premise != "ЖИВА":
        out["why"] = ("посылка не жива (%s) — находка говорит о коде, которого в живом дереве "
                      "не подтвердили" % (d.get("premise") or UNKNOWN))
        return out
    out["premise_ok"] = True

    # 2. ПРЕДМЕТ ВИДЕН КЛИЕНТУ: граф импортов ЛИБО речь о самом ответе.
    by_graph = list(client_files or [])
    by_words = list(sig.get("client") or [])
    if not (by_graph or by_words):
        out["why"] = ("предмет клиенту не виден: адрес премисы вне клиентского контура и о "
                      "самом ответе клиенту находка не говорит")
        return out

    # 3. НАЗВАНО НЕВЕРНОЕ ПОВЕДЕНИЕ — и оно НЕ обёрнуто в разговор о цене.
    if not sig.get("defect"):
        out["why"] = ("неверного поведения не названо — находка про устройство работы, "
                      "а не про то, что клиент получит неверное")
        return out
    if sig.get("cost"):
        out["why"] = ("названа ЦЕНА нашей конструкции (%s), дефект лишь упомянут — канал "
                      "спрашивали именно о цене, и это прочтение по умолчанию"
                      % ", ".join(sig["cost"][:3]))
        return out

    out["is"] = True
    where = ("адрес премисы в клиентском контуре: %s" % ", ".join(by_graph[:3])) if by_graph \
        else ("речь о самом ответе клиенту: %s" % ", ".join(by_words[:3]))
    out["why"] = "%s; названо неверное поведение: %s" % (where, ", ".join(sig["defect"][:3]))
    return out


def route(items, signals=None, client_files=None, cap=CARD_CAP, sent_today=0):
    """Заявки → КОМУ КУДА: карточка владельцу или строка суточной сводки. → list[dict].

    Три исхода, и ни один не молчит:

    * ``card``      — клиентский дефект, потолок ещё есть;
    * ``card_over`` — клиентский дефект, потолок исчерпан. Карточка уходит ВСЁ
                      РАВНО (прямое условие задания) и несёт пометку
                      :data:`OVER_CAP_MARK`, а в сводке появляется строка о том,
                      что сутки вышли за мерку;
    * ``digest``    — всё остальное: строкой в сводке с причиной и указателем на
                      лоток. Заявка при этом остаётся ОТКРЫТОЙ в очереди — сводка
                      её не закрывает и не отвечает за владельца.

    Потолок НИКОГДА не превращает находку в тишину: у ``digest`` и у ``card_over``
    одинаково есть строка сводки. «Отложено потолком» и «отброшено» — разные
    слова, и второго здесь не бывает ни на одной дороге.
    """
    sig_by_key = signals or {}
    files_by_key = client_files or {}
    left = max(0, int(cap) - int(sent_today or 0))
    out = []
    for got in (items or []):
        key = (got or {}).get("key") or ""
        verdict = client_defect(got, sig_by_key.get(key), files_by_key.get(key) or ())
        row = {"key": key, "id": (got or {}).get("id"), "kind": (got or {}).get("kind"),
               "why": verdict["why"], "defect": verdict["is"]}
        if not verdict["is"]:
            row["action"] = "digest"
            out.append(row)
            continue
        if left > 0:
            left -= 1
            row["action"] = "card"
        else:
            row["action"] = "card_over"
            row["why"] = "%s (потолок %d карточек на сутки исчерпан)" % (verdict["why"], cap)
        out.append(row)
    return out


def summary(routed, found=None, inbox_ok=True, inbox_why=""):
    """Суточная сводка находок — ОДНИМ абзацем, читается по желанию. → str.

    Числа задания по порядку: сколько пришло, сколько отобрано карточкой, сколько
    отложено, темы одной фразой, указатель на лоток.

    ЧУЖОГО ТЕКСТА ЗДЕСЬ НЕТ НИ СЛОВА: тема называется ВИДОМ находки (наш разряд) и
    номером ряда, а за самим текстом сводка ОТСЫЛАЕТ в лоток. Прямой запрет
    задания, и держится он тем же устройством, что и в сообщении заявки, — цитата
    сюда просто не доезжает.

    ЛОТОК НЕ ПРОЧИТАН — СВОДКА ГОВОРИТ «НЕИЗВЕСТНО», А НЕ «НОЛЬ». Молчание
    источника не является отсутствием находок, и число «0 находок» в этот день
    было бы прямым враньём: оно неотличимо от честного пустого дня.
    """
    rows = [r for r in (routed or []) if isinstance(r, dict)]
    cards = [r for r in rows if r.get("action") in ("card", "card_over")]
    over = [r for r in rows if r.get("action") == "card_over"]
    held = [r for r in rows if r.get("action") == "digest"]
    if not inbox_ok:
        return ("📊 СВОДКА НАХОДОК ВНЕШНИХ КАНАЛОВ: %s — лоток %s не прочитан (%s). "
                "Сколько находок пришло за сутки — НЕИЗВЕСТНО (это не ноль: "
                "молчание лотка отсутствием находок не является)."
                % (UNKNOWN.upper(), INBOX_DIR, inbox_why or "причина не названа"))
    came = len(rows) if found is None else int(found)
    lines = ["📊 СВОДКА НАХОДОК ВНЕШНИХ КАНАЛОВ за сутки: пришло %d, карточкой отобрано %d, "
             "отложено в эту сводку %d." % (came, len(cards), len(held))]
    if over:
        lines.append("%s: %d карточек ушло сверх суточного потолка %d — это клиентские дефекты, "
                     "потолок их не задерживает." % (OVER_CAP_MARK, len(over), CARD_CAP))
    if held:
        themes = ", ".join("#%s %s" % (r.get("id"), r.get("kind") or UNKNOWN) for r in held[:8])
        lines.append("Отложенное одной фразой: %s%s."
                     % (themes, " и ещё %d" % (len(held) - 8) if len(held) > 8 else ""))
        lines.append("Почему не карточкой: %s." % _clip(held[0].get("why"), 200))
    lines.append("Полные тексты — в лотке %s; каждая заявка осталась ОТКРЫТОЙ в очереди и "
                 "ответа за тебя никто не дал." % INBOX_DIR)
    return " ".join(lines)


# ───────────────────────────── опознание ряда ─────────────────────────────


def is_zayavka(text):
    """Тело ряда очереди — ЗАЯВКА внешнего канала? → bool.

    Один-единственный признак, и он тот же, которым живут гарды демона: маркер
    ПЕРВЫМ (якорь ^). Ряд без маркера — карточка гарда или иная работа, и звать
    её заявкой запрещено.
    """
    return str(text or "").startswith(CLAIM_MARK)


def parse_marker(text):
    """Маркер заявки → (дата, ключ) | None (маркера нет или он битый)."""
    match = _RE_MARK.match(str(text or ""))
    return (match.group(1), match.group(2)) if match else None


def split_awaiting(rows):
    """Ряды `needs_approval` → две КУЧКИ разными словами. → dict.

    Смысл разведения — пункт 5 задания: слово «карточки» остаётся за карточками
    гарда, заявки зовутся заявками и считаются ОТДЕЛЬНО. До 02.09 витрина
    печатала их сумму, и число «3» одинаково честно читалось как «три красные
    операции ждут разрешения» и как «три чужих мнения ждут прочтения» — а это
    разные новости с разной срочностью.

    ``rows`` — ряды как их отдаёт очередь: ``{"id": …, "task_text": …}``. Поле
    тела ищется в ``task_text`` и ``goal`` (слепок очереди хранит первую строку
    под вторым именем), потому что маркер стои́т первым и переживает обрезку.
    """
    out = {"zayavki": [], "cards": []}
    for row in (rows or []):
        if not isinstance(row, dict):
            continue
        text = row.get("task_text")
        if not str(text or "").strip():
            text = row.get("goal")
        out["zayavki" if is_zayavka(text) else "cards"].append(row)
    return out


# ───────────────────────────── разбор тела заявки ─────────────────────────────


def digest(row):
    """Ряд-заявка → поля для сообщения владельцу. → dict.

    ЧИТАЕМ ТОЛЬКО СВОЁ. Тело ряда написано ступенью B и до :data:`QUOTE_HEAD`
    состоит из НАШИХ полей (вид, премиса, источники); ниже начинается дословная
    речь внешнего канала. Обрыв на границе стои́т ЗДЕСЬ, а не в сборщике текста,
    чтобы чужие строки не доехали даже до промежуточной структуры — иначе запрет
    «не переносить телом» держался бы дисциплиной, а не устройством.

    Не нашлось поле — в нём стои́т :data:`UNKNOWN`, а не догадка. Разбор НИКОГДА
    не падает: ряд с изуродованным телом обязан доехать до :func:`consequences`
    и получить честный отказ, а не исчезнуть исключением.
    """
    got = row if isinstance(row, dict) else {}
    text = got.get("task_text")
    if not str(text or "").strip():
        text = got.get("goal")
    lines = str(text or "").splitlines()
    body = []
    for line in lines:
        if line.strip() == QUOTE_HEAD:
            break                      # ← ниже только ЧУЖОЙ текст; не читаем вовсе
        body.append(line)
    marker = parse_marker(str(text or ""))
    out = {
        "schema": SCHEMA,
        "id": got.get("id"),
        "status": got.get("status") or "",
        "date": marker[0] if marker else "",
        "key": marker[1] if marker else "",
        "kind": UNKNOWN,
        "premise": UNKNOWN,
        "premise_why": "",
        "sources": [],
    }
    for line in body:
        hit = _RE_KIND.match(line.strip())
        if hit:
            out["kind"] = hit.group(1).strip() or UNKNOWN
            continue
        hit = _RE_PREMISE.match(line.strip())
        if hit:
            out["premise"] = hit.group(1).strip() or UNKNOWN
            out["premise_why"] = hit.group(2).strip()
            continue
        hit = _RE_SOURCE.match(line)
        if hit:
            out["sources"].append({"channel": hit.group(1), "send_date": hit.group(2),
                                   "pack": hit.group(3), "answer": hit.group(4) or ""})
    return out


def channels(got):
    """Каналы заявки без повторов, в порядке появления. → list[str]."""
    seen, out = set(), []
    for src in (got or {}).get("sources") or []:
        name = src.get("channel")
        if name and name not in seen:
            seen.add(name)
            out.append(name)
    return out


def packs(got):
    """Пакеты-источники без повторов, в порядке появления. → list[str]."""
    return _uniq(got, "pack")


def answers(got):
    """Файлы ЛОТКА без повторов, в порядке появления. → list[str]."""
    return _uniq(got, "answer")


def _uniq(got, field):
    seen, out = set(), []
    for src in (got or {}).get("sources") or []:
        name = src.get(field)
        if name and name not in seen:
            seen.add(name)
            out.append(name)
    return out


# ───────────────────────────── видно ли последствие ─────────────────────────────


def consequences(got):
    """Видно ли из заявки, ЧТО СЛУЧИТСЯ при «да» и при «нет». → (bool, причина).

    Прямое условие задания: «из чего не видно последствия ответа — не отправлять
    вовсе, а сказать в лог почему». Условий три, и они означают РАЗНОЕ, поэтому
    названы отдельными словами, а не сложены в одно «плохая заявка»:

    1. **Некуда деть ответ** — у ряда нет номера. Кнопка без номера ряда нажалась
       бы в никуда, а это хуже молчания: владелец считает, что ответил.
    2. **Отвечать уже не на что** — ряд не в ``needs_approval``. Заявку успели
       закрыть (человеком, TTL, сиротским гардом), и «да» на ней ничего не
       изменит: `approve_task` Моста вернёт ``not_awaiting``.
    3. **Нечего решать** — не разобрались НИ вид находки, НИ исход премисы.
       Тогда «принять к сведению» относится неизвестно к чему, и честнее не
       спрашивать вовсе. Достаточно ОДНОГО из двух полей: заявка с видом, но без
       премисы, остаётся решаемой — просто с меньшей опорой, и это сказано в
       самом сообщении словом.

    Возвращает (True, "") или (False, причина одной строкой).
    """
    d = got or {}
    tid = d.get("id")
    if tid is None or str(tid).strip() == "":
        return False, "у ряда нет номера — ответу некуда деться, кнопка нажалась бы в никуда"
    status = str(d.get("status") or "").strip()
    if status and status != "needs_approval":
        return False, ("ряд уже не ждёт решения (статус %s) — «да» ничего не изменит, "
                       "Мост ответил бы not_awaiting" % status)
    if d.get("kind") in (None, "", UNKNOWN) and d.get("premise") in (None, "", UNKNOWN):
        return False, ("в теле ряда не разобрались ни вид находки, ни исход премисы — "
                       "«принято к сведению» относилось бы неизвестно к чему")
    return True, ""


# ───────────────────────────── текст владельцу ─────────────────────────────


def _clip(text, limit=WHY_MAX):
    one = " ".join(str(text or "").split())
    if len(one) <= limit:
        return one
    return one[: max(1, limit - 1)].rstrip() + "…"


def _under_inbox(name):
    """Имя файла ответа → путь от корня репозитория. → str.

    Ступень B кладёт в поле ``ответ`` УЖЕ относительный путь
    (``docs/review_inbox/2026-09-01-…-codex.md`` — живой замер 02.09), и слепая
    склейка с :data:`INBOX_DIR` давала ``docs/review_inbox/docs/review_inbox/…`` —
    путь, которого нет. Приклеиваем каталог, только если его там ещё нет.
    """
    one = str(name or "").strip().replace("\\", "/")
    if not one:
        return ""
    return one if one.startswith(INBOX_DIR + "/") else "%s/%s" % (INBOX_DIR, one)


def pointer(got):
    """Указатель на лоток и ряд — ВМЕСТО чужого текста. → str.

    Задание требует «указатель на лоток», а не пересылку находки. Первым адресом
    идёт ФАЙЛ ЛОТКА (поле ``ответ`` строки источника): именно он там лежит.
    Пакета в лотке нет — на его имя указывать значило бы послать владельца туда,
    где файла не окажется. Не разобрался ответ — падаем на пакет и говорим это
    словом. Номер ряда даёт второй адрес того же текста на случай, если файл уже
    уехал в архив.
    """
    d = got or {}
    files = [_under_inbox(name) for name in answers(d)]
    if files:
        where = _clip(", ".join(files), PATHS_MAX)
    else:
        names = packs(d)
        where = ("%s (файл ответа не разобрался, пакет %s)"
                 % (INBOX_DIR, _clip(", ".join(names), PATHS_MAX))) if names else INBOX_DIR
    return "полный текст находки: %s и ряд очереди #%s" % (where, d.get("id"))


def message(got, defect_why="", over_cap=False):
    """Заявка → короткое сообщение владельцу. → str (≤ :data:`MSG_MAX`).

    Порядок кусков — порядок чтения: НОМЕР и «это не задача» первым (иначе
    сообщение читается как задание), суть нашими словами, откуда пришло, чем
    подтверждена посылка, что будет при каждом ответе, куда идти за полным
    текстом, и последняя строка — про молчание.

    ``defect_why`` — ЗА ЧТО эта заявка получила карточку, когда прочие ушли
    строкой в сводке. Строка обязана быть в сообщении: с 03.09 карточка означает
    «бот может соврать клиенту», и владелец вправе видеть основание прямо здесь,
    а не восстанавливать его из лотка.

    ``over_cap`` — карточка сверх суточного потолка. Пометка идёт ПЕРВОЙ строкой,
    потому что она меняет прочтение всего сообщения: это не «ещё одна заявка», а
    «сутки уже вышли за мерку, и всё-таки вот это».

    Чужих строк здесь нет ПО ПОСТРОЕНИЮ: во входе их уже нет (:func:`digest`
    обрывается на :data:`QUOTE_HEAD`), а основание карточки собрано из НАШИХ слов
    (:func:`defect_signals` чужих не возвращает).
    """
    d = got or {}
    chan = _clip(", ".join(channels(d)), PATHS_MAX) or "канал не назван"
    pack_names = _clip(", ".join(packs(d)), PATHS_MAX) or "пакет не назван"
    dates = sorted({s.get("send_date") for s in (d.get("sources") or []) if s.get("send_date")})
    when = ", ".join(dates) if dates else "дата отправки не названа"
    premise = d.get("premise") or UNKNOWN
    why = _clip(d.get("premise_why"))
    lines = []
    if over_cap:
        lines.append("%s — суточный потолок %d карточек уже исчерпан, но это клиентский "
                     "дефект, и он не ждёт." % (OVER_CAP_MARK, CARD_CAP))
    lines += [
        "📥 ЗАЯВКА ВНЕШНЕГО КАНАЛА #%s — ждёт твоего решения. Это НЕ задача: "
        "она ничего не исполняет и никуда не едет." % d.get("id"),
        "",
        "Почему карточкой, а не строкой в сводке: %s"
        % (_clip(defect_why, WHY_MAX) or "основание не названо"),
        "Вид находки: %s (наш разбор ответа; дословный текст канала сюда не переношу)"
        % (d.get("kind") or UNKNOWN),
        "Откуда: %s · пакет %s · отправлен %s" % (chan, pack_names, when),
        "Посылка: %s%s" % (premise, (" — %s" % why) if why else ""),
        "  (проверена чтением названного адреса, а не свежестью ответа)",
        pointer(d),
        "",
        "✅ Принято к сведению → заявка помечается принятой и закрывается. "
        "Задача НЕ ставится ни одной веткой: надо исполнять — поставь отдельно, своими словами.",
        "❌ Отклонить → заявка закрывается. Больше не происходит ничего.",
        "",
        "Не ответишь — заявка останется открытой и не исполнится НИКОГДА.",
    ]
    return "\n".join(lines)[:MSG_MAX]


def buttons(tid):
    """Инлайн-клавиатура ответа в ОДИН ТАП. → dict.

    Ответ обязан работать с телефона и не требовать точного набора текста
    (пункт 3 задания) — значит кнопка, а не команда. ``callback_data`` слушает
    `pc_agent` тем же обработчиком, что и кнопки цепей дирижёра: тот же бот-токен
    шлёт карточку и ловит тап, третьего процесса заводить не пришлось.
    """
    return {"inline_keyboard": [[
        {"text": "✅ Принято к сведению", "callback_data": "zayavka:yes:%s" % tid},
        {"text": "❌ Отклонить", "callback_data": "zayavka:no:%s" % tid},
    ]]}


def reminder(items):
    """Напоминание об открытых заявках — ОДНОЙ строкой. → str.

    Условие задания дословно: «напоминание — не чаще раза в сутки и одной
    строкой». Полного текста здесь нет намеренно: повторная отправка того же
    сообщения — это ещё одна карточка на то же решение, то есть ровно тот шум,
    от которого владелец перестаёт читать тему.
    """
    rows = [d for d in (items or []) if (d or {}).get("id") is not None]
    if not rows:
        return ""
    names = ", ".join("#%s (%s)" % (d.get("id"), d.get("kind") or UNKNOWN) for d in rows)
    return ("📥 Открытых заявок внешних каналов: %d — %s. Ответ кнопкой на прежнем сообщении; "
            "без ответа они не исполняются." % (len(rows), names))


