def plan(items, state, now):
    """Заявки + реестр отправленного → что делать с каждой. → list[dict].

    Четыре исхода, и ни один не молчит:

    * ``send``    — не отправляли ни разу; едет полное сообщение с кнопками;
    * ``hold``    — последствие ответа не видно (:func:`consequences`); НЕ шлём,
                    причина названа и уезжает в лог;
    * ``remind``  — отправляли, ответа нет, с прошлого разговора прошли сутки;
    * ``skip``    — отправляли меньше суток назад; молчим.

    ПОВТОРНОЙ ПОЛНОЙ ОТПРАВКИ НЕТ НИ НА ОДНОЙ ДОРОГЕ: ключ, однажды попавший в
    реестр, получает ``remind``/``skip``, но никогда ``send``. Это не гигиена —
    вторая карточка на то же решение неотличима от НОВОЙ заявки, и владелец
    решает один вопрос дважды.

    Часов здесь нет: ``now`` — эпоха секундами полем входа.
    """
    sent = (state or {}).get("sent") or {}
    out = []
    for got in (items or []):
        key = (got or {}).get("key") or ""
        ok, why = consequences(got)
        if not ok:
            out.append({"key": key, "id": (got or {}).get("id"), "action": "hold", "why": why})
            continue
        rec = sent.get(key) if key else None
        if not isinstance(rec, dict):
            out.append({"key": key, "id": got.get("id"), "action": "send",
                        "why": "ещё не отправляли"})
            continue
        last = rec.get("last_at")
        try:
            waited = float(now) - float(last)
        except (TypeError, ValueError):
            # Реестр без метки времени — ТРЕТИЙ ИСХОД: доказать, что сутки прошли,
            # нечем, и мы молчим. Промолчать лишний день дешевле, чем будить
            # владельца каждый оборот на сломанной метке.
            out.append({"key": key, "id": got.get("id"), "action": "skip",
                        "why": "в реестре нет метки времени — сутки не доказать, молчим"})
            continue
        if waited >= REMIND_MIN_SEC:
            out.append({"key": key, "id": got.get("id"), "action": "remind",
                        "why": "без ответа %d ч" % int(waited // 3600)})
        else:
            out.append({"key": key, "id": got.get("id"), "action": "skip",
                        "why": "говорили %d ч назад, чаще раза в сутки не напоминаем"
                               % int(waited // 3600)})
    return out


def index_line(report):
    """Строка-индекс захода для журнала. → str (одна строка, пусто = сказать нечего)."""
    got = report or {}
    sent = got.get("sent") or []
    held = got.get("held") or []
    reminded = got.get("reminded") or []
    if not (sent or held or reminded):
        return ""
    parts = ["ступень G: заявок доставлено %d" % len(sent)]
    for row in sent:
        parts.append("#%s (%s)" % (row.get("id"), row.get("kind") or UNKNOWN))
    if reminded:
        parts.append("напомнено о %d одной строкой" % len(reminded))
    for row in held:
        parts.append("НЕ отправлена #%s: %s" % (row.get("id"), row.get("why")))
    return "; ".join(parts)
