"""Ступень G ревью-контура — ЗАЯВКА ДОХОДИТ ДО ВЛАДЕЛЬЦА И ОТВЕЧАЕТСЯ ОДНИМ ТАПОМ.

Ступень B (:mod:`review_intake`) кладёт находку внешнего канала РЯДОМ ОЧЕРЕДИ со
статусом ``needs_approval``. На этом путь к человеку обрывался, и обрывался
МОЛЧА — что и замерено 02.09.2026:

* в очереди три ряда ``needs_approval`` с телом заявки (#1 ``fb36e990a3b5``,
  #2 ``98c2c8bf1be6``, #3 ``47b3131c052c``);
* исходящих полосы ПК по ним — НОЛЬ (`dispatch_notify.log`, 9732 строки);
* ``set_needs_approval`` Моста пишет в таблицу ``status`` и ``result`` и НЕ ШЛЁТ
  в Telegram ничего — поле ``topic`` в его payload не читается вовсе;
* витрина складывала эти ряды с карточками гарда в одно слово «карточки в
  ожидании: 3».

Итог: решение ждали от человека, которому о нём не сказали. Эта ступень
добавляет ровно одно звено — ЗАЯВКА ПРИХОДИТ К ВЛАДЕЛЬЦУ САМА, коротким
сообщением с двумя кнопками, — и ни одного звена больше.

ЧТО ЭТА СТУПЕНЬ НЕ ДЕЛАЕТ НИ ОДНОЙ ВЕТКОЙ. Не превращает заявку в задачу ни при
каком ответе: «да» означает «принято к сведению», «нет» — «закрыто», и ОБА исхода
задач не рождают (гард демона ``process_approved`` → ``_is_review_claim``, тот же
замок, что у ступени B). Не переносит владельцу ЧУЖОЙ ТЕКСТ: наружу едут только
наши поля — вид находки, исход премисы, канал, пакет, — а дословная цитата
остаётся в ряде очереди и в лотке, на которые сообщение лишь УКАЗЫВАЕТ
(:data:`QUOTE_HEAD` — граница, ниже которой разбор не читает НИЧЕГО).

ЧЕТЫРЕ РЕШЕНИЯ, КОТОРЫЕ ЖИВУТ ЗДЕСЬ:

1. **Заявка это или карточка гарда.** Ряд ``needs_approval`` бывает и тем и
   другим, и до 02.09 витрина звала одним словом оба. Различает МАРКЕР
   (:data:`CLAIM_MARK`) — тот же самый, которым заявку опознают три гарда демона;
   второго определения здесь не заводится (:func:`is_zayavka`).
2. **Видно ли последствие ответа.** Прямой запрет задания: сообщение, из которого
   не видно, что случится при «да» и при «нет», НЕ ОТПРАВЛЯЕТСЯ вовсе, а причина
   уходит в лог. Условий три, и каждое означает разное (:func:`consequences`).
3. **Текст владельцу.** Суть НАШИМИ словами, откуда пришло, чем подтверждена
   посылка, что будет при каждом ответе, указатель на лоток — и ни одной чужой
   строки (:func:`message`).
4. **Молчание — не согласие.** Без ответа заявка остаётся открытой и не
   исполняется никогда; напоминание — не чаще раза в сутки и ОДНОЙ строкой,
   повторной полной отправки не бывает ни на одной дороге (:func:`plan`).

ИНВАРИАНТЫ (те же, что у ступеней A, B, D и слоя ожиданий, и по той же причине):

* **Чистота.** Ни сети, ни диска, ни подпроцессов, ни ``getenv``, ни часов.
  «Сейчас» и строки очереди — ПОЛЯ ВХОДА. Держит тест ``ZAYAVKI_PC_PURE``
  обходом AST.
* **Третий исход.** Не разобрали ряд — это ``неизвестно`` и отказ отправлять, а
  не «отправим как есть».
* **Ничего не выдумывать.** Вид находки и исход премисы берутся ИЗ ТЕЛА РЯДА,
  написанного ступенью B; не нашлись — так и сказано словом.
"""

from __future__ import annotations

import re

SCHEMA = "turbobaby.zayavki_pc/v1"

# ───────────────────────────── маркер и границы ─────────────────────────────
# Литералы намеренно свои, а НЕ импорт из review_intake: этот модуль читает ЧУЖОЙ
# для себя формат, и тест сверяет каждую строку с оригиналом (`test_zayavki_pc`,
# ZAYAVKI_MARKERS_MATCH_STAGE_B). Разойдись они молча — разбор вернул бы «не
# заявка» на живой заявке, то есть ступень перестала бы доносить, ничего не сломав
# видимо. Сверка тестом ловит расхождение в тот же прогон.
CLAIM_MARK = "[заявка-ревью"
_RE_MARK = re.compile(r"^\[заявка-ревью дата=(\d{4}-\d{2}-\d{2}) ключ=([0-9a-f]{6,32})\]")

# ГРАНИЦА ЧУЖОГО ТЕКСТА. Всё, что ступень B написала НИЖЕ этой строки, — дословная
# речь внешнего канала. Разбор обрывается здесь и не читает дальше ни символа:
# запрет задания «чужой текст в сообщение владельцу не переносить телом» держится
# не аккуратностью автора сообщения, а тем, что чужих строк просто НЕТ во входе
# сборщика.
QUOTE_HEAD = "ЦИТАТА ДОСЛОВНО:"

_RE_KIND = re.compile(r"^ВИД НАХОДКИ:\s*(.+)$")
_RE_PREMISE = re.compile(r"^ПРЕМИСА:\s*([^—]+?)\s*—\s*(.+)$")
# Хвост строки источника (`· sha256 пакета … · ответ <файл лотка>`) забран
# НЕОБЯЗАТЕЛЬНОЙ группой намеренно: указатель на лоток — это имя ФАЙЛА ОТВЕТА, а
# не пакета (замер живьём 02.09: `пакет 2026-09-01-chain-pc-…-101.md` и файл
# лотка — разные имена, и первое в `docs/review_inbox` не лежит). Но разойдись
# формат хвоста — строка обязана разобраться хотя бы до канала и пакета, а не
# выпасть из источников целиком.
_RE_SOURCE = re.compile(
    r"^\s*•\s*канал\s+(\S+)\s*·\s*(\S+)\s*·\s*пакет\s+(\S+)\s*·"
    r"(?:.*·\s*ответ\s+(\S+)\s*)?$")

UNKNOWN = "неизвестно"

# Потолки строк сообщения. Витрина мерит своим числом (3900) целую доску, здесь
# же одна заявка: сообщение обязано читаться с телефона ЦЕЛИКОМ, без раскрытия
# «показать полностью», иначе кнопка внизу уезжает под кат.
WHY_MAX = 160
PATHS_MAX = 150           # список каналов/файлов лотка: у заявки их бывает 4 (замер 02.09)
MSG_MAX = 1400

# ПОЧЕМУ ПОТОЛОК ПОДНЯТ И ПОЛЯ РЕЖУТСЯ ПООТДЕЛЬНОСТИ (правка после живой пробы
# 02.09). При потолке 900 живая заявка #2 — три источника, три длинных имени
# файлов — обрезалась ровно на последней строке: «Не ответишь — за». То есть
# первым уходило под нож ЕДИНСТВЕННОЕ предложение про то, что молчание не
# согласие, а вместе с ним и половина второй кнопки. Ножницы на конце текста
# всегда режут хвост, а хвост здесь — смысл. Поэтому длину держат ПОЛЯ (адреса и
# причина премисы), а общий потолок стои́т последним рубежом и никогда не должен
# срабатывать на живых данных (голден ``test_live_three_source_claim_fits``).

# Пол между напоминаниями. Сутки — не круглое число, а прямое условие задания
# («напоминание не чаще раза в сутки») и ровно тот же порядок, каким живёт сводка
# ступени D: чаще — лента, которую перестают читать.
REMIND_MIN_SEC = 86400

INBOX_DIR = "docs/review_inbox"


# ───────────────────────────── опознание ряда ─────────────────────────────


def is_zayavka(text):
    """Тело ряда очереди — ЗАЯВКА внешнего канала? → bool.

    Один-единственный признак, и он тот же, которым живут гарды демона: маркер
    ПЕРВЫМ (якорь ^). Ряд без маркера — карточка гарда или иная работа, и звать
    её заявкой запрещено.
    """
    return str(text or "").startswith(CLAIM_MARK)


def parse_marker(text):
    """Маркер заявки → (дата, ключ) | None (маркера нет или он битый)."""
    match = _RE_MARK.match(str(text or ""))
    return (match.group(1), match.group(2)) if match else None


def split_awaiting(rows):
    """Ряды `needs_approval` → две КУЧКИ разными словами. → dict.

    Смысл разведения — пункт 5 задания: слово «карточки» остаётся за карточками
    гарда, заявки зовутся заявками и считаются ОТДЕЛЬНО. До 02.09 витрина
    печатала их сумму, и число «3» одинаково честно читалось как «три красные
    операции ждут разрешения» и как «три чужих мнения ждут прочтения» — а это
    разные новости с разной срочностью.

    ``rows`` — ряды как их отдаёт очередь: ``{"id": …, "task_text": …}``. Поле
    тела ищется в ``task_text`` и ``goal`` (слепок очереди хранит первую строку
    под вторым именем), потому что маркер стои́т первым и переживает обрезку.
    """
    out = {"zayavki": [], "cards": []}
    for row in (rows or []):
        if not isinstance(row, dict):
            continue
        text = row.get("task_text")
        if not str(text or "").strip():
            text = row.get("goal")
        out["zayavki" if is_zayavka(text) else "cards"].append(row)
    return out


# ───────────────────────────── разбор тела заявки ─────────────────────────────


def digest(row):
    """Ряд-заявка → поля для сообщения владельцу. → dict.

    ЧИТАЕМ ТОЛЬКО СВОЁ. Тело ряда написано ступенью B и до :data:`QUOTE_HEAD`
    состоит из НАШИХ полей (вид, премиса, источники); ниже начинается дословная
    речь внешнего канала. Обрыв на границе стои́т ЗДЕСЬ, а не в сборщике текста,
    чтобы чужие строки не доехали даже до промежуточной структуры — иначе запрет
    «не переносить телом» держался бы дисциплиной, а не устройством.

    Не нашлось поле — в нём стои́т :data:`UNKNOWN`, а не догадка. Разбор НИКОГДА
    не падает: ряд с изуродованным телом обязан доехать до :func:`consequences`
    и получить честный отказ, а не исчезнуть исключением.
    """
    got = row if isinstance(row, dict) else {}
    text = got.get("task_text")
    if not str(text or "").strip():
        text = got.get("goal")
    lines = str(text or "").splitlines()
    body = []
    for line in lines:
        if line.strip() == QUOTE_HEAD:
            break                      # ← ниже только ЧУЖОЙ текст; не читаем вовсе
        body.append(line)
    marker = parse_marker(str(text or ""))
    out = {
        "schema": SCHEMA,
        "id": got.get("id"),
        "status": got.get("status") or "",
        "date": marker[0] if marker else "",
        "key": marker[1] if marker else "",
        "kind": UNKNOWN,
        "premise": UNKNOWN,
        "premise_why": "",
        "sources": [],
    }
    for line in body:
        hit = _RE_KIND.match(line.strip())
        if hit:
            out["kind"] = hit.group(1).strip() or UNKNOWN
            continue
        hit = _RE_PREMISE.match(line.strip())
        if hit:
            out["premise"] = hit.group(1).strip() or UNKNOWN
            out["premise_why"] = hit.group(2).strip()
            continue
        hit = _RE_SOURCE.match(line)
        if hit:
            out["sources"].append({"channel": hit.group(1), "send_date": hit.group(2),
                                   "pack": hit.group(3), "answer": hit.group(4) or ""})
    return out


def channels(got):
    """Каналы заявки без повторов, в порядке появления. → list[str]."""
    seen, out = set(), []
    for src in (got or {}).get("sources") or []:
        name = src.get("channel")
        if name and name not in seen:
            seen.add(name)
            out.append(name)
    return out


def packs(got):
    """Пакеты-источники без повторов, в порядке появления. → list[str]."""
    return _uniq(got, "pack")


def answers(got):
    """Файлы ЛОТКА без повторов, в порядке появления. → list[str]."""
    return _uniq(got, "answer")


def _uniq(got, field):
    seen, out = set(), []
    for src in (got or {}).get("sources") or []:
        name = src.get(field)
        if name and name not in seen:
            seen.add(name)
            out.append(name)
    return out


# ───────────────────────────── видно ли последствие ─────────────────────────────


def consequences(got):
    """Видно ли из заявки, ЧТО СЛУЧИТСЯ при «да» и при «нет». → (bool, причина).

    Прямое условие задания: «из чего не видно последствия ответа — не отправлять
    вовсе, а сказать в лог почему». Условий три, и они означают РАЗНОЕ, поэтому
    названы отдельными словами, а не сложены в одно «плохая заявка»:

    1. **Некуда деть ответ** — у ряда нет номера. Кнопка без номера ряда нажалась
       бы в никуда, а это хуже молчания: владелец считает, что ответил.
    2. **Отвечать уже не на что** — ряд не в ``needs_approval``. Заявку успели
       закрыть (человеком, TTL, сиротским гардом), и «да» на ней ничего не
       изменит: `approve_task` Моста вернёт ``not_awaiting``.
    3. **Нечего решать** — не разобрались НИ вид находки, НИ исход премисы.
       Тогда «принять к сведению» относится неизвестно к чему, и честнее не
       спрашивать вовсе. Достаточно ОДНОГО из двух полей: заявка с видом, но без
       премисы, остаётся решаемой — просто с меньшей опорой, и это сказано в
       самом сообщении словом.

    Возвращает (True, "") или (False, причина одной строкой).
    """
    d = got or {}
    tid = d.get("id")
    if tid is None or str(tid).strip() == "":
        return False, "у ряда нет номера — ответу некуда деться, кнопка нажалась бы в никуда"
    status = str(d.get("status") or "").strip()
    if status and status != "needs_approval":
        return False, ("ряд уже не ждёт решения (статус %s) — «да» ничего не изменит, "
                       "Мост ответил бы not_awaiting" % status)
    if d.get("kind") in (None, "", UNKNOWN) and d.get("premise") in (None, "", UNKNOWN):
        return False, ("в теле ряда не разобрались ни вид находки, ни исход премисы — "
                       "«принято к сведению» относилось бы неизвестно к чему")
    return True, ""


# ───────────────────────────── текст владельцу ─────────────────────────────


def _clip(text, limit=WHY_MAX):
    one = " ".join(str(text or "").split())
    if len(one) <= limit:
        return one
    return one[: max(1, limit - 1)].rstrip() + "…"


def _under_inbox(name):
    """Имя файла ответа → путь от корня репозитория. → str.

    Ступень B кладёт в поле ``ответ`` УЖЕ относительный путь
    (``docs/review_inbox/2026-09-01-…-codex.md`` — живой замер 02.09), и слепая
    склейка с :data:`INBOX_DIR` давала ``docs/review_inbox/docs/review_inbox/…`` —
    путь, которого нет. Приклеиваем каталог, только если его там ещё нет.
    """
    one = str(name or "").strip().replace("\\", "/")
    if not one:
        return ""
    return one if one.startswith(INBOX_DIR + "/") else "%s/%s" % (INBOX_DIR, one)


def pointer(got):
    """Указатель на лоток и ряд — ВМЕСТО чужого текста. → str.

    Задание требует «указатель на лоток», а не пересылку находки. Первым адресом
    идёт ФАЙЛ ЛОТКА (поле ``ответ`` строки источника): именно он там лежит.
    Пакета в лотке нет — на его имя указывать значило бы послать владельца туда,
    где файла не окажется. Не разобрался ответ — падаем на пакет и говорим это
    словом. Номер ряда даёт второй адрес того же текста на случай, если файл уже
    уехал в архив.
    """
    d = got or {}
    files = [_under_inbox(name) for name in answers(d)]
    if files:
        where = _clip(", ".join(files), PATHS_MAX)
    else:
        names = packs(d)
        where = ("%s (файл ответа не разобрался, пакет %s)"
                 % (INBOX_DIR, _clip(", ".join(names), PATHS_MAX))) if names else INBOX_DIR
    return "полный текст находки: %s и ряд очереди #%s" % (where, d.get("id"))


def message(got):
    """Заявка → короткое сообщение владельцу. → str (≤ :data:`MSG_MAX`).

    Порядок кусков — порядок чтения: НОМЕР и «это не задача» первым (иначе
    сообщение читается как задание), суть нашими словами, откуда пришло, чем
    подтверждена посылка, что будет при каждом ответе, куда идти за полным
    текстом, и последняя строка — про молчание.

    Чужих строк здесь нет ПО ПОСТРОЕНИЮ: во входе их уже нет (:func:`digest`
    обрывается на :data:`QUOTE_HEAD`).
    """
    d = got or {}
    chan = _clip(", ".join(channels(d)), PATHS_MAX) or "канал не назван"
    pack_names = _clip(", ".join(packs(d)), PATHS_MAX) or "пакет не назван"
    dates = sorted({s.get("send_date") for s in (d.get("sources") or []) if s.get("send_date")})
    when = ", ".join(dates) if dates else "дата отправки не названа"
    premise = d.get("premise") or UNKNOWN
    why = _clip(d.get("premise_why"))
    lines = [
        "📥 ЗАЯВКА ВНЕШНЕГО КАНАЛА #%s — ждёт твоего решения. Это НЕ задача: "
        "она ничего не исполняет и никуда не едет." % d.get("id"),
        "",
        "Вид находки: %s (наш разбор ответа; дословный текст канала сюда не переношу)"
        % (d.get("kind") or UNKNOWN),
        "Откуда: %s · пакет %s · отправлен %s" % (chan, pack_names, when),
        "Посылка: %s%s" % (premise, (" — %s" % why) if why else ""),
        "  (проверена чтением названного адреса, а не свежестью ответа)",
        pointer(d),
        "",
        "✅ Принято к сведению → заявка помечается принятой и закрывается. "
        "Задача НЕ ставится ни одной веткой: надо исполнять — поставь отдельно, своими словами.",
        "❌ Отклонить → заявка закрывается. Больше не происходит ничего.",
        "",
        "Не ответишь — заявка останется открытой и не исполнится НИКОГДА.",
    ]
    return "\n".join(lines)[:MSG_MAX]


def buttons(tid):
    """Инлайн-клавиатура ответа в ОДИН ТАП. → dict.

    Ответ обязан работать с телефона и не требовать точного набора текста
    (пункт 3 задания) — значит кнопка, а не команда. ``callback_data`` слушает
    `pc_agent` тем же обработчиком, что и кнопки цепей дирижёра: тот же бот-токен
    шлёт карточку и ловит тап, третьего процесса заводить не пришлось.
    """
    return {"inline_keyboard": [[
        {"text": "✅ Принято к сведению", "callback_data": "zayavka:yes:%s" % tid},
        {"text": "❌ Отклонить", "callback_data": "zayavka:no:%s" % tid},
    ]]}


def reminder(items):
    """Напоминание об открытых заявках — ОДНОЙ строкой. → str.

    Условие задания дословно: «напоминание — не чаще раза в сутки и одной
    строкой». Полного текста здесь нет намеренно: повторная отправка того же
    сообщения — это ещё одна карточка на то же решение, то есть ровно тот шум,
    от которого владелец перестаёт читать тему.
    """
    rows = [d for d in (items or []) if (d or {}).get("id") is not None]
    if not rows:
        return ""
    names = ", ".join("#%s (%s)" % (d.get("id"), d.get("kind") or UNKNOWN) for d in rows)
    return ("📥 Открытых заявок внешних каналов: %d — %s. Ответ кнопкой на прежнем сообщении; "
            "без ответа они не исполняются." % (len(rows), names))


