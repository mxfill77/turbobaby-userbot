    # раньше врало. Признак вида был один — маркер ступени B, — а значит КАРТОЧКОЙ
    # ГАРДА звалось всё остальное, включая заявки разведки: живой замер 03.09 даёт
    # пять открытых рядов, из них четыре заявки разведки и одна заявка внешнего
