def axes_tally(total, axis_hits, biz_hits):
    """Хеши коммитов за сутки → счёт по трём осям. → dict {ось: int|None}.

    ``total`` — ВСЕ коммиты суток, ``axis_hits``/``biz_hits`` — попавшие в оси.
    Обслуживание = остаток, и это разобрано в шапке. ``None`` в любом входе →
    ``None`` во всех трёх: посчитать часть на неполном корпусе значит выдать
    неполное число за полное.
    """
    if total is None or axis_hits is None or biz_hits is None:
        return {AXIS_MAIN: None, AXIS_BIZ: None, AXIS_SERVICE: None}
    all_h, ax, bz = set(total), set(axis_hits), set(biz_hits)
    return {AXIS_MAIN: len(ax), AXIS_BIZ: len(bz), AXIS_SERVICE: len(all_h - ax - bz)}


def axes_words(tally, closed_day, why=""):
    """Строка осей: счёт по трём + названная граница признака."""
    got = tally or {}
    parts = ["%s %s" % (name, number(got.get(name), why or "git за сутки не прочитан"))
             for name in AXES]
    return ("заходов за сутки (след — коммит): %s · строк очереди закрылось за сутки: %s"
            % (" · ".join(parts), number(closed_day, "слепок очереди не прочитан")))


# ═════════════════════════ ПРОСТОЙ ПОЛОСЫ И ПРИХОД ШТАБА ═════════════════════
# ЗАЧЕМ ЭТИ ДВЕ СТРОКИ. Петлю замыкает ВНЕШНИЙ агент: он видит пустую очередь и
# будит Штаб. Пока прибора нет, его молчание и настоящая тишина полосы выглядят
# ОДИНАКОВО — пустой очередью, которая читается как спокойствие. Строка «в работе
# строк нет — полоса свободна» (она стои́т в витрине с самого начала) была ровно
# этим ложным спокойствием: слово «свободна» не отличает «только что сдали» от
# «стои́м пятый час, и разбудить нас некому».
#
# Отсюда обе строки и обе — ЧИСЛОМ СО ВРЕМЕНЕМ, а не словом «давно»:
#   • сколько очередь стои́т пустой ПРЯМО СЕЙЧАС и с какого времени;
#   • когда в неё ПОСЛЕДНИЙ РАЗ попадало задание из ящика Штаба.
# Третья строка — ТРЕВОГА — появляется только при обоих условиях сразу: пусто И
# дольше порога. Занята очередь → тревоги нет ни при каком простое в прошлом;
# источник не прочитан → НЕИЗВЕСТНО, и оно тревогой НЕ становится (третий исход
# слоя ожиданий: «проверить нечем» ≠ «плохо» и ≠ «хорошо»).


def coarse_words(sec, step=IDLE_STEP_SEC):
    """Возраст СТУПЕНЬКОЙ и со знаком «≥». → str.

    Первая ступень отдаётся как есть: «≥ 0 с» вместо «2 мин» было бы потерей
    новости ради замка, которого на таких числах ещё не нужно.
    """
    if sec is None:
        return age_words(None)
    try:
        val = max(0.0, float(sec))
    except (TypeError, ValueError):
        return age_words(None)
    if val < float(step):
        return age_words(val)
    return "≥ %s" % age_words((val // float(step)) * float(step))


def idle_words(idle):
    """Простой полосы одной строкой. → str, НИКОГДА не пустая.

    ``idle`` — ``None`` (источник не прочитан) либо словарь:
      ``{"busy": N>0, "ids": [...]}``            — очередь занята, простоя нет
      ``{"busy": 0, "sec": с, "since_words": …}``— пуста, и с какого времени
      ``{"busy": 0, "sec": None, "why": …}``     — пуста, но с какого — неизвестно

    Число простоя идёт ЧЕРЕЗ :func:`number` ровно как все прочие числа витрины:
    «пуста 0 мин» при мёртвом слепке читалось бы как измеренная свежесть.
    """
    got = idle if isinstance(idle, dict) else None
    if got is None:
        return "простой полосы: %s" % number(None, "слепок очереди не прочитан")
    busy = got.get("busy") or 0
    if busy:
        ids = ", ".join("#%s" % i for i in listed(got.get("ids") or [], LIST_MAX))
        return ("простой полосы: очередь НЕ пуста — строк в работе или ждущих взятия: %d%s"
                % (int(busy), (" (%s)" % ids) if ids else ""))
    sec = got.get("sec")
    if sec is None:
        return ("простой полосы: очередь пуста, но с какого времени — %s"
                % number(None, got.get("why") or "последнего закрытия в реестре нет"))
    return ("простой полосы: очередь пуста %s (ступень %s; с %s — закрылась строка #%s), "
            "порог тревоги %s"
            % (coarse_words(sec), age_words(IDLE_STEP_SEC), got.get("since_words") or "?",
               got.get("since_id") or "?", age_words(IDLE_ALARM_SEC)))


def shtab_age_words(last, today=""):
    """Возраст последнего прихода Штаба — коротким хвостом для других строк. → str."""
    got = last if isinstance(last, dict) else None
    if got is None:
        return number(None, "слепок очереди не прочитан")
    if not got.get("found"):
        return "ни одного задания в реестре слепка"
    sec = got.get("sec")
    if sec is not None:
        return coarse_words(sec)
    old = days_between(got.get("day"), today) if (got.get("day") and today) else None
    return ("%d сут назад (по маркеру известны только сутки)" % old if old is not None
            else "возраст неизвестен (у ряда нет ни отметки claim, ни времени закрытия)")


def shtab_last_words(last, today=""):
    """Последний приход Штаба одной строкой. → str, НИКОГДА не пустая.

    ГРАНИЦА НАЗВАНА В САМОЙ СТРОКЕ, и это не вежливость. Реестр слепка — ОКНО, а
    не история: «ни одного задания» значит «ни одного в том, что мы видим», и
    выдать это за «Штаб не приходил никогда» было бы утверждением, которого
    источник не несёт. Замер 03.09: в живом реестре (6 открытых + 71 закрытая
    строка, глубина 23.7 ч) рядов с маркером ящика РОВНО НОЛЬ — то есть первая же
    боевая печать этой строки говорит именно тот случай, ради которого она писана.
    """
    got = last if isinstance(last, dict) else None
    if got is None:
        return "приход Штаба: %s" % number(None, "слепок очереди не прочитан")
    if not got.get("found"):
        return ("приход Штаба: заданий из ящика в реестре слепка нет ни одного "
                "(реестр — окно, а не история; %s)" % (got.get("scope") or "глубина не названа"))
    when = got.get("at_words")
    how = {"claim": "взято полосой", "close": "закрылось"}.get(got.get("at_kind") or "", "")
    tail = ("%s %s — %s назад" % (how, when, coarse_words(got.get("sec")))
            if when and got.get("sec") is not None
            else shtab_age_words(got, today))
    return ("приход Штаба: последнее задание #%s (маркер дата=%s ключ=%s), %s"
            % (got.get("id") or "?", got.get("day") or "?", got.get("key") or "?", tail))


def idle_alarm(idle, last, today="", limit=IDLE_ALARM_SEC):
    """ТРЕВОГА молчания петли. → str; пусто — тревоги нет.

    Сработать обязана ТОЛЬКО при обоих условиях: очередь пуста И пуста дольше
    порога. Три случая молчат намеренно и каждый закрыт отрицательным тестом:
    очередь занята · слепок не прочитан («неизвестно» тревогой не становится) ·
    пусто, но короче порога.
    """
    got = idle if isinstance(idle, dict) else None
    if got is None or (got.get("busy") or 0):
        return ""
    sec = got.get("sec")
    try:
        quiet = float(sec)
    except (TypeError, ValueError):
        return ""
    if quiet <= float(limit):
        return ""
    return ("ТРЕВОГА: очередь пуста %s при пороге %s, а приход Штаба — %s. Петля молчит: "
            "будить Штаб по пустой очереди — работа внешнего агента, и его молчание отсюда "
            "неотличимо от тишины без прибора"
            % (coarse_words(quiet), age_words(limit), shtab_age_words(last, today)))


