def health_verdict(said, stale=None):
    """Слово прибора + молчит ли ЕГО ИСТОЧНИК → (приговор, оговорка). Чистая.

    ПОРЯДОК ВЕТОК — ЧАСТЬ СМЫСЛА, и первая из них важнее остальных вместе взятых:

      1. возраст источника не измерен (``stale is None``) → НЕИЗВЕСТНО. Прочитать слово и не
         знать, когда оно написано, — это не знание;
      2. источник МОЛЧИТ дольше своего предела (``stale is True``) → НЕИЗВЕСТНО, каким бы слово
         ни было. Здесь и живёт :data:`HEALTH_TRACE`: если замершее слово было ЗЕЛЁНЫМ, строка
         обязана сказать «умер, а след остался», иначе владелец прочтёт труп как здоровье;
      3. слова нет вовсе или оно чужое → НЕИЗВЕСТНО с названной причиной. Молчание прибора
         приговором «не работает» не становится — ровно тот дефект, который замер 04.09 нашёл у
         шести наблюдателей полосы;
      4. и только теперь слово переводится в приговор.
    """
    word = str(said or "").strip()
    if stale is None:
        return UNKNOWN_WORD, HEALTH_NO_AGE
    if stale:
        # Зелёное замершее слово называется СМЕРТЬЮ СО СЛЕДОМ, остальные — просто молчанием:
        # «работы нет», застывшее в снимке, ложным зелёным не бывает и пугать им незачем.
        head = HEALTH_TRACE if HEALTH_SAID.get(word) == HEALTH_OK else "источник молчит"
        return UNKNOWN_WORD, "%s: последнее слово «%s»" % (head, word or "не сказано")
    if word not in HEALTH_SAID:
        return UNKNOWN_WORD, "%s (%s)" % (HEALTH_NO_WORD, one_line(word, 40) or "слова нет вовсе")
    return HEALTH_SAID[word], ""


# СТРОКА-УКАЗАТЕЛЬ, КОТОРАЯ ОСТАЁТСЯ ВМЕСТО ПЕРЕНЕСЁННЫХ ХВОСТОВ. Без неё перенос был бы
# неотличим от УДАЛЕНИЯ: раздел просто стал бы короче, и никто бы не узнал, что у каждого
# прибора названа его слепота. Цена указателя — одна строка против 597 симв. хвостов.
BLIND_MOVED = ("чего приборы НЕ ВИДЯТ — строкой «%s» на КАЖДЫЙ узел, целиком в %s "
               "(в окно сообщения не влезают, но не удалены)" % (BLIND_WORDS, FULL_PLACE))


def health_row(node, blind=True):
    """Одна строка узла: приговор одним словом · чем снят и возраст · чего прибор не видит. → str.

    Три вещи обязательны у КАЖДОЙ строки (пункт 4 прежнего задания), и порядок их — порядок
    чтения с телефона: сперва слово, потом чем оно снято, и только потом слепота прибора.

    ``blind=False`` — слепота НЕ ПЕЧАТАЕТСЯ ЗДЕСЬ, потому что она печатается В ДРУГОМ МЕСТЕ
    (:data:`FULL_PLACE`), и на её отсутствие указывает :data:`BLIND_MOVED`. Ключ этот держит
    ровно одно решение — влезает ли текст в окно сообщения, — и потому дефолт у него ПОЛНЫЙ:
    забудь его передать, и витрина скажет БОЛЬШЕ, а не меньше.
    """
    got = node if isinstance(node, dict) else {}
    verdict, note = health_verdict(got.get("said"), got.get("stale"))
    out = "%s — %s · чем: %s, %s" % (one_line(got.get("name"), 40) or "узел без имени", verdict,
                                     one_line(got.get("src"), 72) or "источник не назван",
                                     got.get("age") or "возраст неизвестен")
    if note:
        out += " · %s" % one_line(note, 130)
    tail = one_line(got.get("blind"), 120) if blind else ""
    if tail:
        out += " · %s: %s" % (BLIND_WORDS, tail)
    return out


def part_health(nodes, blind=True):
    """ЧТО РАБОТАЕТ И ЧТО НЕТ: строка на узел, приговор одним словом.

    ``None`` и пустой список — РАЗНЫЕ новости, и ни одна из них не «всё хорошо»: список не собран
    против списка, в котором не оказалось ни одного узла. Молчание раздела здоровьем не является
    по той же причине, по какой им не является молчание любого прибора.

    Указатель на перенесённые хвосты приписывается ТОЛЬКО к живому списку узлов: указывать на
    слепоту приборов, которых мы не собрали, было бы обещанием текста, которого в пульсе нет.
    """
    if nodes is None:
        return ["список узлов не собран: %s" % number(None, "источники здоровья не прочитаны")]
    if not nodes:
        return ["узлов в списке нет — собирать было не из чего, и это НЕ «всё работает»"]
    rows = [health_row(n, blind=blind) for n in nodes]
    return rows if blind else rows + [BLIND_MOVED]


