def part_owner(waiting):
    """ЖДЁТ ВЛАДЕЛЬЦА: открытые решения списком, коротко.

    У заявки внешнего канала своя строка, и это не косметика. Её `goal` в слепке —
    ПЕРВАЯ строка тела, а первая строка тела заявки это машинный маркер
    `[заявка-ревью дата=… ключ=…]`, из которого владельцу не видно ни вида
    находки, ни того, что решать. Печатать его как «цель» значило показывать
    ключ вместо смысла — а смысл теперь приезжает отдельным сообщением ступени G,
    и витрина на него УКАЗЫВАЕТ, вместо того чтобы пересказывать чужой текст.
    """
    if waiting is None:
        return ["%s: %s" % ("открытые решения", number(None, "слепок очереди не прочитан"))]
    if not waiting:
        return ["решения владельца не ждёт ничего"]
    rows = []
    for w in waiting:
        # ДЕРЖИТ ли ряд ящик — говорится В КАЖДОЙ СТРОКЕ, а не выводится из вида:
        # владелец читает список сверху вниз и вправе видеть, какая строка стои́т
        # между полосой и работой, а какая просто ждёт его глаз. Признака нет —
        # считаем держащей, тем же консервативным отказом, что и у остановки.
        holds = w.get("holds", True)
        if w.get("zayavka"):
            rows.append("#%s ЗАЯВКА внешнего канала (ключ %s) — ждёт мнения, ящик НЕ держит; "
                        "суть и кнопки в инбоксе, задачей не станет"
                        % (w.get("id"), w.get("key") or "?"))
        elif not holds:
            rows.append("#%s %s — ждёт мнения, ящик НЕ держит"
                        % (w.get("id"), one_line(w.get("goal"), GOAL_MAX)))
        else:
            rows.append("#%s ДЕРЖИТ операцию: %s"
                        % (w.get("id"), one_line(w.get("goal"), GOAL_MAX)))
    return listed(rows)


