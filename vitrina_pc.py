def sections(facts, blind=True):
    """Разделы витрины парами (заголовок, готовый блок). Порядок — :data:`PARTS`. → list.

    Отдельно от :func:`body` эти пары нужны ровно затем, чтобы окно резало ЦЕЛЫМИ
    разделами и могло НАЗВАТЬ снятое (:func:`fit_message`). Часть, у которой не нашлось
    ни строки, — падение, а не тихий пропуск (тот же закон 3, которым живёт сводка).
    """
    got = facts or {}
    shtab = got.get("shtab") or {}
    today = got.get("day") or ""
    made = {
        "health": part_health(got.get("health"), blind=blind),
        "now": part_now(shtab, got.get("running"), today,
                        idle=got.get("idle"), shtab_last=got.get("shtab_last")),
        "stuck": part_stuck(shtab, got.get("expects"), got.get("failed"), today),
        "goal": part_goal(shtab, got.get("series"), today, why=got.get("series_why") or ""),
        "nums": part_nums(got.get("series"), got.get("shtab_taken"), today,
                          got.get("external"), got.get("awaiting"),
                          box_stop=got.get("box_stop") or "",
                          routed=got.get("routed"), lotok=got.get("lotok")),
        "axes": part_axes(got.get("axes"), got.get("closed_day"), got.get("axes_why") or ""),
        "owner": part_owner(got.get("waiting"), sliders=got.get("sliders")),
    }
    out = []
    for key, title in PARTS:
        rows = [r for r in (made.get(key) or []) if str(r or "").strip()]
        if not rows:
            raise AssertionError("часть %r осталась без строки — витрина обязана говорить" % key)
        out.append((title, "\n".join([title] + ["• %s" % r for r in rows])))
    return out


def body(facts, blind=True):
    """Тело витрины БЕЗ штампа. → str.

    Штампа здесь нет намеренно: по этому телу считается подпись смены
    (:func:`signature`), и время сборки в нём заставляло бы витрину править себя
    каждый оборот (разбор — в шапке модуля).
    """
    return "\n\n".join(block for _title, block in sections(facts, blind=blind))


def signature(facts):
    """Подпись СМЕНЫ ЧИСЕЛ: правим сообщение, только когда она поменялась.

    Считается по ПОЛНОМУ телу, а не по тому, что влезло в окно, и это не мелочь:
    подпись по обрезанному не заметила бы смены в снятом разделе, и витрина стояла бы
    с прежним текстом, пока новость сидит за окном. Смена одних лишь хвостов
    (:data:`BLIND_WORDS`) даст правку, которую Telegram встретит словами «message is not
    modified» — для нас это успех (:func:`edit_same`), а узел пульса при этом обновится.
    """
    return body(facts, blind=True)


def cut_words(lost, dropped, place=FULL_PLACE):
    """Объявление обрезки: СКОЛЬКО не поместилось и ЧЕГО не хватает. → str.

    Оба числа обязательны и оба — по решению 3 Штаба. «Обрезано» без размера не даёт
    судить, потерян абзац или половина витрины; «обрезано» без ИМЁН не даёт узнать, чего
    искать. Прежняя строка не несла ни того, ни другого — она называла ПОТОЛОК.
    """
    names = " · ".join(str(d) for d in dropped)
    if not names:
        # Пустой список тут значит «целиком не снято ничего», и это ОТДЕЛЬНАЯ новость, а не
        # повод молчать: обрезка объявляется и тогда, когда за окно ушёл один лишь хвост.
        names = "ни одного целиком"
    return ("%s: не поместилось %d симв. · разделы целиком НЕ показаны: %s · полностью — в %s"
            % (CUT_MARK, int(lost), names, place))


def fit_message(head, blocks, foot, limit=TEXT_MAX, place=FULL_PLACE):
    """Шапка, разделы и подвал в окно. → (текст, [снятые заголовки], сколько симв. не влезло).

    ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ВИТРИНА РЕШАЕТ, ЧТО ПОКАЗАТЬ, и закон здесь один: раздел либо
    показан ЦЕЛИКОМ, либо НАЗВАН ПО ИМЕНИ. Резать по символу нельзя — оборванный раздел
    читается как полный, и никакая строка внизу этого не чинит: владелец видит список из
    трёх строк там, где их пять, и не имеет повода усомниться.

    Снимаются разделы С ХВОСТА и по одному, пока не влезет вместе с ОБЪЯВЛЕНИЕМ: место под
    объявление считается в тот же счёт, иначе оно само вытолкнуло бы сообщение за окно.

    ЧИСЛО «НЕ ПОМЕСТИЛОСЬ» — это длина полного сообщения минус длина показанного БЕЗ
    объявления, то есть цена молчания в символах. Считать его вместе с объявлением значило
    бы вычесть из потери сообщение о ней.

    Последняя ветка вырожденная (шапка с подвалом сами длиннее окна) и потому режет ГОЛОВУ,
    а не объявление: молчаливой обрезки не бывает ни на одной дороге, включая ту, на
    которой всё уже плохо.
    """
    def join(kept, note):
        rows = [head] + [b for _t, b in kept]
        if note:
            rows.append(note)
        rows.append(foot)
        return "\n\n".join(r for r in rows if r and str(r).strip())

    full = join(blocks, "")
    if len(full) <= limit:
        return full, [], 0
    kept, dropped = list(blocks), []
    while kept:
        dropped.insert(0, kept.pop()[0])
        lost = len(full) - len(join(kept, ""))
        text = join(kept, cut_words(lost, dropped, place))
        if len(text) <= limit:
            return text, dropped, lost
    lost = len(full) - len(join([], ""))
    text = join([], cut_words(lost, dropped, place))
    return (text if len(text) <= limit else text[-limit:]), dropped, lost


def head_lines(changed_words=""):
    """Шапка сообщения. Единственная подпись оборота — время ПОСЛЕДНЕЙ СМЕНЫ чисел, и оно
    приходит готовой строкой от рук: часов в чистом слое нет."""
    return "\n".join([HEAD, "числа менялись последний раз: %s" % (changed_words or "?")])


def message(facts, changed_words="", limit=TEXT_MAX):
    """Сообщение витрины В ОКНО. → (текст, [снятые разделы], сколько симв. не влезло).

    Хвосты «не покрывает» сюда не идут (:data:`BLIND_WORDS`, решение 4 Штаба): 597 симв. на
    живом замере 09.09 — 13% тела, и место им там, где их читают целиком. Полный текст
    собирает :func:`full_text`.
    """
    return fit_message(head_lines(changed_words), sections(facts, blind=False), FOOT, limit)


def render(facts, changed_words=""):
    """Готовое сообщение витрины. → str. Что при этом снято — знает :func:`message`."""
    return message(facts, changed_words)[0]


# Первая строка полного текста говорит, ЧЕМ он отличается от сообщения: без неё две копии
# витрины разного объёма читались бы как расхождение показаний, а не как окно и оригинал.
FULL_HEAD = "ПОЛНЫЙ ТЕКСТ (окна сообщения здесь нет): все разделы и все хвосты «%s»" % BLIND_WORDS


def full_text(facts, changed_words=""):
    """Витрина ЦЕЛИКОМ: все разделы, все хвосты, ни одной обрезки. → str.

    Едет в :data:`FULL_PLACE`. Именно этот текст делает перенос ПЕРЕНОСОМ, а не удалением:
    пока он туда ложится, снятое окном не потеряно, а просто читается в другом месте.
    """
    return "\n\n".join([head_lines(changed_words), FULL_HEAD, body(facts, blind=True), FOOT])


def journal_line(report):
    """Строка-индекс в журнал: что стало с витриной за оборот.

    Обрезка едет и сюда — но ДОБАВКОЙ к тому, что уже сказано в самом сообщении, а не
    вместо него. Журнал здесь второй свидетель, а не единственный: отказ, видный только в
    логе, для дела равен отказу без свидетеля (решение 3 Штаба).
    """
    got = report or {}
    if got.get("skipped"):
        return "NOTE ВИТРИНА ПК: %s" % one_line(got.get("skipped"), 200)
    how = got.get("how") or "не тронута"
    # НЕ `or []`: отсутствие ключа («оборот об обрезке не отчитывался») и пустой список
    # («резать не пришлось») — разные новости, и храповик неразбора прав, что не даёт их
    # склеить. Здесь обе ведут к молчанию строки, но склеены они не идиомой, а веткой.
    dropped = got.get("cut")
    return ("NOTE ВИТРИНА ПК: %s · сообщение %s · тема %s%s%s"
            % (how, got.get("message_id") or "нет", got.get("topic") or "не настроена",
               (" · ОБРЕЗАНО: не поместилось %s симв., сняты разделы %s"
                % (got.get("lost"), ", ".join(str(d) for d in dropped))) if dropped else "",
               ("" if got.get("ok") else " · причина: %s" % one_line(got.get("why"), 120))))
