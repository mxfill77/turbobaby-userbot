def part_now(shtab, running, today="", idle=None, shtab_last=None):
    """СЕЙЧАС ДЕЛАЕМ: слова Штаба + что в работе + ПРОСТОЙ и ПРИХОД ШТАБА.

    ``running`` — ``[{"id":…, "goal":…, "age": сек|None}]`` либо ``None``
    («слепок не прочитан»). Пустой список и ``None`` — РАЗНЫЕ новости, и обе
    названы словами: «в работе ничего» против «неизвестно».

    Строки простоя и прихода Штаба стоя́т ЗДЕСЬ, а не в «ЧИСЛАХ», по одной
    причине: они отвечают на вопрос «что происходит сейчас», и читаются они
    вплотную к строке «полоса свободна», которую до 03.09 было нечем поправить.
    """
    out = ["Штаб: %s" % shtab_words(shtab, "now", today)]
    if running is None:
        out.append("в работе: %s" % number(None, "слепок очереди не прочитан"))
    elif not running:
        out.append("в работе строк нет — полоса свободна")
    else:
        rows = []
        for one in running:
            age = one.get("age")
            rows.append("#%s «%s» — %s"
                        % (one.get("id"), one_line(one.get("goal"), GOAL_MAX),
                           ("идёт %s" % age_words(age)) if age is not None
                           else "с какого времени НЕИЗВЕСТНО (отметки claim нет)"))
        out += ["в работе %d: %s" % (len(running), rows[0])] + rows[1:LIST_MAX]
        if len(rows) > LIST_MAX:
            out.append("…и ещё %d" % (len(rows) - LIST_MAX))
    out.append(idle_words(idle))
    out.append(shtab_last_words(shtab_last, today))
    alarm = idle_alarm(idle, shtab_last, today)
    if alarm:
        out.append(alarm)
    return out


def part_stuck(shtab, expects, failed, today=""):
    """ЗАСТРЯЛО: слова Штаба + открытые ожидания + упавшее за сутки."""
    out = ["Штаб: %s" % shtab_words(shtab, "stuck", today)]
    if expects is None:
        out.append("открытых ожиданий О1–О4: %s" % number(None, "слой ожиданий не прочитан"))
    elif not expects:
        out.append("открытых ожиданий О1–О4 нет")
    else:
        out.append("открытых ожиданий О1–О4: %d — %s"
                   % (len(expects), " · ".join(listed(sorted(expects)))))
    if failed is None:
        out.append("упало за сутки: %s" % number(None, "слепок очереди не прочитан"))
    elif not failed:
        out.append("упавших строк за сутки нет")
    else:
        out.append("упало за сутки %d: %s"
                   % (len(failed), " · ".join(listed(["#%s %s" % (f.get("id"),
                                                                 one_line(f.get("why"), 48))
                                                      for f in failed]))))
    return out


def part_goal(shtab, counted, today="", why=""):
    """ЭТАП И КУДА ИДЁМ: слова Штаба + чем меряется рост и сколько осталось.

    Критерий фазы берётся у сводки (:data:`contour_digest.SERIES_TARGET`) — второе
    определение «тридцати подряд» развело бы два показа при одном источнике.

    ``why`` — ПОЧЕМУ числа нет, готовыми словами от :func:`contour_digest_run.fresh_why`
    (правка 11.09.2026, хвост задания 31-a). До неё здесь стоял один литерал на все
    исходы — «слепок очереди не прочитан», — и при слепке, который ПРОЧИТАН и просто
    старше предела, строка утверждала неправду и посылала чинить диск вместо вставшего
    демона. Слова считаются ТАМ, где известен возраст и предел; своего разбора здесь
    не заводится — он разошёлся бы с гашением числа на первой же правке порога.

    Причину не подали → прежний текст: правка не роняет чужие вызовы, а величина
    («НЕИЗВЕСТНО», а не ноль) не трогается ни одной веткой — она верна с f5dc9ab.
    """
    out = ["Штаб: %s" % shtab_words(shtab, "goal", today)]
    if not counted:
        out.append("критерий фазы: %d чистых цепочек подряд · сейчас %s"
                   % (cd.SERIES_TARGET,
                      number(None, why or "слепок очереди не прочитан")))
