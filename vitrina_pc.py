def part_now(shtab, running, today="", idle=None, shtab_last=None):
    """СЕЙЧАС ДЕЛАЕМ: слова Штаба + что в работе + ПРОСТОЙ и ПРИХОД ШТАБА.

    ``running`` — ``[{"id":…, "goal":…, "age": сек|None}]`` либо ``None``
    («слепок не прочитан»). Пустой список и ``None`` — РАЗНЫЕ новости, и обе
    названы словами: «в работе ничего» против «неизвестно».

    Строки простоя и прихода Штаба стоя́т ЗДЕСЬ, а не в «ЧИСЛАХ», по одной
    причине: они отвечают на вопрос «что происходит сейчас», и читаются они
    вплотную к строке «полоса свободна», которую до 03.09 было нечем поправить.
    """
    out = ["Штаб: %s" % shtab_words(shtab, "now", today)]
    if running is None:
        out.append("в работе: %s" % number(None, "слепок очереди не прочитан"))
    elif not running:
        out.append("в работе строк нет — полоса свободна")
    else:
        rows = []
        for one in running:
            age = one.get("age")
            rows.append("#%s «%s» — %s"
                        % (one.get("id"), one_line(one.get("goal"), GOAL_MAX),
                           ("идёт %s" % age_words(age)) if age is not None
                           else "с какого времени НЕИЗВЕСТНО (отметки claim нет)"))
        out += ["в работе %d: %s" % (len(running), rows[0])] + rows[1:LIST_MAX]
        if len(rows) > LIST_MAX:
            out.append("…и ещё %d" % (len(rows) - LIST_MAX))
    out.append(idle_words(idle))
    out.append(shtab_last_words(shtab_last, today))
    alarm = idle_alarm(idle, shtab_last, today)
    if alarm:
        out.append(alarm)
    return out


