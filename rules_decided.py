# ПРИБОР: три исхода, и «неизвестно» не равно «хорошо».
DELIVERED = "ДОЕХАЛО"
NOT_DELIVERED = "НЕ ДОЕХАЛО"
UNKNOWN = "НЕИЗВЕСТНО"


def build_prompt(**kwargs):
    """Собрать промпт ТОЙ ЖЕ функцией, которой его собирает бот → (промпт, причина-отказа).

    Успех → (str, ''). Отказ → ('', 'своими словами что именно помешало и где'). Исключений
    наружу не бросает СОЗНАТЕЛЬНО: прибор обязан уметь сказать «НЕИЗВЕСТНО» с причиной, а не
    упасть с трейсбеком, из которого исход не читается.

    Книгу правил НЕ передаём и передавать не должны: все записи реестра живут в критичных
    фактах, а критфакты склеиваются безусловно. Промпт с `playbook=''` — это и есть тот
    минимум, который голова видит ВСЕГДА; найдено в нём — значит доедет на любом пути.
    """
    try:
        import suggest
    except Exception as e:                                              # noqa: BLE001
        return "", "не удалось импортировать suggest.py: %s: %s" % (type(e).__name__, e)
    try:
        params = {"faq": "FAQ", "lang": "ru"}
        params.update(kwargs)
        return suggest.make_system_prompt(**params), ""
    except Exception as e:                                              # noqa: BLE001
        return "", "suggest.make_system_prompt бросил %s: %s" % (type(e).__name__, e)


def check_rule(rule, prompt, build_error=""):
    """Один вердикт по одной записи реестра → (исход, пояснение).

    `prompt` пуст И названа причина отказа сборки → НЕИЗВЕСТНО с этой причиной. Пустой промпт
    без причины — тоже НЕИЗВЕСТНО: пустой промпт не является доказательством отсутствия строки.
    """
    if build_error:
        return UNKNOWN, build_error
    if not prompt:
        return UNKNOWN, "промпт собрался пустым — судить о доставке нечем"
    if rule["text"] in prompt:
        return DELIVERED, "формулировка найдена в собранном промпте (%d симв.)" % len(prompt)
    return NOT_DELIVERED, (
        "формулировки нет в собранном промпте (%d симв.); место по реестру — %s"
        % (len(prompt), rule["place"])
    )


def check_all(rules=None, prompt=None, build_error=""):
    """Вердикты по всем записям реестра → [(key, исход, пояснение), …].

    `prompt=None` → собрать самим. Отдельный `rules` нужен отрицательному тесту: он подменяет
    ОДНУ запись во ВРЕМЕННОМ месте (в памяти теста), боевых файлов не касаясь.
    """
    rules = RULES if rules is None else rules
    if prompt is None:
        prompt, build_error = build_prompt()
    return [(r["key"],) + check_rule(r, prompt, build_error) for r in rules]
