# -*- coding: utf-8 -*-
"""ЖИВЫЕ ПРИМЕРЫ «вопрос клиента → ответ нашего менеджера» из обезличенной базы переписки.

ЗАЧЕМ. До 12.09.2026 голова видела перед каждым ответом РУЧНОЙ список `suggest.STYLE_FEWSHOT_PAIRS`
(18 пар, отобранных руками в июле). Список не знает вопроса, на который отвечает голова: на «дайте
прайс» и на «байк не заводится» он показывает одно и то же. Слово владельца 12.09: «у нас полтора
года переписок с клиентами скачано. Это по ним надо учиться». Модуль подбирает 3–5 ближайших пар
ПОД ТЕКУЩИЙ ВОПРОС из живой базы.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Примеры — эталон ТОНА, ФОРМЫ и ДЛИНЫ, и ТОЛЬКО. Факты (цена, наличие, сроки,
правила) берутся из записки и книги правил; пример, назвавший цену, разрешением назвать цену не
становится. Инструкция об этом идёт вместе с блоком (`suggest`), а не подразумевается.

ЧЕТЫРЕ ЗАМКА, каждый закрывает названный способ соврать:

1. **Источник — только `client_chats.anonstable.jsonl`.** Соседний `client_chats.anon.jsonl`
   ЗАПРЕЩЁН заданием и своим же WARNING-файлом: его метка есть функция номера строки, а не
   человека, и любая сцепка по ней ложна. Здесь метка нужна как АДРЕС примера (диалог, реплика) —
   позиционная метка дала бы адрес, меняющийся от пересборки базы.
2. **Свой диалог в примеры не попадает.** Вопрос, дословно лежащий в базе, находит СЕБЯ первым и с
   оценкой 1.0 — и бот учился бы на ответе ровно на этот вопрос. Исключается ВЕСЬ диалог, а не одна
   пара: соседние реплики того же диалога — продолжение того же ответа.
3. **Ниже порога примеров НЕТ.** Случайная пара, подставленная «чтобы было», учит форме ответа на
   другой вопрос. Порог ЗАМЕРЕН (см. `SIM_MIN`), а не назначен круглым.
4. **Наружу — ничего.** Модуль отдаёт текст ТОЛЬКО в промпт головы. Ни печати, ни журнала: числа и
   метки — да, строки переписки — нет.

Сеть не трогается ни одной веткой: подбор словарный (idf-косинус по токенам + канон моделей тем же
детектором, что у бота, `model_name`), детерминированный, без ключей и эмбеддингов.
"""

import hashlib
import json
import math
import os
import re

import model_name

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# ИСТОЧНИК. Только стабильно обезличенный корпус; `client_chats.anon.jsonl` не читается нигде.
BASE_FILE = os.environ.get("STYLE_EXAMPLES_BASE") or os.path.join(
    BASE_DIR, "client_chats.anonstable.jsonl")

# ВЫКЛЮЧАТЕЛЬ. `0`/`off`/`false`/`no` — подбор мёртв целиком, промпт байт-в-байт как до правки.
_OFF_WORDS = frozenset(("0", "off", "false", "no", "нет"))


def enabled():
    """Подбор включён? Дефолт — ДА. Выключается `STYLE_EXAMPLES=0` (и синонимами).

    Читается на КАЖДЫЙ вызов, а не один раз на импорте: демон живёт сутками, и выключатель,
    снятый на импорте, потребовал бы перезапуска процесса — то есть был бы выключателем только
    на словах."""
    return str(os.environ.get("STYLE_EXAMPLES", "1")).strip().lower() not in _OFF_WORDS


# ─────────────────────────────── пороги и пределы (все с паспортом) ──────────────────────────

# ПАСПОРТ ПОРОГА: терпит=шум подбора — насколько чужой вопрос ещё считается похожим
#   | замер=20 случайных вопросов базы (медиана оценки 3-го места = 0.2593) ПРОТИВ контроля из
#     10 вопросов чужого домена (максимум 3-го места = 0.1876); порог — СЕРЕДИНА измеренной
#     полосы между ними, то есть точка наибольшего запаса с обеих сторон
#   | снят=2026-09-12 | делится=ДЕЛИТСЯ (оценка непрерывна) | предел-единицы=1.0 (пример
#     содержит каждое значимое слово вопроса) | род=замер
#   | артефакт=docs/artifacts/2026-09-12-ПРИМЕРЫ-zhivye-menedzhery-1209.md
#
# ПОЧЕМУ НЕ «ДОЛЯ СЛУЧАЙНЫХ ПРОХОДЧИКОВ». Первым критерием здесь стояло «ожидание случайных
# совпадений на вопрос меньше одного», и замер его СНЯЛ: нулевое распределение, собранное из пар
# того же корпуса, загрязнено — случайная пара про ту же аренду совпадает ЗАКОННО («сколько
# стоит» встречается сотни раз), и верхний хвост «шума» состоит из настоящих совпадений. Критерий
# дал порог 1.00, то есть убил бы подбор целиком. Отсюда контроль чужим доменом отдельным списком.
SIM_MIN = 0.2235

EX_MIN = 3          # меньше — показывать нечего, берём запасной путь (ручные пары)
EX_MAX = 5          # больше — промпт растёт, а примеры за 5-м местом уже про другое

Q_MIN_CHARS = 8     # «?», «да», «ок» — не вопрос, учиться на них нечему
Q_MAX_CHARS = 400
A_MIN_CHARS = 12    # «.», «ок», «+» — не ответ менеджера
A_MAX_CHARS = 600   # длиннее — это пересланный прайс/договор, а не образец тона

# Токен короче 3 символов не несёт смысла («и», «на»), пустой df — тем более.
_TOKEN_RE = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)
_DIGITS_RE = re.compile(r"^\d+$")

# Слова, стоящие почти в каждой реплике: их совпадение похожестью не является.
_STOP = frozenset("""
здравствуйте привет добрый день утро вечер спасибо пожалуйста скажите подскажите хотел хотела
можно нужно есть быть был была было будет если это тот эта эти как что где когда чтобы для
или его ему them the and you for are with have this that your from not but can will would
про при под над без так тот там тут вот всё все уже ещё либо тоже даже очень просто конечно
""".split())

# СЛЕД ОБЕЗЛИЧИВАНИЯ. Метки анонимайзера («профиль_xxxx», «Клиент_xxxx», «tgid_xxxx») в текст
# примера не идут: голова приняла бы их за формат обращения и стала бы так писать клиенту.
_ANON_MARK_RE = re.compile(r"(?:профиль|Клиент|tgid|телефон|ссылка)_[0-9a-z]{6,}", re.IGNORECASE)

# ОСТАТОК, КОТОРЫЙ ОБЕЗЛИЧИВАНИЕ НЕ СНЯЛО. Задание велело ПРОВЕРИТЬ, а не предположить, и проверка
# 12.09 нашла в 5575 ответах: ссылок — 14, телефонов — 1, номеров юнитов — 0, процентов — 281.
# Первые два вычищаются здесь (живая ссылка или номер в примере уехала бы клиенту как наша);
# проценты ОСТАЮТСЯ и это решение: в корпусе это скидка за срок — часть нормального тона
# менеджера, а не факт, который голове разрешено брать из примера (инструкция рядом с блоком
# велит брать цифры только из блока ЦЕНА). Комиссии-проценты отсекаются словом, а не знаком.
_LEAK_RE = re.compile(
    r"https?://|www\.|t\.me/|@[a-z0-9_]{4,}|\+\d[\d\-\s()]{8,}\d|\bкомисси", re.IGNORECASE)


def _tokens(text):
    """Текст → МНОЖЕСТВО токенов для сравнения: слова + канон моделей тем же детектором, что у бота.

    Модель кладётся ПСЕВДО-ТОКЕНОМ `mdl:FORZA300`, а не остаётся словом, и это не украшение:
    «форза», «forza», «forza 300» — три разных слова и один и тот же байк, и без канона вопрос про
    форзу не находил бы ответов, где она написана иначе. Вес псевдо-токена считает тот же idf, что
    и у слов, — редкое имя модели весит больше частого само собой, без ручного коэффициента.

    ЧИСТЫЕ ЧИСЛА ОТБРАСЫВАЮТСЯ. В корпусе это даты и суммы; совпадение по «3000» роднит вопрос про
    депозит с вопросом про пробег, а похожестью не является."""
    t = str(text or "").lower()
    out = set()
    for m in _TOKEN_RE.findall(t):
        if len(m) < 3 or m in _STOP or _DIGITS_RE.match(m):
            continue
        out.add(m)
    for mention in model_name.find_mentions(t):
        out.add("mdl:" + model_name.canon_for(mention))
    return out


def _norm_q(text):
    """Вопрос → форма для сверки «это тот же самый вопрос» (замок 2). Регистр и пробелы не значат."""
    return " ".join(str(text or "").lower().split())


# ──────────────────────────────────────── индекс ─────────────────────────────────────────────

class Index(object):
    """Пары «вопрос клиента → следующая реплика нашего менеджера» + обратный индекс по токенам.

    ОТПЕЧАТОК БАЗЫ хранится ВНУТРИ индекса, и на нём же держится самопересборка: база сменилась —
    отпечаток другой — `get_index()` строит заново, не спрашивая никого. Отпечаток — sha256 ФАЙЛА,
    а не размер и не mtime: правка «символ на символ» размера не меняет, а `git checkout` меняет
    mtime, ничего не меняя в тексте; и то и другое пересобирало бы индекс неверно."""

    def __init__(self, fingerprint, pairs, idf, postings, by_norm_q, idf_unseen):
        self.fingerprint = fingerprint
        self.pairs = pairs              # list[dict(dialog,msg,q,a,toks,norm)]
        self.idf = idf                  # token -> idf
        self.idf_unseen = idf_unseen    # вес слова, которого в базе НЕТ ВОВСЕ (см. `similar`)
        self.postings = postings        # token -> list[pair index]
        self.by_norm_q = by_norm_q      # нормализованный вопрос -> set(номера диалогов)
        self.norms = [math.sqrt(sum(idf[t] ** 2 for t in p["toks"])) for p in pairs]

    def __len__(self):
        return len(self.pairs)


def fingerprint(path=None):
    """sha256 файла базы (hex, 16 первых символов) | '' — файла нет. Открывает только чтение."""
    path = path or BASE_FILE
    h = hashlib.sha256()
    try:
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
    except OSError:
        return ""
    return h.hexdigest()[:16]


def _iter_pairs(path):
    """Пары «последняя реплика серии клиента → первая ответная реплика company» из базы.

    Серия клиента СКЛЕИВАЕТСЯ в один вопрос: клиент часто дробит мысль на три сообщения подряд, и
    менеджер отвечает на все три сразу. Взять только последнюю значило бы подписать ответ под
    обрывком («…и ещё шлем?» → полный расчёт) и учить голову отвечать не на то, что спросили.

    Номер реплики (`msg`) — индекс ОТВЕТА менеджера в диалоге: он и есть адрес показанного образца.
    """
    with open(path, encoding="utf-8") as f:
        for dialog_no, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            ms = rec.get("messages") or []
            i = 0
            while i < len(ms):
                if (ms[i] or {}).get("who") != "client":
                    i += 1
                    continue
                j = i
                while j < len(ms) and (ms[j] or {}).get("who") == "client":
                    j += 1
                if j < len(ms) and (ms[j] or {}).get("who") == "company":
                    q = " ".join((ms[k].get("text") or "").strip() for k in range(i, j)).strip()
                    a = (ms[j].get("text") or "").strip()
                    if (Q_MIN_CHARS <= len(q) <= Q_MAX_CHARS
                            and A_MIN_CHARS <= len(a) <= A_MAX_CHARS
                            and not _ANON_MARK_RE.search(a) and not _LEAK_RE.search(a)):
                        yield dialog_no, j, q, a
                i = j


def build_index(path=None):
    """Собрать индекс с нуля. → Index. Файла нет / пуст — пустой индекс (это НЕ исключение:
    отсутствие базы обязано гасить примеры, а не ронять ответ клиенту)."""
    path = path or BASE_FILE
    fp = fingerprint(path)
    pairs, df = [], {}
    if fp:
        for dialog_no, msg_no, q, a in _iter_pairs(path):
            toks = _tokens(q)
            if not toks:
                continue
            pairs.append({"dialog": dialog_no, "msg": msg_no, "q": q, "a": a,
                          "toks": toks, "norm": _norm_q(q)})
            for t in toks:
                df[t] = df.get(t, 0) + 1
    n = len(pairs) or 1
    idf = {t: math.log(1.0 + float(n) / c) for t, c in df.items()}
    postings, by_norm_q = {}, {}
    for i, p in enumerate(pairs):
        for t in p["toks"]:
            postings.setdefault(t, []).append(i)
        by_norm_q.setdefault(p["norm"], set()).add(p["dialog"])
    return Index(fp, pairs, idf, postings, by_norm_q, math.log(1.0 + float(n)))


_INDEX = None


def get_index(path=None):
    """Индекс ЭТОЙ базы. Строится ОДИН раз на процесс и пересобирается САМ, когда сменился
    отпечаток файла.

    Кеш держится в памяти, а не на диске, и это ЗАМЕР, а не лень: полная сборка на 710 диалогах
    занимает доли секунды (число — в артефакте), то есть дисковый кеш экономил бы меньше, чем
    стоит его собственная сверка, и добавил бы второй источник правды, умеющий протухнуть."""
    global _INDEX
    path = path or BASE_FILE
    fp = fingerprint(path)
    if _INDEX is None or _INDEX.fingerprint != fp:
        _INDEX = build_index(path)
    return _INDEX


# ──────────────────────────────────────── подбор ─────────────────────────────────────────────

def similar(question, limit=EX_MAX, threshold=SIM_MIN, index=None):
    """3–5 ближайших пар к вопросу клиента. → list[dict(dialog,msg,client,company,score)].

    ОЦЕНКА — ДОЛЯ СМЫСЛОВОЙ МАССЫ ВОПРОСА, ПОКРЫТАЯ ПРИМЕРОМ: сумма idf общих токенов, делённая на
    сумму idf всех токенов вопроса. Диапазон 0..1, где 1.0 — пример содержит каждое значимое слово
    вопроса. Первой версией здесь стоял симметричный косинус, и он был снят ЗАМЕРОМ, а не по вкусу:
    косинус делит ещё и на длину примера, поэтому длинный вопрос клиента («Здравствуйте! Хочу XMAX
    300 с 6 по 11 октября, залог паспортом, 1 шлем») получал низкую оценку с КАЖДЫМ коротким
    ответом менеджера — то есть ровно с теми, ради которых подбор и заведён. Замер 12.09 на 19
    реальных вопросах: косинус давал 3+ примера восьми, доля массы — десяти, при этом чужой домен
    (8 вопросов не про аренду) остался на нуле у обоих. Длина примера не в знаменателе, а в
    пределах `A_MAX_CHARS`: длинное в индекс не берётся вовсе.

    Ниже порога не отдаём НИ ОДНОЙ
    (замок 3); свой диалог исключается целиком (замок 2). Порядок — по убыванию оценки, при равной
    оценке по адресу (диалог, реплика), чтобы выдача была ВОСПРОИЗВОДИМОЙ: множества в Python
    ходят в произвольном порядке, и без этого добора один и тот же вопрос давал бы разные примеры
    в разных процессах."""
    # `get_index() if index is None else index`, а НЕ `index or get_index()`: у `Index` есть
    # `__len__`, поэтому ПУСТОЙ индекс ЛОЖЕН, и короткая форма молча подменяла бы его живым. Цена
    # ровно та, от которой заведён замок «база недоступна → тишина»: отсутствие базы отдавало бы
    # примеры вместо пустоты. Поймано собственным набором (`test_missing_base_is_silence_not_crash`).
    idx = get_index() if index is None else index
    q_toks = _tokens(question)
    if not q_toks or not idx.pairs:
        return []
    idf = idx.idf
    # СЛОВО, КОТОРОГО В БАЗЕ НЕТ ВОВСЕ, ВЕСИТ МАКСИМУМ, А НЕ НОЛЬ. Замер 12.09 на первой версии,
    # где незнакомое слово весило 0: «Где найти учебник по квантовой электродинамике» получало
    # оценку 0.890, «Сколько стоит поставить брекеты» — 0.616. Причина не в косинусе, а в том, что
    # незнакомые слова выпадали ИЗ ОБЕИХ частей дроби: вопрос про брекеты превращался в вопрос
    # «сколько стоит поставить» и честно находил своих близнецов. Незнакомое слово — самое РЕДКОЕ
    # из возможных (df<1), поэтому его вес — потолок шкалы idf; оно не совпадает ни с чем и тянет
    # оценку вниз ровно в той мере, в какой вопрос про чужое.
    q_weights = {t: idf.get(t, idx.idf_unseen) for t in q_toks}
    q_mass = sum(q_weights.values())
    if q_mass <= 0:
        return []
    # Замок 2: вопрос дословно лежит в базе → весь его диалог вне игры.
    banned = set(idx.by_norm_q.get(_norm_q(question)) or ())
    acc, hits = {}, {}
    for t, w in q_weights.items():
        if w <= 0:
            continue
        for i in idx.postings.get(t, ()):  # пустой кортеж — токена в базе нет вовсе
            acc[i] = acc.get(i, 0.0) + w
            hits[i] = hits.get(i, 0) + 1
    scored = []
    for i, dot in acc.items():
        # ОДНО общее слово похожестью не является: на коротких репликах («Сколько стоит?» — два
        # значимых слова) единственное совпадение забирает половину массы и тащит наверх пару про
        # другое. Требуем ДВА — кроме случая, когда и в самом вопросе значимое слово ровно одно.
        if hits.get(i, 0) < min(2, len(q_toks)):
            continue
        score = dot / q_mass
        if score < threshold:
            continue
        p = idx.pairs[i]
        if p["dialog"] in banned:
            continue
        scored.append((-score, p["dialog"], p["msg"], i))
    scored.sort()
    out = []
    for neg, dialog, msg, i in scored[:max(0, int(limit))]:
        p = idx.pairs[i]
        out.append({"dialog": dialog, "msg": msg, "client": p["q"], "company": p["a"],
                    "score": round(-neg, 4)})
    return out


def pick(question, index=None):
    """То, что реально уходит голове: список 3–5 пар ЛИБО пустой список.

    ВСЁ ИЛИ НИЧЕГО, а не «сколько нашлось»: одна-две пары выше порога — это не образец тона, а
    случайный сосед, и голова приняла бы его за единственную правильную форму ответа. Меньше
    `EX_MIN` — примеров нет, и запасным путём остаются ручные пары `suggest.STYLE_FEWSHOT_PAIRS`."""
    if not enabled():
        return []
    got = similar(question, limit=EX_MAX, index=index)
    return got if len(got) >= EX_MIN else []


