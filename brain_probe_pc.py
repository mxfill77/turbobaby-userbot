MSG_MAX = 300                 # хвост чужого сообщения режем: детали чтения едут в текст вердикта

# Коды `brain_writer.BrainWriterError`, которые нам нужны ПОИМЁННО (1 конфиг/аргументы,
# 2 чтение). Сверяются с живым модулем тестом — литерал в двух местах обязан совпадать.
CODE_CONFIG = 1
CODE_READ = 2

BLAME_HANDS = "руки"
BLAME_SOURCE = "источник"
BLAME_NODE = "узел"
BLAME_TESTRUN = "тест-прогон"
BLAMES = (BLAME_HANDS, BLAME_SOURCE, BLAME_NODE, BLAME_TESTRUN)


class ProbeError(RuntimeError):
    """Отказ чтения С НАЗВАННОЙ ВИНОЙ. `blame` — одно слово из `BLAMES`, либо ПУСТО, если вину
    назвать не удалось. Пустая вина — честный третий исход, а не «наверное, источник»."""

    blame = ""


class HandsBroken(ProbeError):
    """Сломаны МЫ: читателя не собрать, у него нет метода, он вернул не текст."""

    blame = BLAME_HANDS


class SourceDown(ProbeError):
    """Недоступен ИСТОЧНИК: мост не ответил, оборвал, отдал не-ok."""

    blame = BLAME_SOURCE


class UnknownNode(ProbeError):
    """Ключа с таким именем живой реестр не знает — вердикт ПРО ИМЯ, а не про транспорт."""

    blame = BLAME_NODE


class LiveForbidden(ProbeError):
    """Живое чтение запрещено признаком тест-прогона (или тем, что признак не снялся)."""

    blame = BLAME_TESTRUN


def _unnamed(reason):
    """Явное «признак не снят» с названной причиной: ни один `except` здесь не нем.

    Возвращает `None` — ТРЕТИЙ ИСХОД, а не `False`: «не знаю, тест ли это» и «это не тест» —
    разные ответы, и слепить их значило бы пустить живое чтение из-под гейта."""
    return None


def _test_context():
    """Идёт тест-прогон? True/False/None, где None = ПРИЗНАК НЕ СНЯТ.

    Точка правды репо — `log_setup.is_test_context` (тем же адресом её спрашивает
    `brain_writer._in_test_context`). Отличие от соседа намеренное: сосед на сбое отвечает
    `False` (fail-open, ему это ничем не грозит — он всё равно пойдёт по своей ветке), а здесь
    сбой обязан ЗАКРЫТЬ дверь."""
    try:
        from log_setup import is_test_context                          # noqa: PLC0415
    except Exception:                                                  # noqa: BLE001
        return _unnamed("модуль признака тест-прогона не импортировался")
    try:
        return bool(is_test_context())
    except Exception:                                                  # noqa: BLE001
        return _unnamed("признак тест-прогона не ответил")


def _reader_fn():
    """→ живой читатель узла (`brain_writer.read_text`) либо `HandsBroken`.

    Импорт ЛЕНИВЫЙ и обёрнут намеренно: сорвавшийся импорт доверенного писателя — это поломка
    РУК, и она обязана звучать своим словом, а не «источник недоступен»."""
    try:
        import brain_writer                                            # noqa: PLC0415
    except Exception as exc:                                           # noqa: BLE001
        raise HandsBroken("читателя мозга не собрать: %s: %s" % (type(exc).__name__, exc))
    got = getattr(brain_writer, "read_text", None)
    if not callable(got):
        raise HandsBroken("у доверенного писателя нет метода read_text — руки не те")
    return got


def _short(exc):
    """Чужое сообщение об отказе — коротко и без хвоста. Секретов писатель не раскрывает сам."""
    words = "%s: %s" % (type(exc).__name__, exc)
    if len(words) > MSG_MAX:
        return words[:MSG_MAX] + "…"
    return words


def _blamed(exc, key):
    """Отказ читателя → отказ С НАЗВАННОЙ ВИНОЙ. Судим ПОЛЯМИ отказа, а не подстрокой.

    Порядок веток — не вкусовой: вердикт ПРО ИМЯ несёт код 1 (как и отказ конфига), поэтому
    `verdict` спрашивается ПЕРВЫМ, иначе неизвестный ключ узла выглядел бы поломкой рук."""
    words = "узел «%s» не прочитан — %s" % (key, _short(exc))
    if getattr(exc, "verdict", False) is True:
        return UnknownNode(words)
    code = getattr(exc, "code", None)
    if code == CODE_CONFIG:
        return HandsBroken(words)
    if code == CODE_READ:
        return SourceDown(words)
    return ProbeError(words)


def read_doc(doc, allow_test_context=False):
    """КЛЮЧ УЗЛА → ТЕКСТ, либо `ProbeError` с названной виной. Ничего не пишет и не кэширует.

    `allow_test_context=True` — ЕДИНСТВЕННЫЙ waiver замка «под тест-прогоном наружу не ходим».
    Он назван словом, а не выведен из окружения: тест, которому нужны НАСТОЯЩИЕ руки, обязан
    сказать это вслух в своём коде."""
    key = str(doc).strip()
    if len(key) == 0:
        raise HandsBroken("ключ узла пуст — читать нечего")
    if not allow_test_context:
        under_test = _test_context()
        if under_test is None:
            raise LiveForbidden("признак тест-прогона НЕ СНЯТ — живое чтение не пускаю "
                                "(fail-closed: «не знаю» дверь не открывает)")
        if under_test:
            raise LiveForbidden("идёт тест-прогон: живое чтение узла «%s» запрещено — флаг "
                                "держит писателя от записи, а чтение закрываем здесь" % key)
    reader = _reader_fn()
    try:
        text = reader(name=key)
    except Exception as exc:                                           # noqa: BLE001
        raise _blamed(exc, key)
    if not isinstance(text, str):
        raise HandsBroken("узел «%s»: читатель вернул не текст (%s) — контракт рук нарушен"
                          % (key, type(text).__name__))
    return text


def reader(allow_test_context=False):
    """→ ВЫЗЫВАЕМОЕ «ключ узла → текст»: те же руки одним аргументом.

    Ради этого имени модуль и нужен вызывающему: судья адреса держит читателя ОДНОМЕСТНЫМ
    (`read_doc(doc)`), и waiver замка выбирается ЗДЕСЬ, при сборке рук, а не внутри чтения."""
    def read_one(doc):
        return read_doc(doc, allow_test_context=allow_test_context)
    return read_one
