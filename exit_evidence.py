# -*- coding: utf-8 -*-
"""exit_evidence.py — СВИДЕТЕЛЬСТВО ВЫХОДА ПРОЦЕССА, и разведение «нам не дали работать»
от «мы сломались».

ЗАЧЕМ ЭТОТ МОДУЛЬ ЕСТЬ. До 21.09.2026 у полосы ПК было ОДНО слово на два разных события.
Перепись 69n (`docs/artifacts/2026-09-21-69n-PRICHINAPOLEM-2109.md`, §3) измерила это числом:
за семь суток 14–21.09 шесть рядов закрылись кодом `exec_error`, и ни у одного из шести
причина не была установима по записям, которые полоса делает САМА. Механика потери — две
строки чужого кода:

  * у думателя (`pc_orchestrator._thinker_exec`) stderr захвачен `capture_output=True` и
    выброшен ЦЕЛИКОМ: в лог уходило ровно «думатель exit=N — fail-safe», без текста;
  * у исполнителя (`pc_orchestrator._run_task_impl`, ветка `rc != 0`) stderr ехал в отчёт
    ТОЛЬКО фолбэком при пустом stdout, а своей строки лога у ветки не было вовсе.

Кода, который умеет опознать упор в лимит подписки, не существовало: греп по
`usage limit`, `rate limit`, `429` давал ноль совпадений. Живая форма отказа при этом
лежала в фикстурах под тем же `exec_error`.

═══ ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО ЗДЕСЬ НЕТ ═══════════════════════════════════════════════════════

Модуль ЧИСТЫЙ: ни диска, ни сети, ни окружения, ни импортов полосы. Он не решает судьбу
задачи и не пишет никуда — он отвечает на один вопрос о готовом выходе процесса и отдаёт
строку свидетельства. Решение принимает вызывающий (`pc_orchestrator`).

═══ ЗАМОК: ПРИЗНАК ПРИХОДИТ ИЗ ВЫХОДА ПРОЦЕССА ════════════════════════════════════════════

:func:`classify` НИКОГДА не называет исход внешним ограничением без НЕНУЛЕВОГО КОДА ВОЗВРАТА.
Код возврата ставит ОС, а не наш пересказ и не модель: текст доклада его не производит.
`rc == 0` (и `rc`, которого нет вовсе) → :data:`OUT_NONE`, и ни одна ветка ниже не выполняется.
Это не стиль, а предмет отрицательного теста: «признак выглядит правильным, свидетельства нет»
обязано давать отказ.

ВТОРОЙ ЗАМОК — ЯКОРЬ МЕСТА. Слова ищутся ТОЛЬКО на ПОСЛЕДНЕЙ НЕПУСТОЙ СТРОКЕ stdout или
stderr (:func:`last_line`), куда CLI ставит свою фатальную строку. Правило не новое: ровно так
с 17.09 (задание 63-c) судит `pc_orchestrator._fail_is_network`, и по той же причине — задача,
РАЗБИРАЮЩАЯ этот класс, обязана процитировать «You've hit your usage limit» в собственном
докладе, и поиск по всему тексту купил бы ей вердикт «нам не дали работать» за рассказ о нём.
ЦЕНА НАЗВАНА ВСЛУХ: многострочная форма, где фраза отказа стои́т не последней строкой, здесь
опознана не будет — она получит :data:`OUT_UNKNOWN` со СВИДЕТЕЛЬСТВОМ, то есть честное
«не знаю» вместо догадки.

ТРЕТИЙ ЗАМОК — НЕОДНОЗНАЧНОСТЬ НЕ РАЗРЕШАЕТСЯ В ПОЛЬЗУ КРАСИВОГО ИМЕНИ. Совпали слова ДВУХ
разных сортов на одной строке — исход :data:`OUT_UNKNOWN`, а оба совпадения печатаются в
свидетельстве. «Отличить нельзя» — это ответ, а угадывание — нет.

═══ СЕКРЕТЫ ВЫРЕЗАЮТСЯ ДО ЗАПИСИ ══════════════════════════════════════════════════════════

stderr чужого процесса может нести ключи. :func:`scrub` зовётся ВНУТРИ :func:`evidence` до
того, как строка вообще собрана, — не у вызывающего и не «не забыть потом». Вызывающему
незачем помнить о чистке, чтобы она случилась.
"""
from __future__ import annotations

import re

# ── ИСХОДЫ ────────────────────────────────────────────────────────────────────────────────
# Имя исхода обязано совпадать с тем, что он меряет. Общее для трёх первых — «процесс
# ОТКАЗАЛСЯ РАБОТАТЬ по внешнему ограничению», а не «ошибка выполнения»: работа не начиналась
# и от её содержания ничего не зависело.
OUT_LIMIT = "limit"          # упор в лимит/квоту подписки — пережидать до названного сброса
OUT_OVERLOAD = "overload"    # чужая сторона перегружена — повторять скоро, ничего не чинить
OUT_ACCESS = "access"        # доступ не продлён (сессия/ключ) — чинит ЧЕЛОВЕК, ждать бесполезно
OUT_UNKNOWN = "unknown"      # процесс отказал, СВИДЕТЕЛЬСТВО СОХРАНЕНО, разделить его нечем
OUT_NONE = ""                # процесс не отказывался: кода возврата нет или он нулевой

# Человеческие имена. Читает их владелец, поэтому каждое несёт СЛЕДУЮЩИЙ ШАГ, а не ярлык:
# ради разных следующих шагов исходы и разведены.
OUT_NAMES = {
    OUT_LIMIT: "упор в лимит подписки — работать не дали, надо переждать до сброса",
    OUT_OVERLOAD: "чужая сторона перегружена — работать не дали, повтор имеет смысл скоро",
    OUT_ACCESS: "доступ не продлён (сессия/ключ) — работать не дали, ожидание не поможет",
    OUT_UNKNOWN: "процесс отказал, но чем именно — по его словам не отличить",
}
# Исходы, у которых предмет — ВНЕШНЕЕ ОГРАНИЧЕНИЕ (нам не дали работать), а не наша поломка.
# `unknown` сюда НЕ входит сознательно: «не знаю» льготы не даёт нигде на полосе.
OUT_EXTERNAL = (OUT_LIMIT, OUT_OVERLOAD, OUT_ACCESS)

TAIL_MAX = 400               # хвост stderr в свидетельстве; рез объявляет себя числом
SAID_MAX = 200               # слова процесса в свидетельстве
# ИМЯ ПОЛЯ ЖИВЁТ ОДНИМ ЛИТЕРАЛОМ, потому что его теперь ЧИТАЮТ ОБРАТНО. Свидетельство собирает
# `evidence`, а вынимает слова процесса `said_of` — второй экземпляр строки разошёлся бы с первым
# молча (известный класс полосы), и читатель получил бы пустые слова при названных.
SAID_HEAD = "процесс сказал: "

# ── СЛОВАРИ, СНЯТЫЕ С ЖИВЫХ ПРОВАЛОВ ──────────────────────────────────────────────────────
# ═══ ПОЛОСА УЖЕ ПЛАТИЛА ЗА СЛОВАРЬ, И ЭТО СКАЗАНО ЗДЕСЬ, А НЕ ЗАБЫТО ══════════════════════
# 17.09.2026 (задание 62-p) словарь чужих слов был ВЫНУТ из `shtab_box_signals.external_refusal`
# с прямым выводом: «он всегда отстаёт на один чужой текст» (03.09 знал одну форму, 12.09 не
# узнал «session limit», 16.09 не узнал «OAuth session expired»). Почему словарь возвращается
# здесь и почему это не откат того решения — три различия, каждое существенное:
#   1) ТАМ словарь был УСЛОВИЕМ льготы: не узнал форму — ряд терял исход «неизвестно» и съедал
#      слот суток, то есть промах словаря МЕНЯЛ СУДЬБУ ряда. ЗДЕСЬ промах словаря не меняет
#      ничего, кроме имени: исход становится `unknown`, свидетельство сохраняется целиком, а
#      льготу по-прежнему решают ДВА замка без единого слова — ненулевой код и отсутствие следов;
#   2) ТАМ вопрос был «чья сторона сломалась» — и он был не тот. ЗДЕСЬ вопрос «что делать
#      дальше»: ждать сброса, повторить скоро или звать человека. На него без слов процесса не
#      отвечает вообще ничто;
#   3) ТАМ словарь читал НАШ ПЕРЕСКАЗ (поле `result`, куда пишет и модель). ЗДЕСЬ — выход
#      процесса, за ненулевым кодом возврата и на последней строке.
# Обязательство, которое отсюда следует: новая форма отказа обязана приезжать как `unknown` со
# свидетельством, а не как тишина. Это предмет теста, а не обещание.
# Голдены детекта — ДОСЛОВНЫЕ фразы из живых рядов полосы, а не придуманные «похожие»:
# придуманная зеленеет молча, живая ловит различитель на настоящем формате.
#   #90, #92 (18.09) : «You've hit your weekly limit · resets Sep 22, 4am (Asia/Bangkok).»
#   #153, #154 (20.09): «You've hit your session limit · resets 4am (Asia/Bangkok).»
#   #37 (12.09)      : «You've hit your session limit · resets 3:30am (Asia/Bangkok)»
#   #51, #52 (16.09) : «Failed to authenticate: OAuth session expired and could not be refreshed.»
#   #101 (03.09)     : «API Error: 529 Overloaded. This is a server-side issue, usually temporary…»
# Источник первых четырёх — расписки `docs/review_receipts/pc-2026-09-{16,18,20}-*.json`,
# поле `result_head`; остальные — фикстуры `test_ext_refusal_unknown.py`.
_RE_LIMIT = re.compile(
    r"(?:hit your (?:\w+[ -])?limit"
    r"|usage limit|session limit|weekly limit|rate limit(?:ed)?"
    r"|limit (?:reached|exceeded)"
    r"|quota (?:exceeded|exhausted)|out of (?:quota|credits)"
    r"|credit balance is too low|insufficient (?:credits|quota)"
    r"|too many requests|\b429\b)", re.I)
_RE_OVERLOAD = re.compile(
    r"(?:\b529\b|overloaded|server[ -]side issue"
    r"|service (?:unavailable|temporarily unavailable)|temporarily unavailable"
    r"|\b503\b|\b502\b)", re.I)
_RE_ACCESS = re.compile(
    r"(?:failed to authenticate|authentication[_ ]error|oauth[^\n]{0,40}expired"
    r"|session expired|token (?:expired|revoked)|invalid api key|invalid_api_key"
    r"|unauthorized|not authenticated|please run [\"'/`]?login"
    r"|\b401\b|\b403\b)", re.I)
_KIND_RE = ((OUT_LIMIT, _RE_LIMIT), (OUT_OVERLOAD, _RE_OVERLOAD), (OUT_ACCESS, _RE_ACCESS))

# ── ВЫРЕЗАНИЕ СЕКРЕТОВ ────────────────────────────────────────────────────────────────────
# ДВА ПЛЕЧА, и они ловят разное. Первое — НАЗВАННАЯ ПАРА («KEY=значение»): имя остаётся,
# значение уходит, потому что имя переменной диагноз несёт, а значение — нет. Второе — ФОРМА
# САМОГО КЛЮЧА без имени рядом: чужой процесс печатает токен в URL и в заголовке, где имени
# нашей переменной нет вовсе.
# ИМЯ ОГРАНИЧЕНО НАРОЧНО. Первая редакция считала именем любое слово, СОДЕРЖАЩЕЕ «auth», и
# связкой — простой пробел; на живой фикстуре #51 это давало «OAuth ***» вместо «OAuth session
# expired and could not be refreshed», то есть чистка съедала сам диагноз. Поэтому имя обязано
# ЗАКАНЧИВАТЬСЯ ключевым словом (префиксы через `_`/`-`: ANTHROPIC_API_KEY, BRIDGE_TOKEN), а
# связка обязана быть `=` или `:`. Слово «unauthorized» именем не становится ни одной веткой.
_RE_BEARER = re.compile(r"\b(bearer|basic)\s+[A-Za-z0-9._~+/=\-]{8,}", re.I)
_RE_SECRET_PAIR = re.compile(
    r"((?:[A-Za-z][A-Za-z0-9]*[_-])*"  # префиксы через _ или - (оставляем)
    r"(?:API[_-]?KEY|APIKEY|TOKEN|SECRET|PASSWORD|PASSWD|CREDENTIALS?|COOKIE|"
    r"AUTHORIZATION|SESSION[_-]?(?:ID|KEY)))"   # ключевое слово в КОНЦЕ имени
    r"(\s*[=:]\s*)"                    # связка (оставляем)
    r"([\"']?)([^\s\"']{6,})",         # значение (вырезаем)
    re.I)
_RE_SECRET_SHAPE = re.compile(
    r"(?:sk-[A-Za-z0-9_\-]{16,}"                            # ключи API
    r"|gh[pousr]_[A-Za-z0-9]{20,}"                          # токены GitHub
    r"|eyJ[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{5,}"   # JWT
    r"|\b\d{8,12}:[A-Za-z0-9_\-]{30,})")                    # токен бота Telegram
# ГОЛОГО ШЕСТНАДЦАТЕРИЧНОГО ПЛЕЧА ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ. Длинный hex на
# этой полосе — это прежде всего хеш коммита (40) и sha256 артефакта (64), то есть ровно та
# валюта доказательства, ради которой свидетельство и пишется. Плечо «замазать всё длинное
# шестнадцатеричное» съедало бы улику в каждой второй строке ради ключа такой формы, которого
# у нас нет ни одного вида. Ключи ловятся именем (первое плечо) и собственной формой (второе).
MASK = "***"


def scrub(text):
    """Вырезать значения секретов, оставив признак. → str.

    ЧТО ОСТАЁТСЯ И ПОЧЕМУ. Имя переменной и форма строки — остаются: по ним диагноз и
    ставится («claude ругается на ANTHROPIC_API_KEY» — это ответ, а само значение ответом
    не является ни в одном случае). Уходит ровно значение.

    ЧЕГО ЭТА ФУНКЦИЯ НЕ ОБЕЩАЕТ, сказано прямо: она не доказывает, что вырезанное было
    секретом, и не доказывает, что невырезанное им не было. Доказать это значило бы держать
    живой секрет рядом для сверки — то есть сделать ровно то, от чего граница и заведена."""
    s = "" if text is None else str(text)
    s = _RE_BEARER.sub(lambda m: m.group(1) + " " + MASK, s)
    s = _RE_SECRET_PAIR.sub(lambda m: m.group(1) + m.group(2) + m.group(3) + MASK, s)
    return _RE_SECRET_SHAPE.sub(MASK, s)


def last_line(text):
    """Последняя непустая строка → str. Место, куда CLI ставит свою фатальную строку."""
    for line in reversed(str(text or "").splitlines()):
        if line.strip():
            return line.strip()
    return ""


def tail(text, n=TAIL_MAX):
    """Хвост ДЛЯ ЗАПИСИ: рез объявляет себя числом, как `_tail_shown` на полосе.
    Короче потолка → байт-в-байт. Решения по этому показу не принимаются."""
    full = str(text or "").strip()
    if len(full) <= n:
        return full
    return "[хвост %d из %d симв.] %s" % (n, len(full), full[-n:])


_SAID_RE = re.compile(re.escape(SAID_HEAD) + r"«([^»\r\n]{1,%d})»" % SAID_MAX)


def said_of(text):
    """ГОТОВОЕ СВИДЕТЕЛЬСТВО → дословные слова процесса, которые в нём названы. → str | "".

    Обратное чтение :func:`evidence`, и нужно оно ровно там, где свидетельство уже уехало в
    текст итога: заголовок для человека (`close_msg_pc.why_line`) обязан показать слова
    процесса, а склеивать их второй раз из `rc`/`stdout`/`stderr` некому — ни того, ни
    другого у читателя итога нет вовсе.

    Пусто — это «слов в свидетельстве не названо», а не «процесс молчал»: `classify` отдаёт
    пустые слова и тогда, когда словарь отказ не узнал (:data:`OUT_UNKNOWN`). Отличать эти
    два состояния читателю заголовка не нужно — показывать нечего в обоих."""
    m = _SAID_RE.search("" if text is None else str(text))
    return m.group(1).strip() if m else ""


def refused(rc):
    """Процесс ОТКАЗАЛСЯ работать (код возврата есть и он не ноль)? → bool.

    ЕДИНСТВЕННЫЕ ВОРОТА ко всем внешним исходам. `None`, пустое, нечисловое → False: кода
    возврата НЕТ, а значит утверждать отказ нечем. Так «не смог проверить» не превращается
    в «проверено»."""
    if rc is None or isinstance(rc, bool):
        return False
    try:
        return int(rc) != 0
    except (TypeError, ValueError):
        return False


def classify(rc, stdout="", stderr=""):
    """Выход процесса → (исход, дословные слова процесса).

    Исход ∈ :data:`OUT_NONE` · :data:`OUT_LIMIT` · :data:`OUT_OVERLOAD` ·
    :data:`OUT_ACCESS` · :data:`OUT_UNKNOWN`. Слова — ТО, ЧТО СОВПАЛО, дословно и без
    перевода: перевод знает ровно те формы, что и словарь, и на новом тексте отдал бы
    читателю пустое имя (тот же урок, что у `shtab_box_signals._ext_words`, 17.09).

    Порядок веток значения НЕ имеет: совпадения собираются ВСЕ, и ровно одно совпадение
    даёт имя. Ноль и два — :data:`OUT_UNKNOWN`."""
    if not refused(rc):
        return OUT_NONE, ""
    line = last_line(stderr) or ""
    hits = [(k, r.search(line)) for k, r in _KIND_RE]
    hits = [(k, m) for k, m in hits if m]
    if not hits:                       # stderr молчит → та же проба по ПОСЛЕДНЕЙ строке stdout
        line = last_line(stdout) or ""  # (в режиме `claude -p` фатальная строка приходит туда)
        hits = [(k, m) for k, m in ((k, r.search(line)) for k, r in _KIND_RE) if m]
    if len(hits) == 1:
        return hits[0][0], hits[0][1].group(0)
    if len(hits) > 1:
        return OUT_UNKNOWN, " + ".join(sorted(m.group(0) for _, m in hits))
    return OUT_UNKNOWN, ""


def is_external(kind):
    """Исход означает «нам не дали работать»? → bool. `unknown` — НЕТ (льготы за незнание нет)."""
    return kind in OUT_EXTERNAL


def evidence(rc, stdout="", stderr="", n=TAIL_MAX):
    """Одна строка свидетельства ДЛЯ ЗАПИСИ (лог, итог задачи). → str.

    Формат: ``exit=<rc> · исход=<код> (<имя>) · процесс сказал: «…» · stderr(…): …``.
    Секреты вырезаны ЗДЕСЬ, до сборки строки; пустой stderr назван словом, а не пропущен
    молча («пуст» — это факт о канале, а отсутствие поля — это ничего)."""
    kind, said = classify(rc, stdout, stderr)
    parts = ["exit=%s" % ("нет" if rc is None else rc)]
    if kind:
        parts.append("исход=%s (%s)" % (kind, OUT_NAMES.get(kind, "имени нет")))
    if said:
        parts.append(SAID_HEAD + "«%s»" % scrub(said)[:SAID_MAX])
    err = tail(scrub(stderr), n)
    parts.append("stderr: %s" % (err if err else "(пуст)"))
    return " · ".join(parts)
