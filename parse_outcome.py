# -*- coding: utf-8 -*-
"""
parse_outcome.py — КОНТРАКТ РЕЗУЛЬТАТА ЧИТАТЕЛЯ ЖИВОГО ТЕКСТА. Одно место на полосу.

КЛАСС, КОТОРЫЙ ЭТО ЛЕЧИТ — «НУЛЬ ПО НЕРАЗБОРУ». У читателя живого текста (лог, журнал, файл
состояния, stdout команды, тело ответа моста) тип возврата имеет ДВА состояния: «вот что нашёл»
и «пусто». Третьего нет — поэтому «не смог разобрать» приходит наверх ТЕМ ЖЕ нулём, что и
«нечего разбирать», и потребитель читает СЛЕПОТУ ЧИТАТЕЛЯ как МОЛЧАНИЕ ИСТОЧНИКА. Чинить надо
контракт, а не разбор: сколько шаблон ни правь, пока наверх идёт одно число, два состояния
неразличимы. Перепись мест полосы — `docs/artifacts/2026-08-08-zero-by-nonparse-pc-recon.md`
(проход по постоянным источникам: 48 мест, 24 слепых; механический свип точек разбора: 182/102 —
в какой зернистости ни считай, слепа примерно половина).

КОНТРАКТ. Наверх идёт ПАРА ЧИСЕЛ и ИСХОД:

  • `seen`   — сколько единиц источника ОСМОТРЕНО (строк лога, записей реестра, полей);
  • `parsed` — сколько из них читатель ОПОЗНАЛ как свой формат (не «сколько улик нашёл»:
               здоровый источник законно даёт ноль улик, но не ноль опознанных единиц);
  • `outcome` — ровно один из ТРЁХ:

        EMPTY    (seen == 0)              разбирать было нечего — источник молчит;
        PARSED   (parsed > 0)             разобрано;
        NONPARSE (seen > 0 и parsed == 0) ТРЕТИЙ ИСХОД, у него своё имя — «НЕРАЗБОР»:
                                          источник непуст, а читатель не опознал в нём НИ ОДНОЙ
                                          единицы. Это ОТКАЗ ЧИТАТЕЛЯ, а не молчание источника.

Третий исход обязан ПРОИЗНОСИТЬСЯ ВСЛУХ (`Reading.say()`), а не сворачиваться в нуль: цена
молчания — ровно та, что в серверном инциденте (шаблон не совпал ни с одной из 28 непустых
строк, наверх ушло «тиков ещё не было», источник молчал 80.9 ч незамеченным).

`parsed > seen` — ошибка ЧИТАТЕЛЯ, а не входа: разобрать больше, чем осмотрел, нельзя, и такой
вызов падает `ValueError` сразу, а не отдаёт наверх правдоподобное число.

ЧЕГО КОНТРАКТ НЕ ДЕЛАЕТ (граница названа честно, чтобы им не прикрывались). Он НЕ различает
«источник не прочитан» (нет файла, отказ доступа, сорванный stat) и «источник пуст»: это соседний
класс — тихое глотание исключения, — и лечится он на своём слое, отдельным значением «не знаю»
(`None`), а не пустотой. Контракт запрещает лишь одно: выдавать НЕРАЗБОР за пустоту.

Применение (первый переведённый читатель — `rc_auth_detect`):

    import parse_outcome
    r = parse_outcome.reading(seen=292, parsed=0)
    if r.blind:
        log.warning("детектор ослеп: %s", r.say("строк"))
"""

from collections import namedtuple

# Имена исходов — часть контракта: по ним пишут условия потребители, менять нельзя молча.
EMPTY = "empty"          # seen == 0 — разбирать нечего
PARSED = "parsed"        # parsed > 0 — разобрано
NONPARSE = "nonparse"    # seen > 0, parsed == 0 — ТРЕТИЙ исход: отказ читателя
OUTCOMES = (EMPTY, PARSED, NONPARSE)

_Reading = namedtuple("Reading", "seen parsed outcome")


class Reading(_Reading):
    """Пара «осмотрено/разобрано» + исход. Неизменяема, сравнима, печатается числами."""

    __slots__ = ()

    @property
    def blind(self):
        """Читатель слеп: источник непуст, а разобрано ноль."""
        return self.outcome == NONPARSE

    def say(self, unit="единиц"):
        """Фраза для лога/карточки. Числа НАЗЫВАЮТСЯ всегда — по ним отличают слепоту от тишины."""
        if self.outcome == EMPTY:
            return "осмотрено 0 %s — разбирать было нечего" % unit
        if self.outcome == PARSED:
            return "осмотрено %d %s, разобрано %d" % (self.seen, unit, self.parsed)
        return ("НЕРАЗБОР: осмотрено %d %s, разобрано 0 — источник непуст, а читатель не опознал "
                "ни одной единицы; нуль наверху означает ОТКАЗ ЧИТАТЕЛЯ, а не молчание источника"
                % (self.seen, unit))


def outcome(seen, parsed):
    """Исход по паре чисел. → EMPTY | PARSED | NONPARSE."""
    seen, parsed = int(seen), int(parsed)
    if seen < 0 or parsed < 0:
        raise ValueError("осмотрено/разобрано не бывают отрицательными: seen=%d parsed=%d"
                         % (seen, parsed))
    if parsed > seen:
        raise ValueError("разобрано больше, чем осмотрено (seen=%d parsed=%d) — сломан сам "
                         "читатель, а не источник" % (seen, parsed))
    if seen == 0:
        return EMPTY
    if parsed == 0:
        return NONPARSE
    return PARSED


def reading(seen, parsed):
    """Собрать результат читателя по контракту. → Reading(seen, parsed, outcome)."""
    return Reading(int(seen), int(parsed), outcome(seen, parsed))


def is_blind(r):
    """Третий исход у готового Reading (или у пары в кортеже). → bool."""
    if isinstance(r, Reading):
        return r.blind
    seen, parsed = r
    return outcome(seen, parsed) == NONPARSE


def say(seen, parsed, unit="единиц"):
    """Короткий путь: пара чисел → произнесённая вслух фраза."""
    return reading(seen, parsed).say(unit)
