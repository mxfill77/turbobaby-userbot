# -*- coding: utf-8 -*-
"""СЛОВО ВЛАДЕЛЬЦА «урок включи N: причина» — РАЗБОР И ОБРАЗЕЦ В ОДНОМ МЕСТЕ (22.09.2026, 70i).

ЧТО БЫЛО. Форму этого слова знали ЧЕТЫРЕ места, и знали её по памяти автора правки:
разбирал её `pc_agent.LESSON_ON_RE`, а образец «урок включи N: причина словами» печатали
руками `lesson_promote._candidates_card`, `trainer._promote_lesson` и (в виде CLI-строки)
`exam_show.own_take`. Разойтись им было нечем — только молчанием: поправь кто-нибудь глагол
в регулярке, и три образца продолжили бы диктовать владельцу строку, которую разбор уже не
принимает. Цена такого расхождения не «некрасиво», а «владелец сказал ровно то, что ему
написали, и услышал «не разобрал команду»».

ЧТО ЗДЕСЬ. Одно определение формы (`LESSON_ON_RE`) и один строитель образца
(`promote_phrase`), который СВЕРЯЕТ собранную строку тем же разбором, прежде чем её отдать.
Поэтому образец не может пережить правку разбора: он либо собирается и ПРОВЕРЕН, либо
громко отказывает, и молчаливого расхождения не остаётся ни одной ветки.

ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ИМПОРТ `pc_agent`. `pc_agent` тянет `telegram`, `dotenv` и
`load_dotenv` на уровне модуля; звать его из `exam_show` (дверь, которую спавнят на каждый
тап) значило бы затащить в дверь живого бота и чтение конфига ради одной регулярки. Модуль
намеренно на голой стандартной библиотеке: ни одного импорта, кроме `re`.
"""

import re

# ПРИЧИНА ЕДЕТ ДОСЛОВНО, И ПОЭТОМУ РАЗБИРАЕТСЯ ИЗ ОРИГИНАЛА СООБЩЕНИЯ. Роутер темы 205 работает
# на `text` = `msg.text.lower()`, и причина, проехавшая через него, легла бы в таблицу уроков
# строчными буквами навсегда. Разбирающий берёт `msg.text` как есть (`pc_agent`).
LESSON_ON_RE = re.compile(
    r"^(?:урок|lesson)[\s:]+(?:включи(?:ть)?|on)\s+#?(\d+)\s*[:\-—]?\s*(.*)$",
    re.IGNORECASE | re.DOTALL)

# ГЛАГОЛ И СУЩЕСТВИТЕЛЬНОЕ ОБРАЗЦА — ПЕРВЫЕ АЛЬТЕРНАТИВЫ РЕГУЛЯРКИ, а не «похожие слова».
# Регулярка принимает и `lesson on`, и `урок включить`; владельцу диктуется ОДНА форма, иначе
# образец начинает учить разнобою.
PROMOTE_NOUN = "урок"
PROMOTE_VERB = "включи"

# МЕСТО ПРИЧИНЫ В ОБРАЗЦЕ. Причина у перевода ОБЯЗАТЕЛЬНА (`lesson_promote` без неё отказывает),
# поэтому в образце стои́т не «(необязательно)», а прямой вопрос, на который владельцу отвечать.
PROMOTE_REASON_SLOT = "<почему так правильно>"

# Номер в БЕЗНОМЕРНОМ образце (карточка «кандидаты» печатает форму вообще, а не про урок #7).
PROMOTE_NUMBER_SLOT = "N"

# ГДЕ ЭТО СЛОВО СЛЫШАТ — И ЭТО НЕ ТАМ, ГДЕ ВИСИТ КАРТОЧКА ЭКЗАМЕНА (замер 22.09.2026). Живой
# роутер слова ровно один — `pc_agent`, и он слушает ТОЛЬКО тему 205 своего чата (`HQ_THREAD_ID`,
# гейт «только наш чат и только тема 205»); `trainer.promote_lesson` зовёт единственный вызывающий
# — CLI `lesson_promote.py`, то есть словом в чат он не поднимается вовсе. Значит образец, поданный
# без адреса, послал бы владельца говорить слово туда, где его никто не разбирает: ответом под
# карточкой экзамена. Адрес живёт здесь же, где форма, по той же причине, что и форма.
#
# АТОМ — ИМЯ ТЕМЫ, А НЕ ГОТОВАЯ ФРАЗА: адрес попадает в текст в двух падежах («тема «PC-дев» /
# консоль ПК…» у агента, «скажи в теме «PC-дев»» у квитанции), и держать два литерала значило бы
# снова завести два места, знающих один факт.
PROMOTE_TOPIC = "«PC-дев»"
PROMOTE_WHERE = "тема " + PROMOTE_TOPIC

# Число для САМОПРОВЕРКИ безномерного образца: подставляется вместо `N` и обязано разобраться.
# Иначе проверить безномерную форму было бы нечем — `N` числом не является по построению.
_PROBE_NUMBER = 7


class PromoteFormBroken(RuntimeError):
    """Собранный образец НЕ разбирается собственным разбором. Громко, а не молча: молчаливый
    исход здесь — это и есть тот дефект, ради которого модуль заведён."""


def promote_phrase(number=None, why=""):
    """Дословная строка, которой человек включает кандидата. → str (без кавычек).

    `number=None` — безномерная форма («урок включи N: …») для карточек, говорящих о форме
    вообще. `why` — причина, если она уже известна; пусто — место причины остаётся вопросом.

    СОБРАННОЕ СВЕРЯЕТСЯ РАЗБОРОМ ТУТ ЖЕ. Это не перестраховка: без сверки модуль был бы просто
    пятым местом, где форма написана руками, — только теперь ещё и с видом единственного.
    """
    slot = " ".join(str(why or "").split()).strip() or PROMOTE_REASON_SLOT
    shown = PROMOTE_NUMBER_SLOT if number is None else str(int(number))
    phrase = "%s %s %s: %s" % (PROMOTE_NOUN, PROMOTE_VERB, shown, slot)
    probe = phrase if number is not None else "%s %s %d: %s" % (
        PROMOTE_NOUN, PROMOTE_VERB, _PROBE_NUMBER, slot)
    want = _PROBE_NUMBER if number is None else int(number)
    m = LESSON_ON_RE.match(probe)
    if m is None or int(m.group(1)) != want or m.group(2).strip() != slot:
        raise PromoteFormBroken(
            "образец перевода не разбирается собственным разбором: %r" % probe)
    return phrase
