# -*- coding: utf-8 -*-
"""
result_spill.py — обрезка отчёта, которая НАЗЫВАЕТ СЕБЯ, и хвост, который её переживает.
Чистая логика + ОДНА запись на диск: ни сети, ни секретов, ни Telegram, ни очереди.

ЗАЧЕМ (замер 11.08.2026, разбор docs/artifacts/2026-08-11-result-cap-4500-tail-loss.md).
Полный stdout исполнителя жил ТОЛЬКО в памяти демона: `run_claude` возвращает `(rc, out, err)`,
и ни одна ветка не писала `out` на диск. Обрезка стояла двумя голыми срезами `[:RESULT_MAX]`
(выход `_run_task_impl` и клиент моста) — без сравнения длины, без пометки, без следа. По корпусу
466 строк очереди обеих полос в потолок упёрлись 73; на ПК — 45 из 45 МОЛЧА (на сервере 27 из 28
помечены длиной). Длины упёршихся: `{4500: 73}` — ровно потолок, ни одной 4499 или 4501, то есть
4500 это не «такие уж длинные отчёты», а след ножа. У задачи 473 обрыв пришёлся посреди слова, а
вместе с хвостом ушли строка `RESULT:` и любой след верификации.

ЧТО ЗДЕСЬ ЗАКРЕПЛЕНО — ТРИ ПРАВИЛА.

1. ХВОСТ НА ДИСК **ДО** ОБРЕЗКИ. Полный текст → `docs/artifacts/reports/<дата>-<ЧЧММСС>-task<id>.md`,
   в очередь — голова и ссылка. Потолок очереди НЕ поднимаем сознательно: распухшая очередь стоит
   дороже файла, а 15773-символьный отчёт (живой, с серверной полосы) не влез бы и в поднятый.
   Каталог назван явно и живёт рядом с телами журнала (`docs/artifacts/journal/`) — по той же
   причине, по какой заведён тот: витрина отдельно, тела отдельно. Уборки здесь НЕТ: удаление на
   полосе ПК — красная операция, и «кто чистит» решает владелец, а не этот модуль.

2. ОБРЕЗКА НАЗЫВАЕТ СЕБЯ. Сколько символов было, сколько попало, сколько срезано, каким потолком
   и где лежит полное. Формат головы пометки дословно совпадает с серверным
   (`orchestrator_daemon._trunc_note`) НЕ ради красоты: карточки полосы ПК рисует серверный
   `devbot`, и он парсит длину регуляркой `ОБРЕЗАН ДЕМОНОМ: полная длина (\\d+) симв`. Совпадение
   формата = пометка ПК читается уже существующим читателем; расхождение = вторая немая полоса.
   Своё, чего у сервера нет, — ССЫЛКА НА ФАЙЛ: там пометка называет место («ищи в логе»), но текста
   не хранит, и хвост всё равно потерян.

3. ЗАМОК ВЕРИФИКАЦИИ. Запись, у которой блок «FACT» в очередь не попал, проверенной НЕ считается —
   и это решается ПО ТЕКСТУ, а не по памяти исполнителя. Признак — дословно серверный
   (`devbot._FACT_RE`), потому что судит запись именно он. Исходов ТРИ, и третий обязателен:
   блок уцелел → пометки нет; был и срезан → `unverified` с причиной «срезан»; не было вовсе →
   `unverified` с причиной «не было». Слить второй с третьим нельзя: «мы потеряли доказательство»
   и «доказательства не было» — разные диагнозы, и лечатся они разным.
   ЗАМОК ЗАМКА: текст пометки САМ не смеет удовлетворять признаку `FACT` — иначе обрезанная запись
   прочиталась бы сервером как проверенная ровно потому, что мы пожаловались на пропажу. Закреплено
   тестом `test_pometka_sama_ne_schitaetsya_blokom_fact`.

Короткий отчёт (≤ потолка) проходит БАЙТ-В-БАЙТ: ни файла, ни пометки, ни замка — поведение
прежнее. Пометка появляется ровно там, где раньше был молчаливый нож.
"""

import os
import re
import datetime

# Каталог тел отчётов НАЗВАН ЯВНО (в репозитории ПК его не было вовсе — разбор §1).
REPORTS_REL_DIR = "docs/artifacts/reports"
HERE = os.path.dirname(os.path.abspath(__file__))
REPORTS_DIR = os.path.join(HERE, *REPORTS_REL_DIR.split("/"))

# Голова пометки — ДОСЛОВНО серверная: её парсит devbot._TRUNC_FULL_RE.
TRUNC_HEAD = "✂️ РЕЗУЛЬТАТ ОБРЕЗАН ДЕМОНОМ"
UNVERIFIED_MARK = "⚠️ unverified"
# Причины (третий исход обязателен). Ни одна НЕ содержит «FACT:» — см. замок замка в шапке.
CAUSE_CUT = "блок «FACT» в отчёте был, но в очередь не попал (срезан обрезкой)"
CAUSE_ABSENT = "блока «FACT» в отчёте не было вовсе (исполнитель доказательства не дал)"
NO_DUMP_NOTE = "полный текст сохранить НЕ УДАЛОСЬ (диск недоступен) — срезанное восстановить нечем"
RESCUE_MARK = "← спасён из срезанного хвоста"
RESCUE_MAX = 300          # строка итога в пометке: опознать хватает, простыню тащить незачем

# Признак блока верификации — ДОСЛОВНО devbot._FACT_RE (та же полоса судит наши записи).
_FACT_RE = re.compile(r"\bFACT\s*:", re.IGNORECASE)
# Строка итога живёт в КОНЦЕ отчёта и потому срезается первой: разбор §2 намерил, что в 38 случаях
# из 45 демон подтвердил итог по строке, которой в очереди уже нет. Берём ПОСЛЕДНЮЮ.
_RESULT_LINE_RE = re.compile(r"(?m)^[ \t]*RESULT:[ \t]*\S.*$")
# Границы фразы для реза головы — копия `cowork_log_append._CUT_MARKS`. Копия, а не импорт:
# модуль обязан быть самодостаточным (образец `gate_selective._STEP_RE`), а тот писатель тянет
# конфиг с секретами — демону такой импорт ради двух строковых функций не нужен.
_CUT_MARKS = (". ", "! ", "? ", "; ", " — ", " · ", ", ")
_TID_SAFE_RE = re.compile(r"[^0-9A-Za-z_-]+")


def has_fact(text):
    """В тексте есть блок верификации «FACT:»? Признак дословно серверный (devbot._FACT_RE)."""
    return bool(_FACT_RE.search(str(text or "")))


def result_line(text):
    """ПОСЛЕДНЯЯ строка «RESULT: …» отчёта (без хвостовых пробелов) или ''."""
    found = _RESULT_LINE_RE.findall(str(text or ""))
    return found[-1].strip() if found else ""


def cut_head(text, budget):
    """Голова не длиннее budget, обрезанная по границе ФРАЗЫ (иначе — слова).

    Рез посреди слова запрещён: у задачи 473 обрыв пришёлся ровно посреди слова, и читает эту
    строку человек, а не греп. Слишком ранний рез тоже вреден (голова перестаёт быть отчётом),
    поэтому граница принимается только со второй половины бюджета. Логика — копия
    `cowork_log_append._cut_head` (см. про копию выше)."""
    text = str(text or "")
    budget = max(0, int(budget))
    if len(text) <= budget:
        return text
    head = text[:budget]
    floor = budget // 2
    cut = -1
    for mark in _CUT_MARKS:
        i = head.rfind(mark)
        if i >= floor:
            cut = max(cut, i + (1 if mark[0] in ".!?;" else 0))
    if cut < floor:
        cut = head.rfind(" ")
    if cut < floor:
        cut = budget
    return head[:cut].rstrip(" ,;:—·-")


def _safe_tid(tid):
    s = _TID_SAFE_RE.sub("", str(tid if tid is not None else "")) or "noid"
    return s[:32]


def dump_path(reports_dir, now, tid):
    """Свободное имя файла тела: <дата>-<ЧЧММСС>-task<id>[-N].md.

    Имя несёт ID ЗАДАЧИ намеренно: разбор §1 отдельно отмечает, что связи «id → файл» на ПК не
    записано нигде и искать полный вывод приходится по времени. Секунда одна, писателей может быть
    двое (демон + клиент моста) — коллизию разводим суффиксом, а не молча затираем чужое тело."""
    base = "%s-task%s" % (now.strftime("%Y-%m-%d-%H%M%S"), _safe_tid(tid))
    for n in range(1, 100):
        path = os.path.join(reports_dir, "%s%s.md" % (base, "" if n == 1 else "-%d" % n))
        if not os.path.exists(path):
            return path
    return os.path.join(reports_dir, "%s-p%d.md" % (base, os.getpid()))


def dump_text(text, now, tid, cap):
    """Содержимое файла тела: шапка с числами + ИСХОДНЫЙ отчёт целиком, с переносами.
    Схлопнутая в строку простыня нечитаема, а сохранить формат стоит ноль."""
    body = str(text or "")
    return ("# Полный отчёт задачи %s — %s UTC\n\n"
            "Сохранён АВТОМАТИЧЕСКИ демоном `pc_orchestrator.py` **до** обрезки под потолок очереди:\n"
            "отчёт был **%d символов** при потолке **%d**. В очередь ушли голова, пометка обрезки\n"
            "и ссылка на этот файл (очередь — витрина, а не хранилище тел).\n\n"
            "| поле | значение |\n|---|---|\n"
            "| задача | %s |\n| записано | %s |\n| символов в отчёте | %d |\n"
            "| потолок очереди | %d |\n| блок «FACT» в отчёте | %s |\n\n---\n\n%s\n"
            % (tid, now.strftime("%Y-%m-%d %H:%M"), len(body), cap,
               tid, now.strftime("%Y-%m-%d %H:%M:%S"), len(body), cap,
               "есть" if has_fact(body) else "НЕТ", body))


def save_full(text, tid, cap, now=None, reports_dir=None):
    """Полный отчёт → файл ДО обрезки. → путь относительно репо | None (не записалось).

    FAIL-SAFE: сбой записи НЕ отменяет обрезку (потолок очереди жёсткий) и НЕ прячется — пометка
    в этом случае честно говорит, что тела нет. Молчаливой потерей защита от потери быть не может."""
    now = now or datetime.datetime.now(datetime.timezone.utc)
    d = reports_dir or REPORTS_DIR
    try:
        os.makedirs(d, exist_ok=True)
        path = dump_path(d, now, tid)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(dump_text(text, now, tid, cap))
        return REPORTS_REL_DIR + "/" + os.path.basename(path)
    except Exception:
        return None


def _rescued(text, head):
    """Строка итога, если она осталась в срезанном хвосте. Уцелела в голове → '' (не дублируем)."""
    line = result_line(text)
    if not line or line in head:
        return ""
    if len(line) > RESCUE_MAX:
        line = line[:RESCUE_MAX].rstrip() + "…"
    return "\n" + line + "  " + RESCUE_MARK


def _cause(full, landed):
    """Причина пометки unverified — или '' (блок уцелел). Три исхода, см. шапку."""
    if has_fact(landed):
        return ""
    return CAUSE_CUT if has_fact(full) else CAUSE_ABSENT


def note(full_len, kept, cap, rel, rescued="", cause=""):
    """Хвостовая пометка обрезки: числа, адрес тела, спасённый итог, замок верификации."""
    s = ("\n\n%s: полная длина %d симв., в очередь попало %d — срезано %d симв. "
         "(потолок RESULT_MAX=%d). " % (TRUNC_HEAD, full_len, kept, full_len - kept, cap))
    s += ("Полный текст: " + rel) if rel else NO_DUMP_NOTE
    s += rescued
    if cause:
        s += "\n%s: %s — запись проверенной НЕ считается." % (UNVERIFIED_MARK, cause)
    return s


def cap_result(text, tid=None, cap=4500, now=None, reports_dir=None, save=True):
    """Отчёт → (текст для очереди ≤ cap, путь тела | None).

    Короче потолка → возвращаем БАЙТ-В-БАЙТ: ни файла, ни пометки (поведение прежнее).
    Длиннее → тело на диск, голова по границе фразы + пометка, которая называет числа, адрес и
    состояние верификации. Итог гарантированно ≤ cap: голова ужимается, пока пометка со своими
    числами не поместится (числа сами меняют её длину — потому цикл, а не одно вычитание).
    Сходимость: голова только УКОРАЧИВАЕТСЯ, а пометка от укорочения может лишь подрасти на
    причину unverified (блок «FACT» из головы не появляется) — колебания невозможны."""
    s = "" if text is None else str(text)
    n = len(s)
    if n <= cap:
        return s, None
    rel = save_full(s, tid, cap, now=now, reports_dir=reports_dir) if save else None
    budget, head, tail = cap, "", ""
    for _ in range(8):
        head = cut_head(s, budget)
        rescued = _rescued(s, head)
        tail = note(n, len(head), cap, rel, rescued, _cause(s, head + rescued))
        if len(head) + len(tail) <= cap:
            break
        budget = max(1, cap - len(tail))
    if len(head) + len(tail) > cap:      # предохранитель: пометка важнее лишних символов головы
        head = head[:max(0, cap - len(tail))]
    return head + tail, rel
