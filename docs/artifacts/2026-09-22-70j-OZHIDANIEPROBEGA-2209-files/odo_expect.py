"""Ожидание «пробег получен» — чистая функция «факты → вердикт».

АВТОРСТВО, НЕ ВЫКЛАДКА. Модуль написан на полосе ПК заходом 70j (22.09.2026) для
репозитория `/root/turbobaby-manager-bot`. В живой процесс он НЕ доставлен ни одной
строкой; доставка — отдельное задание. Поэтому здесь нет ни одного импорта из
`splinter`/`park_verdict`/`bridge_client`: модуль обязан считаться и краснеть на
полосе ПК, где живого дерева нет.

ЧТО ЭТО. Просьба бота о пробеге сегодня уходит и умирает молча: записи «имя, время,
предмет, адресат» нет ни в одном из четырёх мест (замер 69w, 21.09.2026). Этот модуль
заводит такую запись и судит её ПО ИСТОЧНИКУ, а не по факту отправки просьбы и не по
ответу механика в чате.

КОНТРАКТ НАБЛЮДЕНИЯ, четыре части:

1. РЕЗУЛЬТАТ. У байка появилось показание ЕГО СОБСТВЕННОГО одометра, записанное ПОЗЖЕ
   момента просьбы.
2. ИСТОЧНИК ИСТИНЫ. Bot Data, лист «обслуживание», строка байка: поле `current_km`
   (> 0) и её `updated_at`. Единственный писатель — `_odo_store`
   (`splinter.py:2913` → `:2929` `service_upsert(..., current_km=km_int)`); четыре
   двери, которыми человек туда попадает, названы в артефакте 69u п.5. Чтение обратно —
   `_odo_own_freshest` (`splinter.py:2324`), оно же ветка 1 `_odo_current_src`
   (`splinter.py:2429`), которая называет источник словом `park_verdict.SRC_OWN`.
3. СПОСОБ. Судится СОДЕРЖИМОЕ источника на момент проверки: пара (слово-источник,
   время записи). Ни отправка просьбы, ни текст ответа механика вердикта не меняют —
   у `verdict()` для них нет ни одного входа.
4. ОТРИЦАТЕЛЬНЫЙ ТЕСТ. Механик написал число в чат, а в источник не легло — вердикт
   ОБЯЗАН остаться «ждём». Живой случай: 21.09 VULCAN 650 S 5065, тема 81 — шесть
   просьб за 91 минуту, ноль записей (69w п.2).

СРОКА НЕТ, И ЭТО СКАЗАНО ВСЛУХ, А НЕ СПРЯТАНО ЗА КРУГЛЫМ ЧИСЛОМ.
Срок обязан сверяться с замеренной длительностью того, что он терпит — со временем от
просьбы до появления измеренного одометра. Таких пар в единственном измеренном окне
(7 суток, 14.09–21.09) ровно **0**: просьб 8, приходов 0 (69w п.2). Ноль промежутков —
это меньше сотни, поэтому `SROK_S = None`, исхода «просрочено» в словаре нет вовсе, и
прибор показывает ВОЗРАСТ, а не приговор. Взводится срок ровно одним замером, названным
в `SROK_CHEM_ZAMERIT`.

ТРЕТИЙ ИСХОД ОБЯЗАТЕЛЕН. «Проверить невозможно» → `НЕИЗВЕСТНО` с причиной. Ни одна
ветка не превращает «не смог проверить» в «получен» или в «в порядке».

НАРУЖУ НЕ УХОДИТ НИЧЕГО. В модуле нет ни сети, ни моста, ни Telegram, ни записи на
диск: `verdict()` принимает уже снятые факты и возвращает словарь. Боевой вызов от
проверки отличается тем, что факты подаёт живой `_odo_current_src`, а в тестах —
литерал; сам модуль их не добывает.
"""

# --- СЛОВАРЬ ИСТОЧНИКА -------------------------------------------------------
# Слова ГОТОВЫЕ, они уже живут в `park_verdict.py:70-73` (заход 68u). Здесь они
# продублированы литералами только потому, что выкладки нет и импортировать неоткуда;
# при доставке эти три строки заменяются на `from park_verdict import SRC_*`, а тест
# `test_src_words_are_park_verdict_vocabulary` сверяет их дословно.
SRC_OWN = "свой одометр"
SRC_SUB = "подстановка максимума регистров"
SRC_UNKNOWN = "неизвестно"
SRC_WORDS = (SRC_OWN, SRC_SUB, SRC_UNKNOWN)

# --- СЛОВАРЬ ИСХОДОВ ---------------------------------------------------------
# Ровно три. Слова «просрочено» / «в порядке» / «ok» здесь НЕТ и быть не может, пока
# не замерен срок: см. `SROK_S`.
OUT_POLUCHEN = "получен"
OUT_ZHDYOM = "ждём"
OUT_NEIZVESTNO = "неизвестно"
OUTCOMES = (OUT_POLUCHEN, OUT_ZHDYOM, OUT_NEIZVESTNO)

# --- СРОК --------------------------------------------------------------------
SROK_S = None  # НЕ ЗАМЕРЕН. Пар «просьба → измеренный одометр» в корпусе: 0 из 8 просьб.
SROK_ZAMER_PAR = 0
SROK_ZAMER_OKNO = "14.09.2026 07:30 → 21.09.2026 07:22 UTC (69w)"
SROK_CHEM_ZAMERIT = (
    "пары (время просьбы, время ближайшей следующей записи `_odo_store` по тому же "
    "байку) по `splinter.log` за окно, где таких пар не меньше ста; до тех пор прибор "
    "идёт без отказа"
)

# --- ИМЯ ОЖИДАНИЯ ------------------------------------------------------------
NAME = "пробег байка"

# Вид просьбы — чем именно бот попросил. Слова взяты из замера 69w п.2, не выдуманы.
ASK_KINDS = ("пол ответа", "подсказка I", "партия одометра")


def _parse_utc(s):
    """ISO-8601 UTC → (год, месяц, день, час, минута, секунда) в секундах эпохи.

    Возвращает `None` на всём, что не разбирается: пустом, кривом, None. Ни одна
    ветка не подставляет «сейчас» вместо неразобранного времени — подстановка тут
    превратила бы «не знаю когда» в «только что», то есть в ложный зелёный.
    """
    if not isinstance(s, str) or not s.strip():
        return None
    import datetime
    t = s.strip().replace("Z", "+00:00")
    try:
        d = datetime.datetime.fromisoformat(t)
    except ValueError:
        return None
    if d.tzinfo is None:
        d = d.replace(tzinfo=datetime.timezone.utc)
    return d.timestamp()


def key(chat_id, topic_id, bike):
    """Ключ ожидания. ВРЕМЕНИ В НЁМ НЕТ — это и есть идемпотентность.

    Замок: шесть повторов одной просьбы по одному байку (живой случай 21.09, тема 81)
    обязаны дать ОДНО ожидание, а не шесть. Положи в ключ время — и поток одинаковых
    записей вернётся ровно в том размере, в каком он сегодня идёт в чат.
    """
    return ("одометр", chat_id, topic_id, (bike or "").strip())


def open_expect(chat_id, topic_id, bike, asked_at_utc, ask_kind, addressee=None):
    """Заводит запись ожидания. Чистая: ничего не пишет и никуда не ходит."""
    return {
        "name": NAME,
        "key": key(chat_id, topic_id, bike),
        "predmet": (bike or "").strip(),
        "chat_id": chat_id,
        "topic_id": topic_id,
        # адресат назван МЕСТОМ, а не человеком: имени механика у бота нет
        "addressee": addressee or "группа обслуживания, тема байка",
        "ask_kind": ask_kind,
        "asked_at_utc": asked_at_utc,
        "first_asked_at_utc": asked_at_utc,
        "repeats": 1,
        "srok_s": SROK_S,
    }


def merge_repeat(exp, asked_at_utc):
    """Повтор просьбы. ВОЗРАСТ СЧИТАЕТСЯ ОТ ПЕРВОЙ ПРОСЬБЫ, а не от последней.

    Замок: если повтор двигает точку отсчёта, то шесть просьб за 91 минуту дают
    возраст последнего интервала (3.7 мин) вместо 91 — и висящая полтора часа просьба
    выглядит свежей. Повтор увеличивает счётчик и сдвигает `asked_at_utc` (последняя
    просьба), но `first_asked_at_utc` не трогает ничем.
    """
    out = dict(exp)
    out["repeats"] = int(exp.get("repeats") or 0) + 1
    out["asked_at_utc"] = asked_at_utc
    out.setdefault("first_asked_at_utc", exp.get("asked_at_utc"))
    return out


def _neizv(why, age_s=None):
    return {"outcome": OUT_NEIZVESTNO, "why": why, "age_s": age_s,
            "delay_s": None, "srok_s": SROK_S}


def verdict(exp, now_utc, fact):
    """Вердикт по СОДЕРЖИМОМУ источника. Три исхода, четвёртого нет.

    `fact` — уже снятый срез источника, форма зеркалит живой `_odo_current_src`
    плюс время строки:
        {"ok": bool, "why": str, "src": <слово из SRC_WORDS>,
         "km": str, "updated_at_utc": "…Z"}
    `ok=False` означает «источник не прочитан» (мост молчит, лист не отдался) — и это
    НЕ «пробег не пришёл», а третий исход.
    """
    if not isinstance(exp, dict):
        return _neizv("ожидания нет — судить нечего")

    t_ask = _parse_utc(exp.get("first_asked_at_utc") or exp.get("asked_at_utc"))
    t_now = _parse_utc(now_utc)
    age = None if (t_ask is None or t_now is None) else (t_now - t_ask)

    if not isinstance(fact, dict) or not fact.get("ok"):
        why = (fact or {}).get("why") if isinstance(fact, dict) else None
        return _neizv("источник не прочитан: " + (why or "причина не названа"), age)
    if t_ask is None:
        return _neizv("у просьбы нет времени — сравнивать не с чем", None)
    if t_now is None:
        return _neizv("часов нет — возраст не берётся", None)

    src = fact.get("src")
    if src not in SRC_WORDS:
        # Умолчание ЗАКРЫТОЕ: не названный источник — это неизвестность, а не «получен».
        return _neizv("происхождение пробега не названо", age)
    if src != SRC_OWN:
        # Подстановка max(I/J/K/L) — честное число, но это одометр на момент ЗАМЕНЫ.
        # Она стои́т у 29 байков из 38 и поднималась бы БЕЗ всякого события.
        return {"outcome": OUT_ZHDYOM, "why": "в источнике не измерение: " + src,
                "age_s": age, "delay_s": None, "srok_s": SROK_S}

    t_upd = _parse_utc(fact.get("updated_at_utc"))
    if t_upd is None:
        # Свой одометр есть, а когда записан — неизвестно. Сказать «получен» здесь
        # значило бы засчитать штамп, лежащий с 12.09, за ответ на сегодняшнюю просьбу.
        return _neizv("у измерения нет времени — с просьбой не сравнить", age)
    if t_upd <= t_ask:
        return {"outcome": OUT_ZHDYOM,
                "why": "измерение старше просьбы на %.0f с — оно было до неё" % (t_ask - t_upd),
                "age_s": age, "delay_s": None, "srok_s": SROK_S}

    return {"outcome": OUT_POLUCHEN, "why": "измерение записано после просьбы",
            "age_s": age, "delay_s": t_upd - t_ask, "srok_s": SROK_S,
            "km": fact.get("km")}
