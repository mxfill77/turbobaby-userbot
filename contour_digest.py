# ═════════════════════════ ВРЕМЯ И ПРЕДЕЛЫ ═══════════════════════════════════

def source(name):
    """Паспорт источника: адрес · предел · почему предел такой. → dict (копия)."""
    got = SOURCES.get(name)
    return dict(got) if isinstance(got, dict) else {"addr": "", "limit": None, "why": ""}


def limit_of(name):
    """Предел свежести источника в секундах, `None` — источник возраста не имеет."""
    return source(name).get("limit")


def stale(read_at, now, limit):
    """Слепок старше предела? → True / False / None («сказать нечем»).

    `None` — ТРЕТИЙ ИСХОД, и он ведёт в «неизвестно», а не в «свежо»: отсутствие
    метки замера доказывает только отсутствие метки.
    """
    if limit is None:
        return False
    if read_at is None or now is None:
        return None
    try:
        return (float(now) - float(read_at)) > float(limit)
    except (TypeError, ValueError):
        return None


def age_words(read_at, now):
    """Возраст замера словами. Нет чем мерить — так и сказано."""
    if read_at is None or now is None:
        return "возраст неизвестен"
    try:
        sec = max(0.0, float(now) - float(read_at))
    except (TypeError, ValueError):
        return "возраст неизвестен"
    if sec < 90:
        return "%d с назад" % int(sec)
    if sec < 5400:
        return "%d мин назад" % int(round(sec / 60.0))
    return "%.1f ч назад" % (sec / 3600.0)


def interval_words(sec=INTERVAL_SEC):
    """Интервал ЧИСЛОМ и словами разом: читающий обязан видеть окно сводки."""
    try:
        val = float(sec)
    except (TypeError, ValueError):
        return "интервал не назван"
    if val >= 3600 and abs(val / 3600.0 - round(val / 3600.0)) < 1e-9:
        return "%d ч = %d с" % (int(round(val / 3600.0)), int(val))
    return "%d мин = %d с" % (int(round(val / 60.0)), int(val))


def one_line(value, limit=GOAL_MAX):
    """Текст в одну строку сообщения. Переносы — в пробел, хвост — в многоточие."""
    text = " ".join(str(value or "").split())
    if len(text) <= limit:
        return text
    return text[: max(1, limit - 1)].rstrip() + "…"


