def read_only_marks():
    """Метки корней, которые контур ставит СЕБЕ ради чтения. ВЫВОДЯТСЯ, не набраны.

    Расхождение двух экземпляров одной метки молчаливо (класс полосы), поэтому
    источник метки ровно один — модуль, который её ставит.
    """
    return (review_intake.CLAIM_MARK, recon_auto.TASK_MARK, recon_auto.ASK_MARK)


def changes_state(root_text):
    """Строка меняла операционное состояние? → bool.

    Признак — МАШИННАЯ МЕТКА КОРНЯ, а не смысл текста. Граница названа в шапке:
    рабочая строка без метки считается изменившей состояние.
    """
    text = str(root_text or "")
    return not any(text.startswith(m) for m in read_only_marks())


def is_clean(outcome):
    """Чистая цепочка = сданная. НЕ СВЕРЕННЫЙ исход — обрыв, как и «упало»."""
    return outcome == "done"


def series(rows, target=SERIES_TARGET):
    """Счёт серии по закрытым строкам очереди. → dict.

    `rows` — уже отсортированные ПО ВРЕМЕНИ ЗАКРЫТИЯ (старые впереди) записи
    вида ``{"id":…, "at":…, "outcome":…, "goal":…}``. Служебные корни отсеиваются
    признаком счётчика :mod:`series_pc`, а не своим.

    Серия считается С ХВОСТА: сколько последних подряд чистых. Это ровно то, что
    спрашивает критерий фазы, — «подряд прямо сейчас», а не «всего чистых».
    """
    taken, service = [], 0
    for row in (rows or []):
        goal = (row or {}).get("goal")
        if series_pc.is_service(goal):
            service += 1
            continue
        taken.append(row)
    window = taken[-int(target):] if target else taken
    streak, moved = 0, 0
    for row in reversed(window):
        if not is_clean(row.get("outcome")):
            break
        streak += 1
        if changes_state(row.get("goal")):
            moved += 1
    return {"target": int(target), "streak": streak, "moved": moved,
            "window": len(window), "service": service, "seen": len(taken)}


def series_line(counted, rd=None):
    """Строка серии — ОТДЕЛЬНАЯ и всегда одна. → str.

    Источник умер → та же строка говорит «неизвестно»: число серии, пропавшее
    молча, читается как ноль, а ноль — это утверждение.
    """
    if rd is not None and rd.get("kind") in (UNKNOWN, HYPO):
        return line_text(rd)
    got = counted or {}
    words = ("%d чистых подряд из %d · из них меняли операционное состояние %d "
             "· цепочек в окне %d · служебных мимо счёта %d"
             % (got.get("streak", 0), got.get("target", SERIES_TARGET), got.get("moved", 0),
                got.get("window", 0), got.get("service", 0)))
    if rd is None:
        return "• %s" % words
    shown = dict(rd)
    shown["words"] = words
    return line_text(shown)


