def read_only_marks():
    """Метки корней, которые контур ставит СЕБЕ ради чтения. ВЫВОДЯТСЯ, не набраны.

    Расхождение двух экземпляров одной метки молчаливо (класс полосы), поэтому
    источник метки ровно один — модуль, который её ставит.
    """
    return (review_intake.CLAIM_MARK, recon_auto.TASK_MARK, recon_auto.ASK_MARK)


def changes_state(root_text):
    """Строка меняла операционное состояние? → bool.

    Признак — МАШИННАЯ МЕТКА КОРНЯ, а не смысл текста. Граница названа в шапке:
    рабочая строка без метки считается изменившей состояние.
    """
    text = str(root_text or "")
    return not any(text.startswith(m) for m in read_only_marks())


def is_closed_done(outcome):
    """Строка СДАНА (исход очереди `done`)? НЕ СВЕРЕННЫЙ исход — обрыв, как и «упало».

    Сданность — это ещё НЕ чистота: чистой цепочку делает вердикт судьи
    (:func:`is_clean`). Разведены они намеренно — ровно на этом склеивании и стоял
    класс 02.09 (шапка, §«DONE ЧИСТОЙ НЕ ДЕЛАЕТ»).
    """
    return outcome == "done"


def judged_of(tid, judged=None):
    """Что судья закрытия сказал об этой строке. → одно из четырёх слов раздела шапки.

    ``judged`` — реестр вердиктов (:func:`done_judge_pc.read_ledger`), поданный
    руками. ``None`` и ``{}`` — ОДИН ответ: «судья не судил», и он не чистый.
    Имена полей — зеркало литералов судьи, равенство сторожит тест.
    """
    rows = judged if isinstance(judged, dict) else {}
    one = rows.get(str(tid))
    if not isinstance(one, dict):
        return JUDGE_SILENT
    if one.get(F_PROVED) is True:
        return JUDGE_PROVED
    if not one.get(F_ADDRESSED):
        return JUDGE_BLIND
    return JUDGE_UNPROVED


def is_unknown(row):
    """Цепочка вышла НЕИЗВЕСТНОЙ — судья не смог прочитать её продукт? → bool.

    Спрашивается у ИСХОДА РЯДА, а не у реестра вердиктов: слепок очереди уже
    отделил этот исход маркером судьи (:func:`queue_snapshot_pc.outcome_of`), и
    второе мнение о том же вопросе разошлось бы с первым молча.

    ГРАНИЦА НАЗВАНА, А НЕ ПОДРАЗУМЕВАЕТСЯ: «судья не смог прочитать» — это НЕ
    «адрес не назван». Второе остаётся своим словом (:data:`JUDGE_BLIND`), в
    знаменателе и в обрывах. Там споткнулся не судья — там задача не сказала, чем
    себя проверять, и прятать это из счёта значило бы открыть дыру ровно того
    класса, от которого сторожит :data:`UNKNOWN_ALARM_NUM`.
    """
    return isinstance(row, dict) and row.get("outcome") == OUT_UNKNOWN


def is_clean(row, judged=None):
    """ЧИСТАЯ цепочка = СДАНА и ДОКАЗАНА судьёй. → bool.

    Оба условия обязательны. Одного `done` не хватает: в режиме `addr` безадресное
    закрытие остаётся `done`, и счёт по одному исходу зачитывал бы работу, которую
    никто не проверял.
    """
    one = row or {}
    return (is_closed_done(one.get("outcome"))
            and judged_of(one.get("id"), judged) == JUDGE_PROVED)


def series(rows, target=SERIES_TARGET, judged=None):
    """Счёт серии по закрытым строкам очереди. → dict.

    `rows` — уже отсортированные ПО ВРЕМЕНИ ЗАКРЫТИЯ (старые впереди) записи
    вида ``{"id":…, "at":…, "outcome":…, "goal":…}``. Служебные корни отсеиваются
    признаком счётчика :mod:`series_pc`, а не своим.

    Серия считается С ХВОСТА: сколько последних подряд чистых. Это ровно то, что
    спрашивает критерий фазы, — «подряд прямо сейчас», а не «всего чистых».

    Разбор закрытий окна едет ОТДЕЛЬНЫМИ ЧИСЛАМИ (`proved`/`blind`/`unproved`/
    `unjudged`), и сумма их равна числу сданных строк окна. Без него владелец
    читал бы одну цифру серии, не видя, на чём она стои́т, — а именно это и
    позволило числу врать до 02.09.

    ═══ НЕИЗВЕСТНОСТЬ НЕ ЗАСЧИТЫВАЕТ И НЕ РВЁТ (11.09.2026) ═════════════════

    Решение Штаба, п. 2. Цепочка, у которой судья НЕ СМОГ ПРОЧИТАТЬ продукт, из
    ЗНАМЕНАТЕЛЯ выходит (`denom` = окно минус неизвестные) и серию не обрывает —
    обход хвоста её ПРОПУСКАЕТ, а не останавливается на ней. Довод прямой: цепочка
    осуждена не за работу, а за то, что прибор её не прочитал, и записывать это в
    провал полосы значило бы мерить судью работой.

    ЗАМОК ОТ ДЫРЫ СТОИ́Т ТУТ ЖЕ, и он громкий: `unknown` печатается ВСЕГДА, а доля
    выше :data:`UNKNOWN_ALARM_NUM`/:data:`UNKNOWN_ALARM_DEN` от окна — тревога.
    Без него «неизвестно» стало бы способом не считаться ни в одном числе.
    """
    taken, service = [], 0
    for row in (rows or []):
        goal = (row or {}).get("goal")
        if series_pc.is_service(goal):
            service += 1
            continue
        taken.append(row)
    window = taken[-int(target):] if target else taken
    tally = {JUDGE_PROVED: 0, JUDGE_BLIND: 0, JUDGE_UNPROVED: 0, JUDGE_SILENT: 0}
    unknown = 0
    for row in window:
        if is_unknown(row):
            unknown += 1
            continue
        if is_closed_done((row or {}).get("outcome")):
            tally[judged_of((row or {}).get("id"), judged)] += 1
    streak, moved = 0, 0
    for row in reversed(window):
        if is_unknown(row):
            continue                      # не засчитывает и не рвёт — просто не участвует
        if not is_clean(row, judged):
            break
        streak += 1
        if changes_state(row.get("goal")):
            moved += 1
    return {"target": int(target), "streak": streak, "moved": moved,
            "window": len(window), "service": service, "seen": len(taken),
            "unknown": unknown, "denom": len(window) - unknown,
            "alarm": unknown * UNKNOWN_ALARM_DEN > len(window) * UNKNOWN_ALARM_NUM,
            "proved": tally[JUDGE_PROVED], "blind": tally[JUDGE_BLIND],
            "unproved": tally[JUDGE_UNPROVED], "unjudged": tally[JUDGE_SILENT]}


def shtab_taken(rows, day):
    """Задания Штаба, взятые полосой за названные сутки. → int | None.

    ``rows`` — строки слепка очереди (открытые + закрытые), у каждой поле
    ``goal``: первая значащая строка ``task_text``, обрезанная по 90 символов
    (:func:`queue_snapshot_pc.goal_line`). Маркер ящика стои́т ПЕРВОЙ строкой и в
    90 символов помещается целиком — иначе счёт молча поехал бы вниз.

    Счёт ведёт САМ ЯЩИК (:func:`shtab_box.taken_today`), а не своя регулярка: у
    замка полосы и у сводки обязан быть ОДИН источник числа. Разойдись они — и
    владелец читал бы в сводке одно, а полоса держала бы другое, причём молча.

    ``None`` — слепок не прочитан. Ноль вместо незнания не ставится: «взято 0»
    читается как «Штаб ничего не клал», а это утверждение, которого при мёртвом
    источнике мы делать не вправе (закон 3).
    """
    if rows is None:
        return None
    return shtab_box.taken_today([{"task_text": (r or {}).get("goal")} for r in rows], day)


def shtab_line(taken, day, rd=None):
    """Отдельный счёт «задач от Штаба взято N» — ОТДЕЛЬНОЙ строкой и всегда одной.

    Отдельной, потому что ящик — НОВЫЙ путь задачи на полосу: до него всё, что
    исполнялось, присылал человек. Число, растворённое в общем счёте закрытого,
    отвечало бы на вопрос «сколько работала полоса», а спрошено другое — «сколько
    она взяла себе САМА, минуя владельца». Источник умер → строка говорит
    «неизвестно» и не пропадает.
    """
    if rd is not None and rd.get("kind") in (UNKNOWN, HYPO):
        return line_text(rd)
    ok = taken is not None
    words = shtab_box.digest_line(taken or 0, day, ok=ok,
                                  why="слепок очереди не прочитан")
    if rd is None:
        return "• %s" % words
    shown = dict(rd)
    shown["words"] = words
    return line_text(shown)


def unknown_words(counted):
    """ЧИСЛО НЕИЗВЕСТНЫХ — вслух и всегда, тревога — теми же словами, что красное.

    ВСЕГДА, в том числе нулём: исход, спрятанный при нуле, читается как «такого не
    бывает», а именно так «неизвестно» и жило до 11.09 — его не было видно нигде.

    ТРЕВОГА ЗВУЧИТ ПРО СУДЬЮ, А НЕ ПРО РАБОТУ, и это не оформление: доля выше
    пятой части означает, что прибор перестал читать продукт, а не что полоса
    перестала его делать. Читающий, который спутает эти две новости, пойдёт чинить
    не то. Слово :data:`MARK` берётся у красного — тревоге положено звучать так же
    громко, как звучит красное, и другим шрифтом её звучать нельзя.
    """
    got = counted if isinstance(counted, dict) else {}
    unknown, window = got.get("unknown", 0), got.get("window", 0)
    words = "НЕИЗВЕСТНО %d из %d" % (unknown, window)
    if not got.get("alarm"):
        return words
    return ("%s: %s — доля выше %d/%d, и это ТРЕВОГА ПРО СУДЬЮ, а не про работу "
            "(продукт не прочитан, а не не сделан)"
            % (MARK[RED], words, UNKNOWN_ALARM_NUM, UNKNOWN_ALARM_DEN))


def series_line(counted, rd=None):
    """Строка серии — ОТДЕЛЬНАЯ и всегда одна. → str.

    Источник умер → та же строка говорит «неизвестно»: число серии, пропавшее
    молча, читается как ноль, а ноль — это утверждение.

    РАЗБОР ЗАКРЫТИЙ ЕДЕТ В САМОЙ СТРОКЕ, а не остаётся в коде: владелец обязан
    видеть, СКОЛЬКО цепочек окна судья доказал и сколько закрылись без адреса, не
    открывая ни одного файла. Числа печатаются ВСЕ ЧЕТЫРЕ и в том числе нулём —
    исход, спрятанный при нуле, читается как «такого не бывает».
    """
    if rd is not None and rd.get("kind") in (UNKNOWN, HYPO):
        return line_text(rd)
    got = counted or {}
    words = ("%d чистых подряд из %d · судья доказал %d · закрыто без адреса %d "
             "· не доказано %d · судья не судил %d · из них меняли операционное состояние %d "
             "· цепочек в окне %d (в знаменателе %d) · %s · служебных мимо счёта %d"
             % (got.get("streak", 0), got.get("target", SERIES_TARGET),
                got.get("proved", 0), got.get("blind", 0), got.get("unproved", 0),
                got.get("unjudged", 0), got.get("moved", 0),
                got.get("window", 0), got.get("denom", got.get("window", 0)),
                unknown_words(got), got.get("service", 0)))
    if rd is None:
        return "• %s" % words
    shown = dict(rd)
    shown["words"] = words
    return line_text(shown)


