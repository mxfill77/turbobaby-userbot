def is_calm(report):
    """Спокойно? = ни красного, ни неизвестного, ни ждущего решения.

    Гипотеза спокойствия НЕ ломает: она честно названа гипотезой и новостью не
    является. Неизвестное ломает — «проверить не смог» это не «всё хорошо».
    """
    for key in TOPIC_KEYS:
        for rd in (report.get("readings") or {}).get(key, []):
            if rd.get("kind") in (RED, WAIT, UNKNOWN):
                return False
    return True


def calm_line(report):
    """Спокойствие — ОДНОЙ строкой (закон 4), с числом закрытого за окно."""
    closed = report.get("closed_count")
    tail = ("за окно закрылось %d" % closed) if isinstance(closed, int) else "закрытых не сверить"
    return "СПОКОЙНО: красного нет, решения владельца не ждёт ничего, %s." % tail


def sources_line():
    """Пределы всех источников одной строкой: читающий видит, чем мы судим возраст."""
    parts = []
    for name in ("queue", "expect", "outbox"):
        paper = source(name)
        parts.append("%s %d мин" % (paper["addr"], int(round(float(paper["limit"]) / 60.0))))
    return "ПРЕДЕЛЫ СЛЕПКОВ: " + " · ".join(parts)


def render(report):
    """Готовое сообщение. → str.

    Разделы строятся обходом :data:`TOPICS`: тема без строк — падение теста, а не
    тихий пропуск. Серия печатается ВСЕГДА и отдельной строкой, даже в спокойной
    сводке: её просили числом, а не признаком новости.
    """
    readings = report.get("readings") or {}
    out = [HEAD,
           "интервал %s · окно %s → %s · собрано %s"
           % (interval_words(report.get("interval", INTERVAL_SEC)),
              report.get("since_words") or "начало не названо",
              report.get("now_words") or "?", report.get("now_words") or "?")]
    calm = is_calm(report)
    if calm:
        out += ["", calm_line(report)]
    else:
        for key, title in TOPICS:
            if key == "series":
                continue
            rows = list(readings.get(key) or [])
            if not rows:
                raise AssertionError("тема %r осталась без строки — закон 3 нарушен" % key)
            out += ["", "%s:" % title]
            for rd in rows[:LIST_MAX]:
                out.append(line_text(rd))
            if len(rows) > LIST_MAX:
                out.append("• …и ещё %d — по адресам выше" % (len(rows) - LIST_MAX))
    out += ["", "СЕРИЯ ЦЕПОЧЕК: %s"
            % series_line(report.get("series"), (readings.get("series") or [None])[0]).lstrip("• ")]
    out += ["", sources_line(), FOOT]
    return "\n".join(out)


def journal_line(report):
    """Строка-индекс в журнал: итог, а не пересказ (журнал — индекс, не хранилище)."""
    counted = report.get("series") or {}
    reds = sum(1 for k in TOPIC_KEYS
               for rd in (report.get("readings") or {}).get(k, []) if rd.get("kind") == RED)
    unk = sum(1 for k in TOPIC_KEYS
              for rd in (report.get("readings") or {}).get(k, []) if rd.get("kind") == UNKNOWN)
    waits = sum(1 for k in TOPIC_KEYS
                for rd in (report.get("readings") or {}).get(k, []) if rd.get("kind") == WAIT)
    return ("NOTE СВОДКА КОНТУРА · ПК · интервал %s: закрылось %s · красного %d · неизвестного %d "
            "· ждёт решения %d · серия %d/%d (меняли состояние %d) · %s"
            % (interval_words(report.get("interval", INTERVAL_SEC)),
               report.get("closed_count") if isinstance(report.get("closed_count"), int) else "?",
               reds, unk, waits, counted.get("streak", 0), counted.get("target", SERIES_TARGET),
               counted.get("moved", 0),
               ("отправлено" if report.get("sent") else "не отправлено: %s"
                % one_line(report.get("send_why") or "причина не названа", 90))))
