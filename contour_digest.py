def reading(topic, words, src=None, read_at=None, now=None, kind=OK, why=""):
    """Одна строка сводки с УЖЕ РАЗРЕШЁННЫМ исходом. → dict.

    Разрешение исхода живёт здесь, а не у зовущего, потому что законы 1 и 2 —
    свойство ПОКАЗА, а не свойство конкретного источника. Порядок строгий:

      нет адреса источника  → ГИПОТЕЗА (закон 1) — что бы ни просил зовущий;
      нет метки замера      → НЕИЗВЕСТНО;
      слепок старше предела → НЕИЗВЕСТНО (закон 2), и предел назван числом;
      иначе                 → исход, названный зовущим.

    Гипотеза сильнее просьбы намеренно: строка без адреса не становится фактом
    оттого, что собиравший в него верит.
    """
    paper = source(src) if src else {"addr": "", "limit": None, "why": ""}
    addr = paper.get("addr") or ""
    out = {"topic": topic, "words": str(words or ""), "src": src or "", "addr": addr,
           "read_at": read_at, "kind": kind if kind in VERDICTS else OK, "why": str(why or ""),
           "age": age_words(read_at, now)}
    if not addr:
        out["kind"] = HYPO
        if not out["why"]:
            out["why"] = "ссылки на источник нет"
        return out
    if read_at is None:
        out["kind"] = UNKNOWN
        if not out["why"]:
            out["why"] = "время замера не снято"
        return out
    old = stale(read_at, now, paper.get("limit"))
    if old is None:
        out["kind"] = UNKNOWN
        out["why"] = out["why"] or "возраст слепка не сверить"
    elif old:
        out["kind"] = UNKNOWN
        out["why"] = ("слепок старше своего предела (%s: %d мин, %s)"
                      % (addr, int(round(float(paper["limit"]) / 60.0)), paper.get("why") or ""))
    return out


def dead_source(topic, src, why):
    """Источник не прочитался → строка ВСЁ РАВНО есть и говорит «неизвестно».

    Отдельная дверь, а не ветка в :func:`reading`, потому что она закрывает
    отрицательный тест закона 3 и обязана быть видна в коде одним именем.
    """
    return reading(topic, "источник не ответил", src=src, read_at=None, kind=UNKNOWN,
                   why=one_line(why, 120) or "причина не названа")


def line_text(rd):
    """Строка сводки словами: исход · суть · адрес · возраст замера."""
    mark = MARK.get(rd.get("kind"), "")
    body = rd.get("words") or ""
    head = ("%s — %s" % (mark, body)) if mark else body
    why = rd.get("why") or ""
    if why and rd.get("kind") in (UNKNOWN, HYPO):
        head = "%s (%s)" % (head, why)
    addr = rd.get("addr") or ""
    if not addr:
        return "• %s" % head
    return "• %s · %s · %s" % (head, addr, rd.get("age") or "возраст неизвестен")


