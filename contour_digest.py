#
# У ступени E исход считается ДВУМЯ РАЗНЫМИ СЛОВАМИ и не сливается: «разведка» —
# полоса пошла разбирать сама, «заявка владельцу» — предмет требует человека.
# Оба взяты у модуля-владельца (:data:`recon_auto.ROUTE_RECON` / ``ROUTE_OWNER``),
# литералами здесь не набраны — второй экземпляр разошёлся бы молча.

FATE_UNKNOWN = "неизвестно"


def finding_keys(records, day):
    """Ключи находок за КАЛЕНДАРНЫЕ сутки. → list[str] (порядок записей сохранён).

    Ключ считает СТУПЕНЬ B (:func:`review_intake.claim_key`), а не своя формула:
    судьба ищется в ЕЁ реестре, и второй способ считать ключ промахивался бы мимо
    записей молча — ровно тот класс, которым живёт вся полоса.
    """
    want = str(day or "")
    out = []
    for rec in (records or []):
        if not isinstance(rec, dict) or (rec.get("send_date") or "") != want:
            continue
        try:
            key = review_intake.claim_key(rec)
        except (TypeError, ValueError, AttributeError):
            continue                       # запись не разобралась → в счёт судьбы не идёт
        if key:
            out.append(key)
    return out


def _claims_by_record(intake):
    """Реестр ступени B → {ключ ЗАПИСИ: (ключ заявки, запись реестра)}.

    Разворот идёт по ВСЕМУ набору ключей заявки, а не по одному якорному: якорь
    переезжает с приходом второго канала (урок ступени B §4), и узнавание по
    одному ключу теряло бы заявку каждый раз, когда в лоток падает новый ответ.
    """
    out = {}
    for ckey, rec in ((intake or {}).get("claims") or {}).items():
        if not isinstance(rec, dict):
            continue
        for key in [ckey] + list(rec.get("keys") or []):
            if key:
                out[str(key)] = (str(ckey), rec)
    return out


def _recon_record(ckey, rec, table):
    """Повод ступени E по ЛЮБОМУ ключу заявки. → запись реестра | None.

    Ключ повода ступень E считает САМА (:func:`recon_auto.key_of`) и берёт для
    него ключ РЯДА, а не текущий якорный. Какой из ключей заявки оказался ключом
    ряда, отсюда не видно — поэтому пробуем весь набор, а не гадаем.
    """
    for key in [ckey] + list((rec or {}).get("keys") or []):
        got = (table or {}).get(recon_auto.key_of(recon_auto.SRC_CLAIM, str(key)))
        if isinstance(got, dict):
            return got
    return None


def external_fate(records, day, intake=None, recon=None, queue=None):
    """Находки суток → их СУДЬБА по трём реестрам полосы. → dict.

    Каждое число — либо ``int``, либо ``None``, и ``None`` значит «прибор молчал»,
    а не «ноль» (закон 3). Реестр, поданный ``None``, гасит СВОИ числа и не трогает
    чужие: смерть ступени E не отменяет того, что ступень B уже посчитала.

    ``queue`` — слепок очереди; отказ владельца берётся ИСХОДОМ ряда ``rejected``,
    который посчитал :mod:`queue_snapshot_pc` по своему маркеру. Второго экземпляра
    маркера здесь нет намеренно: «отклонено» — не статус очереди, а разрез, и
    считать его дважды значит развести два ответа на один вопрос.

    ``benefit`` считается ТОЛЬКО когда живы ОБА его источника: это объединение
    двух множеств, и при мёртвой половине получилась бы нижняя оценка, выданная за
    число. Нижняя оценка, напечатанная как факт, — это и есть враньё прибора.
    """
    keys = finding_keys(records, day)
    out = {"day": str(day or ""), "findings": len(keys),
           "claimed": None, "unmapped": None,
           "recon": None, "owner_ask": None, "held": None,
           "waiting": None, "rejected": None, "worked": None, "offsnap": None,
           "benefit": None}
    if not isinstance(intake, dict):
        return out                          # без реестра ступени B судьбы не знает никто
    by_rec = _claims_by_record(intake)
    claimed = [(k, by_rec[k]) for k in keys if k in by_rec]
    out["claimed"] = len(claimed)
    out["unmapped"] = len(keys) - len(claimed)
    useful = set()
    if isinstance(recon, dict):
        placed = recon.get("placed") if isinstance(recon.get("placed"), dict) else {}
        held = recon.get("held") if isinstance(recon.get("held"), dict) else {}
        out["recon"] = out["owner_ask"] = out["held"] = 0
        for key, (ckey, rec) in claimed:
            got = _recon_record(ckey, rec, placed)
            if got is not None:
                if str(got.get("way") or "") == recon_auto.ROUTE_RECON:
                    out["recon"] += 1
                    useful.add(key)
                else:
                    out["owner_ask"] += 1
                continue
            if _recon_record(ckey, rec, held) is not None:
                out["held"] += 1
    if isinstance(queue, dict):
        opened = queue.get("open") if isinstance(queue.get("open"), dict) else {}
        closed = queue.get("closed") if isinstance(queue.get("closed"), dict) else {}
        out["waiting"] = out["rejected"] = out["worked"] = out["offsnap"] = 0
        for key, (_ckey, rec) in claimed:
            tid = str(rec.get("queue_id"))
            row = opened.get(tid)
            if isinstance(row, dict):
                if row.get("status") == "needs_approval":
                    out["waiting"] += 1
                continue
            row = closed.get(tid)
            if not isinstance(row, dict):
                # Ряда нет НИ В ОДНОЙ половине слепка — это не «пропал» и не «сдан»:
                # слепок пишется по смене состояния и старых рядов может не помнить.
                out["offsnap"] += 1
                continue
            if row.get("outcome") == "rejected":
                out["rejected"] += 1
            elif row.get("outcome") == "done":
                out["worked"] += 1
                useful.add(key)
    if isinstance(recon, dict) and isinstance(queue, dict):
        out["benefit"] = len(useful)
    return out


def _num(value):
    """Число или СЛОВО «неизвестно». Ноль вместо молчания прибора не ставится."""
    return str(value) if isinstance(value, int) else FATE_UNKNOWN


