def external_stats(headers, records, day):
    """Шапки лотка + записи находок за КАЛЕНДАРНЫЙ день → числа строки. → dict.

    День календарный, а не «назад на 24 часа», и это не упрощение. В файле
    ответа стоит ``отправлено: YYYY-MM-DD`` БЕЗ ВРЕМЕНИ
    (:func:`review_intake.parse_answer`), поэтому скользящее окно пришлось бы
    ВЫДУМАТЬ — а выдуманное окно врало бы ровно на границе, где его и читают.
    Тот же выбор уже сделан суточной сводкой ступени D
    (:func:`review_audit.day_stats`): второе определение суток развело бы два
    показа в числах при одном источнике.

    Молчание канала считается ОТДЕЛЬНО от нуля ответов: ``down`` — это каналы, в
    которые за сутки ходили и которые не ответили НИ РАЗУ.
    """
    day = str(day or "")
    rows = [h for h in (headers or [])
            if isinstance(h, dict) and (h.get("send_date") or "") == day]
    answered = [h for h in rows if h.get("answered")]
    refused = [h for h in rows if not h.get("answered")]
    tried = sorted({(h.get("channel") or "?") for h in rows})
    replied = sorted({(h.get("channel") or "?") for h in answered})
    reasons = {}
    for h in refused:
        why = h.get("reason") or h.get("outcome") or "причина не названа"
        reasons[why] = reasons.get(why, 0) + 1
    kinds = {}
    for rec in (records or []):
        if isinstance(rec, dict) and (rec.get("send_date") or "") == day:
            kind = rec.get("kind") or "иное"
            kinds[kind] = kinds.get(kind, 0) + 1
    return {
        "day": day,
        "attempts": len(rows),
        "answers": len(answered),
        "refused": len(refused),
        "channels_tried": len(tried),
        "channels_answered": len(replied),
        # Канал, в который ходили и который не ответил ни разу. См.
        # :func:`external_words` — он называется СЛОВОМ, а не нулём.
        "down": [c for c in tried if c not in replied],
        "reasons": sorted(reasons.items(), key=lambda kv: (-kv[1], kv[0])),
        "kinds": sorted(kinds.items(), key=lambda kv: (-kv[1], kv[0])),
        "findings": sum(kinds.values()),
    }


def external_verdict(stats):
    """Исход строки внешних ответов. → OK | RED.

    Красное ровно одно — ЛЕЖАЩИЙ КАНАЛ. Молчание канала это не «ревьюер ничего
    не нашёл», а «спросить не удалось», и эти две новости обязаны различаться с
    одного взгляда: ноль находок при живом канале — итог, ноль находок при
    лежащем — дыра в наблюдении.
    """
    return RED if (stats or {}).get("down") else OK


def external_words(stats):
    """Числа суток внешних ответов → ОДНА строка сводки. → str.

    Порядок полей — порядок вопроса владельца: сколько пришло, сколько каналов
    ответило, сколько было отказов. Дальше — причины отказов, лежащие каналы,
    темы находок и указатель на лоток. Ни одного чужого знака.
    """
    got = stats or {}
    day = got.get("day") or "?"
    if not got.get("attempts"):
        return "внешние ответы за %s: заходов в каналы не было — спрашивать было нечего" % day
    parts = ["внешние ответы за %s: пришло %d · каналов ответило %d из %d · отказов канала %d"
             % (day, got.get("answers", 0), got.get("channels_answered", 0),
                got.get("channels_tried", 0), got.get("refused", 0))]
    reasons = got.get("reasons") or []
    if reasons:
        shown = ", ".join("%s ×%d" % (w, n) for w, n in reasons[:EXTERNAL_TOP])
        if len(reasons) > EXTERNAL_TOP:
            shown += " …и ещё %d причин" % (len(reasons) - EXTERNAL_TOP)
        parts.append("причины отказа: %s" % shown)
    if got.get("down"):
        # СЛОВОМ, А НЕ НУЛЁМ. «Ответов 0» читается как «нечего было сказать»;
        # «канал лежал» означает «мы не смогли спросить», и это разные новости.
        parts.append("КАНАЛ ЛЕЖАЛ: %s" % ", ".join(got["down"]))
    kinds = got.get("kinds") or []
    if kinds:
        shown = ", ".join("%s ×%d" % (k, n) for k, n in kinds[:EXTERNAL_TOP])
        if len(kinds) > EXTERNAL_TOP:
            shown += " …и ещё %d тем" % (len(kinds) - EXTERNAL_TOP)
        parts.append("темы находок (%d): %s" % (got.get("findings", 0), shown))
    else:
        parts.append("находок в ответах за сутки нет")
    # Адрес лотка второй раз НЕ печатаем: его уже ставит :func:`line_text`
    # хвостом строки, как всякому источнику. Два экземпляра одного адреса в
    # одной строке — это не «надёжнее», а место, где они разойдутся.
    parts.append("тексты не пересылаем — они лежат в лотке")
    return " · ".join(parts)


