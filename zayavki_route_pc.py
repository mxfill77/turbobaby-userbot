# -*- coding: utf-8 -*-
"""zayavki_route_pc.py — ИНФОРМАЦИОННАЯ ЗАЯВКА ИДЁТ СПИСКОМ, А НЕ КАРТОЧКОЙ. Чистая логика.

ПОВОД, НАЗВАННЫЙ ЧИСЛОМ, А НЕ ВКУСОМ (замер 09.09.2026 живыми файлами полосы):

* в очереди ТРИ ряда ``needs_approval``, и ВСЕ ТРИ — заявки ступени E
  (``zayavki_pc_run.py --status``: «заявок-ревью 0, карточек гарда 0, заявок
  ступени E 3»). То есть весь остаток ящика владельца — вопросы, на которые
  никто не ждёт ответа, чтобы работать дальше;
* за 08–09.09 ступень G закрыла отбором ДЕВЯТЬ заявок и отправила карточкой ОДНУ
  (``zayavki_pc_state.json``: девять записей ``closed`` и одна ``sent``);
* слово владельца 09.09: пересказывать ему заявки и ждать кнопки есть пустая
  трата времени.

ЧТО ЭТОТ МОДУЛЬ МЕНЯЕТ И ЧЕГО НЕ МЕНЯЕТ. Меняется РОВНО МАРШРУТ и ровно у того,
что САМО объявляет себя не-задачей: такой ряд перестаёт просить карточку и
попадает в СПИСОК. Право решать не двигается ни на шаг — по операционным
карточкам решает владелец, как и вчера; ни одной ветки, которая что-то за него
разрешает, здесь нет. Задач модуль не ставит, процессов не трогает, наружу не
ходит.

ПРИЗНАК РОДА БЕРЁТСЯ ЧУЖОЙ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА. Различитель ряда
``needs_approval`` на полосе ОДИН — :func:`shtab_box_signals.awaiting_kind`; он
уже держит равенство своих признаков ступеням B и E тестами, а витрина и ящик уже
зовут по нему один ряд одним словом. Второй экземпляр тех же строк разошёлся бы с
обоими МОЛЧА — ровно тем способом, каким до 03.09 «карточек гарда 4» означало
четыре заявки разведки.

ДВА ПРИЗНАКА, А НЕ ОДИН, И ОБА ОБЯЗАНЫ СОВПАСТЬ (условие задания «если заявка
ДЕРЖИТ РАБОТУ — она остаётся карточкой; проверить признаком из кода»):

1. **РОД** — маркер ПЕРВЫМ в теле ряда (:func:`shtab_box_signals.awaiting_kind`
   → :data:`~shtab_box_signals.KIND_ASK`). Маркеры — константы НАШЕГО кода
   (``[заявка-ревью``, ``[разведка-заявка``, ``[ревизор-находки]``), а не слова
   находки: их пишет тот же код, который ряд ставит.
2. **ДЕРЖИТ ЛИ РАБОТУ** — :func:`pc_orchestrator._is_owner_work`, та самая
   функция, которой полоса уже судит, уступать ли ревизорской цепи и брать ли
   новое задание из ящика. Она смотрит поле ``from`` РЯДА, а не текст.

Совпали оба («род — заявка» И «работой не является») → маршрут списком. Разошлись
или не спрошены → КАРТОЧКА, как сегодня. Направление отказа выбрано не для
симметрии: несостоявшаяся карточка — это заглушенный вопрос владельца, а лишняя
строка списка стоит строку.

ТЕКСТ ЗАЯВКИ НЕ СУДИТ ЗДЕСЬ НИЧЕГО. Прямой запрет задания («текст есть нарратив»):
ни одного поиска слов по телу ряда в этом файле нет, и тест ловит это обходом AST
(``ROUTE_PC_NO_PROSE``). Единственное, что читается из тела, — МАРКЕР, то есть
литерал, который наш же код туда и поставил.

НИЧЕГО НЕ ПОДАВЛЯЕТСЯ МОЛЧА — И ЭТО ДЕРЖИТСЯ УСТРОЙСТВОМ, А НЕ ОБЕЩАНИЕМ. Снятая
с инбокса заявка обязана быть видна В ДВУХ МЕСТАХ, и оба называет сам вердикт:

* СПИСКОМ — реестр маршрута, который витрина печатает строками и который вместе с
  витриной уезжает и в тему сводок, и в узел мозга ``pulse_pc`` (Штаб читает
  мозг сам). Строку собирает :func:`list_line`;
* ЧИСЛОМ — отдельная строка витрины (:func:`vitrina_lines`), и число это НИКОГДА
  не бывает нулём по незнанию: реестр не прочитан → «НЕИЗВЕСТНО» с причиной.

ЧИСТОТА. Ни сети, ни диска, ни подпроцессов, ни ``getenv``, ни часов: «сейчас»,
ряд и реестр — ПОЛЯ ВХОДА. Держит тест ``ZAYAVKI_ROUTE_PC_PURE`` обходом AST.
"""

from __future__ import annotations

import shtab_box_signals as sbs

SCHEMA = "turbobaby.zayavki_route_pc/v1"

# Имя реестра маршрута. Руки кладут его рядом с прочими файлами состояния полосы
# и уводят под тест в temp (`log_setup.state_path`) — здесь только имя, потому что
# путь это уже диск.
REGISTRY = "zayavki_route_pc_state.json"

# Рубильник ступени называется здесь, а спрашивается руками: чистый слой в
# окружение не смотрит. Поднят — маршрут прежний, байт-в-байт.
OFF_FLAG = "ZAYAVKI_ROUTE_PC_OFF"

ROUTE_CARD = "карточка владельцу"
ROUTE_LIST = "список Штаба"

# Сутки скользящим окном — та же мерка, что у потолка карточек ступени G: полночь
# UTC границей внимания владельца не является.
DAY_SEC = 86400.0

UNKNOWN = "НЕИЗВЕСТНО"

# ─── МАРКЕР → `from`, КОТОРЫЙ ЭТОТ МАРКЕР ВСЕГДА СОПРОВОЖДАЕТ ────────────────────
# Пары написаны не по догадке: каждый маркер и каждое `from` кладёт В ОДНОЙ И ТОЙ
# ЖЕ функции один и тот же код (`review_intake_run.Queue.place`,
# `recon_auto_run.Queue.place_ask`, `pc_orchestrator._revizor_owner_card`).
# Зачем пара вообще нужна: горлышко, где стои́т замок (`Bridge.set_needs_approval`),
# знает ТЕКСТ ряда и не знает его `from` — а второй признак спрашивают именно по
# `from`. Пара даёт задать вопрос, не выдумывая ответа: маркер не из списка →
# `from` пустой → `_is_owner_work` отвечает «работа» → карточка. Fail-closed.
FROM_BY_MARK = (
    ("[заявка-ревью", "Filipp-review-claim"),      # = pc_orchestrator.REVIEW_CLAIM_FROM
    ("[разведка-заявка", "Filipp-recon-ask"),      # = pc_orchestrator.RECON_ASK_FROM
    ("[ревизор-находки]", "Filipp-revizor"),       # = pc_orchestrator.REVIZOR_OWNER_FROM
)

# ─── КТО САМ ОБЪЯВЛЯЕТ СЕБЯ НЕ-ЗАДАЧЕЙ. ТРЕТИЙ ИЗ ТРЁХ — НЕ ОБЪЯВЛЯЕТ ────────────
# Условие задания дословно: «маршрут меняется ТОЛЬКО у того, что само объявляет
# себя не-задачей». Различитель `awaiting_kind` зовёт заявкой ТРИ рода — он отвечает
# на вопрос «держит ли ряд операцию», и по этому вопросу все три одинаковы. Наш
# вопрос ДРУГОЙ, и по нему они расходятся, поэтому третий род здесь отсутствует
# СОЗНАТЕЛЬНО:
#
#   [заявка-ревью    → `review_intake.CLAIM_HEAD`: «ЗАЯВКА ВНЕШНЕГО КАНАЛА — НЕ
#                       ЗАДАЧА. Ничего не исполняет и в работу не уходит»;
#   [разведка-заявка → `recon_auto.ask_text`: «Это НЕ задача: ничего не исполняется
#                       и в работу не уходит»;
#   [ревизор-находки]→ `pc_orchestrator` :12304 «🔍 Ревизор: находки — ТРЕБУЮТ
#                       ТВОЕГО РЕШЕНИЯ». Не-задачей себя не объявляет НИ СЛОВОМ, а
#                       его единственная кнопка ГАСИТ находки (расписка
#                       `_revizor_card_keys_add`) — то есть ответ владельца там
#                       что-то меняет. Снять её значило бы решить за него.
#
# Отсюда правило файла: маркер обязан быть в ЭТОМ списке, а не просто получить
# `KIND_ASK`. Появится завтра четвёртый род, объявляющий себя не-задачей, — его
# впишут сюда осознанно, а не унаследуют молча.
SELF_DECLARED = ("[заявка-ревью", "[разведка-заявка")


def body_of(row):
    """Ряд → тело, по которому опознаётся род. Спрашиваем ЧУЖУЮ функцию. → str."""
    return sbs.body_of(row)


def from_of(row):
    """Ряд → его ``from``; нет своего — выводим из МАРКЕРА. → (str, чем взят).

    Порядок именно такой: настоящее поле ряда сильнее выведенного. Вывод из
    маркера — не догадка о чужом ряде, а ответ на вопрос «каким `from` наш
    собственный код ставит ряд с таким маркером», и разойдись пара — второй
    признак честно скажет «работа» и карточка уедет владельцу.
    """
    got = row if isinstance(row, dict) else {}
    frm = str(got.get("from") or "").strip()
    if frm:
        return frm, "поле ряда"
    text = body_of(got)
    for mark, name in FROM_BY_MARK:
        if text.startswith(mark):
            return name, "выведен из маркера %s" % mark
    return "", "ни поля, ни знакомого маркера"


def self_declared(row):
    """Ряд САМ объявляет себя не-задачей? → bool.

    Спрашивается МАРКЕР, а не слова тела: маркер кладёт наш код вместе с самой
    самодекларацией, а слова находки — нарратив внешнего канала, и искать
    «не задача» в них значило бы дать чужому тексту право на маршрут.
    """
    text = body_of(row)
    return any(text.startswith(mark) for mark in SELF_DECLARED)


def decide(row, owner_work=None, enabled=True):
    """Ряд ``needs_approval`` → КУДА он едет. → dict.

    Поля возврата: ``route`` (:data:`ROUTE_CARD` / :data:`ROUTE_LIST`), ``kind`` и
    ``how`` (слова различителя), ``informational`` (bool), ``why`` — причина
    ЧЕЛОВЕЧЕСКИМИ словами, и она есть у КАЖДОГО исхода, включая обычный.

    ``owner_work`` — ответ :func:`pc_orchestrator._is_owner_work` о ЭТОМ ряде.
    ``None`` значит «не спросили», и это тот же исход, что «держит»: судить по
    одному признаку, когда правило требует двух, нельзя.

    ``enabled=False`` — рубильник поднят руками; маршрут прежний, и сказано это
    словом, а не молчанием.
    """
    got = row if isinstance(row, dict) else {}
    kind, how = sbs.awaiting_kind(got)
    frm, frm_how = from_of(got)
    out = {"schema": SCHEMA, "id": got.get("id"), "kind": kind, "how": how,
           "from": frm, "from_how": frm_how, "informational": False,
           "route": ROUTE_CARD, "why": ""}
    if not enabled:
        out["why"] = "маршрут выключен рубильником %s — карточка как прежде" % OFF_FLAG
        return out
    if kind != sbs.KIND_ASK:
        out["why"] = ("род «%s» (%s) — это НЕ информационная заявка, карточка владельцу "
                      "уходит точно так же, как вчера" % (kind, how))
        return out
    if not self_declared(got):
        out["why"] = ("род «%s», но не-задачей себя ряд НЕ объявляет (маркера нет в списке "
                      "SELF_DECLARED) — карточка владельцу как прежде" % kind)
        return out
    if owner_work is not True and owner_work is not False:
        out["why"] = ("род «%s», но второй признак (держит ли ряд работу) НЕ СПРОШЕН — "
                      "маршрут не меняем: одного признака мало" % kind)
        return out
    if owner_work:
        out["why"] = ("род «%s», но ряд ДЕРЖИТ РАБОТУ полосы (_is_owner_work по from=%s, %s) "
                      "— остаётся карточкой" % (kind, frm or "пусто", frm_how))
        return out
    out["informational"] = True
    out["route"] = ROUTE_LIST
    out["why"] = ("информационная заявка: род «%s» (%s) и работы не держит "
                  "(_is_owner_work=False по from=%s, %s)" % (kind, how, frm, frm_how))
    return out


def card_topic(verdict, topic):
    """Вердикт + тема карточки → тема, которую называют Мосту. → (тема|None, сказать ли вслух).

    ЕДИНСТВЕННОЕ место, где решение превращается в действие. ``None`` означает
    «карточки не просим»: тему постановки карточки называет ЗОВУЩИЙ, и не назвать
    её — это весь наш инструмент. Ничего не удаляется и не отменяется: ряд как
    стоял в очереди, так и стои́т, и виден списком.
    """
    d = verdict if isinstance(verdict, dict) else {}
    if d.get("informational"):
        return None, True
    return topic, False


def list_line(row, verdict):
    """Снятая с инбокса заявка → ОДНА строка списка. → str.

    Чужого текста в строке нет ни слова: номер ряда, наш род, наш маркер и наша
    причина. Полный текст лежит в самом ряде очереди, и строка на него УКАЗЫВАЕТ
    номером, а не пересказывает.
    """
    d = verdict if isinstance(verdict, dict) else {}
    got = row if isinstance(row, dict) else {}
    return ("#%s %s (%s) — карточки владельцу НЕ БЫЛО: %s; ряд в очереди на месте, "
            "полный текст там" % (got.get("id"), d.get("kind") or UNKNOWN,
                                  d.get("from") or "from не назван", d.get("why")))


def registry_add(state, row, verdict, now):
    """Реестр + снятая заявка → НОВЫЙ реестр. Чистая: вход не мутируется. → dict."""
    old = state if isinstance(state, dict) else {}
    rows = dict(old.get("routed") or {})
    key = str((row or {}).get("id"))
    rows[key] = {"at": now, "id": (row or {}).get("id"), "kind": (verdict or {}).get("kind"),
                 "from": (verdict or {}).get("from"), "why": (verdict or {}).get("why"),
                 "line": list_line(row, verdict)}
    return {"schema": SCHEMA, "routed": rows}


def day_rows(state, now):
    """Реестр → записи ПОСЛЕДНИХ СУТОК, свежие первыми. → list[dict]."""
    out = []
    for rec in ((state or {}).get("routed") or {}).values():
        try:
            if float(now) - float((rec or {}).get("at")) < DAY_SEC:
                out.append(rec)
        except (TypeError, ValueError):
            continue                      # запись без метки времени суткам не принадлежит
    return sorted(out, key=lambda r: float(r.get("at") or 0), reverse=True)


def vitrina_lines(rows, ok=True, why="", limit=6):
    """Записи суток → строки витрины: ЧИСЛО отдельной строкой + список. → list[str].

    ЧИСЛА НОЛЬ ПО НЕЗНАНИЮ НЕ БЫВАЕТ. Реестр не прочитан → ``ok=False`` и строка
    говорит :data:`UNKNOWN` с причиной: «снято 0» читалось бы как измеренный факт
    и было бы неотличимо от честного спокойного дня — ровно тот класс, ради
    которого витрина завела единую дверь числа.

    Список идёт ВТОРОЙ строкой и обрезан по ``limit`` с явным «и ещё N»: молчаливое
    усечение читается как «это всё», а мы обязаны показать, что показали не всё.
    """
    if not ok:
        return ["ЗАЯВКИ МИМО ИНБОКСА за сутки: %s (%s)"
                % (UNKNOWN, why or "реестр маршрута не прочитан")]
    got = list(rows or [])
    head = ("ЗАЯВКИ МИМО ИНБОКСА за сутки: %d — карточки владельцу не было, решать по ним "
            "нечего (род объявляет себя не-задачей и работы не держит)" % len(got))
    if not got:
        return [head]
    shown = got[:limit]
    tail = " и ещё %d" % (len(got) - limit) if len(got) > limit else ""
    return [head, "  списком: %s%s" % ("; ".join(str(r.get("line") or "") for r in shown), tail)]
