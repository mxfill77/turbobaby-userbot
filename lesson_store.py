# ПОЧЕМУ ОТПЕЧАТОК, А НЕ ПОРЯДКОВЫЙ НОМЕР РЕДАКЦИИ. К любому признаку есть третий вопрос:
# можно ли поднять его, НЕ СОВЕРШИВ события? У порядкового номера ответ «да» — число вписывается
# руками за секунду, и после этого признак врёт молча. Такой признак негоден ЦЕЛИКОМ, а не «годен
# с оговоркой», поэтому он и не выбран. Версией назначен ОТПЕЧАТОК ТЕЛА таблицы: он не
# назначается, а ВЫЧИСЛЯЕТСЯ, и разойтись с содержимым не может по устройству.
#
# ЧЕСТНО О ЦЕНЕ ВЫБОРА: отпечаток НЕ ЗАДАЁТ ПОРЯДКА. По двум значениям нельзя сказать, какое
# раньше — он отвечает «та ли это редакция», а не «которая по счёту». Порядок редакций в базе
# даёт не версия, а следовые файлы со штампами (`.promote`, `.batch`) и поле `когда` у строк.
# Это названо вслух, а не спрятано: признак, отвечающий на один вопрос правдиво, дороже признака,
# отвечающего на два, из которых один — враньё.
#
# ОТ ЧЕГО ВЕРСИЯ ДВИЖЕТСЯ: от КАЖДОГО события записи в таблицу — записан урок или кандидат,
# снят урок/день/автор/набор, переведён кандидат, откачен перевод, переведены строки в формат с
# источником. Любое из них меняет байты таблицы, а значит и отпечаток.
# КТО ЕЁ ПОДНИМАЕТ: НИКТО РУКАМИ. Поднимает сам код записи — `_stamp_version` зовётся из двух
# мест, и оба это места, трогающие байты таблицы (`_add_row` после дозаписи и `_rewrite` после
# подмены файла). Человеку двери записи версии не дано ни одной.
#
# ИДИОМА ВЗЯТА ИЗ ЭТОГО ЖЕ РЕПОЗИТОРИЯ, а не сочинена: так же устроен `corpus_sha`
# (`client_contour.py:532`) — sha256, первые 16 hex, и вердикт обязан назвать ТОТ корпус, что
# лежит на диске. Здесь то же правило, только предмет — база уроков.
#
# ПОЧЕМУ САЙДКАР, А НЕ КОЛОНКА И НЕ СЛУЖЕБНАЯ СТРОКА В ФАЙЛЕ. Версия — свойство ВСЕЙ таблицы, а
# не строки, поэтому колонкой ей быть нечем. Служебной строкой в самом файле — нельзя: `load`
# узнаёт шапку только первой строкой (`idx == 1`), и вставка перед ней увела бы шапку в `broken`,
# то есть подняла бы НЕРАЗБОР на ровном месте. Сайдкар рядом с таблицей — уже заведённая в этом
# модуле форма (`.bak`, `.promote`, `.batch`), и ни одного байта лежащих строк она не трогает.
VERSION_SUFFIX = ".version"
VERSION_LEN = 16

SAY_VERSION_NONE = "версия не названа"
SAY_VERSION_NO_TABLE = "версия не названа: таблицы нет"
SAY_VERSION_STALE = ("версия названа, но содержимому не отвечает: записано «%s», а таблица даёт "
                     "«%s». Либо поле заполнено мимо события, либо таблицу правили мимо двери")
SAY_VERSION_OK = "версия %s"

# `said` — что ЗАПИСАНО в поле; `live` — что ПЕРЕСЧИТАНО по таблице; `ok` — сошлись ли они.
# Три поля, а не одно «ok», СОЗНАТЕЛЬНО: на расхождении надо уметь назвать обе стороны, иначе
# отказ не отличить от «не смог прочитать», и третий исход схлопнется во второй.
Version = namedtuple("Version", "said live ok exists say")


def version_path(path=None):
    """Путь сайдкара версии рядом с таблицей."""
    return _path(path) + VERSION_SUFFIX


def fingerprint(path=None):
    """Отпечаток таблицы (sha256, 16 hex) → `None` при нечитаемом файле.

    `None`, а не пустая строка: «не смог прочитать» обязано отличаться от значения, иначе два
    нечитаемых файла оказались бы «одной версии»."""
    try:
        with open(_path(path), "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()[:VERSION_LEN]
    except OSError:
        return None


def version(path=None):
    """ЕДИНСТВЕННАЯ ДВЕРЬ ЧТЕНИЯ ВЕРСИИ. → Version.

    ТРИ ИСХОДА, и ни один не превращается в другой:
      • таблицы нет вовсе      → `ok=False`, `said=None`, `exists=False` — «не названа»;
      • поле есть, но разошлось с пересчётом → `ok=False`, названы ОБЕ стороны — ОТКАЗ;
      • сошлось                → `ok=True`.

    Записанное поле НЕ отдаётся на слово ни на одной ветке: оно всегда сверяется с пересчётом по
    таблице. В этом весь смысл признака — версия, принятая на слово, поднимается вписыванием."""
    target = _path(path)
    live = fingerprint(target)
    said = None
    try:
        with open(version_path(target), encoding="utf-8", newline="") as f:
            said = f.read().strip() or None
    except OSError:
        said = None

    if live is None:
        return Version(said, None, False, False, SAY_VERSION_NO_TABLE)
    if said is None:
        return Version(None, live, False, True, SAY_VERSION_NONE)
    if said != live:
        return Version(said, live, False, True, SAY_VERSION_STALE % (said, live))
    return Version(said, live, True, True, SAY_VERSION_OK % said)


def _stamp_version(target):
    """Поднять версию ПО ФАКТУ состоявшейся записи. Зовётся ТОЛЬКО кодом и ТОЛЬКО после того, как
    байты таблицы уже легли, — иначе поле описывало бы намерение, а не событие.

    Сбой записи сайдкара НЕ роняет уже состоявшуюся правку таблицы: потерянная версия честно
    читается как «названа, но содержимому не отвечает» (отказ), а потерянный урок не читается
    никак. Из двух бед выбрана громкая.

    ПИШЕТСЯ ЧЕРЕЗ ВРЕМЕННЫЙ ФАЙЛ И `os.replace`, как и таблица, — усекается ОН, а не сайдкар.
    Инвариант модуля «единственный усекающий `open` открывает временный файл» держится тестом
    (`test_only_truncating_open_is_the_temp_file`), и обходить его здесь было бы обменом живого
    замка на две сэкономленные строки: оборванная запись оставила бы версию ПОЛУПУСТОЙ, то есть
    значением, которого не даёт ни одна таблица."""
    value = fingerprint(target)
    if value is None:
        return None
    said = version_path(target)
    tmp = said + TMP_SUFFIX
    try:
        with open(tmp, "w", encoding="utf-8", newline="") as f:
            f.write(value + "\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, said)
    except OSError:
        return None
    return value


def norm_who(who):
    """Ключ автора: без пробелов по краям, без ведущей собачки, регистр не значим."""
    return who.strip().lstrip("@").casefold()


def is_active(lesson):
    return lesson.state == STATE_ACTIVE


def is_candidate(lesson):
    return lesson.state == STATE_CANDIDATE


def active(lessons):
    """Только ДЕЙСТВУЮЩИЕ. Кандидаты сюда не попадают ни одной веткой — это и есть замок
    «действующий урок всегда с причиной»: без `promote` (а он без причины отказывает) строка
    состояние `актив` не получает."""
    return tuple(les for les in lessons if is_active(les))


def candidates(lessons):
    """Только кандидаты — записанные, но ещё не действующие."""
    return tuple(les for les in lessons if is_candidate(les))


def by_author(lessons, who):
    """Уроки одного человека (снятые тоже — фильтруй `active()` сверху, если не нужны)."""
    key = norm_who(who)
    return tuple(les for les in lessons if norm_who(les.who) == key)


def by_day(lessons, day):
    """Уроки за сутки «ГГГГ-ММ-ДД»."""
    key = day.strip()
    return tuple(les for les in lessons if day_of(les.when) == key)


def by_source(lessons, source):
    """Уроки ОДНОГО набора. Строка с неизвестным источником сюда не попадает ни при каком
    ключе — включая попытку спросить `None`: «не знаю» набором не является, и снимать по нему
    целиком было бы снятием всего, что старше формата."""
    key = norm_source(source)
    if key is None:
        return ()
    return tuple(les for les in lessons
                 if les.source is not SOURCE_UNKNOWN and norm_source(les.source) == key)


def by_batch(lessons, source, batch):
    """Уроки ОДНОЙ ЗАЛИВКИ названного набора. `batch=BATCH_ANY` — все заливки этого источника
    (то же, что `by_source`), `batch=BATCH_UNKNOWN` — только строки БЕЗ номера заливки.

    Три ответа, а не два, СОЗНАТЕЛЬНО: «любая» и «без номера» — разные множества, и схлопнуть их
    значило бы снять при одном ключе то, что показали при другом."""
    rows = by_source(lessons, source)
    if batch is BATCH_ANY:
        return rows
    want = norm_batch(batch) if batch is not BATCH_UNKNOWN else BATCH_UNKNOWN
    return tuple(les for les in rows if les.batch == want)


def batches_census(lessons, source=None):
    """Перепись ЗАЛИВОК числами: {(источник, партия | None): сколько строк}. Порядок —
    `SOURCES`, внутри источника по номеру, строки без номера последними: так строка отчёта не
    пляшет между запусками (тот же довод, что у `sources_census`)."""
    rows = lessons if source is None else by_source(lessons, source)
    seen = Counter((say_source(les.source), les.batch) for les in rows)
    order = {name: i for i, name in enumerate(SOURCES)}

    def key(pair):
        src, num = pair
        return (order.get(src, len(SOURCES)), src,
                0 if num is not BATCH_UNKNOWN else 1, num or 0)

    return tuple((pair, seen[pair]) for pair in sorted(seen, key=key))


def modes_census(lessons):
    """Перепись РЕЖИМОВ числами: {режим словами: сколько строк}. Неизвестный называется словами
    и стои́т последним — он не режим, а его отсутствие."""
    seen = Counter(say_mode(les.mode) for les in lessons)
    out = []
    for name in MODES:
        if seen.get(name):
            out.append((name, seen.pop(name)))
    rest = seen.pop(SAY_MODE_UNKNOWN, 0)
    for name in sorted(seen):
        out.append((name, seen[name]))
    if rest:
        out.append((SAY_MODE_UNKNOWN, rest))
    return tuple(out)


def unknown_source(lessons):
    """Уроки, у которых источника нет (строки старше формата). Названы отдельным разрезом ЧТЕНИЯ,
    но НЕ разрезом снятия: снять «всё, что старше формата» одним движением — это не набор, а
    возраст, и такого требования не было."""
    return tuple(les for les in lessons if les.source is SOURCE_UNKNOWN)


def sources_census(lessons):
    """Перепись набора числами: {источник или SAY_UNKNOWN: сколько строк}. Порядок — `SOURCES`,
    потом чужие значения, потом неизвестные: так строка отчёта не пляшет между запусками."""
    seen = Counter(say_source(les.source) for les in lessons)
    out = []
    for src in SOURCES:
        if seen.get(src):
            out.append((src, seen.pop(src)))
    rest = seen.pop(SAY_UNKNOWN, 0)
    for name in sorted(seen):
        out.append((name, seen[name]))
    if rest:
        out.append((SAY_UNKNOWN, rest))
    return tuple(out)


