# Признак («все, у кого причина такая-то») соблазнителен и опасен: он молча накрыл бы строку,
# похожую на набор, но пришедшую другой дорогой, — то есть поставил бы ДОГАДКУ там, где нужен
# ФАКТ. Кто доказал происхождение, тот и перечисляет номера; доказательство живёт у него, а не
# здесь. Строка, которую не назвали, остаётся без источника — и это честный третий исход.
SetSourceResult = namedtuple("SetSourceResult",
                             "source numbers stamped already missing lines_before lines_after")


def set_source(numbers, source, path=None):
    """Проставить ИСТОЧНИК НАБОРА уже лежащим строкам, названным ПОИМЁННО. → SetSourceResult.

    Источник судится ТОЙ ЖЕ дверью, что и у новой строки (`validate_source`), и отказ такой же
    ГРОМКИЙ: чужое значение — это `LessonRejected`, а не «переведено 0 строк». Второго списка
    источников здесь нет ни одного.

    Шапка переезжает ВМЕСТЕ со строками, одним и тем же движком: восьмиколоночная шапка дорастает
    именем девятой колонки. Иначе файл остался бы с шапкой, не описывающей его строки.

    `stamped` — сколько строк получило источник, `already` — сколько его уже несли (второй раз не
    ставим), `missing` — какие названные номера в таблице не нашлись. Числа НЕ схлопнуты в одно:
    «не нашёлся» и «уже стоял» — разные новости, и подводить их под общий итог значило бы прятать
    ту, из-за которой стоит остановиться."""
    ok, reason, canon = validate_source(source)
    if not ok:
        raise LessonRejected(reason, field=COL_SOURCE)

    target = _path(path)
    store = load(target)
    if not store.exists:
        return SetSourceResult(canon, tuple(numbers), 0, 0, tuple(numbers), 0, 0)

    want = tuple(int(n) for n in numbers)
    by_number = {les.number: les for les in store.lessons}
    tails, stamped, already, missing = {}, 0, 0, []
    for num in want:
        les = by_number.get(num)
        if les is None:
            missing.append(num)
            continue
        if les.source is not SOURCE_UNKNOWN:
            already += 1
            continue
        tails[les.line] = esc(canon)
        stamped += 1

    if not tails:
        lines = _count_lines(target)
        return SetSourceResult(canon, want, 0, already, tuple(missing), lines, lines)

    # Шапка растёт ТОЛЬКО если она восьмиколоночная: `_grow_row` сам откажется трогать
    # девятиколоночную, но спрашивать его вслепую было бы ставкой на его молчание.
    with open(target, encoding="utf-8", newline="") as f:
        head = f.readline().rstrip("\n").rstrip("\r")
    if head == HEADER_BASE_LINE:
        tails[1] = COL_SOURCE

    before, after = _rewrite(target, {}, tails_by_line=tails)
    return SetSourceResult(canon, want, stamped, already, tuple(missing), before, after)


