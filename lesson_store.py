def _render(lesson):
    return ("#%d [%s] %s | %s | набор: %s | %s | %s\n    вопрос: %s\n    ответил бот: %s\n"
            "    как правильно: %s\n    почему: %s"
            % (lesson.number, lesson.state, lesson.who, lesson.when, say_source(lesson.source),
               say_batch(lesson.batch), say_mode(lesson.mode),
               lesson.question, lesson.bot_answer, lesson.correct, lesson.why))


def main(argv=None):
    io_utf8.force_utf8()
    ap = argparse.ArgumentParser(description="хранилище уроков тренажёра (чтение)")
    ap.add_argument("--status", action="store_true", help="ёмкость и целостность числами")
    ap.add_argument("--list", action="store_true", help="перечислить уроки")
    ap.add_argument("--trace", action="store_true", help="след переводов и откатов")
    ap.add_argument("--batch-trace", action="store_true", dest="batch_trace",
                    help="след снятий и возвратов НАБОРОВ (своя таблица, свой ключ)")
    ap.add_argument("--all", action="store_true", help="вместе со снятыми")
    ap.add_argument("--who", help="только уроки этого человека")
    ap.add_argument("--day", help="только уроки за сутки ГГГГ-ММ-ДД")
    ap.add_argument("--source", help="только уроки этого набора (%s)" % ", ".join(SOURCES))
    ap.add_argument("--batch", help="только уроки этой заливки (число; «-» — строки без номера); "
                                    "требует --source")
    ap.add_argument("--mode", help="только уроки этого режима (%s; «-» — режим неизвестен)"
                                   % ", ".join(MODES))
    ap.add_argument("--path", help="другой файл таблицы (по умолчанию %s)" % STORE_NAME)
    args = ap.parse_args(sys.argv[1:] if argv is None else argv)

    store = load(args.path)
    if args.trace:
        seen = load_trace(args.path)
        print("след: %s (%s)" % (promote_log_path(args.path),
                                 "есть" if len(seen) > 0 else "пуст или не заведён"))
        for t in seen:
            print("%s  %-7s #%-4d %-16s было «%s» → стало «%s»"
                  % (t.stamp, t.act, t.number, t.who, unesc(t.prev_state), unesc(t.new_why)))
        print("— всего движений: %d" % len(seen))
        return 0

    if args.batch_trace:
        # СВОЙ след и СВОЙ ключ: у набора объект — источник, а не номер урока (см. §НАБОР).
        seen = load_batch_trace(args.path)
        print("след наборов: %s (%s)" % (batch_log_path(args.path),
                                         "есть" if len(seen) > 0 else "пуст или не заведён"))
        for t in seen:
            print("%s  движение %-4d %-14s %-18s #%-4d %-16s было «%s» → стало «%s» (всего %d)"
                  % (t.stamp, t.move, t.act, t.source, t.number, t.who, t.prev_state,
                     t.new_state, t.total))
        print("— всего строк следа: %d" % len(seen))
        return 0

    if not args.list:
        cap = capacity(args.path)
        integ = integrity(args.path)
        print("файл: %s (%s)" % (store.path, "есть" if store.exists else "ещё не заведён"))
        print("ёмкость: %s; байт %d" % (cap.say, cap.bytes))
        cands = candidates(store.lessons)
        print("действующих: %d; кандидатов: %d; снятых: %d"
              % (len(active(store.lessons)), len(cands),
                 len(store.lessons) - len(active(store.lessons)) - len(cands)))
        # НАБОРЫ ЧИСЛАМИ — иначе «снять набор» нечем прицелиться. Строки старше формата названы
        # своим словом, а не свалены в первый попавшийся источник.
        census = sources_census(store.lessons)
        print("наборы: %s" % ("; ".join("%s — %d" % pair for pair in census) or "—"))
        # ЗАЛИВКИ И РЕЖИМЫ ЧИСЛАМИ — по тому же доводу, что наборы: без них не видно ни того,
        # что одним ключом уедут две поставки, ни того, сколько строк лежит без названного режима.
        lots = batches_census(store.lessons)
        print("заливки: %s" % ("; ".join("%s/%s — %d" % (src, num if num is not BATCH_UNKNOWN
                                                         else "без номера", cnt)
                                          for (src, num), cnt in lots) or "—"))
        print("режимы: %s" % ("; ".join("%s — %d" % pair
                                        for pair in modes_census(store.lessons)) or "—"))
        print(integ.say)
        return 0

    rows = store.lessons
    if args.who is not None:
        rows = by_author(rows, args.who)
    if args.day is not None:
        rows = by_day(rows, args.day)
    if args.source is not None:
        rows = by_source(rows, args.source)
    if args.batch is not None:
        if args.source is None:
            print("--batch требует --source: номер заливки без набора ни на что не указывает")
            return 2
        rows = by_batch(rows, args.source, batch_key(args.batch))
    if args.mode is not None:
        want = None if args.mode.strip() == "-" else known_mode(args.mode)
        if want is None and args.mode.strip() != "-":
            print("--mode: режим «%s» мне неизвестен (знаю %s)"
                  % (args.mode.strip(), ", ".join(MODES)))
            return 2
        rows = tuple(les for les in rows if les.mode == want)
    if not args.all:
        rows = active(rows)
    for les in rows:
        print(_render(les))
    print("— всего строк показано: %d" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
