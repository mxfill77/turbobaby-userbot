# Снятие: три разреза владельца. Строка ОСТАЁТСЯ, меняется только последнее поле.
# ---------------------------------------------------------------------------------------
# `lines_*` считает ФИЗИЧЕСКИЕ строки файла (шапка входит) — это и есть доказательство, что
# снятие ничего не удалило: числа обязаны совпасть.
WithdrawResult = namedtuple("WithdrawResult", "cut key marked already lines_before lines_after")


def _matches(lesson, cut, key):
    """Подходит ли строка под разрез. КАЖДАЯ ветка названа, и есть ЯВНЫЙ хвост `False`.

    До 09.09 хвоста не было: последней строкой стояло `return norm_who(...)`, то есть «всё, что
    не урок и не день, — автор». С четвёртым разрезом такой хвост стал бы миной: неизвестный
    разрез молча снимал бы по автору."""
    if cut == CUT_ONE:
        return lesson.number == key
    if cut == CUT_DAY:
        return day_of(lesson.when) == key
    if cut == CUT_WHO:
        return norm_who(lesson.who) == key
    if cut == CUT_SOURCE:
        # Строка без источника не принадлежит НИ ОДНОМУ набору — см. `by_source`.
        return lesson.source is not SOURCE_UNKNOWN and norm_source(lesson.source) == key
    if cut == CUT_BATCH:
        # Ключ ПАРЫ: (источник, партия). Источник судится тем же условием, что выше, — второго
        # определения «строка принадлежит набору» здесь нет.
        src_key, lot = key
        if lesson.source is SOURCE_UNKNOWN or norm_source(lesson.source) != src_key:
            return False
        return lesson.batch == lot
    return False


def _replace_state(raw, state):
    """Последнее поле ВОСЬМИКОЛОНОЧНОЙ части СЫРОЙ строки → новое состояние. Остальные байты не
    трогаются вовсе: круг «разобрать → собрать» не байт-в-байт на чужих экранированных
    последовательностях.

    ВЕТКОЙ НЕ ЗОВЁТСЯ НИ ОТКУДА (снятие и перевод ходят через `_replace_fields`), но оставлен и
    ПОЧИНЕН, а не удалён: прежнее тело резало по ПОСЛЕДНЕЙ табуляции, и на строке с хвостом
    источника оно записало бы состояние в графу источника. Мина, которая ждала бы первого
    вызывающего."""
    return _replace_fields(raw, {IDX_STATE: state})


def _replace_fields(raw, by_index):
    """Названные колонки СЫРОЙ строки → новые УЖЕ ЭКРАНИРОВАННЫЕ значения; остальные байты
    переносятся дословно. Разбор здесь идёт только по табуляции и БЕЗ `unesc`/`esc` — то есть
    нетронутые поля не проходят круг «разобрать → собрать», на котором чужая последовательность
    могла бы поменяться. Строка не той ширины не правится вовсе (лучше не тронуть, чем испортить)."""
    parts = raw.split("\t")
    if len(parts) not in WIDTHS:
        return raw
    for idx, value in by_index.items():
        # ХВОСТ НЕ ДОПИСЫВАЕТСЯ ПРАВКОЙ. У восьмиколоночной строки графы источника нет, и
        # `parts[8] = …` бросил бы IndexError ПОСРЕДИ перезаписи — то есть после копии `.bak` и
        # на половине временного файла. Решение Штаба ровно об этом: формат растёт хвостом у НОВЫХ
        # строк, а лежащие не переписываются; поэтому здесь пропуск, а не рост строки. Что ни одна
        # ветка не пытается править источник — сторожит тест на исходнике.
        if idx >= len(parts):
            continue
        parts[idx] = value
    return "\t".join(parts)


def _grow_row(raw, tail):
    """СЫРАЯ строка законной ширины + УЖЕ ЭКРАНИРОВАННЫЙ хвост → строка СЛЕДУЮЩЕЙ законной ширины.
    Всё прочее возвращается НЕТРОНУТЫМ.

    `tail` — строка (одна графа) либо кортеж граф. Обе формы, а не одна: перевод 8→9 приписывает
    источник, перевод 9→11 приписывает партию и режим ПАРОЙ, и разбивать вторую на два прохода
    значило бы завести на полпути строку ширины 10, которой в формате нет.

    Это единственное место, где лежащая строка РАСТЁТ, и оно намеренно узкое. `_replace_fields`
    расти отказывается (см. комментарий там): правка полей не смеет менять ширину строки, иначе
    `parts[9] = …` бросил бы IndexError посреди перезаписи. Рост — отдельное действие с отдельным
    именем, и применяется он только переводом формата (`set_source`, `set_batch`), а не правкой.

    ЗАКОННОСТЬ СУДИТСЯ ПО ОБЕИМ СТОРОНАМ: и исходная ширина, и получившаяся обязаны быть в
    `WIDTHS`. Отсюда даром получается три отказа, каждый из которых иначе пришлось бы сторожить
    руками: строка, уже несущая хвост, второго не получит; битая строка не трогается вовсе;
    восьмиколоночная не перепрыгнет сразу в одиннадцать, миновав источник (8+2 = 10, ширины нет)."""
    fields = (tail,) if isinstance(tail, str) else tuple(tail)
    parts = raw.split("\t")
    if len(parts) not in WIDTHS or (len(parts) + len(fields)) not in WIDTHS:
        return raw
    return raw + "".join("\t" + f for f in fields)


def _count_lines(target):
    """Физических строк в файле (шапка входит). Потоком: размер файла не уходит в память."""
    total = 0
    with open(target, encoding="utf-8", newline="") as f:
        for _line in f:
            total += 1
    return total


def _rewrite(target, edits_by_line, tails_by_line=None):
    """Единственное место, трогающее уже лежащие байты. Копия `.bak` кладётся ДО правки,
    новое тело пишется во ВРЕМЕННЫЙ файл (усекается ОН, не таблица) и въезжает атомарным
    `os.replace`. → (строк прочитано, строк записано) — числа обязаны совпасть.

    `edits_by_line` — {номер физической строки: {индекс колонки: экранированное значение}}.
    `tails_by_line` — {номер физической строки: экранированный хвост} для ПЕРЕВОДА ФОРМАТА.
    Каждая строка источника переписывается в приёмник; меняются только названные поля и растут
    только названные строки. Ни одна ветка не пропускает строку — в этом и состоит «не удаляем».

    ХВОСТ ЖИВЁТ В ЭТОМ ЖЕ ДВИЖКЕ, а не во втором писателе рядом, СОЗНАТЕЛЬНО: дисциплина правки
    таблицы (копия до, временный файл, атомарная подмена, сверка числа строк, подъём версии)
    обязана быть ОДНА. Второй писатель разошёлся бы с ней по мелочи молча — и разошёлся бы именно
    в той операции, которую делают раз в жизни и потому не перепроверяют."""
    shutil.copyfile(target, target + BACKUP_SUFFIX)
    tmp = target + TMP_SUFFIX
    tails = tails_by_line or {}
    lines_in, lines_out = 0, 0
    with open(target, encoding="utf-8", newline="") as src:
        with open(tmp, "w", encoding="utf-8", newline="") as dst:
            for idx, line in enumerate(src, start=1):
                lines_in += 1
                body = line.rstrip("\n").rstrip("\r")
                edit = edits_by_line.get(idx)
                if edit:
                    body = _replace_fields(body, edit)
                tail = tails.get(idx)
                if tail is not None:
                    body = _grow_row(body, tail)
                dst.write(body + "\n")
                lines_out += 1
            dst.flush()
            os.fsync(dst.fileno())
    os.replace(tmp, target)
    # ВЕРСИЯ ПОДНИМАЕТСЯ ЗДЕСЬ — после `os.replace`, то есть когда новые байты уже стали таблицей.
    # Это второе и последнее место подъёма: снятие, перевод, откат и перевод формата ходят сюда.
    _stamp_version(target)
    return lines_in, lines_out


