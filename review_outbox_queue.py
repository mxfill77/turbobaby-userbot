# по возрасту, и причина пишется в запись словами.
#
# Число не назначено, а взято с живого класса 02.09.2026. Вердикт «повтор
# воспроизвёл бы ту же ошибку» судит НЕ канал, а ПОСЫЛКУ — наш отправщик, наш
