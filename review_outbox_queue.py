# а не стирание: сама запись, её история и пакет в лотке остаются нетронутыми.
STATES = ("queued", "exhausted", "closed", "archived")

# Исход архива. Развилка ровно одна и она про ЧУЖИЕ ДЕНЬГИ — см.
# :func:`archive_outcome_of`.
ARCHIVE_OUTCOMES = ("refused", "unknown")

