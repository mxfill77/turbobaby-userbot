# есть только при НОВОМ заходе.
#
# Сутки — окно, внутри которого посылка ещё та же: полоса ПК за сутки кладёт
# 4.3 закрытых цепочки и один-два коммита в отправщик. Дальше запись судит о
# коде, которого нет, и держать её живой значит обещать повтор, которого не
# будет. Срок НЕ УДАЛЯЕТ ничего — он переводит запись в архив (:func:`archive`).
EXPIRE_AFTER_SEC = 86400

# Потолок слоя поводов, внутрь которого обязаны уместиться наши окна. Литерал, а
# не импорт: ``review_auto`` тянет за собой лоток и разбор ответов, а этому
# модулю нужно одно число. Сверку литерала с живой константой держит регресс
