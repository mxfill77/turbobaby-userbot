REVIEW_AUTO_RETRY_AFTER_SEC = 3600
# Сокет-таймаут отправщика: столько может стоить ОДИН заход, упёршийся в мёртвый
# сокет. Тот же литерал и тот же замок (``review_send_run.DEFAULT_TIMEOUT``).
SEND_TIMEOUT_SEC = 900

