def digest_line(taken, day, ok=True, why=""):
    """Отдельный счёт для сводки контура: «задач от Штаба взято N». → str.

    ЧИСЛО ИЛИ «НЕИЗВЕСТНО», третьего не дано и ноль вместо незнания не ставится:
    «взято 0» читается как «Штаб ничего не клал», а это утверждение, которого при
    непрочитанном источнике мы делать не вправе.
    """
    if not ok:
        return ("задач от Штаба взято: НЕИЗВЕСТНО — %s (узел %s)"
                % (why or "источник не прочитан", NODE_NAME))
    return ("задач от Штаба взято %d за %s (потолок %d/сут, узел %s)"
            % (int(taken), str(day or "?"), DAILY_BUDGET, NODE_NAME))
