def parse_node(text):
    """Текст узла-ящика → (блоки, отказы разбора).

    Блок — ``{"key":…, "body":…, "line":…}``; отказ — ``{"key":…, "why":…}``.
    Оба списка отдаются ВСЕГДА: молча пропущенный битый блок читается как «Штаб
    ничего не клал», и это ровно та разница, из-за которой ящик выглядел бы
    пустым при полном узле.

    ЧТО СЧИТАЕТСЯ ОТКАЗОМ РАЗБОРА (не путать с отказом ВОРОТ — тот в :func:`check`):

    * блок открыт и не закрыт — возможно, узел обрезан или Штаб не дописал;
    * ключ закрытия не совпал с ключом открытия — границы блоков разъехались;
    * внутри блока встретилось открытие следующего — предыдущий не закрыт;
    * закрытие без открытия — мусор, и о нём надо сказать, а не проглотить;
    * ДВА БЛОКА С ОДНИМ КЛЮЧОМ — отказывают ОБА. Ключ и есть имя, которым дедуп
      отличает задачи друг от друга: взяв один из двойников, полоса пометила бы
      выполненным и второй, а он другой.
    """
    lines = str(text or "").splitlines()
    blocks, bad = [], []
    key, start, body = "", 0, []
    for i, raw in enumerate(lines, 1):
        opened = OPEN_RE.match(raw)
        closed = CLOSE_RE.match(raw)
        if opened:
            if key:
                bad.append({"key": key, "line": start,
                            "why": "блок не закрыт: на строке %d открылся следующий" % i})
            key, start, body = opened.group(1), i, []
            continue
        if closed:
            if not key:
                bad.append({"key": closed.group(1), "line": i,
                            "why": "закрытие без открытия — границы блоков разъехались"})
                continue
            if closed.group(1) != key:
                bad.append({"key": key, "line": start,
                            "why": "ключ закрытия %r не совпал с ключом открытия"
                                   % closed.group(1)})
                key = ""
                continue
            blocks.append({"key": key, "body": "\n".join(body).strip(), "line": start})
            key = ""
            continue
        if key:
            body.append(raw)
    if key:
        bad.append({"key": key, "line": start,
                    "why": "блок не закрыт до конца узла — возможно, он обрезан"})
    seen = {}
    for blk in blocks:
        seen[blk["key"]] = seen.get(blk["key"], 0) + 1
    out = []
    for blk in blocks:
        if seen[blk["key"]] > 1:
            bad.append({"key": blk["key"], "line": blk["line"],
                        "why": "ключ встретился в узле %d раза — двойники не берём ни один"
                               % seen[blk["key"]]})
            continue
        out.append(blk)
    return out, bad


