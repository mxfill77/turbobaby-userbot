# первые 89 символов, иначе `MARK_RE` перестанет совпадать и счёт «взято N»
# поедет ВНИЗ МОЛЧА. Постоянная часть маркера «[от Штаба дата=ГГГГ-ММ-ДД ключ=]»
# — 32 символа, значит ключу остаётся 57. Берём 40: запас в 17 символов на случай,
