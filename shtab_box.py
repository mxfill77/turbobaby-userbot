def select(blocks, *, task_marks=(), today="", budget=DAILY_BUDGET, owner_busy=False,
           limit=TICK_LIMIT, marks_ok=True, node_ok=True, stop_words=""):
    """Что взять СЕЙЧАС. → (к постановке [(блок, текст)], отложенные [(ключ, причина)]).

    ПОРЯДОК ЗАМКОВ — ЭТО ПОРЯДОК ИХ ЦЕНЫ, от самого дешёвого «не знаю» к самому
    дорогому «нельзя»:

    1. **узел не прочитан** → не берём НИЧЕГО и говорим «неизвестно». Молчание
       источника пустотой не является: пустой ящик и недоступный ящик — разные
       новости, и путать их значит брать решение на незнании;
    2. **работа владельца в очереди** → ни одной. Прямой замок задания, судит
       ``_is_owner_work`` демона;
    3. **СИГНАЛЬНАЯ ОСТАНОВКА** (:mod:`shtab_box_signals`, 02.09.2026) → ни одной,
       и причина едет СЛОВАМИ. Разбор ниже;
    4. **корпус маркеров неполон** → день ИСЧЕРПАН, и сказано это ДРУГИМИ
       словами, чем исчерпанный бюджет: «сверить нечем» — поломка моста, которая
       сама не пройдёт, а «бюджет кончился» — норма, за которой не идут смотреть;
    5. **уже брали** (ключ в маркерах живой очереди) → никогда больше;
    6. **ворота приёма** (:func:`check`) → отказ с названной причиной;
    7. **бюджет суток** и **лимит витка** → отложено до завтра / до следующего.

    Замок владельца стои́т ВЫШЕ ворот приёма СОЗНАТЕЛЬНО: пока полоса занята
    человеком, она не обязана даже разбирать чужой ящик — а разобрав, записала бы
    отказы в лог, которых владелец не просил.

    ═══ ПОЧЕМУ СИГНАЛЫ ПРИЕЗЖАЮТ ГОТОВОЙ ФРАЗОЙ, А НЕ СЧИТАЮТСЯ ЗДЕСЬ ═══════════

    ``stop_words`` — уже собранная фраза остановки
    (:func:`shtab_box_signals.stop_words`); непустая значит «стоп», и текст её
    едет причиной каждому блоку. Импорта сигналов здесь НЕТ и быть не может:
    сигналы спрашивают судью о закрытиях через :mod:`contour_digest`, а тот
    импортирует ЭТОТ модуль — импорт в обратную сторону замкнул бы кольцо.

    Но дело не только в кольце. Правило «сработал ли сигнал» обязано иметь ОДНОГО
    владельца. Проверяй мы здесь поля сигналов заново (``on`` и ``released`` и
    ``enforced``), у полосы завелось бы второе мнение о том, что такое
    сработавший сигнал, — и разошлось бы оно с первым молча, ровно как разошлись
    бы два счёта суточного потолка. Поэтому здесь ровно один вопрос: фраза пуста
    или нет.

    ЧТО ЭТО НЕ ОСЛАБЛЯЕТ. Ни одного прежнего замка ветка не трогает: она стои́т
    СВЕРХ них и умеет только НЕ БРАТЬ. Пустая фраза возвращает поведение,
    байт-в-байт равное прежнему, — это держит тест, а не обещание здесь.
    """
    blocks = list(blocks or [])
    held = []
    if not node_ok:
        return [], [("", "узел-ящик не прочитан — что в нём лежит, НЕИЗВЕСТНО; "
                         "не берём ничего (пустой ящик и недоступный — разные новости)")]
    if owner_busy:
        return [], [(str(b.get("key") or ""),
                     "в очереди есть задача владельца — заданий Штаба не берём ни одного")
                    for b in blocks]
    stop = str(stop_words or "").strip()
    if stop:
        return [], [(str(b.get("key") or ""), stop) for b in blocks]
    seen = {k for _d, k in (task_marks or ())}
    left = budget_left(task_marks, today, budget, marks_ok)
    take = []
    for blk in blocks:
        key = str(blk.get("key") or "")
        if key in seen:
            held.append((key, "уже брали — маркер этого ключа стои́т в очереди"))
            continue
        ok, reason, why = check(blk)
        if not ok:
            held.append((key, "НЕ ПРИНЯТ (%s): %s" % (reason, why)))
            continue
        if left <= 0:
            held.append((key, ("корпус маркеров очереди не прочитан — сколько взято сегодня, "
                               "НЕИЗВЕСТНО; день считаем исчерпанным") if not marks_ok
                         else "суточный потолок исчерпан (%d задачи от Штаба)" % int(budget)))
            continue
        if limit is not None and len(take) >= int(limit):
            held.append((key, "не больше %d за виток — возьмём следующим" % int(limit)))
            continue
        text = task_text(blk, today)
        if not text:
            held.append((key, "текст ряда не собрался — не ставим вовсе"))
            continue
        take.append((blk, text))
        seen.add(key)
        left -= 1
    return take, held


