def doc_name(key):
    """Ключ → ИМЯ ДОКУМЕНТА, которым Штаб называет задание. → str.

    Одно место, где префикс склеивается с ключом. Штаб читает это имя из отказа
    ворот и из строки остановки — набери мы его вторым литералом, отказ учил бы
    называть документ иначе, чем ящик его ищет.
    """
    return "%s%s" % (TASK_PREFIX, str(key or ""))


def revoked_name(name):
    """Имя документа → (снято ли Штабом, имя без метки). → (bool, str).

    Метка ищется РОВНО В ХВОСТЕ и отделена одним из :data:`REVOKE_SEPS`. Регистр
    не важен (``.СНЯТО`` и ``.снято`` — одно и то же), но слово обязано стоять
    целиком: документ ``shtab_task_snyatokrytiya`` снятым НЕ является, и кириллица
    метки против латиницы ключа это и гарантирует.
    """
    raw = str(name or "").rstrip()
    low, mark = raw.casefold(), REVOKE_MARK.casefold()
    for sep in REVOKE_SEPS:
        tail = "%s%s" % (sep, mark)
        if low.endswith(tail) and len(raw) > len(tail):
            return True, raw[:-len(tail)].rstrip()
    return False, raw


def parse_folder(files, prefix=None):
    """Дети папки → (документы-кандидаты, отказы разбора).

    Документ — ``{"key","name","id","revoked"}``; отказ — ``{"key","name","why"}``.
    Оба списка отдаются ВСЕГДА и по той же причине, что у :func:`parse_node`: молча
    выброшенный документ читается как «Штаб ничего не клал».

    ОТБОР ПО ПРЕФИКСУ ДЕЛАЕТСЯ ЗДЕСЬ ЗАНОВО, хотя мост уже умеет отбирать сам, и
    это не дубль правила, а его ЕДИНСТВЕННЫЙ владелец. Отбор моста — параметр
    запроса: он экономит трафик и может быть не передан, передан не тем, или
    когда-нибудь смениться на той стороне. Решает, что считать заданием, ВСЕГДА эта
    строка — и проверить её можно без моста вовсе.

    ПОРЯДОК НАЗНАЧЕН ЯВНО: ПО ИМЕНИ ДОКУМЕНТА, ПО ВОЗРАСТАНИЮ КОДОВЫХ ТОЧЕК.
    Обоснование — четыре пункта, и ни один из них не «так удобнее»:

    1. **Имя — единственное, что Штаб видит и чем управляет.** Хочет очерёдности —
       называет ``shtab_task_01_…`` и ``shtab_task_02_…``; никакого скрытого поля,
       по которому «почему-то взяли не то», в этом порядке нет.
    2. **Имя И ЕСТЬ ключ.** По нему же идут дедуп, маркер очереди и строка журнала.
       Сортируй мы по чему-то другому, «первый» решался бы полем, которого в
       маркере не видно, — и объяснить выбор задним числом было бы нечем.
    3. **Времени у нас нет ВООБЩЕ.** Замер 03.09: ответ моста даёт у файла ровно
       три поля — ``id``, ``mime``, ``name``. Ни создания, ни правки; порядок «по
       времени» потребовал бы отдельного похода в мост за каждым документом.
    4. **Порядок обязан быть ОДИНАКОВ НА ДВУХ ВИТКАХ ПОДРЯД.** Правка документа
       Штабом сдвинула бы время и молча переставила очередь; имя не меняется само.

    СОРТИРУЕМ САМИ, ХОТЯ МОСТ УЖЕ ОТСОРТИРОВАЛ. Причина измерена: при
    ``truncated=True`` мост сортирует УЖЕ ОБРЕЗАННЫЙ произвольный кусок (замер
    03.09, ``limit=3`` на 49 файлах — вернулись не три первых по алфавиту). Порядок
    оттуда выглядит началом, началом не являясь. Своя сортировка этого не чинит —
    усечение судит вызывающий, — но она делает «первый» вопросом, на который
    отвечает код, который можно прогнать тестом.

    ДВОЙНИКИ ПО КЛЮЧУ ОТКАЗЫВАЮТ ОБА, и в папке это не теория: Drive разрешает
    двум файлам одно имя, а кроме того ключ повторяется парой ``shtab_task_x`` +
    ``shtab_task_x.СНЯТО``. Ключ — имя задачи для дедупа: взяв одного из двойников,
    полоса пометила бы выполненным и второго, а он другой. СНЯТЫЕ СЧИТАЮТСЯ НАРАВНЕ
    со взятыми — иначе «снял и положил заново под тем же ключом» проехало бы как
    новая задача, а маркер очереди у неё был бы старый.
    """
    pref = TASK_PREFIX if prefix is None else str(prefix)
    docs, bad = [], []
    for row in (files or ()):
        row = row if isinstance(row, dict) else {}
        name = str(row.get("name") or "")
        if not name.startswith(pref):
            continue
        gone, clean = revoked_name(name)
        key = clean[len(pref):].strip()
        if not key:
            bad.append({"key": name, "name": name, "id": str(row.get("id") or ""),
                        "why": "имя состоит из одного префикса — ключа в нём нет вовсе"})
            continue
        docs.append({"key": key, "name": name, "id": str(row.get("id") or ""),
                     "revoked": gone})
    docs.sort(key=lambda d: d["name"])
    seen = {}
    for doc in docs:
        seen[doc["key"]] = seen.get(doc["key"], 0) + 1
    out = []
    for doc in docs:
        if seen[doc["key"]] > 1:
            bad.append({"key": doc["key"], "name": doc["name"], "id": doc["id"],
                        "why": "ключ %r несут %d документа папки — двойники не берём ни один "
                               "(ключ и есть имя задачи для дедупа)"
                               % (doc["key"], seen[doc["key"]])})
            continue
        if not doc["id"]:
            bad.append({"key": doc["key"], "name": doc["name"], "id": "",
                        "why": "у документа нет file id — читать его нечем "
                               "(по имени такой документ мост не отдаёт)"})
            continue
        out.append(doc)
    return out, bad


