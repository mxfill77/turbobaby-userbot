def task_text(block, day):
    """Принятый блок + день → ТЕКСТ РЯДА ОЧЕРЕДИ. → str | ``None``.

    ``None`` — ворота не пропустили: собирать текст непринятому блоку нельзя, иначе
    отказ существовал бы только в логе, а задача всё равно уехала бы в очередь.

    ЧУЖОГО ТЕКСТА МЫ НЕ ТРОГАЕМ НИ СИМВОЛОМ. Тело блока едет ДОСЛОВНО: правка
    чужого задания «для красоты» — это редактирование постановки без ведома
    постановщика, и заметить её было бы нечем. Наше здесь ровно две строки —
    маркер (по нему узнают ряд) и одна строка происхождения (по ней владелец
    понимает, откуда взялась задача, не читая кода).
    """
    ok, _reason, _why = check(block)
    if not ok:
        return None
    day = str(day or "")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", day):
        return None
    # ПЕРВАЯ СТРОКА НЕ МЕНЯЛАСЬ ПЕРЕЕЗДОМ 03.09 НИ СИМВОЛОМ, и это условие, а не
    # совпадение: маркер читают трое (дедуп, суточный счёт, сводка контура), и все
    # трое живут на другом конце — в очереди. Смени мы форму маркера вместе с
    # источником, дедуп перестал бы узнавать вчерашние задания и полоса взяла бы
    # их заново — молча, потому что «ключа нет в маркерах» и «маркеров не стало»
    # выглядят одинаково.
    return "\n".join([
        "%s дата=%s ключ=%s] %s" % (MARK, day, block["key"], HEAD_WORDS),
        # ВТОРАЯ СТРОКА НАЗЫВАЕТ ПОЛОСУ И ТО, КТО ЕЁ ВЫБРАЛ. До 03.09 здесь стояло
        # «взято полосой ПК автоматически» — правда ровно потому, что другой полосы
        # не бывало. Теперь бывает, и «на какой машине это исполнится» обязано быть
        # видно из САМОГО РЯДА: строку читает человек, открывший очередь, а не код.
        "Источник: документ %s папки мозга (file id %s); ставит ящик заданий Штаба с полосы ПК, "
        "исполняет %s."
        % (str(block.get("name") or doc_name(block["key"])), str(block.get("id") or "?"),
           lane_words(lane_of(block))),
        "Владелец задачу НЕ пересылал; карточки, ворота и гард работают как обычно.",
        "",
        str(block.get("body") or "").strip(),
    ])


