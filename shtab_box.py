def prohibitions_named(body):
    """Стандартный блок запретов назван? → (bool, [неназванные темы]).

    Смотрит ТЕМЫ, а не дословность (обоснование — у :data:`REQUIRED`). Регистр не
    важен: Штаб пишет и капслоком, и строчными.
    """
    hay = str(body or "").casefold()
    missing = [name for name, words in REQUIRED
               if not any(w.casefold() in hay for w in words)]
    return (not missing), missing


def read_lane(body):
    """Тело задания → ПОЛОСА ИСПОЛНЕНИЯ. → dict(lane, named, ok, why, raw).

    ТРИ ИСХОДА, И ТРЕТИЙ НЕ ПРИТВОРЯЕТСЯ ПЕРВЫМ:

    * **названа и опознана** — ``ok=True, named=True``, полоса машинным именем;
    * **не названа** — ``ok=True, named=False``, полоса :data:`LANE_DEFAULT`, и
      причина СЛОВАМИ. Дефолт обязан быть СКАЗАН, а не подразумеваться: строку
      «взято на полосу ПК» владелец читает одинаково и когда Штаб её выбрал, и
      когда за него выбрали мы, — а это разные новости;
    * **названа, но неопознана ИЛИ названа по-разному** — ``ok=False``, и задание
      не берётся ВОВСЕ. Молчаливого «поставлю куда-нибудь» здесь нет ни одной
      ветки: неизвестное имя полосы — это указание Штаба, которого мы не поняли,
      и исполнить его наугад хуже, чем не исполнить.

    ПОЧЕМУ РАЗНЫЕ ИМЕНА ОТКАЗЫВАЮТ ОБА, А НЕ «ПЕРВОЕ ПОБЕЖДАЕТ». Это тот же урок,
    что у двойников ключа в :func:`parse_folder`, и у него есть свой живой класс:
    канон рамки прямо запрещает ЦИТИРОВАТЬ форму маркера в прозе задания, потому
    что разбор принимает цитату за указание. Задание ПРО полосы (вроде этого)
    цитату содержит почти наверняка. «Первое побеждает» дало бы тихий промах —
    поехали бы по цитате; несогласие двух имён даёт громкий отказ.
    """
    found = [m.group(1).strip(LANE_TRIM) for m in LANE_RE.finditer(str(body or ""))]
    found = [w for w in found if w]
    if not found:
        return {"lane": LANE_DEFAULT, "named": False, "ok": True, "raw": "",
                "why": "полоса заданием не названа — по умолчанию %s (сменить: строка «%s» в теле)"
                       % (LANE_HUMAN[LANE_DEFAULT], LANE_LINE)}
    unknown = [w for w in found if w.casefold() not in LANE_WORDS]
    if unknown:
        return {"lane": "", "named": True, "ok": False, "raw": unknown[0],
                "why": "полоса названа неизвестным именем %r — куда ставить, НЕИЗВЕСТНО, "
                       "и задание не берём вовсе. Форма одна: %s" % (unknown[0], LANE_FORM)}
    lanes = sorted({LANE_WORDS[w.casefold()] for w in found})
    if len(lanes) > 1:
        return {"lane": "", "named": True, "ok": False, "raw": ", ".join(found),
                "why": "полоса названа %d раза и по-разному (%s → %s) — какая из них настоящая, "
                       "НЕИЗВЕСТНО, и задание не берём вовсе. Форму указания полосы в прозе "
                       "задания НЕ цитировать: разбор принимает цитату за указание"
                       % (len(found), ", ".join(found), ", ".join(lanes))}
    return {"lane": lanes[0], "named": True, "ok": True, "raw": found[0],
            "why": "полоса названа заданием: %s" % LANE_HUMAN[lanes[0]]}


def lane_of(block):
    """Блок → dict :func:`read_lane` по его телу. Одна дорога к полосе, не две."""
    block = block if isinstance(block, dict) else {}
    return read_lane(block.get("body"))


def lane_words(lane):
    """Полоса + признак «названа ли» → слова для лога. → str.

    Живёт здесь, а не в руках, ровно потому, что строку про дефолт печатают ДВОЕ
    (строка-индекс журнала и отчёт оборота), и два её экземпляра разъехались бы
    молча — тот же класс, которым живёт весь модуль.
    """
    ln = lane if isinstance(lane, dict) else {"lane": str(lane or LANE_DEFAULT), "named": True}
    raw = str(ln.get("lane") or "?")
    name = LANE_HUMAN.get(raw, raw)
    return ("полоса %s (названа заданием)" % name if ln.get("named")
            else "полоса %s (по умолчанию: заданием полоса не названа)" % name)


def check(block):
    """Блок → (принят, машинная причина, слова человеку).

    Порядок ворот выбран, а не случаен: сначала то, без чего блока нет вовсе
    (пустое тело, переросшее тело), потом ЗАПРЕТЫ, и только последним АДРЕС. Так
    причина отказа называет ПЕРВУЮ настоящую нехватку, а не последнюю по счёту:
    «адрес не назван» у пустого блока было бы правдой и бесполезностью сразу.
    """
    block = block if isinstance(block, dict) else {}
    key = str(block.get("key") or "")
    body = str(block.get("body") or "").strip()
    if not KEY_RE.match(key):
        return False, "bad_key", "ключ %r не по форме (латиница, цифры, . _ -, 3–64)" % key
    if not body:
        return False, "empty", "тело блока пустое — брать нечего"
    if len(body) > BODY_MAX:
        return False, "too_long", ("тело блока %d символов при потолке %d — строка очереди "
                                   "носит его целиком, а длинное режется с хвоста"
                                   % (len(body), BODY_MAX))
    ok, missing = prohibitions_named(body)
    if not ok:
        return False, "no_prohibitions", ("в блоке не названы запреты: %s. Стандартный блок "
                                          "обязателен ЦЕЛИКОМ — образец в shtab_box.PROHIBITIONS"
                                          % ", ".join(missing))
    # СПРАШИВАЕМ САМОГО СУДЬЮ. Не «нашу регулярку той же формы» — именно его
    # функцию: ворота, принимающие форму, которую судья не читает, ставят задачу,
    # закрыть которую доказанной нельзя ни при каком исполнении (замер 02.09 —
    # пересечение прежних двух форм было ПУСТО, см. шапку).
    addr = done_judge_pc.read_address(body)
    if not addr:
        return False, "no_address", ("адрес результата не назван формой, которую читает судья "
                                     "закрытия. Форма одна: %s" % ADDRESS_FORM)
    # ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ВОПРОСА. Судья отвергает адрес без слов дословно
    # («доказывать таким адресом нечего»), и ворота обязаны отвергнуть его здесь —
    # иначе блок брался бы ради закрытия, которое заведомо не состоится.
    if not addr.get("words"):
        return False, "no_address", ("адрес назван без слов: доказывать таким адресом нечего "
                                     "(судья закрытия отвергнет его теми же словами). Форма "
                                     "одна: %s" % ADDRESS_FORM)
    # ПОЛОСА — ПОСЛЕДНИМИ ВОРОТАМИ, и порядок здесь тот же, что у всех прочих: без
    # запретов и без адреса блока нет вовсе, а неопознанная полоса — это ЦЕЛЫЙ блок
    # с непонятым указанием. Отказ ворот, а не отдельная ветка отбора, — сознательно:
    # так неизвестная полоса видна в `--status` там же, где остальные отказы, и по ней
    # можно поправить документ, не читая кода.
    lane = read_lane(body)
    if not lane["ok"]:
        return False, "bad_lane", lane["why"]
    return True, "", ""


