def markers(items):
    """Ряды очереди → пары «дата, ключ» уже взятого. → list.

    СЧЁТ ВЕДЁТ ЧУЖОЕ УСТРОЙСТВО (:func:`recon_auto.markers`), и это не экономия
    строк. У полосы ОДИН механизм «маркер в task_text → живая очередь → суточный
    потолок», выучивший на своей шкуре, что считать надо и по ЗАКРЫТЫМ рядам
    тоже (ступень E, 01.09: пять разведок за одни сутки при потолке 2 — каждая
    закрывалась и освобождала место следующей). Второй экземпляр того же счёта
    разошёлся бы с первым молча; наше здесь — только своя регулярка.
    """
    return recon_auto.markers(items, rx=MARK_RE)


def budget_left(marks, today, budget=DAILY_BUDGET, marks_ok=True):
    """Сколько ещё можно взять СЕГОДНЯ. → int ≥ 0.

    Тот же :func:`recon_auto.budget_left` и тот же ТРЕТИЙ ИСХОД: корпус маркеров
    прочитан не весь → день ИСЧЕРПАН, а не пуст. Пустой список маркеров при
    упавшем чтении неотличим от пустого при честном нуле, поэтому различает их
    отдельный признак, а не длина списка.
    """
    return recon_auto.budget_left(marks, today, budget, marks_ok)


def taken_today(rows, day):
    """Сколько заданий Штаба взято за названный день. → int.

    Считает по ТЕМ ЖЕ маркерам, что и потолок: у сводки и у замка обязан быть
    ОДИН источник числа, иначе владелец увидит в сводке одно, а полоса будет
    держать другое. ``rows`` — ряды с полем ``task_text`` (для слепка очереди его
    роль играет ``goal``: маркер стои́т первой строкой и в 90 символов слепка
    помещается целиком).
    """
    return sum(1 for d, _k in markers(rows) if d == str(day or ""))


