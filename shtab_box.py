def parse_node(text):
    """Текст узла-ящика → (блоки, отказы разбора).

    Блок — ``{"key":…, "body":…, "line":…}``; отказ — ``{"key":…, "why":…}``.
    Оба списка отдаются ВСЕГДА: молча пропущенный битый блок читается как «Штаб
    ничего не клал», и это ровно та разница, из-за которой ящик выглядел бы
    пустым при полном узле.

    ЧТО СЧИТАЕТСЯ ОТКАЗОМ РАЗБОРА (не путать с отказом ВОРОТ — тот в :func:`check`):

    * блок открыт и не закрыт — возможно, узел обрезан или Штаб не дописал;
    * ключ закрытия не совпал с ключом открытия — границы блоков разъехались;
    * внутри блока встретилось открытие следующего — предыдущий не закрыт;
    * закрытие без открытия — мусор, и о нём надо сказать, а не проглотить;
    * ДВА БЛОКА С ОДНИМ КЛЮЧОМ — отказывают ОБА. Ключ и есть имя, которым дедуп
      отличает задачи друг от друга: взяв один из двойников, полоса пометила бы
      выполненным и второй, а он другой.
    """
    lines = str(text or "").splitlines()
    blocks, bad = [], []
    key, start, body = "", 0, []
    for i, raw in enumerate(lines, 1):
        opened = OPEN_RE.match(raw)
        closed = CLOSE_RE.match(raw)
        if opened:
            if key:
                bad.append({"key": key, "line": start,
                            "why": "блок не закрыт: на строке %d открылся следующий" % i})
            key, start, body = opened.group(1), i, []
            continue
        if closed:
            if not key:
                bad.append({"key": closed.group(1), "line": i,
                            "why": "закрытие без открытия — границы блоков разъехались"})
                continue
            if closed.group(1) != key:
                bad.append({"key": key, "line": start,
                            "why": "ключ закрытия %r не совпал с ключом открытия"
                                   % closed.group(1)})
                key = ""
                continue
            blocks.append({"key": key, "body": "\n".join(body).strip(), "line": start})
            key = ""
            continue
        if key:
            body.append(raw)
    if key:
        bad.append({"key": key, "line": start,
                    "why": "блок не закрыт до конца узла — возможно, он обрезан"})
    seen = {}
    for blk in blocks:
        seen[blk["key"]] = seen.get(blk["key"], 0) + 1
    out = []
    for blk in blocks:
        if seen[blk["key"]] > 1:
            bad.append({"key": blk["key"], "line": blk["line"],
                        "why": "ключ встретился в узле %d раза — двойники не берём ни один"
                               % seen[blk["key"]]})
            continue
        out.append(blk)
    return out, bad


# ═════════════════════════ ВОРОТА ═══════════════════════════════════════════


def prohibitions_named(body):
    """Стандартный блок запретов назван? → (bool, [неназванные темы]).

    Смотрит ТЕМЫ, а не дословность (обоснование — у :data:`REQUIRED`). Регистр не
    важен: Штаб пишет и капслоком, и строчными.
    """
    hay = str(body or "").casefold()
    missing = [name for name, words in REQUIRED
               if not any(w.casefold() in hay for w in words)]
    return (not missing), missing


def check(block):
    """Блок → (принят, машинная причина, слова человеку).

    Порядок ворот выбран, а не случаен: сначала то, без чего блока нет вовсе
    (пустое тело, переросшее тело), потом ЗАПРЕТЫ, и только последним АДРЕС. Так
    причина отказа называет ПЕРВУЮ настоящую нехватку, а не последнюю по счёту:
    «адрес не назван» у пустого блока было бы правдой и бесполезностью сразу.
    """
    block = block if isinstance(block, dict) else {}
    key = str(block.get("key") or "")
    body = str(block.get("body") or "").strip()
    if not KEY_RE.match(key):
        return False, "bad_key", "ключ %r не по форме (латиница, цифры, . _ -, 3–64)" % key
    if not body:
        return False, "empty", "тело блока пустое — брать нечего"
    if len(body) > BODY_MAX:
        return False, "too_long", ("тело блока %d символов при потолке %d — строка очереди "
                                   "носит его целиком, а длинное режется с хвоста"
                                   % (len(body), BODY_MAX))
    ok, missing = prohibitions_named(body)
    if not ok:
        return False, "no_prohibitions", ("в блоке не названы запреты: %s. Стандартный блок "
                                          "обязателен ЦЕЛИКОМ — образец в shtab_box.PROHIBITIONS"
                                          % ", ".join(missing))
    # СПРАШИВАЕМ САМОГО СУДЬЮ. Не «нашу регулярку той же формы» — именно его
    # функцию: ворота, принимающие форму, которую судья не читает, ставят задачу,
    # закрыть которую доказанной нельзя ни при каком исполнении (замер 02.09 —
    # пересечение прежних двух форм было ПУСТО, см. шапку).
    addr = done_judge_pc.read_address(body)
    if not addr:
        return False, "no_address", ("адрес результата не назван формой, которую читает судья "
                                     "закрытия. Форма одна: %s" % ADDRESS_FORM)
    # ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ВОПРОСА. Судья отвергает адрес без слов дословно
    # («доказывать таким адресом нечего»), и ворота обязаны отвергнуть его здесь —
    # иначе блок брался бы ради закрытия, которое заведомо не состоится.
    if not addr.get("words"):
        return False, "no_address", ("адрес назван без слов: доказывать таким адресом нечего "
                                     "(судья закрытия отвергнет его теми же словами). Форма "
                                     "одна: %s" % ADDRESS_FORM)
    return True, "", ""


# ═════════════════════════ ТЕКСТ ЗАДАЧИ ══════════════════════════════════════


def task_text(block, day):
    """Принятый блок + день → ТЕКСТ РЯДА ОЧЕРЕДИ. → str | ``None``.

    ``None`` — ворота не пропустили: собирать текст непринятому блоку нельзя, иначе
    отказ существовал бы только в логе, а задача всё равно уехала бы в очередь.

    ЧУЖОГО ТЕКСТА МЫ НЕ ТРОГАЕМ НИ СИМВОЛОМ. Тело блока едет ДОСЛОВНО: правка
    чужого задания «для красоты» — это редактирование постановки без ведома
    постановщика, и заметить её было бы нечем. Наше здесь ровно две строки —
    маркер (по нему узнают ряд) и одна строка происхождения (по ней владелец
    понимает, откуда взялась задача, не читая кода).
    """
    ok, _reason, _why = check(block)
    if not ok:
        return None
    day = str(day or "")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", day):
        return None
    return "\n".join([
        "%s дата=%s ключ=%s] %s" % (MARK, day, block["key"], HEAD_WORDS),
        "Источник: узел мозга %s, взято полосой ПК автоматически (ящик заданий Штаба)."
        % NODE_NAME,
        "Владелец задачу НЕ пересылал; карточки, ворота и гард работают как обычно.",
        "",
        str(block.get("body") or "").strip(),
    ])


