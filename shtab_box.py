# ═════════════════════════ ФОРМАТ БЛОКА ══════════════════════════════════════
# БЛОКИ ИДУТ ПОДРЯД, У КАЖДОГО СВОЙ КЛЮЧ. Всё, что лежит между блоками (шапка
# узла, заметки Штаба, пустые строки), разбором игнорируется — узел остаётся
# человеческим документом, а не машинным файлом.
#
#     [[ЗАДАЧА ключ=<ключ>]]
#     <тело задания: цель · ЗАПРЕТЫ · признак сделанности · [result_ref: …]>
#     [[КОНЕЦ ключ=<ключ>]]
#
# ЗАКРЫВАЮЩАЯ СТРОКА ОБЯЗАТЕЛЬНА, И ЭТО НЕ ЦЕРЕМОНИЯ. Без неё «блок» и «хвост
# узла, который Штаб не дописал» неотличимы: недописанный блок взялся бы как
# готовый, а обрезанное задание — ровно тот случай, когда обрежется вопрос, а не
# защита. Незакрытый блок отказывается с названной причиной.
# РАЗБОР ГРАНИЦ НАМЕРЕННО ШИРЕ, ЧЕМ ФОРМА КЛЮЧА, и это не небрежность, а прямое
# следствие правила «молча пропущенный блок читается как пустой ящик». Признай
# границу блока только у ПРАВИЛЬНОГО ключа — и блок с кривым ключом перестал бы
# существовать вовсе: ни задачи, ни отказа, ни строки в логе, а у Штаба на экране
# лежит задание, которое «почему-то не берут». Поэтому границу ловим по любому
# непробельному ключу, а форму ключа судят ВОРОТА (:func:`check`) и говорят
# причину словами.
OPEN_RE = re.compile(r"^\s*\[\[\s*ЗАДАЧА\s+ключ=([^\s\]]{1,120})\s*\]\]\s*$")
CLOSE_RE = re.compile(r"^\s*\[\[\s*КОНЕЦ\s+ключ=([^\s\]]{1,120})\s*\]\]\s*$")

# КЛЮЧ — ЛАТИНИЦА, ЦИФРЫ, ТОЧКА, ДЕФИС, ПОДЧЁРК, ОТ ТРЁХ СИМВОЛОВ. Кириллицы в
# ключе нет намеренно: ключ едет в МАРКЕР ОЧЕРЕДИ и сверяется регуляркой на
# другом конце — визуально одинаковые «с» латинская и «с» кириллическая дали бы
# два разных ключа у одного блока, то есть дедуп, промахивающийся молча. Пол в
# три символа — оттуда же: ключ есть ИМЯ задачи, и однобуквенное имя слишком
# дёшево повторить по невнимательности, а повтор ключа — это молчаливый отказ
# брать НОВОЕ задание (дедуп сочтёт его уже взятым).
#
# ПОТОЛОК КЛЮЧА ПОСЧИТАН, А НЕ ВЫБРАН, и вот бюджет. Слепок очереди хранит первую
# значащую строку ряда, обрезанную по 90 символов с многоточием на 90-м
