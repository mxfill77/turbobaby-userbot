# ─────────────────────────────── ДВА ВЕРДИКТА, И «ДА» СРЕДИ НИХ НЕТ ───────────────────────────
PARK = "park"      # прежний путь байт-в-байт: set_needs_approval, кнопка владельцу
CLOSE = "close"    # ряд закрыт ПРОЧИТАННЫМ продуктом: complete_task(done) + извещение без кнопки

# ─────────────────── ИМЕНА УСЛОВИЙ. Имя уходит в журнал демона и в отчёт ─────────────────────
R_PROVEN = "продукт-прочитан"      # ЕДИНСТВЕННОЕ условие закрытия
R_NOT_GUARD = "источник-не-гард"   # карточка не от файла-маркера гарда — не наш класс вовсе
R_NO_ADDRESS = "адрес-не-назван"   # задача не назвала адреса результата — читать нечего
R_RED_ADDRESS = "адрес-красный"    # адрес назван, а продукт по нему НЕ прочитан → КОНТРФАКТ

ORIGIN_GUARD = "guard"             # зеркало `pc_orchestrator._duty_origin` (сверяется тестом)
UNNAMED = "не назван"              # чем заполняется пустое поле извещения — тишиной оно не станет


def facts(card, origin, proven=False, addressed=False, reason="", chosen="", obj="", kind=""):
    """Факты захода → словарь для `verdict()`. Перевод из мира демона делает вызывающий: сюда
    приходят уже примитивы, и поэтому модулю не нужны ни импорты, ни константы соседей."""
    return {
        "card": str(card or ""),
        "origin": str(origin or ""),
        "proven": bool(proven),        # V0 сказал «сделано» по НАЗВАННОМУ адресу
        "addressed": bool(addressed),  # адрес результата в тексте задачи назван
        "reason": " ".join(str(reason or "").split()),
        "chosen": str(chosen or ""),
        "obj": " ".join(str(obj or "").split()),
        "kind": " ".join(str(kind or "").split()),
    }


def verdict(f):
    """(действие, условие, чем доказано). Три удержания — ПЕРЕД единственным закрытием.

    Порядок не косметический: он идёт от самого широкого сомнения к самому узкому, и каждое
    условие отвечает на свой вопрос — «наш ли это класс», «есть ли что читать», «прочиталось ли».
    """
    f = f if isinstance(f, dict) else {}
    if f.get("origin") != ORIGIN_GUARD:
        # Замок происхождения (`_detect_needs_approval`, 31.07.2026): карточкой считается ТОЛЬКО
        # файл-маркер гарда со своим run_token. Не он — значит перед нами не тот класс, о котором
        # мерена премиса, и трогать такой ряд мы не вправе.
        return PARK, R_NOT_GUARD, "карточка не помечена замком происхождения — это не маркер гарда"
    if not f.get("addressed"):
        # Адреса нет — нет и предмета суда. «Не назван» здесь не мягче и не строже прежнего:
        # ряд идёт владельцу ровно так, как шёл до этой правки.
        return PARK, R_NO_ADDRESS, "адрес результата задачей не назван — читать нечего"
    if not f.get("proven"):
        # ═══ КОНТРФАКТ ═══ Тот же маркер, тот же вход, красный адрес → ряд паркуется и
        # спрашивает владельца. Причина берётся ДОСЛОВНО у судьи адреса: своего суждения о
        # продукте у этого модуля нет ни одной ветки.
        return PARK, R_RED_ADDRESS, (f.get("reason")
                                     or "продукт по названному адресу НЕ прочитан")
    return CLOSE, R_PROVEN, "продукт прочитан по названному адресу: %s · %s" % (
        f.get("chosen") or "(файл не назван судьёй)",
        f.get("reason") or "вердикт судьи адреса")


def decide(card, origin, proven=False, addressed=False, reason="", chosen="", obj="", kind=""):
    """Удобная обёртка «факты → вердикт» (её зовут демон и тесты)."""
    return verdict(facts(card, origin, proven=proven, addressed=addressed, reason=reason,
                         chosen=chosen, obj=obj, kind=kind))


def _named(value):
    """Поле извещения: пусто или прочерк → честное «не назван». Тишины здесь не бывает."""
    v = " ".join(str(value or "").split())
    return UNNAMED if v in ("", "—", "-") else v


def notice(lane, tid, obj="", kind="", chosen=""):
    """ИЗВЕЩЕНИЕ ОБ ОТКАЗЕ ГАРДА — одна строка в тему карточек. Не вопрос: кнопок нет, номера
    для ответа нет, слова «да» нет — отвечать не на что и нечем.

    НАЗЫВАЕТ КЛАСС И ОБЪЕКТ ВСЕГДА. Пустое поле становится «не назван», а не исчезает: молчание
    здесь неотличимо от «отказа не было», и ровно этого запрещено допускать."""
    return ("📣 отказ гарда · %s · задача %s · команда ОТКЛОНЕНА и НЕ выполнена · "
            "класс: %s · объект: %s · ряд закрыт продуктом по адресу: %s · ответа не требует"
            % (lane, tid, _named(kind), _named(obj), _named(chosen)))


def close_result(card, rule, proof, obj="", kind="", draft=""):
    """Терминальный текст ряда, чей исход суждён адресом. Кнопки нет: демон кладёт его в
    `complete_task(done)`.

    ПЕРВЫЙ СИМВОЛ «✅» — НЕ УКРАШЕНИЕ. У полосы первый символ поля `result` читают МАШИНЫ
    (`pc_orchestrator.NO_HEAL_PREFIXES` держит по нему оба гейта самопочинки), и знак успеха
    здесь обязан отличаться от знаков причины провала (⏱/✋/📡). Самопочинку он не зовёт и звать
    не может: она живёт только на `failed`.

    ЧЕРНОВИК ДОКЛАДА ИДЁТ ВЫШЕ КАРТОЧКИ И НИЖЕ ВЕРДИКТА. Причина материальная: stdout исполнителя
    на этой дороге ВЫБРОШЕН (`_run_task_impl` вернул карточку вместо отчёта), и без блока
    черновика владелец прочитал бы вердикт судьи и текст карточки, но не единого слова самого
    захода. Текст карточки сохраняется ДОСЛОВНО и последним: молча из истории ничего не исчезает,
    а режется отчёт с хвоста."""
    parts = [
        "✅ ИСХОД ЗАХОДА СУЖДЁН ПО АДРЕСУ РЕЗУЛЬТАТА, А НЕ МАРКЕРОМ ГАРДА "
        "(кнопки «да» здесь нет намеренно)",
        "Условие: %s. Чем доказано: %s." % (rule, proof),
        "ОТКАЗ ГАРДА ОСТАЁТСЯ В СИЛЕ: команда класса «%s» над объектом «%s» ОТКЛОНЕНА и НЕ "
        "выполнена. Решение гарда не менялось, прав эта запись не добавляет ни одному классу — "
        "снят вопрос о СУДЬБЕ РЯДА, а не запрет на операцию. Нужна сама операция — ставь её "
        "отдельной задачей: когда команду РЕАЛЬНО попробуют, её снова перехватит гард."
        % (_named(kind), _named(obj)),
        "Владельцу ушло ИЗВЕЩЕНИЕ об отказе в тему карточек (ответа не требует).",
    ]
    if draft:
        parts.append(str(draft))
    parts.append("─── ниже ДОСЛОВНО карточка, которая собиралась спросить «да» ───")
    parts.append(str(card or "(текст карточки пуст)"))
    return "\n".join(parts)
