    """Сообщение не несёт наружу лишнего? → list находок стражи (пусто = чисто).

    Проверка ЦЕЛОГО сообщения — второй слой поверх построчного
    (:func:`safe_line`). Первый чинит цитату, этот — отвечает на вопрос «можно ли
    отправлять вообще»: если страж видит что-то и после починки, отправлять
    нельзя, и руки обязаны остановиться с названной причиной.
    """
    return review_send.outbound_violations(text)


