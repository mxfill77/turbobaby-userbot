SCHEMA = "turbobaby.review_audit/v1"

# Первая строка КАЖДОГО сообщения ступени. Не украшение и не вежливость: в теме
# Аудит лежит чужое мнение, и владелец обязан видеть это раньше, чем прочтёт
# само мнение. Зеркало «НЕ ИСПОЛНЯТЬ» ступени 2 и «НЕ ЗАДАЧА» ступени B.
NOT_EXEC_HEAD = "НЕ ИСПОЛНЯТЬ: мнение внешнего канала"

FINDING_HEAD = "🔎 НАХОДКА ВЫСОКОЙ ВАЖНОСТИ"
DIGEST_HEAD = "📋 РЕВЬЮ-КОНТУР ЗА СУТКИ"

# ─────────────────────────── вес находки ───────────────────────────
# Числа ниже — не шкала «важности вообще», а ЦЕНА ЗАДЕРЖКИ показа, и каждое
# стоит на факте, посчитанном раньше и не здесь.
STOP_WEIGHT = 2        # «чего НЕ ДЕЛАТЬ ВОВСЕ»: работа идёт сейчас, задержка стоит ещё одного дня
# СОГЛАСИЕ — ступенька, а не лесенка. Второй источник это качественный скачок:
# ту же находку назвал НЕЗАВИСИМЫЙ пакет (или другой канал), и подтверждение
# стоит ровно столько же, сколько стоп-вид. Третий и последующие не добавляют
# ничего: один канал, повторивший себя в четырёх пакетах, согласием с собой не
# является — иначе многословие перевешивало бы существо.
AGREEMENT_WEIGHT = 2
HIGH_MIN = 2           # порог «высокой»: либо стоп-находка, либо согласие двух источников

# ПОТОЛОК НЕМЕДЛЕННОГО ПОКАЗА — главный замок против потока. Число то же, что у
# бюджета заявок ступени B, и по той же причине: ровно столько находок несёт ОДИН
# ответ канала (хвост пакета задаёт три вопроса). Больше трёх сообщений в сутки —
# это уже лента, которую перестают читать, а перестав читать её, владелец теряет
# и те находки, ради которых всё построено.
IMMEDIATE_BUDGET = 3

# Потолок сообщения Telegram — 4096 знаков; берём с запасом на служебный конверт.
MESSAGE_MAX = 3900
FINDING_LINE_MAX = 300   # «находка одной строкой» — строкой, а не абзацем
TOP_N = 3                # «три самых весомых» в суточной сводке

_RE_SPACE = re.compile(r"\s+")
_RE_ITEM_HEAD = re.compile(r"^\s*\d{1,2}[.)]\s*")
_RE_CUT = re.compile(r"[.;:!?]\s")


class ReviewAuditError(Exception):
    """Отказ ступени D с НАЗВАННОЙ причиной (зеркало ошибок ступеней 2 и B)."""

    def __init__(self, reason, detail=None):
        super().__init__(detail or reason)
        self.reason = reason
        self.detail = detail


# ───────────────────────────── вид находки ─────────────────────────────


def stop_kind():
    """Вид «чего НЕ ДЕЛАТЬ ВОВСЕ» — ВЫВЕДЕННЫЙ, а не набранный литералом. → str.

    Единственный источник правды о видах находок — хвост пакета
    (``review_pack.TAIL_QUESTIONS``), и ступень B уже умеет доставать оттуда
    ярлыки (:func:`review_intake.kind_labels`). Литерал здесь разошёлся бы с
    вопросами на первой их правке, и вес молча поехал бы не на тот вид — то есть
    поток в тему Аудит сменил бы состав, а никто бы не заметил.

    Стоп-вопрос — ВТОРОЙ в хвосте. Порядок вопросов — часть контракта пакета:
    ответ канала приходит «по пунктам 1, 2, 3», и номер пункта у ступени B прямо
    работает видом находки. Хвост короче двух вопросов → стоп-вида нет вовсе, и
    вес стоп-находки не начислится никому (честнее, чем угадать).
    """
    labels = review_intake.kind_labels()
    return labels[1] if len(labels) >= 2 else ""


# ───────────────────────────── вес и отбор ─────────────────────────────


def weight(claim, premise_out):
    """Заявка + исход премисы → ВЕС ПОКАЗА. → dict(score, parts, alive, high).

    Ни одно слагаемое не берётся из чтения текста находки: всё это поля, которые
    посчитала ступень B. Здесь только арифметика — и потому решение
    воспроизводится на тех же фактах кем угодно, включая владельца с калькулятором.

    ``parts`` возвращается вместе со счётом СОЗНАТЕЛЬНО: сообщение показывает
    владельцу, ПОЧЕМУ находка названа высокой, а «доверься весу 3» — не довод.
    """
    claim = claim or {}
    outcome = (premise_out or {}).get("outcome")
    alive = outcome == review_intake.PREMISE_ALIVE
    parts, score = [], 0
    stop = stop_kind()
    if stop and (claim.get("kind") or "") == stop:
        score += STOP_WEIGHT
        parts.append("стоп-находка «%s» (+%d)" % (stop, STOP_WEIGHT))
    count = len(claim.get("sources") or [])
    if count >= 2:
        score += AGREEMENT_WEIGHT
        parts.append("источников %d — согласие независимых пакетов (+%d)"
                     % (count, AGREEMENT_WEIGHT))
    if not parts:
        parts.append("особых признаков нет (+0)")
    return {"score": score, "parts": parts, "alive": alive,
            "premise": outcome, "high": bool(alive and score >= HIGH_MIN)}


def is_high(item):
    """Элемент сборки (заявка + премиса) — находка высокой важности? → bool."""
    return bool(weight((item or {}).get("claim"), (item or {}).get("premise"))["high"])


def rank(items):
    """Заявки → порядок показа: тяжёлые первыми. → list (тот же вид элементов).

    Ключ сортировки полный и детерминированный (вес ↓, число источников ↓, ключ):
    недетерминированный порядок означал бы, что «три самых весомых» меняются от
    прогона к прогону на одном и том же корпусе, и сводка перестала бы быть
    проверяемой.
    """
    def key(item):
        claim = item.get("claim") or {}
        w = weight(claim, item.get("premise"))
        return (-w["score"], -len(claim.get("sources") or []), claim.get("key") or "")

    return sorted([i for i in (items or []) if isinstance(i, dict)], key=key)


def select_immediate(items, *, posted=(), budget=IMMEDIATE_BUDGET, limit=None, held_over=()):
    """Что показать НЕМЕДЛЕННО. → (к показу, отложенные[(item, причина)]).

    ЧЕТЫРЕ причины отсрочки, и каждая названа своим словом, потому что означают
    они разное: ``не высокой важности`` (пойдёт в суточную сводку), ``уже
    показана`` (реестр), ``отложена бутстрапом`` (лоток старше ступени — только
    явным ``--force``) и ``бюджет суток исчерпан`` (политика, вернётся завтра).

    Узнавание «уже показана» идёт ПО НАБОРУ КЛЮЧЕЙ заявки
    (:func:`review_intake.claim_keys`), а не по одному: ключ заявки — это ключ её
    ЯКОРНОЙ записи, и приход второго канала меняет якорь. Тот же урок, что
    поймала регрессом ступень B; повторять его вторым слоем не будем.

    ``held_over`` — ключи, отложенные БУТСТРАПОМ, и без этого входа бутстрап был
    декоративным: он молчит РОВНО ОДИН оборот, а на следующем backlog снова
    становится годным к показу и потёк бы в тему по три в сутки, пока не кончится.
    Это ровно то, ради чего бутстрап заведён, только растянутое на неделю —
    поэтому ключи остатка обязаны спрашиваться, а не просто записываться.

    Порядок проверок НЕ произволен: ``held_over`` стои́т ПОСЛЕ ворот важности,
    чтобы у невысокой заявки осталась её собственная, более точная причина —
    «пойдёт суточной сводкой». Иначе одно слово-остаток съело бы три разных.
    """
    seen = set(posted or ())
    stale = set(held_over or ())
    take, held = [], []
    for item in rank(items):
        claim = item.get("claim") or {}
        keys = review_intake.claim_keys(claim)
        if seen.intersection(keys):
            held.append((item, "уже показана"))
            continue
        if not is_high(item):
            held.append((item, "не высокой важности — пойдёт суточной сводкой"))
            continue
        if stale.intersection(keys):
            held.append((item, "отложена бутстрапом — берётся только явным --force"))
            continue
        if limit is not None and len(take) >= limit:
            held.append((item, "сверх лимита захода"))
            continue
        if len(take) >= max(0, int(budget)):
            held.append((item, "бюджет немедленных суток исчерпан — пойдёт суточной сводкой"))
            continue
        take.append(item)
        seen.update(keys)
    return take, held


# ───────────────────────────── текст находки ─────────────────────────────


def one_line(quote, limit=FINDING_LINE_MAX):
    """Находка ОДНОЙ СТРОКОЙ. → str.

    Режем по границе фразы, а не по букве: обрубок посреди слова читается как
    сбой, и владелец идёт открывать файл ради того, что должно было уместиться в
    строку. Номер пункта («2. ») снимаем — он про место в ответе канала, а вид
    находки в сообщении назван отдельным полем.

    Дословность цитаты этим НЕ нарушается: полный текст всегда лежит файлом и
    назван в сообщении путём, а строка честно кончается многоточием.
    """
    text = _RE_SPACE.sub(" ", str(quote or "")).strip()
    text = _RE_ITEM_HEAD.sub("", text)
    if len(text) <= limit:
        return text
    head = text[:limit]
    cuts = [m.end() for m in _RE_CUT.finditer(head)]
    if cuts and cuts[-1] >= limit // 2:
        return head[:cuts[-1]].strip() + " …"
    space = head.rfind(" ")
    return (head[:space] if space > limit // 2 else head).rstrip() + " …"


def safe_line(text, limit=None, cut=None):
    """Строка чужого текста → (строка, причина замены).

    Цитата приехала ИЗВНЕ, и наружу её выпускает та же стража, что держит
    исходящее ступени 2 (:func:`review_send.outbound_violations`) — один страж на
    полосу, а не второе мнение о том, что считать утечкой.

    Задержанная цитата НЕ ГЛУШИТ сообщение целиком: строку заменяет НАЗВАННАЯ
    пометка, а путь к файлу с полным текстом в сообщении и так есть. Молчание
    здесь было бы хуже — владелец не узнал бы даже, что находка есть.

    СНАЧАЛА СУДИ, ПОТОМ РЕЖЬ (правка 17.09.2026, задание 62-t). Режущая функция
    показа (``cut``) приходит СЮДА, а не зовётся до стража: до правки все три места
    (сводка, витрина, эта ступень) звали ``safe_line(one_line(x, limit))``, и страж
    видел уже укороченную строку. Ключ, разрезанный границей короче своего шаблона,
    не опознаётся — а его голова уезжает наружу. Судят ТРИ формы разом: полный текст
    как пришёл, он же в одну строку (склейка переносов рождает форму, которой в
    сыром тексте не было) и строки показа — прежняя, срезанная ровно как до правки, и
    новая (рез тоже умеет родить форму). Прежняя строка судится намеренно: так ни
    одно задержание до правки не теряется ПО ПОСТРОЕНИЮ. Рез объявляет себя числом
    ``[N из M]`` В ПРЕЖНЕЙ ШИРИНЕ: соседи ждут строку не длиннее ``limit``.

    Форма, которая НАЧИНАЕТСЯ за пределом показа (позиция в строке ≥ ``limit``), строку
    не глушит: показ — префикс склеенного текста не длиннее ``limit``, и ни одного её
    знака наружу не уходит. Без этой оговорки путь в хвосте итога в 4 500 знаков
    гасил бы причину упавшего ряда, которую сводка показывает первыми 50 знаками.
    Форма, видимая только в сыром тексте (склейка её разрушила), глушит всегда.
    """
    full = str(text or "")
    if cut is None:
        whole = plain = line = full
    else:
        whole = cut(full, len(full) + 1)
        plain = line = cut(full, limit)
        if line != whole:
            room = max(1, int(limit) - len(" [%d из %d]" % (int(limit), len(whole))))
            line = cut(full, room)
            line = "%s [%d из %d]" % (line, len(line), len(whole))
    seen = review_send.outbound_violations(whole)
    reach = len(whole) if cut is None else int(limit)
    hits = [h for h in seen if h["pos"] < reach]
    glued = {h["kind"] for h in seen}
    hits.extend(h for h in review_send.outbound_violations(full) if h["kind"] not in glued)
    for form in dict.fromkeys((plain, line)):
        hits.extend(review_send.outbound_violations(form))
    if not hits:
        return line, ""
    kinds = ", ".join(sorted({h["kind"] for h in hits}))
    return ("[строка не показана: страж исходящего задержал форму — %s; "
            "полный текст в файле ответа]" % kinds), kinds


def source_line(claim):
    """Источники заявки → две строки шапки: пакеты и каналы. → (пакеты, каналы).

    Требование дедупа исполняется ЗДЕСЬ и видимо глазом: одна находка из двух
    каналов — ОДНО сообщение, в котором названы ОБА источника. Склейку сделала
    ступень B (:func:`review_intake.merge`), и второго механизма склейки мы не
    заводим: два разных дедупа на одну полосу — это два разных ответа на один
    вопрос.
    """
    sources = (claim or {}).get("sources") or []
    packs = [s.get("pack") or "?" for s in sources]
    channels = sorted({s.get("channel") or "?" for s in sources})
    return "; ".join(packs) or "—", "+".join(channels) or "—"


def artifact_line(claim):
    """Имя артефакта с ПОЛНЫМ текстом находки. → str (пути через «; »).

    Полным текстом владеет файл ответа канала в лотке, а не наше сообщение: в
    сообщение едет строка, в файл — дословный ответ целиком вместе с sha256
    пакета. Источников несколько → путей несколько, и все они названы: заявка,
    у которой проверяем только один источник, — заявка с необъявленной половиной.
    """
    out = []
    for src in (claim or {}).get("sources") or []:
        rel = src.get("answer") or ""
        if rel and rel not in out:
            out.append(rel)
    return "; ".join(out) or "—"


def finding_message(item, today, queue_id=None):
    """Находка высокой важности → сообщение в тему Аудит. → str (≤ MESSAGE_MAX).

    Порядок полей — порядок чтения: «НЕ ИСПОЛНЯТЬ», затем ПАКЕТ, КАНАЛ, ВЕРДИКТ,
    находка ОДНОЙ СТРОКОЙ и имя артефакта с полным текстом. Вердикт несёт вид
    находки И исход премисы вместе: «НЕ ДЕЛАТЬ ВОВСЕ» на протухшей посылке и то
    же самое на живой — разные новости, и различить их владелец обязан раньше,
    чем прочтёт саму находку.

    Строка «почему высокая» стоит в конце и не для красоты: правило отбора должно
    быть видно НА САМОМ СООБЩЕНИИ, иначе спорить с ним можно только чтением кода.
    """
    if not review_intake._RE_DATE.match(str(today or "")):
        raise ReviewAuditError("invalid_date", "today must be YYYY-MM-DD, got %r" % (today,))
    claim = (item or {}).get("claim") or {}
    premise_out = (item or {}).get("premise") or {}
    w = weight(claim, premise_out)
    packs, channels = source_line(claim)
    quote, _why = safe_line(claim.get("quote"), FINDING_LINE_MAX, one_line)
    lines = [
        NOT_EXEC_HEAD,
        "%s · %s · ключ=%s" % (FINDING_HEAD, today, claim.get("key") or "?"),
        "пакет: %s" % packs,
        "канал: %s · источников: %d" % (channels, len(claim.get("sources") or [])),
        "вердикт: %s · премиса %s — %s" % (
            claim.get("kind") or "иное",
            review_intake.PREMISE_TITLE.get(w["premise"], "?"),
            premise_out.get("why") or "причина не названа"),
        "находка: %s" % quote,
        "полный текст: %s" % artifact_line(claim),
    ]
    if queue_id:
        lines.append("заявка очереди: #%s (ждёт твоего решения, ничего не исполняет)" % queue_id)
    lines.append("почему высокая: вес %d — %s" % (w["score"], "; ".join(w["parts"])))
    return "\n".join(lines)[:MESSAGE_MAX]


# ───────────────────────────── суточная сводка ─────────────────────────────


def day_stats(headers, items, day):
    """Шапки файлов лотка + заявки → числа суток. → dict.

    Считаем по ФАЙЛАМ ЛОТКА, а не по находкам: «пакетов ушло» и «ответов
    получено» — это про заходы в каналы, и находки на них не отвечают (отказ
    канала находок не несёт вовсе, а один ответ несёт три).

    Отказ канала — ОТДЕЛЬНОЕ число с разбивкой по причинам, а не «не ответили».
    Живой замер 01.09 говорит, зачем: 14 заходов в Manus дали 10 ``http_400``,
    3 ``accepted_no_answer`` и 1 ``no_credentials`` — три РАЗНЫЕ новости
    (потолок сообщения, канал принял и промолчал, ключа не было), и слитые в одно
    слово они перестают быть новостями.

    День берётся ПОЛЕМ, а не часами: сводка обязана воспроизводиться на тех же
    фактах завтра и послезавтра. Гранулярность источника — КАЛЕНДАРНЫЙ ДЕНЬ
    (в файле ответа стоит ``отправлено: YYYY-MM-DD`` без времени), поэтому окна
    «назад на 24 часа» здесь быть не может, и мы его не изображаем.
    """
    day = str(day or "")
    rows = [h for h in (headers or []) if isinstance(h, dict) and (h.get("send_date") or "") == day]
    answered = [h for h in rows if h.get("outcome") == "answered"]
    refused = [h for h in rows if h.get("outcome") != "answered"]
    reasons = {}
    for h in refused:
        why = h.get("reason") or h.get("outcome") or "причина не названа"
        reasons[why] = reasons.get(why, 0) + 1
    today_items = [i for i in (items or [])
                   if any((s.get("send_date") or "") == day
                          for s in ((i.get("claim") or {}).get("sources") or []))]
    findings = sum(len((i.get("claim") or {}).get("sources") or []) for i in today_items)
    high = [i for i in today_items if is_high(i)]
    return {
        "day": day,
        "attempts": len(rows),
        "packs": len({h.get("pack") or "" for h in rows if h.get("pack")}),
        "answered": len(answered),
        "refused": len(refused),
        "reasons": sorted(reasons.items(), key=lambda kv: (-kv[1], kv[0])),
        "findings": findings,
        "claims": len(today_items),
        "merged": findings - len(today_items),
        "high": len(high),
        "items": today_items,
    }


def _num(value, unknown="неизвестно"):
    """Число или ЧЕСТНОЕ «неизвестно». → str.

    Третий исход обязателен ровно по той же доктрине, что в слое ожиданий: ни
    одна ветка не превращает «проверить не смог» в «проверено и хорошо». Очередь
    не ответила — сводка говорит «неизвестно», а не «ноль»: ноль означал бы, что
    заявок не заводили, и это была бы ложь о работе контура.
    """
    return unknown if value is None else str(value)


def digest_message(stats, day, *, placed=None, placed_ids=(), shown_today=None,
                   top_n=TOP_N, note=""):
    """Числа суток + три самых весомых → СУТОЧНАЯ СВОДКА. → str (≤ MESSAGE_MAX).

    Четыре числа задания стоят первыми и в его же порядке: пакетов ушло, ответов
    получено, заявок заведено, дальше — три самых весомых находки. Пятое число
    добавлено нами и без него сводка врала бы умолчанием: сколько высоких находок
    БЫЛО и сколько из них показано немедленно. Иначе «показали три» неотличимо
    от «их всего три».

    ``placed=None`` означает «очередь не ответила» и печатается словом
    «неизвестно» (:func:`_num`) — см. там, почему не нулём.
    """
    lines = [
        NOT_EXEC_HEAD,
        "%s %s" % (DIGEST_HEAD, day),
        "пакетов ушло: %d (заходов в каналы: %d)" % (stats.get("packs", 0), stats.get("attempts", 0)),
        "ответов получено: %d · отказов каналов: %d%s" % (
            stats.get("answered", 0), stats.get("refused", 0),
            (" (%s)" % ", ".join("%s ×%d" % (why, n) for why, n in stats.get("reasons") or []))
            if stats.get("reasons") else ""),
        "заявок заведено в очередь: %s%s" % (
            _num(placed),
            (" (%s)" % ", ".join("#%s" % i for i in placed_ids)) if placed_ids else ""),
        "находок: %d → заявок после склейки дублей: %d (склеено %d)" % (
            stats.get("findings", 0), stats.get("claims", 0), stats.get("merged", 0)),
        "высокой важности: %d · показано немедленно: %s" % (
            stats.get("high", 0), _num(shown_today)),
        "",
    ]
    top = rank(stats.get("items") or [])[:max(0, int(top_n))]
    if not top:
        lines.append("ТРИ САМЫХ ВЕСОМЫХ: находок за сутки нет.")
    else:
        lines.append("ТРИ САМЫХ ВЕСОМЫХ (вес — правило отбора, а не оценка правоты):")
        for n, item in enumerate(top, 1):
            claim = item.get("claim") or {}
            w = weight(claim, item.get("premise"))
            quote, _why = safe_line(claim.get("quote"), FINDING_LINE_MAX // 2, one_line)
            _packs, channels = source_line(claim)
            lines.append("%d. %s · премиса %s · источников %d · канал %s · вес %d"
                         % (n, claim.get("kind") or "иное",
                            review_intake.PREMISE_TITLE.get(w["premise"], "?"),
                            len(claim.get("sources") or []), channels, w["score"]))
            lines.append("   %s" % quote)
            lines.append("   → %s" % artifact_line(claim))
    lines.append("")
    if note:
        lines.append(note)
    lines.append("Сводка ничего не исполняет и задач не ставит: решение по каждой находке — твоё.")
    return "\n".join(lines)[:MESSAGE_MAX]


