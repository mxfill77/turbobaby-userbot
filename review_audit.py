def shown_keys(registry):
    """Реестр показанного → множество ключей. → set.

    В реестр ложится ВЕСЬ набор ключей заявки, а не один: якорь группы меняется,
    когда та же находка приезжает вторым каналом раньше по порядку, — и дедуп по
    одному ключу промахнулся бы ровно на том случае, ради которого он заведён.
    """
    out = set()
    for row in (registry or {}).values():
        if isinstance(row, dict):
            out.update(row.get("keys") or [])
    return out


def shown_count(registry, day):
    """Сколько находок уже показано НЕМЕДЛЕННО за этот день. → int.

    Бюджет суток считается по реестру, а не по памяти процесса: демон
    перезапускается, а «не больше трёх в сутки» обязано держаться именно после
    рестарта.
    """
    return sum(1 for row in (registry or {}).values()
               if isinstance(row, dict) and (row.get("day") or "") == str(day or ""))


def digest_done(registry, day):
    """Сводка за этот день уже уходила? → bool."""
    return bool((registry or {}).get(str(day or "")))


def index_line(item, kind_word="находка"):
    """Строка-индекс показа для журнала. → str (одна строка).

    Журнал — индекс, а не хранилище тел: сюда идут ключ, вид, исход премисы, вес
    и путь к файлу с полным текстом. Тело живёт файлом лотка, как и было.
    """
    claim = (item or {}).get("claim") or {}
    w = weight(claim, (item or {}).get("premise"))
    return ("ARTIFACT ревью-аудит %s ключ=%s вид=%s премиса=%s вес=%d источников=%d → %s"
            % (kind_word, claim.get("key"), claim.get("kind"),
               review_intake.PREMISE_TITLE.get(w["premise"], "?"), w["score"],
               len(claim.get("sources") or []), artifact_line(claim)))


def digest_index_line(stats, day, placed=None):
    """Строка-индекс суточной сводки для журнала. → str (одна строка)."""
    return ("ARTIFACT ревью-аудит сводка %s: пакетов %d, ответов %d, отказов %d, "
            "находок %d → заявок %d (высоких %d), заявок в очередь %s"
            % (day, stats.get("packs", 0), stats.get("answered", 0), stats.get("refused", 0),
               stats.get("findings", 0), stats.get("claims", 0), stats.get("high", 0),
               _num(placed)))


def previous_day(day):
    """День, за который считается АВТОМАТИЧЕСКАЯ сводка. → 'YYYY-MM-DD'.

    Сутки, которые ещё идут, сводке не подлежат: «пакетов ушло за сегодня» в
    полдень — это не итог, а промежуточный счёт, и завтрашняя правильная цифра
    ему противоречила бы. Поэтому автоматическая сводка всегда про ЗАКОНЧЕННЫЙ
    день, а ручной заход называет день вслух.

    Считаем сами, без ``datetime``: модуль обязан оставаться без часов, а
    ``timedelta`` тянет за собой соблазн спросить «сейчас».
    """
    if not review_intake._RE_DATE.match(str(day or "")):
        raise ReviewAuditError("invalid_date", "day must be YYYY-MM-DD, got %r" % (day,))
    y, m, d = (int(p) for p in day.split("-"))
    if d > 1:
        return "%04d-%02d-%02d" % (y, m, d - 1)
    if m > 1:
        return "%04d-%02d-%02d" % (y, m - 1, _days_in(y, m - 1))
    return "%04d-12-31" % (y - 1)


def _days_in(year, month):
    if month == 2:
        leap = (year % 4 == 0 and year % 100 != 0) or year % 400 == 0
        return 29 if leap else 28
    return 30 if month in (4, 6, 9, 11) else 31


