"""Ступень D внешнего ревью-контура — ПОКАЗ НАХОДОК ВЛАДЕЛЬЦУ В ТЕМЕ АУДИТ.

Ступень A (:mod:`review_auto`) сама находит повод и относит пакет второго мнения
в канал; ступень B (:mod:`review_intake`) превращает находку ответа в ЗАЯВКУ
очереди, ждущую решения человека. Обе кончаются там, куда владелец должен
ПРИЙТИ САМ: лоток ``docs/review_inbox`` — файлы, очередь заявок — карточки. За
01.09 это 42 находки в 32 заявках; прочитать их глазами по файлу — работа на час,
и потому она не делается вовсе. Ступень D добавляет ровно одно звено — находка
ПРИХОДИТ К ВЛАДЕЛЬЦУ САМА, в тему Аудит, — и ни одного звена больше.

СВОДКОЙ, А НЕ ПОТОКОМ — это и есть предмет модуля. Тема, в которую сыплется всё
подряд, перестаёт читаться на второй день, и тогда контур мёртв при живом коде.
Поэтому здесь два РАЗНЫХ канала показа, и разделение между ними — не вкус, а
измеренная цена задержки:

* **немедленно** — только находки ВЫСОКОЙ ВАЖНОСТИ (:func:`weight`,
  :func:`is_high`), потолок :data:`IMMEDIATE_BUDGET` штук в сутки;
* **раз в сутки** — СВОДКА (:func:`digest_message`): сколько пакетов ушло,
  сколько ответов получено, сколько заявок заведено и три самых весомых находки.

Не показанное немедленно НЕ ТЕРЯЕТСЯ: сводка называет его числом, а полный текст
каждой находки всегда лежит файлом в лотке и назван в сообщении путём.

ЧЕТЫРЕ РЕШЕНИЯ, КОТОРЫЕ ЗДЕСЬ ПРИНЯТЫ (и почему именно так):

1. **«Высокая важность» — не оценка текста, а функция УЖЕ ИЗМЕРЕННЫХ полей.**
   Читать находку и решать, важна ли она, значило бы завести здесь второго
   ревьюера — и врать его голосом. Вес складывается из трёх фактов, каждый из
   которых посчитан раньше и не нами: ВИД находки (из хвоста пакета), ИСХОД
   ПРЕМИСЫ (проба по названному адресу, ступень B) и ЧИСЛО ИСТОЧНИКОВ (склейка
   дублей, ступень B).
2. **Премиса — ЖЁСТКИЕ ворота, а не слагаемое.** Находка, стоящая на посылке
   «НЕИЗВЕСТНО» или «ПРОТУХЛА», немедленного решения не требует по построению:
   решать нечего, пока не ясно, о живом ли коде речь. Такие идут в суточную
   сводку, а не в поток. Замер живого корпуса 01.09: 32 заявки, премиса ЖИВА у
   17 — одни ворота срезают почти половину.
3. **Стоп-находка весит больше остальных, и это не вкусовщина.** Пакет
   спрашивает канал о трёх разных вещах (``review_pack.TAIL_QUESTIONS``), и цена
   ЗАДЕРЖКИ у них разная: «чего не делать вовсе» — про работу, которая ИДЁТ
   ПРЯМО СЕЙЧАС, и каждый день молчания стоит ещё одного дня этой работы;
   «упрощаемо» и «переусложнено» — про то, КАК сделано уже стоящее, и до завтра
   не дорожают. Между этими двумя мы порядка НЕ выдумываем: обе весят ноль,
   потому что назвать одну важнее другой нечем.
4. **Согласие двух источников — тоже вес.** Одна и та же находка, приехавшая
   двумя пакетами (или двумя каналами), — это независимое подтверждение, а не
   повтор. Ступень B уже склеила их в одну заявку; здесь склейка становится
   ПРИЧИНОЙ показать её раньше прочих.

ИНВАРИАНТЫ (те же, что у ступеней 1–2, A и B, и по той же причине):

* **Чистота.** Ни сети, ни диска, ни подпроцессов, ни ``getenv``, ни часов.
  «Сегодня», реестр показанного и номера рядов очереди — ПОЛЯ ВХОДА. Держит
  тест ``REVIEW_AUDIT_PURE`` обходом AST.
* **Ничего не выдумывать.** Ни вид находки, ни исход премисы здесь не
  вычисляются заново — они приезжают из ступени B. Стоп-вид ВЫВОДИТСЯ из хвоста
  пакета (:func:`stop_kind`), а не набран литералом: список, набранный руками,
  разошёлся бы с вопросами на первой их правке и молча начал бы врать.
* **Первая строка любого сообщения — «НЕ ИСПОЛНЯТЬ»** (:data:`NOT_EXEC_HEAD`).
  Ровно как первая строка файла ответа на ступени 2 и первая строка заявки на
  ступени B: текст пришёл ИЗВНЕ, и сказать это надо раньше, чем его содержание.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ НИ ОДНОЙ ВЕТКОЙ: не ставит задач, не исполняет
находок, не правит код, не ходит в очередь, не читает файлов и НЕ ЗНАЕТ НОМЕРА
ТЕМЫ — адрес живёт в руках (:mod:`review_audit_run`) и приезжает из настройки
демона, а не из литерала здесь.
"""
from __future__ import annotations

