# -*- coding: utf-8 -*-
"""
decision_waits.py — ОТКРЫТЫЕ РЕШЕНИЯ ВЛАДЕЛЬЦА, КОТОРЫЕ НЕ ТЕРЯЮТСЯ, ПОКА ОН СПИТ (06.09.2026).

ПОВОД (заказ владельца дословно): «если выйдет нужная карточка, а я сплю — можно как-то решить
самостоятельно?». Сегодня нельзя: карточка живёт `APPROVAL_TTL` (2760 с = 46 мин), и ряд очереди
после срока ЗАКРЫВАЕТСЯ насмерть — `process_approval_timeouts` пишет `failed` поверх текста
карточки. В безопасную сторону это исправно: молчание работает как отказ, к ботам не едет ничего.
Теряется ПРОТИВОПОЛОЖНОЕ — повод, который владелец одобрил бы, к утру ответить уже нельзя, и
теряется его внимание: он разбирает десяток карточек, где почти все — повторы одного решения.

ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ И ЧЕГО НЕ ДЕЛАЕТ НИ ОДНОЙ ВЕТКОЙ
  • ДЕРЖИТ открытые поводы (парковка): срок ряда очереди закрывает РЯД, а не ВОПРОС;
  • СВОРАЧИВАЕТ поводы одного класса в ОДНУ сводку с числом и последним поводом;
  • РАЗБИРАЕТ ответ на класс целиком, сверяя СОСТАВ каждого повода с тем, что владелец видел;
  • НИЧЕГО НЕ ПРИМЕНЯЕТ. Здесь нет ни рестарта, ни записи основания, ни сети, ни очереди. Модуль
    возвращает РАЗБОР, применяет — вызывающий, своими прежними гейтами. Это не стиль, а замок:
    предсмертный взгляд задания назван прямо — «накопленные поводы начнут применяться утренним
    „да“ скопом, и владелец одним нажатием выкатит детям то, чего не видел». Пока применение
    физически отсутствует в модуле, скопом применить нечего.

FAIL-CLOSED, И НАПРАВЛЕНИЕ ОДНО. Не смог прочитать хранилище, не смог назвать состав, состав не
совпал, слова владельца нет — во ВСЕХ исходах ответ «не применяем». Ни одна ветка не превращает
«не знаю» в «можно».

ГДЕ ХРАНИМ И ПОЧЕМУ ЗДЕСЬ. Файл `pc_orchestrator.decision_waits.json` в корне репо — рядом с
`client_release.json`/`gate_seen.json`, тем же классом имени (`pc_orchestrator.*.json` уже в
.gitignore, боевое состояние в git не едет). Новой сущности не заводим сознательно: мозг для
этого не годится (повод обязан переживать молчание Моста — ровно в ночь, когда он и нужен), а
очередь Bridge — это то самое место, которое повод и теряет.
"""

import io
import json
import os
import time

REPO = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.join(REPO, "pc_orchestrator.decision_waits.json")

KEEP_CLOSED = 50      # хвост закрытых поводов: след ответа, а не свалка

# ─── ПОРОГ СВЁРТКИ И ЧАСТОТА СВОДКИ: ОБА ЧИСЛА ИЗМЕРЕНЫ, А НЕ НАЗНАЧЕНЫ ───────────────────────
# ПОРОГ = 2. При ОДНОМ открытом поводе сводка — это та же карточка, только через лишний слой:
# владелец теряет кнопку и получает пересказ. Свёртка начинается ровно там, где появляется
# «второй такой же», то есть с числа, при котором слово «повтор» вообще применимо.
#
# ЧАСТОТА = 6 ч на класс. Два независимых замера сошлись на этом числе:
#   • живой темп поводов полосы (боевой `pc_orchestrator.log`): 05.09 ворота отказали 53 раза за
#     сутки = карточка каждые 27 мин. Ночь владельца (23:00–07:00, 8 ч) даёт ≈18 поводов — это и
#     есть «десяток, из которых почти все повторы» из постановки. Окно 6 ч сворачивает ту же ночь
#     в ДВЕ сводки, сутки — в четыре;
#   • 6 ч уже названы числом НА ЭТОЙ ПОЛОСЕ — порог тишины журнала у ожидания О4
#     (`expectations_pc`, замер 13.08: 16 ч 04 мин молчания = 2.67 окна). Берём его, а не своё
#     новое: одна полоса не должна держать два разных представления о том, сколько молчания
#     терпимо, — иначе диагностика поедет по тому числу, которое вспомнили.
# Обе ручки — константы модуля, а не среда: срок, который можно молча укоротить стухшим `.env`,
# перестаёт быть замком (класс #194 этой полосы).
FOLD_MIN = 2
DIGEST_EVERY_SEC = 6 * 3600

# Исходы парковки. Ровно три, и «reshaped» — не украшение: он и есть отказ воскрешать одобрение
# вслепую. Состав изменился → повод НОВЫЙ, счёт с нуля, ответ на прежний к нему не относится.
PARK_NEW, PARK_AGAIN, PARK_RESHAPED = "new", "again", "reshaped"

# Исходы разбора ответа. «applied» здесь значит «РАЗРЕШЕНО применить вызывающему», а не
# «применено»: применяет вызывающий, своими гейтами (см. шапку).
ANS_APPLIED, ANS_CHANGED, ANS_GONE = "applied", "changed", "gone"

# ─── ПОСТОЯННОЕ РЕШЕНИЕ ЗАВОДИТСЯ ТОЛЬКО ЯВНЫМ СЛОВОМ ВЛАДЕЛЬЦА ──────────────────────────────
# Списки ЗАКРЫТЫ нарочно, и догадки здесь запрещены в обе стороны. «Ну наверное не надо»,
# «пока не спрашивай», «отстань» — это НЕ правило: система, которая заводит постоянное молчание
# по настроению фразы, однажды заведёт его само себе. Слово либо в списке, либо правила нет.
RULE_ON_WORDS = ("правило: не спрашивать", "больше не спрашивай про этот класс",
                 "постоянное решение: молчать")
RULE_OFF_WORDS = ("правило: спрашивать снова", "отмени правило", "постоянное решение: отменить")


def _cancel_words():
    """Дословный способ ОТМЕНЫ — та же строка, что уедет и в запись правила, и владельцу.

    ПРАВИЛО БЕЗ ОТМЕНЫ НЕ ЗАВОДИТСЯ. Постоянное молчание, которое нечем снять, — это не решение
    владельца, а потерянный класс: он замолчит, и через неделю никто (включая владельца) не
    вспомнит, каким словом его вернуть."""
    return "«%s»" % RULE_OFF_WORDS[0]


# ------------------------------- хранилище -----------------------------------

def _load(path=None):
    """Хранилище с диска → dict правильной формы. Битый/отсутствующий файл читается как ПУСТОЙ,
    а не роняет вызов: повод, потерянный из-за одной кривой скобки, — худший исход из возможных.
    Ошибку при этом не глотаем в тишину — её видит `_load_err`."""
    try:
        with io.open(path or STORE, "r", encoding="utf-8") as f:
            d = json.load(f)
    except (OSError, ValueError):
        d = {}
    if not isinstance(d, dict):
        d = {}
    for k in ("waits", "rules", "digest"):
        if not isinstance(d.get(k), dict):
            d[k] = {}
    if not isinstance(d.get("closed"), list):
        d["closed"] = []
    return d


def _save(d, path=None):
    """Хранилище на диск. → (True | None, дословная причина). `None`, а не `False`: «записать не
    смог» — это НЕ знание, и наверх обязано доехать «не знаю», а не «не получилось, но всё ок».
    Причина уезжает В САМ ответ владельцу: иначе он видит «повод припаркован» там, где не
    припаркован ничего."""
    try:
        d["closed"] = d.get("closed", [])[-KEEP_CLOSED:]
        tmp = (path or STORE) + ".tmp"
        with io.open(tmp, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=0)
        os.replace(tmp, path or STORE)
        return True, ""
    except (OSError, TypeError, ValueError) as e:
        return None, "%s: %s" % (type(e).__name__, e)


def _now(now=None):
    return time.time() if now is None else float(now)


def shape_of(parts):
    """ОТПЕЧАТОК СОСТАВА повода — дословно то, что владелец видел глазами.

    Не хеш и не дата: подпись читается человеком, потому что она уезжает и в сводку, и в
    объяснение «состав изменился». Перечни сортируем — порядок файлов в диффе меняется сам по
    себе и не является изменением состава. Не перечень → строка как есть."""
    out = []
    for p in (parts if isinstance(parts, (list, tuple)) else [parts]):
        if isinstance(p, (list, tuple, set, frozenset)):
            out.append(",".join(sorted(str(x).strip() for x in p if str(x).strip())))
        else:
            out.append(str(p or "").strip())
    return "|".join(out)


# ------------------------------- парковка повода ------------------------------

def park(cls, key, shape, title, where="", answer_at="", path=None, now=None):
    """ПОВОД НЕ ИСЧЕЗАЕТ: положить открытое решение в парковку. → (исход, запись, причина сбоя).

    Зовётся ТАМ, ГДЕ ПОВОД СЕГОДНЯ УМИРАЕТ, — перед закрытием ряда по сроку. Срок ряда остаётся
    как был и закрывает РЯД (иначе локальная цепь висит открытой, и её не видит ни один сторож —
    забор Честертона у `APPROVAL_TTL` разобран в `pc_orchestrator` :142). Закрывается ряд, а не
    вопрос: вопрос переезжает сюда и живёт, пока владелец не ответит.

    ТРИ ИСХОДА, и третий — главный:
      • `new`      — повода такого не было;
      • `again`    — тот же повод с ТЕМ ЖЕ составом: счётчик и «последний раз», новой записи нет;
      • `reshaped` — тот же класс и ключ, но СОСТАВ ДРУГОЙ. Запись заводится ЗАНОВО, счёт с нуля.
        Это и есть запрет «воскрешать одобрение вслепую»: владелец видел другое, значит и вопрос
        другой, и ответ на прежний к нему не относится."""
    d = _load(path)
    c, k = str(cls or "").strip(), str(key or "").strip()
    if not c or not k:
        return None, None, "повод без класса или без ключа не паркуется (нечем ответить)"
    sh, ts = str(shape or ""), _now(now)
    box = d["waits"].setdefault(c, {})
    rec, old = box.get(k), None
    if isinstance(rec, dict) and rec.get("shape") == sh:
        rec["last"], rec["n"] = ts, (rec.get("n") or 0) + 1
        rec["title"] = str(title or rec.get("title") or "")
        out = PARK_AGAIN
    else:
        old = rec.get("shape") if isinstance(rec, dict) else None
        rec = {"cls": c, "key": k, "shape": sh, "title": str(title or ""),
               "where": str(where or ""), "answer_at": str(answer_at or ""),
               "first": ts, "last": ts, "n": 1, "was": old}
        out = PARK_RESHAPED if old is not None else PARK_NEW
    box[k] = rec
    saved, err = _save(d, path)
    return out, rec, ("" if saved else err)


def open_waits(cls=None, path=None):
    """Открытые поводы списком, старые первыми. Пустой список — честный ответ «решать нечего»."""
    d = _load(path)
    out = []
    for c, box in d["waits"].items():
        if cls and c != cls:
            continue
        out.extend(r for r in box.values() if isinstance(r, dict))
    return sorted(out, key=lambda r: r.get("first") or 0)


def close(cls, keys, why, path=None, now=None):
    """Снять поводы (ответ получен / повод больше не существует). → (сколько снято, причина сбоя).

    Записи не пропадают: они уезжают в хвост `closed` вместе с причиной и временем. Молчаливое
    исчезновение повода неотличимо от потери — ровно от неё этот модуль и заведён."""
    d = _load(path)
    box = d["waits"].get(str(cls or ""), {})
    ts, n = _now(now), 0
    for k in [str(x) for x in (keys if isinstance(keys, (list, tuple, set)) else [keys])]:
        rec = box.pop(k, None)
        if isinstance(rec, dict):
            rec["closed_at"], rec["closed_why"] = ts, str(why or "")
            d["closed"].append(rec)
            n += 1
    saved, err = _save(d, path)
    return n, ("" if saved else err)


# ------------------------------- постоянное решение на класс -------------------

def rule_active(cls, path=None):
    """Стои́т ли постоянное решение владельца по классу. → (стоит?, дословная причина).

    Правило глушит ВОПРОС, а не держит и не применяет ничего: отказы как уходили в ленту, так и
    уходят. Ровно то же разделение, что у заморозки контура (решение владельца 05.09.2026)."""
    r = _load(path)["rules"].get(str(cls or ""))
    if not isinstance(r, dict) or not r.get("on"):
        return False, ""
    return True, ("постоянное решение владельца от %s: про класс «%s» не спрашивать. Отменить — %s"
                  % (r.get("when_h") or "?", cls, r.get("cancel") or _cancel_words()))


def rule_set(cls, word, who="owner", path=None, now=None):
    """Завести постоянное решение — ТОЛЬКО по явному слову владельца. → (ok, дословный ответ).

    Слово сверяется с закрытым списком `RULE_ON_WORDS`. Похожее, вежливое, усталое и любое другое
    правила НЕ заводит: система, догадавшаяся о постоянном молчании, однажды догадается о нём
    сама себе. И правило не заводится без отмены — способ снять его пишется В САМУ запись и
    называется владельцу тем же ответом."""
    w = str(word or "").strip().lower()
    c = str(cls or "").strip()
    if not c:
        return False, "класс не назван — правило не заведено"
    if not any(w == s or w.startswith(s) for s in RULE_ON_WORDS):
        return False, ("«%s» постоянным решением не считаю и ничего не завёл: догадка тут "
                       "запрещена. Правило заводится ровно словом «%s» — и снимается %s."
                       % (str(word or "").strip() or "(пусто)", RULE_ON_WORDS[0], _cancel_words()))
    d = _load(path)
    ts = _now(now)
    d["rules"][c] = {"on": True, "who": str(who or "owner"), "when": ts,
                     "when_h": time.strftime("%d.%m.%Y %H:%M", time.localtime(ts)),
                     "word": str(word or "").strip(), "cancel": _cancel_words()}
    saved, err = _save(d, path)
    if not saved:
        return False, "правило НЕ заведено (хранилище не записано: %s)" % err
    return True, ("✅ Записал постоянное решение: про класс «%s» больше не спрашиваю. Отказы "
                  "продолжают уходить в ленту, применяться само ничего не начнёт.\n"
                  "Отменить в любой момент — %s." % (c, _cancel_words()))


def rule_clear(cls, word, path=None, now=None):
    """Снять постоянное решение — тоже ТОЛЬКО явным словом (`RULE_OFF_WORDS`). → (ok, ответ)."""
    w = str(word or "").strip().lower()
    c = str(cls or "").strip()
    if not any(w == s or w.startswith(s) for s in RULE_OFF_WORDS):
        return False, ("«%s» отменой правила не считаю — правило на месте. Снять: %s."
                       % (str(word or "").strip() or "(пусто)", _cancel_words()))
    d = _load(path)
    r = d["rules"].get(c)
    if not isinstance(r, dict) or not r.get("on"):
        return False, "по классу «%s» постоянного решения нет — отменять нечего" % c
    r["on"], r["off_at"] = False, _now(now)
    saved, err = _save(d, path)
    if not saved:
        return False, "правило НЕ снято (хранилище не записано: %s)" % err
    return True, ("✅ Постоянное решение по классу «%s» снято — спрашиваю снова, как раньше." % c)


# ------------------------------- сводка вместо десяти карточек -----------------

def digest_due(cls, path=None, now=None):
    """Пора ли слать сводку по классу. → (пора?, дословная причина).

    Три замка, и каждый отвечает за свой способ надоесть: поводов меньше порога — сводки нет
    (одна карточка лучше пересказа одной карточки); прошло меньше окна — сводки нет; постоянное
    решение владельца — сводки нет ВООБЩЕ, класс молчит до его же слова."""
    c = str(cls or "").strip()
    on, why = rule_active(c, path)
    if on:
        return False, why
    n = len(open_waits(c, path))
    if n < FOLD_MIN:
        return False, "открытых поводов %d — порог свёртки %d не достигнут" % (n, FOLD_MIN)
    d = _load(path)
    last = d["digest"].get(c) or 0
    left = DIGEST_EVERY_SEC - (_now(now) - last)
    if last and left > 0:
        return False, "сводка по классу уже уходила, следующая не раньше чем через %d мин" % (left // 60)
    return True, "открытых поводов %d, окно %d ч прошло" % (n, DIGEST_EVERY_SEC // 3600)


def digest_mark(cls, path=None, now=None):
    """Отметить, что сводка ушла. Отдельным вызовом, а не внутри `digest_text`: пометить
    отправленным то, что не отправлено, — это ровно та потеря, от которой заведён модуль."""
    d = _load(path)
    d["digest"][str(cls or "")] = _now(now)
    saved, err = _save(d, path)
    return bool(saved), err


def digest_text(cls, path=None, now=None, answer_at=""):
    """ОДНА СВОДКА ВМЕСТО ДЕСЯТИ КАРТОЧЕК: число, последний повод, как ответить на всё сразу.

    Сводка честно говорит ДВЕ вещи, без которых она была бы опаснее десяти карточек: что за время
    молчания не применилось ничего, и что «да» на класс проверит состав КАЖДОГО повода заново."""
    ws = open_waits(cls, path)
    if not ws:
        return ""
    ts = _now(now)
    last = max(ws, key=lambda r: r.get("last") or 0)
    oldest_h = (ts - (min(r.get("first") or ts for r in ws))) / 3600.0
    lines = ["🗂 Открытые решения, класс «%s»: %d — пока ты был недоступен." % (cls, len(ws)),
             "За это время НЕ применилось ничего: молчание работает как отказ, ворота держали.",
             "Последний повод: %s" % (last.get("title") or last.get("key")),
             "Самый старый ждёт %.1f ч. Всего поводов (с повторами): %d."
             % (oldest_h, sum((r.get("n") or 1) for r in ws)),
             "Список:"]
    for r in ws[:10]:
        lines.append("  • %s — %s (повторов %d)"
                     % (r.get("key"), (r.get("title") or "").strip() or "без описания", r.get("n") or 1))
    if len(ws) > 10:
        lines.append("  … и ещё %d — показаны первые 10 по возрасту." % (len(ws) - 10))
    lines += [
        "Ответить на ВЕСЬ класс одним движением: «да» — разрешаю; «нет» — отказ (ничего не"
        " применяется и не откатывается).",
        "«Да» НЕ значит «выкатить всё скопом»: у каждого повода состав сверяется заново, и всё,"
        " что изменилось с момента вопроса, будет спрошено ЗАНОВО, а не применено.",
        "Больше не спрашивать про этот класс вовсе — «%s» (снять: %s)."
        % (RULE_ON_WORDS[0], _cancel_words()),
    ]
    if str(answer_at or "").strip():
        lines.append("ГДЕ ОТВЕЧАТЬ: %s" % str(answer_at).strip())
    return "\n".join(lines)


# ------------------------------- разбор ответа на класс ------------------------

def answer_class(cls, verdict, shapes_now, path=None, now=None):
    """ОТВЕТ НА НАКОПЛЕННОЕ ОДНИМ ДВИЖЕНИЕМ — и главный замок всего модуля.

    `shapes_now` — состав, снятый ВЫЗЫВАЮЩИМ ПРЯМО СЕЙЧАС: {ключ повода: отпечаток}. Мы не ходим
    за ним сами сознательно — состав знает тот, кто задавал вопрос, а модуль обязан остаться
    чистой функцией, которую голденит тест без сети и без git.

    → dict: applied[] · changed[] · gone[] · text (дословный ответ владельцу) · saved.

    ЧТО ЗДЕСЬ ЗАПРЕЩЕНО. Ничего не применяется: `applied` — это СПИСОК РАЗРЕШЁННОГО, вызывающий
    применяет сам и своими гейтами. Предсмертный взгляд задания назван так: «накопленные поводы
    начнут применяться утренним „да“ скопом, и владелец одним нажатием выкатит детям то, чего не
    видел». Замок против него ровно один и стои́т ниже: повод попадает в `applied` ТОЛЬКО если
    сегодняшний состав ПОСИМВОЛЬНО равен тому, что владелец видел. Состав уехал → `changed`, и
    повод переспрашивается заново. Повода больше нет в мире → `gone`, и он тоже не применяется.
    Правило симметрично для «да» и «нет» намеренно: «нет» — тоже решение о конкретном составе, и
    закрыть им повод, которого владелец не видел, значит потерять вопрос молча."""
    c, v = str(cls or "").strip(), str(verdict or "").strip().lower()
    if v not in ("yes", "no"):
        return {"applied": [], "changed": [], "gone": [], "saved": True,
                "text": "«%s» ответом на класс не считаю — жду «да» или «нет», ничего не тронул."
                        % (str(verdict or "").strip() or "(пусто)")}
    shapes = shapes_now if isinstance(shapes_now, dict) else {}
    applied, changed, gone = [], [], []
    for r in open_waits(c, path):
        k, was = r.get("key"), r.get("shape")
        if k not in shapes:
            gone.append(k)
        elif str(shapes[k]) == str(was):
            applied.append(k)
        else:
            changed.append(k)
    # Закрываем ТОЛЬКО совпавшие: у них ответ владельца относится к тому, что он видел. Поводы с
    # уехавшим составом остаются ОТКРЫТЫМИ — они и есть «спросить заново».
    n, err = close(c, applied, "ответ владельца на класс: %s" % v, path, now)
    word = "разрешено" if v == "yes" else "отказано"
    head = ("✅ Принял «да» по классу «%s»." if v == "yes" else "🚫 Принял «нет» по классу «%s».") % c
    body = ["%s Поводов %s: %d." % (head, word, len(applied))]
    if v == "yes":
        body.append("Это РАЗРЕШЕНИЕ, а не выкатка: применение пойдёт штатно, со всеми прежними "
                    "гейтами (тесты, анти-флап, запрет грязного дерева).")
    else:
        body.append("Ничего не применено и ничего не откачено — живые боты остались на прежнем коде.")
    if changed:
        body.append("НЕ применил %d: состав изменился с момента вопроса (%s). Их спрошу ЗАНОВО — "
                    "твоё решение принималось по другому составу."
                    % (len(changed), ", ".join(map(str, changed[:5]))))
    if gone:
        body.append("Ещё %d повода(ов) больше не существует (%s) — они закрылись сами, ответа не "
                    "требуют." % (len(gone), ", ".join(map(str, gone[:5]))))
    if err:
        body.append("⚠️ Хранилище НЕ записано (%s): часть поводов может прийти повторно. На "
                    "применение это не влияет — применяет вызывающий, а не эта запись." % err)
    return {"applied": applied, "changed": changed, "gone": gone,
            "saved": (not err), "text": "\n".join(body)}


# ------------------------------- протухшее нажатие объясняет себя --------------

def stale_explain(what="карточка", key="", why="", answer_at="", parked=None):
    """ЧЕЛОВЕЧЕСКАЯ СТРОКА НА ПРОТУХШЕЕ НАЖАТИЕ. Молчаливое «не ок» — дефект (п.3 задания).

    ЖИВОЙ ЗАМЕР, ради которого функция и заведена (05.09.2026 10:29:12, `pc_agent.log:18550`):
    `data='gate:no:4528917' uid=… → action=None ok=False`. Владелец нажал — и получил «карточка
    устарела», то есть НЕ ту причину: повод не протухал вовсе. Обработчик кнопки ворот
    (`GATE_CB_RE`) внесён коммитом `4bbe548` 05.09 в 05:20, а живой процесс агента стартовал
    03.09 в 05:02 и перезапустился только в 12:06 — нажатие пришло в процесс СТАРШЕ КНОПКИ.
    Отсюда правило этой строки: причина называется ДОСЛОВНО и не выдумывается. Не знаем причину —
    так и говорим, а не выдаём одну из двух за обе.

    Строка обязана отвечать на три вопроса и отвечает ровно в этом порядке: что случилось · почему
    · что делать ПРЯМО СЕЙЧАС. Третий — главный: нажатие, оставшееся без двери, теряется целиком."""
    parts = ["⚠️ Твоё нажатие не стало ответом: %s%s больше не принимает решение."
             % (what, (" %s" % key) if str(key or "").strip() else "")]
    parts.append("Почему: %s" % (str(why or "").strip()
                                 or "причину назвать не могу — не выдумываю её"))
    if parked:
        parts.append("Повод НЕ потерян: он открыт и ждёт ответа (я не применил ничего — молчание "
                     "работает как отказ). Он придёт сводкой открытых решений.")
    else:
        parts.append("Повод по этой кнопке я не нашёл — значит применить по ней нечего, и ничего "
                     "не применено.")
    if str(answer_at or "").strip():
        parts.append("Ответить прямо сейчас: %s" % str(answer_at).strip())
    return "\n".join(parts)
