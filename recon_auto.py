def expect_causes(open_eps, analysed=()):
    """Открытые эпизоды наблюдателя → поводы вида «ожидание без разбора».

    ``open_eps`` — словарь ``{ключ: {"first": ts, "kind": …}}``, снятый руками с
    состояния наблюдателя (``tmp/expect_pc/state.json``). ``analysed`` — ключи,
    по которым разбор УЖЕ ЕСТЬ.

    Наблюдатель живёт ВНЕ демона, а ставящий — ВНУТРИ. Отсюда свойство, которое
    надо знать, чтобы не поставить ложного диагноза: повод «демон не даёт
    оборота» физически доходит сюда только ПОСЛЕ того, как оборот вернулся, —
    вставший демон не ставит задач ни одной веткой. То есть это всегда разбор
    ПРОШЕДШЕГО эпизода, а не тревога о текущем. Тревога — предмет наблюдателя, и
    она уже ушла владельцу его заметкой.
    """
    done = set(analysed or ())
    out = []
    for ekey, rec in sorted((open_eps or {}).items()):
        rec = rec if isinstance(rec, dict) else {}
        kind = str(rec.get("kind") or "")
        if kind not in expectations_pc.KINDS:
            continue                      # чужой/битый ключ разбирать нечем
        key = key_of(SRC_EXPECT, ekey)
        if key in done:
            continue
        head = expectations_pc.NOTE_HEAD.get(kind, kind)
        out.append({
            "src": SRC_EXPECT, "key": key, "kind": kind,
            "title": head,
            "ident": str(ekey),
            "subject": "ожидание %s полосы ПК" % kind,
            "evidence": ["tmp/expect_pc/state.json (ключ эпизода %s)" % ekey,
                         "pc_orchestrator.log", "expectations_pc.py"],
            "first": rec.get("first"),
            "count": 1,
            "slug": _slug(kind.replace("_", "-")),
        })
    return out


def claim_causes(rows, built, analysed=()):
    """Живые ряды-заявки ступени B + ЕЁ ЖЕ живая сборка → поводы «премиса жива».

    ``rows`` — ``{ключ заявки: {"id": номер ряда, "day": дата}}``, снятое руками с
    ЖИВОЙ очереди; ``built`` — список ``{"claim":…, "premise":…}`` из
    ``review_intake_run.build`` (лоток → находки → склейка → проба премисы).

    ПОЧЕМУ ИСТОЧНИКА ДВА, А НЕ ОДИН. Реестр ступени B (``review_intake_state``)
    хранит ИСХОД премисы, но не её АДРЕС, а без адреса цели разведки не собрать —
    получилась бы задача «проверь что-нибудь». Поэтому исход и адрес берутся
    ПЕРЕСБОРКОЙ тем же кодом, которым заявка и родилась, а очередь отвечает на
    другой вопрос: существует ли ряд-заявка на самом деле. Повод — их
    пересечение: «заявка ЕСТЬ в очереди И её премиса жива СЕЙЧАС».

    Узнавание идёт по НАБОРУ ключей (``review_intake.claim_keys``), а не по
    одному: ключ заявки — это ключ её ЯКОРНОЙ записи, и приход второго канала
    якорь меняет. Урок ступени B (§4), пойманный там регрессом; повторять его
    здесь вторым слоем не стали.

    БЕРЁМ ТОЛЬКО ЖИВУЮ ПРЕМИСУ, и это не строгость ради строгости: находка на
    посылке «НЕИЗВЕСТНО»/«ПРОТУХЛА» разведке не поддаётся — разведывать нечего,
    пока неясно, о живом ли коде речь. Те же ворота, что у веса ступени D.
    """
    done = set(analysed or ())
    live = {str(k): (v if isinstance(v, dict) else {}) for k, v in (rows or {}).items()}
    labels = set(review_intake.kind_labels())
    out = []
    for item in (built or []):
        claim = (item or {}).get("claim") or {}
        premise = (item or {}).get("premise") or {}
        keys = [str(k) for k in review_intake.claim_keys(claim)]
        # ОПОЗНАЁМ повод ключом РЯДА, а не текущим якорным ключом заявки. Замер
        # 01.09 поймал это живьём: заявка #88 стоит в очереди под ключом
        # `2d08a1342da8`, а пересборка того же лотка даёт ей уже `27156c1e275d` —
        # корпус вырос, якорь переехал. Возьми мы текущий ключ, и повод менял бы
        # имя вместе с якорем: дедуп промахивался бы, а разведка приезжала бы
        # заново каждый раз, когда в лоток падает новый ответ.
        ckey = next((k for k in keys if k in live), "")
        if not ckey:
            continue                      # находка есть, а ЗАЯВКИ в очереди нет — повода нет
        row = live[ckey]
        if str(premise.get("outcome") or "") != review_intake.PREMISE_ALIVE:
            continue
        kind = str(claim.get("kind") or "")
        if kind not in labels:
            continue                      # вид находки обязан быть ИЗ хвоста пакета, не любым
        key = key_of(SRC_CLAIM, ckey)
        if key in done:
            continue
        addr = str(premise.get("address") or "")
        answers = sorted({str(s.get("answer")) for s in (claim.get("sources") or [])
                          if s.get("answer")})
        out.append({
            "src": SRC_CLAIM, "key": key, "kind": kind,
            "title": "находка внешнего канала, вид «%s»" % kind,
            "ident": ckey,
            "subject": "премиса находки по адресу %s" % (addr or "адрес не назван"),
            "evidence": ([addr] if addr else []) + answers,
            "queue_id": row.get("id"),
            "sources": len(claim.get("sources") or []) or 1,
            "address": addr,
            "count": 1,
            "slug": _slug("zayavka-%s" % ckey),
        })
    return out


def repeat_causes(signals, analysed=(), floor=2):
    """Счётчики «красного/неизвестно» → поводы «повторилось дважды».

    ``signals`` — список словарей ``{"class":…, "reason":…, "count":…,
    "where":[…]}``, посчитанных руками по ИЗМЕРИМОМУ корпусу (исходы файлов
    лотка, маркеры вердикта V0 в очереди). Порог ``floor`` — ДВА, дословно по
    заданию.

    ЕДИНИЦА — НЕ ПОВОД, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Один отказ канала бывает от чего
    угодно (сеть моргнула, ключ протух на минуту); повторившийся — это уже
    свойство, а не случай. Разница между «случилось» и «воспроизводится» — вся
    разница между шумом и предметом разведки.
    """
    done = set(analysed or ())
    out = []
    for sig in sorted(signals or [], key=lambda s: (-int(s.get("count") or 0),
                                                    str(s.get("class")), str(s.get("reason")))):
        cls, reason = str(sig.get("class") or ""), str(sig.get("reason") or "")
        count = int(sig.get("count") or 0)
        if not cls or not reason or count < int(floor):
            continue
        key = key_of(SRC_REPEAT, "%s|%s" % (cls, reason))
        if key in done:
            continue
        out.append({
            "src": SRC_REPEAT, "key": key, "kind": cls, "reason": reason,
            "title": "повторяющееся «%s: %s» (%d раз)" % (cls, reason, count),
            "ident": "%s|%s" % (cls, reason),
            "subject": "повтор исхода «%s» в классе «%s»" % (reason, cls),
            "evidence": [str(w) for w in (sig.get("where") or [])][:6],
            "count": count,
            "slug": _slug("%s-%s" % (cls, reason)),
        })
    return out


def analysed(causes, artifact_names):
    """Ключи поводов, по которым РАЗБОР УЖЕ ЛЕЖИТ файлом. → set.

    Признак — имя файла в ``docs/artifacts``: разведка обязана положить результат
    по :func:`result_address`, и существование этого файла (за любой день)
    означает, что вопрос уже задан и отвечен. Так повод закрывается СВОИМ ЖЕ
    продуктом, а не отдельным реестром — реестр можно потерять, файл лежит в git.

    ЧЕГО ПРИЗНАК НЕ ВИДИТ (называем прямо): разбор, написанный человеком под
    другим именем. Тогда повод поднимется ещё раз, и снимет его дедуп по ключу в
    очереди и реестре — то есть цена промаха ровно одна лишняя разведка, а не
    вечный повтор. Обратной ошибки («файл есть, а разбора нет») признак не даёт:
    имя с нашим слагом кладём только мы.
    """
    names = [str(n) for n in (artifact_names or [])]
    out = set()
    for cause in causes or []:
        slug = str(cause.get("slug") or "")
        if not slug:
            continue
        mark = "разведка-%s" % slug
        if any(mark in n for n in names):
            out.add(str(cause.get("key")))
    return out


def order(causes):
    """Поводы в порядке разбора. → list.

    Порядок между ВИДАМИ повода — :data:`SOURCES` (обоснование там же, у
    константы). Внутри вида — по ключу: детерминированность здесь важнее любой
    «умной» сортировки, потому что от порядка зависит, кто попадёт в потолок
    суток, а кто подождёт до завтра, и это должно быть воспроизводимо.
    """
    rank = {name: i for i, name in enumerate(SOURCES)}
    return sorted(causes or [], key=lambda c: (rank.get(str(c.get("src")), 99),
                                               str(c.get("key"))))


