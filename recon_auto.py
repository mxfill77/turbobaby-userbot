"""Ступень E полосы ПК — ДЕМОН САМ СТАВИТ СЕБЕ РАЗВЕДОЧНЫЕ ЗАДАЧИ.

Ступень A (:mod:`review_auto`) сама находит повод и относит пакет второго мнения
в канал; ступень B (:mod:`review_intake`) превращает находку ответа в ЗАЯВКУ
очереди; ступень C (:mod:`done_judge_pc`) отняла у исполнителя право закрывать
задачу словом; ступень D (:mod:`review_audit`) довела находку до глаз владельца.
Все четыре кончаются ЗНАНИЕМ: файл в лотке, ряд в очереди, сообщение в теме.
Дальше знание лежит и ждёт человека — а сработавшее ожидание, у которого никто
не спросил «почему», не отличается от несработавшего.

**Ступень E добавляет ровно одно звено: у поднятого ожидания появляется РАЗБОР —
задача, которую полоса ставит себе сама. И ни одного звена больше.**

ЧТО ТАКОЕ «РАЗВЕДОЧНАЯ» — ЭТО НЕ ТОН ЗАДАНИЯ, А ЕГО ГРАНИЦА. Автозадача меняет
ТОЛЬКО информационное состояние: читает, считает, пишет артефакт. Операционного
состояния она не трогает никогда — ни процессов, ни живых таблиц, ни денег, ни
детей контура, ни выкаток, ни удалений. Поэтому у неё нет и не может быть
«успешного» исхода, меняющего поведение полосы: она кончается ФАЙЛОМ ПО АДРЕСУ,
а решение по этому файлу принимает человек.

ЧЕТЫРЕ ЧАСТИ, БЕЗ КОТОРЫХ ЗАДАЧА НЕ СТАВИТСЯ ВОВСЕ (:func:`task_text` → ``None``):

1. **ЦЕЛЬ** — своими словами, выведенная из структурных полей повода;
2. **СТАНДАРТНЫЙ БЛОК ЗАПРЕТОВ** (:data:`PROHIBITIONS`) — дословно и целиком;
3. **ПРИЗНАК СДЕЛАННОСТИ** — проверяемый не отчётом, а чтением;
4. **АДРЕС РЕЗУЛЬТАТА** — путь файла, который обязан появиться.

Отсутствие любой из четырёх — не «поставим попроще», а отказ ставить: задача без
адреса результата закрывается словом исполнителя, и ступень C ровно это право у
полосы отняла. Проверяемость признака здесь не на честном слове: адрес назван →
закрытие судит V0 (``done_judge_pc``), читая продукт ПО АДРЕСУ.

ГЛАВНЫЙ ЗАМОК ЭТОГО МОДУЛЯ — **В ЗАДАНИИ НЕТ НИ ОДНОГО СИМВОЛА ЧУЖОГО ТЕКСТА.**
Повод «заявка из findings» приходит от ВНЕШНЕГО канала, и путь «чужой текст →
зелёная задача дирижёру» был бы каналом исполнения чужих команд на этой машине —
ровно тем, ради закрытия которого ступень B построена так, как построена. Поэтому
в задание едут только СТРУКТУРНЫЕ поля, посчитанные нами: вид находки, исход
премисы, АДРЕС премисы, число источников и ПУТЬ файла с полным текстом. Цитаты
нет. Читать мнение канала исполнитель идёт сам — по названному пути и уже зная
из задания, что это мнение, а не задание. Инвариант держит тест
``RECON_NO_FOREIGN_TEXT``, а не этот абзац.

ВТОРОЙ ЗАМОК — **МАРШРУТ ПО ПРЕДМЕТУ, А НЕ ПО ТЕКСТУ** (:func:`route`). Повод,
чей предмет требует ОПЕРАЦИОННОГО действия, обязан дать ЗАЯВКУ ВЛАДЕЛЬЦУ, а не
автозадачу: разведать «почему модербот не делает работу» нельзя, не тронув живого
ребёнка контура, а разведать «клиенту ушло сообщение» нельзя, не войдя в
клиентский контур — оба запрещены заданию ступени прямым текстом. Решает
СТРУКТУРНОЕ ПОЛЕ (вид ожидания, признак клиентского контура), а не подстрока:
правило 5 свода среды («судить по ДЕЙСТВИЮ, а не по подстроке») здесь и
применяется. Текстовая сеть :data:`OPERATIONAL_RE` стои́т ПОСЛЕ структурного
признака и только УЖЕСТОЧАЕТ — как страховка кодом у мандата ревизора, а не как
основной признак.

ИНВАРИАНТЫ (те же, что у ступеней A/B/D, и по той же причине):

* **Чистота.** Ни сети, ни диска, ни подпроцессов, ни ``getenv``, ни часов.
  «Сегодня», реестр поставленного, снимок очереди и признак клиентского контура —
  ПОЛЯ ВХОДА. Держит тест ``RECON_AUTO_PURE`` обходом AST.
* **Ничего не выдумывать.** Заголовки ожиданий берутся у
  ``expectations_pc.NOTE_HEAD``, виды находок — у ``review_intake.kind_labels()``.
  Список, набранный литералом, разошёлся бы с источником на первой его правке и
  молча начал бы врать — урок стоп-вида ступени D.
* **Третий исход.** Источник не прочитан → повода НЕТ (а не «поводов ноль»):
  молчание источника поводом не является и тишиной здоровья тоже.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ НИ ОДНОЙ ВЕТКОЙ: не ходит в очередь, не читает файлов,
не исполняет находок, не правит кода, не удаляет, не знает номеров тем и не
принимает решения о постановке — он его только ГОТОВИТ. Ставит руки
(:mod:`recon_auto_run`), и только они.
"""

