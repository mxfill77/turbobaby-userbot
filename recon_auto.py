def index_line(cause, way, queue_id, address=""):
    """Строка-индекс в мозг: ЧТО поставлено и КУДА придёт результат. → str."""
    head = "ARTIFACT ступень E разведка" if way == ROUTE_RECON else "ARTIFACT ступень E заявка"
    tail = (" → результат %s" % address) if address else ""
    return ("%s повод=%s ключ=%s вид=%s → очередь #%s%s"
            % (head, str(cause.get("src")), str(cause.get("key")),
               str(cause.get("kind")), queue_id, tail))
