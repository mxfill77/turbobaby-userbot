def key_of(src, ident):
    """Ключ повода — 12 hex от «вид|опознавательное». → str.

    ДЕНЬ В КЛЮЧ НЕ ВХОДИТ, и это выбор, а не упущение. У ступени A день в ключе
    обязателен (номера очереди переиспользуются, и без дня две разные работы
    склеились бы в один повод). Здесь наоборот: повод «то же ожидание сработало
    снова» — это ТОТ ЖЕ повод, и разбор, написанный вчера, отвечает на него
    сегодня. День в ключе означал бы новую разведку каждые сутки об одном и том
    же — то есть ленту, а не разбор.
    """
    raw = "%s|%s" % (str(src or ""), str(ident or ""))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:12]


def _slug(text, limit=48):
    """Хвост имени файла-результата: латиница, цифры, дефис. → str.

    Кириллицу НЕ транслитерируем и не выбрасываем молча — в имени артефакта она
    законна и на этой полосе обычна. Режем только то, что ломает путь.
    """
    out = re.sub(r"[^0-9A-Za-zА-Яа-яЁё-]+", "-", str(text or "")).strip("-").lower()
    out = re.sub(r"-{2,}", "-", out)
    return out[:limit].strip("-") or "bez-imeni"


