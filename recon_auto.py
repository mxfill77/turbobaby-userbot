def markers(items, kind="task"):
    """Ряды очереди → пары «дата, ключ» УЖЕ поставленного. → list.

    Источник — очередь, а не наш реестр: рестарт демона обнуляет память процесса,
    но не очередь, и потолок суток обязан пережить self-update (их на этой полосе
    десятки в день).
    """
    rx = _ASK_RE if kind == "ask" else _TASK_RE
    out = []
    for it in (items or []):
        m = rx.match(str((it or {}).get("task_text") or ""))
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def budget_left(marks, today, budget):
    """Сколько ещё можно поставить СЕГОДНЯ. → int ≥ 0."""
    used = sum(1 for day, _key in (marks or ()) if day == str(today or ""))
    return max(0, int(budget) - used)


def select(causes, *, placed=(), task_marks=(), ask_marks=(), today="",
           budget=DAILY_BUDGET, ask_budget=ASK_BUDGET, owner_busy=False,
           routes=None, limit=None):
    """Что ставить СЕЙЧАС. → (к постановке[(повод, маршрут, причина)], отложенные[(повод, причина)]).

    ЗАМОК ВЛАДЕЛЬЦА (``owner_busy``) СТОИ́Т ПЕРВЫМ И ГЛУШИТ ВСЁ — но только
    АВТОЗАДАЧИ. Правило задания дословно: «не больше двух автозадач в сутки, и
    ни одной, пока в очереди есть задача владельца». Заявка владельцу под него не
    попадает, и это не лазейка: заявка ничего не исполняет, ничьего времени
    полосы не занимает и существует ровно затем, чтобы владелец узнал о поводе,
    который полоса разведать НЕ ВПРАВЕ. Заглушить её вместе с задачами значило бы
    молчать именно там, где молчать опаснее всего.

    Причины отказа названы РАЗНЫМИ словами, потому что означают разное: «уже
    ставили» (вернётся, только если повод новый), «бюджет суток» (вернётся
    завтра), «в очереди задача владельца» (вернётся, как только она закроется).
    """
    routes = routes or {}
    seen = set(placed or ()) | {k for _d, k in (task_marks or ())} | {k for _d, k in (ask_marks or ())}
    take, held = [], []
    left = budget_left(task_marks, today, budget)
    ask_left = budget_left(ask_marks, today, ask_budget)
    for cause in order(causes):
        key = str(cause.get("key") or "")
        if key in seen:
            held.append((cause, "уже ставили — повод не новый"))
            continue
        way, why = routes.get(key) or (ROUTE_RECON, "")
        if way == ROUTE_OWNER:
            if ask_left <= 0:
                held.append((cause, "бюджет заявок владельцу на сутки исчерпан"))
                continue
            take.append((cause, ROUTE_OWNER, why))
            seen.add(key)
            ask_left -= 1
            continue
        if owner_busy:
            held.append((cause, "в очереди есть задача владельца — автозадач не ставим ни одной"))
            continue
        if limit is not None and sum(1 for _c, w, _w in take if w == ROUTE_RECON) >= limit:
            held.append((cause, "сверх лимита захода"))
            continue
        if left <= 0:
            held.append((cause, "бюджет суток исчерпан (%d автозадачи)" % int(budget)))
            continue
        take.append((cause, ROUTE_RECON, why))
        seen.add(key)
        left -= 1
    return take, held


