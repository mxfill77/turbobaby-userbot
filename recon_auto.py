def route(cause, client=None):
    """Повод → (маршрут, причина). :data:`ROUTE_RECON` | :data:`ROUTE_OWNER`.

    ``client`` — исход признака клиентского контура, снятый руками:
    ``{"hit":…, "files":[…], "determinate":…, "ok":…}``. Прибор УПАЛ
    (``ok=False``) → ЗАЯВКА ВЛАДЕЛЬЦУ: отказ прибора — это не «внутренний».

    ПОЧЕМУ ``determinate=False`` ЗДЕСЬ **НЕ** ОТДАЁТ ПОВОД ВЛАДЕЛЬЦУ, хотя у
    ревизора отдаёт. Это не послабление, а сверка ПОСЫЛКИ зеркалимого правила
    (правило-класс полосы от 04.08). Fail-closed ворот входа ревизора стои́т на
    посылке «дев-ТЗ БУДЕТ ПРАВИТЬ файлы; не знаю какие — значит могу тронуть
    живого бота». У разведки этой посылки нет ни в одной ветке: она не правит
    ничего, и весь её контакт с любым контуром — ЧТЕНИЕ. Поэтому «имён
    репозитория в предмете нет вовсе» здесь значит «предмет не в коде» (отказ
    канала, вид находки, эпизод ожидания), а не «может оказаться клиентским».
    Слепая копия чужого fail-closed отправляла бы владельцу карточку «признак не
    определился» на каждый HTTP-отказ внешнего канала — измерено на живом корпусе
    01.09: 2 повода из 5. Клиентский контур при этом закрыт с ДРУГОЙ стороны и
    структурно: виды О5 стоя́т в :data:`OWNER_KINDS` и до этой ветки не доходят.

    Порядок проверок выбран, а не случаен: сначала СТРУКТУРНОЕ поле (вид
    ожидания), потом измеренный признак контура, и только последней — текстовая
    сеть. Поставь сеть первой — и она съела бы точные причины своим общим словом,
    ровно как реестр остатка съел бы три точных отказа у ступени D (§11.6).
    """
    cause = cause if isinstance(cause, dict) else {}
    kind = str(cause.get("kind") or "")
    if cause.get("src") == SRC_EXPECT and kind in OWNER_KINDS:
        return ROUTE_OWNER, ("предмет ожидания %s разведке не подлежит: это %s" % (
            kind,
            "живой ребёнок контура" if kind == "o3_pc_moderbot" else "клиентский контур"))
    info = client if isinstance(client, dict) else {}
    if info and not info.get("ok", True):
        return ROUTE_OWNER, "признак клиентского контура УПАЛ — держим по fail-closed"
    if info.get("determinate", True) and info.get("hit"):
        files = ", ".join(str(f) for f in (info.get("files") or [])) or "файлы не названы"
        return ROUTE_OWNER, "предмет задевает клиентский контур (%s)" % files
    hay = " ".join([str(cause.get("subject") or ""), str(cause.get("title") or "")]
                   + [str(e) for e in (cause.get("evidence") or [])])
    hit = OPERATIONAL_RE.search(hay)
    if hit:
        return ROUTE_OWNER, "предмет требует операционного действия (слово «%s»)" % hit.group(0)
    if not info.get("determinate", True):
        return ROUTE_RECON, ("предмет читается и клиентских файлов не называет вовсе "
                             "(имён репозитория в нём нет) — операционного действия не нужно")
    return ROUTE_RECON, "предмет читается: очередь, лог, дерево — операционного действия не нужно"


