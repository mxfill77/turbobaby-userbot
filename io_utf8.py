# -*- coding: utf-8 -*-
"""
io_utf8.py — единый переключатель вывода процесса в UTF-8 (ПК-контур).

КЛАСС БАГА (укусил ТРИЖДЫ за 29–30.07.2026): текст с не-ASCII (кириллица, эмодзи 📊 ⏹ 🔔)
уходит наружу — print() в консоль/пайп, запись в файл, ответ кнопки, — а Python на Windows
кодирует его КОДИРОВКОЙ КОНСОЛИ (здесь cp1251). Эмодзи вне cp1251 роняют процесс
(`'charmap' codec can't encode character '\\U0001f4ca'` — это 📊), кириллица в UTF-8-приёмник
ложится мохибейком. Три отдельные починки (093119e — stdin журнала, dispatch_notify — stdin
хука, кнопка «Статус цепи») лечили ПО ОДНОМУ месту из трёх, и класс возвращался.

Здесь — общий шов на ПОЛОСУ ВЫВОДА: КАЖДЫЙ вход-процесс ПК-контура первой командой зовёт
force_utf8(), и его stdout/stderr гарантированно пишут UTF-8 — откуда бы его ни поднял
Планировщик, терминал или родитель субпроцессом. Страж класса — test_utf8_output_guard.py:
новый print-скрипт без force_utf8 или новый text-режим subprocess без encoding валит гейт.

Почему reconfigure, а НЕ PYTHONIOENCODING в окружении: env помогает только тем ДЕТЯМ, которых
мы сами спавним со своим env; процесс, поднятый Планировщиком/из терминала, про наш env не
знает. reconfigure чинит САМ процесс — независимо от того, кто и как его запустил. Пара к этому
шву на стороне ЧТЕНИЯ чужого вывода — encoding="utf-8" в каждом subprocess.run(text=True).

ВХОДНАЯ ПОЛОСА (ЧЕТВЁРТЫЙ КАНАЛ, заведена 20.09.2026, задание 68v). `force_utf8()` трогает
ТОЛЬКО stdout/stderr, а у процесса есть ещё и stdin, и он на Windows декодируется ЛОКАЛЬЮ
(cp1251). Родитель, пишущий в трубу UTF-8 (`subprocess.run(input=…, encoding="utf-8")`),
и ребёнок, читающий её локалью, дают ровно мохибейк «РљР°СЃР°РµРјРѕ» вместо «Касаемо» —
класс, который на этой полосе чинили ПО ОДНОМУ месту трижды (`cowork_log_append.read_stdin_text`
29.07, `brain_writer._stdin_text`, `dispatch_notify`/`pretool_guard` через reconfigure), и он
вернулся четвёртый раз — уже в дверь экзамена (`exam_show.py --own-text`), где текст владельца
лёг битым в базу уроков живого набора (три урока, 18–19.09.2026). Здесь у полосы появляется
ОДНО устройство и на вход тоже — чтобы пятое место не изобретало своё.
"""
import sys


def force_utf8():
    """stdout+stderr текущего процесса → UTF-8 (errors=replace). Идемпотентно и безопасно:
    подменённый в тесте поток без .reconfigure (StringIO) пропускаем, любую ошибку глотаем —
    переключатель вывода НЕ смеет ронять вызывающего (вывод вторичен по отношению к работе).
    → список реально переключённых потоков (для диагностики/тестов)."""
    switched = []
    for name in ("stdout", "stderr"):
        stream = getattr(sys, name, None)
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue                      # StringIO/нестандартный поток — менять нечего и нечем
        try:
            reconfigure(encoding="utf-8", errors="replace")
            switched.append(name)
        except Exception:
            pass                          # поток закрыт/не поддерживает — не падаем на диагностике
    return switched


def read_stdin_utf8(stream=None):
    """ВЕСЬ stdin как текст, ЯВНО в UTF-8 → str. Пара к force_utf8() на входной полосе.

    Читаем БАЙТЫ сами (`stream.buffer`), а не полагаемся на декодер потока: `sys.stdin` на
    Windows создан с кодировкой локали ещё до первой нашей строки, и `reconfigure` починил бы
    его только там, где он настоящий, — а у нас он бывает и подменённым (тест, обёртка).

    Порядок кодировок тот же, что у `cowork_log_append.read_stdin_text`, и он не вкусовщина:
      • utf-8 — так пишет в трубу КАЖДЫЙ наш родитель (`subprocess.run(encoding="utf-8")`);
      • cp1251 — так шлёт РОДНАЯ консоль Windows, если человек зовёт дверь руками;
      • utf-8 с заменой — последний рубеж: пустую строку из-за кодировки не отдаём никогда,
        потому что потерянный текст владельца хуже текста с одним знаком «?».

    Мохибейк НЕ ЛОВИТСЯ НИ ОДНИМ ГАРДОМ: длина растёт, текст непустой, обратное чтение совпадает
    с записанным. Поэтому чинится он ЗДЕСЬ, на входе, а не проверками после записи."""
    stream = stream if stream is not None else sys.stdin
    if stream is None:                    # процесс без stdin вовсе (pythonw, DEVNULL) — не падаем
        return ""                         # пустой текст вызывающий уже умеет назвать словами
    buf = getattr(stream, "buffer", None)
    if buf is None:                       # подменённый в тесте StringIO — там уже текст
        return stream.read()
    raw = buf.read()
    for enc in ("utf-8", "cp1251"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")
