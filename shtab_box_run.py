def _named_replace(err):
    """Обработчик кодека: незаписываемый знак → ``[U+XXXX]``. → (замена, позиция).

    Считает подстановки в :data:`_CONSOLE_LOST`, чтобы канал мог доложить о них
    отдельной строкой (:func:`console_note`), а не только вставкой на месте.
    """
    bad = err.object[err.start:err.end]
    _CONSOLE_LOST.append(bad)
    return ("".join("[U+%04X]" % ord(ch) for ch in bad), err.end)


_CONSOLE_LOST = []
codecs.register_error(CONSOLE_ERRORS, _named_replace)


def console_ready(*streams):
    """Починить канал вывода ОДИН РАЗ НА ВЕСЬ МОДУЛЬ. → int (сколько потоков взяли).

    ДВА СЛОЯ, И ВТОРОЙ НЕ ДУБЛИРУЕТ ПЕРВЫЙ:

    1. ЛАНЕВОЙ ШОВ :func:`io_utf8.force_utf8` — вывод процесса становится UTF-8,
       и терять в нём нечего вовсе. Своего переключателя здесь НЕТ и быть не
       должно: устройство у полосы одно.
    2. ПОЛИТИКА ОШИБКИ поверх того, что вышло. Если поток уйти с cp1251 не сумел
       (шов не взялся, поток чужой, кодировка прибита) — незаписываемый знак
       ОБЪЯВИТ СЕБЯ ``[U+XXXX]`` вместо `?` штатной замены и вместо падения.

    Зовётся первой строкой :func:`main`. Молчит и НЕ падает, если поток чинить
    нечем: цель канала — чтобы отчёт доехал, и починка канала не смеет уронить
    ход сама.

    ``streams`` задаются ТОЛЬКО набором (живой вызов идёт без аргументов и берёт
    ``sys.stdout``/``sys.stderr``): фикстуре нужен именованный поток, а полосе —
    ровно её собственный вывод.
    """
    if not streams:
        io_utf8.force_utf8()
    took = 0
    for st in (streams or (sys.stdout, sys.stderr)):
        rec = getattr(st, "reconfigure", None)
        if rec is None:
            continue
        try:
            rec(errors=CONSOLE_ERRORS)
            took += 1
        except Exception:                                   # noqa: BLE001
            continue
    return took


def console_note():
    """Строка о подстановках канала. → str (пусто = подставлять не пришлось).

    Второе объявление той же потери, и оно НЕ лишнее: вставка `[U+2705]` видна
    тому, кто читает строку целиком, а эта строка — тому, кто смотрит на хвост
    вывода. Дороже всего здесь стои́т случай, когда потерю не заметили вовсе.
    """
    if not _CONSOLE_LOST:
        return ""
    seen = []
    for piece in _CONSOLE_LOST:
        for ch in piece:
            if ch not in seen:
                seen.append(ch)
    return ("ЗАМЕЧАНИЕ КАНАЛА: кодировка консоли (%s) не приняла %d знак(ов) — они напечатаны "
            "кодовой точкой [U+XXXX], текст сообщения не менялся. Знаки: %s"
            % (getattr(sys.stdout, "encoding", "?"), len(_CONSOLE_LOST),
               ", ".join("U+%04X" % ord(c) for c in seen)))


def say(text, stream=None):
    """Напечатать отчёт так, чтобы он НЕ МОГ убить уже сделанный ход. → bool (напечатано).

    Решение Штаба №3: «сделал, потом доложил» остаётся, но доклад не имеет права
    превращать успешную запись в ненулевой код возврата. Канал выше делает падение
    вывода невозможным на нормальной дороге; :func:`say` закрывает НЕНОРМАЛЬНУЮ —
    поток без ``reconfigure``, закрытый stdout, полная труба. Тогда мы пробуем
    сказать то же самое в stderr, а если и там нечем — молчим и возвращаем
    ``False``: молчание честнее трейсбека поверх удавшегося действия.

    Ставится ровно там, где ХОД УЖЕ СОСТОЯЛСЯ (снятие остановки, постановка
    задания). Ветки только-чтения обходятся обычным ``print``: там убивать нечего.
    """
    out = stream if stream is not None else sys.stdout
    for target in (out, sys.stderr):
        try:
            print(text, file=target)
            note = console_note()
            if note:
                print(note, file=target)
            return True
        except Exception:                                   # noqa: BLE001
            continue
    return False


def main(argv=None):
    # ПЕРВОЙ СТРОКОЙ И ДО РАЗБОРА АРГУМЕНТОВ: `argparse` печатает помощь и свои
    # отказы САМ, а в описании ниже стои́т стрелка `→` (U+2192), которой в cp1251
    # тоже нет. Почини мы канал позже — `--help` падал бы ровно так же, как падало
    # снятие.
    console_ready()
    parser = argparse.ArgumentParser(
        description="Ящик заданий Штаба: документы папки мозга → задача полосы ПК "
                    "(не более одной за виток).")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--status", action="store_true", help="что лежит в ящике и что мешает")
    mode.add_argument("--dry", action="store_true", help="собрать всё, очередь НЕ трогать")
    mode.add_argument("--place", action="store_true", help="боевая постановка")
    parser.add_argument("--show", default=None, help="дословный текст ряда по ключу задания")
    parser.add_argument("--free", default=None,
                        help="снять сигнальную остановку по метке (зовёт кнопка/слово pc_agent)")
    parser.add_argument("--by", default="", help="кем снято — след в замке, не проверка права")
    parser.add_argument("--limit", type=int, default=shtab_box.TICK_LIMIT,
                        help="потолок заданий за виток")
    parser.add_argument("--budget", type=int, default=shtab_box.DAILY_BUDGET,
                        help="потолок заданий на сутки")
    parser.add_argument("--journal", action="store_true", help="писать строки-индексы в журнал")
    parser.add_argument("--json", action="store_true", help="отчёт машиночитаемо")
    args = parser.parse_args(argv)

    if args.free:
        # СНЯТИЕ — ОТДЕЛЬНАЯ ДОРОГА, И ОНА НЕ ЧИТАЕТ НИ МОСТА, НИ ОЧЕРЕДИ: ответ
        # владельца обязан проходить и тогда, когда мост молчит, — иначе решение
        # человека зависело бы от прибора, к которому оно не имеет отношения.
        ok, words = free_mark(args.free, root=HERE, by=args.by)
        # ДОКЛАД НЕ СМЕЕТ УБИТЬ СНЯТИЕ (решение Штаба №3). Снятие уже на диске —
        # значит код возврата обязан говорить о НЁМ, а не о судьбе печати: 10.09
        # вышло наоборот, и владелец прочитал «упало» о том, что удалось.
        say(words)
        return 0 if ok else 1
    if args.show:
        # ТЕКСТ ПО КЛЮЧУ — отдельная дорога, не зависящая от отбора: замок владельца
        # и потолок суток режут блок ДО сборки текста, и «покажи, что ты собирался
        # поставить» упиралось бы в «ничего не выбрано» ровно тогда, когда ответ
        # важнее всего.
        data = build(HERE)
        for doc in data["docs"]:
            if doc["key"] != args.show:
                continue
            text = shtab_box.task_text(doc, data["today"])
            if text:
                print("# %s" % shtab_box.lane_words(shtab_box.lane_of(doc)))
                print(text)
            elif doc.get("revoked"):
                print("ЗАДАНИЕ ОТОЗВАНО ШТАБОМ: документ %s" % doc["name"])
            elif doc.get("unread"):
                print("ТЕЛО НЕ ПРОЧИТАНО: %s" % doc["unread"])
            else:
                gate = data["gates"].get(doc["key"], {})
                print("ЗАДАНИЕ НЕ ПРИНЯТО (%s): %s" % (gate.get("reason"), gate.get("why")))
            return 0
        print("задания с ключом %s в ящике сейчас нет (искали документ %s)"
              % (args.show, shtab_box.doc_name(args.show)))
        return 0
    if args.status or not (args.dry or args.place):
        data = build(HERE, budget=args.budget)
        data.pop("queue", None)
        print(json.dumps(data, ensure_ascii=False, indent=2, default=str) if args.json
              else _render(None, data))
        return 0
    report = tick(HERE, place=bool(args.place), limit=args.limit, budget=args.budget,
                  write_journal=bool(args.journal))
    # ТОТ ЖЕ ДОВОД, ЧТО У СНЯТИЯ: при `--place` задание УЖЕ стои́т в очереди, ключ
    # УЖЕ записан в долгую память, и упавшая печать отчёта не смеет объявить этот
    # ход провалившимся.
    if args.json:
        say(json.dumps(report, ensure_ascii=False, indent=2, default=str))
    else:
        say(_render(report, report.get("build")))
    return 0


if __name__ == "__main__":            # pragma: no cover
    sys.exit(main())
