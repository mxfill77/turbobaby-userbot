def artifact_of(text, root=HERE):
    """Текст ряда → (текст артефакта, прочитан ли, причина, путь). Только ЧТЕНИЕ диска.

    АДРЕС И ВЫБОР ФАЙЛА — ЧУЖИЕ, И ЭТО УСЛОВИЕ, А НЕ ЭКОНОМИЯ. Адрес читает
    :func:`done_judge_pc.read_address`, снимок по нему — :func:`done_judge_pc.scan`,
    «отвечает ли файл словам адреса» — :func:`content_product_verifier.address_hit`.
    Заведи приёмка своё мнение хоть об одном из трёх, она судила бы НЕ ТОТ файл,
    который судья закрытия назвал продуктом, — и расхождение это было бы молчаливым.

    ТРИ ИСХОДА, И ТРЕТИЙ НЕ ПРИТВОРЯЕТСЯ ВТОРЫМ: продукт прочитан · по адресу
    ПУСТО · по адресу НЕСКОЛЬКО файлов, отвечающих словам, и который из них продукт
    — неизвестно. Оба последних дают «не прочитан», то есть приёмка скажет
    НЕИЗВЕСТНО и на дожим не отправит: гонять полосу по кругу на своей же
    неуверенности дороже, чем сказать «не знаю».
    """
    addr = done_judge_pc.read_address(text)
    if not addr:
        return "", False, "адрес результата задачей не назван — сверять нечего", ""
    if not addr.get("words"):
        return "", False, "адрес назван без слов — какой файл продукт, неизвестно", ""
    now = done_judge_pc.scan(addr, root)
    if now is None:
        return "", False, "чтение по адресу сорвалось (папка недоступна)", ""
    hits = []
    for path in sorted(now):
        full = os.path.join(root, path.replace("/", os.sep))
        body = done_judge_pc._read_text(full, done_judge_pc.MAX_ARTIFACT_BYTES)
        if v0.address_hit(path, body, addr["words"]):
            hits.append((path, body))
    if not hits:
        return "", False, ("по адресу нет файла, отвечающего словам адреса (%s) — продукта, "
                           "который можно сверить с пунктами, нет" % addr["words"][:80]), ""
    if len(hits) > 1:
        return "", False, ("по адресу %d файла(ов) отвечают словам адреса (%s) — который из них "
                           "продукт, приёмка не знает"
                           % (len(hits), ", ".join(p for p, _b in hits[:3]))), ""
    return hits[0][1], True, "", hits[0][0]


def retry_blocks(closed_rows, seen_keys, root=HERE, artifact_fn=None,
                 attempt_max=acc.ATTEMPT_MAX, body_max=shtab_box.BODY_MAX):
    """Закрытые ряды ящика → (блоки ДОЖИМА, строки исходов приёмки). Диск только на чтение.

    ПРИЁМКА ЗАХОДИТ ПОСЛЕ ЗАКРЫТИЯ и только к ``done``: провал (``failed``) — это не
    «закрыто наполовину», а несостоявшийся заход, и о нём говорят сигналы
    (:mod:`shtab_box_signals`), а не приёмка. Отправлять провал на дожим значило бы
    завести второй механизм повтора рядом с первым и разойтись с ним молча.

    ПАМЯТЬ У ДОЖИМА ОДНА И ТА ЖЕ — ЖИВАЯ ОЧЕРЕДЬ. Реестра на диске здесь нет ровно
    по той же причине, по которой его нет у ящика: он не переживает self-update, а
    дедуп обязан пережить всё. Уже поставленный дожим узнаётся по СВОЕМУ ключу в
    маркерах (``seen_keys``) — то есть тем же замком, что и всё остальное.
    """
    art = artifact_fn or (lambda text: artifact_of(text, root))
    blocks, notes = [], []
    # «РЯД ИЗ ЯЩИКА» ОПОЗНАЁТ ОДНА ФУНКЦИЯ НА ПОЛОСЕ — :func:`shtab_box_signals.box_rows`,
    # тот же маркер, которым живут дедуп и суточный счёт. Она отдаёт УРЕЗАННЫЙ ряд
    # (номер, день, ключ, статус) и текста задания в нём нет, поэтому здесь она
    # работает ФИЛЬТРОМ по номерам, а тело берётся из исходного ряда. Своя
    # регулярка «а не из ящика ли это» завела бы второе мнение о том же вопросе —
    # и разошлась бы с первым молча.
    box_ids = {r.get("id") for r in sig.box_rows(closed_rows, statuses=("done",))}
    for raw in (closed_rows or ()):
        row = raw if isinstance(raw, dict) else {}
        try:
            num = int(row.get("id"))
        except (TypeError, ValueError):
            continue
        if num not in box_ids:
            continue
        text = str(row.get("task_text") or "")
        key = acc.key_of(text)
        if not key:
            continue
        body = acc.body_of(text)
        art_text, art_ok, art_why, art_path = art(text)
        verdict = acc.accept(body, art_text, artifact_ok=art_ok, why_unread=art_why)
        note = {"key": key, "id": row.get("id"), "verdict": verdict["verdict"],
                "why": verdict["why"], "artifact": art_path, "attempt": acc.attempt_of(key),
                "card": "", "next": "", "held": ""}
        if verdict["verdict"] != acc.RETRY:
            notes.append(note)
            continue
        src = acc.source_of(text)
        nxt, why = acc.retry_key(key, attempt_max=attempt_max)
        if not nxt:
            # ПОТОЛОК ПОПЫТОК ИЛИ НЕВОЗМОЖНЫЙ КЛЮЧ — молча не бросаем ни в одном
            # случае: карточка называет заходы, пункты и способ, которым это
            # установлено, и решение уходит владельцу.
            note["card"] = acc.owner_card(key, verdict, attempt=acc.attempt_of(key),
                                          name=src.get("name"))
            note["held"] = why
            notes.append(note)
            continue
        if nxt in (seen_keys or ()):
            note["held"] = "дожим %s уже стои́т в очереди — второй раз не ставим" % nxt
            notes.append(note)
            continue
        new_body, why_body = acc.retry_body(body, verdict["remainder"], acc.attempt_of(key) + 1,
                                            artifact=art_path, body_max=body_max)
        if not new_body:
            note["held"] = why_body
            notes.append(note)
            continue
        note["next"] = nxt
        notes.append(note)
        blocks.append({"key": nxt, "body": new_body, "name": src.get("name"),
                       "id": src.get("id"), "retry": True, "of": key,
                       "attempt": acc.attempt_of(key) + 1})
    return blocks, notes


class Queue(recon_auto_run.Queue):
    """Очередь ящика: тот же клиент моста и тот же механизм, что у ступеней B и E.

    Наследуемся, а не переписываем: постановка ряда, чтение статусов и признак
    «в очереди есть работа владельца» — один механизм на полосу. Отличий с
    03.09.2026 два — метка ``from`` и ДВЕ ПОЛОСЫ вместо одной.

    ЗАЯВОК ВЛАДЕЛЬЦУ ЯЩИК НЕ СТАВИТ НИ ОДНОЙ, и ``place_ask`` здесь не зовётся
    нигде: у ящика нет собственного мнения, о котором стоило бы спрашивать. Он
    либо берёт готовый блок, либо не берёт и говорит почему.
    """

    def rows(self, statuses=OPEN_STATUSES):
        """Ряды ОБЕИХ полос в названных статусах. → (list, ok, why).

        ═══ ПОЧЕМУ ЧУЖУЮ ПОЛОСУ ЧИТАТЬ ОБЯЗАТЕЛЬНО ═══════════════════════════

        Наследованный ``rows`` читал ``get_pending(status)`` с дефолтным
        ``lane='pc'`` и вдобавок отбрасывал чужие ряды сам. Пока ящик ставил
        только своей полосой, это было верно. С маршрутом 03.09 то же чтение
        стало БЕСШУМНОЙ МАШИНОЙ ДУБЛЕЙ: дедуп ящика живёт в маркере ряда живой
        очереди, ряд ушёл на ``lane=vps`` — и маркер невидим. Ящик брал бы одно и
        то же задание КАЖДЫЙ ВИТОК, а суточный потолок, считаемый теми же
        маркерами, не остановил бы его ни разу: и «взято 0», и «не вижу взятых»
        выглядят одинаково. Это ровно класс 539, из-за которого на полосе VPS
        родились четыре дубля за трое суток.

        ОДИН ВЫЗОВ, А НЕ ДВА: ``lane='all'`` проверен живой пробой 03.09 (`done`:
        pc 61 + vps 4 = all 65). Два вызова на статус удвоили бы цену витка ровно
        там, где задание просит его учащать.

        ЧУЖИЕ РЯДЫ НЕ ОТБРАСЫВАЮТСЯ, а ПОМЕЧАЮТСЯ ПОЛОСОЙ: разделение по полосам
        делает вызывающий (:func:`build`), потому что разным замкам нужны разные
        корпуса — дедупу обе полосы, замку владельца только своя.
        """
        out = []
        for status in statuses:
            res = self._d.bc.get_pending(status, lane=LANE_ALL)
            if not res.get("ok"):
                # ПРИЧИНА ПО СУЩЕСТВУ, не именем класса — см. одноимённый блок у родителя.
                # Третий исход потолка моста («не спрашивали, мост был занят») обязан доехать
                # до ящика СЛОВАМИ: ящик и так не берёт ничего при ok=False, но молчаливое
                # «BridgeBudgetExhausted» превратило бы отложенное чтение в мнимую поломку.
                return [], False, str(res.get("error_text") or res.get("error") or "мост не ответил")
            for it in (res.get("items") or []):
                item = dict(it)
                item.setdefault("status", status)
                item["lane"] = shtab_box.row_lane(it)
                out.append(item)
        return out, True, ""

    def place_task(self, text, lane=None):
        """Задание Штаба — зелёный ряд ``new`` НА НАЗВАННОЙ ПОЛОСЕ. → (ok, id|None, причина).

        Ни ``claim``, ни ``set_needs_approval``: ряд подберёт штатный
        ``process_new`` СВОЕЙ полосы и исполнит headless-ребёнком под обычным
        гардом. Это и есть «демон сам берёт задачу из ящика» — не имитация ряда, а
        обычная работа полосы.

        ДОРОГА ПОЛОСЫ ПК НЕ ТРОНУТА НИ СИМВОЛОМ: она по-прежнему идёт через
        ``enqueue_pc_task``, у которого ``lane`` зашит жёстко («чужие полосы не
        создаём») и который пишет свою строку в лог демона. Чужая полоса —
        ОТДЕЛЬНАЯ ветка тем же экшеном моста, и она проверяет имя полосы по
        НАБОРУ (:data:`shtab_box.LANES`), а не доверяет вызывающему: полосы,
        которой нет, ряд достаться не может даже по опечатке.
        """
        ln = str(lane or shtab_box.LANE_DEFAULT)
        if ln == shtab_box.LANE_PC:
            ok, tid, err = self._d.enqueue_pc_task(text, frm=FROM)
            return (bool(ok), tid, "" if ok else str(err or "enqueue отклонён"))
        if ln not in shtab_box.LANES:
            return False, None, ("полоса %r не из набора %s — ряд не ставим вовсе"
                                 % (ln, list(shtab_box.LANES)))
        body = str(text or "").strip()
        if not body:
            return False, None, "пустой текст задачи"
        res = self._d.bc.enqueue_task(FROM, body, lane=ln)
        if not (isinstance(res, dict) and res.get("ok")):
            return False, None, str((res or {}).get("error") or "enqueue отклонён Bridge")
        return True, res.get("id"), ""


# ───────────────────────────── сборка ─────────────────────────────


def build(root=HERE, queue=None, clock=None, reader=None, node=None,
          budget=shtab_box.DAILY_BUDGET, ledger=None, lister=None, doc_reader=None,
          prefix=None, read_max=shtab_box.READ_MAX, taken_reader=None, hold_reader=None):
    """Всё, что нужно для решения: ящик + очередь + маркеры. → dict.

    Ничего не ставит и никуда не пишет — этой же функцией живут ``--status`` и
    ``--dry``.

    ПОРЯДОК ЧТЕНИЙ — ЭТО ПОРЯДОК ИХ ЦЕНЫ, и он выбран, а не случаен:

    1. **стоп-файл** — стои́т диска;
    2. **ПЕРЕЧИСЛЕНИЕ ПАПКИ** — один вызов моста, отдаёт имена и file id всех
       заданий разом. Пустой ящик закрывается ЗДЕСЬ, не тронув ни очереди, ни
       единого тела;
    3. **ШАПКА** :data:`shtab_box.NODE_NAME` — второе чтение моста, и оно
       БЕЗУСЛОВНОЕ. Соблазн прочитать её только при живом кандидате велик и
       неверен: шапка несёт метки снятия сигналов И блоки СТАРОЙ ФОРМЫ, а старый
       блок опаснее всего ровно тогда, когда папка пуста — Штаб положил задание по
       прежней памяти, и «ящик пуст» было бы про пустую папку правдой, а про
       положенное задание враньём;
    4. **открытые ряды** — замок владельца;
    5. **закрытые ряды** — только при живом кандидате. Замер полосы:
       ``get_pending("done")`` — 120 строк за **26.8 с** против 2.9 с у ``failed``
       (`queue_snapshot_pc`, 14.08.2026), а виток демона исполняется синхронно;
    6. **ТЕЛА ДОКУМЕНТОВ** — последними и не все. Тело стои́т отдельного похода в
       мост, поэтому не читается у того, кого всё равно не возьмут: у снятого
       Штабом и у уже взятого (ключ в маркерах). Оставшиеся читаются по порядку
       имён, не больше :data:`shtab_box.READ_MAX` за виток, и КАЖДЫЙ непрочитанный
       получает свою строку — тихого обрезания здесь нет.

    Третье состояние названо честно везде: «не спрашивали, потому что незачем» —
    это НЕ отказ прибора и НЕ прочитанный ноль.
    """
    stamp = now_iso(clock)
    # ДЕНЬ ЯЩИКА — МЕСТНЫЙ, А НЕ UTC (04.09.2026). `review_intake.today_utc` здесь
    # больше не зовётся НЕ потому, что она плоха, а потому что её день считают
    # четверо и он у них UTC по построению корпусов; сдвинь мы её — сутки уехали бы
    # всем МОЛЧА. Своя дверь — `shtab_box.lane_day`, там же названо, что происходит
    # с маркерами уже взятых задач на стыке двух отсчётов.
    today = shtab_box.lane_day(stamp)
    out = {"schema": shtab_box.SCHEMA, "stamp": stamp, "today": today,
           "node": node or shtab_box.NODE_NAME, "node_ok": False, "node_why": "",
           "prefix": shtab_box.TASK_PREFIX if prefix is None else str(prefix),
           "folder_ok": False, "folder_why": "", "files": 0,
           "docs": [], "bad": [], "gates": {}, "read": 0, "old_door": "",
           "off": False, "off_why": "",
           "queue_ok": False, "queue_asked": False, "queue_why": "",
           "owner_busy": None, "owner_rows": [],
           "marks_ok": False, "marks_asked": False, "marks_why": "", "task_marks": [],
           # МАРКЕРЫ В ДВУХ РАЗРЕЗАХ: общий (дедуп по обеим полосам) и по полосам
           # (суточный потолок у каждой свой). Одного корпуса тут мало не потому, что
           # так удобнее, а потому что вопросы разные — см. :func:`shtab_box.marks_by_lane`.
           "lane_marks": {}, "taken_by_lane": {},
           # ВНЕШНИЙ ОТКАЗ — ОТДЕЛЬНОЕ ЧИСЛО, А НЕ ПОПРАВКА К ВЗЯТОМУ. Ключи
           # заданий, сгоревших на чужом API; их считает ОДИН различитель
           # (:func:`shtab_box_signals.external_refusal`), и им же пользуется
           # сигнал А. Показывать их врозь обязательно: «взято 8» и «съедено 5»
           # — разные новости, и одно число на обе научило бы владельца не верить
           # ни одному.
           "external": [], "billed_today": None, "billed_by_lane": {},
           "rows": 0, "taken_today": None,
           # СИГНАЛЬНАЯ ОСТАНОВКА: три состояния, как у маркеров суток, — посчитана ·
           # не посчитана, потому что до неё не дошло · посчитана и говорит «не знаю».
           "signals": [], "signals_asked": False, "signals_why": "", "released": [],
           "judged_ok": False, "judged_why": "", "stop": "",
           # ЗАМОК ОСТАНОВКИ: своё поле, свой признак чтения, своя причина — по
           # той же причине, что и у долгой памяти строкой ниже. «Замка нет» и
           # «замок не прочитан» ведут ящик в разные стороны, и различать их
           # обязано отдельное поле, а не длина списка.
           "hold": [], "hold_ok": False, "hold_n": 0,
           "hold_why": "замок остановки не читали — оборот кончился раньше",
           "arm": [], "free": [],
           # ДОЛГАЯ ПАМЯТЬ: своё поле, свой признак чтения, своя причина. Значения
           # по умолчанию описывают путь, на котором до неё не дошли (выключенный
           # ящик) — «не читали» и «прочитана и пуста» здесь не одно и то же.
           "known": [], "known_ok": False, "known_n": 0,
           "known_why": "долгую память не читали — оборот кончился раньше"}

    out["off"], out["off_why"] = stopped(root)
    if out["off"]:
        return out

    # ДОЛГАЯ ПАМЯТЬ ЧИТАЕТСЯ ВТОРОЙ, СРАЗУ ЗА СТОП-ФАЙЛОМ, и порядок тут — цена:
    # она стои́т ДИСКА, а не моста, и это единственный корпус, переживающий круг
    # номеров очереди (разбор и числа — `shtab_box.merge_known`). Читаем её ДО
    # папки, чтобы её отказ был виден даже тогда, когда мост молчит.
    known, known_ok, known_why = (taken_reader or read_taken)(root)
    out["known"], out["known_ok"], out["known_why"] = known, bool(known_ok), str(known_why or "")
    out["known_n"] = len(known)

    # ЗАМОК ЧИТАЕТСЯ ТРЕТЬИМ, РЯДОМ С ПАМЯТЬЮ И ПО ТОЙ ЖЕ ПРИЧИНЕ: он стои́т
    # ДИСКА, а не моста, и его отказ обязан быть виден даже тогда, когда мост
    # молчит. Больше того — именно при молчащем мосте замок и говорит: живого
    # корпуса нет, а остановка, объявленная вчера, никуда не делась.
    hold_recs, hold_ok, hold_why = (hold_reader or read_hold)(root)
    out["hold"], out["hold_ok"], out["hold_why"] = hold_recs, bool(hold_ok), str(hold_why or "")
    out["hold_n"] = len(hold_recs)

    files, folder_ok, folder_why = read_folder(out["prefix"], lister=lister)
    out["folder_ok"], out["folder_why"], out["files"] = folder_ok, folder_why, len(files)
    if not folder_ok:
        # ЗАМОК ГОВОРИТ И ЗДЕСЬ — ИМЕННО ЗДЕСЬ ОН И НУЖЕН БОЛЬШЕ ВСЕГО. Мост не
        # ответил, живых сигналов нет ни одного, ящик и так не берёт ничего; но
        # витрина и `--status` читают `stop`, и пустая строка на запертом ящике
        # читалась бы как «остановки нет». Снятия берутся ТОЛЬКО запомненные:
        # шапку в этот оборот не читали, а выдумывать снятие нельзя.
        out["signals"], out["arm"], out["free"] = sig.merge_held(
            [], held=out["hold"], released=sig.hold_release(out["hold"], ()), now=stamp)
        out["stop"] = sig.stop_words(out["signals"], node=out["node"], checked=False,
                                     why="шапку узла в этот оборот не читали — %s"
                                         % (folder_why or "папка заданий не перечислена"))
        out["signals_why"] = out["stop"] or ("живые сигналы не считались — папка заданий не "
                                             "перечислена")
        return out

    docs, bad = shtab_box.parse_folder(files, prefix=out["prefix"])
    out["docs"], out["bad"] = docs, bad

    # ШАПКА: метки снятия сигналов + ДОКЛАД О ЗАКРЫТОЙ ДВЕРИ. Её отказ НЕ
    # останавливает ящик — источником задач она быть перестала, а нечитаемые метки
    # снятия дают ровно один эффект: снятый владельцем сигнал остаётся стоять. Это
    # строже, а не слабее, и потому законно.
    text, node_ok, node_why = read_node(out["node"], reader=reader)
    out["node_ok"], out["node_why"] = node_ok, node_why
    if node_ok:
        stale, _stale_bad = shtab_box.parse_node(text)
        out["old_door"] = shtab_box.old_door_line(len(stale))

    q = None if queue is False else (queue or Queue())
    live_rows, ok, qwhy = ([], False, "очередь не спрашивали")
    if q is not None:
        live_rows, ok, qwhy = q.rows(OPEN_STATUSES)
        out["queue_asked"] = True
    out["queue_ok"], out["queue_why"] = ok, qwhy
    # ЗАМКИ, СУЩЕСТВОВАВШИЕ ДО МАРШРУТА, СУДЯТ РОВНО ТОТ ЖЕ КОРПУС, ЧТО И ВЧЕРА —
    # ряды СВОЕЙ полосы. Это не осторожность: `_is_owner_work` и сигнал В — правила,
    # измеренные НА ЭТОЙ полосе (правило зеркала: посылку меряют здесь). Накорми мы
    # их чужими рядами, карточка, ждущая владельца на сервере, глушила бы ящик ПК —
    # поведение, которого никто не мерил и которое никем не заказано.
    live_pc = shtab_box.rows_by_lane(live_rows)[shtab_box.LANE_PC] if ok else []
    if ok:
        busy, ids = q.owner_busy(live_pc)
        out["owner_busy"], out["owner_rows"] = busy, ids

    closed_rows, closed_ok, closed_why = ([], False, "закрытые ряды не спрашивали")
    # ЖИВОЙ КАНДИДАТ СЧИТАЕТСЯ ДО ЧТЕНИЯ ТЕЛ, и иначе быть не может: ворота судят
    # тело, тело читается только у невзятых, а невзятые известны лишь из маркеров —
    # то есть из того самого дорогого чтения, ради которого вопрос и задан. Круг
    # разрывается ДЕШЁВЫМ признаком: кандидат — это документ, которого Штаб НЕ
    # СНИМАЛ. Папка из одних снятых документов дорогого чтения не стои́т.
    fresh = [d for d in docs if not d.get("revoked")]
    if q is None or not ok:
        closed_why = "очередь не прочитана — маркеров суток нет ни одного"
    elif out["owner_busy"]:
        closed_why = "в очереди работа владельца — дорогое чтение done не понадобилось"
    elif not fresh:
        closed_why = ("заданий, не снятых Штабом, в папке нет — дорогое чтение done "
                      "не понадобилось")
    else:
        closed_rows, closed_ok, closed_why = q.rows(CLOSED_STATUSES)
        out["marks_asked"] = True
    known = out["known"]
    # НЕПРОЧИТАННАЯ ПАМЯТЬ РАВНА НЕПРОЧИТАННЫМ ЗАКРЫТЫМ РЯДАМ: и то и другое —
    # «какие ключи уже брали, НЕИЗВЕСТНО», и оба ведут к одному поступку.
    known_ok, known_why = out["known_ok"], out["known_why"]
    # НЕПРОЧИТАННЫЙ ЗАМОК РАВЕН НЕПРОЧИТАННЫМ РЯДАМ И НЕПРОЧИТАННОЙ ПАМЯТИ, и
    # присоединяется к ним ТЕМ ЖЕ признаком, а не пятым сигналом: вопрос у всех
    # трёх один — «брать ли на незнании», и ответ один — «нет». Заводить под это
    # отдельного сторожа значило бы завести второе мнение о том же.
    out["marks_ok"] = bool(ok and closed_ok and known_ok and out["hold_ok"])
    out["marks_why"] = closed_why
    for extra_ok, extra_why in ((known_ok, known_why), (out["hold_ok"], out["hold_why"])):
        if extra_ok:
            continue
        out["marks_why"] = ("%s · %s" % (out["marks_why"], extra_why) if out["marks_why"]
                            else extra_why)
    if ok:
        all_rows = list(live_rows) + list(closed_rows)
        out["rows"] = len(all_rows)
        # ДВА РАЗНЫХ СЧЁТА ИЗ ОДНОГО КОРПУСА: дедуп — по ОБЕИМ полосам (ключ есть имя
        # задачи, и «уже взято» не перестаёт быть правдой от смены машины), потолок —
        # у КАЖДОЙ свой (мощности две, и друг у друга они ничего не отнимают).
        # КОРПУС ТЕПЕРЬ ШИРЕ РЯДОВ: к маркерам живой очереди подмешивается долгая
        # память — добавлением, а не заменой (ослабить дедуп слияние не может).
        out["task_marks"], out["lane_marks"] = shtab_box.merge_known(
            shtab_box.markers(all_rows), shtab_box.marks_by_lane(all_rows), known)
        # ЕДИНСТВЕННОЕ МЕСТО, ГДЕ СУТОЧНЫЙ СЧЁТ СПРАШИВАЕТ ПРО ВНЕШНИЙ ОТКАЗ, и
        # спрашивает он ТОТ ЖЕ различитель, которым живёт сигнал А. Второго
        # экземпляра правила у полосы нет ни одной ветки — ровно от этого
        # предостерегал предсмертный взгляд задания.
        out["external"] = sorted(sig.external_keys(sig.box_rows(closed_rows)))
        if out["marks_ok"]:
            # ВЗЯТО и СЪЕДЕНО — ДВА ЧИСЛА, И ОБА НУЖНЫ. `taken_*` отвечает «сколько
            # заданий полоса вообще взяла» (по нему живёт дедуп и по нему сводка
            # читает маркеры), `billed_*` — «сколько слотов дня на это ушло».
            # Слить их в одно значило бы либо соврать вверх (внешний отказ съел
            # день, которого не тратил), либо потерять факт взятия.
            out["taken_today"] = shtab_box.marks_today(out["task_marks"], today)
            out["taken_by_lane"] = {ln: shtab_box.marks_today(marks, today)
                                    for ln, marks in out["lane_marks"].items()}
            out["billed_today"] = shtab_box.marks_today(
                shtab_box.billable(out["task_marks"], out["external"]), today)
            out["billed_by_lane"] = {
                ln: shtab_box.marks_today(shtab_box.billable(marks, out["external"]), today)
                for ln, marks in out["lane_marks"].items()}

    # ── ПРИЁМКА И ДОЖИМ ───────────────────────────────────────────────────────
    # ЗАХОДИТ ТОЛЬКО НА ПРОЧИТАННОМ КОРПУСЕ ЗАКРЫТЫХ РЯДОВ, и это не осторожность
    # ради осторожности: дожим узнаёт себя по СВОЕМУ ключу в маркерах, и при
    # непрочитанных маркерах «дожим ещё не ставили» и «мы его не видим» выглядят
    # одинаково. Поставить на этом дожим значило бы дублировать задание — ровно то,
    # от чего дедуп и заведён.
    out["retry"], out["accepted"] = [], []
    if not out["marks_ok"]:
        out["accept_why"] = ("приёмка не заходила: закрытые ряды не прочитаны (%s) — сверять "
                             "нечего и дожимать вслепую нельзя" % (closed_why or "причина не названа"))
    else:
        out["retry"], out["accepted"] = retry_blocks(
            closed_rows, {k for _d, k in out["task_marks"]}, root)
        out["accept_why"] = ("приёмка: закрытых заданий ящика %d, к дожиму %d"
                             % (len(out["accepted"]), len(out["retry"])))

    # ── ТЕЛА ДОКУМЕНТОВ ───────────────────────────────────────────────────────
    # ПОСЛЕДНЕЕ ЧТЕНИЕ И САМОЕ ИЗБИРАТЕЛЬНОЕ: каждое тело — свой поход в мост.
    # Не читаем у снятого (его не возьмут) и у уже взятого (маркер ключа стои́т в
    # очереди). Порядок — тот, что назначен `parse_folder`, то есть по имени:
    # потолок витка обязан отрезать ХВОСТ предсказуемого списка, а не случайных.
    taken_keys = {k for _d, k in out["task_marks"]}
    queue_ue = []
    for doc in docs:
        if doc.get("revoked"):
            continue
        if doc["key"] in taken_keys:
            doc["taken"] = True
            continue
        queue_ue.append(doc)
    cap = int(read_max) if read_max is not None else len(queue_ue)
    for i, doc in enumerate(queue_ue):
        if i >= cap:
            doc["unread"] = ("тело в этот виток не читали: за виток читаем не больше %d "
                             "документов, а ждут %d — дойдём следующим витком"
                             % (cap, len(queue_ue)))
            continue
        body, body_ok, body_why = read_doc_text(doc["id"], reader=doc_reader)
        if not body_ok:
            doc["unread"] = body_why
            continue
        doc["body"] = body.strip()
        out["read"] += 1
        # Ворота считаются ДЛЯ ВСЕХ прочитанных, а не только для взятого: владелец
        # должен видеть в `--status`, почему лежащее в ящике задание не берётся, —
        # иначе ящик выглядит сломанным ровно тогда, когда он честно отказывает.
        gate_ok, reason, why = shtab_box.check(doc, today)
        out["gates"][doc["key"]] = {"ok": gate_ok, "reason": reason, "why": why}
        # ПОЛОСА ЧИТАЕТСЯ У КАЖДОГО ПРОЧИТАННОГО, А НЕ ТОЛЬКО У ВЗЯТОГО, и по той же
        # причине, что и ворота: владелец обязан видеть в `--status`, КУДА уедет
        # лежащее в ящике задание, ДО того как оно уехало. Дефолт «полоса не названа
        # → ПК» тем более обязан быть виден: он и есть то, что чаще всего надо
        # поправить одной строкой в документе.
        doc["lane_read"] = shtab_box.read_lane(doc["body"])

    # ── СИГНАЛЬНАЯ ОСТАНОВКА ──────────────────────────────────────────────────
    # ЖИВОЙ СЧЁТ СИГНАЛОВ идёт РОВНО ТОГДА, КОГДА СПРАШИВАЛИ ЗАКРЫТЫЕ РЯДЫ, и это
    # не экономия ради экономии, а тот же третий исход, что у маркеров суток. Не
    # дошли до дорогого чтения `done` — значит либо очередь не прочитана, либо в
    # ней работа владельца, либо принятых блоков нет вовсе; во всех трёх случаях
    # ящик и так не возьмёт ничего, а рапорт «сигналы говорят НЕ ЗНАЮ» повесил бы
    # на них чужую вину и приучил владельца не верить остановке.
    #
    # ЗАМОК ЖЕ ПРИМЕНЯЕТСЯ БЕЗУСЛОВНО, И ЭТО ГЛАВНАЯ ПРАВКА 05.09.2026. Прежде
    # запрет брать был чистой функцией от корпуса, читаемого мостом КАЖДЫЙ виток,
    # а объявление владельцу обещало ЗАМОК («снимается ТОЛЬКО словом владельца»).
    # Корпус этот не вечен — номера очереди идут по кругу, ряды пропадают, — и
    # 05.09 остановка `e0140bfc78dc` исчезала МОЛЧА дважды, а ящик взял между
    # объявлениями шесть заданий, ничего не спросив. Числа, доказательство и
    # доктрина «что запирается, а что нет» — в шапке :mod:`shtab_box_signals`.
    #
    # ОДНО РЕШЕНИЕ В ОДНОМ МЕСТЕ: `out["signals"]` — единственный список, из
    # которого дальше берутся И фраза владельцу (`stop_words` → журнал, витрина,
    # карточка), И запрет брать (`shtab_box.select(stop_words=...)`). Второго
    # мнения о том, стои́т ли остановка, у полосы нет ни одной ветки.
    live_signals, judged = [], None
    if not out["marks_asked"]:
        out["signals_why"] = ("живые сигналы не считались — до них не дошло (%s)"
                              % (closed_why or "дорогое чтение done не понадобилось"))
    else:
        out["signals_asked"] = True
        judged, judged_ok, judged_why = (ledger or read_ledger)(root)
        out["judged_ok"], out["judged_why"] = judged_ok, judged_why
    # МЕТКИ СНЯТИЯ ЖИВУТ В ШАПКЕ, а шапка с 03.09 читается отдельно и может не
    # прочитаться. Прежде нечитаемая шапка означала «меток снятия НЕТ», и это
    # звалось строгостью — но строгость эта била по ЧЕЛОВЕКУ: ящик снова просил
    # положить метку, которую владелец уже положил, и отличить «мост молчит» от
    # «владелец не ответил» было нечем. Слово владельца из узла не исчезает,
    # поэтому однажды увиденное снятие ПОМНИТСЯ (:func:`shtab_box_signals.hold_release`),
    # и молчание моста больше не отменяет решения человека.
    out["released"] = sorted(sig.release_marks(text)) if node_ok else []
    gone = sig.hold_release(out["hold"], out["released"])
    if out["marks_asked"]:
        # ОСТАТОК ДНЯ ДЛЯ СИГНАЛА Г — МЕНЬШИЙ ИЗ ДВУХ, и выбор назван вслух, потому
        # что при раздельных потолках «остаток» перестал быть одним числом. Сигнал Г
        # ПОКАЗЫВАЕТ, а не держит (`enforced=False`), и первая новость показа —
        # «день кончился ХОТЬ У КОГО-ТО»: именно она объясняет Штабу, почему его
        # задание ждёт. У КОГО именно — говорят строка сводки (разрез по полосам) и
        # причина отказа в отчёте, где полоса названа прямо.
        # СУММА (6 при потолке 3) соврала бы вверх, а счёт по ОБЩИМ маркерам — вниз:
        # он записал бы серверные постановки в съеденный бюджет ПК, то есть вернул
        # бы общий потолок через чёрный ход.
        # ПОТОЛОК СЧИТАЕТСЯ ПО СЪЕДЕННЫМ СЛОТАМ, А НЕ ПО ВЗЯТЫМ РЯДАМ (06.09.2026):
        # ограничитель ящика переехал с календаря на ИСХОД. Вычитаются ровно те
        # ключи, что назвал единственный различитель внешнего отказа, — и только
        # они; всё остальное в счёте суток осталось как было.
        left = min(shtab_box.budget_left(
            shtab_box.billable(out["lane_marks"].get(ln, ()), out["external"]),
            today, budget, out["marks_ok"]) for ln in shtab_box.LANES)
        live_signals = sig.evaluate(
            # ЗАКРЫТЫЕ РЯДЫ — ОБЕИХ ПОЛОС: `box_rows` отбирает по МАРКЕРУ ящика, то
            # есть видит только собственные задания. Провалившееся задание ящика не
            # перестаёт быть его провалом оттого, что исполнялось на сервере, — и
            # сигналы А/Б обязаны его сосчитать. Сегодня это ничего не меняет (рядов
            # ящика на чужой полосе ноль), а завтра закрывает дыру.
            closed=sig.box_rows(closed_rows), open_rows=live_pc, judged=judged,
            day=today, left=left, budget=budget, released=gone,
            rows_ok=bool(closed_ok), open_ok=bool(ok), judged_ok=bool(judged_ok),
            marks_ok=bool(out["marks_ok"]))
    out["signals"], out["arm"], out["free"] = sig.merge_held(
        live_signals, held=out["hold"], released=gone, now=stamp)
    out["stop"] = sig.stop_words(out["signals"], node=out["node"], checked=bool(node_ok),
                                 why=out["node_why"])
    if out["signals_asked"]:
        out["signals_why"] = out["stop"] or "все сигналы молчат"
    elif out["stop"]:
        # ЗАМОК ГОВОРИТ ДАЖЕ ТАМ, ГДЕ ЖИВОЙ СЧЁТ НЕ ЗАХОДИЛ, и молчать ему нельзя:
        # витрина и `--status` читают эту строку, а «сигналы не считались» на
        # запертом ящике — правда, читающаяся как «остановки нет».
        out["signals_why"] = out["stop"]
    out["queue"] = q
    return out


# ───────────────────────────── оборот ─────────────────────────────


def tick(root=HERE, place=False, limit=shtab_box.TICK_LIMIT,
         budget=shtab_box.DAILY_BUDGET, write_journal=False, clock=None, queue=None,
         journal_fn=None, reader=None, node=None, ledger=None, lister=None,
         doc_reader=None, prefix=None, read_max=shtab_box.READ_MAX,
         taken_reader=None, remember_fn=None, hold_reader=None, hold_writer=None,
         notify_fn=None, hold_notify_fn=None):
    """Один оборот ящика. → dict отчёта.

    ``place=False`` — сухой ход: папка перечислена, документы разобраны, тела
    прочитаны, ворота посчитаны, текст ряда собран, ОЧЕРЕДЬ НЕ ТРОНУТА. Боевой ход
    отличается ДВУМЯ действиями — постановкой ряда и записью ключа в долгую
    память (:func:`remember`), в этом порядке.

    ═══ ЗДЕСЬ СТОЯЛО «РЕЕСТРА НА ДИСКЕ НЕТ И НЕ БУДЕТ» (снято 05.09.2026) ═════

    Дословно: «память процесса и файл рядом с ним переживают ровно до первого
    self-update… источник истины один — ЖИВАЯ ОЧЕРЕДЬ». Обе половины замерены и
    обе неверны: самообновление — это ``git fetch`` + ``git pull --ff-only``, и
    файл рядом с кодом его переживает (соседний
    ``pc_orchestrator.shtab_box_tick.json`` несёт хвост моментов взятия сквозь
    десяток обновлений подряд), а живая очередь НЕ вечна — её номера идут по
    кругу, и 05.09 корпус в две с половиной сотни рядов стал семью с номерами
    1..7. Цена ошибки — три повторно взятых закрытых задания за одни сутки.
    Числа и разбор: :func:`shtab_box.merge_known`.
    """
    data = build(root, queue=queue, clock=clock, reader=reader, node=node, budget=budget,
                 ledger=ledger, lister=lister, doc_reader=doc_reader, prefix=prefix,
                 read_max=read_max, taken_reader=taken_reader, hold_reader=hold_reader)
    today = data["today"]
    report = {"acted": False, "why": "", "today": today, "stamp": data["stamp"],
              "node": data["node"], "docs": len(data["docs"]), "bad": data["bad"],
              "placed": [], "failed": [], "held": [], "texts": {}, "memory": [],
              "known_ok": data["known_ok"], "known_n": data["known_n"],
              "off": data["off"], "node_ok": data["node_ok"],
              "folder_ok": data["folder_ok"], "old_door": data["old_door"],
              "queue_ok": data["queue_ok"], "marks_ok": data["marks_ok"],
              "owner_busy": data["owner_busy"], "owner_rows": data["owner_rows"],
              "taken_today": data["taken_today"], "line": "",
              # ВНЕШНИЕ ОТКАЗЫ ВИДНЫ В ОТЧЁТЕ ОТДЕЛЬНЫМ ЧИСЛОМ, а не спрятаны в
              # разнице двух чисел: льгота, которую нельзя увидеть, неотличима от
              # сломанного счёта.
              "external": list(data.get("external") or ()),
              "billed_today": data.get("billed_today"),
              "stop": data["stop"], "signals": data["signals"],
              "signals_asked": data["signals_asked"],
              "stop_marks": sig.marks(data["signals"]),
              # ТЕ ЖЕ СЛОВА, ЧТО УВИДИТ ВЛАДЕЛЕЦ: признак «шапку прочитали»
              # едет и сюда, иначе журнал просил бы метку там, где фраза
              # остановки честно говорит «проверить не удалось».
              "signal_journal": sig.journal_line(data["signals"], today, node=data["node"],
                                                 checked=bool(data["node_ok"]),
                                                 why=data["node_why"]),
              # ПРИЁМКА ВИДНА В ОТЧЁТЕ ВСЕГДА, включая исход ПРИНЯТО: приёмка,
              # молчащая при успехе, неотличима от приёмки, которая не работала.
              "accepted": list(data.get("accepted") or ()),
              "accept_why": str(data.get("accept_why") or ""),
              # КАРТОЧКА ВЛАДЕЛЬЦУ РОЖДАЕТСЯ ЗДЕСЬ СТРОКОЙ, А ДОСТАВКИ У НЕЁ ПОКА
              # НЕТ, и граница названа честно, а не спрятана. Исход «пятая попытка
              # не принята» ПОСТОЯНЕН: закрытый ряд лежит в очереди вечно, и приёмка
              # будет рождать эту карточку КАЖДЫЙ виток. Отправлять её без замка
              # «сказать один раз» значит завалить владельца одной и той же новостью
              # каждые десять минут — хуже молчания. Замка у ящика нет ни одного
              # (реестра на диске он не держит сознательно), и заводить его — своя
              # правка со своим замером. Пока карточка живёт в отчёте и в `--status`,
              # где её видит человек, открывший ящик.
              "cards": [str(n.get("card")) for n in (data.get("accepted") or ())
                        if n.get("card")],
              # ЗАМОК ВИДЕН В ОТЧЁТЕ ОБЕИМИ ПОЛОВИНАМИ: что заперли этим оборотом
              # и что отпустили словом владельца. Молча запертая остановка так же
              # плоха, как молча пропавшая, — по ней нельзя проверить, что замок
              # вообще работает.
              "armed": [], "freed": [], "hold_n": data["hold_n"],
              "hold_ok": data["hold_ok"], "hold_why": data["hold_why"],
              # ИЗВЕЩЕНИЕ ОБ ОСТАНОВКЕ — ТЕМИ ЖЕ ТРЕМЯ ГРАФАМИ, что и извещение о
              # взятии: «текст собран» (есть и на сухом ходу) · «ушло и записано,
              # что сказали» · «не ушло, вот почему». Один счётчик слил бы
              # «сказали» с «собирались сказать» — а именно эта разница и есть
              # предмет задания 06.09: молчащую остановку от сказанной нельзя
              # отличить ничем другим.
              "hold_notices": [], "hold_told": [], "hold_notice_failed": [],
              # ИЗВЕЩЕНИЕ О ВЗЯТИИ — ТРЕМЯ РАЗНЫМИ ГРАФАМИ, а не одним счётчиком:
              # «текст собран» (`notices` — есть и на сухом ходу), «ушло»
              # (`noticed`) и «не ушло, вот почему» (`notice_failed`). Один
              # счётчик слил бы «сказали» с «собирались сказать», а именно эта
              # разница и есть предмет задания 05.09.
              "notices": [], "noticed": [], "notice_failed": []}

    if data["off"]:
        report["why"] = data["off_why"]
        report["build"] = {k: v for k, v in data.items() if k != "queue"}
        return report

    # ДОЖИМЫ ПОДАЮТСЯ В ОТБОР ПЕРВЫМИ — «доделать начатое важнее, чем начать новое»
    # (требование задания 04.09 дословно). При потолке витка в одну задачу это и
    # значит буквально: пока есть чем дожать, новых документов ящик не берёт.
    # ЛЬГОТЫ ПО СУТОЧНОМУ ПОТОЛКУ У ДОЖИМА НЕТ НИ ОДНОЙ, и отдельной ветки под это
    # не заведено: у него свой ключ, свой маркер в очереди — значит те же
    # `markers`, тот же `budget_left`, тот же `DAILY_BUDGET` на полосу
    # (`shtab_box_accept.BUDGET_WORDS` называет это словами для следующего
    # читающего, чтобы он не счёл отсутствие ветки поблажкой).
    take, held = shtab_box.select(
        list(data.get("retry") or []) + list(data["docs"]),
        task_marks=data["task_marks"], lane_marks=data["lane_marks"],
        today=today, budget=budget,
        owner_busy=bool(data["owner_busy"]), limit=limit,
        marks_ok=bool(data["marks_ok"]), source_ok=bool(data["folder_ok"]),
        stop_words=data["stop"])
    report["held"] = [(k, why) for k, why in held]
    # Отказы РАЗБОРА докладываются наравне с отказами ворот: документ, о котором не
    # сказали, — это задание, молча пропавшее по дороге. «Где именно» называется
    # адресом того источника, из которого запись пришла: у документа папки это ИМЯ
    # (строк у него нет), у блока старой формы — строка узла.
    for row in data["bad"]:
        where = ("документ %s" % row["name"]) if row.get("name") else ("строка %s" % row.get("line"))
        report["held"].append((str(row.get("key") or "?"),
                               "не разобран: %s (%s)" % (row.get("why"), where)))
    # ЗАКРЫТАЯ ДВЕРЬ — ОТДЕЛЬНАЯ СТРОКА ОТЧЁТА, а не молчание: блок старой формы в
    # шапке иначе выглядел бы для Штаба положенным заданием, которое «не берут».
    if data["old_door"]:
        report["held"].append(("", data["old_door"]))

    # ── ЗАМОК НА ДИСК ─────────────────────────────────────────────────────────
    # ДО ПОСТАНОВКИ РЯДА, а не после: остановка, которую заперли бы после
    # placement, потерялась бы ровно на том обороте, где процесс упал между
    # двумя действиями. Сухой ход (`place=False`) не пишет НИЧЕГО — `--status` и
    # `--dry` обязаны оставаться чтением, иначе разведка меняла бы предмет.
    if place:
        for rec in (data.get("arm") or ()):
            ok_w, why_w = (hold_writer or write_hold)(root, rec)
            (report["armed"] if ok_w else report["memory"]).append(
                rec.get("mark") if ok_w else (str(rec.get("mark") or ""), why_w))
        for mark in (data.get("free") or ()):
            ok_w, why_w = (hold_writer or write_hold)(root, sig.hold_free(mark, now=data["stamp"]))
            (report["freed"] if ok_w else report["memory"]).append(
                mark if ok_w else (str(mark), why_w))

    # ── ИЗВЕЩЕНИЕ ВЛАДЕЛЬЦУ: «ЯЩИК ОСТАНОВЛЕН СИГНАЛОМ» ──────────────────────
    # СТОИ́Т ПОСЛЕ ЗАПИСИ ЗАМКА, и порядок выбран, а не случаен: карточка зовёт
    # снять ИМЕННО ЭТОТ случай кнопкой с меткой, а снимается случай, ЗАПИСАННЫЙ в
    # замок. Скажи мы раньше записи — владелец получил бы кнопку на случай,
    # которого в замке нет, и его тап честно ответил бы «метки нет». Поэтому в
    # список «о чём говорим» идут ровно те свежие записи, что ЛЕГЛИ НА ДИСК
    # (`report["armed"]`), плюс старые, о которых сказать не удалось раньше.
    #
    # СУХОЙ ХОД СОБИРАЕТ ТЕКСТ И НЕ ШЛЁТ НИЧЕГО — запрет задания дословно:
    # «пробных извещений владельцу не слать ни одного; у боевого пути и проверки
    # разные вызовы». Владелец обязан иметь дорогу увидеть будущую карточку
    # целиком, ничего не послав, — как у извещения о взятии.
    armed_now = {str(m) for m in (report["armed"] or ())}
    tell = sig.untold(list(data.get("hold") or ())
                      + [r for r in (data.get("arm") or ())
                         if not place or str(r.get("mark") or "") in armed_now])
    for rec in tell:
        mark = str(rec.get("mark") or "")
        notice = sig.hold_notice(rec)
        report["hold_notices"].append({"mark": mark, "dry": not place, "text": notice})
        if not place:
            continue
        # СБОЙ ДОСТАВКИ НЕ ОТМЕНЯЕТ ОСТАНОВКИ и не роняет виток: замок уже стои́т,
        # и молчание Telegram — не повод отпускать ящик. Но оно ОБЯЗАНО БЫТЬ
        # СЛЫШНО (`_why`), и «сказали» на диск не ложится: следующий виток скажет
        # заново — это ровно то, ради чего признак `told` пишется ПОСЛЕ отправки.
        try:
            n_ok, n_where, n_why = (hold_notify_fn or notify_hold)(
                notice, sig.release_buttons(mark))
        except Exception as exc:                        # noqa: BLE001
            n_ok, n_where, n_why = False, "", "извещение об остановке не ушло: %s" % exc
        if not n_ok:
            report["hold_notice_failed"].append({"mark": mark, "why": n_why})
            continue
        ok_w, why_w = (hold_writer or write_hold)(root, sig.hold_told(mark, now=data["stamp"]))
        report["hold_told"].append({"mark": mark, "channel": n_where, "written": bool(ok_w)})
        if not ok_w:
            # Молчащий отказ этой записи неотличим от здорового дедупа ровно до
            # следующего витка, когда владелец получит ту же карточку второй раз.
            report["memory"].append(
                (mark, "%s — извещение об этой остановке уйдёт ВТОРОЙ раз" % why_w))

    for blk, text in take:
        report["texts"][blk["key"]] = text
        # ПОЛОСА НАЗЫВАЕТСЯ В КАЖДОЙ СТРОКЕ ИСХОДА, включая сухой ход и отказ: «куда
        # это уедет» — первый вопрос владельца к автоматической постановке, и
        # отвечать на него чтением кода он не обязан.
        lane = str(blk.get("lane") or shtab_box.LANE_DEFAULT)
        words = shtab_box.lane_words({"lane": lane, "named": bool(blk.get("lane_named"))})
        if not place:
            report["held"].append((blk["key"],
                                   "сухой ход: текст собран, очередь не тронута (%s)" % words))
            # ТЕКСТ ИЗВЕЩЕНИЯ ПОКАЗЫВАЕМ И НА СУХОМ ХОДУ, НЕ ОТПРАВЛЯЯ. Запрет
            # задания дословно: «проверка идёт на отключённой отправке либо
            # разбором готового текста, а не живой посылкой» — значит у владельца
            # обязана быть дорога увидеть будущее извещение целиком, ничего не
            # послав. Номера очереди на сухом ходу НЕ БЫВАЕТ, и вместо него стои́т
            # прочерк: подставить сюда правдоподобное число значило бы показать
            # владельцу номер ряда, которого не существует.
            report["notices"].append({"key": blk["key"], "id": "", "dry": True,
                                      "text": shtab_box.take_notice(blk, "—", today)})
            continue
        if not (data["queue_ok"] and data.get("queue") is not None):
            report["held"].append((blk["key"], "очередь недоступна — не ставим вслепую"))
            continue
        ok, tid, err = data["queue"].place_task(text, lane=lane)
        if not ok:
            report["failed"].append({"key": blk["key"], "why": err, "id": tid, "lane": lane})
            continue
        report["placed"].append({"key": blk["key"], "id": tid, "lane": lane,
                                 "lane_named": bool(blk.get("lane_named")), "lane_words": words,
                                 # ДОЖИМ ВИДЕН В СТРОКЕ ИСХОДА, а не только по хвосту
                                 # ключа: «взято #123» одинаково читается и для нового
                                 # задания, и для четвёртого захода по старому, а это
                                 # разные новости для того, кто смотрит на полосу.
                                 "retry": bool(blk.get("retry")), "of": blk.get("of") or "",
                                 "attempt": int(blk.get("attempt") or 1)})
        # ПАМЯТЬ ПИШЕТСЯ СРАЗУ ЗА РЯДОМ И ДО ЖУРНАЛА: журнал — новость для людей и
        # теряет строки, а это замок. Отказ записи не отменяет уже поставленного
        # ряда (отменить его нечем), но обязан быть СЛЫШЕН: он и означает «следующий
        # виток может взять то же задание второй раз».
        mem_ok, mem_why = (remember_fn or remember)(
            root, key=blk["key"], day=today, lane=lane, tid=tid, at=data["stamp"],
            src="ряд очереди")
        if not mem_ok:
            report["memory"].append((blk["key"], mem_why))
        if write_journal:
            (journal_fn or _journal)(shtab_box.index_line(blk, tid, today), repo=root)
        # ── ИЗВЕЩЕНИЕ ВЛАДЕЛЬЦУ: «полоса ВЗЯЛА задание Штаба» ────────────────
        # СТОИ́Т ПОСЛЕДНИМ В ЦЕПОЧКЕ ВЗЯТИЯ, и порядок выбран, а не случаен: ряд →
        # память (замок) → журнал (индекс) → извещение (новость человеку). Встань
        # оно раньше замка — процесс, упавший между отправкой и `remember`, оставил
        # бы владельцу извещение о взятии, которого следующий виток не помнит и
        # берёт заново: одно взятие, ДВА извещения.
        #
        # «ОДНО ВЗЯТИЕ — ОДНО ИЗВЕЩЕНИЕ» ДЕРЖИТСЯ НЕ СВОИМ РЕЕСТРОМ, А ТЕМ ЖЕ
        # ДЕДУПОМ, ЧТО И ВЗЯТИЕ (пункт 5 задания). Извещение живёт ВНУТРИ ветки
        # `placed` — то есть ровно там, где `select` уже пропустил ключ мимо
        # маркеров очереди и долгой памяти. Перезапуск демона не задваивает его
        # потому, что не задваивает ВЗЯТИЕ: следующий виток видит маркер ряда и
        # ключ в `taken`, и до этой строки не доходит вовсе. Второй реестр «кому
        # уже сказали» разошёлся бы с первым молча — это класс 539 в чистом виде.
        #
        # ОТРИЦАТЕЛЬНЫЙ ТЕСТ (пункт 6) ЗАКРЫТ МЕСТОМ, А НЕ УСЛОВИЕМ: задание,
        # присланное владельцем напрямую, в этот цикл не попадает НИ ОДНОЙ дорогой
        # — цикл идёт по документам папки мозга (`take`), а владелец кладёт ряд
        # прямо в очередь мимо ящика. Условия «а не владелец ли это» здесь нет
        # СОЗНАТЕЛЬНО: условие можно ошибочно вычислить, места ошибиться нельзя.
        #
        # СБОЙ ДОСТАВКИ НЕ ОТМЕНЯЕТ ВЗЯТИЯ и не роняет виток: ряд уже стои́т, и
        # молчание Telegram — не повод бросать очередь. Но оно ОБЯЗАНО БЫТЬ СЛЫШНО
        # строкой отчёта: «взято и сказали» и «взято, а сказать не смогли» — разные
        # новости, и различать их владелец обязан без чтения кода.
        notice = shtab_box.take_notice(blk, tid, today)
        report["notices"].append({"key": blk["key"], "id": tid, "dry": False, "text": notice})
        try:
            n_ok, n_detail, n_why = (notify_fn or notify_taken)(notice)
        except Exception as exc:                        # noqa: BLE001
            n_ok, n_detail, n_why = False, "", "извещение не ушло: %s" % exc
        if n_ok:
            report["noticed"].append({"key": blk["key"], "id": tid, "msg": n_detail})
        else:
            report["notice_failed"].append({"key": blk["key"], "id": tid, "why": n_why})

    report["acted"] = bool(report["placed"] or report["failed"])
    report["line"] = _line(report)
    report["why"] = _why(report, data)
    # НЕУШЕДШЕЕ ИЗВЕЩЕНИЕ ОБ ОСТАНОВКЕ ЕДЕТ В `why`, А НЕ В `line`, и это не вкус:
    # `_line` пишется ТОЛЬКО при взятии (`placed`/`failed`), а остановленный ящик
    # не берёт ничего по построению — то есть на остановке строки исхода не бывает
    # вовсе, и новость утонула бы ровно в том случае, ради которого заведена.
    # `why` демон кладёт в лог КАЖДЫЙ оборот, в том числе холостой.
    for row in (report["hold_notice_failed"] or ()):
        report["why"] = ("%s · ИЗВЕЩЕНИЕ ОБ ОСТАНОВКЕ НЕ УШЛО (метка %s): %s — владелец о ней НЕ "
                         "ЗНАЕТ, скажем следующим витком"
                         % (report["why"], row.get("mark"), row.get("why")))
    report["build"] = {k: v for k, v in data.items() if k != "queue"}
    return report


