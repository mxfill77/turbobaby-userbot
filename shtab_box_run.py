def now_iso(clock=None):
    """Текущее время UTC в ISO. Единственная точка, где ветка смотрит на часы."""
    stamp = (clock or datetime.datetime.now)(datetime.timezone.utc)
    return stamp.isoformat().replace("+00:00", "Z")


