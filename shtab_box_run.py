def notify_taken(text, topic=None, sender=None):
    """Извещение о взятии — в рабочую тему постановки задач. → (ok, detail, why).

    ═══ ЗАЧЕМ ОНО ВООБЩЕ ЕСТЬ (премиса задания 05.09, перемерена по коду) ══════

    До этой правки о взятии задания Штаба узнавали ДВОЕ и оба не владелец: лог
    демона и журнал среды (:func:`_journal` → ``cowork_log``). Отправки наружу у
    ящика не было ни одной — ``dispatch_notify`` не упоминался ни в одном из
    четырёх его модулей. Задания, которые владелец шлёт САМ, видны ему потому, что
    он их отправил; положенное Штабом было невидимо до самого закрытия.

    ═══ ПОЧЕМУ ДВЕРЬ ИМЕННО `send_topic_strict` ══════════════════════════════

    У ``send_topic`` каскад «тема → инбокс 1160 → личка», и он там прав для
    сигналов о жизни контура. Здесь он был бы ВРЕДЕН: инбокс 1160 — тема, которую
    владелец открывает РАДИ ОТВЕТА, а это извещение ответа не ждёт (пункт запретов:
    «кнопок у него нет и ответа оно не ждёт»). Севшее в 1160 извещение читается как
    заявка и требует от владельца действия, которого мы не просим. Поэтому дверь
    без фолбэков: чужой адрес здесь хуже молчания, а отказ ВОЗВРАЩАЕТСЯ причиной,
    чтобы виток мог о нём отчитаться, а не проглотить.

    ТЕМУ БЕРЁМ У ``dispatch_notify``, А НЕ СВОЮ КОНСТАНТУ: номер темы постановки
    задач живёт там одним значением (``TASKS_THREAD_ID``), и второй его экземпляр
    здесь разошёлся бы с первым молча — ровно классом «правишь не ту ручку».

    КАРТОЧКИ НЕ РОЖДАЕМ НИ ОДНОЙ: ``reply_markup`` не передаётся и передать его
    нечем — у ``send_topic_strict`` такого довода нет вовсе.
    """
    body = str(text or "").strip()
    if not body:
        return False, "", "пустой текст извещения — не отправляем"
    import dispatch_notify

    tid = int(topic if topic is not None else dispatch_notify.TASKS_THREAD_ID)
    # ИМЯ МЕСТНОЙ ПЕРЕМЕННОЙ — НЕ `send`: инвариант «ящик не открывает дверей с
    # каскадом и кнопкой» судит по ВЫЗЫВАЕМЫМ ИМЕНАМ обходом AST, и `send(...)`
    # здесь погасил бы его собственной подписью, а не чужой дверью.
    door = sender if sender is not None else dispatch_notify.send_topic_strict
    _channel, ok, detail = door(body, tid)
    return bool(ok), (detail if ok else ""), ("" if ok else str(detail or "не отправлено"))


def notify_hold(text, markup=None, sender=None):
    """Извещение об ОСТАНОВКЕ — критическим каналом, С КНОПКОЙ. → (ok, канал, причина).

    ═══ ПОЧЕМУ ЭТО ВТОРАЯ ДВЕРЬ, А НЕ ВЕТКА ПЕРВОЙ ═══════════════════════════

    Соседняя :func:`notify_taken` шлёт БЕЗ каскада и БЕЗ кнопки, и в её докстринге
    прямо сказано почему: извещение о взятии ответа не ждёт, а севшее в инбокс
    1160 читается как заявка и требует действия, которого мы не просим. Здесь всё
    ровно наоборот: остановка ЖДЁТ ответа — им она и снимается, — а инбокс 1160
    есть тема ответа владельца. Один признак («ждёт ли ответа», правило владельца
    10.08.2026) разводит два сообщения по двум дверям.

    Слить их в одну функцию с флагом было бы дешевле на три строки и дороже на
    один класс: флаг можно вычислить неверно, дверь перепутать нельзя. Ровно тем
    же доводом живёт отрицательный тест извещения о взятии («закрыто МЕСТОМ, а не
    условием»).

    КАСКАД ЗДЕСЬ ЗАКОНЕН И НУЖЕН: `send_critical` идёт тема 1160 → личка, и
    `reply_markup` едет ОБОИМИ каналами (замок доктрины адреса) — у карточки с
    кнопкой смена канала не смеет отнять кнопку, иначе владельцу нечем ответить.

    ОТКАЗ ВОЗВРАЩАЕТСЯ ПРИЧИНОЙ, а не глотается: «сказали» и «сказать не смогли»
    — разные новости, и от второй зависит, скажем ли мы это следующим витком
    (:func:`shtab_box_signals.hold_told` пишется только после успеха).
    """
    body = str(text or "").strip()
    if not body:
        return False, "", "пустой текст извещения — не отправляем"
    import dispatch_notify

    # ИМЯ МЕСТНОЙ ПЕРЕМЕННОЙ — НЕ `send`, по той же причине, что у соседней двери:
    # инвариант «каскад и кнопка живут ровно в одной функции» судит по ВЫЗЫВАЕМЫМ
    # ИМЕНАМ обходом AST, и `send(...)` здесь погасил бы его собственной подписью.
    door = sender if sender is not None else dispatch_notify.send_critical
    channel, ok = door(body, markup)
    return bool(ok), (str(channel) if ok else ""), ("" if ok else "канал %s отказал" % channel)


def free_mark(mark, root=HERE, at="", by="", hold_reader=None, hold_writer=None):
    """Снятие остановки ОТВЕТОМ ВЛАДЕЛЬЦА (кнопка или слово Telegram). → (ok, слова).

    Слова возвращаются ГОТОВЫМИ и печатает их `pc_agent` в чат карточки — второй
    формулировки того же исхода заводить нельзя (тот же довод, что у
    `zayavki_pc_run.answer`): «снято» на кнопке и «снято» в замке разошлись бы
    словами при одном действии.

    ═══ ЧЕТЫРЕ ИСХОДА, И НИ ОДИН НЕ МОЛЧИТ ══════════════════════════════════

    * замок не прочитан → НЕ СНИМАЕМ. Дописать снятие в файл, который мы не сумели
      прочесть, значит снять НЕИЗВЕСТНО ЧТО: метка могла принадлежать другому
      случаю, а могла не существовать вовсе;
    * метки в замке нет → НЕ СНИМАЕМ и называем открытые. Это контрфакт задания
      («снятие по неверной метке не проходит») и он закрыт МЕСТОМ: снимаются
      только те случаи, которые ящик сам записал, — выдуманная метка не найдёт
      себе записи ни одной дорогой;
    * метка уже снята → ``ok``, но словами «уже». Повторный тап по той же
      карточке — обычное дело у человека, и пугать его отказом за это нельзя;
    * снято → говорим, ЧТО именно снято и когда ящик поедет.

    ПРАВО ЗДЕСЬ НЕ СУДИТСЯ, И ЭТО НАЗВАНО ВСЛУХ, а не забыто. Личности звонящего
    у этого слоя нет вовсе: он видит аргумент командной строки. Право судит ОДНО
    место — `pc_agent`, где живёт номер владельца и куда физически приходит тап
    (`_chain_cb_authorized`); второй экземпляр этого номера здесь разошёлся бы с
    первым молча. ``by`` — СЛЕД для человека, читающего замок, а не проверка.
    """
    m = str(mark or "").strip()
    if not m:
        return False, "⚠️ Метка не названа — снимать нечего."
    held, ok, why = (hold_reader or read_hold)(root)
    if not ok:
        return False, ("⚠️ Остановка НЕ СНЯТА: замок не прочитан (%s). Пока замок не читается, "
                       "ящик не берёт ничего и снять случай нечем — строку файла %s надо "
                       "поправить руками." % (why, HOLD_FILE))
    idx = sig.hold_index(held)
    rec = idx.get(m)
    if rec is None:
        live = sorted(k for k, r in idx.items() if not r.get("released"))
        return False, ("⚠️ Метки %s в замке остановки НЕТ — ничего не снято. Открытых остановок: "
                       "%s. Метку берите из самого извещения: она снимает ровно тот случай, о "
                       "котором пришла." % (m, ", ".join(live) if live else "ни одной"))
    if rec.get("released"):
        return True, ("✅ Остановка %s (сигнал %s) уже снята%s — снимать второй раз нечего."
                      % (m, str(rec.get("sig") or "?"),
                         (" %s" % rec["at"]) if rec.get("at") else ""))
    ok_w, why_w = (hold_writer or write_hold)(root, sig.hold_free(m, now=at or now_iso(None), by=by))
    if not ok_w:
        return False, ("⚠️ Остановка %s НЕ СНЯТА: %s. Ящик по-прежнему не берёт заданий."
                       % (m, why_w))
    return True, ("✅ Остановка снята: сигнал %s (%s), метка %s. Ящик берёт задания Штаба со "
                  "следующего витка. Снят РОВНО этот случай — такой же следующий остановит снова."
                  % (str(rec.get("sig") or "?"),
                     sig.TITLE.get(str(rec.get("sig") or ""), "имя сигнала не сохранилось"), m))


def _why(report, data):
    """Одна строка «почему исход такой». Причина названа ВСЕГДА, в том числе когда
    ничего не взято: молчание ящика и его отказ — разные новости, и различать их
    владелец обязан без чтения кода."""
    if data["off"]:
        return data["off_why"]
    # ИСТОЧНИК — ПАПКА, И ЕГО МОЛЧАНИЕ ГОВОРИТ ПЕРВЫМ. Слово «пусто» на этой ветке
    # прозвучать не может ни одной дорогой: перечисление не ответило (или ответило
    # усечённым списком) — значит НЕИЗВЕСТНО, что лежит в ящике.
    if not data["folder_ok"]:
        return ("папка заданий не перечислена (%s) — что в ящике лежит, НЕИЗВЕСТНО; "
                "не берём ничего" % (data["folder_why"] or "причина не названа"))
    if data["queue_asked"] and not data["queue_ok"]:
        return "очередь недоступна (%s) — не берём ничего" % (data["queue_why"] or "?")
    if data["owner_busy"]:
        return ("в очереди задача владельца (%s) — заданий Штаба не берём ни одного"
                % ", ".join("#%s" % i for i in data["owner_rows"]))
    # СИГНАЛЬНАЯ ОСТАНОВКА ГОВОРИТ РАНЬШЕ «ящик пуст» и раньше отказов ворот: она
    # объясняет, почему ящик не возьмёт НИЧЕГО, даже когда брать есть что, — а
    # причина «блоков 0» на остановленном ящике была бы правдой и обманом сразу.
    #
    # НО ПРЕЖНЮЮ НОВОСТЬ ОНА НЕ ВЫТЕСНЯЕТ, и это поймал набор ящика, а не глаз:
    # непрочитанный корпус закрытых рядов даёт СРАЗУ ДВЕ новости — «день считаем
    # исчерпанным» (прежний замок) и «определить сигнал нельзя» (новый). Скажи мы
    # одну, владелец пошёл бы чинить не то. Порядок внутри строки — прежняя
    # первой: она старше и её ищут глазами.
    if data["stop"]:
        if data["marks_asked"] and not data["marks_ok"]:
            return "%s · %s" % (_marks_unread(data), data["stop"])
        return data["stop"]
    if not data["docs"]:
        # ПУСТАЯ ПАПКА И ЗАКРЫТАЯ ДВЕРЬ — РАЗНЫЕ НОВОСТИ. Скажи мы здесь «ящик
        # пуст», Штаб, положивший блок в шапку по прежней памяти, прочитал бы
        # честное сообщение как поломку — задание лежит, а полоса говорит «пусто».
        empty = ("ящик пуст: документов %s* в папке мозга нет%s"
                 % (data["prefix"],
                    (", не разобрано %d" % len(data["bad"])) if data["bad"] else ""))
        return "%s · %s" % (empty, data["old_door"]) if data["old_door"] else empty
    if report["placed"]:
        return ("взято %d (%s), отложено %d"
                % (len(report["placed"]),
                   ", ".join("#%s %s" % (r.get("id"),
                                         shtab_box.LANE_HUMAN.get(r.get("lane"), r.get("lane")))
                             for r in report["placed"]),
                   len(report["held"])))
    refused = [w for _k, w in report["held"] if w.startswith("НЕ ПРИНЯТ")]
    if refused and len(refused) == len(report["held"]):
        return "документов %d, принят 0 — %s" % (len(data["docs"]), "; ".join(refused[:2]))
    # ОТКАЗ ПРИБОРА — ТОЛЬКО ЕСЛИ ПРИБОР СПРАШИВАЛИ. Дорогое чтение `done` мы
    # пропускаем сознательно, когда ставить нечего, и это НЕ поломка моста: назови
    # мы её так, каждый оборот с непринятым блоком кричал бы «сверить нечем», и
    # владелец перестал бы отличать настоящий отказ моста от нашей же экономии.
    # Ровно тот класс, который ступень E назвала третьим состоянием: «не
    # спрашивали, потому что незачем».
    # ДОЛГАЯ ПАМЯТЬ СПРОШЕНА ВСЕГДА, поэтому её отказ судится ОТДЕЛЬНЫМ условием, а
    # не через `marks_asked`: тот признак говорит про дорогое чтение закрытых рядов,
    # которого могло и не быть, а память читается с диска каждый оборот. Повесь мы
    # её на чужой признак — непрочитанная память молчала бы ровно в тех витках, где
    # ящик и так ничего не ставит, то есть новость терялась бы вся.
    if (not data["known_ok"] or not data["hold_ok"]
            or (data["marks_asked"] and not data["marks_ok"])):
        return _marks_unread(data)
    return "документов %d, взято 0, отложено %d" % (len(data["docs"]), len(report["held"]))


def _marks_unread(data):
    """Прежняя новость о непрочитанном корпусе — ОДНОЙ строкой в одном месте.

    Вынесена из :func:`_why` не для красоты: она нужна в ДВУХ ветках (одна сама по
    себе, вторая рядом с фразой остановки), а два её экземпляра разъехались бы
    молча — тот же класс, которым живёт весь этот куст.
    """
    if not data.get("hold_ok", True):
        # ЗАМОК ГОВОРИТ ПЕРВЫМ: «не знаю, какие ключи брали» — про дубль, а «не
        # знаю, стои́т ли остановка» — про обход решения владельца, и второе
        # дороже. Слова разные потому, что идут за ними в разные места.
        return ("замок сигнальной остановки не прочитан (%s) — стои́т ли остановка, НЕИЗВЕСТНО; "
                "день считаем исчерпанным и не берём ничего" % data.get("hold_why", "?"))
    if not data.get("known_ok", True):
        return ("долгая память ящика не прочитана (%s) — какие ключи уже брали, НЕИЗВЕСТНО; "
                "день считаем исчерпанным и не берём ничего" % data.get("known_why", "?"))
    return ("закрытые ряды очереди не прочитаны (%s) — сколько заданий Штаба взято сегодня, "
            "НЕИЗВЕСТНО; день считаем исчерпанным и не берём ничего" % data["marks_why"])


def _line(report):
    """Строка исхода оборота для журнала/ленты. → str (пусто = писать нечего)."""
    placed = report.get("placed") or []
    if not placed and not report.get("failed"):
        return ""
    retries = sum(1 for r in placed if r.get("retry"))
    parts = ["ящик Штаба: взято %d%s"
             % (len(placed), (" (из них дожимов %d)" % retries) if retries else "")]
    for row in placed:
        # ПОЛОСА — В СТРОКЕ ИСХОДА, а не только в журнальном индексе. Эту строку
        # демон кладёт в `cowork_log` и в свой лог; по ней же владелец узнаёт о
        # постановке. «Взято #123» без полосы на двух полосах — половина новости.
        parts.append("#%s (ключ %s, %s)"
                     % (row["id"], row["key"],
                        row.get("lane_words")
                        or shtab_box.lane_words({"lane": row.get("lane"),
                                                 "named": bool(row.get("lane_named"))})))
    if report.get("failed"):
        parts.append("не встало %d" % len(report["failed"]))
    # ОТКАЗ ДОЛГОЙ ПАМЯТИ ЕДЕТ В ТУ ЖЕ СТРОКУ, что и постановка: молчащий отказ
    # памяти неотличим от здоровой полосы ровно до второго взятия того же ключа.
    for key, why in (report.get("memory") or ()):
        parts.append("ПАМЯТЬ НЕ ЗАПИСАНА (%s): %s" % (key, why))
    # НЕУШЕДШЕЕ ИЗВЕЩЕНИЕ — В ТОЙ ЖЕ СТРОКЕ, И ТОЛЬКО ОНО. Успех сюда не пишется
    # СОЗНАТЕЛЬНО: строка исхода едет в журнал на КАЖДОМ взятии, и «сказали
    # владельцу» в ней — шум, повторяющий сам факт взятия. А вот «взяли, а сказать
    # не смогли» иначе не узнать ниоткуда: извещения нет и новости о том, что его
    # нет, тоже нет — ровно та невидимость, ради снятия которой всё это заведено.
    for row in (report.get("notice_failed") or ()):
        parts.append("ИЗВЕЩЕНИЕ НЕ УШЛО (#%s, ключ %s): %s"
                     % (row.get("id"), row.get("key"), row.get("why")))
    return "; ".join(parts)


