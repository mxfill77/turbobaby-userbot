import re

# ─────────────────────────────── ВЕРДИКТЫ (их ровно два) ───────────────────────────────
HOLD = "hold"     # поднять владельцу — прежний путь, байт-в-байт
CLOSE = "close"   # снять вопрос: терминальный failed без кнопки + заметка в тему карточек

# ─────────────────────────────── ИМЕНА ЧЕТЫРЁХ УСЛОВИЙ ───────────────────────────────
# Имя уходит в заметку владельцу и в журнал демона — по нему видно, ПОЧЕМУ карточка снята.
R_OBJECT = "объект"          # 1. объект пуст — карточка не должна была родиться
R_SOURCE = "источник"        # 2. источник не гард — за карточкой нет операции
R_DONE = "сделано"           # 3. операция уже сделана — цель достигнута до ответа
R_PROBE = "проба-дубль"      # 4. проба или дубль — карточка родилась из теста, не из работы

# ── ЧИТАТЕЛИ ПК-ФОРМЫ. Каждый — зеркало КАНОНИЧЕСКОГО читателя гарда, а не своя регулярка ──
# ГОЛОВА карточки: зеркало `pretool_guard._RE_CARD_HEAD`. Ловит и голову блока («🔴 …»), и
# шапку высшего вида («⛔ ВЫСШАЯ ЦЕНА …»), и обе — с префиксом демона «NEEDS_APPROVAL (гард): ».
_HEAD_RE = re.compile(r"^(?:NEEDS_APPROVAL[^:]*:\s*)?[\U0001F534⛔]")
# ПОДПИСАННЫЕ строки — ровно в том виде, в каком их печатает `pretool_guard._card`.
_OBJ_RE = re.compile(r"^Объект: (.+)$")
_NUM_RE = re.compile(r"^Число: (.+)$")
# СТРОКА ПОСЛЕДСТВИЯ «ДА» — зеркало `pretool_guard.CONSEQ_LINE_PREFIX` (её ввёл 39fb7e4 от
# 03.09.2026). ЕДИНСТВЕННОЕ, что печатающая сторона кладёт МЕЖДУ объектом и числом; литерал
# дублируется здесь намеренно (модуль чистый, импортировать гард нельзя) и сверяется с живым
# гардом отдельным тестом — `test_card_duty.TestFieldReadFromGuardPlace`.
_CONSEQ_PREFIX = "Если «да»: "
# ШТАМП КЛАССА: зеркало `pretool_guard._RE_KIND_LINE` (пишет `_write_marker` последней строкой).
_KIND_RE = re.compile(r"^Класс операции: ([a-z_]+(?:, [a-z_]+)*)$")
# Пометка пробы ПК: её ставит САМ гард на границе изоляции (`pretool_guard._probe_intercept`).
_PROBE_MARK = "🧪 ПРОБА — ПЕРЕХВАЧЕНО НА ГРАНИЦЕ"
_DASH = "—"
# ИМЕНА, КОТОРЫМИ ГАРД НАЗЫВАЕТ СОБСТВЕННОЕ НЕЗНАНИЕ (не красные классы — см. шапку, пункт 3).
# Пустой объект у них ЗАКОНОМЕРЕН и означает «не разобрал», а не «совпало слово».
_UNPARSED_KINDS = frozenset(("unknown", "unknown_tool"))


def _obj_index(lines):
    """Индекс строки «Объект:», СТОЯЩЕЙ НА СВОЁМ МЕСТЕ, или -1.

    Зеркало `pretool_guard.object_from_card` + `_is_obj_place`: своим считается место
    непосредственно под ГОЛОВОЙ карточки (пустые строки формата не меняют и пропускаются).
    Читать поле поиском по всему тексту нельзя — это ровно тот корень, из-за которого служебное
    значение ищут в свободном тексте: строка «Объект:», приехавшая в тело вместе с объектом
    операции, читалась бы наравне со служебной.
    """
    for i, ln in enumerate(lines):
        if not _OBJ_RE.match(ln.strip()):
            continue
        for prev in reversed(lines[:i]):
            s = prev.strip()
            if not s:
                continue
            if _HEAD_RE.match(s):
                return i
            break
    return -1


def _num_index(lines, i):
    """Индекс строки «Число:», СТОЯЩЕЙ НА СВОЁМ МЕСТЕ при объекте из строки `i`, или -1.

    ЧИТАЕМ ТЕМ ЖЕ УСТРОЙСТВОМ, КАКИМ ПЕЧАТАЕТ `pretool_guard._card`, А НЕ СМЕЩЕНИЕМ. До
    07.09.2026 число брали `lines[i + 1]` — «строкой ниже объекта», и рядом стоял комментарий
    «`_card` печатает их подряд». ПОДРЯД ИХ ПЕЧАТАТЬ ПЕРЕСТАЛИ: коммит `39fb7e4` от 03.09.2026
    вставил между ними строку последствия «да» (`CONSEQ_LINE_PREFIX`). С того дня число терялось
    у КАЖДОЙ живой карточки — не у одной формы, а у всех: `facts()["num"]` отдавал пусто там, где
    гард напечатал «1 цель», и владелец видел прочерк в заметке дежурного.

    ПОЧЕМУ НЕ ЧИНИМ ПОЗИЦИЕЙ (`i + 2`): связка со смещением уже сломалась один раз и сломается
    снова — при следующей строке, вставленной печатающей стороной. Здесь описано МЕСТО, а не
    расстояние: число стоит в том же блоке, что и объект, и печатающая сторона кладёт между ними
    ровно одну необязательную строку — последствие. Всё прочее означает, что форма карточки
    разъехалась с этим читателем.

    СТРОГОСТЬ БЕЗОПАСНА, ВОЛЬНОСТЬ — НЕТ (тот же довод, что у `_is_obj_place` в гарде): читатель,
    ищущий «Число:» по всему тексту или до конца блока, приписал бы объекту число ЧУЖОЙ строки —
    соседнего блока многоблочного маркера или тела, приехавшего вместе с операцией. Ошибка
    строгости даёт пустое поле (владелец видит прочерк), ошибка вольности — правдоподобное ЧУЖОЕ
    число под честным объектом. Поэтому не нашли на месте → «не знаю», и это НЕ молча: сходимость
    печатающей и читающей стороны по ВСЕМУ живому словарю видов закреплена тестом, и следующая
    вставленная строка покраснит гейт, а не карточку владельца.
    """
    if i < 0:
        return -1
    for j in range(i + 1, len(lines)):
        s = lines[j].strip()
        if not s:                          # пустые строки формата не меняют — как у `_obj_index`
            continue
        if _NUM_RE.match(s):
            return j
        if s.startswith(_CONSEQ_PREFIX):   # единственная законная строка между ними
            continue
        return -1
    return -1


def _value(rx, line):
    """Значение подписанной строки: пусто, если строки нет или в ней прочерк (чтение как у гарда)."""
    m = rx.match((line or "").strip())
    if not m:
        return ""
    v = " ".join((m.group(1) or "").split())
    return "" if (not v or v == _DASH) else v


def _kind(lines):
    """Класс операции из ШТАМПА ГАРДА → str ('' — штампа нет либо он называет НЕ один вид).

    Всё-или-ничего, как у `pretool_guard.kinds_from_card`: штамп на несколько видов законным быть
    не может (маркер несёт один блок по построению — латч `_write_marker`), и ошибаться здесь надо
    в сторону «класс не назван». Значение это ИНФОРМАЦИОННОЕ: оно уходит в заметку владельцу и
    решения НЕ принимает — иначе здесь появился бы третий перечень видов (см. шапку, пункт 3).
    """
    for ln in lines:
        m = _KIND_RE.match(ln.strip())
        if m:
            kinds = [k.strip() for k in m.group(1).split(",")]
            return kinds[0] if len(kinds) == 1 else ""
    return ""


def facts(card, origin, op="other", dup_id="", answered_id=""):
    """Собрать ФАКТЫ карточки. Только разбор строк — ни одного обращения к миру.

    card        — текст карточки (`result` задачи в момент needs_approval), ДОСЛОВНО;
    origin      — вердикт замка происхождения ПК: guard | self | legacy (см. шапку: `self` на ПК
                  до карточки не доезжает, замок терминализует его раньше);
    op          — класс операции по мнению вызывающего; штамп гарда в карточке точнее и побеждает;
    dup_id      — id ОТКРЫТОЙ карточки с тем же отпечатком (считает вызывающий по очереди);
    answered_id — id карточки с тем же отпечатком, на которую владелец УЖЕ ответил «да».
    """
    t = str(card or "")
    lines = t.splitlines()
    i = _obj_index(lines)
    j = _num_index(lines, i)
    stamped = _kind(lines)
    return {
        "card": t,
        "origin": str(origin or "legacy"),
        "op": stamped or str(op or "other"),
        "hit": stamped,
        "obj": _value(_OBJ_RE, lines[i]) if i >= 0 else "",
        # ЧИСЛО читается С МЕСТА, которое ему отводит печатающая сторона (`_num_index`), а не со
        # смещения «строкой ниже объекта» и не свободным поиском: у поля «Число» тот же изъян
        # свободного поиска, что у поля «Объект», и та же цена у связки со смещением — 03.09.2026
        # между ними встала строка последствия, и число потерялось у всех карточек разом.
        "num": _value(_NUM_RE, lines[j]) if j >= 0 else "",
        "has_card_shape": i >= 0,
        "probe": _PROBE_MARK in t,
        "dup_id": str(dup_id or ""),
        "answered_id": str(answered_id or ""),
    }


def _highest_kind(f):
    """ПЕРВАЯ И НЕОТМЕНЯЕМАЯ проверка → причина удержания | "" (не высший вид).

    ДВЕ ПОЛОВИНЫ, обе намеренно грубые в безопасную сторону (полный довод — в шапке, пункт 3):

      · НАЗВАНА ЦЕЛЬ — значит за карточкой стоит операция, а любая операция, до которой гард ПК
        дотягивается, доктринально красная (`_stays_red`) и принадлежит высшему виду владельца.
        Перечня красных классов здесь НЕТ намеренно: третья копия рассинхронилась бы молча.
      · ГАРД НАЗВАЛ КЛАСС ШТАМПОМ (любой вид `_KIND_VOCAB`) — тогда пустой объект означает НЕ
        «совпало слово», а одно из двух, и оба — операция: `unknown`/`unknown_tool` = «я не смог
        разобрать» (fail-closed гарда, `_HARD_CARD` спрашивает всегда), любой другой штамп =
        «действие разобрано, цель не извлеклась» (замер 02.08, класс Д-3 — см. шапку). Закрыть
        такую карточку значит отменить решение гарда его же слоем позже.

    Единственная оставшаяся дверь — карточка БЕЗ штампа класса (форма старше 31.07.2026): там
    посылка «нет объекта ⇔ поймали подстроку» ещё верна, потому что замок `_verb_acts` тогда не
    работал. Ею и занимается условие 1.
    """
    if f.get("obj"):
        return "названа цель операции: %s" % f["obj"]
    hit = f.get("hit")
    if hit in _UNPARSED_KINDS:
        return ("гард признался, что не разобрал (класс «%s»): пустой объект здесь — "
                "не совпадение слова, а честное «не знаю», и карточка спрашивает всегда" % hit)
    if hit:
        return ("гард назвал класс штампом («%s»), а цель не извлеклась: с 02.08.2026 это "
                "означает «действие разобрано» (замер: ветка подстроки не срабатывает с 31.07), "
                "то есть за карточкой стоит операция" % hit)
    return ""


def _rule_object(f):
    """1. ОБЪЕКТ ПУСТ — карточка не должна была родиться.

    ДО ЭТОГО ПРАВИЛА ДОХОДИТ ТОЛЬКО КАРТОЧКА БЕЗ ШТАМПА КЛАССА: всё штампованное задержано
    ПЕРВОЙ проверкой (`_highest_kind`, вторая клауза). Это НЕ формальность, а вся разница между
    зеркалом и слепой копией — полный довод и замер 02.08.2026 в шапке модуля, пункт 3. Коротко:
    посылка сервера «пустой объект ⇔ поймали подстроку» на ПК измерена мёртвой (ветка подстроки
    не срабатывает с 31.07, `_verb_acts`), и закрывать по ней штампованную карточку значило бы
    глушить РАЗОБРАННУЮ операцию — среди фикстур замера был снос всех python на машине.

    Форма всё равно обязательна (строка «Объект:» на СВОЁМ месте): свободный текст формой не
    опознан, и молчание формы поводом закрыть не является.

    ЧИСЛО В УСЛОВИЕ НЕ ВХОДИТ, и это осознанное сужение постановки — на ПК с собственным
    основанием, не переписанным с сервера. Прежнее ПК-правило звучало «пусто И объект, И число →
    журнал» и снято тем же 02.08 (класс Д-3): одно правило вместо двух — ОБЪЕКТ гейт, ЧИСЛО поле.
    Число честно пусто там, где операция не несёт его ПО ПРИРОДЕ: снятие процесса по имени,
    остановка сервиса, `git clean`, SQL в чужую базу.
    """
    if not f.get("has_card_shape"):
        return ""
    if f.get("obj") or f.get("hit"):
        return ""
    return ("строка «Объект:» карточки пуста (прочерк), число «%s», штампа класса нет — форма "
            "старше 31.07.2026, для которой посылка «нет цели ⇔ совпало слово» ещё верна: "
            "подтверждать нечего" % (f.get("num") or _DASH))


def _rule_source(f):
    """2. ИСТОЧНИК НЕ ГАРД — за карточкой нет операции.

    Закрываем ТОЛЬКО доказанное `self`. НА ПК ЭТО ПРАВИЛО СЕГОДНЯ БЕЗ НОСИТЕЛЯ, и сказано это
    прямо, чтобы никто не измерял им вклад: замок происхождения (31.07.2026) признаёт карточкой
    ТОЛЬКО файл-маркер гарда со своим `run_token`, а заявку исполнителя терминализует раньше и
    без кнопки (`FAIL_UNBACKED_RED`). Правило остаётся СЕТКОЙ под замком: если замок когда-нибудь
    ослабнет и слова исполнителя снова доедут до карточки, вопрос снимется здесь.

    `legacy` (штампа демона нет вовсе) НЕ закрываем — fail-closed: недоказуемое происхождение
    поднимают, а не закрывают. Доктрина прямо говорит «реальный блок терять нельзя».
    """
    if f.get("origin") != "self":
        return ""
    return ("штамп источника, поставленный демоном: слова исполнителя — гард ни одной команды "
            "не перехватывал, объекта операции никто не видел")


def _rule_done(f):
    """3. ОПЕРАЦИЯ УЖЕ СДЕЛАНА — цель достигнута до ответа.

    Проверяемая форма ровно одна: владелец УЖЕ сказал «да» на карточку с тем же отпечатком
    (`answered_id`), то есть по этому вопросу его воля на записи и операция пошла своим ходом.
    Второй такой же вопрос ответом ничего не добавляет.

    ЧЕСТНО: живого случая в окне замера ПК нет, как не было и в окне сервера. Правило заведено
    правилом, а не догадкой, и покрыто тестом; «уже сделано» в более широком смысле (сверить
    состояние живой таблицы) сюда НЕ берём — это чтение рабочих данных ради снятия вопроса о
    записи в них, цена ошибки выше цены карточки.
    """
    a = f.get("answered_id")
    if not a:
        return ""
    return "владелец уже ответил «да» на карточку с тем же отпечатком — задача %s" % a


def _rule_probe(f):
    """4. ПРОБА ИЛИ ДУБЛЬ — карточка родилась из теста, не из работы.

    ДУБЛЬ: та же карточка уже ОТКРЫТА у владельца (`dup_id`) — второй кнопки для того же вопроса
    не нужно. Это единственная половина условия, у которой на ПК есть носитель.
    ПРОБА: пометка `🧪 ПРОБА — ПЕРЕХВАЧЕНО НА ГРАНИЦЕ`, которую ставит САМ гард. НА ПК ОНА ДО
    ВЛАДЕЛЬЦА НЕ ДОЕЗЖАЕТ: изоляция пробы уводит маркер в соседний файл, которого демон не
    открывает, и глушит прямой канал (`pretool_guard.isolated`/`marker_path`). Своего признака
    пробы у дежурного нет намеренно — второй список породил бы класс «наполовину изолированной
    пробы» (01.08.2026), где каждый канал закрывал ровно то, что оставлял открытым другой.

    Сила этого условия намеренно мала: карточка с названной целью до правил не доходит (высший
    вид), а без цели её закрывает условие 1. Так и задумано — см. «ЧЕСТНЫЙ ПРЕДЕЛ» в шапке:
    признак пробы подделывается тем же uid, и он не должен стоить владельцу ни одной операции.
    """
    if f.get("dup_id"):
        return "та же карточка уже открыта у владельца — задача %s" % f["dup_id"]
    if f.get("probe"):
        return "карточка несёт пометку пробы, поставленную гардом (изоляция границы, не работа)"
    return ""


# Порядок = нумерация владельца. Первое совпавшее правило и решает — оно же уходит в заметку.
_RULES = (
    (R_OBJECT, _rule_object),
    (R_SOURCE, _rule_source),
    (R_DONE, _rule_done),
    (R_PROBE, _rule_probe),
)


def verdict(f):
    """(действие, правило, доказательство). Действие — только HOLD или CLOSE.

    FAIL-CLOSED ВЕЗДЕ: высший вид, неизвестная форма, сбой любого правила, пустые факты →
    HOLD, то есть ровно сегодняшнее поведение. Закрытие требует ПОЛОЖИТЕЛЬНОГО доказательства.
    """
    if not isinstance(f, dict):
        return (HOLD, "", "факты не собраны — поднимаю владельцу")
    hk = _highest_kind(f)
    if hk:
        return (HOLD, "", "высший вид: %s" % hk)
    for name, rule in _RULES:
        try:
            proof = rule(f)
        except Exception:
            return (HOLD, "", "правило «%s» не отработало — поднимаю владельцу" % name)
        if proof:
            return (CLOSE, name, proof)
    return (HOLD, "", "ни одно из четырёх условий не доказано — поднимаю владельцу")


def decide(card, origin, op="other", dup_id="", answered_id=""):
    """Удобная обёртка «текст карточки → вердикт» (её зовут демон и тесты)."""
    return verdict(facts(card, origin, op=op, dup_id=dup_id, answered_id=answered_id))


def close_result(card, rule, proof):
    """Терминальный текст задачи, чью карточку дежурный снял. Кнопки нет: демон кладёт его в
    `complete_task(failed)`, и такой исход devbot рендерит без approve.

    ПЕРВЫЙ СИМВОЛ «✋» — НЕ УКРАШЕНИЕ, А МАШИННЫЙ КОНТРАКТ ПК-ПОЛОСЫ. Это
    `pc_orchestrator.MANUAL_MARK`, и по нему `NO_HEAL_PREFIXES` держит самопочинку и надзор цепи:
    снятую дежурным карточку думатель НЕ переформулирует и цепь на неё не тратит круг. Совпадение
    с формой сервера здесь случайно — там `✋` смысла контракта не несёт, — поэтому оно закреплено
    тестом (`test_close_result_starts_with_manual_mark`): переформулируют шапку — гейт покраснеет.

    Текст карточки сохраняем ДОСЛОВНО: молча из истории ничего не исчезает."""
    return "\n".join([
        "✋ КАРТОЧКА СНЯТА ДЕЖУРНЫМ (кнопки «да» здесь нет намеренно)",
        "Владельца не спрашиваю: за этой карточкой не стоит операции, которую его «да» могло бы "
        "разрешить. Условие: %s. Чем доказано: %s." % (rule, proof),
        "ВАЖНО: операция НЕ выполнена и остаётся заблокированной — решение гарда не менялось. "
        "Снят вопрос, а не запрет. Если действие всё же нужно — поставь его отдельной задачей: "
        "когда команду РЕАЛЬНО попробуют, её перехватит гард и пришлёт карточку с объектом.",
        "Владельцу ушла заметка в тему карточек (ответа не требует).",
        "─── ниже ДОСЛОВНО карточка, которая собиралась спросить «да» ───",
        str(card or "(текст карточки пуст)"),
    ])


def note(lane, tid, rule, proof):
    """Одна строка в тему карточек: что снял, по какому условию, чем доказал. Кнопок нет, номера
    карточки для ответа нет, слова «да» нет — отвечать не на что и нечем (форма заметки)."""
    return "🧹 дежурный по карточкам · %s · задача %s · карточка снята · условие: %s · %s" % (
        lane, tid, rule, proof)
